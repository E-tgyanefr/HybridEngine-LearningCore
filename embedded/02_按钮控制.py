# 第 02 课：按钮控制 LED —— 让程序学会"听"

# 要做：
#   1. 写一个函数 接按钮(板子)：在**引脚 3** 上建一个输入引脚，并把它 return 出来。
#         return 板子.输入引脚(3, 名字="按钮", 上下拉="上拉")
#      结尾那三个字「上下拉」不能漏 —— 漏了这个引脚就是"悬空"的（下面讲为什么危险）。
#
#   2. 写一个函数 按钮点灯(板子, 按钮, led)：
#         先读一次按钮：板子.读到(按钮)   →  True 表示按下，False 表示松开
#         然后：按下 → led.高()（点亮）
#               松开 → led.低()（灭掉）
#
#   检查会这样验你：先在"松开"的状态下调一次 按钮点灯，记下 LED；
#   再在"按下"的状态下调一次，再记一次。
#   **两次的 LED 必须不一样。**
#   一样就说明你根本没在读按钮 —— 只是每次进来都无条件点灯，
#   那这个按钮就是白接的（这也是这一课唯一真正要考的东西）。

# ─────────────────────────────────────────────────────
#  从"输出"到"输入"：程序开始有感觉了
# ─────────────────────────────────────────────────────
#
# 第 01 课只用了输出引脚 —— 板子单方面往外说话。
# 这一课要用**输入引脚** —— 板子开始听外面的动静。
#
# 这一个字的区别，是"点灯玩具"和"真正的控制"之间的分界线：
#
#     只会输出 = 一段固定的动作（跑一遍就完了，跟外面没关系）
#     能读输入 = 程序**根据外面的情况做决定**（这才叫控制）
#
# 你身边所有"聪明"的设备 —— 微波炉、电梯、洗衣机的每一个按钮，
# 本质都是这一课的内容：读输入 → 做决定 → 改输出。
#
# ─────────────────────────────────────────────────────
#  输入引脚读到的是什么
# ─────────────────────────────────────────────────────
#
# 引脚只有两种状态：高（有电压）或低（没电压）。按钮就是一根线：
#     按下 = 接通      松开 = 断开
#
# 板子.读到(按钮) 就是问板子"这根线现在是通是断"：
#     True  = 按下（通）      False = 松开（断）
#
# ⚠ 有一个"反转"必须记住（真板子上会咬你一口）：
#   最常见的是**上拉**接法 —— 按钮一端接引脚、一端接地。
#   松开时引脚被电阻拉到高电平；按下时被直接接到地，变成低电平。
#   所以真板子上是：**按下 → 读到低；松开 → 读到高**，正好反过来。
#
#   模拟器为了让你先专心学"控制流程"，统一成 **按下就返回 True**。
#   你的代码不用改，但心里要记着真板子上这个反转 ——
#   不然第一次接真板子会出现"按钮逻辑整个是反的"这种经典事故。
#
# ─────────────────────────────────────────────────────
#  悬空输入：为什么"上下拉"不是可选项
# ─────────────────────────────────────────────────────
#
# 如果按钮只接了引脚这一端，另一端什么都没接（或者线松了、掉了）：
# 那个引脚就是一根**悬空的天线**。它会感应周围的电磁噪声，
# 读到的值完全不确定 —— 你按十次，可能八次读到"按下"，也可能一次都读不到。
#
# 这种 bug 最难查，因为代码看起来完全正确、换一块板子症状还不一样。
# 上下拉电阻就是给引脚一个**确定的默认值**：
#
#     上拉（接到电源）：什么都不按时，稳定读到高
#     下拉（接到地）  ：什么都不按时，稳定读到低
#
# 模拟器会替你盯这件事：输入引脚没设上下拉，板子.报告() 里会出现
# 「⚠ 没设上下拉」的提醒，检查里也专门有一条抓它。
# （真板子上没有任何人会提醒你 —— 所以从这一课就养成习惯。）
#
# ─────────────────────────────────────────────────────
#  ⚠ 模拟器验证不了电路（这一课尤其要记住）
# ─────────────────────────────────────────────────────
#
# 检查全过 ≠ 插上板子就能用。模拟器只跑**程序逻辑**，它看不见：
#   · **限流电阻** —— LED 必须串一个 220Ω~1kΩ 的电阻，直接接引脚会烧掉
#   · **LED 正负极** —— 长脚（正极）接引脚、短脚（负极）接地，接反了不亮
#   · **接线位置** —— 按钮接在哪两个孔、上拉电阻有没有真的接上，只有你知道
#   · 电压对不对、杜邦线插紧没有、按钮是常开还是常闭
#
# 代码检查通过而板子不亮的时候，先查上面这几条，别急着怀疑代码。
#
# ─────────────────────────────────────────────────────
#  排查工具：板子.报告()
# ─────────────────────────────────────────────────────
#
# 在你的答案文件里写：
#     板子 = 模拟器(引脚数=8)
#     按钮 = 板子.输入引脚(3, 名字="按钮", 上下拉="上拉")
#     print(板子.报告())
#
# 它会列出每个引脚现在的模式、电平和有没有上下拉 ——
# 接线类的错误（引脚方向设反、忘了上下拉）基本一眼就能看出来。
#
# ─────────────────────────────────────────────────────
#  写完之后
# ─────────────────────────────────────────────────────
#   python -m learncode 嵌入式 检查 02


