import sys


class _跑不完(Exception):
    """学生的函数停不下来时，用它从函数**内部**把它打断。"""


def _限步调用(函数, 参数=(), 最多行数=200000):
    """调用学生的函数；如果它停不下来，就把它打断，而不是让检查永远卡住。

    ══ 为什么需要这个（这一课很容易踩）══
    很自然的想法是写：

        def 按钮点灯(板子, 按钮, led):
            while not 板子.读到(按钮):     # 等按钮被按下
                pass
            led.高()

    在真板子上这叫"死等"，虽然不好但能跑；在这个模拟器里它会
    **永远转下去** —— 因为没人会在这个函数执行期间去按按钮。
    学生看到的是一片空白，完全不知道发生了什么。

    所以这里数着执行了多少行，超了就往函数里抛一个异常。
    """
    计数 = [0]

    def 追踪(frame, event, arg):
        if event == "line":
            计数[0] += 1
            if 计数[0] > 最多行数:
                raise _跑不完()
        return 追踪

    原来的 = sys.gettrace()
    sys.settrace(追踪)
    try:
        return 函数(*参数)
    finally:
        sys.settrace(原来的)


def _停不下来的说明(函数名):
    return (f"{函数名} 停不下来了 —— 它里面有个转不完的循环。\n"
            "      这类函数的定位是「看一眼按钮，然后把灯设成对应的样子」，看完就返回。\n"
            "      **不要在这里等按钮被按下**：真板子上那个「等」在固件的循环里，\n"
            "      不在这个函数里；而且在这里等，检查就永远等不到结果。\n"
            "      改成直接读一次、立刻做决定：\n"
            "          现在 = 板子.读到(按钮)\n"
            "          if 现在:\n"
            "              led.高()\n"
            "          else:\n"
            "              led.低()")


def _新板():
    """建一块模拟板子，带一个 LED（和第 01 课一样）。"""
    from learncode.mcu import 模拟器
    板 = 模拟器(引脚数=8, 名字="模拟开发板")
    led = 板.输出引脚(2, 名字="LED")
    return 板, led


def _接线(答案):
    """建板、建 LED，再调用学生的 接按钮。

    返回 (板, led, 按钮, 错误说明)。错误说明非空 = 接线这一步就没成，
    后面的检查都别做了 —— 先让接线能跑通。

    ══ 为什么要先验一遍引脚能不能按 ══
    学生可能 return 了别的东西（板子本身、一个字符串、None），
    那样后面 板.按下(按钮) 会抛一个很难懂的错。
    在这里拦住，就能给一句人话。
    """
    if not hasattr(答案, "接按钮"):
        return None, None, None, ("还没有定义「接按钮」函数。\n"
                                  "      写法：\n"
                                  "          def 接按钮(板子):\n"
                                  '              return 板子.输入引脚(3, 名字="按钮", 上下拉="上拉")')
    板, led = _新板()
    try:
        按钮 = _限步调用(答案.接按钮, (板,))
    except _跑不完:
        return 板, led, None, _停不下来的说明("接按钮")
    except TypeError as e:
        return 板, led, None, (f"调用 接按钮(板子) 时参数不对：{e}\n"
                               f"      接按钮 应该接收**一个**参数（板子）：def 接按钮(板子):")
    except Exception as e:                            # noqa: BLE001
        return 板, led, None, (f"调用 接按钮(板子) 时出错了：{type(e).__name__}: {e}\n"
                               f"      常见原因：引脚号写错、忘了写 板子.输入引脚(...)。")

    if 按钮 is None:
        return 板, led, None, ("接按钮(板子) 没有 return 任何东西 —— 检查拿不到按钮，\n"
                               "      就没法替你按下它了。\n"
                               "      改法（最后一定要 return）：\n"
                               '          return 板子.输入引脚(3, 名字="按钮", 上下拉="上拉")')

    try:
        板.读到(按钮)
    except Exception as e:                            # noqa: BLE001
        return 板, led, None, (f"接按钮 返回的东西不能当输入引脚用：{type(e).__name__}: {e}\n"
                               "      要返回的是 板子.输入引脚(...) 建出来的那个引脚对象，\n"
                               "      不是板子本身，也不是引脚号那个数字。")

    try:
        板.按下(按钮)
        板.松开(按钮)
    except Exception as e:                            # noqa: BLE001
        return 板, led, None, (f"拿到按钮之后按不动它：{type(e).__name__}: {e}\n"
                               "      多半是 接按钮 建引脚的那块板子和传进来的板子不是同一块。\n"
                               "      请用传进来的 板子 去建引脚。")

    return 板, led, 按钮, ""


def _点灯一次(答案, 板, 按钮, led):
    """调用学生的 按钮点灯，把异常翻译成人话。返回 "错误说明"（空字符串 = 没出错）。"""
    try:
        _限步调用(答案.按钮点灯, (板, 按钮, led))
    except _跑不完:
        return _停不下来的说明("按钮点灯")
    except TypeError as e:
        return (f"调用 按钮点灯(板子, 按钮, led) 时参数不对：{e}\n"
                "      它必须接收三个参数：def 按钮点灯(板子, 按钮, led):")
    except Exception as e:                            # noqa: BLE001
        return (f"调用 按钮点灯(板子, 按钮, led) 时出错了：{type(e).__name__}: {e}\n"
                "      检查一下函数是不是接收了三个参数（板子、按钮、led），顺序别换。")
    return ""


def CHECK_两个函数都在(答案):
    if not hasattr(答案, "接按钮"):
        return False, ("还没有定义「接按钮」函数。\n"
                       "      写法：def 接按钮(板子): ... 并 return 建好的输入引脚")
    if not callable(答案.接按钮):
        return False, "「接按钮」存在，但它不是函数。要用 def 定义。"
    if not hasattr(答案, "按钮点灯"):
        return False, ("还没有定义「按钮点灯」函数。\n"
                       "      写法：def 按钮点灯(板子, 按钮, led): ... （三个参数，顺序别换）")
    if not callable(答案.按钮点灯):
        return False, "「按钮点灯」存在，但它不是函数。要用 def 定义。"
    return True, "接按钮、按钮点灯 都是函数"


def CHECK_接按钮返回能按的输入引脚(答案):
    """返回的东西必须真的是一个**可以按、可以读**的输入引脚。"""
    板, led, 按钮, 错误 = _接线(答案)
    if 错误:
        return False, 错误
    return True, f"引脚 {按钮.号} 是输入引脚，按得动、读得到"


def CHECK_输入引脚设了上下拉(答案):
    """没设上下拉的输入引脚 = 悬空 = 读到的值是随机的。

    怎么验：模拟器把"输入引脚没设上下拉"记在 板子.上限警告 里，
    同时日志里会留下"设为输入，上拉/下拉"这一行。
    """
    if not hasattr(答案, "接按钮"):
        return False, "还没有定义「接按钮」函数"
    板, led = _新板()
    try:
        _限步调用(答案.接按钮, (板,))
    except _跑不完:
        return False, _停不下来的说明("接按钮")
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 接按钮(板子) 时出错了：{type(e).__name__}: {e}"

    日志 = 板.日志文本()
    if "设为输入" not in 日志:
        return False, ("板子的日志里没有「设为输入」这一步 —— 说明你没有用 "
                       "板子.输入引脚() 去建这个按钮。\n"
                       f"      日志内容：\n          {日志}\n"
                       "      输入和输出是两种不同的引脚，别搞混：\n"
                       "        输出引脚：板子往外送电（点灯、蜂鸣器）\n"
                       "        输入引脚：板子读外面的电平（按钮、传感器）")

    if 板.上限警告:
        return False, ("引脚设成了输入，但**没设上下拉**。\n"
                       "      真实电路里这叫「悬空」：引脚像一根天线，读到的值是随机的，\n"
                       "      你按十次可能只有两次读到按下 —— 而代码看起来完全正常，\n"
                       "      这是嵌入式里最难查的一类 bug。\n"
                       "      改法：\n"
                       '          return 板子.输入引脚(3, 名字="按钮", 上下拉="上拉")\n'
                       "      板子自己的提醒：\n"
                       f"          {板.上限警告[0].splitlines()[0]}\n"
                       "      ⚠ 模拟器只是在**提醒**你。真板子上这个「确定默认值」要靠\n"
                       "        一个真的电阻（或者芯片内部的上拉），模拟器看不见它。")

    return True, ("输入引脚带了上下拉 —— 不会悬空。\n"
                  "      （真板子上这是靠一个真的电阻做到的，模拟器验证不了那一半。）")


def CHECK_LED跟着按钮变(答案):
    """★ 本课的核心检查：LED 必须**响应按钮的状态**。

    怎么验：同一份代码，在"松开"和"按下"两种状态下各调一次，
    两次的 LED 状态必须不同。
    如果两次一样 —— 不管灯是亮是灭 —— 都说明你没在读按钮，
    只是每次进来都无条件设了同一个状态。
    """
    板, led, 按钮, 错误 = _接线(答案)
    if 错误:
        return False, 错误
    if not hasattr(答案, "按钮点灯"):
        return False, "还没有定义「按钮点灯」函数"

    板.松开(按钮)
    错误 = _点灯一次(答案, 板, 按钮, led)
    if 错误:
        return False, 错误
    松开时 = led.状态()

    板.按下(按钮)
    错误 = _点灯一次(答案, 板, 按钮, led)
    if 错误:
        return False, 错误
    按下时 = led.状态()

    if 松开时 != 按下时:
        return True, (f"松开 → {松开时}；按下 → {按下时} —— "
                      f"LED 真的跟着按钮变了")

    return False, (
        f"松开时 LED 是「{松开时}」，按下时还是「{按下时}」—— 两次一模一样。\n"
        "      这说明你的函数**没有读按钮**，每次进来都设了同一个状态。\n"
        "      要让 LED 跟着按钮走，函数体得先读、再决定：\n"
        "          现在 = 板子.读到(按钮)      # True = 按下，False = 松开\n"
        "          if 现在:\n"
        "              led.高()                # 按下 → 亮\n"
        "          else:\n"
        "              led.低()                # 松开 → 灭\n"
        "      顺便记住：读输入是嵌入式一切「自动」行为的起点。\n"
        "      ⚠ 还有一半是模拟器管不了的：限流电阻、LED 正负极、按钮接在哪两个脚 ——\n"
        "        这些接错了，程序逻辑再对板子也不会亮。")


def CHECK_按下亮松开灭(答案):
    """方向也要对：按下要亮、松开要灭（课程里是这么要求的）。

    这一条比上一条更细：上一条只要"两种状态不一样"，
    所以"按下灭、松开亮"这种反的也能过；这一条把它按住。
    """
    板, led, 按钮, 错误 = _接线(答案)
    if 错误:
        return False, 错误
    if not hasattr(答案, "按钮点灯"):
        return False, "还没有定义「按钮点灯」函数"

    观测 = []
    for 该按下 in (False, True, False, True):
        if 该按下:
            板.按下(按钮)
        else:
            板.松开(按钮)
        错误 = _点灯一次(答案, 板, 按钮, led)
        if 错误:
            return False, 错误
        观测.append((该按下, led.状态()))

    错的 = [(按, 态) for 按, 态 in 观测 if (态 == "亮") != 按]
    if not 错的:
        return True, "四个来回都对：按下 → 亮，松开 → 灭"

    按, 态 = 错的[0]
    return False, (
        f"方向不对：{'按下' if 按 else '松开'}的时候 LED 是「{态}」。\n"
        f"      课程要求的是「按下亮、松开灭」，实际观测：{观测}\n"
        + ("      像是把 if/else 的两边写反了 —— 检查一下是不是成了「按下灭、松开亮」。\n"
           if all((态 == "亮") != 按 for 按, 态 in 观测) else
           "      像是只在按下时写了 led.高()，松开时没把它灭掉。\n")
        + "      正确写法：\n"
          "          if 板子.读到(按钮):\n"
          "              led.高()\n"
          "          else:\n"
          "              led.低()\n"
          "      ⚠ 顺便记住真板子上的那一半：上拉接法时「按下」读到的是**低**电平，\n"
          "        和模拟器正好相反。模拟器这样定是为了让你先专心学流程。")


def CHECK_是走引脚改的(答案):
    """LED 必须通过引脚对象改 —— 不是偷偷直接改板子的内部状态。

    怎么验：板子会记录每一次操作，正常做法一定会在日志里留下
    「LED → 高」和「LED → 低」这两行。
    """
    板, led, 按钮, 错误 = _接线(答案)
    if 错误:
        return False, 错误
    if not hasattr(答案, "按钮点灯"):
        return False, "还没有定义「按钮点灯」函数"

    板.按下(按钮)
    错误 = _点灯一次(答案, 板, 按钮, led)
    if 错误:
        return False, 错误
    板.松开(按钮)
    错误 = _点灯一次(答案, 板, 按钮, led)
    if 错误:
        return False, 错误

    日志 = 板.日志文本()
    if ("→ 高" in 日志) and ("→ 低" in 日志):
        return True, "日志里能看到你拉高过、也拉低过 —— 是走引脚控制的"
    return False, (
        "板子的操作日志里没看到完整的「拉高 / 拉低」记录。\n"
        f"      日志内容：\n          {日志}\n"
        "      请用 led.高() / led.低() 来改它的状态 —— 那是程序控制硬件的正规路径。")
