# 要做：
#   1. 写一个函数 闪一步(板子, led)：让时间往前走一小段，然后把 LED **翻到相反的状态**。
#         板子.时间推进(0.5)     # 让模拟的时间走 0.5 秒
#         led.翻转()             # 亮变灭、灭变亮（比 if 判断省事，也少出 bug）
#      "一步" = 半个周期：这一步亮了，下一步就该灭。
#
#   2. 写一个函数 闪烁(板子, led, 次数)：把 闪一步 做 次数 遍。
#         用 for 循环，**别用 while True** ——
#         检查会传一个次数给它（比如 3），它必须做完就**停下来**。
#
#   检查会连续调用 闪一步 好几次，把每次调完的 LED 状态记下来，
#   要求是：亮、灭、亮、灭…… **必须交替**。
#   一直亮 或 一直灭 都会被抓出来 —— 那叫"通电"，不叫"闪烁"。

# ─────────────────────────────────────────────────────
#  闪烁 = 程序第一次有了"节奏"
# ─────────────────────────────────────────────────────
#
# 第 01 课是"设一个状态就不管了"，第 02 课是"跟着输入走"。
# 这一课多了一个新东西：**时间**。
#
# 有了时间，程序才能做出"动作"而不只是"状态"：
#   · 闪烁的 LED（灯语、故障指示）
#   · 蜂鸣器滴一声、滴三声
#   · "长按 3 秒关机"（第 04、05 课会用上）
#   · 超时、心跳、采样周期……
#
# 状态 + 时间 = 节奏。这是嵌入式真正开始有意思的地方。
#
# ─────────────────────────────────────────────────────
#  为什么要"翻转"，而不是 set 成亮/灭
# ─────────────────────────────────────────────────────
#
# 你完全可以写成：
#     if led.是高: led.低()
#     else:        led.高()
#
# 但 led.翻转() 一行就够了，而且**少一个出错的机会**：
# 手写判断的时候很容易两边都写成 高()，结果灯一直亮着 —— 还特别难看出来。
#
# 更重要的是思路上的转变：
#   "把它设成亮"  → 你要知道现在是什么状态
#   "把它翻过来"  → 你不需要知道现在是什么状态
# 后者在任何时候调用都是对的 —— 这种"不依赖当前状态"的写法，
# 是写状态机（第 04 课）之前最重要的一次思维练习。
#
# ─────────────────────────────────────────────────────
#  ⚠ 为什么模拟器要"手动"推进时间（这一课的关键）
# ─────────────────────────────────────────────────────
#
# 这是模拟器和真板子差别最大的一处，必须说清楚，不然你会以为模拟器有病。
#
# 真实板子上，时间**自己会走**。所以你写：
#       while 时间还没到 1 秒:
#           pass
# 循环空转几百万圈之后，一秒真的过去了，循环会结束。
#
# 模拟器里没有"真的时间"。计算机跑这段代码只要几微秒，
# 它不知道你想等一秒。所以：
#       while 板子.时间 < 1.0:
#           pass
# **永远跑不完** —— 板子.时间 只有你调用 板子.时间推进() 才会变，
# 而循环体里没有它。这不是 bug，这是模拟器唯一诚实的做法：
# 它没法替你"等"，只能让你**明确说出来**。
#
# 所以模拟器里所有和时间有关的写法都是：
#       板子.时间推进(0.5)      ← 明确告诉它"过了 0.5 秒"
#         ↑ 在真板子上，这一行是 time.sleep(0.5)，或者"等定时器到点"
#
# 这个设计其实帮了你一个大忙：闪烁的快慢、去抖要等多久，
# 你都能**精确控制、瞬间完成**，不用真的盯着表等 ——
# 第 05 课做去抖的时候，这一点会非常明显。
#
# （所以也别写 import time; time.sleep(0.5)：那会真的卡住，而且
#   板子.时间 一动不动 —— 检查一眼就能看出来。）
#
# ─────────────────────────────────────────────────────
#  ⚠ 模拟器验证不了电路（每一课都要说一遍）
# ─────────────────────────────────────────────────────
#
# 检查全过 ≠ 插上板子就能用。模拟器只跑**程序逻辑**，它看不见：
#   · **限流电阻** —— LED 必须串 220Ω~1kΩ，直接接引脚会烧（闪烁时电流一直在通断，
#     少了电阻更容易出问题）
#   · **LED 正负极** —— 长脚（正极）接引脚、短脚（负极）接地，接反了永远不亮
#   · **接线位置** —— 接在哪个引脚、面包板哪一行，只有你自己知道
#   · 引脚驱动能力够不够、电压对不对
#
# 尤其是"灯不闪"，先怀疑接线，再怀疑代码。
#
# ─────────────────────────────────────────────────────
#  写完之后
# ─────────────────────────────────────────────────────
#   python -m hybridengine_light 嵌入式 检查 03


# ── 下面是检查用的代码，不用改 ──

import sys


class _跑不完(Exception):
    """学生的函数停不下来时，用它从函数**内部**把它打断。"""


def _新板():
    from hybridengine_light.mcu import 模拟器
    板 = 模拟器(引脚数=8, 名字="模拟开发板")
    led = 板.输出引脚(2, 名字="LED")
    return 板, led


def _限步调用(函数, 参数=(), 最多行数=200000):
    """调用学生的函数；如果它停不下来，就把它打断，而不是让检查永远卡住。

    ══ 为什么需要这个 ══
    学生很自然会写 `while True:` 来做"一直闪" —— 在真板子上那是对的
    （固件本来就永远在 loop 里转）。但在这里它会把检查命令**永久挂住**：
    屏幕上什么都没有，学生完全不知道发生了什么。那比报错糟糕得多。

    做法：用 sys.settrace 数执行了多少行，超了就抛一个异常进去。
    """
    计数 = [0]

    def 追踪(frame, event, arg):
        if event == "line":
            计数[0] += 1
            if 计数[0] > 最多行数:
                raise _跑不完()
        return 追踪

    原来的 = sys.gettrace()
    sys.settrace(追踪)
    try:
        return 函数(*参数)
    finally:
        sys.settrace(原来的)


def _翻转次数(板, 从第几行=0):
    """数日志里 LED 的状态变化了几次（→ 高 / → 低 都算一次变化）。"""
    return sum(1 for 行 in 板.日志[从第几行:] if ("→ 高" in 行 or "→ 低" in 行))


def sequence_text(序列):
    """把状态序列拼成 "灭 → 亮 → 灭" 这样，方便在提示里给学生看。"""
    return " → ".join(序列)


def CHECK_两个函数都在(答案):
    if not hasattr(答案, "闪一步"):
        return False, ("还没有定义「闪一步」函数。\n"
                       "      写法：\n"
                       "          def 闪一步(板子, led):\n"
                       "              板子.时间推进(0.5)\n"
                       "              led.翻转()")
    if not callable(答案.闪一步):
        return False, "「闪一步」存在，但它不是函数。要用 def 定义。"
    if not hasattr(答案, "闪烁"):
        return False, ("还没有定义「闪烁」函数。\n"
                       "      写法：def 闪烁(板子, led, 次数): ... （三个参数，顺序别换）")
    if not callable(答案.闪烁):
        return False, "「闪烁」存在，但它不是函数。要用 def 定义。"
    return True, "闪一步、闪烁 都是函数"


def CHECK_闪一步不报错(答案):
    if not hasattr(答案, "闪一步"):
        return False, "还没有定义「闪一步」函数"
    板, led = _新板()
    try:
        _限步调用(答案.闪一步, (板, led))
    except _跑不完:
        return False, ("闪一步 停不下来了 —— 它里面有个转不完的循环。\n"
                       "      「闪一步」只做**一步**：推进一次时间、翻转一次 LED，然后就该返回。\n"
                       "      循环（一直闪）是「闪烁」那个函数的事。")
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 闪一步(板子, led) 时出错了：{type(e).__name__}: {e}\n"
                       "      检查一下函数是不是接收了两个参数（板子、led），顺序别换。")
    return True, "调用没有报错"


def CHECK_闪一步推进了时间(答案):
    """★ 本课的新东西：时间必须真的被推进。

    怎么验：连着调 4 次，看板子上的时间有没有往前走。
    一点都不走 = 你只是改了 LED，没用时间 —— 那不叫闪烁，
    只是在真板子上"以 CPU 的速度狂闪"（肉眼看起来就是一直亮）。
    """
    if not hasattr(答案, "闪一步"):
        return False, "还没有定义「闪一步」函数"
    板, led = _新板()
    try:
        for _ in range(4):
            _限步调用(答案.闪一步, (板, led))
    except _跑不完:
        return False, "闪一步 停不下来（里面有转不完的循环），先让它只做一步"
    except Exception as e:                            # noqa: BLE001
        return False, f"调用出错了：{type(e).__name__}: {e}"

    if 板.时间 <= 0:
        return False, (
            "调了 4 次 闪一步，板子上的时间还是 0 —— 程序里没有用到时间。\n"
            "      模拟器的时间不会自己走，只有这一行会让它动：\n"
            "          板子.时间推进(0.5)      # 0.5 秒，闪烁周期就是 1 秒\n"
            "      （真板子上对应的是 time.sleep(0.5) 或者等定时器，\n"
            "        但在这里用 time.sleep 只会真的卡住，板子.时间 还是不动。）\n"
            "      ⚠ 少了时间控制，真板子上灯会以 CPU 的速度疯狂开关 ——\n"
            "        肉眼看到的其实是一直亮（或者一直灭），而且电流一直在冲击 LED。")
    if 板.时间 < 0.05:
        return False, (f"4 次 闪一步 一共只走了 {板.时间:.6f} 秒 —— 太快了。\n"
                       "      闪烁要人眼看得见，半个周期取 0.2~1 秒比较合适（比如 0.5）。")
    return True, f"4 次 闪一步 一共走了 {板.时间:.2f} 秒 —— 时间真的在动"


def CHECK_闪一步每次都翻转(答案):
    """★ 本课的核心检查：LED 必须**交替**变化。

    怎么验：从"灭"开始，连调 4 次，每次都记下状态。
    正确的序列是：灭 → 亮 → 灭 → 亮 → 灭（相邻两次必须不同）。
    一直亮或一直灭都会被这一条抓出来。
    """
    if not hasattr(答案, "闪一步"):
        return False, "还没有定义「闪一步」函数"
    板, led = _新板()

    序列 = [led.状态()]
    try:
        for _ in range(4):
            _限步调用(答案.闪一步, (板, led))
            序列.append(led.状态())
    except _跑不完:
        return False, "闪一步 停不下来（里面有转不完的循环），先让它只做一步"
    except Exception as e:                            # noqa: BLE001
        return False, f"调用出错了：{type(e).__name__}: {e}"

    交替 = all(序列[i] != 序列[i + 1] for i in range(len(序列) - 1))
    两种都有 = len(set(序列)) == 2

    if 交替 and 两种都有:
        return True, f"状态序列 {sequence_text(序列)} —— 亮灭交替，真的在闪"

    if not 两种都有:
        return False, (
            f"4 次 闪一步 之后，LED 一直是「{序列[-1]}」—— 只有一种状态。\n"
            f"      观测到的序列：{sequence_text(序列)}\n"
            "      「闪烁」要求两种状态**都出现过**：\n"
            "          · 一直是灭 —— 大概是把 led.翻转() 写成了 led.低()\n"
            "          · 一直是亮 —— 大概是把 led.翻转() 写成了 led.高()\n"
            "      翻转的写法是 led.翻转()：亮变灭、灭变亮，你不用先判断现在是什么状态。")

    return False, (
        f"状态没有交替变化。观测到的序列：{sequence_text(序列)}\n"
        "      正确的是：灭 → 亮 → 灭 → 亮 → 灭（相邻两次必须不同）。\n"
        "      常见原因：\n"
        "        · 每次都设成同一个状态（led.高()），没有翻转\n"
        "        · 一次调用里亮一下又灭回去（高()...低()），等于白闪 ——\n"
        "          「闪一步」只走**半个周期**，下一次调用才轮到灭\n"
        "      ⚠ 顺便记住：真板子上灯「不闪」最常见的原因不是代码，\n"
        "        而是 LED 正负极接反、或者忘了串限流电阻。模拟器看不见这些。")


def CHECK_闪一步节奏均匀(答案):
    """闪烁要有**均匀**的节奏：每一步推进的时间应该一样。"""
    if not hasattr(答案, "闪一步"):
        return False, "还没有定义「闪一步」函数"
    板, led = _新板()
    每步 = []
    try:
        for _ in range(4):
            之前 = 板.时间
            _限步调用(答案.闪一步, (板, led))
            每步.append(round(板.时间 - 之前, 6))
    except _跑不完:
        return False, "闪一步 停不下来（里面有转不完的循环），先让它只做一步"
    except Exception as e:                            # noqa: BLE001
        return False, f"调用出错了：{type(e).__name__}: {e}"

    if len(set(每步)) == 1 and 每步[0] > 0:
        return True, f"每一步都走了 {每步[0]} 秒 —— 节奏均匀"
    return False, (
        f"每一步推进的时间不一样：{每步}\n"
        "      闪烁的节奏要均匀（这也是「闪烁」和「乱闪」的区别）：\n"
        "      每一次 闪一步 推进的时间应该是同一个值。\n"
        "      检查一下 板子.时间推进(...) 是不是写在了会变的分支里。")


def CHECK_闪烁会按次数交替(答案):
    """★ 核心：闪烁(板子, led, 3) 必须真的闪 3 次然后停下来。

    怎么验：从"灭"开始，一次调用里做 3 遍 → 应该翻转 3 次、时间走 3 步、
    最后停在"亮"。只设一次状态的那种写法会在这里露馅。
    """
    if not hasattr(答案, "闪烁"):
        return False, "还没有定义「闪烁」函数"
    板, led = _新板()
    日志起点 = len(板.日志)
    try:
        _限步调用(答案.闪烁, (板, led, 3))
    except _跑不完:
        return False, (
            "闪烁(板子, led, 3) 没有停下来 —— 它里面有个转不完的循环。\n"
            "      检查会传给它一个次数，它必须做完就返回：\n"
            "          def 闪烁(板子, led, 次数):\n"
            "              for i in range(次数):\n"
            "                  闪一步(板子, led)\n"
            "      真板子的固件确实会写 while True（永远在 loop 里转），\n"
            "      但那样检查就永远等不到结果 —— 所以这一课要求写成「做几次就停」。")
    except TypeError as e:
        return False, (f"调用 闪烁(板子, led, 3) 时参数不对：{e}\n"
                       "      闪烁 必须接收三个参数：def 闪烁(板子, led, 次数):")
    except Exception as e:                            # noqa: BLE001
        return False, f"调用出错了：{type(e).__name__}: {e}"

    翻转 = _翻转次数(板, 日志起点)
    经过 = 板.时间

    if 经过 <= 0:
        return False, (
            f"闪烁 一次都没推进时间（板子.时间 还是 0）—— 灯没有「闪」的节奏。\n"
            f"      日志：\n          {板.日志文本()}\n"
            "      闪烁 = 翻转 + 等一会儿，两件事都要做。")

    if 翻转 < 3:
        return False, (
            f"闪烁(板子, led, 3) 只让 LED 变化了 {翻转} 次，时间走了 {经过:.2f} 秒。\n"
            f"      日志：\n          {板.日志文本()}\n"
            "      闪 3 次 = 翻转 3 次（亮、灭、亮）。\n"
            "      常见原因：把状态**设**成固定值（led.高()）而不是**翻转**（led.翻转()），\n"
            "      或者循环里只做了一次翻转。")

    if led.状态() != "亮":
        return False, (
            f"闪烁(板子, led, 3) 之后 LED 停在「{led.状态()}」，应该是「亮」。\n"
            f"      从灭开始翻转 3 次：灭→亮→灭→亮。\n"
            "      检查一下循环是不是多做了一次（比如 range(次数 + 1)）。")

    return True, (f"闪了 {翻转} 次、时间走了 {经过:.2f} 秒，最后停在「亮」—— "
                  f"次数、节奏、交替都对")


def CHECK_闪烁次数为0时什么都不做(答案):
    """边界：次数 = 0 就是"一次都不闪"，不该动时间、也不该动灯。"""
    if not hasattr(答案, "闪烁"):
        return False, "还没有定义「闪烁」函数"
    板, led = _新板()
    日志起点 = len(板.日志)
    try:
        _限步调用(答案.闪烁, (板, led, 0))
    except _跑不完:
        return False, "闪烁(板子, led, 0) 没有停下来 —— 循环条件有问题"
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 闪烁(板子, led, 0) 时出错了：{type(e).__name__}: {e}"

    翻转 = _翻转次数(板, 日志起点)
    经过 = 板.时间
    if 经过 > 0:
        return False, (f"闪烁(板子, led, 0) 走了 {经过:.2f} 秒 —— 次数是 0 就该什么都不做。\n"
                       "      检查一下循环是不是写成了 range(次数 + 1) 或者固定次数。")
    if 翻转:
        return False, (f"闪烁(板子, led, 0) 还是让 LED 变了 {翻转} 次 —— 次数是 0 就该一下都不闪。\n"
                       "      检查一下循环是不是写成了 while 而不是 for i in range(次数)。")
    return True, "次数为 0 时确实什么都没做"
