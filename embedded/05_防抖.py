def CHECK_松开再按能报第二次(答案):
    """松开、再按一次，必须能报出**新的**一次 —— 不能一次之后就"死"了。"""
    样本, 分界 = _抖动样本()
    板, 事件, 错误 = _驱动(答案, 样本)
    if 错误:
        return False, 错误

    第二次 = [t for t, _ in 事件 if t > 分界["松开完"]]
    if len(第二次) == 1:
        return True, f"松手之后再按，又报了 1 次（在 {第二次[0]:.3f} 秒）—— 能反复使用"
    if not 第二次:
        return False, (
            "松手、再按一次，你一次都没报 —— 这个函数用过一次就「死」了。\n"
            "      报过一次之后，一定要有一个**复位**的时机：\n"
            "          if not 现在:                  # 按钮松开了\n"
            "              板子.已确认 = False       # 准备好接受下一次\n"
            "      不然 已确认 一直是 True，第二次按下就再也报不出来了。")
    return False, (f"松手之后再按，报了 {len(第二次)} 次"
                   f"（时刻：{['%.3f' % t for t in 第二次[:6]]}）—— 应该正好 1 次。\n"
                   "      这一次输入是**干净**的（没有抖动），所以多出来的不是抖动问题，\n"
                   "      检查一下 已确认 的复位时机，以及松开时有没有把状态都清对。")


def CHECK_等到稳定才确认(答案):
    """报出来的那一次，必须是在电平**稳定了一小段**之后。

    怎么验：看"报 True 的时刻"和"最后一次电平变化的时刻"差多少。
    差 0（或者 1 毫秒）= 你看到跳变就报，等于没去抖。
    抖动最长能到 20 毫秒，所以这里要求至少等 5 毫秒才确认。
    """
    样本, 分界 = _抖动样本()
    板, 事件, 错误 = _驱动(答案, 样本)
    if 错误:
        return False, 错误
    if not 事件:
        return False, "还没有报出任何一次按下 —— 先让「抖动只算一次按下」那条通过"

    时刻, 变化时刻 = 事件[0]
    等了 = 时刻 - 变化时刻
    if 等了 >= 0.0045:
        return True, f"电平稳定了 {等了 * 1000:.1f} 毫秒之后才确认 —— 真的等了"

    return False, (
        f"电平刚变，你马上就确认了（只等了 {等了 * 1000:.1f} 毫秒）。\n"
        "      真实的抖动会持续 5~20 毫秒 —— 等这么短等于没等，\n"
        "      这次没被算错只是因为运气好（抖动的形状每次都不一样）。\n"
        "      改法：把等待时间加长到 20 毫秒左右：\n"
        "          板子.时间推进 不会自己发生，时间是**你**推的 —— 所以这里的「等」\n"
        "          就是比较两个时刻：板子.时间 - 板子.变化时间 >= 0.02\n"
        "      如果用的是「连续读到几次按下才算」这种按次数判断的写法：\n"
        "      那在真板子上也不算错，但这一课要求用**时间**来判断 ——\n"
        "      因为按钮的快慢、固件循环的快慢都会变，只有时间是不会骗人的。")


