# 第 05 课：防抖 —— 真实世界的麻烦

# 要做：
#   真实按钮按下去的一瞬间，里面的金属片会**弹跳** —— 电平在几毫秒里
#   通断好几次。程序如果直接读，就会把"按一次"当成"按了好几次"。
#   这一课要写一个**能识破抖动**的读按钮函数。
#
#   1. 写一个函数 准备(板子)：把三样东西记在板子上（检查每次都会先调它，
#      它就相当于真板子上的"开机初始化"）：
#          板子.上次读到 = False     # 上一次读到的是通还是断
#          板子.变化时间 = 0.0       # 电平上一次**发生变化**是什么时候
#          板子.已确认 = False       # 这一次"按住"是不是已经报过了
#
#   2. 写一个函数 有新按下(板子, 按钮)：每次被调用时返回 True 或 False。
#      只有"真的新按下了一次"才返回 True。三条要求：
#          · 抖动（几毫秒内通断乱跳）只能算**一次**按下
#          · 按住不放不能重复报（被调用一百次，也只有第一次是 True）
#          · 松开之后重新按，要能再报一次
#
#      思路（照这个骨架填就行）：
#          现在 = 板子.读到(按钮)
#          if 现在 != 板子.上次读到:               # 电平刚变了 —— 还不敢信
#              板子.上次读到 = 现在
#              板子.变化时间 = 板子.时间
#              return False                        # 先记下，等它稳住再说
#          if 现在 and 板子.时间 - 板子.变化时间 >= 0.02 and not 板子.已确认:
#              板子.已确认 = True                  # 稳定够 20 毫秒了 → 算一次真按下
#              return True
#          if not 现在:
#              板子.已确认 = False                 # 松开 = 准备好接受下一次
#          return False
#
#   检查会喂给它一段**抖动的输入**（前 15 毫秒里通断乱跳 8 次，然后稳定按住），
#   要求整个过程只报**一次** True。

# ─────────────────────────────────────────────────────
#  这一课的价值：真实世界是不完美的
# ─────────────────────────────────────────────────────
#
# 前四课的东西，在"理想的"世界里全都成立：引脚干净地变高变低，
# 按钮按下就是按下、松开就是松开。
#
# 真实世界不是这样。
#
# 机械按钮里面是一片弹性的金属片。你按下去的时候它不会"啪"一下干脆地接触，
# 而是会**弹几下**才稳定下来 —— 就像把一本书拍在桌子上，它会颤一下。
# 这几下弹跳在电平上看就是：通、断、通、断、通……
#
# 这段时间很短：**1 到 20 毫秒** —— 短到你完全感觉不到，
# 但程序跑得比这快得多（单片机每秒能读几十万次）。
# 于是你按一下，程序数出来 3 次、5 次、8 次。
#
# 这就是这一课要解决的全部问题。听起来很小，但它是**分水岭**：
#
#     纯软件的世界：输入是干净的（你要的数据就在那里，不多不少）
#     嵌入式的世界：输入是**物理**的，物理的东西天生不干净
#
# 传感器有噪声、电源会波动、通信会丢包、晶振有误差、温度会漂移……
# 一个嵌入式工程师的大半功力，都花在"对付不完美"上。
#
# 顺便说一句：这个 bug 最坑的地方是**在实验室里测不出来**。
# 你拿一块开发板按十次，可能十次都正常 —— 因为新按钮弹跳轻。
# 等产品装到外壳里、按钮用旧了、天冷了，它才开始"按一下跳三个"。
#
# ─────────────────────────────────────────────────────
#  抖动的电平长什么样
# ─────────────────────────────────────────────────────
#
#   一格 = 1 毫秒。▁=断开  █=接通
#
#        ▁█▁██▁█▁█▁█▁█▁██████████████████████████████
#        ↑手指按下
#        └─── 抖动 15 毫秒 ───┘└──── 手一直按着 ────→
#
#   人看到的是"按了一下"；程序看到的是"通了 7 次"。
#
# 两种对付办法：
#
#   ① 硬件去抖：在按钮两端并一个 0.1μF 电容（再加个施密特触发器更稳）。
#      抖动被电容"磨平"，引脚上就是干净的跳变。
#      ⚠ 这一半模拟器完全看不见 —— 它只模拟程序。
#
#   ② 软件去抖（这一课写的）：**不马上相信**这次电平变化，
#      等它稳定一小段时间（比如 20 毫秒）再确认。
#      好处是不花钱、不改电路，坏处是你要在代码里把它写对。
#
# ─────────────────────────────────────────────────────
#  ⚠ 为什么这里不能用"睡 20 毫秒再看一眼"的写法
# ─────────────────────────────────────────────────────
#
# 你可能听过最经典的去抖写法：
#     "读到电平变了 → 等 20 毫秒 → 再读一次确认"
# 真板子上这确实能用（那 20 毫秒用 sleep 或者定时器等）。
#
# 但在**这个模拟器**里它算不出正确结果，原因是模拟器一个很诚实的设计：
# 检查是在**两次调用之间**改变引脚电平的。你在函数里面"等"（板子.时间推进），
# 引脚的状态并不会跟着变 —— 所以你"再看一眼"看到的还是刚才那个值。
# 结果就是：抖动的那几次跳变，在你的函数看来是四次**独立的**按下。
#
# 所以这一课要写的是**跨调用**的去抖：把"上次读到什么、什么时候变的"
# 记在设备上；每次被调用时判断"这个电平已经稳定够久了吗"。
#
# 这也是真实固件里最常见的写法 —— 因为固件本来就待在 loop 里被反复调用，
# 它不需要"停下来等"，它只要每次都想一想。
#
# 所以这一课的 有新按下(板子, 按钮) 不是"读一次按钮"，
# 而是"**看一眼、然后决定要不要报告一次按下**"。它会被反复调用。
#
# ─────────────────────────────────────────────────────
#  ⚠ 模拟器验证不了电路（每一课都要说一遍）
# ─────────────────────────────────────────────────────
#
# 检查全过 ≠ 插上板子就能用。模拟器只跑**程序逻辑**，它看不见：
#   · **限流电阻** —— LED 必须串 220Ω~1kΩ，直接接引脚会烧
#   · **LED 正负极** —— 长脚（正极）接引脚、短脚（负极）接地，接反了不亮
#   · **接线位置** —— 按钮接在哪两个脚、有没有上拉电阻，只有你自己知道
#   · **去抖电容**有没有真的焊上（软件去抖只是替代方案，不是唯一方案）
#   · 按钮是不是常开、线有没有插紧（接触不良的线，抖动会比你手里的按钮厉害得多）
#
# 真实故障里"按一次跳好几次"有一半是**接触不良**，不是按钮本身 ——
# 软件去抖能救一部分，但插紧那根线才是根治。
#
# ─────────────────────────────────────────────────────
#  写完之后
# ─────────────────────────────────────────────────────
#   python -m hybridengine_light 嵌入式 检查 05


