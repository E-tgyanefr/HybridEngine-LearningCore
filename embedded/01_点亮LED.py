# 第 01 课：点亮一个 LED —— 让程序控制真实世界的东西

# 要做：
#   写一个函数 亮灯(板子, led)，把传入的 LED 点亮。
#   就这一件事 —— 但它是嵌入式的"Hello World"。

# ─────────────────────────────────────────────────────
#  为什么第一件事是点灯
# ─────────────────────────────────────────────────────
#
# 编程课的第一句通常是 print("Hello") —— 让程序**说出来**。
# 嵌入式的第一件事是**让程序动手**：点亮一个真实的灯。
#
# 差别在于：print 的结果只在屏幕上，而点灯的结果在**物理世界**里。
# 这就是嵌入式最让人着迷的地方 —— 你的代码能让东西动起来。
#
# ─────────────────────────────────────────────────────
#  三个概念（比语法重要得多）
# ─────────────────────────────────────────────────────
#
# ① **引脚（pin）**
#    板子边上那些金属小脚。每个引脚可以被程序设成"输出"或"输入"。
#      · 输出 = 板子往外送电（点灯、驱动蜂鸣器、转马达）
#      · 输入 = 板子读外面的电平（按钮、传感器）
#
#    写错引脚号在真实硬件上**不会报错** —— 板子只是毫无反应。
#    所以模拟器特意做成报错，帮你养成"先确认引脚号"的习惯。
#
# ② **电平（高/低）**
#    引脚只有两种状态：高（有电压）或低（没电压）。
#    LED 接在引脚和地之间，所以：
#        引脚 = 高  →  有电流 → 灯亮
#        引脚 = 低  →  没电流 → 灯灭
#    没有"半亮"这回事 —— 除非你用 PWM（后面会讲）。
#
# ③ **限流电阻**（⚠ 这个模拟器管不了）
#    LED 直接接引脚会**烧掉**（它几乎没有电阻，电流会很大）。
#    必须串一个电阻（通常 220Ω~1kΩ）。
#
#    **模拟器发现不了这个错误。** 它只模拟程序逻辑，不模拟电路。
#    所以我在这里说清楚：检查通过 ≠ 插上板子就能亮。
#
# ─────────────────────────────────────────────────────
#  写完之后
# ─────────────────────────────────────────────────────
#   python -m learncode 嵌入式 检查 01
#
# 你不需要买板子。模拟器会替你"插上"板和 LED。


# ── 下面是检查用的代码，不用改 ──

def _新板():
    """建一块模拟板子，带一个 LED。"""
    from learncode.mcu import 模拟器
    板 = 模拟器(引脚数=8, 名字="模拟开发板")
    led = 板.输出引脚(2, 名字="LED")
    return 板, led


def CHECK_函数存在(答案):
    if not hasattr(答案, "亮灯"):
        return False, ("还没有定义「亮灯」这个函数。\n"
                       "      写法：\n"
                       "          def 亮灯(板子, led):\n"
                       "              ...")
    if not callable(答案.亮灯):
        return False, "「亮灯」存在，但它不是函数。要用 def 定义。"
    return True, "亮灯 是个函数"


def CHECK_能调用不报错(答案):
    if not hasattr(答案, "亮灯"):
        return False, "还没有定义「亮灯」函数"
    板, led = _新板()
    try:
        答案.亮灯(板, led)
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 亮灯(板子, led) 时出错了：{type(e).__name__}: {e}\n"
                       f"      检查一下你的函数有没有正确接收两个参数（板子、led）。")
    return True, "调用没有报错"


def CHECK_LED真的亮了(答案):
    """这一条是本课的核心：调用之后 LED 必须真的变成「亮」。"""
    if not hasattr(答案, "亮灯"):
        return False, "还没有定义「亮灯」函数"
    板, led = _新板()

    before = led.状态()
    try:
        答案.亮灯(板, led)
    except Exception as e:                            # noqa: BLE001
        return False, f"调用出错了：{type(e).__name__}: {e}"

    after = led.状态()
    if after == "亮":
        return True, f"LED 从「{before}」变成了「{after}」—— 点亮成功"

    return False, (
        "LED 还是「灭」的 —— 你的函数没有把它点亮。\n"
        "      要让 LED 亮，需要把引脚的**电平拉高**：\n"
        "          led.高()\n"
        "      为什么高电平就亮：LED 接在引脚和地之间，\n"
        "        引脚高 → 有电流流过 → 亮\n"
        "        引脚低 → 没电流     → 灭\n"
        "      ⚠ 顺便记住（模拟器管不了的事）：真实的 LED 必须串一个**限流电阻**，\n"
        "        否则电流太大会烧掉它。")


def CHECK_用的是引脚而不是乱改状态(答案):
    """防止"直接把状态设成亮"这种绕过引脚的写法。

    怎么验：板子会记录每一次操作。正常的做法一定会在日志里留下
    "LED → 高" 这一行。如果日志里没有，说明学生用别的手段改了状态 ——
    那在真实硬件上是不存在的路径。
    """
    if not hasattr(答案, "亮灯"):
        return False, "还没有定义「亮灯」函数"
    板, led = _新板()
    try:
        答案.亮灯(板, led)
    except Exception:                                 # noqa: BLE001
        return False, "调用出错了，先让它能正常执行"

    if "高" in 板.日志文本():
        return True, "从日志看，你确实是通过引脚把它拉高的"
    return False, (
        "板子的操作日志里没有看到「拉高引脚」这一步。\n"
        f"      日志内容：\n          {板.日志文本()}\n"
        "      请用 led.高() 来点亮它 —— 那是程序控制硬件的正规路径。")
