import sys


class _跑不完(Exception):
    """学生的函数停不下来时，用它从函数**内部**把它打断。"""


def _限步调用(函数, 参数=(), 最多行数=200000):
    """调用学生的函数；如果它停不下来，就把它打断，而不是让检查永远卡住。

    这一课特别需要：学生很容易写 `while True:` 去"一直盯着按钮看"。
    那在真板子上是对的（固件本来就永远在 loop 里转），但在这里会把
    检查命令永久挂住 —— 屏幕上一片空白，比报错糟糕得多。
    """
    计数 = [0]

    def 追踪(frame, event, arg):
        if event == "line":
            计数[0] += 1
            if 计数[0] > 最多行数:
                raise _跑不完()
        return 追踪

    原来的 = sys.gettrace()
    sys.settrace(追踪)
    try:
        return 函数(*参数)
    finally:
        sys.settrace(原来的)


def _建好(答案):
    """建板、LED、按钮（引脚 3，带上拉），并调用学生的 初始化。

    返回 (板, led, 按钮, 错误说明)。错误说明非空 = 这一步就没成。
    """
    if not hasattr(答案, "初始化"):
        return None, None, None, ("还没有定义「初始化」函数。\n"
                                  "      写法：\n"
                                  "          def 初始化(板子):\n"
                                  "              板子.模式 = 0\n"
                                  "              板子.上次按下 = False")
    if not callable(答案.初始化):
        return None, None, None, "「初始化」存在，但它不是函数。要用 def 定义。"

    from hybridengine_light.mcu import 模拟器
    板 = 模拟器(引脚数=8, 名字="模拟开发板")
    led = 板.输出引脚(2, 名字="LED")
    按钮 = 板.输入引脚(3, 名字="按钮", 上下拉="上拉")

    try:
        答案.初始化(板)
    except Exception as e:                            # noqa: BLE001
        return 板, led, 按钮, (f"调用 初始化(板子) 时出错了：{type(e).__name__}: {e}\n"
                               "      它只该做一件事：把状态变量建在板子上。")

    if not hasattr(板, "模式"):
        return 板, led, 按钮, (
            "初始化 跑完了，但板子上找不到「模式」这个变量。\n"
            "      状态要**存在板子上**（真固件里状态就存在设备里，不是每次重新算）：\n"
            "          def 初始化(板子):\n"
            "              板子.模式 = 0            #  ← 检查会读这个名字\n"
            "              板子.上次按下 = False\n"
            "      把状态放在函数外面的全局变量里也能跑，但那样一换板子状态就串了。")
    return 板, led, 按钮, ""


def _按一下(答案, 板, 按钮, led):
    """在一次"按下"和一次"松开"上各调用一次学生的 按一下。"""
    板.按下(按钮)
    _限步调用(答案.按一下, (板, 按钮, led))
    板.松开(按钮)
    _限步调用(答案.按一下, (板, 按钮, led))


def _翻转次数(板, 从第几行=0):
    """数日志里 LED 的状态变化了几次（→ 高 / → 低 都算一次变化）。"""
    return sum(1 for 行 in 板.日志[从第几行:] if ("→ 高" in 行 or "→ 低" in 行))


def CHECK_两个函数都在(答案):
    if not hasattr(答案, "初始化"):
        return False, "还没有定义「初始化」函数（def 初始化(板子)）"
    if not hasattr(答案, "按一下"):
        return False, ("还没有定义「按一下」函数。\n"
                       "      写法：def 按一下(板子, 按钮, led): ... （三个参数，顺序别换）")
    if not callable(答案.初始化):
        return False, "「初始化」不是函数。要用 def 定义。"
    if not callable(答案.按一下):
        return False, "「按一下」不是函数。要用 def 定义。"
    return True, "初始化、按一下 都是函数"


def CHECK_初始化把模式建在板子上(答案):
    """状态必须有一个明确的起点 —— 真固件里这叫"上电初始化"。"""
    板, led, 按钮, 错误 = _建好(答案)
    if 错误:
        return False, 错误
    值 = getattr(板, "模式", None)
    if 值 == 0:
        return True, "初始化之后 板子.模式 = 0（从「灭」开始）"
    return False, (f"初始化之后 板子.模式 应该是 0（灭），实际是 {值!r}。\n"
                   "      设备一上电必须有一个确定的起点，不能是「随便什么值」。\n"
                   "      改法：\n"
                   "          def 初始化(板子):\n"
                   "              板子.模式 = 0\n"
                   "              板子.上次按下 = False")


def CHECK_模式会循环切换(答案):
    """★ 本课的核心检查：连按多次，模式必须**循环**切换。

    怎么验：按 6 次，每次记下 板子.模式。
    正确的结果是 1、2、0、1、2、0 —— 每次 +1 并且回到开头。
    一直不变、一直往上加、跳着变，都会被抓出来。
    """
    板, led, 按钮, 错误 = _建好(答案)
    if 错误:
        return False, 错误
    if not hasattr(答案, "按一下"):
        return False, "还没有定义「按一下」函数"

    序列 = []
    try:
        for _ in range(6):
            _按一下(答案, 板, 按钮, led)
            序列.append(getattr(板, "模式", None))
    except _跑不完:
        return False, (
            "按一下 没有停下来 —— 它里面有个转不完的循环。\n"
            "      检查会替你把「按下」这件事喂给它：按一下 只处理**一次**按钮事件，\n"
            "      处理完就返回。真板子的固件确实会写 while True，但那是固件的循环，\n"
            "      不是这个函数的。")
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 按一下(板子, 按钮, led) 时出错了：{type(e).__name__}: {e}\n"
                       "      检查一下参数是不是三个（板子、按钮、led），顺序别换。")

    期望 = [1, 2, 0, 1, 2, 0]
    if 序列 == 期望:
        return True, f"连按 6 次，模式是 {序列} —— 0→1→2→0 循环切换"

    越界 = [v for v in 序列 if v not in (0, 1, 2)]
    if 越界:
        return False, (
            f"模式出现了 0 / 1 / 2 以外的值：{序列}\n"
            "      模式只有三种，回到开头要用**取余**：\n"
            "          板子.模式 = (板子.模式 + 1) % 3      # 2 再加 1 就变回 0\n"
            "      光写 板子.模式 + 1 的话它会一直涨下去，第 4 种模式谁也没定义。")

    if 序列 == [0] * 6:
        return False, (
            "按了 6 次，板子.模式 一直是 0 —— 模式根本没变。\n"
            "      可能的原因：\n"
            "        · 按一下 里读的是别的引脚（按钮在引脚 3）\n"
            "        · 判断写成了 if 板子.读到(按钮): 但没真的改 板子.模式\n"
            "        · 换了模式却把结果存到了别的变量上（检查读的是 板子.模式）\n"
            "      检查一下这三行是不是都在：\n"
            "          现在按下 = 板子.读到(按钮)\n"
            "          if 现在按下 and not 板子.上次按下:\n"
            "              板子.模式 = (板子.模式 + 1) % 3")

    return False, (
        f"连按 6 次，模式是 {序列}\n"
        f"      期望是 {期望}（每次 +1，超过 2 就回到 0）。\n"
        "      排查方向：\n"
        "        · 是不是少了好几次变化 —— 边沿检测写反了（比如把 not 丢了），\n"
        "          结果只在松开的那一下才换模式\n"
        "        · 是不是每次都变两次 —— 按下和松开各调了一次 按一下，\n"
        "          如果两个都触发切换就会跳着走\n"
        "      用一个变量记住「上一次读到什么」，只在「上次没按、这次按了」时切换。")


def CHECK_模式看得见(答案):
    """模式不能只是个数字 —— 它必须**看得见**（灭 / 亮）。"""
    板, led, 按钮, 错误 = _建好(答案)
    if 错误:
        return False, 错误
    if not hasattr(答案, "按一下"):
        return False, "还没有定义「按一下」函数"

    try:
        # 模式 0：什么都不按时，灯应该是灭的
        _限步调用(答案.按一下, (板, 按钮, led))
    except _跑不完:
        return False, ("按一下 停不下来 —— 它里面有个转不完的循环。\n"
                       "      它只处理**一次**按钮事件，处理完就返回。")
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 按一下 时出错了：{type(e).__name__}: {e}"
    if led.状态() != "灭":
        return False, (
            f"模式 0 的时候 LED 是「{led.状态()}」，应该是「灭」。\n"
            "      每个模式都要对应一个**看得见**的效果，不然用户根本不知道\n"
            "      自己按到第几个模式了 —— 真实产品里这叫「状态指示」。\n"
            "      模式 0 → led.低()")

    try:
        # 切到模式 1：按一次
        _按一下(答案, 板, 按钮, led)
    except _跑不完:
        return False, ("按一下 停不下来 —— 它里面有个转不完的循环。\n"
                       "      它只处理**一次**按钮事件，处理完就返回。")
    except Exception as e:                            # noqa: BLE001
        return False, f"按一下 时出错了：{type(e).__name__}: {e}"
    模式 = getattr(板, "模式", None)
    if 模式 != 1:
        return False, f"按了一下之后 板子.模式 是 {模式!r}，应该是 1（先让切换能跑通）"
    if led.状态() != "亮":
        return False, (
            f"模式 1 的时候 LED 是「{led.状态()}」，应该是「亮」。\n"
            "      模式 1 → led.高()")
    return True, "模式 0 → 灭、模式 1 → 亮 —— 模式真的看得见"


def CHECK_按住不放只算一次(答案):
    """★ 边上检测的核心：按住不放不能一直换模式。

    怎么验：按住不放，连着调 3 次 按一下。
    真板子上这个函数每秒会被调用几万次 —— 如果它在"按着"的时候
    每次都切换，模式会瞬间转好几千圈。
    """
    板, led, 按钮, 错误 = _建好(答案)
    if 错误:
        return False, 错误
    if not hasattr(答案, "按一下"):
        return False, "还没有定义「按一下」函数"

    板.按下(按钮)
    try:
        for _ in range(3):
            _限步调用(答案.按一下, (板, 按钮, led))
    except _跑不完:
        return False, "按一下 停不下来（里面有转不完的循环）"
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 按一下 时出错了：{type(e).__name__}: {e}"

    模式 = getattr(板, "模式", None)
    if 模式 == 1:
        return True, "按住不放连调 3 次，模式还是 1 —— 没有重复触发"
    if 模式 == 3:
        return False, (
            "按住不放的时候，每调用一次 按一下 模式就 +1（3 次变成了 3）。\n"
            "      问题在于程序分不清：\n"
            "          「按钮**现在**是按下的」   ← 这是**状态**，一直是真的\n"
            "          「按钮**刚刚**被按下」     ← 这才是**事件**，只发生一次\n"
            "      真板子的固件每秒判断几万次，你按住 0.2 秒它就会切换几千次。\n"
            "      改法：把上一次读到的值也存起来，只在「跳变的那一下」处理：\n"
            "          现在按下 = 板子.读到(按钮)\n"
            "          if 现在按下 and not 板子.上次按下:   # ← 上次没按、这次按了\n"
            "              板子.模式 = (板子.模式 + 1) % 3\n"
            "          板子.上次按下 = 现在按下             # ← 这一行别忘\n"
            "      顺便记住：这个技巧叫「边沿检测」，第 05 课会讲它还不够用。")
    return False, (f"按住不放连调 3 次之后，板子.模式 是 {模式!r}（期望 1）。\n"
                   "      可能是切换的条件写错了，先在「松开」状态下也调一次看看模式怎么变。")


def CHECK_第三个模式真的在闪(答案):
    """模式 2 = 闪两下。这一条验它真的用了时间、真的闪了。

    怎么验：切到模式 2，看这段时间里 LED 变了几次、时间走了多少。
    """
    板, led, 按钮, 错误 = _建好(答案)
    if 错误:
        return False, 错误
    if not hasattr(答案, "按一下"):
        return False, "还没有定义「按一下」函数"

    try:
        _按一下(答案, 板, 按钮, led)               # → 模式 1
        if getattr(板, "模式", None) != 1:
            return False, "还没切到模式 2：模式 1 都还没跑通，先把切换做对"
        日志起点 = len(板.日志)
        时间起点 = 板.时间
        板.按下(按钮)                                # → 模式 2
        _限步调用(答案.按一下, (板, 按钮, led))
        板.松开(按钮)
    except _跑不完:
        return False, "按一下 停不下来（里面有转不完的循环）"
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 按一下 时出错了：{type(e).__name__}: {e}"

    模式 = getattr(板, "模式", None)
    if 模式 != 2:
        return False, f"第二次按下之后 板子.模式 是 {模式!r}，应该是 2"

    经过 = 板.时间 - 时间起点
    翻转 = _翻转次数(板, 日志起点)
    if 经过 <= 0:
        return False, (
            "模式 2 一点时间都没走（板子.时间 没变）—— 那不是「闪」，那只是「亮了一下」。\n"
            "      闪 = 翻转 + 等一会儿：\n"
            "          led.高(); 板子.时间推进(0.2)\n"
            "          led.低(); 板子.时间推进(0.2)      # 这就是一下\n"
            "      模拟器的时间不会自己走，要靠 板子.时间推进（第 03 课讲过）。")
    if 翻转 < 4:
        return False, (
            f"模式 2 只让 LED 变了 {翻转} 次（时间走了 {经过:.2f} 秒）—— 闪两下应该是 4 次变化。\n"
            f"      日志：\n          {板.日志文本()}\n"
            "      闪两下 = 亮→灭→亮→灭，也就是循环 2 次、每次一高一低。")
    if led.状态() != "灭":
        return False, (f"模式 2 闪完之后 LED 停在「{led.状态()}」，应该停在「灭」。\n"
                       "      让每个模式结束后都回到一个确定的状态，"
                       "下一个模式才不会从奇怪的地方接着走。")
    return True, f"模式 2 真的闪了（变了 {翻转} 次，时间走了 {经过:.2f} 秒，最后停在灭）"
