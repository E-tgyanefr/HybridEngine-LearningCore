# ─────────────────────────────────────────────────────
#  这一课你会学到
# ─────────────────────────────────────────────────────
#    状态机：按一下换一种模式
#
#  需要先会
#    第 02 课：按钮控制、第 03 课：时间


# 要做：
#   这一课要做的东西真板子上到处都是：**按一下按钮，换一种工作模式**。
#
#   1. 写一个函数 初始化(板子)：把状态建在**板子上**（真固件里状态就存在设备里）：
#         板子.模式 = 0             # 0 = 灭    1 = 亮    2 = 闪两下
#         板子.上次按下 = False     # 上一次读到的按钮状态（下面讲为什么要记它）
#
#   2. 写一个函数 按一下(板子, 按钮, led)：处理"这一瞬间"发生的事：
#         现在按下 = 板子.读到(按钮)
#         # 只在"上次没按、这次按了"的那**一下**才换模式：
#         if 现在按下 and not 板子.上次按下:
#             板子.模式 = (板子.模式 + 1) % 3      # 0→1→2→0 循环
#         板子.上次按下 = 现在按下                  # 记住这一次读到了什么
#         # 然后按当前模式把 LED 设成对应的样子：
#         #   0 → led.低()      灭
#         #   1 → led.高()      亮
#         #   2 → 闪两下（用 板子.时间推进 + led.翻转），最后停在灭
#
#   检查会模拟"按下 → 松开 → 按下 → 松开……"，每次读一下 板子.模式：
#   连按 6 次必须是 1、2、0、1、2、0 —— **循环**，不是一直往上加。
#   还会按住不放连调 3 次：模式必须只动**一次**。
#   （所以「板子.模式」这个名字要写对，检查是读它来判断的。）

# ─────────────────────────────────────────────────────
#  这一课才是"程序"真正开始的地方
# ─────────────────────────────────────────────────────
#
# 前三课的代码都是"一条直线"：
#     设一个状态 → 读输入 → 闪一下
# 每一步做什么，看代码就能数出来。
#
# 但从这一课开始，程序有了**记忆**：
#     "现在处于哪种模式" 这件事，被存进了一个变量里。
# 于是同一行代码，在不同的时刻会做不同的事 —— 这就是状态机。
#
# 为什么说它是嵌入式里最重要的思维模型：
# 你身边每一个有点"脾气"的设备，行为都是状态机：
#     · 微波炉：待机 → 设定时间 → 加热 → 叮 → 待机
#     · 红绿灯：绿 → 黄 → 红 → 绿
#     · 洗衣机：进水 → 洗 → 漂 → 脱水 → 完
#     · 手机：锁屏 → 亮屏 → 解锁 → 亮屏 → 锁屏
#
# 写这类程序的套路永远是同一句话：
#     **当前状态 + 这次输入 → 新状态 + 输出**
# 你能把这句话写清楚，代码就只是把它翻译一遍。
#
# ─────────────────────────────────────────────────────
#  为什么必须记"上次按下"
# ─────────────────────────────────────────────────────
#
# 这是初学者最常踩的坑，也是这一课第二个要学的东西。
#
# 如果只写 if 板子.读到(按钮): 板子.模式 += 1 —— 会怎样？
# 真板子的固件是**每秒判断几万次**的。你按住按钮 0.2 秒，
# 这个 if 就被执行了几千次 → 模式瞬间转了几千圈。
# 你的手指还没抬起来，模式已经不知道转到哪里去了。
#
# 问题出在：程序分不清
#       "按钮**现在**是按下的"（状态）
#  和  "按钮**刚刚被按下**"  （事件）
#
# 想要的是后者。做法就是记住上一次读到什么：
#       上次是松、这次是按下  →  这是一次**新按下**，处理它
#       上次是按下、这次还是按下 →  人家一直按着，什么都不做
#
# 这个技巧叫**边沿检测**（检测电平"跳变"的那一下）。
# 第 05 课会告诉你：光有边沿检测还不够 —— 真实按钮会抖。
#
# ─────────────────────────────────────────────────────
#  为什么模式要写成 (模式 + 1) % 3
# ─────────────────────────────────────────────────────
#
# % 是取余数。任何数 % 3 的结果只可能是 0、1、2：
#       0 + 1 = 1 → 1 % 3 = 1
#       1 + 1 = 2 → 2 % 3 = 2
#       2 + 1 = 3 → 3 % 3 = 0      ← 自动回到开头
#
# 比手写 if 模式 == 2: 模式 = 0 else: 模式 += 1 短，而且**加多少种模式都不用改**：
# 以后从 3 种模式变成 5 种，只改那个 3 就行。
#
# ─────────────────────────────────────────────────────
#  ⚠ 模拟器验证不了电路（每一课都要说一遍）
# ─────────────────────────────────────────────────────
#
# 检查全过 ≠ 插上板子就能用。模拟器只跑**程序逻辑**，它看不见：
#   · **限流电阻** —— LED 必须串 220Ω~1kΩ，直接接引脚会烧
#   · **LED 正负极** —— 长脚（正极）接引脚、短脚（负极）接地，接反了模式全对也不亮
#   · **接线位置 / 上下拉** —— 按钮接在哪个引脚、有没有上拉电阻，只有你自己知道
#   · 还有：按钮是不是常开、有没有真的接到地
#
# 一个很典型的真实故障：逻辑全对，但按钮那根线没插紧 ——
# 表现是"按十次只成功两次"，和代码毫无关系。
#
# ─────────────────────────────────────────────────────
#  写完之后
# ─────────────────────────────────────────────────────
#   python -m hybridengine_light 嵌入式 检查 04


