"""第 03 课的参考答案：闪烁。"""


def 闪一步(板子, led):
    """半个闪烁周期：让时间走一段，再把 LED 翻过来。

    ══ 两个要点 ══
    ① 时间必须**手动**推进。模拟器里的时间不会自己走 ——
       在真板子上这一行是 time.sleep(0.5) 或者"等定时器到点"。
    ② 用「翻转」而不是「设成亮/灭」：翻转不关心现在是什么状态，
       任何时刻调用都是对的，也少一个写错的机会。

    ⚠ 真板子上：LED 必须串限流电阻（220Ω~1kΩ）；
      正负极接反了永远不亮。这两件事模拟器都看不见。
    """
    板子.时间推进(0.5)
    led.翻转()


def 闪烁(板子, led, 次数):
    """做 次数 遍 闪一步。

    用 for + 次数，而不是 while True：
    固件在真板子上确实永远在 loop 里转，但那样检查就永远等不到结果 ——
    所以这里做成"做几次就停"。
    """
    for _ in range(次数):
        闪一步(板子, led)
