"""第 04 课的参考答案：状态机 —— 按一下换一种模式。"""

模式数 = 3          # 0 = 灭，1 = 亮，2 = 闪两下


def 初始化(板子):
    """相当于真固件里的"上电初始化"：给设备一个确定的起点。

    状态存在**板子上**（真固件里状态就存在设备里）。
    注意 上次按下：它是"边沿检测"的关键，下面解释。
    """
    板子.模式 = 0
    板子.上次按下 = False


def 按一下(板子, 按钮, led):
    """处理一瞬间的事：读一次按钮 → 可能换模式 → 把 LED 设成新模式的样子。"""
    现在按下 = 板子.读到(按钮)

    # ★ 边沿检测：只在"上次没按、这次按了"的那一下才换模式。
    #
    # 为什么不能直接写 if 板子.读到(按钮): 板子.模式 += 1 ——
    # 真板子的固件每秒判断几万次，你按住 0.2 秒它就切换几千次，
    # 手指还没抬起来模式已经不知道转哪去了。
    # 程序必须分得清"现在按着"（状态）和"刚刚按下"（事件）。
    if 现在按下 and not 板子.上次按下:
        板子.模式 = (板子.模式 + 1) % 模式数     # 2 再加 1 就回到 0

    板子.上次按下 = 现在按下                     # 这一行别忘，它就是"记忆"

    # 把"当前模式"变成看得见的东西 —— 不然用户不知道自己按到第几个了。
    if 板子.模式 == 0:
        led.低()                                # 灭
    elif 板子.模式 == 1:
        led.高()                                # 亮
    else:
        闪两下(板子, led)


def 闪两下(板子, led):
    """第 03 课的技能在这里变成了状态机里的一个"模式"。

    ⚠ 真板子上：限流电阻、LED 正负极、按钮接在哪个脚、有没有上拉 ——
      模拟器一个都验证不了。逻辑全对而板子不听话时，先查接线。
    """
    for _ in range(2):
        led.高()
        板子.时间推进(0.2)
        led.低()
        板子.时间推进(0.2)
