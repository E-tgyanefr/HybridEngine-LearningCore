"""第 05 课的参考答案：防抖。"""

去抖时间 = 0.02         # 电平要稳定这么久，才承认它（20 毫秒）


def 准备(板子):
    """相当于开机初始化：把去抖要用的三样东西记在**设备上**。"""
    板子.上次读到 = False        # 上一次读到的是通还是断
    板子.变化时间 = 0.0          # 电平上一次发生变化是什么时候
    板子.已确认 = False          # 这一次"按住"报过了没有


def 有新按下(板子, 按钮):
    """每轮 loop 调用一次：这一轮有没有"一次真的新按下"？

    ══ 为什么不能只做边沿检测（第 04 课那一套）══
    机械按钮按下的一瞬间，金属片会弹跳 1~20 毫秒：
    通、断、通、断…… 每一次跳变在程序看来都是"电平刚变"，
    所以边沿检测会把"按一次"数成 7 次。
    实验室里测不出来（新按钮弹跳轻），装到外壳里用旧了才发作。

    ══ 所以：不要马上相信这次变化 ══
    先把它记成"刚变的、什么时候变的"，然后**等它稳定够久**再确认。
    这叫跨调用的去抖，也是真实固件里最常见的写法。

    ══ 为什么不用"睡 20 毫秒再看一眼" ══
    真板子上那种写法能用，但在这个模拟器里算不出正确结果：
    检查是在两次调用之间改电平的，函数里"等"的时候引脚不会变，
    所以你再看一眼看到的还是刚才那个值，抖动照样被算成好几次。

    ⚠ 真板子上对症的另一半：按钮两端并一个 0.1μF 电容（硬件去抖），
      以及 —— 把线插紧。模拟器验证不了这些。
    """
    现在 = 板子.读到(按钮)

    # ① 电平刚变：还不敢信，只记下"什么时候变的"
    if 现在 != 板子.上次读到:
        板子.上次读到 = 现在
        板子.变化时间 = 板子.时间
        return False

    # ② 松开了：准备好接受下一次
    if not 现在:
        板子.已确认 = False
        return False

    # ③ 已经报过了：按住不放不能重复报
    if 板子.已确认:
        return False

    # ④ 稳定够久了：这才是"一次真的按下"
    if 板子.时间 - 板子.变化时间 >= 去抖时间:
        板子.已确认 = True
        return True

    return False
