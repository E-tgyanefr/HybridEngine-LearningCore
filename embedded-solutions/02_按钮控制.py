"""第 02 课的参考答案：按钮控制 LED。"""


def 接按钮(板子):
    """在引脚 3 上建一个输入引脚，并把它交出去（检查要用它来按）。

    ⚠ 上下拉不能省：没有它，引脚就是"悬空"的，
      真实电路里读到的值是随机的（按十次可能只认两次）。
      真板子上这个"确定的默认值"是靠一个真的电阻做到的 ——
      模拟器只能提醒你，看不见那个电阻。
    """
    return 板子.输入引脚(3, 名字="按钮", 上下拉="上拉")


def 按钮点灯(板子, 按钮, led):
    """读一次按钮，让 LED 跟着它的状态走。

    ⚠ 真板子上通常是**反过来**的：上拉接法时按下读到的是**低**电平。
      模拟器统一成"按下 = True"，是为了让你先专心学控制流程。
      顺便记住：限流电阻、LED 正负极、按钮接在哪两个脚 ——
      这三件事模拟器一个都验证不了。
    """
    if 板子.读到(按钮):
        led.高()          # 按下 → 亮
    else:
        led.低()          # 松开 → 灭
