"""小游戏 2：井字棋（图形版，用 Stage 画）

════ 这个游戏要教的东西 ════

猜数字是"命令行 + 纯逻辑"，这个不一样，它把**画面**也管起来：

    棋盘状态（数据）  →  画出来（显示）  →  按键（输入）  →  改状态

这四步是一个循环，也是**所有游戏的最小骨架**。看懂这个，
换个游戏（贪吃蛇、俄罗斯方块）也是同样的骨架。

════ 玩法 ════
    方向键移动光标，空格落子，Esc 退出。
    你执黑先走，电脑执白。连成三个就赢。

直接运行： python games/井字棋.py
"""

import random
import sys
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from hybridengine_light import Stage

# ── 棋盘 ──
# 用"三层列表"还是"一维列表"？这里用**一维**，因为 3×3 的一维下标很好算：
#     第 r 行第 c 列  →  下标 = r * 3 + c
# 三层列表 a[行][列] 读起来更直观，但对初学者来说，
# "两个下标变一个"这件事本身就是个要理解的负担。一维更简单。

空 = 0
我 = 1
电脑 = 2


def 新棋盘() -> list[int]:
    return [空] * 9


def 能落子(棋盘: list[int], 位置: int) -> bool:
    """位置必须合法，而且是空的。"""
    return 0 <= 位置 < 9 and 棋盘[位置] == 空


def 落子(棋盘: list[int], 位置: int, 谁: int) -> None:
    棋盘[位置] = 谁


def 赢家(棋盘: list[int]) -> int:
    """返回赢家（我 / 电脑），没人赢返回 空。

    连成三线的所有可能 —— 这是这个游戏唯一的"知识"，
    写成一张表比写一堆 if 清楚得多。
    """
    三线 = [
        (0, 1, 2), (3, 4, 5), (6, 7, 8),      # 三行
        (0, 3, 6), (1, 4, 7), (2, 5, 8),      # 三列
        (0, 4, 8), (2, 4, 6),                 # 两条对角线
    ]
    for a, b, c in 三线:
        if 棋盘[a] != 空 and 棋盘[a] == 棋盘[b] == 棋盘[c]:
            return 棋盘[a]
    return 空


def 平局(棋盘: list[int]) -> bool:
    return 赢家(棋盘) == 空 and all(x != 空 for x in 棋盘)


# ── 电脑的策略 ──
# 分三层，从强到弱 —— 这就是"AI"的最朴素形态：
# 先看能不能立刻赢，再看要不要立刻挡，都不行就随便走。
def 电脑走(棋盘: list[int]) -> int:
    空的位 = [i for i in range(9) if 棋盘[i] == 空]

    # ① 我能一步赢吗？
    for i in 空的位:
        棋盘[i] = 电脑
        赢了 = 赢家(棋盘) == 电脑
        棋盘[i] = 空
        if 赢了:
            return i

    # ② 对手能一步赢吗？能就挡住
    for i in 空的位:
        棋盘[i] = 我
        输了 = 赢家(棋盘) == 我
        棋盘[i] = 空
        if 输了:
            return i

    # ③ 占中间最好，其次随便
    if 4 in 空的位:
        return 4
    return random.choice(空的位)


# ── 画面 ──
# 棋盘画在 100×100 的虚拟坐标里（原点左下角，和数学课一致）
格 = 30          # 每格 30 单位
左上 = 5         # 棋盘从 (5, 5) 开始


def 格中心(位置: int) -> tuple[float, float]:
    """把 0~8 的位置换算成格子的中心坐标。"""
    行, 列 = divmod(位置, 3)
    # 注意 y 要往上算：第 0 行在最上面，所以 y 用 (2-行)
    return 左上 + 列 * 格 + 格 / 2, 左上 + (2 - 行) * 格 + 格 / 2


def 画棋盘(舞台: Stage, 棋盘: list[int], 光标: int, 结果: str):
    舞台.clear()

    # 格子线
    for k in range(1, 3):
        舞台.line(左上 + k * 格, 左上, 左上 + k * 格, 左上 + 3 * 格, "灰", 0.5)
        舞台.line(左上, 左上 + k * 格, 左上 + 3 * 格, 左上 + k * 格, "灰", 0.5)

    # 棋子
    for i in range(9):
        cx, cy = 格中心(i)
        if 棋盘[i] == 我:
            舞台.dot(cx, cy, 10, "黑")
        elif 棋盘[i] == 电脑:
            舞台.dot(cx, cy, 10, "白")
            舞台.dot(cx, cy, 10, "灰")     # 白棋加个边框才看得见
            舞台.dot(cx, cy, 8, "白")

    # 光标（用一个小点表示"你现在指这里"）
    if 棋盘[光标] == 空 and 结果 == "":
        cx, cy = 格中心(光标)
        舞台.dot(cx, cy, 3, "红")

    # 结果
    if 结果:
        舞台.text(50, 92, 结果, "红", 18)


def 主流程():
    舞台 = Stage(size=100, width=480, height=480, title="井字棋")
    舞台.hint("方向键移动，空格落子，Esc 退出")

    棋盘 = 新棋盘()
    光标 = 0
    结果 = ""

    while True:
        画棋盘(舞台, 棋盘, 光标, 结果)
        舞台.show()

        k = 舞台.key()

        if k == "Escape":
            舞台.close()
            return

        if 结果:
            # 已经结束了 —— 按空格再来一局
            if k == "空格":
                棋盘 = 新棋盘()
                光标 = 0
                结果 = ""
            continue

        # 移动光标
        if k in ("上", "下", "左", "右"):
            行, 列 = divmod(光标, 3)
            if k == "上":
                行 = (行 - 1) % 3
            elif k == "下":
                行 = (行 + 1) % 3
            elif k == "左":
                列 = (列 - 1) % 3
            else:
                列 = (列 + 1) % 3
            光标 = 行 * 3 + 列
            continue

        if k == "空格" and 能落子(棋盘, 光标):
            落子(棋盘, 光标, 我)

            if 赢家(棋盘) == 我:
                结果 = "你赢了！按空格再来"
                continue
            if 平局(棋盘):
                结果 = "平局。按空格再来"
                continue

            # 轮到电脑
            位 = 电脑走(棋盘)
            落子(棋盘, 位, 电脑)
            if 赢家(棋盘) == 电脑:
                结果 = "电脑赢了。按空格再来"
            elif 平局(棋盘):
                结果 = "平局。按空格再来"


if __name__ == "__main__":
    主流程()
