"""井字棋 —— 三连成线就赢。

════════════════════════════════════════════════════
  这个游戏为什么值得读
════════════════════════════════════════════════════

它是整套课程里第一个**规则和画面分开写**的程序：

    规则部分  新棋盘 / 赢家 / 平局 / 能落子 / 落子 / 电脑走
    画面部分  画棋盘 / 输入 / main

为什么要这么分？因为**规则可以自动测**，画面只能人看。

    · 赢了不判赢、电脑下在已占的格子上 —— 这些 bug 玩家遇到
      只会觉得"这游戏坏了"，不会去报告。
    · 分出来之后，`tests/test_games.py` 就能把这些规则逐条验证。

所以读这个文件的时候，注意看**每个函数都只做一件事**，
而且都不碰屏幕 —— 屏幕的事全在最后那几个函数里。

════════════════════════════════════════════════════
  用到前 13 课学过的哪些东西
════════════════════════════════════════════════════

    列表     棋盘就是一个 9 个格子的列表
    常量     空 / 我 / 电脑 三个标记
    函数     每个规则一个函数
    循环     赢家要遍历 8 条线；电脑走要遍历 9 个格子
    条件     判断三连、判断平局
    字典     8 条可能的连线
"""
from __future__ import annotations

# ══════════════════ 规则 ══════════════════

#: 空格子。用空格当标记，这样直接画出来就是空的 —— 不用特判显示。
空 = " "
#: 玩家（人）
我 = "X"
#: 电脑
电脑 = "O"

#: 所有能连成三个的位置组合。
#: ⚠ 就这 8 条，一条不多一条不少 —— 3 横 + 3 竖 + 2 斜。
线 = (
    (0, 1, 2), (3, 4, 5), (6, 7, 8),        # 横
    (0, 3, 6), (1, 4, 7), (2, 5, 8),        # 竖
    (0, 4, 8), (2, 4, 6),                   # 斜
)


def 新棋盘() -> list[str]:
    """一个空棋盘 —— 9 个格子，下标 0..8。

    下标和位置的对应（画出来是这样）：

        0 | 1 | 2
       ---+---+---
        3 | 4 | 5
       ---+---+---
        6 | 7 | 8

    为什么用**一维**列表而不是二维：8 条线写起来是硬编码的下标，
    一维更短、更不容易写错。代价是显示的时候要自己分行。
    """
    return [空] * 9


def 赢家(棋盘: list[str]) -> str:
    """谁赢了？没人赢就返回 `空`。

    ⚠ 判据只看**这 8 条线**，别自己另想一套（比如逐行查）——
      斜线是最容易漏掉的那两条。
    """
    for a, b, c in 线:
        if 棋盘[a] != 空 and 棋盘[a] == 棋盘[b] == 棋盘[c]:
            return 棋盘[a]
    return 空


def 平局(棋盘: list[str]) -> bool:
    """满盘而且没人赢 = 平局。

    ⚠ 顺序很重要：**先判赢家**。满盘但最后一步连成了三个，那是赢不是平。
      这里写成 `赢家(棋盘) == 空 and 没有空格`，两个条件都要。
    """
    return 赢家(棋盘) == 空 and all(x != 空 for x in 棋盘)


def 能落子(棋盘: list[str], 位: int) -> bool:
    """这个位置能不能下？

    三个条件缺一不可：下标在范围内、而且那个格子是空的。
    ⚠ 负数下标在 Python 里**不会报错**（`棋盘[-1]` 是最后一格），
      所以必须显式查 `位 >= 0`，否则玩家输 -1 会下到右下角去。
    """
    return 0 <= 位 < 9 and 棋盘[位] == 空


def 落子(棋盘: list[str], 位: int, 谁: str) -> None:
    """把 `谁` 下在 `位` 上。就地修改棋盘（不返回新列表）。"""
    棋盘[位] = 谁


def 电脑走(棋盘: list[str]) -> int:
    """电脑选一个位置。返回下标。

    策略分三层，**顺序不能反**：

        ① 能赢就赢     —— 自己差一步就赢，立刻赢
        ② 该挡就挡     —— 玩家差一步就赢，挡住
        ③ 否则选中间，再退而求其次选角，最后选边

    ⚠ ①必须在②前面。反过来的话，电脑会在自己能赢的时候跑去防守 ——
      看起来"很谨慎"，其实永远赢不了。这是这一课最值得记住的一点。

    怎么实现 ①②：**假装下一步，看会不会赢**。同一个函数用两次，
    一次假装自己是 `电脑`，一次假装自己是 `我`。
    """
    # ① 能赢就赢
    for 位 in range(9):
        if 能落子(棋盘, 位):
            棋盘[位] = 电脑
            赢了 = 赢家(棋盘) == 电脑
            棋盘[位] = 空                  # ⚠ 假装的，一定要还原
            if 赢了:
                return 位

    # ② 该挡就挡（同一招，换成假裝玩家）
    for 位 in range(9):
        if 能落子(棋盘, 位):
            棋盘[位] = 我
            要输 = 赢家(棋盘) == 我
            棋盘[位] = 空
            if 要输:
                return 位

    # ③ 中间 > 角 > 边。这个顺序是有讲究的：
    #    中间那一格参与 4 条线，角参与 3 条，边只参与 2 条。
    for 位 in (4, 0, 2, 6, 8, 1, 3, 5, 7):
        if 能落子(棋盘, 位):
            return 位

    return -1                               # 满盘，没得走


# ══════════════════ 画面 ══════════════════

#: 棋盘画出来有多大（虚拟坐标的单位）。格子边长 = 板宽 / 3。
板宽 = 300.0


def 格中心(位: int) -> tuple[float, float]:
    """第 `位` 号格子的中心点，返回 (x, y)。

    ⚠⚠ **坐标语义要说清楚**（这是画面和逻辑的接缝，最容易搞反）：

        原点在**左下角**，y **向上**增大 —— 和数学课上的坐标一样，
        不是屏幕坐标（屏幕坐标原点在左上角、y 向下）。

      所以"视觉上更靠上"对应 **y 更大**：

          位 0（左上） → y 大    位 6（左下） → y 小
          位 2（右上） → x 大    位 8（右下） → x 大、y 小

    为什么值得单独写成一个函数：棋盘规则用的是**一维下标 0..8**，
    而画面上要的是**二维坐标**。这个换算是两套东西之间唯一的接缝 ——
    留在别处散着写，早晚会出现"规则说下在 5、画面上画到了 8"这种 bug。
    """
    格 = 板宽 / 3.0
    列 = 位 % 3                 # 0=左 1=中 2=右
    行 = 位 // 3                # 0=上 1=中 2=下
    # 行 0 在上面 ⇒ y 要最大：两行之下是底部，再加上半格到中心
    return (列 * 格 + 格 / 2.0,
            (2 - 行) * 格 + 格 / 2.0)


def 画(棋盘: list[str]) -> str:
    """把棋盘画成一段文字。

    ⚠ 规则部分不碰屏幕，所以画棋盘是**单独一个函数** ——
      这样它也能被测试，而且想在别处显示（比如网页）时不用重写规则。
    """
    行们 = []
    for r in range(3):
        格 = 棋盘[r * 3: r * 3 + 3]
        # 每个格子占 3 格宽，看起来才对齐；中间用竖线隔开
        行们.append(" " + " | ".join(f"{x:^3}" for x in 格))
        if r < 2:
            行们.append("----+---+----")
    return "\n".join(行们)


def 读位置(文字: str) -> int | None:
    """把玩家输入的一行字解析成位置（0..8）。解析不了返回 None。

    ⚠ 玩家的输入永远不能信：可能打中文、可能打 9、可能直接回车。
      所以这里用 try/except 兜住，而不是假设他一定会输数字。
    """
    文字 = 文字.strip()
    if not 文字:
        return None
    try:
        位 = int(文字)
    except ValueError:
        return None
    return 位 if 0 <= 位 < 9 else None


def main() -> int:
    """人机对战。你执 X，先手。"""
    import sys

    # ⚠ 打包成 exe 之后没有交互终端 —— 直接说清楚，别让它卡住。
    if not sys.stdin.isatty():
        print()
        print("  井字棋（规则演示）")
        print("  " + "─" * 44)
        print("  这个游戏需要有人输入，所以要在**终端**里跑：")
        print()
        print("      python games/井字棋.py")
        print()
        print("  输入 0~8 表示下在哪一格（看下面的编号）：")
        print()
        print("       0 | 1 | 2")
        print("      ---+---+---")
        print("       3 | 4 | 5")
        print("      ---+---+---")
        print("       6 | 7 | 8")
        print()
        print("  ⚠ 提示：电脑会「能赢就赢、该挡就挡」，不是随便下的。")
        print()
        return 0

    棋盘 = 新棋盘()
    print()
    print("  井字棋 —— 你执 X，先手。输入 0~8：")
    print()

    while True:
        print(画(棋盘))
        print()

        # ── 你走 ──
        while True:
            位 = 读位置(input("  你下在哪？ "))
            if 位 is None:
                print("  ⚠ 要输入 0~8 之间的一个数字。")
                continue
            if not 能落子(棋盘, 位):
                print("  ⚠ 那一格已经有子了，换一个。")
                continue
            break
        落子(棋盘, 位, 我)

        if 赢家(棋盘) == 我:
            print()
            print(画(棋盘))
            print("\n  你赢了！\n")
            return 0
        if 平局(棋盘):
            print()
            print(画(棋盘))
            print("\n  平局。\n")
            return 0

        # ── 电脑走 ──
        它 = 电脑走(棋盘)
        落子(棋盘, 它, 电脑)
        print(f"\n  电脑下在 {它}。\n")

        if 赢家(棋盘) == 电脑:
            print(画(棋盘))
            print("\n  电脑赢了。再来一局？\n")
            return 0
        if 平局(棋盘):
            print(画(棋盘))
            print("\n  平局。\n")
            return 0


if __name__ == "__main__":
    raise SystemExit(main())
