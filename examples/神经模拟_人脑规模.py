"""人脑规模的**群体 / mean-field 层**神经模拟 —— 轻量版（纯 Python · 零依赖）。

    python examples/神经模拟_人脑规模.py              # 默认：跑口径网格（无窗口）
    python examples/神经模拟_人脑规模.py --快          # 只跑前两格
    python examples/神经模拟_人脑规模.py --窗口        # 开个窗口看放电率柱子

═══════════════════════════════════════════════════════════════════════
  ⚠ 这个例子**模拟了哪一层**（先读这条，不然会读成"模拟了人脑"）
═══════════════════════════════════════════════════════════════════════

人脑有 **860 亿神经元 / 约 100 万亿突触**，**逐细胞做不到**。
这里站的是**大规模群体（population / mean-field）层**：

    一个「群体」= 一大群同质神经元（默认 8600 万个）
    状态 = 这个群体的**平均放电率**（一个标量），不是任何单个细胞的膜电位

**没模拟**：单个神经元的膜电位/树突/离子通道、逐突触的权重与可塑性、
空间结构（皮层柱/层、传导延迟）、以及任何"意识/认知"层面的东西。

⇒ 所以下面打印的 `REPRESENTED_NEURONS = 8.6e10` 是**账面上的算术换算**，
  **不是**"这个程序在模拟 860 亿个细胞"。真正的计算量是 `NNZ_PER_STEP`。

═══════════════════════════════════════════════════════════════════════
  同口径：和专业版（C++）跑的是**同一个计算**，不是"差不多的模型"
═══════════════════════════════════════════════════════════════════════

`核对参照()` 拿专业版 C++ 实测的 `MEAN_RATE_ALL` / `DIGEST` 逐个比 ——
**逐位**，不给容差。对上了才说明"慢多少倍"比的是同一件事。
"""
from __future__ import annotations

import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
#: 让 `python examples/xxx.py` 也能 import 到包（不依赖 cwd）
_LC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _LC not in sys.path:
    sys.path.insert(0, _LC)

from hybridengine_light import neural as N        # noqa: E402


def 主(argv: list[str]) -> int:
    快 = "--快" in argv
    要窗口 = "--窗口" in argv

    print("═" * 68)
    print("  轻量版 · 人脑规模**群体层**神经模拟（Python · stdlib only）")
    print("  hybridengine_light.neural v%s" % N.__version__)
    print("═" * 68)
    print()

    # ── ① 跨语言核对：证明两边跑的是同一个计算 ──────────────────────────
    print("① 跨语言核对（参照点 = 专业版 C++ 实测输出，逐位比）")
    print("─" * 68)
    结果 = N.核对参照()
    全对 = all(率对 and 摘对 for (_, _, _, _, _, _, 率对, _, _, 摘对) in 结果)
    print("  ⇒ %s（DIGEST 是全 64 位逐位比较，不给容差）"
          % ("全部逐位对上 ✅" if 全对 else "**有对不上的 ❌**"))
    print()
    if not 全对:
        print("  ⚠ 对不上说明两边不是同一个计算 ⇒ 下面的「慢多少倍」没有意义。")
        return 1

    # ── ② 同一张网格 ────────────────────────────────────────────────────
    档 = N.口径网格[:2] if 快 else N.口径网格
    print("② 人脑规模实测（群体数 × 每群 8.6e10/P 个代表神经元）")
    print("─" * 68)
    实测 = N.口径网格_群体(档)
    print()
    print("③ 汇总")
    print("─" * 68)
    N.打印网格(实测)
    print()
    print("  ⚠ `MS_PER_STEP` = **纯 step 循环**的墙上时间（建表不计、不画、不开窗）")
    print("     —— 与专业版 `--engine 0 --threads 1` 是同一个口径。")
    print("  ⚠ 这里**没有**和 C++ 的倍数 —— 那条在 docs/神经模拟.md 里，")
    print("     并且是由实测两边的 ms/step 相除得到的（22x ~ 111x，不是「略慢」）。")
    print()

    # ── ④ 用引擎的轻量渲染画出来（默认无窗口）──────────────────────────
    print("④ 接引擎的轻量渲染（默认 headless：录制后端，不建窗口）")
    print("─" * 68)
    网 = N.人脑网络(群体数=1000)
    游戏 = N.建演示(网, 子步每帧=20)
    游戏.跑(帧数=30)
    后 = 游戏.后端
    print("  跑了 %d 帧 × 每帧 20 个神经步 = %d 神经步（dt=%.1e s）"
          % (游戏.帧数, 网.步数, 网.dt))
    print("  录制后端本帧指令数 = %d（柱子 %d + 平均线 1 + 文字 1）"
          % (len(后.本帧()), len(后.有矩形())))
    print("  ⚠ 走的是 `录制后端` ⇒ **没有建窗口**、没有把渲染耗时混进上面的模拟数。")
    print()

    if 要窗口:
        print("⑤ 开真窗口（Tk 后端）—— 手动关窗口才结束")
        print("─" * 68)
        from hybridengine_light import pyengine as E
        网2 = N.人脑网络(群体数=1000)
        游戏2 = N.建演示(网2, 后端=E.Tk后端(720, 480, 100, "神经模拟（轻量版）"),
                          子步每帧=20)
        游戏2.跑()
    else:
        print("（想开窗口看柱子：加 `--窗口`。默认 headless —— 基准不该弹窗。）")
    return 0


if __name__ == "__main__":
    sys.exit(主(sys.argv[1:]))
