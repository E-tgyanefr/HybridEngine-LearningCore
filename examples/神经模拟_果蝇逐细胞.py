"""果蝇规模的**逐细胞**脉冲神经模拟 —— 轻量版（纯 Python · 零依赖）。

    python examples/神经模拟_果蝇逐细胞.py             # 默认：10 万神经元 / 100 万突触（无窗口）
    python examples/神经模拟_果蝇逐细胞.py --大         # 500 万突触（更接近果蝇，但更慢）
    python examples/神经模拟_果蝇逐细胞.py --窗口       # 开个窗口看发放栅格

═══════════════════════════════════════════════════════════════════════
  ⚠ 这条线和"人脑群体层"那条**不是一层东西**，别混
═══════════════════════════════════════════════════════════════════════

    `examples/神经模拟_人脑规模.py`  →  **群体 / mean-field 层**（状态 = 群体的平均放电率）
    本文件                          →  **逐细胞层**（状态 = 每个神经元自己的 LIF 膜电位）

果蝇是**唯一**一条能真逐细胞跑的线：它的神经元数（约 10 万）还在纯 Python 的
射程内。人脑的 860 亿做不到 —— 本文件末尾会用实测的"每神经元每步毫秒数"
把那条账算给你看。

═══════════════════════════════════════════════════════════════════════
  ⚠⚠ 两个必须照实说的近似（别读成"模拟了果蝇全脑"）
═══════════════════════════════════════════════════════════════════════

**① 突触数是"显式表示"的，不是果蝇真实的 ~5×10⁷ 条。**
  默认只显式表示 **1×10⁶** 条（平均出度 10），占真实的 **2%**。
  真实果蝇全脑（FlyWire 量级）约 1.4×10⁵ 神经元 / 约 5×10⁷ 突触（平均出度 ~350）。
  纯 Python 里把 5×10⁷ 条塞进 `array` 要 ~200 MB(索引) + ~400 MB(权重)，
  还要每步扫 —— 不现实。**缺掉的连通性用背景外部电流顶上**（真实脑里也有大量背景输入）。

**② 默认落在"强直驱动"区间**（平均放电率 ~9 Hz），**不是自发活动网络**。
  每神经元只有 10 条突触（真实的 ~1/35），撑不起自发持续放电；
  把驱动降到阈值以下网络就静默（实测过）。
"""
from __future__ import annotations

import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
_LC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _LC not in sys.path:
    sys.path.insert(0, _LC)

from hybridengine_light import neural as N        # noqa: E402


def 主(argv: list[str]) -> int:
    大 = "--大" in argv
    要窗口 = "--窗口" in argv
    突触数 = 5_000_000 if 大 else 1_000_000

    print("═" * 68)
    print("  轻量版 · 果蝇规模**逐细胞**脉冲神经模拟（Python · stdlib only）")
    print("  hybridengine_light.neural v%s" % N.__version__)
    print("═" * 68)
    print()

    # ── ① 逐细胞真跑 ────────────────────────────────────────────────────
    print("① 逐细胞实测（每个神经元一个 LIF 膜电位，事件驱动投递突触）")
    print("─" * 68)
    r = N.基准_逐细胞(神经元数=N.果蝇神经元数, 突触数=突触数, 步数=500, 热身=50)
    print()
    print("  换算一下这两条（都是**算术**，不是实测，写出来是为了让人有感觉）：")
    实时率 = r["SIM_SECONDS"] / (r["MS_PER_STEP"] * r["STEPS"] / 1e3)
    print("    · 实时率：跑 %.3f s 生物时间要 %.1f s 墙钟 ⇒ **%.2f%% 实时**"
          % (r["SIM_SECONDS"], r["MS_PER_STEP"] * r["STEPS"] / 1e3, 实时率 * 100))
    人脑一步秒 = r["MS_PER_STEP_PER_NEURON"] * N.人脑神经元数 / 1e3
    print("    · 按这个速度，人脑 8.6e10 个神经元跑**一步**（0.1 ms 生物时间）要 **%.1f 小时**"
          % (人脑一步秒 / 3600))
    print("      ⇒ 模拟人脑**1 秒**生物时间要 **%.1f 年**"
          % (人脑一步秒 * 10_000 / 3600 / 24 / 365))
    print("      ⇒ 这就是「人脑为什么只能走群体层」的算术。")
    print()

    # ── ② 突触投递本身多快 ──────────────────────────────────────────────
    print("② 纯突触投递吞吐（把每步都逼成全体发放，单独量突触这一层）")
    print("─" * 68)
    N.基准_突触吞吐(突触数=突触数, 神经元数=N.果蝇神经元数, 重复=3)
    print("  ⚠ 真实脉冲网络里每步只有一小部分神经元发放 ⇒ 上面的 `MS_PER_STEP`")
    print("     主要花在 O(N) 的整数组更新上，**不**花在突触上。")
    print()

    # ── ③ 接引擎的轻量渲染（默认无窗口）────────────────────────────────
    print("③ 接引擎的轻量渲染（默认 headless：录制后端，不建窗口）")
    print("─" * 68)
    网 = N.果蝇网络(神经元数=20_000, 突触数=200_000)
    #: ⚠ 子步要给够：默认外部电流 1.20 时，膜电位从 0 充到阈值要
    #:   `−τ_m·ln(1−1/1.2)` ≈ **35.8 ms = 358 步**（τ_m = 20 ms）。
    #:   只给 300 步的话窗口里**一个发放都没有**（第一版就是这样，栅格是空的）。
    游戏 = N.建演示(网, 子步每帧=30)
    游戏.跑(帧数=30)
    后 = 游戏.后端
    print("  跑了 %d 帧 × 每帧 30 个神经步 = %d 神经步（dt=%.1e s = %.1f ms 生物时间）"
          % (游戏.帧数, 网.步数, 网.dt, 网.步数 * 网.dt * 1e3))
    print("  录制后端本帧指令数 = %d（发放栅格 %d 个圆 + 文字）"
          % (len(后.本帧()), len(后.有圆())))
    print("  ⚠ 走的是 `录制后端` ⇒ **没有建窗口**、没有把渲染耗时混进模拟数。")
    print()

    if 要窗口:
        print("④ 开真窗口（Tk 后端）—— 手动关窗口才结束")
        print("─" * 68)
        from hybridengine_light import pyengine as E
        网2 = N.果蝇网络(神经元数=20_000, 突触数=200_000)
        游戏2 = N.建演示(网2, 后端=E.Tk后端(720, 480, 100, "神经模拟 · 果蝇逐细胞"),
                          子步每帧=30)
        游戏2.跑()
    else:
        print("（想开窗口看发放栅格：加 `--窗口`。默认 headless —— 基准不该弹窗。）")
    return 0


if __name__ == "__main__":
    sys.exit(主(sys.argv[1:]))
