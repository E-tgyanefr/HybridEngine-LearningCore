def CHECK_函数存在(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    return True, "搭一个游戏 是个函数"


def CHECK_自己写的组件是组件(答案):
    """⚠ 这条查的是"你有没有真的自己写一个组件"，而不是直接用原生组件。"""
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    from hybridengine_light import pyengine as E
    from hybridengine_light.pyengine import components as C
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    圆 = _找对象(游戏, "圆")
    if 圆 is None:
        return False, "场景里没有叫「圆」的对象（写法：场景.造(\"圆\", 50, 50)）"
    原生 = (C.圆点, C.方块, C.标签, C.匀速移动, C.按键驱动, C.重力,
           C.跟随相机, C.计时器, C.分数, C.生命周期, C.圆形碰撞, C.闪烁, C.尾迹)
    自己写的 = [c for c in 圆.组件们 if not isinstance(c, 原生)]
    if not 自己写的:
        return False, ("「圆」身上的组件都是引擎自带的 —— 这一课要**你自己写一个**。\n"
                       "      写法：\n"
                       "          class 往右跑(E.组件):\n"
                       "              def 每帧(self, dt):\n"
                       "                  ...\n"
                       "          圆.加(C.圆点(半径=5), 往右跑())")
    类 = 自己写的[0]
    if not isinstance(类, E.组件):
        return False, f"「{type(类).__name__}」没有继承 E.组件"
    return True, f"找到你自己写的组件「{type(类).__name__}」"


def CHECK_真的在往右移动(答案):
    """⚠ 核心判据：跑几帧，x 必须**增加**。"""
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=0)
    if 错:
        return False, 错
    圆 = _找对象(游戏, "圆")
    if 圆 is None:
        return False, "场景里没有叫「圆」的对象"
    起 = 圆.变换.位置.x
    for _ in range(30):
        游戏.一步()
    终 = 圆.变换.位置.x
    if 终 <= 起:
        return False, (f"跑了 30 帧，x 从 {起:g} 变成 {终:g} —— **没有往右移动**。\n"
                       f"      检查两件事：\n"
                       f"        ① 你的组件写的是 `每帧(self, dt)` 吗（方法名要一模一样）\n"
                       f"        ② 有没有真的 `.加(它)` 到「圆」身上")
    return True, f"x 从 {起:g} 移到 {终:g}，确实在动"


def CHECK_移动用的是dt而不是每帧固定值(答案):
    """⚠⚠ 这条是本课的重点：**移动距离要乘 dt**。

    怎么判：用**两种不同的帧数**跑同样长的逻辑时间。
    乘了 dt 的话结果一样；每帧加固定值的话结果会差很多。
    """
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"

    def 跑到(步长, 步数):
        后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=0)
        if 错:
            return None
        圆 = _找对象(游戏, "圆")
        if 圆 is None:
            return None
        for _ in range(步数):
            游戏.一步(步长)
        return 圆.变换.位置.x

    a = 跑到(1 / 60, 60)        # 1 秒（60 帧）
    b = 跑到(1 / 120, 120)      # 同样 1 秒（120 帧）
    if a is None or b is None:
        return False, "跑不起来（见上一条的报错）"
    if abs(a - b) > 1.0:
        return False, (f"同样跑 1 秒，60 帧时移到 {a:.2f}，120 帧时移到 {b:.2f} —— "
                       f"**两者不一样**。\n"
                       f"      说明你写的是「每帧加固定值」，而不是「速度 × dt」。\n"
                       f"      后果：这份代码在快电脑上会跑得更快。\n"
                       f"      正确写法：self.宿主.变换.位置 = E.向量(p.x + 速度 * dt, p.y)")
    return True, f"两种帧率下都到 {a:.2f}（乘了 dt，与帧率无关）"
