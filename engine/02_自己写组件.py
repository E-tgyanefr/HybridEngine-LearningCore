# ─────────────────────────────────────────────────────
#  这一课你会学到
# ─────────────────────────────────────────────────────
#    自己写一个组件：让东西「会动」
#
#  需要先会
#    第 01 课：场景与对象


# 要做：
#   写一个函数 `搭一个游戏()`：
#     1. 建 `E.游戏`（用传进来的后端）
#     2. 造一个对象叫「圆」，位置 (50, 50)
#     3. 给它挂 `C.圆点(半径=5)`，**再挂一个你自己写的组件**
#     4. 你写的组件要让它**往右移动**：每帧把位置 x 加 `20 * dt`
#     5. 返回游戏

# ─────────────────────────────────────────────────────
#  组件长什么样
# ─────────────────────────────────────────────────────
#
#      class 往右跑(E.组件):
#          def 每帧(self, dt):
#              self.宿主.变换.位置 = ...
#
#  要记住的就三件事：
#
#    ① **继承** `E.组件`
#    ② 写 `每帧(self, dt)` —— 引擎每个逻辑帧都调它一次
#    ③ `self.宿主` 就是"你挂在哪個东西上"
#
#  ⚠ `dt` 是"这一帧过了多少秒"（约 0.0167）。
#    移动距离要写成 `速度 * dt`，**不能写成每帧加固定的 20**：
#    否则在快电脑上跑得更快 —— 学员最常犯、也最难自己发现的一个错。
#
# ═════════════════════════════════════════════════════
#  为什么"每帧"这个钩子是关键
# ═════════════════════════════════════════════════════
#
# 没有组件时，想让东西动，你得在某处写：
#
#     while True:
#         圆.位置.x += 1
#         子弹.位置.y += 2
#         ...
#
# 加一个会动的东西就要改那个循环 —— 越加越长，最后没人敢动。
#
# 有组件之后，**每个东西自己管自己**：
#    圆.加(往右跑())      ← 这一行就够了，别处一个字都不用改
#
# 这就是"模块化"解决的真实问题。


# ─────────────────────────────────────────────────────
#  判分辅助（课程自带；学员不用管）
# ─────────────────────────────────────────────────────

def _跑无头(搭建函数, 帧数: int = 3):
    """用**无头后端**跑学员搭的场景，返回 (录制后端, 游戏)。

    ⚠ 为什么不开窗口：判分要的是"你搭出来的结构对不对"，
      不是"窗口好不好看"。无头跑还让学员在自己机器上得到一样的结论。
    """
    from hybridengine_light import pyengine as E
    后 = E.录制后端()
    游戏 = 搭建函数(后)
    if not isinstance(游戏, E.游戏):
        return None, None, "你的函数应当**返回** `游戏` 对象（现在返回的是 %s）" % type(游戏).__name__
    for _ in range(帧数):
        游戏.一步()
    return 后, 游戏, None


def _找对象(游戏, 名字: str):
    if 游戏 is None:
        return None
    return 游戏.场景.找(名字)


