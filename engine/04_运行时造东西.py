# 第 04 课：运行时造东西 —— 子弹、粒子、飘字

# 要做：
#   写一个函数 `搭一个游戏()`：
#     1. 建 `E.游戏`（用传进来的后端）
#     2. 造一个对象叫「发射器」，位置 (50, 50)，挂 `C.圆点(半径=3)`
#     3. 给它挂一个 `C.计时器(间隔=0.1, 回调=...)`：
#        每 0.1 秒在**发射器的位置**造一个新对象（名字 `子弹N`），
#        挂 `C.圆点(半径=1, 颜色="黄")` + `C.生命周期(寿命=0.3)`
#     4. 返回游戏
#
#   检查会跑够时间，然后看有没有出现子弹、以及它们有没有自己消失。

# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课有一个**必须记住的坑**
# ─────────────────────────────────────────────────────
#
# 在 `每帧`（或计时器回调）里给场景加东西时，
# **要用 `场景.延后加根(...)`，不要用 `场景.加根(...)`**。
#
#  为什么？因为这时候引擎**正在遍历对象列表**。
#  一边遍历一边往列表里加东西 ⇒ 有些对象会被跳过、甚至直接崩。
#  这是所有语言里都存在的经典陷阱，Python 也不例外。
#
#     场景.延后加根(新对象)      ← 安全：先记下，这一帧结束后才真的加进去
#
#  引擎把这个"安全加东西"的入口专门留出来了 —— 用它就行。
#
# ─────────────────────────────────────────────────────
#  另外两个组件
# ─────────────────────────────────────────────────────
#
#  · `C.计时器(间隔, 回调)` —— 每 0.1 秒调一次你的函数。
#    回调的签名是 `回调(宿主, 第几次)`。
#
#  · `C.生命周期(寿命)` —— 活够这么多秒就**自动消失**。
#    ⚠ 它只是把对象标记成"死了"，由场景在帧末统一清理 ——
#      组件**不该**自己从容器里删自己（同样是"遍历中改容器"）。


