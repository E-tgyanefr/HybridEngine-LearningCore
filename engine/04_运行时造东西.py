def CHECK_函数存在(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    return True, "搭一个游戏 是个函数"


def CHECK_有发射器(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    if _找对象(游戏, "发射器") is None:
        名字们 = [o.名字 for o in 游戏.场景.遍历()]
        return False, f"场景里没有叫「发射器」的对象。现在有：{名字们}"
    return True, "找到「发射器」"


def CHECK_挂了计时器(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    from hybridengine_light.pyengine import components as C
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    发 = _找对象(游戏, "发射器")
    if 发 is None:
        return False, "场景里没有叫「发射器」的对象"
    if 发.取(C.计时器) is None:
        return False, ("「发射器」身上没有 `C.计时器`。\n"
                       "      写法：发射器.加(C.计时器(间隔=0.1, 回调=发一颗))\n"
                       "      ⚠ 回调的签名是 `回调(宿主, 第几次)`。")
    return True, "计时器已挂上"


def CHECK_真的造出了子弹(答案):
    """⚠ 核心判据。"""
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=0)
    if 错:
        return False, 错
    起 = sum(1 for o in 游戏.场景.遍历() if o.名字.startswith("子弹"))
    for _ in range(30):                 # 0.5 秒 ⇒ 计时器 0.1 秒该触发几次
        游戏.一步()
    终 = sum(1 for o in 游戏.场景.遍历() if o.名字.startswith("子弹"))
    if 终 == 0 and 起 == 0:
        return False, ("跑了 0.5 秒，一颗「子弹」都没出现。\n"
                       "      检查三件事：\n"
                       "        ① 计时器的回调签名是 `回调(宿主, 第几次)` 吗\n"
                       "        ② 新对象有没有加进场景？\n"
                       "           ⚠ 必须用 `场景.延后加根(新对象)`，"
                       "不能用 `场景.加根` —— 那是在每帧遍历里改列表。\n"
                       "        ③ 名字是不是以「子弹」开头")
    if 终 == 0:
        return False, f"一开始有 {起} 颗子弹，0.5 秒后全没了 —— 寿命太短？"
    return True, f"造出了子弹（当前场景里有 {终} 颗）"


def CHECK_子弹会自己消失(答案):
    """⚠ 生命周期组件的作用 —— 不清理的话子弹会越积越多。"""
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=0)
    if 错:
        return False, 错
    for _ in range(120):                # 2 秒（寿命 0.3 秒，早该没了）
        游戏.一步()
    存活 = [o.名字 for o in 游戏.场景.遍历() if o.名字.startswith("子弹")]
    if len(存活) > 6:
        return False, (f"2 秒后还剩 {len(存活)} 颗子弹 —— 它们没有自己消失。\n"
                       f"      写法：新.加(..., C.生命周期(寿命=0.3))\n"
                       f"      ⚠ 不清理的话子弹会越积越多，游戏会越来越慢。")
    return True, f"2 秒后只剩 {len(存活)} 颗（旧的都消失了）"
