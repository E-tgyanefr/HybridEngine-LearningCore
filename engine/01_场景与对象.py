def CHECK_函数存在(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, ("还没有定义「搭一个游戏」这个函数。\n"
                       "      写法：\n"
                       "          def 搭一个游戏(后端):\n"
                       "              ...\n"
                       "              return 游戏")
    if not callable(答案.搭一个游戏):
        return False, "「搭一个游戏」存在，但它不是函数。要用 def 定义。"
    return True, "搭一个游戏 是个函数"


def CHECK_返回的是一个游戏(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    return True, "返回了 E.游戏 对象"


def CHECK_场景里有玩家(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    玩家 = _找对象(游戏, "玩家")
    if 玩家 is None:
        名字们 = [o.名字 for o in 游戏.场景.遍历()]
        return False, (f"场景里没有叫「玩家」的对象。\n"
                       f"      现在有的是：{名字们}\n"
                       f"      写法：游戏.场景.造(\"玩家\", 50, 50)")
    return True, f"找到「玩家」，位置 {玩家.变换.位置}"



def CHECK_玩家位置对(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    玩家 = _找对象(游戏, "玩家")
    if 玩家 is None:
        return False, "场景里没有叫「玩家」的对象"
    p = 玩家.变换.位置
    if abs(p.x - 50) > 1e-6 or abs(p.y - 50) > 1e-6:
        return False, (f"玩家的位置应当是 (50, 50)，现在是 ({p.x:g}, {p.y:g})。\n"
                       f"      写法：游戏.场景.造(\"玩家\", 50, 50)")
    return True, f"玩家在 (50, 50)"


def CHECK_玩家挂上了圆点(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=2)
    if 错:
        return False, 错
    圆们 = 后.有圆()
    if not 圆们:
        return False, ("玩家身上没有「圆点」组件，所以什么都没画出来。\n"
                       "      写法：玩家.加(C.圆点(半径=5, 颜色=\"红\"))\n"
                       "      ⚠ 忘了 `C.圆点` 是最常见的一步 —— 场景造出来了，"
                       "但没有任何组件负责画它。")
    # 圆的圆心必须在玩家位置
    玩家 = _找对象(游戏, "玩家")
    p = 玩家.世界位置
    for d in 圆们:
        if abs(d[1] - p.x) < 1e-6 and abs(d[2] - p.y) < 1e-6:
            return True, f"画出了半径 {d[3]:g} 的圆，位置正确"
    return False, (f"画了圆，但位置不对：圆在 {圆们[0][1:3]}，玩家在 ({p.x:g}, {p.y:g})。\n"
                   f"      `圆点` 组件是画在**宿主位置**上的，不该手填坐标。")
