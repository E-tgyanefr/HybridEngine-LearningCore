# 第 01 课：场景与对象 —— 先有个"东西"

# 要做：
#   写一个函数 `搭一个游戏()`：
#     1. 建一个 `E.游戏`（用传进来的后端），标题随便
#     2. 在它的场景里造一个对象，**名字叫「玩家」，位置 (50, 50)**
#     3. 给它挂一个 `C.圆点(半径=5, 颜色="红")`
#     4. 把游戏对象**返回**出去

# ─────────────────────────────────────────────────────
#  为什么第一件事是"场景 + 对象"
# ─────────────────────────────────────────────────────
#
# 学语言时你写的是一个**变量**：`名字 = "小明"`。
# 做游戏时你面对的是**世界里的东西**：玩家、子弹、敌人、地面。
#
# 引擎把它们统一叫「**场景对象**」：
#
#     场景对象 = 名字 + 位置 + 一堆"能力"
#
#     玩家 = 场景.造("玩家", 50, 50)      ← 造一个东西
#     玩家.加(C.圆点(半径=5))              ← 给它"能画出来"这个能力
#
# ⚠ `场景.造(名字, x, y)` 的坐标是**数学坐标**：
#   原点在左下角，y 往上越大。和你上数学课一样。
#
# ═════════════════════════════════════════════════════
#  ⚠ 一条主线，从这里就开始
# ═════════════════════════════════════════════════════
#
# 后面四课都在反复做同一个动作：
#
#     **给一个东西加上一种能力。**
#
# 这件事有个正式名字：**组件（component）**。
# 加能力不用改这个"东西"本身，也不用改别处的代码 —— 只是 `.加(...)`。
#
# 这就是模块化编程的核心手感。整条引擎课程都在练它。


