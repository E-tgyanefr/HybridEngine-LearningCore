# 看第 6 步：分数要涨，就得**自己写一个组件**接到 HUD 上。
# 你可以写"每 0.2 秒加 1"，也可以写"每帧加 dt*5"。
# 两种都对 —— 而第二种更好，因为它**与帧率无关**。
