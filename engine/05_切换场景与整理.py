def CHECK_函数存在(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    return True, "搭一个游戏 是个函数"


def CHECK_三样东西都在(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    缺 = [n for n in ("玩家", "敌人", "HUD") if _找对象(游戏, n) is None]
    if 缺:
        名字们 = [o.名字 for o in 游戏.场景.遍历()]
        return False, (f"场景里缺这些对象：{缺}\n"
                       f"      现在有的是：{名字们}")
    return True, "玩家 / 敌人 / HUD 都在"


def CHECK_玩家能控制(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    玩家 = _找对象(游戏, "玩家")
    if 玩家 is None:
        return False, "没有「玩家」"
    起 = 玩家.变换.位置.x
    游戏.输入._按("d")
    for _ in range(30):
        游戏.一步()
    if 玩家.变换.位置.x <= 起:
        return False, "按住 D 玩家没动 —— 检查输入服务注册了吗、按键驱动挂上了吗"
    return True, "玩家能按键移动"


def CHECK_敌人在动而且没跑出边界(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=0)
    if 错:
        return False, 错
    敌 = _找对象(游戏, "敌人")
    if 敌 is None:
        return False, "没有「敌人」"
    起 = 敌.变换.位置.x
    越界 = None
    for _ in range(200):
        游戏.一步()
        if not (0 - 1e-6 <= 敌.变换.位置.x <= 100 + 1e-6):
            越界 = 敌.变换.位置.x
            break
    if 越界 is not None:
        return False, (f"敌人跑到 x={越界:.1f}，出了边界 (0, 100)。\n"
                       f"      写法：C.匀速移动(vx=-8, vy=0, 边界=(0, 100))\n"
                       f"      ⚠ 边界是**一个元组**（最小, 最大），两个方向共用。")
    if abs(敌.变换.位置.x - 起) < 1e-9:
        return False, "敌人一直没动 —— 没挂 `C.匀速移动`？"
    return True, f"敌人在动（x 从 {起:g} 走到 {敌.变换.位置.x:.1f}），且没出边界"


def CHECK_分数会涨(答案):
    """⚠ 这条查的是"你有没有自己写一个组件接到 HUD 上"。"""
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    from hybridengine_light.pyengine import components as C
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=0)
    if 错:
        return False, 错
    HUD = _找对象(游戏, "HUD")
    if HUD is None:
        return False, "没有「HUD」"
    分 = HUD.取(C.分数)
    if 分 is None:
        return False, ("「HUD」身上没有 `C.分数` 组件。\n"
                       "      写法：HUD.加(C.分数(初值=0))")
    if 分.值 != 0:
        return False, f"分数初值应当是 0，现在是 {分.值}（写法：C.分数(初值=0)）"
    for _ in range(90):                 # 1.5 秒
        游戏.一步()
    if 分.值 <= 0:
        自己写的 = [type(c).__name__ for c in HUD.组件们
                  if not isinstance(c, (C.分数, C.圆点, C.方块, C.标签))]
        return False, ("跑了 1.5 秒，分数还是 0 —— 需要**你自己写一个组件**让分数涨。\n"
                       f"      HUD 现在的组件：{自己写的 or '（只有自带的那个）'}\n"
                       "      写法：\n"
                       "          class 自动加分(E.组件):\n"
                       "              def 每帧(self, dt):\n"
                       "                  ...\n"
                       "          HUD.加(C.分数(初值=0), 自动加分())")
    return True, f"1.5 秒后分数涨到 {分.值}"
