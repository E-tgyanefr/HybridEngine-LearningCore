# 要做：
#   写一个函数 `搭一个游戏()`：
#     1. 建 `E.游戏`（用传进来的后端）
#     2. 把 `游戏.输入` 注册成场景服务：`游戏.场景.设服务("输入", 游戏.输入)`
#     3. 造一个对象叫「玩家」，位置 (50, 50)
#     4. 给它挂 `C.圆点(半径=3)` + `C.按键驱动(速度=40)` + `C.跟随相机()`
#     5. 返回游戏
#
#   检查会**假装按住某个方向键**，看玩家有没有真的动。

# ─────────────────────────────────────────────────────
#  三个概念
# ─────────────────────────────────────────────────────
#
#  ① **输入服务**
#     引擎不自己去问键盘，而是问场景里那个叫 "输入" 的服务。
#     所以必须 `设服务("输入", 游戏.输入)` —— 少了这一行，
#     `按键驱动` 找不到输入，玩家一动不动（而且**不报错**）。
#
#  ② **按键驱动**
#     `C.按键驱动(速度=40)`：按 WASD / 方向键就移动。
#     ⚠ 它内部已经把斜向归一了 —— 同时按 W 和 D 不会比单按快 41%。
#
#  ③ **跟随相机**
#     `C.跟随相机()` 让镜头跟着这个对象走。
#
#     ⚠ 这一行值得停一下看：**加"镜头跟着我"只是挂一个组件**。
#       没有它你就得自己去改相机的位置、处理边界、写平滑 ——
#       而那些代码和"玩家"这件事毫无关系。
#
# ═════════════════════════════════════════════════════
#  组合的威力就在这一课
# ═════════════════════════════════════════════════════
#
# 玩家身上现在挂了三个组件：
#
#     圆点         —— 负责"长什么样"
#     按键驱动     —— 负责"怎么动"
#     跟随相机     —— 负责"镜头怎么看它"
#
# **三件事互不知道对方存在。** 想换外观就换第一个，
# 想改成自动巡逻就把第二个换掉 —— 第三个不用动。


