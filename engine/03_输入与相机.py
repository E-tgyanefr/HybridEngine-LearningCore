def _跑无头(搭建函数, 帧数: int = 3):
    """用**无头后端**跑学员搭的场景，返回 (录制后端, 游戏)。

    ⚠ 为什么不开窗口：判分要的是"你搭出来的结构对不对"，
      不是"窗口好不好看"。无头跑还让学员在自己机器上得到一样的结论。
    """
    from hybridengine_light import pyengine as E
    后 = E.录制后端()
    游戏 = 搭建函数(后)
    if not isinstance(游戏, E.游戏):
        return None, None, "你的函数应当**返回** `游戏` 对象（现在返回的是 %s）" % type(游戏).__name__
    for _ in range(帧数):
        游戏.一步()
    return 后, 游戏, None


def _找对象(游戏, 名字: str):
    if 游戏 is None:
        return None
    return 游戏.场景.找(名字)


