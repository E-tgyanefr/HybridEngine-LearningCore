def CHECK_函数存在(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    return True, "搭一个游戏 是个函数"


def CHECK_注册了输入服务(答案):
    """⚠ 少了这一行，`按键驱动` 找不到输入 —— 玩家不动，而且**不报错**。"""
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    if 游戏.场景.取服务("输入") is None:
        return False, ("场景里没有注册「输入」服务。\n"
                       "      写法：游戏.场景.设服务(\"输入\", 游戏.输入)\n"
                       "      ⚠ 少了这一行，`按键驱动` 找不到输入 —— "
                       "玩家一动不动，而且**不会报错**（最难查的那种）。")
    return True, "输入服务已注册"


def CHECK_玩家挂齐了三个组件(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    from hybridengine_light.pyengine import components as C
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    玩家 = _找对象(游戏, "玩家")
    if 玩家 is None:
        return False, "场景里没有叫「玩家」的对象"
    缺 = []
    if 玩家.取(C.圆点) is None:
        缺.append("C.圆点（没有它什么都看不见）")
    if 玩家.取(C.按键驱动) is None:
        缺.append("C.按键驱动（没有它按键不会让它动）")
    if 玩家.取(C.跟随相机) is None:
        缺.append("C.跟随相机（没有它镜头不跟着走）")
    if 缺:
        return False, "玩家身上还缺：\n      · " + "\n      · ".join(缺)
    return True, "圆点 / 按键驱动 / 跟随相机 都挂上了"


def CHECK_按键真的让它动(答案):
    """⚠ 核心判据：假装按住右方向键，看玩家有没有真的移动。"""
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    玩家 = _找对象(游戏, "玩家")
    if 玩家 is None:
        return False, "场景里没有叫「玩家」的对象"
    起 = 玩家.变换.位置.x
    游戏.输入._按("d")            # 假装按住 D
    for _ in range(30):
        游戏.一步()
    终 = 玩家.变换.位置.x
    if 终 <= 起:
        return False, (f"按住 D 跑了 30 帧，x 从 {起:g} 变成 {终:g} —— 玩家没动。\n"
                       f"      最可能的原因：**没有注册输入服务**（见上一条）。\n"
                       f"      其次：`按键驱动` 没挂到「玩家」身上。")
    return True, f"按住 D 后 x 从 {起:g} 移到 {终:g}"


def CHECK_相机跟上了玩家(答案):
    if not hasattr(答案, "搭一个游戏"):
        return False, "还没有定义「搭一个游戏」函数"
    后, 游戏, 错 = _跑无头(答案.搭一个游戏, 帧数=1)
    if 错:
        return False, 错
    玩家 = _找对象(游戏, "玩家")
    if 玩家 is None:
        return False, "场景里没有叫「玩家」的对象"
    相 = 游戏.场景.取服务("相机")
    if 相 is None:
        return False, "场景里没有相机服务（引擎应当自动建一个）"
    if 相.跟随 is None:
        return False, ("相机没有跟随任何对象。\n"
                       "      写法：玩家.加(C.跟随相机())\n"
                       "      ⚠ 「镜头跟着我」就是一个组件的事。")
    if 相.跟随 is not 玩家:
        return False, f"相机跟的是「{相.跟随.名字}」，不是「玩家」"
    # 跑几帧，相机应当移到玩家位置上
    for _ in range(10):
        游戏.一步()
    p = 玩家.世界位置
    if abs(相.x - p.x) > 3.0 or abs(相.y - p.y) > 3.0:
        return False, (f"相机应当跟到玩家 {p}，实际在 ({相.x:.1f}, {相.y:.1f})")
    return True, f"相机跟到了 {p}"
