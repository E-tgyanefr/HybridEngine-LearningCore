import random


def _定规律(样本数=300):
    """随机定一条"真规则"（西瓜世界里的自然规律）。

    用标准化之后的空间来定，这样间隔大小不受糖度量级的影响：
      · 均值 / 标准差 从一批原始样本里估出来（学生待会儿也会算这两个东西）
      · 权重取单位向量，偏置很小 —— 保证两类大致均衡
    """
    原始 = [[random.uniform(0.0, 1.0), random.uniform(0.0, 1.0), random.uniform(5.0, 15.0)]
            for _ in range(样本数)]
    列 = list(zip(*原始))
    均值 = [sum(c) / 样本数 for c in 列]
    标准差 = [(sum((v - m) ** 2 for v in c) / 样本数) ** 0.5 for c, m in zip(列, 均值)]
    w = [random.uniform(-1, 1) for _ in range(3)]
    长 = sum(t * t for t in w) ** 0.5
    w = [t / 长 for t in w]
    b = random.uniform(-0.2, 0.2)
    return 均值, 标准差, w, b


def _造西瓜(规律, 条数):
    """按给定规律造一批"没见过的"西瓜 —— 每次运行都不一样。"""
    均值, 标准差, w, b = 规律
    数据, 标签 = [], []
    安全 = 0
    while len(数据) < 条数 and 安全 < 条数 * 500:
        安全 += 1
        行 = [random.uniform(0.0, 1.0), random.uniform(0.0, 1.0), random.uniform(5.0, 15.0)]
        标准 = [(行[i] - 均值[i]) / 标准差[i] for i in range(3)]
        分 = sum(wi * zi for wi, zi in zip(w, 标准)) + b
        if abs(分) < 0.6:                # 离分界线太近的不要，留出间隔
            continue
        数据.append(行)
        标签.append(1 if 分 > 0 else 0)
    return 数据, 标签


def _取标准化结果(结果):
    """把 标准化 的返回值整理成 (数据, 均值, 标准差)；形状不对返回 None。"""
    try:
        数据, 均值, 标准差 = 结果
        数据 = [[float(v) for v in 行] for 行 in 数据]
        均值 = [float(v) for v in 均值]
        标准差 = [float(v) for v in 标准差]
    except Exception:                                 # noqa: BLE001
        return None
    return 数据, 均值, 标准差


def _取参数(结果):
    try:
        权重, 偏置 = 结果
        return [float(w) for w in 权重], float(偏置)
    except Exception:                                 # noqa: BLE001
        return None


def _判对率(答案, 权重, 偏置, 数据, 标签):
    对 = 0
    for 特征, 正确 in zip(数据, 标签):
        if (1 if 答案.预测(权重, 偏置, list(特征)) else 0) == 正确:
            对 += 1
    return 对, len(标签)


def CHECK_该有的东西都在(答案):
    缺 = [n for n in ("西瓜数据", "西瓜标签", "标准化", "训练", "预测", "准确率")
          if not hasattr(答案, n)]
    if 缺:
        return False, (
            "还缺这些：" + "、".join(缺) + "\n"
            "      这一课要交的是：\n"
            "          西瓜数据 / 西瓜标签        你自己给的数据（至少 12 条）\n"
            "          标准化(数据)               → (新数据, 均值, 标准差)\n"
            "          训练(数据, 标签, ...)       → (权重, 偏置)\n"
            "          预测(权重, 偏置, 特征)      → 0 或 1\n"
            "          准确率(权重, 偏置, 数据, 标签) → 判对的比例")
    for n in ("标准化", "训练", "预测", "准确率"):
        if not callable(getattr(答案, n)):
            return False, f"「{n}」存在，但它不是函数。要用 def 定义。"
    return True, "数据 + 标准化 / 训练 / 预测 / 准确率 都在"


def CHECK_自己准备的数据像样(答案):
    if not hasattr(答案, "西瓜数据") or not hasattr(答案, "西瓜标签"):
        return False, "需要先定义「西瓜数据」和「西瓜标签」"
    数据 = getattr(答案, "西瓜数据")
    标签 = getattr(答案, "西瓜标签")
    if not hasattr(数据, "__len__") or not hasattr(标签, "__len__"):
        return False, "西瓜数据 和 西瓜标签 都应该是列表"
    if len(数据) != len(标签):
        return False, (f"数据和标签对不上：{len(数据)} 条数据，{len(标签)} 个标签。\n"
                       f"      它们必须一一对应，标签[i] 是 数据[i] 的答案。")
    if len(数据) < 12:
        return False, (
            f"只有 {len(数据)} 条数据 —— 这一课至少要有 12 条。\n"
            "      数据太少，模型学不到规律，只会背下这几条。\n"
            "      而且真实项目里数据少也是最大的瓶颈，这个要求不算苛刻。")
    for i, 行 in enumerate(数据):
        if not hasattr(行, "__len__") or len(行) != 3:
            return False, (f"第 {i + 1} 条数据的特征个数不对：应该是 3 个"
                           f"（颜色深浅、敲击声、糖度），你给的是 {行!r}")
        for v in 行:
            if isinstance(v, bool) or not isinstance(v, (int, float)):
                return False, (f"第 {i + 1} 条数据里有不是数字的东西：{v!r}\n"
                               f"      特征必须是数字，文字（比如'深绿'）得先转成数字。")
    for i, y in enumerate(标签):
        if y not in (0, 1):
            return False, (f"第 {i + 1} 个标签是 {y!r} —— 标签只能是 0（坏瓜）或 1（好瓜）。\n"
                           f"      如果原来写的是 True/False 或者「好」「坏」，统一转成 0/1。")
    好 = sum(1 for y in 标签 if y == 1)
    坏 = len(标签) - 好
    if 好 < 3 or 坏 < 3:
        return False, (
            f"两类太不均衡了：好瓜 {好} 条、坏瓜 {坏} 条。\n"
            "      两类各至少要 3 条 —— 只学好瓜（或只学坏瓜），\n"
            "      模型可以靠「一律猜多的那类」骗到很高的准确率，但它什么都没学会。")
    # 顺手看一眼量纲：如果某一列的数值范围特别大，提醒一句（不算错）
    列 = list(zip(*数据))
    范围 = [max(c) - min(c) for c in 列]
    提示 = ""
    if max(范围) > 8 * min(范围):
        最大 = 范围.index(max(范围))
        提示 = (f"（顺便：第 {最大 + 1} 列的范围是 {范围[最大]:.1f}，"
                f"第 {范围.index(min(范围)) + 1} 列只有 {min(范围):.1f} —— "
                f"量纲差得多，标准化这一步别省。）")
    return True, f"{len(数据)} 条数据：好瓜 {好} 条、坏瓜 {坏} 条，特征格式没问题。{提示}"


def CHECK_标准化算得对(答案):
    if not hasattr(答案, "标准化"):
        return False, "还没有定义「标准化」函数"
    # 用一组量纲差得很远的数据：糖度 5~15，颜色 0~1
    数据 = [[random.uniform(0.0, 1.0), random.uniform(0.0, 1.0), random.uniform(5.0, 15.0)]
            for _ in range(20)]
    try:
        结果 = 答案.标准化(数据)
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 标准化(数据) 出错了：{type(e).__name__}: {e}\n"
                       f"      它要返回三个东西：return 新数据, 均值, 标准差")
    取 = _取标准化结果(结果)
    if 取 is None:
        return False, (f"标准化 要返回 (标准化后的数据, 均值列表, 标准差列表) 三个东西。\n"
                       f"      现在返回的是：{结果!r}")
    新数据, 均值, 标准差 = 取
    if len(新数据) != len(数据) or any(len(行) != 3 for 行 in 新数据):
        return False, (f"标准化后的数据形状变了：原来是 {len(数据)} 行 3 列，\n"
                       f"      现在有 {len(新数据)} 行。行数、列数都不能变。")
    if len(均值) != 3 or len(标准差) != 3:
        return False, (f"均值/标准差 应该各有 3 个数（每个特征一个），"
                       f"你给的是 {len(均值)} 和 {len(标准差)} 个。")
    # 检查本质：每一列标准化之后，均值≈0、标准差≈1
    n = len(新数据)
    列 = list(zip(*新数据))
    for j, c in enumerate(列):
        m = sum(c) / n
        s = (sum((v - m) ** 2 for v in c) / n) ** 0.5
        if abs(m) > 1e-6:
            return False, (
                f"第 {j + 1} 列标准化之后，均值是 {m:.6f}，应该是 0。\n"
                f"      说明你减掉的不是这一列的均值。\n"
                f"      写法：z = (x - 这一列的均值) / 这一列的标准差")
        if not (0.9 < s < 1.1):
            return False, (
                f"第 {j + 1} 列标准化之后，标准差是 {s:.6f}，应该是 1。\n"
                f"      常见原因：\n"
                f"        · 除的不是标准差（比如除了总和、或者除了极差 max-min）\n"
                f"        · 标准差算错了（漏了开根号 → 结果会偏差很大）\n"
                f"        · 用另一列的均值/标准差去除这一列")
    # 均值 / 标准差本身也要和原始数据对得上
    for j in range(3):
        原列 = [行[j] for 行 in 数据]
        真均值 = sum(原列) / len(原列)
        if abs(均值[j] - 真均值) > 1e-6 * max(1.0, abs(真均值)):
            return False, (f"第 {j + 1} 列的均值应该是 {真均值:.6f}，你返回的是 {均值[j]:.6f}。")
        真标准差 = (sum((v - 真均值) ** 2 for v in 原列) / len(原列)) ** 0.5
        if abs(标准差[j] - 真标准差) > 0.05 * 真标准差:
            return False, (f"第 {j + 1} 列的标准差应该是 {真标准差:.6f}，"
                           f"你返回的是 {标准差[j]:.6f}。\n"
                           f"      （除以 n 或 n-1 都可以，差别很小；但差得多就是公式错了。）")
    return True, "每一列都拉成了均值 0、标准差 1，返回的均值和标准差也对得上"


def CHECK_准确率算得对(答案):
    if not hasattr(答案, "准确率"):
        return False, "还没有定义「准确率」函数"
    数据 = [[0.0, 0.0, 5.0], [1.0, 1.0, 15.0]]
    标签 = [0, 0]
    权重, 偏置 = [1.0, 1.0, 1.0], -100.0        # 一律判 0
    try:
        得 = 答案.准确率(权重, 偏置, 数据, 标签)
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 准确率(权重, 偏置, 数据, 标签) 出错了：{type(e).__name__}: {e}"
    if not isinstance(得, (int, float)) or isinstance(得, bool):
        return False, f"准确率 应该返回一个数字（比例），现在是 {type(得).__name__}：{得!r}"
    if abs(得 - 1.0) > 1e-9:
        return False, (f"这组数据两个都该判对（一律判 0 正好全对），应该是 1.0，你算出 {得!r}。\n"
                       f"      写法：判对几个 ÷ 总数。")
    数据2 = [[0.0, 0.0, 5.0], [1.0, 1.0, 15.0]]
    标签2 = [0, 1]                                    # 第二个应该是 1，但模型一律判 0
    try:
        得2 = 答案.准确率(权重, 偏置, 数据2, 标签2)
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 准确率 出错了：{type(e).__name__}: {e}"
    if abs(得2 - 0.5) > 1e-9:
        return False, (f"一对一错时准确率应该是 0.5，你算出 {得2!r}。\n"
                       f"      检查：是不是只数了判对的、忘了除以总数？")
    return True, "全对是 1.0、一对一错是 0.5，算得对"


def _跑一遍(答案, 原始数据, 标签):
    """走一遍完整流程：标准化 → 训练。返回 (权重, 偏置)。

    形状不对就抛 ValueError，由调用方翻译成人话。
    """
    取 = _取标准化结果(答案.标准化(原始数据))
    if 取 is None:
        raise ValueError("标准化 要返回 (标准化后的数据, 均值列表, 标准差列表) 三个东西")
    标准数据, _均值, _标准差 = 取
    if len(标准数据) != len(标签):
        raise ValueError("标准化之后的行数和标签数对不上 —— 别在标准化里丢数据")
    参数 = _取参数(答案.训练(标准数据, 标签, 0.1, 500))
    if 参数 is None:
        raise ValueError("训练 要返回 (权重, 偏置)")
    return 参数[0], 参数[1], 标准数据


def CHECK_核心_自己的数据上要学得会(答案):
    """第一关：在你自己的数据上训练，准确率要够高。

    ⚠ 这一关**可以**被"数据造假"糊弄（比如两类分得特别开），
      所以真正的把关是下一关（换一批没见过的数据）。
    """
    for n in ("西瓜数据", "西瓜标签", "标准化", "训练", "预测", "准确率"):
        if not hasattr(答案, n):
            return False, f"需要先有「{n}」"
    try:
        取 = _取标准化结果(答案.标准化(getattr(答案, "西瓜数据")))
    except ZeroDivisionError:
        return False, (
            "对自己的数据做标准化时除以 0 了（ZeroDivisionError）。\n"
            "      说明你的数据里有某一列**所有值都一样**（标准差是 0）。\n"
            "      标准化是 (x - 均值) / 标准差 —— 标准差是 0 就没法除了。\n"
            "      真实数据里这种「死列」很常见，处理办法：\n"
            "        · 给那一列多一点变化（比如你把所有西瓜的敲击声都写成 0.5）\n"
            "        · 或者干脆把这一列从特征里去掉 —— 一个永远不变的量\n"
            "          不可能帮你区分好坏瓜。")
    except Exception as e:                            # noqa: BLE001
        return False, f"对自己的数据做标准化时出错了：{type(e).__name__}: {e}"
    if 取 is None:
        return False, "标准化 要返回 (新数据, 均值, 标准差) 三个东西"
    标准数据, _均值, _标准差 = 取
    标签 = list(getattr(答案, "西瓜标签"))
    if len(标准数据) != len(标签):
        return False, "标准化之后的行数和标签数对不上 —— 别在标准化里丢数据"
    try:
        原样 = 答案.训练(标准数据, 标签, 0.1, 500)
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 训练(标准化后的数据, 标签, 0.1, 500) 出错了："
                       f"{type(e).__name__}: {e}\n"
                       f"      它要返回 (权重, 偏置)。")
    参数 = _取参数(原样)
    if 参数 is None:
        return False, (f"训练 要返回 (权重, 偏置) 两个东西，"
                       f"现在返回的是：{原样!r}")
    权重, 偏置 = 参数
    if len(权重) != 3:
        return False, (f"权重应该有 3 个（每个特征一个），你的有 {len(权重)} 个。\n"
                       f"      （三个特征对应三个权重，别忘了偏置是单独的一个数。）")
    try:
        对, 总 = _判对率(答案, 权重, 偏置, 标准数据, 标签)
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 预测(权重, 偏置, 特征) 出错了：{type(e).__name__}: {e}"
    准 = 对 / 总
    try:
        自报 = 答案.准确率(权重, 偏置, 标准数据, 标签)
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 准确率 出错了：{type(e).__name__}: {e}"
    if abs(自报 - 准) > 1e-9:
        return False, (f"你的 准确率 和实际判对的比例对不上：\n"
                       f"      实际判对 {对}/{总} = {准:.4f}，你返回的是 {自报!r}")
    if 准 >= 0.8:
        return True, f"自己的数据上判对 {对}/{总}（准确率 {准:.2f}），在权重 {[round(w, 2) for w in 权重]} 偏置 {偏置:.2f} 下"
    return False, (
        f"自己的数据上只判对了 {对}/{总}（准确率 {准:.2f}），这一关要求 0.8 以上。\n"
        f"      按这个顺序排查（**第一条最常见**）：\n"
        f"        1. 数据里有没有**自相矛盾**的例子？两个西瓜的特征几乎一样、\n"
        f"           标签却相反 —— 一条直线没法同时满足它们，感知机只能来回改。\n"
        f"        2. 好瓜和坏瓜是不是在某个特征上真的不一样？\n"
        f"           （如果两类混在一起，谁也学不会 —— 这不是代码的问题，是数据的问题。）\n"
        f"        3. 训练轮数够不够？学习率是不是太小？\n"
        f"        4. 标准化那一步做了吗？\n"
        f"      ⚠ 记住：**Garbage in, garbage out。**\n"
        f"        模型的本事不可能超过数据的本事。")


def CHECK_核心_换一批没见过的数据还要能用(答案):
    """第二关（真正的把关）：临时造一批随机的新西瓜，走完整流程再考一次。

    ⚠ 这批数据是**现场随机生成**的，学生不可能提前知道 ——
      所以背训练数据、写死权重、写死准确率，在这一关全都用不上。
      它考的是"你写的流程是不是真的能学"。

    ⚠ 一句实话：**光靠这一条挡不住所有"写死"**。
      实测发现，一组固定的权重有大约 7% 的概率"碰巧还挺准"
      （随机方向落在同一个半球里的概率没想象中那么小）。
      所以真正把"写死参数"钉死的是**下一条检查（标签对调）** ——
      那条完全不靠随机：一批数据和它标签取反后的准确率加起来正好是 1，
      同一个固定权重不可能两边都 ≥ 0.9。
      两条检查合起来，既考"会不会泛化"，也考"是不是真的在学"。
    """
    for n in ("标准化", "训练", "预测", "准确率"):
        if not hasattr(答案, n):
            return False, f"需要先有「{n}」"
    规律 = _定规律()
    训练数据, 训练标签 = _造西瓜(规律, 60)
    测试数据, 测试标签 = _造西瓜(规律, 20)      # 另造一批，同一个规律
    if len(训练数据) < 50 or len(测试数据) < 18:
        return True, "（随机数据没造够，跳过这一关）"

    try:
        取 = _取标准化结果(答案.标准化(训练数据))
    except Exception as e:                            # noqa: BLE001
        return False, f"对随机数据做标准化时出错了：{type(e).__name__}: {e}"
    if 取 is None:
        return False, "标准化 要返回 (新数据, 均值, 标准差) 三个东西"
    标准训练, 均值, 标准差 = 取
    try:
        原样 = 答案.训练(标准训练, 训练标签, 0.1, 500)
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 训练 出错了：{type(e).__name__}: {e}"
    参数 = _取参数(原样)
    if 参数 is None:
        return False, (f"训练 要返回 (权重, 偏置) 两个东西，"
                       f"现在返回的是：{原样!r}")
    权重, 偏置 = 参数

    if len(权重) != 3:
        return False, f"权重应该有 3 个（每个特征一个），你的有 {len(权重)} 个。"
    try:
        对训练, 总训练 = _判对率(答案, 权重, 偏置, 标准训练, 训练标签)
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 预测 出错了：{type(e).__name__}: {e}"
    训练准 = 对训练 / 总训练
    if 训练准 < 0.9:
        return False, (
            f"在新造的 {总训练} 个西瓜上训练，只判对了 {对训练}/{总训练}"
            f"（准确率 {训练准:.2f}），要求 0.9 以上。\n"
            f"      这批数据的规律是**一条直线**（新西瓜由一条隐藏的分界线生成的），\n"
            f"      感知机只要正常训练就应该全部判对。\n"
            f"      常见原因：\n"
            f"        · 训练时没有真的改权重（比如只跑了一轮就退出）\n"
            f"        · 更新公式错了（误差 = 正确标签 - 预测值，别写反）\n"
            f"        · 标准化把数据搞坏了（比如除以了 0，或者用了错的列）\n"
            f"        · 提前 break 的条件写错了")

    # 关键：测试集要用**训练集**的均值和标准差来标准化（不能各自标准化）
    标准测试 = []
    for 行 in 测试数据:
        标准测试.append([(行[j] - 均值[j]) / 标准差[j] for j in range(3)])
    try:
        对测试, 总测试 = _判对率(答案, 权重, 偏置, 标准测试, 测试标签)
    except Exception as e:                            # noqa: BLE001
        return False, f"在新数据上调用 预测 出错了：{type(e).__name__}: {e}"
    测试准 = 对测试 / 总测试
    # 为什么是 0.8 而不是 1.0：感知机一判对全部训练数据就停了，
    # 它学到的那条线不一定正好是"真规律"那条 —— 偶尔会有一两个点
    # 落在两条线之间被切错。这是算法的真实行为，不是学生写错了。
    # （门槛也不能再低：一律猜多数类只有 ~50%，0.8 依然拦得住。）
    if 测试准 < 0.8:
        return False, (
            f"训练集上判对 {训练准:.2f}，但**换一批没见过的西瓜**只有 {测试准:.2f}"
            f"（{对测试}/{总测试}），要求 0.8 以上。\n"
            f"      训练集学得好、新数据上不行，这叫**过拟合** —— 模型背下了训练数据，\n"
            f"      没学到规律。（真实项目里这是最常见、最要命的问题。）\n"
            f"      先检查一件事：你的 预测 是不是只对训练时见过的数字有效？\n"
            f"      再检查：标准化返回的均值和标准差，有没有真的用在训练上？\n"
            f"      （训练用的数据和预测时喂进去的数据，必须是同一套标准化的结果。）")
    return True, (f"新造的数据上：训练 {对训练}/{总训练}（{训练准:.2f}），"
                  f"没见过的测试集 {对测试}/{总测试}（{测试准:.2f}）—— 流程真的能用")


def CHECK_核心_标签反过来答案就得反过来(答案):
    """把同一批西瓜的好坏**全部对调**，重新训练 —— 模型也必须跟着对调。

    ⚠ 这一条是防"写死权重"最狠的一招，而且**不靠随机**：
      一批数据的准确率和它标签取反后的准确率加起来正好是 1
      （同一个模型，在完全相反的答案上，不可能两边都对）。
      所以只要有一边 ≥ 0.9，另一边必然 ≤ 0.1 ——
      写死的权重一定会在其中一边翻车，躲不掉。
      （检查"换一批数据"时我用过一个写死的权重碰巧蒙对的情况，
        所以才补了这一条。）
    """
    for n in ("标准化", "训练", "预测"):
        if not hasattr(答案, n):
            return False, f"需要先有「{n}」"
    规律 = _定规律()
    数据, 标签 = _造西瓜(规律, 40)
    反标签 = [1 - y for y in 标签]
    if len(数据) < 34:
        return True, "（随机数据没造够，跳过这一关）"

    结果 = []
    for 这份标签, 名字 in ((标签, "原来的标签"), (反标签, "对调后的标签")):
        try:
            权重, 偏置, 标准数据 = _跑一遍(答案, 数据, 这份标签)
        except Exception as e:                        # noqa: BLE001
            return False, f"（{名字}）跑流程时出错了：{type(e).__name__}: {e}"
        try:
            对, 总 = _判对率(答案, 权重, 偏置, 标准数据, 这份标签)
        except Exception as e:                        # noqa: BLE001
            return False, f"调用 预测 出错了：{type(e).__name__}: {e}"
        结果.append((对 / 总, [round(w, 3) for w in 权重], 偏置))

    准1, 权1, 偏1 = 结果[0]
    准2, 权2, 偏2 = 结果[1]
    if 准1 >= 0.9 and 准2 >= 0.9:
        return True, (f"标签对调前 {准1:.2f}、对调后 {准2:.2f} —— "
                      f"两次都学对了，权重确实跟着数据变"
                      f"（{权1}/{偏1:.2f} → {权2}/{偏2:.2f}）")
    return False, (
        f"我把同一批西瓜的标签**全部对调**（好瓜变坏瓜），重新训练了一次。\n"
        f"      原来的标签：准确率 {准1:.2f}，权重 {权1}，偏置 {偏1:.2f}\n"
        f"      对调后的标签：准确率 {准2:.2f}，权重 {权2}，偏置 {偏2:.2f}\n"
        f"      两批数据的**特征完全一样，答案完全相反** ——\n"
        f"      所以同一个模型不可能两边都答对（两个准确率加起来正好是 1）。\n"
        f"      要两边都能到 0.9 以上，唯一的办法就是**每次都真的重新训练**。\n"
        f"      如果两次的权重一模一样，或者有一次明显不行：\n"
        f"        参数是写死的。训练必须看数据：判错就按误差改权重。")


def CHECK_没偷偷用第三方库(答案):
    """零依赖不是口号：这台机器上根本没有 numpy / sklearn，import 了也会崩。"""
    路径 = getattr(答案, "__file__", None)
    if not 路径:
        return True, "（拿不到源码文件，跳过）"
    try:
        from pathlib import Path
        源码 = Path(路径).read_text(encoding="utf-8")
    except Exception:                                 # noqa: BLE001
        return True, "（源码读不出来，跳过）"
    禁用 = ("numpy", "sklearn", "scipy", "torch", "tensorflow", "pandas")
    用了 = []
    for 行 in 源码.splitlines():
        行 = 行.strip()
        if 行.startswith("#"):
            continue
        for 库 in 禁用:
            if 行.startswith(f"import {库}") or 行.startswith(f"from {库}"):
                用了.append(库)
    if 用了:
        return False, (
            "你的答案里 import 了：" + "、".join(sorted(set(用了))) + "\n"
            "      这台机器上没有装它们，跑不起来的。\n"
            "      这一课要的是你**自己写的**流程：标准化、感知机、评估，全部纯 Python。")
    return True, "没有依赖任何第三方库"
