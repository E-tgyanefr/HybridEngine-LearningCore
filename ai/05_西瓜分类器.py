# 第 05 课：把 AI 用起来 —— 判断西瓜好坏

# 要做：
#   1. 自己准备数据（这一课的数据要**你**给）：
#        · 西瓜数据：一个列表，**至少 12 条**，每条是 3 个特征：
#            [颜色深浅, 敲击声, 糖度]
#            颜色深浅：0.0（青绿）~ 1.0（深绿）
#            敲击声：  0.0（沉闷）~ 1.0（清脆）
#            糖度：    5.0 ~ 15.0
#        · 西瓜标签：和上面一一对应，1 = 好瓜，0 = 坏瓜，**两种都要有**。
#   2. 写一个函数 标准化(数据)：返回 (标准化后的数据, 均值列表, 标准差列表)
#      每一列减自己的均值、再除以自己的标准差。
#   3. 写一个函数 训练(数据, 标签, 学习率=0.1, 最多轮数=500)
#      数据是**已经标准化过**的。用第 02 课的感知机，返回 (权重, 偏置)。
#   4. 写一个函数 预测(权重, 偏置, 特征)：返回 0 或 1。
#   5. 写一个函数 准确率(权重, 偏置, 数据, 标签)：返回判对的比例。
#
#   ⚠ 检查分成两关：
#      · 先在你的数据上考（准确率要够高）
#      · 再**换一批你没见过的数据**重新训练、重新考一遍
#     所以"背下训练数据"是没用的，你得写出一个真的会学的流程。

# ─────────────────────────────────────────────────────
#  一、发生了什么：这一课你就是做 AI 的人
# ─────────────────────────────────────────────────────
#
# 挑西瓜这件事，老瓜农靠手感：拍一拍、看一看。他脑子里其实有一套
# **打分规则**：颜色深的加分、声音清脆的加分、糖度高的加分……
#
# 这一课你要做的，就是让程序**从例子里把这套规则找出来**。
# 你负责给例子（数据），程序负责找规则（训练），最后拿新西瓜考验它。
#
# 整件事的流程和真实项目一模一样，一共六步：
#
#     ① 拿数据     →  西瓜数据、西瓜标签
#     ② 看数据     →  特征是什么意思？两类是不是真的不一样？
#     ③ 分数据     →  **留出一部分当测试集**（这一步最容易被跳过）
#     ④ 标准化     →  让每个特征"说话一样大声"
#     ⑤ 训练       →  感知机调权重（第 02 课已经写过了）
#     ⑥ 评估       →  在**没见过**的数据上算准确率
#
# 真实项目里，②③④ 花的时间远超 ⑤。这不是巧合 ——
# **模型是现成的，数据才是你要花力气的地方。**
#
# （顺便说：用"色泽、敲声、糖度"判断西瓜，是周志华《机器学习》里
#   著名的"西瓜数据集"。这是中文 AI 教材里最有名的一张表。）

