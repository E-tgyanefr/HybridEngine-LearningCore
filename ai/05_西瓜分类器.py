#   西瓜数据 / 西瓜标签          → **你给的例子**。这一课真正的原料。
#   标准化(数据)                 → 把量纲拉齐，返回新数据 + 均值 + 标准差。
#   训练(数据, 标签, ...)         → 感知机学习（第 02 课那个，可以直接抄）。
#   预测(权重, 偏置, 特征)        → 判断一个新西瓜。
#   准确率(权重, 偏置, 数据, 标签) → 打分。
#
# 数据长这样（前 5 条示例，你需要至少 12 条，自己补）：
#
#     西瓜数据 = [
#         [0.85, 0.20, 12.0],   # 深绿、声音沉闷、很甜   → 好瓜
#         [0.90, 0.15, 13.5],   # 更深、更闷、更甜       → 好瓜
#         [0.20, 0.80,  6.0],   # 青绿、清脆、不甜       → 坏瓜
#         [0.30, 0.75,  7.5],   # ...
#         [0.75, 0.30, 11.0],   # ...
#     ]
#     西瓜标签 = [1, 1, 0, 0, 1]
#
# ⚠ 给数据时注意三条：
#   · **两类都要有**，而且别只给两三条 —— 12 条以上，两类大致均衡。
#   · **别给自相矛盾的数据**：两个特征几乎一样的西瓜，一个标 1 一个标 0。
#     感知机只能画一条分界线，你让它同时满足两个矛盾的例子，它就只能来回改。
#   · 好瓜和坏瓜要**真的不一样**。你想让程序学会分辨，
#     至少得让好瓜在某个特征上明显高（或低）一些。

# ─────────────────────────────────────────────────────
#  三、应该怎么写
# ─────────────────────────────────────────────────────
#
# ① 标准化：这一课唯一的新知识，也是最重要的一步
#
#    先看一个数字。假设两个西瓜：
#
#        西瓜甲：[0.80, 0.50, 12.0]
#        西瓜乙：[0.30, 0.50,  6.0]
#
#    它们的距离（第 04 课那种算法）：
#        颜色差 0.5  → 平方 0.25
#        声音差 0.0  → 平方 0.00
#        糖度差 6.0  → 平方 36.0          ← 其它两项加起来不到它的 1%
#        距离 ≈ 6.02
#
#    看出问题了吗？**糖度一个人说了算。**
#    颜色和敲击声的差别被彻底淹没了 —— 不是它们不重要，
#    是它们的**单位太小**（0~1 对 5~15）。
#
#    感知机也会被这件事坑：糖度那一维的输入大，梯度就大，
#    权重一次被改动很多、来回震荡；颜色那一维几乎不动。
#
#    解决办法很朴素：**把每一列都拉成"均值 0、标准差 1"**。
#
#        z = (x - 这一列的均值) / 这一列的标准差
#
#    直觉：先问"这个值比平均高还是低"（减均值），
#    再问"高了多少个'典型波动'"（除以标准差）。
#    拉完之后，没有哪一列还能因为单位大就压过别人。
#
#    ⚠ 两个坑：
#      · **要用训练集的均值和标准差去处理测试集**，不能各自标准化。
#        各自标准化等于"偷偷看了测试集的信息" ——
#        而且两边尺度不一致，模型看到的数就不是同一套了。
#        检查就是这么做的：用你返回的均值和标准差去处理新数据。
#      · 如果某一列所有值都一样，标准差是 0，除法会崩（ZeroDivisionError）。
#        真实数据里这种"死列"很常见，一般直接扔掉那一列。
#
# ② 均值、标准差怎么算（纯 Python，一个循环）
#
#        列数 = len(数据[0])
#        均值 = [0.0] * 列数
#        for 行 in 数据:
#            for j in range(列数):
#                均值[j] += 行[j]
#        均值 = [s / len(数据) for s in 均值]
#
#        标准差 = [0.0] * 列数
#        for 行 in 数据:
#            for j in range(列数):
#                标准差[j] += (行[j] - 均值[j]) ** 2
#        标准差 = [(s / len(数据)) ** 0.5 for s in 标准差]
#
#    （上面除以的是 n。统计学里样本标准差有时除以 n-1，
#      两种都行、差别很小 —— 检查两种都接受。）
#
# ③ 训练 / 预测：第 02 课的感知机，直接搬过来
#
#    一模一样，不用改。这就是把算法学明白的好处：
#    换个问题，代码原样能用。唯一区别是输入从 2 个特征变成了 3 个 ——
#    而我们当初就是用循环写的，所以一个字都不用改。
#
# ④ 评估：为什么要留出测试集
#
#    最诱人的做法是拿训练数据考自己：准确率 100%，皆大欢喜。
#    但那是**假的**。第 04 课说过 KNN 的极端例子：
#    K=1 时拿训练集考自己永远是满分，因为最近的邻居就是它自己。
#
#    这在 AI 里叫**过拟合**：模型把训练数据**背下来**了，
#    而不是学到了规律。判断它有没有背，唯一的办法是
#    拿**它从没见过的数据**考它 —— 这就是测试集存在的全部理由。
#
#    检查会这么做：临时造一批**随机的新西瓜**（你不可能提前知道），
#    用你的 标准化 / 训练 / 预测 走一遍完整流程。
#    这一关过得了，才说明你写的是一个**能用的流程**，不是一份答案。
#
# ⑤ 如果准确率上不去，怎么办（按这个顺序排查）
#
#     1. 数据本身有没有矛盾？（两个几乎一样的西瓜标签相反 → 谁也学不会）
#     2. 两类是不是真的能分开？（画在纸上看看，或者想想有没有一条线能分开）
#     3. 训练轮数够不够？学习率是不是太小/太大？（第 03 课的教训）
#     4. 标准化做了没有？
#
#    ⚠ 注意第 1 条永远排在最前面。有一句话在 AI 圈里人人都会背：
#      **Garbage in, garbage out（垃圾进，垃圾出）。**
#      模型的水平不可能超过数据的水平 —— 这一课你会亲身感受到。

# ─────────────────────────────────────────────────────
#  四、顺便记住什么
# ─────────────────────────────────────────────────────
#  · 你的这套流程（感知机 + 标准化）**只能画一条直线**。
#    如果好瓜的规律是"糖度高**并且**颜色深"（像 AND 那样），它能学会；
#    如果是"糖度高**或者**颜色深"，也能；
#    但如果是"**要么**糖度高、**要么**颜色深，两个都高反而不好"（像 XOR），
#    它就学不会了 —— 第 02 课讲的那个死穴，在这里会原样再出现一次。
#  · 特征不是越多越好。加一个跟好坏无关的特征（比如"西瓜的编号"），
#    模型可能碰巧在训练集上利用它，换一批数据就完蛋。
#  · 到这里，AI 入门的五个基本件你都摸过了：
#    **线性回归**（拟合）、**感知机**（分类）、**梯度下降**（优化）、
#    **KNN**（距离）、**标准化与评估**（工程）。
#    今天所有的大模型，都是这几件事的放大版：
#    更多层、更多参数、更多数据 —— 但没有一件是新原理。

