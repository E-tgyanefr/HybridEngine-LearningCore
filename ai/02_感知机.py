import random

AND数据 = [[0, 0], [0, 1], [1, 0], [1, 1]]
AND标签 = [0, 0, 0, 1]
OR标签 = [0, 1, 1, 1]


def _取参数(结果):
    """把学生返回的东西变成 (权重列表, 偏置)；形状不对返回 None。"""
    try:
        权重, 偏置 = 结果
        return [float(w) for w in 权重], float(偏置)
    except Exception:                                 # noqa: BLE001
        return None


def _判对率(答案, 权重, 偏置, 数据, 标签):
    """用学生的 预测 数一数判对几个。返回 (对几个, 总共几个, 明细)。"""
    对 = 0
    明细 = []
    for 输入, 正确 in zip(数据, 标签):
        得 = 答案.预测(权重, 偏置, list(输入))
        得 = 1 if 得 else 0                    # True/False 也认，别在这上面卡人
        明细.append(f"{输入}→{得}(应为{正确})")
        if 得 == 正确:
            对 += 1
    return 对, len(数据), "  ".join(明细)


def _造可分数据(条数=30):
    """随机造一批"一条直线能分开"的点。

    ⚠ 关键：每次运行都重新随机 —— 所以写死权重必然过不了这一条。
    """
    while True:
        w1, w2 = random.uniform(-1, 1), random.uniform(-1, 1)
        长度 = (w1 * w1 + w2 * w2) ** 0.5
        if 长度 > 0.5:
            break
    w1, w2 = w1 / 长度, w2 / 长度          # 单位法向量，好控制"间隔"有多大
    偏 = random.uniform(-0.4, 0.4)
    数据, 标签 = [], []
    while len(数据) < 条数:
        x1, x2 = random.uniform(-1, 1), random.uniform(-1, 1)
        z = w1 * x1 + w2 * x2 + 偏
        if abs(z) < 0.35:                  # 离分界线太近的点不要 —— 保证有余量
            continue
        数据.append([x1, x2])
        标签.append(1 if z > 0 else 0)
    return 数据, 标签, (w1, w2, 偏)


def CHECK_三个函数都在(答案):
    缺 = [n for n in ("阶跃", "预测", "训练") if not hasattr(答案, n)]
    if 缺:
        return False, (
            "还缺这些函数：" + "、".join(缺) + "\n"
            "      三个函数各管一件事：\n"
            "          阶跃(z)                    放电开关（激活函数）\n"
            "          预测(权重, 偏置, 输入)        用当前参数判断一次\n"
            "          训练(数据, 标签, ...)         反复改参数，直到判对")
    for n in ("阶跃", "预测", "训练"):
        if not callable(getattr(答案, n)):
            return False, f"「{n}」存在，但它不是函数。要用 def 定义。"
    return True, "阶跃 / 预测 / 训练 都在"


def CHECK_阶跃函数(答案):
    if not hasattr(答案, "阶跃"):
        return False, "还没有定义「阶跃」函数"
    for z, 期望 in ((-3.0, 0), (-0.001, 0), (0.001, 1), (5.0, 1), (-100.0, 0)):
        try:
            得 = 答案.阶跃(z)
        except Exception as e:                        # noqa: BLE001
            return False, f"调用 阶跃({z}) 出错了：{type(e).__name__}: {e}"
        if (1 if 得 else 0) != 期望:
            return False, (f"阶跃({z}) 应该是 {期望}，你返回的是 {得!r}。\n"
                           f"      写法：return 1 if z >= 0 else 0\n"
                           f"      注意阶跃只该输出 0 或 1，不该把 z 原样返回。")
    # z 正好等于 0 时用 >= 还是 > 都行 —— 这是约定问题，不是对错问题，
    # 所以两种都算过（详见课程里的说明）。
    try:
        零 = 答案.阶跃(0)
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 阶跃(0) 出错了：{type(e).__name__}: {e}"
    if 1 if 零 else 0:
        return True, "正数→1、负数→0；0 这里按课程约定也当 1，没问题"
    return True, ("正数→1、负数→0 都对。0 这里你返回了 0 —— 也可以，\n"
                  "      只要前后一致就行（课程约定是 >= 0，两种都不算错）。")


def CHECK_预测用的是加权和(答案):
    if not hasattr(答案, "预测"):
        return False, "还没有定义「预测」函数"
    例 = []
    for _ in range(5):
        权重 = [random.uniform(-2, 2) for _ in range(3)]
        偏置 = random.uniform(-2, 2)
        输入 = [random.uniform(-2, 2) for _ in range(3)]
        总分 = sum(w * x for w, x in zip(权重, 输入)) + 偏置
        if abs(总分) < 0.3:
            continue                       # 离门槛太近，不拿它考人
        期望 = 1 if 总分 > 0 else 0
        try:
            得 = 答案.预测(权重, 偏置, 输入)
        except Exception as e:                        # noqa: BLE001
            return False, (f"调用 预测(权重, 偏置, 输入) 出错了：{type(e).__name__}: {e}\n"
                           f"      权重和输入都是列表，函数要接收三个参数。")
        if (1 if 得 else 0) != 期望:
            return False, (
                f"预测 判错了。\n"
                f"      权重 = {[round(w, 3) for w in 权重]}\n"
                f"      偏置 = {偏置:.3f}\n"
                f"      输入 = {[round(x, 3) for x in 输入]}\n"
                f"      加权和 = {总分:.4f}（应该是 {期望}）\n"
                f"      实际输出：{得!r}\n"
                f"      写法：总分 = 偏置 + 权重[i] * 输入[i] 的累加，再 return 阶跃(总分)。")
        例.append(f"加权和 {总分:.3f} → {得}")
    if not 例:
        return True, "（随机到的点都太靠近门槛，跳过一组）"
    return True, "；".join(例[:3])


def CHECK_学会AND(答案):
    if not hasattr(答案, "训练"):
        return False, "还没有定义「训练」函数"
    try:
        结果 = 答案.训练(AND数据, AND标签, 0.1, 100)
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 训练(数据, 标签, 0.1, 100) 出错了：{type(e).__name__}: {e}\n"
                       f"      它要返回 (权重, 偏置) —— 用 return 权重, 偏置")
    参数 = _取参数(结果)
    if 参数 is None:
        return False, (f"训练 应该返回 (权重, 偏置)，现在返回的是：{结果!r}\n"
                       f"      权重是列表、偏置是一个数。")
    权重, 偏置 = 参数
    对, 总, 明细 = _判对率(答案, 权重, 偏置, AND数据, AND标签)
    if 对 == 总:
        return True, f"AND 四条全对：{明细}"
    return False, (
        f"AND 只判对了 {对}/{总}。\n"
        f"      {明细}\n"
        f"      学出来的参数：权重 = {权重}，偏置 = {偏置}\n"
        f"      AND 的规律是「两个都是 1 才是 1」，所以两个权重都该是**正的**\n"
        f"      （输入越大越支持「是」），偏置该是**负的**（门槛高，光一个 1 不够）。\n"
        f"      先检查你的更新公式：\n"
        f"          误差 = 正确标签 - 预测值\n"
        f"          权重[i] += 学习率 * 误差 * 输入[i]\n"
        f"          偏置   += 学习率 * 误差\n"
        f"      常见错误：符号写反（+ 写成 -）、忘了乘 输入[i]、\n"
        f"                拿错误标签去减（要用 正确标签 - 预测值）。")


