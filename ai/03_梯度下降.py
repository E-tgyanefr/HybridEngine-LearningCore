# 第 03 课：梯度下降 —— 机器怎么"找方向"

# 要做：
#   1. 写一个函数 数值梯度(函数, x, 步长=1e-5)
#      用中心差分估个斜率：(函数(x+步长) - 函数(x-步长)) / (2 * 步长)
#   2. 写一个函数 梯度下降(函数, 起点, 学习率=0.1, 步数=100)
#      从 起点 出发走 步数 步，每一步：
#          x = x - 学习率 * 数值梯度(函数, x)
#      返回一个**列表**：走过的每一个 x 都记下来，
#      长度是 步数+1（第一个就是起点）。
#
#   ⚠ 检查会**随机换一个函数**再问你一次 ——
#     所以不能针对某个具体函数写死（比如 x*x 就 return 2*x）。
#     你的 数值梯度 必须对**任意**函数都成立。

# ─────────────────────────────────────────────────────
#  一、发生了什么：闭着眼睛下山
# ─────────────────────────────────────────────────────
#
# 第 01 课我们是**一步算出**最好的那条线的（最小二乘有公式解）。
# 但绝大多数模型没有公式解 —— 一个几百层的神经网络，
# 你没法推导出一个式子直接算出所有参数。
#
# 那怎么办？只能一点一点试。办法叫**梯度下降**，它的画面感很强：
#
#     你被蒙着眼放在山坡上，要走到山谷最低点。
#     你看不见全局，但能用脚摸出**脚下哪个方向最陡**。
#     于是你往最陡的**下坡方向**迈一小步，停，再摸一次，再迈一步。
#     重复几百次，你就到谷底了。
#
# 对应到数学：
#   · "脚下哪个方向最陡" = **导数（梯度）**。导数就是斜率。
#   · "往哪边走" = 往梯度的**反方向**。因为梯度指向的是**上升**最快的方向，
#                 我们要下山，所以取负号。
#   · "迈多大一步" = **学习率**。这是整件事里唯一要你自己定的数。
#
# 一句话：**梯度告诉你去哪，学习率告诉你走多远。**
#
# ⚠ 这里有个最重要的观念转变：
#   第 01 课的"学习"是算出来的，第 03 课的"学习"是**试出来的**。
#   今天所有深度学习，用的都是这个"试"字（所以叫"训练"不叫"求解"）。

# ─────────────────────────────────────────────────────
#  二、你写的是什么：两个函数
# ─────────────────────────────────────────────────────
#
#   数值梯度(函数, x, 步长)      → "摸一下脚下的坡有多陡"。**求方向**。
#   梯度下降(函数, 起点, ...)     → 按方向一步步走，把脚印记下来。**走路**。
#
# 为什么只要这两个函数？因为这一课的主角不是某个函数，
# 是"怎么找最小值"这件事本身 —— 所以 函数 是**参数**，传进来就行。
# 检查会传各种各样的函数给你（包括随机生成的），你必须都能处理。

# ─────────────────────────────────────────────────────
#  三、应该怎么写
# ─────────────────────────────────────────────────────
#
# ① 数值梯度：不知道导数公式，也能算出斜率
#
#    导数的定义是"一个小变化引起的另一个小变化"：
#
#        导数 ≈ (函数(x + 步长) - 函数(x)) / 步长
#
#    这叫**前向差分**。但这一课要写的是**中心差分**：
#
#        导数 ≈ (函数(x + 步长) - 函数(x - 步长)) / (2 * 步长)
#
#    为什么要往前、往后各看一眼？因为这样更准。
#    前向差分的误差跟 步长 成正比，中心差分的误差跟 步长² 成正比 ——
#    步长取 1e-5 时，前者的误差约 1e-5，后者约 1e-10，差了十万倍。
#    直觉：只往前看，你摸到的是"前方一小段的平均坡度"；
#    前后都看，两边的偏差正好抵消掉大半。
#
#    ⚠ 两个坑：
#      · 分母是 2 * 步长，不是 步长（漏了 2，结果正好差一倍 —— 很常见）
#      · 步长不能取太小：1e-20 会让 x+步长 和 x 变成同一个浮点数，除出来是 0。
#        1e-5 是个常用的折中值。
#
#    顺便说：真实的 AI 框架不用这个办法 —— 它们用**反向传播**直接算出精确导数
#    （快得多）。但数值微分有一件反向传播替代不了的作用：
#    它是**检验**反向传播写没写错的黄金标准。所以这不是"玩具"，是真在用的工具。
#
# ② 梯度下降：一个 for 循环
#
#        x = 起点
#        脚印 = [x]                      # ← 起点也要记下来
#        for _ in range(步数):
#            x = x - 学习率 * 数值梯度(函数, x)
#            脚印.append(x)
#        return 脚印
#
#    **为什么要把脚印都记下来？** 因为只看最后一个数字，你没法判断
#    它是"稳稳走到谷底"还是"在半路上来回横跳"。把过程记下来，
#    一眼就能看出区别 —— 这也是检查能判断你写对没写对的关键。
#
# ③ 学习率：三种完全不同的结局（拿 f(x) = (x-3)² 亲手试一遍）
#
#    对这个函数，第 n 步离谷底的距离有个精确的规律：
#
#        (x_{n+1} - 3) = (1 - 2×学习率) × (x_n - 3)
#
#    也就是说，每一步距离都乘上同一个数 (1 - 2×学习率)。
#    乘数的绝对值小于 1 就收敛，大于 1 就发散。于是：
#
#     学习率        乘数      结局
#     ────────────────────────────────────────────────────
#      0.01         0.98     稳稳靠近，但**慢得让人着急**（要几百步才走一半）
#      0.3          0.4      又快又稳 —— 好学习率
#      0.5          0        一步到位（数学上最漂亮的情况）
#      0.7         -0.4      来回横跳，但幅度在变小 → 最终也能到
#      1.0         -1.0      左右等幅横跳，**永远到不了**
#      1.1         -1.2      每一步都更远 → **飞出去，数字爆炸**
#      2.0         -3.0      几步就变成天文数字
#
#    检查里有两条专门盯住两端：
#      · 学习率 1e-4 走 10 步 → 几乎没动（"太小"的样子）
#      · 学习率 1.1 走 50 步 → 数字飞了（"太大"的样子）
#
#    ⚠ 这两条也是**忠实性**检查：如果你在代码里偷偷加了"限幅"
#      或者"没变好就停"的保护，反而会露馅 ——
#      保护本身没错，但这一课要你亲眼看到它真的会飞。
#      真实训练里学习率调大了就是这个后果：损失变成 nan，一晚上白跑。
#
# ④ 为什么是"减"不是"加"
#
#    先确认一件事：**梯度指向的是"上升"最快的方向，不是下降。**
#    拿 f(x) = (x-3)² 试：在 x=0 处导数是 2×(0-3) = -6，是个负数。
#    往负方向走（x 变小，走到 -1）f 变成 16，比原来的 9 更大 ——
#    确实是在"往高处走"。所以梯度的方向是**上坡**。
#
#    我们想让它变小，就必须**减去**梯度：减一个负数 = 往正方向走。
#    写反了就是在"爬山"，越走越高 ——
#    检查里"误差一直在下降"那条会立刻抓住。

# ─────────────────────────────────────────────────────
#  四、顺便记住什么
# ─────────────────────────────────────────────────────
#  · **梯度下降只能保证找到"局部"最低点**。函数有几个坑时，
#    从哪出发就掉进哪个坑。这就是"随机初始化"存在的原因 ——
#    多试几个起点，或者用带动量的方法。
#  · 这一课的 函数 只有一个参数 x。真实模型有几百万个参数，
#    但做法一模一样：**每个参数各求一次梯度，一起往下走**。
#    多参数的版本叫"梯度向量"，代码里就是多套一层循环。
#  · "学习率调度"（先大步走、接近谷底改成小步）是真实训练的标配，
#    来源就是右边那张表：太大会飞，太小太慢。
#  · 真实训练还会**分批**（每次只看一小撮数据算梯度）——
#    数据太多时，每走一步都看完所有数据是不现实的。
#    这个想法叫"随机梯度下降"，是今天所有大模型的训练方式。

