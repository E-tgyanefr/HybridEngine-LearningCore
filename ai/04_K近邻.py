import random


def _参考距离(a, b):
    return sum((p - q) ** 2 for p, q in zip(a, b)) ** 0.5


def _正常邻居(结果):
    """把学生返回的邻居列表变成 [(点, 标签)]；形状不对返回 None。

    ⚠ 这里**不**向学生要距离：距离由检查自己按定义重算一遍
      （`_参考距离`），这样才能验出"排序对不对"。
      如果拿学生自己报的距离来验，他把距离算错了也照样"排好序"。
    """
    if isinstance(结果, (str, bytes)) or not hasattr(结果, "__len__"):
        return None
    出 = []
    for 项 in 结果:
        try:
            点, 标签 = 项
            出.append(([float(v) for v in 点], 标签))
        except Exception:                             # noqa: BLE001
            return None
    return 出


def _造两簇(每簇=8, 间距=6.0):
    """随机造两簇分得很开的点，返回 (训练集, 簇A的点, 簇B的点)。"""
    心A = [random.uniform(-间距, -2.0), random.uniform(-5.0, 5.0)]
    心B = [random.uniform(2.0, 间距), random.uniform(-5.0, 5.0)]
    训练集 = []
    for 心, 标签 in ((心A, 0), (心B, 1)):
        for _ in range(每簇):
            点 = [心[0] + random.uniform(-0.7, 0.7), 心[1] + random.uniform(-0.7, 0.7)]
            训练集.append((点, 标签))
    random.shuffle(训练集)
    return 训练集, 心A, 心B


def _参考分类(训练集, 查询点, k):
    """按定义老老实实算一遍（选择题答案用，不参与给分）。"""
    排序 = sorted(训练集, key=lambda t: _参考距离(t[0], 查询点))
    票 = {}
    for _点, 标签 in 排序[:k]:
        票[标签] = 票.get(标签, 0) + 1
    return max(票, key=票.get)


def CHECK_四个函数都在(答案):
    缺 = [n for n in ("距离", "找邻居", "分类", "准确率") if not hasattr(答案, n)]
    if 缺:
        return False, (
            "还缺这些函数：" + "、".join(缺) + "\n"
            "      四个函数各管一件事：\n"
            "          距离(a, b)                两个点有多像\n"
            "          找邻居(训练集, 查询点, k)  找出最近的 k 个\n"
            "          分类(训练集, 查询点, k)    让邻居投票\n"
            "          准确率(训练集, 测试集, k)  在没见过的数据上考一次")
    for n in ("距离", "找邻居", "分类", "准确率"):
        if not callable(getattr(答案, n)):
            return False, f"「{n}」存在，但它不是函数。要用 def 定义。"
    return True, "距离 / 找邻居 / 分类 / 准确率 都在"


def CHECK_距离算得对(答案):
    if not hasattr(答案, "距离"):
        return False, "还没有定义「距离」函数"
    # 二维：随机点，对照勾股定理
    for _ in range(3):
        a = [random.uniform(-10, 10), random.uniform(-10, 10)]
        b = [random.uniform(-10, 10), random.uniform(-10, 10)]
        try:
            得 = 答案.距离(a, b)
        except Exception as e:                        # noqa: BLE001
            return False, (f"调用 距离({[round(v, 2) for v in a]}, "
                           f"{[round(v, 2) for v in b]}) 出错了："
                           f"{type(e).__name__}: {e}")
        期望 = _参考距离(a, b)
        if not isinstance(得, (int, float)) or isinstance(得, bool):
            return False, f"距离 应该返回一个数字，现在返回的是 {type(得).__name__}：{得!r}"
        if abs(得 - 期望) > 1e-6 * max(1.0, 期望):
            曼哈顿 = sum(abs(p - q) for p, q in zip(a, b))
            if abs(得 - 曼哈顿) < 1e-6 * max(1.0, 曼哈顿):
                return False, (
                    f"你算出来的是**曼哈顿距离**（差值取绝对值直接相加）。\n"
                    f"      a = {[round(v, 3) for v in a]}\n"
                    f"      b = {[round(v, 3) for v in b]}\n"
                    f"      你算出 {得:.6f}，但欧氏距离应该是 {期望:.6f}\n"
                    f"      欧氏距离要先平方再相加、最后**开根号**：\n"
                    f"          平方和 += (p - q) ** 2\n"
                    f"          return 平方和 ** 0.5")
            return False, (
                f"距离算错了。\n"
                f"      a = {[round(v, 3) for v in a]}\n"
                f"      b = {[round(v, 3) for v in b]}\n"
                f"      期望：{期望:.6f}\n"
                f"      实际：{得:.6f}\n"
                f"      检查：每个特征相减、**平方**、加起来、最后**开根号**（** 0.5）。")
    # 三维：防止写死 a[0]、a[1]
    a = [random.uniform(-5, 5) for _ in range(3)]
    b = [random.uniform(-5, 5) for _ in range(3)]
    try:
        得 = 答案.距离(a, b)
    except Exception as e:                            # noqa: BLE001
        return False, f"三维的点调用出错了：{type(e).__name__}: {e}"
    期望 = _参考距离(a, b)
    if abs(得 - 期望) > 1e-6 * max(1.0, 期望):
        两维 = _参考距离(a[:2], b[:2])
        if abs(得 - 两维) < 1e-6 * max(1.0, 两维):
            return False, (
                "两个点有 **3 个特征**，但你的结果只用了前两个。\n"
                f"      a = {[round(v, 3) for v in a]}\n"
                f"      b = {[round(v, 3) for v in b]}\n"
                f"      你算的 {得:.6f} 正好是只看前两维的距离（{两维:.6f}）。\n"
                f"      写法：别写死下标，用 zip 配对：\n"
                f"          for p, q in zip(a, b): 平方和 += (p - q) ** 2")
        return False, (f"三维的点算错了：期望 {期望:.6f}，你算出 {得:.6f}。\n"
                       f"      用 zip 配对，别写死 a[0]、a[1]。")
    # 同一个点到自己的距离必须是 0
    try:
        自己 = 答案.距离(a, list(a))
    except Exception as e:                            # noqa: BLE001
        return False, f"调用出错了：{type(e).__name__}: {e}"
    if abs(自己) > 1e-9:
        return False, f"一个点到自己的距离应该是 0，你算出 {自己!r}。"
    return True, "二维、三维、点到自身都算对了"


def CHECK_找邻居找得对(答案):
    if not hasattr(答案, "找邻居"):
        return False, "还没有定义「找邻居」函数"

    # ① 先来一个精心安排的数据集：欧氏距离和曼哈顿距离会给出**不同**的最近邻
    #    查询点 (0,0)；欧氏最近的是 (0.8, 0.05)，曼哈顿最近的是 (0.0, 0.83)
    训练集 = [
        ([0.6, 0.6], "甲"),        # 欧氏 0.849，曼哈顿 1.20
        ([0.8, 0.05], "乙"),       # 欧氏 0.802，曼哈顿 0.85   ← 欧氏里最近
        ([0.0, 0.83], "丙"),       # 欧氏 0.830，曼哈顿 0.83   ← 曼哈顿里最近
    ]
    try:
        得 = _正常邻居(答案.找邻居(训练集, [0.0, 0.0], 1))
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 找邻居(训练集, [0.0, 0.0], 1) 出错了：\n"
                       f"      {type(e).__name__}: {e}\n"
                       f"      参数顺序是 (训练集, 查询点, k)；\n"
                       f"      训练集里每项是 (点, 标签) 这样一个二元组。")
    if 得 is None:
        return False, ("找邻居 应该返回一个列表，里面是 (点, 标签) 二元组，\n"
                       "      现在返回的东西没法按这个形状读出来。")
    if len(得) != 1:
        return False, f"k=1 时应该返回 1 个邻居，你返回了 {len(得)} 个。"
    if 得[0][1] == "丙":
        return False, (
            "最近的那个邻居找错了 —— 你找到的是「丙」，正确答案是「乙」。\n"
            "      查询点是 (0.0, 0.0)，三个邻居的距离：\n"
            "          (0.6, 0.60)  欧氏 0.849   曼哈顿 1.200\n"
            "          (0.8, 0.05)  欧氏 0.802 ← 欧氏最近   曼哈顿 0.850\n"
            "          (0.0, 0.83)  欧氏 0.830   曼哈顿 0.830 ← 曼哈顿最近\n"
            "      你选的是曼哈顿距离最近的 —— 说明你的距离没开根号，\n"
            "      或者把 |差值| 直接相加了。这一课要的是**欧氏距离**。")
    if 得[0][1] != "乙":
        return False, f"最近邻应该是「乙」，你给的是「{得[0][1]}」。"

    # ② 随机数据集：按定义检查（比"对不对"更严格：顺序、不重不漏）
    for _ in range(2):
        训练集 = []
        已用 = set()
        while len(训练集) < 15:
            点 = (round(random.uniform(-10, 10), 3), round(random.uniform(-10, 10), 3))
            if 点 in 已用:
                continue
            已用.add(点)
            训练集.append(([点[0], 点[1]], f"类{len(训练集) % 3}"))
        查询点 = [random.uniform(-10, 10), random.uniform(-10, 10)]
        k = random.choice([1, 2, 3, 5])
        try:
            得 = _正常邻居(答案.找邻居(训练集, 查询点, k))
        except Exception as e:                        # noqa: BLE001
            return False, f"调用 找邻居 出错了：{type(e).__name__}: {e}"
        if 得 is None:
            return False, "找邻居 应该返回一个列表，里面是 (点, 标签) 二元组"
        if len(得) != k:
            return False, (f"k={k} 时应该返回 {k} 个邻居，你返回了 {len(得)} 个。\n"
                           f"      写法：把距离排序之后用 [:k] 切片。")
        距离 = [_参考距离(点, 查询点) for 点, _标签 in 得]
        if any(距离[i] > 距离[i + 1] + 1e-9 for i in range(len(距离) - 1)):
            return False, (f"邻居没有按距离从近到远排序（我按你返回的点重算的距离）：\n"
                           f"      {[round(d, 3) for d in 距离]}\n"
                           f"      要先排好序再返回 —— 顺序本身也是信息。")
        全部距离 = sorted(_参考距离(点, 查询点) for 点, _标签 in 训练集)
        if abs(距离[-1] - 全部距离[k - 1]) > 1e-6 or abs(距离[0] - 全部距离[0]) > 1e-6:
            return False, (
                "找出来的不是最近的 k 个。\n"
                f"      查询点 {[round(v, 3) for v in 查询点]}，k={k}\n"
                f"      你的邻居距离：{[round(d, 3) for d in 距离]}\n"
                f"      真正最近的 {k} 个距离：{[round(d, 3) for d in 全部距离[:k]]}\n"
                f"      检查：是不是排序的方向反了（从远到近）？或者切片写成了 [-k:]？")
    return True, "欧氏/曼哈顿的判别例子对了；随机数据集的邻居也对（最近的 k 个，排好序）"


def CHECK_核心_分类由距离决定(答案):
    """本课核心之一：随机造两簇点 —— 只有真的在算距离才判得对。"""
    if not hasattr(答案, "分类"):
        return False, "还没有定义「分类」函数"
    for _ in range(2):
        训练集, 心A, 心B = _造两簇()
        k = 3
        查A = [心A[0] + random.uniform(-0.3, 0.3), 心A[1] + random.uniform(-0.3, 0.3)]
        查B = [心B[0] + random.uniform(-0.3, 0.3), 心B[1] + random.uniform(-0.3, 0.3)]
        try:
            得A = 答案.分类(训练集, 查A, k)
            得B = 答案.分类(训练集, 查B, k)
        except Exception as e:                        # noqa: BLE001
            return False, (f"调用 分类(训练集, 查询点, {k}) 出错了：\n"
                           f"      {type(e).__name__}: {e}\n"
                           f"      参数顺序是 (训练集, 查询点, k)。")
        if 得A != 0 or 得B != 1:
            return False, (
                "分类结果不对。\n"
                f"      这组数据（随机生成的两簇，每次都不一样）里，\n"
                f"      簇 0 的中心在 {[round(v, 2) for v in 心A]}，"
                f"簇 1 的中心在 {[round(v, 2) for v in 心B]}，两簇离得很远。\n"
                f"      我拿一个几乎就在簇 0 中心的点去问，得到 {得A!r}（应该是 0）；\n"
                f"      拿簇 1 中心的点去问，得到 {得B!r}（应该是 1）。\n"
                f"      如果两次结果一样：分类没有在算距离，或者答案被写死了。\n"
                f"      如果结果反了：检查投票 —— 是**近的**邻居说了算，\n"
                f"      别把距离最小的排到了最后。")
    return True, "随机两组两簇数据，都把查询点判给了自己那一簇（k=3）"


def CHECK_核心_换个测试点答案就要跟着变(答案):
    """本课核心之二：同一份训练集，只换测试点，答案必须跟着变。

    这是"没有写死"最直接的证据 —— 不管你的函数内部怎么实现，
    换一个明显在另一边的点，标签就该反过来。
    """
    if not hasattr(答案, "分类"):
        return False, "还没有定义「分类」函数"
    训练集, 心A, 心B = _造两簇()
    k = 3
    结果 = []
    for 心 in (心A, 心B):
        点 = [心[0] + random.uniform(-0.2, 0.2), 心[1] + random.uniform(-0.2, 0.2)]
        try:
            结果.append(答案.分类(训练集, 点, k))
        except Exception as e:                        # noqa: BLE001
            return False, f"调用 分类 出错了：{type(e).__name__}: {e}"
    if 结果[0] == 结果[1]:
        return False, (
            f"两个测试点分别在两簇的正中间，你的模型都判成了 {结果[0]!r}。\n"
            f"      簇 0 中心 {[round(v, 2) for v in 心A]}，"
            f"簇 1 中心 {[round(v, 2) for v in 心B]}\n"
            f"      同一份训练集、只换了一个测试点，答案就该跟着变。\n"
            f"      两次一样说明它没在看测试点的位置 —— 距离算错了，或者写死了。")
    return True, (f"换成另一边的点，答案从 {结果[0]!r} 变成 {结果[1]!r} —— "
                  f"确实是距离在决定结果")


def CHECK_K的大小会影响结果(答案):
    """这一条不是防作弊，是让 K 的威力**可见**。

    邻居距离依次是 0.1(A)、0.2(B)、0.3(B)、0.4(B)、0.5(B)：
    K=1 只看最近的 → A；K=5 投票 → B。同一份数据，答案翻了。
    """
    if not hasattr(答案, "分类"):
        return False, "还没有定义「分类」函数"
    训练集 = [
        ([0.1, 0.0], "A"),
        ([0.2, 0.0], "B"),
        ([0.3, 0.0], "B"),
        ([0.4, 0.0], "B"),
        ([0.5, 0.0], "B"),
    ]
    查询点 = [0.0, 0.0]
    try:
        小 = 答案.分类(训练集, 查询点, 1)
        大 = 答案.分类(训练集, 查询点, 5)
    except Exception as e:                            # noqa: BLE001
        return False, f"调用 分类 出错了：{type(e).__name__}: {e}"
    if 小 == "A" and 大 == "B":
        return True, ("K=1 时听最近那个邻居的（A），K=5 时投票结果是 B"
                      " —— 只改了一个 K，答案就翻了")
    return False, (
        f"这组数据是特意排好的：查询点 (0,0) 的 5 个邻居距离依次是\n"
        f"      0.1(A)、0.2(B)、0.3(B)、0.4(B)、0.5(B)\n"
        f"      所以 K=1 应该返回 'A'（最近的邻居），你返回了 {小!r}；\n"
        f"      K=5 应该返回 'B'（B 有四票），你返回了 {大!r}。\n"
        f"      检查：K=1 时是不是返回了列表而不是标签？\n"
        f"           投票时是不是把标签当数字算了（标签是文字，只能数票）？\n"
        f"           K 个邻居是不是按距离从近到远取的？")


def CHECK_准确率算得对(答案):
    if not hasattr(答案, "准确率"):
        return False, "还没有定义「准确率」函数"
    # ① 手算得出来的一小例：两个测试点，一对一错
    训练集 = [([0.0, 0.0], 0), ([10.0, 10.0], 1)]
    测试集 = [([0.1, 0.1], 0), ([0.2, 0.2], 1)]      # 第二个必错（最近邻是标签 0）
    try:
        得 = 答案.准确率(训练集, 测试集, 1)
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 准确率(训练集, 测试集, 1) 出错了：{type(e).__name__}: {e}\n"
                       f"      参数顺序是 (训练集, 测试集, k)。")
    if not isinstance(得, (int, float)) or isinstance(得, bool):
        return False, f"准确率 应该返回一个数字（比例），现在是 {type(得).__name__}：{得!r}"
    if abs(得 - 0.5) > 1e-9:
        if abs(得 - 1) < 1e-9:
            return False, (
                "准确率算成了 1（全对）—— 但这两个测试点里有一个是**错的**。\n"
                "      训练集是 (0,0)→0 和 (10,10)→1，测试点是\n"
                "      (0.1,0.1)→0（对）和 (0.2,0.2)→1（错，最近的邻居标签是 0）。\n"
                "      正确结果是 1/2 = 0.5。检查：是不是把'判对'的计数和\n"
                "      '总数'搞混了，或者只统计了判对的那些？")
        return False, (f"准确率应该是 0.5（两个测试点一对一错），你算出 {得!r}。\n"
                       f"      写法：判对几个 ÷ 测试集总数。")
    # ② 随机数据：和"按定义算一遍"的结果对照
    #
    # ⚠ 这里**不能**用"两簇分得很开"的数据：那种数据准确率恒等于 1.0，
    #   学生写 `return 1.0` 也能过。所以故意用**有噪声的标签** ——
    #   同一条规律上掺 25% 的错标，准确率落在 0.7 附近，蒙不出来。
    验过 = 0
    for _ in range(4):
        训练集, 测试集 = [], []
        for i in range(40):
            点 = [random.uniform(-5, 5), random.uniform(-5, 5)]
            真标签 = 1 if 点[0] + 点[1] > 0 else 0
            if random.random() < 0.25:               # 25% 的标签是错的（噪声）
                真标签 = 1 - 真标签
            if i < 30:
                训练集.append((点, 真标签))
            else:
                测试集.append((点, 真标签))
        k = 3
        期望 = sum(1 for 点, 标签 in 测试集
                   if _参考分类(训练集, 点, k) == 标签) / len(测试集)
        if not (0.1 < 期望 < 0.95):
            continue          # 万一这组数据碰巧太好分/太乱，换下一组
        验过 += 1
        try:
            得 = 答案.准确率(训练集, 测试集, k)
        except Exception as e:                        # noqa: BLE001
            return False, f"调用 准确率 出错了：{type(e).__name__}: {e}"
        if not isinstance(得, (int, float)) or isinstance(得, bool):
            return False, f"准确率 应该返回一个数字（比例），现在是 {type(得).__name__}：{得!r}"
        if abs(得 - 期望) > 1e-9:
            return False, (
                f"随机数据集上的准确率算错了。\n"
                f"      期望 {期望:.4f}（10 个测试点里判对 {round(期望 * 10)} 个）\n"
                f"      实际 {得!r}\n"
                f"      这组数据的标签里掺了 25% 的噪声，所以准确率不可能是 1.0 ——\n"
                f"      写死一个数（或者只数判对的、忘了除以总数）都会露馅。\n"
                f"      （准确率是靠调用你的 分类 算出来的：如果 分类 有问题，\n"
                f"        这里也会跟着对不上。）")
        if 验过 >= 2:
            break
    if 验过 == 0:
        return True, "手算的小例子是 0.5（随机那几组碰巧不适用，跳过了）"
    return True, f"手算的小例子是 0.5；{验过} 组随机噪声数据上也和按定义算的一致"
