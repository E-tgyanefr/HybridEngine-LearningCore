# 第 01 课：让程序"学"一条直线（线性回归）

# 要做：
#   1. 写一个函数 预测(直线, x)
#      直线是一个 (斜率, 截距) 的元组，函数返回 斜率 * x + 截距。
#   2. 写一个函数 误差平方和(xs, ys, 直线)
#      对每个点算「预测值 - 真实值」，求平方，再全部加起来。
#   3. 写一个函数 拟合(xs, ys)
#      用**最小二乘法**算出最合适的一条直线，返回 (斜率, 截距)。
#
#   ⚠ 检查会**换一批随机数据**再来问你的 拟合 ——
#     所以不能把某个答案写死（比如直接 return (2.0, 1.0)），
#     必须真的从 xs、ys 里算出来。

# ─────────────────────────────────────────────────────
#  一、发生了什么：什么叫"让程序学"
# ─────────────────────────────────────────────────────
#
# 先看一件事：假设你手上有几个点
#
#     x:  1   2   3   4   5
#     y:  3   5   7   9   11
#
# 你一眼就看出来：y = 2x + 1。你是怎么看出来的？
# 你脑子里做了一件很朴素的事：**找一条线，让它离所有点都最近**。
#
# "学习"在 AI 里就是这个意思，一点都不玄：
#
#     ① 先定一个**模型**（这里是"一条直线"，由斜率和截距两个数决定）
#     ② 再定一个**打分方式**（这条线有多差 → 叫"误差"或"损失"）
#     ③ 然后**调整参数**，让这个分数变小
#
# 第 ③ 步做完，程序就"学会"了。整门 AI 课，后面每一课都是这三步，
# 只是模型越来越复杂、调整的方法越来越聪明。
#
# ⚠ 关键在这句话：**模型自己不会学习，是你写的代码在调整参数。**
#    "学习"= 在数据上把误差调小。记住这句，这一课就没白上。

# ─────────────────────────────────────────────────────
#  二、你写的是什么：三个函数，各管一件事
# ─────────────────────────────────────────────────────
#
#   预测(直线, x)          → 拿一条线，算它在 x 处的 y。这是**用**模型。
#   误差平方和(xs, ys, 直线) → 给这条线打个分，越小越好。这是**评价**。
#   拟合(xs, ys)           → 直接算出最好的那条线。这是**学习**。
#
# 三个函数拆开写，是因为它们以后各自都会被换掉：
# 换个模型只改 预测，换个打分方式只改 误差平方和，换个算法只改 拟合。
# 真正做 AI 的代码也是这么分层的。

# ─────────────────────────────────────────────────────
#  三、应该怎么写
# ─────────────────────────────────────────────────────
#
# ① 误差：为什么是「预测 - 真实」，为什么要求平方
#
#    最自然的想法是"把每个点的偏差加起来"。但偏差有正有负：
#        线在上面 → 预测 > 真实 → 正
#        线在下面 → 预测 < 真实 → 负
#    直接相加，正负会**互相抵消**：
#        +10 和 -10 加起来 = 0 —— 明明错得离谱，分数却是满分。
#    （检查里专门有一条就是抓这个：两个点误差分别是 -1 和 -3，正确答案是 10。）
#
#    所以要么取绝对值，要么求平方。这里用平方，有三个理由：
#      · 平方后一定是正数，不会抵消
#      · 平方会**放大**大误差：错 10 的惩罚是错 1 的 100 倍
#        → 模型会拼命避免"错得特别离谱"，这正是我们想要的
#      · 平方是光滑的（可以求导），下一课"梯度下降"要用到这个性质
#        绝对值在 0 那里有个尖角，导数不存在，不好用
#
# ② 拟合：怎么直接算出那条最好的线
#
#    先讲直觉，别看公式。
#
#    **第一条直觉：最好的线一定穿过"平均点" (x̄, ȳ)。**
#      把线整体上下平移，平移量直接加到每个点的误差上。
#      往哪个方向平移都会让总误差变大 —— 所以最优点在"不多不少"的位置，
#      也就是线的中心正好落在数据中心。
#
#    **第二条直觉：斜率 = 两个东西"一起变"的程度 ÷ x 自己"变"的程度。**
#
#      把每个点减去平均值，得到它"偏离中心多少"：dx = x - x̄，dy = y - ȳ。
#
#        · 如果 dx 和 dy **同号**（x 偏大时 y 也偏大）→ 这是上升趋势
#          它们的乘积 dx·dy 是正的，加起来就是个大正数 → 斜率大
#        · 如果 dx 和 dy **反号** → 下降趋势，乘积是负的 → 斜率为负
#        · 如果两者没关系（x 大 x 小，y 都乱跳）→ 乘积正负抵消，接近 0
#
#      所以  分子 = Σ(dx · dy)   就是"x 和 y 一起变的程度"
#            分母 = Σ(dx · dx)  就是"x 自己变的程度"
#
#      斜率 k = 分子 / 分母。除一下是为了**去掉单位**：
#      不管你把 x 用米还是厘米量，这个比值算出来都一样。
#
#      截距再用第一条直觉倒推：线要穿过平均点，所以
#            b = ȳ - k · x̄
#
#    写成代码（dx、dy 用循环算，和上面一模一样）：
#
#        n = len(xs)
#        平均x = sum(xs) / n
#        平均y = sum(ys) / n
#        分子 = 0.0
#        分母 = 0.0
#        for x, y in zip(xs, ys):
#            dx = x - 平均x
#            dy = y - 平均y
#            分子 += dx * dy
#            分母 += dx * dx
#        k = 分子 / 分母
#        b = 平均y - k * 平均x
#
#    ⚠ 别背这个公式，记两条直觉：**穿过平均点**、**斜率是"一起变 ÷ 自己变"**。
#      忘掉公式时，这两句话能让你重新推出来。
#
# ③ 为什么检查要"换一批数据"
#
#    因为 AI 课最容易的作弊方式就是写死答案：
#        def 拟合(xs, ys): return (2.0, 1.0)
#    它对某一组数据完全正确 —— 但那不是学习，那是抄答案。
#    所以检查会用**随机生成的数据**再问你一次：
#    真的在算的会跟着变，写死的不会。

# ─────────────────────────────────────────────────────
#  四、顺便记住什么
# ─────────────────────────────────────────────────────
#  · 这一课叫"线性回归"。"回归"就是"用一条线去拟合数据"，
#    名字来自一百多年前高尔顿研究父子身高，和"回归"这个词的字面意思无关。
#  · **一个离群点能毁掉整条线**：因为误差是平方的，一个偏得离谱的点
#    贡献的误差可能是其他所有点加起来的好几倍。真实项目里，
#    清洗数据（把明显错的数据挑出来）常常比换模型更管用。
#  · 拟合得好 ≠ 预测得准。数据本身就不成直线时，
#    最小二乘照样能给你一条线 —— 它不会告诉你"这数据不该用直线"。
#  · 只用标准库就够了：这一课从头到尾没 import 任何第三方库。

