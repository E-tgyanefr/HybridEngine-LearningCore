"""第 05 课的参考答案：温室监测器（把前四课拼起来）。

════ 这一课唯一的新东西是"判断力" ════

零件前面四课都学过了：读传感器、判断、记录、循环。
这一课要练的是**什么时候不该响**：

    报警器的价值 = 它响的时候你真的会去看。

一个"永远报警"的监测器比不装还差 —— 三天之后人就把它当背景音了，
真正出事那一次照样没人去看，而它还给了你一种"有人在看着"的错觉。

所以三个函数里，最值得琢磨的是 判断报警 的最后那一句 return ""。
"""


def 判断报警(温度, 上限=30.0, 下限=10.0):
    """三个出口：太热 / 太冷 / 正常。

    温室和一般的"过热报警器"不一样：**夜里会冷**。
    冻害和热害一样能把一棚作物毁掉，所以两头都要管。

    注意顺序：先判上限、再判下限，**最后**才是"没超就正常"。
    把 正常 这一句写在前面会让后面两个分支永远不执行。
    """
    if 温度 > 上限:
        return f"太热了，{温度}°C，上限 {上限}°C"
    if 温度 < 下限:
        return f"太冷了，{温度}°C，下限 {下限}°C"
    # ← 这一句是"安静"的来源：正常就该不吭声。
    #   少了它，函数会返回 None，逻辑上算"没报警"，
    #   但调用方（记录、上报、界面）拿到 None 会很难处理 ——
    #   明确地返回空字符串，是一种契约。
    return ""


def 监测一次(派, 路径, 上限=30.0, 下限=10.0):
    """跑一轮完整流程：读 → 判断 → 报警 → 记录 → 时间前进。

    一轮 = 一次"看一眼温室"。这个函数就是整套系统的**一个心跳**，
    第 04 课的循环只是让这个心跳重复下去。
    """
    # ① 读
    温度 = 派.温度.读()

    # ② 判断
    报警词 = 判断报警(温度, 上限, 下限)

    # ③ 动作：报警就点亮报警灯，正常就灭掉。
    #    ⚠ else 里的 led.灭() 不能省 —— 
    #      程序结束不会自动复位引脚，报警解除了灯还亮着，
    #      人就以为还在出事。报警器一旦"喊错"，人就会开始无视它。
    led = 派.接LED(17, 名字="报警灯")
    if 报警词:
        led.亮()
    else:
        led.灭()

    # ④ 记录：**无条件**，每一轮都记。
    #    报警时在行尾多加一个标记，方便以后筛出"出过事的时刻"——
    #    但正常的数据一条都不能少：出事之前温度怎么爬上去的，
    #    才是分析时最有用的部分。
    标记 = "报警" if 报警词 else "正常"
    派.写文件(路径, f"{派.时间:.1f},{温度},{标记}\n")

    # ⑤ 时间前进（相当于 time.sleep）。真实项目里多久一次是设计决定：
    #    温室温度一分钟一次足够。写太勤既没用又磨 SD 卡。
    派.时间推进(1.0)

    return 报警词


def 一直监测(派, 轮数, 路径, 上限=30.0, 下限=10.0):
    """重复 监测一次 轮数 次。

    ⚠ 真实上线时这里是 while True（永不结束），再套一层 systemd 服务
      让它开机自启、崩了自动重启。作业里用 轮数 控制，
      检查才验得了你到底跑了几轮。
    """
    led = 派.接LED(17, 名字="报警灯")
    报警次数 = 0

    for 第几轮 in range(轮数):
        if 监测一次(派, 路径, 上限, 下限):
            报警次数 += 1

    # 收尾：跑完把灯关掉。
    # 这一句在真实项目里对应的是"程序被停掉时的清理"——
    # 第 04 课那个 finally 里的 GPIO.清理()。
    led.灭()

    return {"轮数": 轮数, "报警次数": 报警次数}


