"""第 03 课的参考答案：把数据记下来（追加，不是覆盖）。

════ 这一课的关键只有一件事 ════

**每一次都往文件末尾追加一行**，而不是把整个文件重写一遍。

    覆盖 → 文件里永远只有最后一条。跑 24 小时得到 1 行数据，
           温度什么时候开始升高的？不知道 —— 中间全被抹掉了。
    追加 → 每一条都在，按时间排好。跑得越久，数据越值钱。

模拟器里 派.写文件() 本身就是这样 —— 等价于真实的 open(路径, "a")。
真实代码里最常见的错法是把 open(路径, "w") 写在循环**里面**，
那样每转一圈就清空一次文件，和追加正好相反。
"""

# ⚠ `list[tuple[float, float]]` 这种写法**在 3.9 上会运行时崩**
#   （`TypeError: 'type' object is not subscriptable`）。
#   加了下面这行，注解变成字符串、不执行，3.9 也能跑。
#   项目自己的基线是 3.9（见 _build/build_src.py 的版本闸门），原来这个文件漏了。
from __future__ import annotations

import re


def 记录一次(派, 传感器, 路径):
    # ① 读数从**参数**里来，不是写死 派.温度。
    #    这样同一个函数既能记温度，也能记光线、湿度、土壤 —— 不用改一行代码。
    #    第 05 课要同时记好几样东西，到时候就看出好处了。
    读数 = 传感器.读()

    # ② 一行一条：时间戳 + 读数，逗号分隔（这就是最简单的 CSV）。
    #    为什么必须带时间：一条没有时间的温度记录 = 一个孤零零的数字，
    #    没法画曲线、算平均、找规律。时间才是让数据变成信息的东西。
    #    行尾的 \n 不能忘 —— 忘了的话所有记录会挤成一行。
    这一条 = f"{派.时间:.1f},{读数}\n"

    # ③ 写文件（模拟器里是追加语义）。
    #    真实代码对应的是：
    #        打开 = open(路径, "a", encoding="utf-8")   # 在循环外面开一次
    #        打开.write(这一条)
    #        # 循环结束后 打开.close()
    #    ⚠ "a" 绝对不能写成 "w" —— 那是覆盖，历史数据当场清零。
    派.写文件(路径, 这一条)

    # ④ 让时间往前走一点（相当于 time.sleep(1)）。
    #    不推进时间的话，每条记录的时间戳都是 0.0 —— 数据就没法看了。
    #    真实项目里"多久记一次"是个设计决定：温室温度一分钟一次就够，
    #    振动监测可能要每秒几千次。而且写得越勤，SD 卡磨损越快（见下）。
    派.时间推进(1.0)

    # 返回这一条，方便调用它的人（比如日志）直接用。
    return 这一条


def 记了几条(派, 路径) -> int:
    """数一数文件里现在有几条记录。

    这个小工具是给自己**验证**用的：写完一个记录程序，
    最该做的第一件事就是把文件读回来看一眼 —— 数据对不对、
    格式对不对、条数对不对。检查也是这么做的。
    """
    return len([l for l in 派.读文件(路径).splitlines() if l.strip()])


def 读回来(派, 路径) -> list[tuple[float, float]]:
    """把记录读回成 [(时间, 读数), ...]。

    记录写下去只是第一步 —— 数据要能被**读回来用**才算有价值。
    真实项目里这一步是 pandas / 数据库的活，这里手写几行看得更清楚。
    """
    出 = []
    for 行 in 派.读文件(路径).splitlines():
        if not 行.strip():
            continue
        数 = re.findall(r"-?\d+(?:\.\d+)?", 行)
        if len(数) >= 2:
            出.append((float(数[0]), float(数[-1])))
    return 出


