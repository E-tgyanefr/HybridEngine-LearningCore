"""第 02 课的参考答案：读传感器 → 做判断。

════ 这一课的"标准答案"为什么长这样 ════

整个函数里没有一处"结论"，只有由读数算出来的结果：

    温度 = 派.温度.读()      ← 先拿到事实
    if 温度 > 上限:          ← 再根据事实做决定
        return 报警的话
    return ""               ← 正常就该安静

如果把这两行换成一句无条件的 return "太热了"，代码照样能跑、
输出照样好看 —— 但它没有读任何东西。检查抓的就是这种"假实现"。
"""


def 判断报警(派, 上限=30.0, led=None):
    # ① 先读。这一步是整节课的核心：结论必须建立在读数上。
    温度 = 派.温度.读()

    # ② 再判断。阈值用**参数**（上限），不要写死 30 ——
    #    真实项目里阈值是会变的：夏天 30、冬天 20，不同作物还不一样。
    超了 = 温度 > 上限

    # ③ （可选）报警时点亮报警灯，让"有人看得见"。
    #    正常时记得灭掉 —— 报警解除了灯还亮着，人就会以为还在出事。
    #    第 01 课的规矩在这里仍然有效：程序结束不会自动复位引脚。
    if led is not None:
        if 超了:
            led.亮()
        else:
            led.灭()

    # ④ 返回一句话（报警）或者空字符串（正常）。
    #    返回文字而不是直接 print，是因为调用它的程序
    #    （第 05 课）要拿这句话去点灯、去写日志、去联网 ——
    #    print 出来的东西，别的程序拿不到。
    if 超了:
        # 把读数写进消息里：出了问题要能一眼看出"当时是多少度"。
        return f"太热了，温度 {温度}°C（上限 {上限}°C）"
    return ""


