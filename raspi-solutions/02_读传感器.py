if __name__ == "__main__":
    from learncode.raspi import 树莓派

    派 = 树莓派()
    派.加传感器("温度", "°C", (0.0, 50.0), 22.0)
    led = 派.接LED(17, 名字="报警灯")

    for 读数 in (22.0, 35.5, 18.0, 42.0):
        派.温度.设为(读数)
        结果 = 判断报警(派, 30.0, led)
        print(f"{读数:5.1f}°C → {结果 or '（正常，不报警）':<32} 灯：{led.状态()}")

