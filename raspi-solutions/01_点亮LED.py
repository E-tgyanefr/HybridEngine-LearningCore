def 闪(派, led, 次数=3):
    """闪 `次数` 下，每一下是「亮 → 等 → 灭 → 等」。

    ⚠⚠ 2026-10-14 修：**这份参考答案原来是过时的** ——
      它写的是 `def 闪一下(派):`（**一个参数**，而且在函数里自己 `派.接LED(17)`），
      而这一课的正文（第 12 行）要求的是：

          写一个函数 闪(派, led, 次数=3)，让它闪 次数 下

      检查也是按三参调用：`函数(派, led, 次数)` ——
      于是**参考答案自己过不了自己的检查**（4 条全红）：
          × 函数存在        × 真的动了LED
          × 次数真的起作用   × 用了循环

      ⇒ 症状对学员是致命的：**照着参考答案抄，一定过不了**。
      ⚠ 而这个 bug 一直没被发现，是因为"参考答案全过"这条判据
        （`_build/_verify_reference_all.py`）**2026-10-14 才第一次跑**。

    ⚠ 为什么 `次数` 要当**参数**：想闪几下是**会变的** ——
      写死 `range(3)` 的函数，`次数=1` 和 `次数=3` 跑出来一模一样，
      检查专门验这一条（"次数真的起作用"）。
    """
    for _ in range(次数):
        led.亮()          # 亮
        派.睡(0.5)        # 等一下（单位秒）
        led.灭()          # 灭
        派.睡(0.5)        # 再等一下

    # ⚠ 循环最后一次已经是 `led.灭()`，所以最后状态是「灭」——
    #   这正是检查要的（第 23-24 行：程序结束不复位引脚，
    #   灯留在亮着会让人一直以为还在出事）。
    #   若哪天把循环体改成「先灭后亮」，这里就必须补一句 `led.灭()`。
