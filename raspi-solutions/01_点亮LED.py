def 闪一下(派):
    # 用 接LED 一步配好引脚（相当于 setup + 拿到一个顺手的小对象）
    led = 派.接LED(17)

    led.亮()          # 先亮
    # 真实程序里这里通常会有 time.sleep(0.5) 让人看得见。
    # 模拟器不用睡 —— 检查看的是"亮过、然后灭了"这个顺序。
    led.灭()          # 再灭

    # ⚠ 这一步不能省：**程序结束不会自动复位引脚**。
    #   真实树莓派上，你的程序退出后引脚会保持最后的状态 ——
    #   不关的话 LED 会一直亮着。
