"""第 04 课的参考答案：长时间监测 —— 树莓派上没有 loop()，要自己写。

════ 这一课真正要记住的一句话 ════

    单片机：你写 loop()，框架**替你**反复调用，永远在转。
    树莓派：你的程序是一个**普通进程**，想一直监测就**自己写循环**。

这个差别会咬人两次：
  · 你以为"读温度 → 报警"装好了，其实程序早就退出了，什么都不会再发生；
  · 反过来，你写的每一段代码都要**自己负责什么时候结束**
    （这就是为什么作业里要有 轮数 这个参数）。

真实上线时，这个函数会被套上一层 systemd 服务：开机自启、崩了自动重启、
日志交给 journalctl —— 那才是"装进温室"的样子。这一课写的就是它的核心循环。
"""


def 循环监测(派, 轮数, 路径, 上限=30.0):
    """跑 轮数 轮：读一次 → 判断 → 记录 → 时间前进。

    参数 轮数 是真实项目里 while True 的替身。
    真实设备上那个循环是**永远不停**的（跑到断电或者被停掉为止），
    但在模拟器里必须能说清"转多少圈就收工"，检查才能验你到底转了几圈。

    ⚠ 别把 轮数 换成 while True 交作业 —— 检查会一直等它，命令会卡死。
      真实的树莓派程序就是这样：它永远不会自己结束。
    """
    led = 派.接LED(17, 名字="报警灯")

    读取次数 = 0
    报警次数 = 0

    # ── 循环本体：里面的事**每一轮**都要做一遍 ──
    # ⚠ 缩进是这一课最大的坑：只要有一行没缩进来，
    #   它就只执行一次，而代码看起来完全正常。
    for 第几轮 in range(轮数):
        # ① 读（这就是"看一眼"）
        温度 = 派.温度.读()
        读取次数 += 1

        # ② 判断 + 动作
        超了 = 温度 > 上限
        if 超了:
            报警次数 += 1
            led.亮()          # 报警要让人看得见
        else:
            led.灭()          # 正常时把它关掉：程序结束不会自动复位引脚

        # ③ 记录：**无条件**记，不管报没报警。
        #    只记报警的那几条 = 你只知道"什么时候出过事"，
        #    不知道"出事之前温度是怎么爬上去的" —— 后者才是数据的价值。
        派.写文件(路径, f"{派.时间:.1f},{温度}\n")

        # ④ 让时间走一点。少了这一句，程序会全速空转：
        #    一秒读几万次、日志爆掉、SD 卡很快写坏（第 03 课那个坑）。
        #    真实代码里这里是 time.sleep(60) —— 
        #    和单片机的 delay 不同，sleep 期间系统还在跑别的东西。
        派.时间推进(1.0)

    # ── return 必须在循环**外面** ──
    # 写在循环里 = 第一轮就收工，文件里只会有一条记录。
    # 这就是这一课要抓的"只处理一轮"。
    return {"读取次数": 读取次数, "报警次数": 报警次数}


def 一直跑(派, 路径, 上限=30.0):
    """真实项目里的形态：一直跑，直到有人把它停下来（Ctrl+C / systemd stop）。

    ⚠ 这个函数**不会自己结束** —— 别在作业里调用它，检查会一直等。
      写在这里是为了让你看清"真实上线"和"课后作业"差在哪一行：
      就是 range(轮数) 换成了 while True。
    """
    led = 派.接LED(17, 名字="报警灯")
    try:
        while True:
            温度 = 派.温度.读()
            if 温度 > 上限:
                led.亮()
            else:
                led.灭()
            派.写文件(路径, f"{派.时间:.1f},{温度}\n")
            派.时间推进(1.0)
    except KeyboardInterrupt:
        # 有人按了 Ctrl+C（或者 systemd 发来停止信号）。
        # 真实的长跑程序**必须**接住它，才有机会收尾。
        pass
    finally:
        # 收尾：引脚复位 + 数据落盘。
        # 第 01 课那条"程序结束不会自动复位引脚"，在这里从"知识点"
        # 变成了"必须处理的事故" —— 灯一直亮着，人就以为还在出事。
        led.灭()
        派.GPIO.清理()
        print("已收尾：引脚复位、数据已写盘。")
    return {"读取次数": -1, "报警次数": -1}


