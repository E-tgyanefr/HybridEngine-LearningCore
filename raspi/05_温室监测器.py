#  发生了什么：零件都有了，缺的是"装起来"
# ─────────────────────────────────────────────────────
#
#  第 01 课：会点灯（输出）
#  第 02 课：会读传感器、会判断（输入 + 决策）
#  第 03 课：会把数据留下来（记录）
#  第 04 课：会让程序一直跑（循环）
#
# 这一课不加新知识 —— 只是把它们拼成一个**别人能用的东西**。
# 而"拼起来"这件事本身就是一门手艺，而且是最接近真实工作的一部分：
#
#     真实项目里，难的从来不是某一行代码，是"这些部分怎么接上"。
#
# 一个具体的例子：第 02 课的判断函数只要返回一句话就行了；
# 但在温室监测器里，那句话还得**同时**变成"灯亮起来"和"文件里的一条记录"。
# 一份判断，三个出口 —— 这就是拼装。
#
# ─────────────────────────────────────────────────────
#  你写的是什么：一个"没有 UI 的产品"
# ─────────────────────────────────────────────────────
#
# 温室监测器装好之后是什么样子？
#   没有人看着它、没有屏幕、没有手机 App —— 它就挂在那儿，
#   每分钟读一次温度，正常的时候一声不响，出事的时候灯亮起来、
#   文件里留下一行证据。你去收菜的时候才知道"上周三下午热过"。
#
# 这就是这一课真正的产出：**一个安静的、会自己盯着的程序。**
#
# 而"安静"是它最重要也最难做对的品质 —— 见下面那条。
#
# ─────────────────────────────────────────────────────
#  应该怎么写：把四课的东西对号入座
# ─────────────────────────────────────────────────────
#
# 这一课不给步骤，但可以告诉你每一块对应前面哪一课：
#
#     读温度        →  第 02 课：传感器.读()
#     上下限判断    →  第 02 课：if / else（这一课是两个条件）
#     点亮/熄灭灯   →  第 01 课：led.亮() / led.灭()
#     记进文件      →  第 03 课：派.写文件()（**追加**，一条一行）
#     时间推进      →  第 03 课：派.时间推进()
#     循环 轮数 次  →  第 04 课：for ... in range(轮数)
#
# 三个容易写错的地方，检查全都盯着：
#
#   ① **正常的时候也要记录。**
#      只记报警的那几条 = 你只知道"什么时候出过事"，
#      不知道"出事之前温度是怎么爬上去的"——
#      而后者才是数据记录的全部价值。
#      记录是**无条件**的，报警只是记录里的一个额外标记。
#
#   ② **正常的时候要把灯灭掉。**
#      第 01 课的规矩在这一课变成硬要求：程序结束不复位引脚。
#      报警解除了灯还亮着，人就以为还在出事 —— 报警器一旦"喊错"，
#      人就会开始无视它，那它装了也白装。
#
#   ③ **上下限都要判，而且不能判反。**
#      超过上限是"热"，低于下限是"冷"。
#      两个条件写成一个 if / elif 最清楚。
#
# ─────────────────────────────────────────────────────
#  顺便记住什么：为什么"永远报警"是最坏的实现
# ─────────────────────────────────────────────────────
#
# 这一课专门有一条检查是"正常时不许报警"，值得说清为什么：
#
#   报警器的价值 **= 它响的时候你真的会去看**。
#   如果它一天响 200 次，第三天你就会把它的声音当背景音 ——
#   真正出事的那一次，你照样不会去看。
#   所以一个"永远报警"的监测器，比不装还差：它花了电、占了位置、
#   而且给了你一种"有人在看着"的**错觉**。
#
# 真实项目里这件事有一个专门的名字，叫**误报（false positive）**，
# 是监测系统最花心思去压的东西。常见的做法：
#
#   · **连续 N 次超标才算**（防一次噪声读数就报警）
#   · **迟滞**：超过 30 报警，但要掉到 28 以下才解除 ——
#     否则温度在阈值附近抖动时，报警会疯狂开关
#   · 不同时段用不同阈值（夜里本来就该冷）
#
# 这些现在都不用做，但你要知道：**"什么时候不该响"和"什么时候该响"
# 一样重要**。这是这一课真正要教给你的判断力。
#
# ─────────────────────────────────────────────────────
#  ⚠ 模拟器验证不了电路（拼装完成的这一刻特别要记住）
# ─────────────────────────────────────────────────────
#
# 五课的代码都通过 ≠ 这个东西真的能挂进温室。模拟器只跑**程序逻辑**，看不见：
#
#   · **限流电阻** —— 报警灯没有 220Ω~1kΩ 限流电阻，早晚烧掉。
#     温室里的设备要长期通电，这一条比在桌面上试的时候更重要。
#   · **接线位置** —— 温室里潮湿、有震动、线要走好几米：
#     杜邦线松、接头氧化、线太长被干扰 —— 真实的长期项目里，
#     接线故障比代码 bug 多得多。
#   · **I2C 地址冲突** —— 温室监测器通常会挂好几样东西
#     （温度、湿度、光照、土壤）。这些都走 I2C 的时候，
#     地址撞了就会读数错乱：你会看到"土壤湿度 = 38.5°C"这种荒唐数据。
#     接之前先 `i2cdetect -y 1` 扫一遍，把每个设备的地址记在本子上。
#   · **传感器型号差异** —— 同样是"温度传感器"，DS18B20 防水探头能埋在土里，
#     DHT11 只能测空气、精度 ±2°C 而且不能长期在潮湿环境里 ——
#     装到温室里两周就坏了。**选型和代码一样是工程的一部分。**
#   · 还有：防水、供电（温室里拉电要小心）、夏天箱内温度可能比外面高 20°C，
#     树莓派自己会过热降频 —— 那些都是"跑一个夏天"才会暴露的问题。
