# 要做：
#   把前四课学到的东西拼成一个**能用的东西**：一个温室监测器。
#   下面是它要有的**功能清单** —— 怎么实现是你的事，这一课不给步骤。
#
#   ── 功能清单 ────────────────────────────────────────────
#
#   ① 判断报警(温度, 上限=30.0, 下限=10.0)  →  返回一句话
#
#        · 温度 **超过 上限**      → 返回一句非空文字（例如 "太热了，38.5°C"）
#        · 温度 **低于 下限**      → 返回一句非空文字（例如 "太冷了，6.2°C"）
#        · 在上下限之间            → 返回 ""      （正常，不报警）
#
#      ⚠ 温室和一般的报警器不一样：**太热和太冷都要管**。
#        温室夜里会冷、中午会热，两头都能把作物弄死。
#
#   ② 监测一次(派, 路径, 上限=30.0, 下限=10.0)  →  跑一轮完整流程
#
#        · 读一次温度
#        · 判断要不要报警
#        · 报警 → 点亮报警灯；正常 → 把灯灭掉
#        · **每一次都要**把这一轮的读数和时间记进 路径 这个文件（一条一行）
#        · 让时间往前走一点
#
#   ③ 一直监测(派, 轮数, 路径, 上限=30.0, 下限=10.0)  →  重复 ② 轮数 次
#
#   ── 检查会怎么验你 ─────────────────────────────────────
#
#     · 读数正常时**不该**报警（这是最容易糊弄过去的一条：
#       "永远报警"的假实现看起来功能齐全，其实等于没装）
#     · 超上限要报警、低于下限也要报警
#     · 每跑一轮就留一条记录，跑几轮就有几条
#     · 报警灯要跟着读数亮/灭
#
#   ⚠ 别在答案里写 while True。"一直监测"靠 轮数 这个参数控制，
#     否则检查会一直等你的程序，命令直接卡死。

