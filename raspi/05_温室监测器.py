    函数, 错误 = _取监测一次(答案)
    if 函数 is None:
        return False, 错误

    派, led = _新派(22.0)
    for 值 in (22.0, 35.0, 22.0, 5.0):
        派.温度.设为(值)
        错误 = _调监测一次(函数, 派)
        if 错误:
            return False, 错误

    内容 = 派.读文件(路径)
    行数 = _行数(内容)

    if 行数 == 4:
        return True, f"跑了 4 轮 → 文件里正好 4 条记录：{内容.strip()!r}"

    if 行数 == 1:
        return False, (
            "跑了 4 轮（其中两轮正常、一轮太热、一轮太冷），文件里却只有 **1 条**记录。\n"
            f"      文件内容：\n          {内容.strip()!r}\n"
            "      记录必须是**每一次都写**、而且**追加**（不能覆盖）：\n"
            "        · 覆盖着写 → 只剩最后一条\n"
            "        · 只在报警时才记 → 只剩报警那两条，"
            "出事之前温度怎么爬上去的就看不到了\n"
            "      记录是**无条件**的，报警只是记录里多一个标记。\n"
            "      ⚠ 顺便记住：真实项目里写盘太勤会磨坏 SD 卡（第 03 课讲过）——\n"
            "        真要长期跑，通常先在内存里攒几条再一次性写下去。")
    if 行数 < 4:
        return False, (f"跑了 4 轮，文件里只有 {行数} 条记录 —— 少了。\n"
                       f"      文件内容：\n          {内容.strip()!r}\n"
                       "      每一轮都要记一条，**包括正常的那几轮**。\n"
                       "      如果只有报警时才记，正常的时候就没有数据 ——\n"
                       "      那你就不知道出事之前温度是怎么变化的。")
