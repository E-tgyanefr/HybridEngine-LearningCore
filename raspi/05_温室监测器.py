def CHECK_阈值能调(答案):
    """上限下限必须是参数，不能写死 30 / 10。

    怎么验：读数 28°C，上下限分别给 (35, 25) —— 28 在区间里，不报警；
    再给 (25, 5) —— 28 超过了 25，该报警。两次必须不同。
    """
    函数, 错误 = _取报警判断(答案)
    if 函数 is None:
        return False, 错误

    宽, 错误 = _叫判断(函数, 28.0, 35.0, 25.0)
    if 错误:
        return False, 错误
    严, 错误 = _叫判断(函数, 28.0, 25.0, 5.0)
    if 错误:
        return False, 错误

    if 宽 == 严:
        return False, (
            "读数都是 28°C：上下限给 (35, 25) 时返回「" + 宽 + "」，\n"
            "      给 (25, 5) 时也返回「" + 严 + "」—— 两次一样。\n"
            "      **上下限参数没有起作用**，说明函数里写死了 30 和 10。\n"
            "      为什么必须做成参数：不同作物、不同季节、不同棚，阈值都不一样\n"
            "      （草莓和番茄不一样，白天和夜里也不一样）。\n"
            "      真实项目里阈值通常是配置文件里的一行，改它不用动代码。\n"
            "      改法：比较的时候用参数：\n"
            "          if 温度 > 上限: ...\n"
            "          elif 温度 < 下限: ...")
    if 宽 != "":
        return False, (
            f"读数 28°C、上下限 (35, 25)：28 在 25~35 之间，**不该**报警，\n"
            f"      但返回了「{宽}」。\n"
            "      检查一下区间判断：温度要同时满足 温度 <= 上限 和 温度 >= 下限 才算正常。")

    return True, "28°C 配 (35, 25) 不报警、配 (25, 5) 就报警 —— 阈值真的在起作用"


