# 第 02 课：读传感器做判断 —— 让程序跟着读数走

# 要做：
#   写一个函数 判断报警(派, 上限=30.0)，做这三件事：
#
#     1. 读一次温度：    温度 = 派.温度.读()      ← 读数是个小数，例如 22.5
#     2. 拿它和上限比：  温度 > 上限 就该报警
#     3. 返回一句话：
#          报警（超了上限）→ 返回一句**非空**的文字，例如 "太热了，温度 38.5°C"
#          没超（正常）    → 返回 ""  （空字符串 = 不报警）
#
#   上限要**由参数传进来**，所以第二个参数要写默认值 上限=30.0。
#   这样同一个函数既能用 30 当阈值，也能用 28 当阈值，不用改代码。
#
#   检查会这样验你：**同一个函数，在不同的读数下各调一次。**
#   读数 42°C 和读数 22°C 必须给出**不一样**的结果。
#   如果两次结果一样，就说明你的函数没在读传感器 ——
#   而是把结论写死了（比如无脑 return "太热了"），那这个传感器就是白接的。
#   这是这一课唯一真正要考的东西。
#
#   加分项（不影响通过，但真实项目都这么做）：
#   给它加第三个参数 led=None，如果传了 LED，报警时顺便把它点亮。
#   报警灯亮着，人才知道出事了 —— 第 05 课会正式用到。

# ─────────────────────────────────────────────────────
#  发生了什么：从"固定动作"到"看情况做决定"
# ─────────────────────────────────────────────────────
#
# 第 01 课的程序是一段**固定动作**：亮、灭、结束。
# 你运行一百次，它做的一百次都一模一样 —— 它跟外面的世界没有任何关系。
#
# 这一课开始不一样了：
#
#     第 01 课：  程序 → 改变世界（点灯）
#     第 02 课：  世界 → 程序 → 改变世界（读温度 → 判断 → 报警）
#
# 多出来的那一步「读」，就是"玩具"和"真正的设备"之间的分界线。
# 空调、热水器、电饭煲、汽车发动机 —— 它们全部都是这个结构：
#
#     读一个数  →  和阈值比  →  超过就动作
#
# 你写的就是这个结构。区别只是传感器的种类和阈值的数值。
#
# ─────────────────────────────────────────────────────
#  你写的是什么：一个"判断函数"，不是一个"结论"
# ─────────────────────────────────────────────────────
#
# 新手最容易写出这种代码：
#
#     def 判断报警(派, 上限=30.0):
#         return "太热了"                  # ← 错了，但看起来很对
#
# 它"能跑"、"有返回值"、"输出也对"（因为现在确实很热）——
# 可是它**没有读任何东西**。温度降到 10°C 它还是喊"太热了"。
#
# 判断函数里必须出现「读」这一步，而且结论必须**由那个读数算出来**：
#
#     温度 = 派.温度.读()        # ① 先拿到事实
#     if 温度 > 上限:            # ② 再根据事实做决定
#         return f"太热了，温度 {温度}°C"
#     return ""
#
# 一句话概括：**函数里不能有"答案"，只能有"算法"。**
# 答案（到底热不热）是运行时由读数决定的，不是写代码时定下来的。
#
# ─────────────────────────────────────────────────────
#  应该怎么写：三个新东西
# ─────────────────────────────────────────────────────
#
# ① 加一个传感器
#
#     派.加传感器("温度", "°C", (0.0, 50.0), 22.0)
#                  ↑名字   ↑单位  ↑量程      ↑初始读数
#
#    · 量程 (低, 高) 是这个传感器能报出来的范围。以后 设为() 超出量程会报错 ——
#      真实传感器也是这样：DS18B20 测不到 200°C，硬要它报就是错的数据。
#    · 加完之后可以**直接用名字访问**：派.温度.读()
#
# ② 读一次
#
#     温度 = 派.温度.读()        # 返回一个小数，例如 22.5
#     print(温度)                # 调试时先把读数打出来看看
#
#    ⚠ 读() 每次返回的是**当前**读数。你不改环境，它就一直是同一个数。
#      真实世界里温度自己会变；模拟器里要你自己用 派.温度.设为(38.5) 去"改变环境"。
#      检查就是用 设为() 来模拟"现在变热了/变冷了"。
#
# ③ 比较和分支
#
#     if 温度 > 上限:
#         ...报警...
#     else:
#         ...不报警...
#
#   注意用的是 `>` 而不是 `>=`：**正好等于上限算不算超**，
#   是你要自己想清楚的一个约定。真实的报警器都要明确这件事
#   （"超过 30 度报警"和"到 30 度就报警"是两种设备）。
#
# ─────────────────────────────────────────────────────
#  顺便记住什么：三个真会咬人的坑
# ─────────────────────────────────────────────────────
#
# ① 阈值要写成一个**可以调的数**，不要散在代码各处
#    真实项目里阈值永远是配置项（写在文件里或者参数里），
#    因为"几度算热"会随着季节、房间、作物一直改。
#    这一课把它做成参数 上限=30.0，就是让你先习惯这件事。
#
# ② 读数永远是"脏"的
#    真实传感器会跳：25.1、25.3、24.8、31.0、25.2 —— 那个 31.0 可能是干扰。
#    所以真实的报警器常常要求"连续 N 次超标才报警"，否则会被噪声吵死。
#    模拟器的读数很干净，**这是模拟器和真实世界最大的差距之一**。
#
# ③ 报警之后要有人收尾
#    报警不是 print 一行就完了 —— 要有人看到（点灯、响蜂鸣器）、
#    要记下来（第 03 课）、还要能解除。只喊不动的报警器等于没装。
#
# ─────────────────────────────────────────────────────
#  ⚠ 模拟器验证不了电路（这一课尤其要记住）
# ─────────────────────────────────────────────────────
#
# 检查全过 ≠ 插上真传感器就能用。模拟器只跑**程序逻辑**，它看不见：
#
#   · **限流电阻** —— 报警灯（LED）必须串一个 220Ω~1kΩ 的电阻。
#     直接接在引脚上会烧掉 LED，严重时连树莓派的引脚一起烧。
#   · **接线位置** —— LED 正负极、传感器接在哪几个排针上，只有你知道；
#     接错了程序不会报错，只是数据是错的（或者根本读不到）。
#   · **I2C 地址冲突** —— 这是树莓派上最经典的坑：
#     很多传感器（温湿度、气压、OLED）都走 I2C 总线，每个设备有一个地址。
#     同一根总线上**两个设备用同一个地址就会打架**，表现是读数时好时坏、
#     或者干脆读到另一个设备的数据。买之前先查地址，买之后用
#     `i2cdetect -y 1` 扫一遍。
#   · **传感器型号差异** —— 这一课模拟器统一给你一个 读()，
#     但真实世界完全不是这样：DHT11 要按特定时序读、DS18B20 走单总线、
#     BMP280 走 I2C 还要先算补偿公式、模拟量的光敏电阻还得自己 ADC。
#     拿到具体型号时，**要换掉的是"读"那一行**，判断逻辑一行都不用改 ——
#     这正是这一课把读取收成一个 读() 的原因。
#   · 还有：供电够不够、杜邦线插紧没有、传感器是不是 3.3V 的（5V 会烧）。
#
# 代码检查通过而板子读数不对的时候，先查上面这几条，别急着怀疑代码。
#
# ─────────────────────────────────────────────────────
#  写完之后
# ─────────────────────────────────────────────────────
#   python -m learncode 树莓派 检查 02
#
#  卡住了？先在答案文件里这样试一下，把过程打出来看：
#      派 = 树莓派()
#      派.加传感器("温度", "°C", (0.0, 50.0), 22.0)
#      派.温度.设为(38.5)
#      print(判断报警(派, 30.0))     # 应该报警
#      派.温度.设为(20.0)
#      print(判断报警(派, 30.0))     # 应该不报警 —— 两次结果必须不一样


