# 第 01 课：点亮一盏 LED —— 树莓派和你以前听说的单片机不一样

# 要做：
#   写一个函数 闪(派, led, 次数=3)，让它闪 次数 下：
#
#     1. 亮一下       led.亮()
#     2. 等一下       派.睡(0.5)        ← 单位是秒
#     3. 灭掉         led.灭()
#     4. 再等一下     派.睡(0.5)
#   这样算**一下**。重复 次数 次，最后 led 是**灭**的。
#
#   检查会这样验你：
#     · 次数=1 和 次数=3，调用之后 LED 的"亮灭记录"必须**不一样长** ——
#       写死"只亮一次"的函数通不过。
#     · 最终状态必须是「灭」—— 程序结束不复位引脚，灯留在亮着，
#       人就会一直以为还在出事。
#
#   ⚠ 这一课唯一要记住的东西**不在代码里**，在下面第一段：
#     树莓派和单片机写代码的方式**根本不同**。

# ═════════════════════════════════════════════════════
#  一、最重要的一件事：树莓派 ≠ 单片机
# ═════════════════════════════════════════════════════
#
# 你可能见过 Arduino 那一类的单片机教程，代码长这样：
#
#     void setup() { pinMode(13, OUTPUT); }
#     void loop()  { digitalWrite(13, HIGH); delay(500);
#                    digitalWrite(13, LOW);  delay(500); }
#
#   `loop()` 是**主循环** —— 没有任何操作系统，你的代码就是整个程序，
#   它从通电开始**永远在转**，一直到断电。控制节奏靠 `delay()`。
#
# 树莓派**不是这样**。它跑着完整的 Linux，是一个**小电脑**：
#
#     ┌──────────────┬──────────────────────────┬──────────────────────┐
#     │              │ 单片机（Arduino 那类）    │ 树莓派                │
#     ├──────────────┼──────────────────────────┼──────────────────────┤
#     │ 有没有操作系统 │ 没有，你的代码就是全部     │ 有，完整的 Linux      │
#     │ 程序是什么     │ 一个永不返回的 loop()     │ 一个**普通进程**      │
#     │ 有没有开始结束 │ 没有，上电跑到断电         │ **有**开始、有结束    │
#     │ 想一直监测     │ 天生如此（loop 自己转）    │ 自己写 while True    │
#     │               │                          │ 或者用定时任务        │
#     │ 能用文件/网络  │ 基本不能                  │ 能，它就是台电脑      │
#     │ 断电之后       │ 什么都不剩                │ 文件还在硬盘上        │
#     └──────────────┴──────────────────────────┴──────────────────────┘
#
# ⚠⚠ **这条差别是整条树莓派课线的重点。**
#   学完单片机再来学树莓派的人，最常见的错误是：把 Tree Pi 的程序
#   写成一个"永不结束的 loop"，然后在里面 delay ——
#   在单片机里那是对的，在树莓派里那叫"占着一个进程不放"。
#
#   树莓派上的正确想法是：
#     · 我要么**做完一件事就退出**（像这一课：闪三下，结束）
#     · 要么明确地**写一个长期运行的服务**（`while True:`）——
#       但那要处理"怎么停"、"崩了怎么重启"、"日志写哪"
#       （第 04 课「长时间监测」专门讲这个）
#
#   一句话：**单片机是"把程序烧进去让它一直转"，
#            树莓派是"在电脑上跑一个程序，跑完就完"。**

# ═════════════════════════════════════════════════════
#  二、你写的是什么：一次"有始有终"的点灯
# ═════════════════════════════════════════════════════
#
# 这一课的程序是**做完就结束**的：
#
#     接上 LED  →  闪三下  →  灭掉  →  进程退出
#
# 运行一百次，做的一百次都一样。它跟外面的世界还没有关系 ——
# 「读传感器」（第 02 课）才会让它开始看情况做事。
#
# ─────────────────────────────────────────────────────
#  三、三个新东西
# ─────────────────────────────────────────────────────
#
# ① 接一个 LED
#
#     led = 派.接LED(17, 名字="指示灯")
#                    ↑ BCM 引脚号
#
#   接完之后可以：led.亮()、led.灭()、led.翻转()、led.状态()
#   ⚠ `状态()` 返回的是中文「亮」或「灭」—— 用来在检查里看你到底有没有动它。
#
# ② 等一会儿
#
#     派.睡(0.5)              # 睡 0.5 秒
#
#   ⚠ 这里的 `0.5` 是**真实的一秒的一半**。模拟器里它不会真的卡住，
#     但它会记录"你在什么时刻做了什么" ——
#     所以**忘了写睡()，闪烁就会快到看不见**，而程序依然"能跑"。
#     真实板子上，不 sleep 的闪灯是人眼完全看不到的。
#
# ③ 重复做 —— 用循环，不要复制粘贴
#
#     for _ in range(次数):
#         led.亮(); 派.睡(0.5)
#         led.灭(); 派.睡(0.5)
#
#   ⚠ 新手最容易这样写：把"亮、睡、灭、睡"手抄三遍。
#     抄三遍的问题不是字多，是**改的时候要改三处** —— 漏一处就是 bug。
#
# ─────────────────────────────────────────────────────
#  四、真会咬人的三个坑
# ─────────────────────────────────────────────────────
#
# ① **程序结束不复位引脚**
#    进程退出了，引脚还停在最后一次写的电平上。
#    所以最后必须 `led.灭()` —— 否则灯一直亮着，
#    而"灯亮着"在真实设备里意味着"还在报警"。
#
# ② **限流电阻不能省**
#    LED 必须串一个 220Ω ~ 1kΩ 的电阻。直接接在引脚上会烧 LED，
#    严重时连树莓派的引脚一起烧。
#    ⚠ 模拟器**看不见**这个 —— 它只跑程序逻辑。见下面第五节。
#
# ③ **不要用 busy-wait 代替 睡()**
#    写 `while time.time() < 开始 + 0.5: pass` 来"等半秒"是错的：
#    它会把一个 CPU 核占满。树莓派是台电脑，别的进程还要用。
#
# ─────────────────────────────────────────────────────
#  五、⚠ 模拟器验证不了电路（整条线都要记住）
# ─────────────────────────────────────────────────────
#
# 检查全过 ≠ 插上线就能亮。模拟器只跑**程序逻辑**，它看不见：
#
#   · 限流电阻   —— 报警灯/LED 必须串 220Ω~1kΩ，不串会烧
#   · 接线位置   —— LED 正负极、接在哪两个排针上，只有你知道；
#                  接反了程序不报错，只是不亮
#   · 引脚号     —— 树莓派的引脚编号有两套（BCM 和物理排针号），
#                  写错一套程序"能跑"但灯不亮。本项目统一用 **BCM**
#   · 供电       —— LED 多了、传感器多了，3.3V 引脚带不动
#   · 3.3V/5V   —— 很多传感器是 3.3V 的，接到 5V 上会烧
#
# 代码检查通过而板子不亮的时候，先查上面这几条，别急着怀疑代码。
#
# ─────────────────────────────────────────────────────
#  六、写完之后怎么自己测
# ─────────────────────────────────────────────────────
#   python -m hybridengine_light 树莓派 检查 01
#
#  想先手动试试，可以在答案文件里写：
#      from hybridengine_light.raspi import 树莓派
#      派 = 树莓派()
#      led = 派.接LED(17, 名字="指示灯")
#      闪(派, led, 3)
#      print(led.状态())        # 应该是「灭」
#      print(派.报告())         # 看它记下来的亮灭过程


# ── 下面是检查用的代码，不用改 ──

def _新派():
    """建一块模拟树莓派，接好一盏叫「指示灯」的 LED（BCM 17）。"""
    from hybridengine_light.raspi import 树莓派
    派 = 树莓派(名字="模拟树莓派")
    led = 派.接LED(17, 名字="指示灯")
    return 派, led


def _取闪(答案):
    if not hasattr(答案, "闪"):
        return None, ("还没有定义「闪」函数。写法：\n"
                      "          def 闪(派, led, 次数=3):\n"
                      "              for _ in range(次数):\n"
                      "                  led.亮(); 派.睡(0.5)\n"
                      "                  led.灭(); 派.睡(0.5)")
    if not callable(答案.闪):
        return None, "「闪」存在，但它不是函数。要用 def 定义。"
    return 答案.闪, ""


def _调用(函数, 次数):
    """调用一次，返回 (最终状态, 亮灭记录长度, 错误说明)。"""
    派, led = _新派()
    try:
        函数(派, led, 次数)
    except TypeError as e:
        return None, 0, ("调用 闪(派, led, 次数) 时参数不对：" + str(e) + "\n"
                         "      它应该收三个参数：派、led、次数（次数要有默认值）：\n"
                         "          def 闪(派, led, 次数=3):")
    except Exception as e:                              # noqa: BLE001
        return None, 0, (f"调用 闪(派, led, {次数}) 出错了："
                         f"{type(e).__name__}: {e}\n"
                         "      常见原因：LED 变量名写错（检查传进来的是 led）、\n"
                         "      忘了写 派.睡(...)、或者用了没定义的变量。")
    # ⚠⚠ 判据是**日志里的写引脚次数**，不是 `报告()` 的行数。
    #   我第一版数的是 派.报告() 的行数 —— 报告只列**当前**状态，
    #   不管闪几下都是同一个长度，于是"闪 1 次"和"闪 3 次"看起来一样，
    #   检查把**正确答案判成了错的**（实测就是）。
    #   派.日志 才逐条记：每次写引脚（亮/灭）追加一行。
    写次数 = sum(1 for l in 派.日志 if "←" in l)
    return led.状态(), 写次数, ""


def CHECK_函数存在(答案):
    """「闪」必须是个接收三个参数的函数。"""
    函数, 错误 = _取闪(答案)
    if 函数 is None:
        return False, 错误
    try:
        import inspect
        参数 = list(inspect.signature(函数).parameters)
    except Exception:                                   # noqa: BLE001
        return True, "闪 是个函数"
    if len(参数) < 3:
        return False, (f"「闪」现在只接收 {len(参数)} 个参数（{参数}）。\n"
                       "      它需要三个：派、led、次数，而且次数要给默认值：\n"
                       "          def 闪(派, led, 次数=3):\n"
                       "      为什么次数要当参数：想闪几下是**会变的**，\n"
                       "      写死在函数里，改一次就要动一次代码。")
    return True, f"闪(派, led, 次数) 是个函数 —— 参数：{参数}"


def CHECK_真的动了LED(答案):
    """★ 核心检查：必须真的去写引脚，不能只是「看起来像」。

    怎么验：跑一次，看 LED 的最终状态 ——
    亮着说明没写 灭()，一直灭说明根本没动它。
    """
    函数, 错误 = _取闪(答案)
    if 函数 is None:
        return False, 错误
    终态, _, 错误 = _调用(函数, 1)
    if 错误:
        return False, 错误
    if 终态 == "灭":
        # 灭是对的，但也可能是"根本没碰过 LED" —— 交给下一条判
        return True, "闪一下之后 LED 是「灭」的"
    return False, (f"闪完之后 LED 还是「{终态}」的。\n"
                   "      ⚠ 这是树莓派上很典型的一个坑：**进程退出不会复位引脚**。\n"
                   "        程序结束了，引脚还停在最后一次写的电平上 ——\n"
                   "        灯一直亮着，别人就会以为还在出事。\n"
                   "      所以循环的最后一定要写 led.灭()。")


def CHECK_次数真的起作用(答案):
    """★ 本课的核心检查：次数参数必须真的影响行为，不能写死。

    怎么验：次数=1 和 次数=3 各跑一次，看 LED 的亮灭记录长度。
    两次一样 —— 说明函数没在用「次数」，而是写死了「闪一下」。
    """
    函数, 错误 = _取闪(答案)
    if 函数 is None:
        return False, 错误
    一次, 长1, 错误 = _调用(函数, 1)
    if 错误:
        return False, 错误
    三次, 长3, 错误 = _调用(函数, 3)
    if 错误:
        return False, 错误

    if 长1 == 长3 == 0:
        return False, ("跑完之后「报告」里什么都没有 —— 说明函数**根本没有碰 LED**。\n"
                       "      它可能只是算了一下、或者 print 了几行。\n"
                       "      要真的去写引脚：led.亮() / led.灭()。")

    if 长1 == 长3:
        return False, (
            f"次数=1 和 次数=3 跑出来一样（都是 {长1} 条记录）——\n"
            "      说明函数**没有在用「次数」这个参数**，而是写死了闪几下。\n"
            "      常见原因：循环写成了 range(3) 这种固定数字，而不是 range(次数)。\n"
            "      改法：\n"
            "          def 闪(派, led, 次数=3):\n"
            "              for _ in range(次数):        # ← 用参数，别写数字\n"
            "                  led.亮(); 派.睡(0.5)\n"
            "                  led.灭(); 派.睡(0.5)\n"
            "      一句话：**函数里不能有「答案」，只能有「算法」**。")

    if 长3 < 长1:
        return False, (f"次数=3 的记录反而比 次数=1 短（{长3} < {长1}）—— 次数好像用反了。")

    if 终态 := 三次:
        if 终态 != "灭":
            return False, (f"闪三下之后 LED 是「{终态}」的 —— 最后要 led.灭()。")
    return True, (f"次数=1 → {长1} 条记录，次数=3 → {长3} 条记录；"
                  f"最后都是「灭」—— 次数真的在起作用")


def CHECK_用了循环(答案):
    """必须用循环，不能把「亮睡灭睡「手抄三遍。

    为什么查这个：手抄的版本在「次数「变成 10 的时候就不成立了。
    判据看源码里有没有 for/while —— 这是一条**源码判据**，
    弱一些（能绕过），但这一课要教的正是「用循环代替重复」。
    """
    import io
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    正文 = "\n".join(l for l in 源码.splitlines() if not l.strip().startswith("#"))
    if "for " in 正文 or "while " in 正文:
        return True, "用了循环 —— 改次数不用改代码"
    return False, ("没看到循环（for / while）。\n"
                   "      如果代码里是「亮、睡、灭、睡「手抄三遍 —— 那「次数「就只能是 3。\n"
                   "      抄三遍的问题不是字多，是**改的时候要改三处**，漏一处就是 bug。\n"
                   "      改法：\n"
                   "          for _ in range(次数):\n"
                   "              led.亮(); 派.睡(0.5)\n"
                   "              led.灭(); 派.睡(0.5)")
