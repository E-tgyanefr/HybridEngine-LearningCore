# 第 01 课：用树莓派点亮 LED —— 但它和单片机不一样

# 要做：
#   写一个函数 闪一下(派)，让传入的 LED 先亮、然后灭。
#   就这一件事 —— 但这一课的重点不在"点灯"，在**搞清树莓派和单片机的差别**。

# ─────────────────────────────────────────────────────
#  树莓派 vs 单片机：一个必须搞清的差别
# ─────────────────────────────────────────────────────
#
# 两者都能"用程序控制引脚"，但**写代码的方式根本不同**：
#
#   单片机（Arduino 那类）
#       你写一个 loop()，程序**永远在转**，靠 delay 控制节奏。
#       没有操作系统 —— 你的代码就是这台机器的全部。
#
#     　void loop() {
#           digitalWrite(LED, HIGH);
#           delay(1000);
#           digitalWrite(LED, LOW);
#           delay(1000);
#       }                        ← 这段代码会一直重复，直到断电
#
#   树莓派
#       它跑的是**完整的 Linux**，你的程序是一个**普通进程** ——
#       有开始、有结束。想一直监测就得自己写 while True 或者做成定时任务。
#
#       # 这就是一个完整的树莓派程序：跑完就退出了
#       GPIO.output(17, True)
#       time.sleep(1)
#       GPIO.output(17, False)
#       # 到这里程序结束，LED 保持灭的状态
#
# **为什么这个差别重要**：
#   很多单片机教程搬过来会让人困惑 —— "我的 loop 呢？"
#   树莓派上没有 loop，只有你要不要自己写循环。
#
# ─────────────────────────────────────────────────────
#  两个概念
# ─────────────────────────────────────────────────────
#
# ① **BCM 编号**
#    树莓派的引脚号用的是芯片的编号（BCM），不是物理排针的位置。
#    常用的是 GPIO 17、18、27、22、23、24、25、2、3 ...
#    写错编号在真实板子上**不会报错** —— 那个引脚只是毫无反应。
#    （模拟器会报错，帮你养成先查编号的习惯。）
#
# ② **先设模式，再读写**
#    每个引脚必须先声明是输入还是输出：
#        GPIO.setmode(GPIO.BCM)      # 声明用 BCM 编号
#        GPIO.setup(17, GPIO.OUT)    # 17 号脚当输出
#        GPIO.output(17, GPIO.HIGH)  # 输出高电平 → 灯亮
#    没设模式就写，真实板子上也是**没反应**（不报错）。
#
# ─────────────────────────────────────────────────────
#  模拟器里的写法
# ─────────────────────────────────────────────────────
#
#     派.GPIO.设模式(17, GPIO.输出)      ← 相当于 GPIO.setup(17, GPIO.OUT)
#     派.GPIO.写(17, GPIO.高)            ← 相当于 GPIO.output(17, GPIO.HIGH)
#
#   或者更省事：
#     led = 派.接LED(17)                 ← 一步配好并返回一个 LED 对象
#     led.亮() / led.灭() / led.翻转() / led.状态()
#
# ─────────────────────────────────────────────────────
#  写完之后
# ─────────────────────────────────────────────────────
#   python -m learncode 树莓派 检查 01


# ── 下面是检查用的代码，不用改 ──

def _新派():
    from learncode.raspi import 树莓派
    派 = 树莓派(名字="模拟树莓派")
    led = 派.接LED(17, 名字="LED")
    return 派, led


def CHECK_函数存在(答案):
    if not hasattr(答案, "闪一下"):
        return False, ("还没有定义「闪一下」这个函数。\n"
                       "      写法：\n"
                       "          def 闪一下(派):\n"
                       "              ...")
    if not callable(答案.闪一下):
        return False, "「闪一下」不是函数。要用 def 定义。"
    return True, "闪一下 是个函数"


def CHECK_能调用(答案):
    if not hasattr(答案, "闪一下"):
        return False, "还没有定义「闪一下」函数"
    派, led = _新派()
    try:
        答案.闪一下(派)
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 闪一下(派) 时出错了：{type(e).__name__}: {e}\n"
                       f"      检查你的函数有没有正确接收「派」这个参数。")
    return True, "调用没有报错"


def CHECK_最终是灭的(答案):
    """函数结束时 LED 必须是灭的 —— 这是"闪一下"的定义。

    ⚠ 这一条背后是树莓派思维：**程序结束不等于引脚复位**。
      真实板子上，程序退出后引脚会保持最后的状态。
      所以"闪一下"必须**自己**把它关掉，不能指望程序结束帮你收尾。
      这正是树莓派和单片机的一个实际差别 —— 值得讲清楚。
    """
    if not hasattr(答案, "闪一下"):
        return False, "还没有定义「闪一下」函数"
    派, led = _新派()
    try:
        答案.闪一下(派)
    except Exception:                                 # noqa: BLE001
        return False, "调用出错了，先让它能正常执行"

    if led.状态() == "灭":
        return True, "函数结束时 LED 是灭的 —— 收尾做对了"
    return False, (
        "函数结束时 LED 还是**亮**的。\n"
        "      「闪一下」的意思是：亮起来，然后**关掉**再结束。\n"
        "      改法：最后加一句把引脚拉低 ——\n"
        "          led.灭()        或者       派.GPIO.写(17, GPIO.低)\n"
        "      ⚠ 为什么必须自己关：**程序结束不会自动复位引脚**。\n"
        "        真实树莓派上，你的程序退出之后，那个引脚会一直保持高电平 ——\n"
        "        LED 就一直亮着。这不是 bug，是硬件的行为。")


def CHECK_真的亮过(答案):
    """必须**真的亮过**，而不是从头到尾都是灭的。

    怎么验：看板子的操作日志。日志里必须出现"拉高"这一步 ——
    如果只有"拉低"，说明学生忘了先点亮。
    """
    if not hasattr(答案, "闪一下"):
        return False, "还没有定义「闪一下」函数"
    派, led = _新派()
    try:
        答案.闪一下(派)
    except Exception:                                 # noqa: BLE001
        return False, "调用出错了"

    日志 = 派.日志文本()
    if "高" in 日志:
        return True, "从日志看，LED 确实被点亮过"

    return False, (
        "板子的操作日志里没有看到「拉高引脚」这一步 —— LED 一次都没亮。\n"
        f"      日志内容：\n          {日志}\n"
        "      「闪一下」要先亮再灭：\n"
        "          led.亮()      ← 这一步不能少\n"
        "          led.灭()")


def CHECK_顺序对(答案):
    """顺序必须是「先亮后灭」，不能反过来。

    怎么验：日志是**按发生顺序**记的，直接看第一条电平操作是高还是低。
    """
    if not hasattr(答案, "闪一下"):
        return False, "还没有定义「闪一下」函数"
    派, led = _新派()
    try:
        答案.闪一下(派)
    except Exception:                                 # noqa: BLE001
        return False, "调用出错了"

    # 只看和 LED 有关的电平操作
    序列 = [l for l in 派.日志 if "GPIO 17" in l and ("高" in l or "低" in l)]
    if not 序列:
        return False, "日志里没有找到对 GPIO 17 的电平操作"

    第一条 = 序列[0]
    if "高" in 第一条:
        return True, f"顺序正确：{第一条.split(']')[-1].strip()} 在前"
    return False, (
        "顺序反了 —— 先把它关掉、再点亮，那就不叫「闪一下」了。\n"
        f"      日志里的顺序：\n" +
        "".join(f"          {l}\n" for l in 序列) +
        "      改法：先 led.亮()，再 led.灭()。")
