# 第 04 课：长时间监测 —— 树莓派上没有 loop()，要自己写

# 要做：
#   写一个函数 循环监测(派, 轮数, 路径, 上限=30.0)：
#
#     · 读一次温度        →  温度 = 派.温度.读()
#     · 一旦超过 上限      →  报警（点亮报警灯 / 把这件事记下来）
#     · **每一轮都要**把这一轮的读数和时间记进 路径 这个文件（一条一行，
#        和上一课一样用 派.写文件() 追加）
#     · 让时间往前走一点  →  派.时间推进(1.0)
#     · 上面这几步要**重复 轮数 次**，然后才结束、才 return
#
#   参数 轮数 是这一课的钥匙：它让你能说清"跑多少轮就停"。
#   真实项目里那个循环是**永远不停**的（while True），一直跑到你关机；
#   但在模拟器里我们不能真的让它转到天荒地老 ——
#   所以课程把"转多少圈"交给你当参数传进来。
#   等你写真正上线的程序时，把它换成 while True 就成形了。
#
#   检查会这样验你：调用 循环监测(派, 5, 路径) ——
#   然后数文件里是**不是 5 条**记录。
#   只处理一轮就结束（忘了缩进进循环 / 忘了循环 /
#   在循环里 return）都会被抓：文件里只有 1 条。
#
#   ⚠ 千万别在答案里写 while True 来交作业。
#     检查会一直等它，命令会卡死在那儿不动（真实的树莓派程序就是这样 ——
#     它永远不会自己结束）。要"一直跑"的是真项目，
#     这一课的作业必须是"跑 轮数 轮就收工"。

# ─────────────────────────────────────────────────────
#  发生了什么：程序可以一直活着
# ─────────────────────────────────────────────────────
#
# 前三课的程序都是**跑完就死**的：读一次、判断一次、记一次，进程结束。
# 可真实的监测设备不是这样 —— 温室监测器要跑一整个夏天，
# 每小时记一次数据，期间没人会去重新运行它。
#
# 这就是"程序要一直跑"这件事：它是树莓派最典型的用法，
# 也是它和单片机**最大的思维差别**所在。
#
# ─────────────────────────────────────────────────────
#  ★ 树莓派 vs 单片机：这一课专门讲这个
# ─────────────────────────────────────────────────────
#
#   单片机（Arduino 那类）
#       你写的 loop() **会被自动反复调用**，永远在转。
#       不需要你写循环 —— 框架替你写了。
#
#           void setup() { ... }      // 开机跑一次
#           void loop()  { ... }      // 然后**永远**重复这一段
#
#       没有操作系统，你的代码就是这台机器的全部。
#       断电 = 世界结束；没有文件、没有别人、没有"退出"。
#
#   树莓派
#       它跑的是**完整的 Linux**。你的程序只是一个**普通进程** ——
#       有开始、有结束，跟你在电脑上跑的任何程序没有本质区别：
#
#           print("开始")
#           print("结束")        # 到这里进程就死了，不会再来一遍
#
#       想一直监测？**自己写循环**：
#
#           while True:
#               ...读一次、判断、记录...
#               time.sleep(60)
#
# **为什么这个差别会咬人**（几乎每个从单片机转过来的人都会踩）：
#   ① 你写了一段"读温度 → 报警"，运行了一下，看到输出，就以为装好了 ——
#      其实程序已经退出了，什么都不会再发生。
#   ② 反过来说，树莓派上你写的每一段代码**都要自己负责"什么时候结束"**，
#      而单片机上你从来不用想这件事。
#   ③ 单片机的 loop 里 delay(1000) 是"睡一秒"；
#      树莓派上 time.sleep(60) 是"让出 CPU 一分钟"——
#      这期间系统还在跑别的东西（网络、别的服务）。**你不是这台机器唯一的主人**，
#      这是单片机思维里完全没有的概念。
#
# ─────────────────────────────────────────────────────
#  真实项目里这种程序长什么样：开机自启的后台服务
# ─────────────────────────────────────────────────────
#
# 这一课写的循环，在真实项目里**不会**是你在终端里手动跑的一个脚本 ——
# 因为那种程序一关终端就没了，重启也没了。真正上线是这样：
#
#   · **systemd 服务**（树莓派上最常见的做法）
#     把一个 .service 文件放进 /etc/systemd/system/，里面写清楚
#     "开机就跑这个脚本、崩了就自动重启"，然后：
#         sudo systemctl enable 我的监测器     # 开机自启
#         sudo systemctl start  我的监测器     # 现在就跑起来
#         journalctl -u 我的监测器             # 看它打出来的日志
#     这样它就在后台一直跑着，不需要有人登录、不需要开着终端。
#
#   · **cron / systemd timer**：不用常驻，
#     让系统"每 5 分钟叫醒我跑一次"就行 —— 很多采集任务这样更省事。
#
#   · **日志交给 journald / 写进文件**：
#     后台跑的程序没有屏幕，print 出来的东西没人看得见。
#     所以第 03 课的"记录到文件"在这里是必需品，不是练习。
#
# 所以这一课其实是在写一个**服务的核心循环**：
# 真正上线时你要做的只是给它套一层 systemd 的外壳，
# 再把 while 轮数 换成 while True。
#
# ⚠ 两个真实世界才有的细节（模拟器里一个都不会发生，但你要知道）：
#   · **收尾**：程序可能被 Ctrl+C 或者 systemd 停掉。
#     真实代码要接住它，把引脚复位、把没写完的数据落盘：
#         try:
#             while True: ...
#         except KeyboardInterrupt:        # 有人按了 Ctrl+C
#             pass
#         finally:
#             GPIO.cleanup()               # 引脚复位，不然灯一直亮着
#             # 该关的文件关掉、该 flush 的 flush 掉
#     （第 01 课那条"程序结束不会自动复位引脚"在这里变成了一件正事。）
#   · **它得能从错误里活下来**：传感器偶尔读失败、网络断了、
#     文件写不进去 —— 一个没接住异常的循环会当场死掉，
#     而你第二天早上才发现昨晚 2 点它就停了。
#     真实项目里循环体外面通常包着 try/except + 记下错误继续跑。
#
# ─────────────────────────────────────────────────────
#  应该怎么写：一个"次数由参数决定"的循环
# ─────────────────────────────────────────────────────
#
#     def 循环监测(派, 轮数, 路径, 上限=30.0):
#         for 第几轮 in range(轮数):         # ← 重复 轮数 次
#             温度 = 派.温度.读()
#             if 温度 > 上限:
#                 ...
#             派.写文件(路径, f"{派.时间},{温度}\n")   # 每一轮都记
#             派.时间推进(1.0)
#         return ...                          # ← 循环**外面**才 return
#
# 三个最容易错的地方，检查全都盯着：
#
#   ① **缩进**：要做的几件事必须在 for 里面（缩进一层）。
#      少缩进一行 → 那件事只做一次，循环等于白写。
#      这是初学者第一大坑，而且代码"看起来"完全正常。
#
#   ② **return 的位置**：return 写在循环里 = 第一轮就跑路。
#      这就是这一课要抓的"只处理了一轮"。
#
#   ③ **每轮都要记录**：只在报警时记 = 正常的时候一条数据都没有，
#      那你永远不知道"什么时候开始不正常的"。
#      记录必须是**每轮无条件**的，报警只是记录里多一个标记。
#
# ─────────────────────────────────────────────────────
#  顺便记住什么
# ─────────────────────────────────────────────────────
#
# ① 为什么要 sleep / 时间推进
#    不睡的话循环会**全速空转**：一秒能读几万次，CPU 占满、日志爆掉、
#    SD 卡很快就写坏（见第 03 课）。真实的监测程序都要"每 N 秒看一眼"。
#    树莓派的 sleep 和单片机 delay 有个关键差别：
#    **sleep 期间系统还在跑别的东西** —— 网络、别的服务、你自己登录的终端。
#    这也是为什么树莓派能一边监测一边当服务器，单片机不行。
#
# ② 多久读一次，是个设计决定
#    温室温度：一分钟一次足够；振动、声音：可能要几千次每秒。
#    读太快 = 数据垃圾多、SD 卡损耗快；读太慢 = 错过真正的事件。
#    这个取舍没有标准答案，取决于你在看什么。
#
# ③ 程序"一直跑"就意味着"一直可能出问题"
#    跑一小时不出错很容易，跑一个夏天不出错是另一回事。
#    所以真实项目里：写日志、能被 systemd 自动重启、出错要留证据。
#
# ─────────────────────────────────────────────────────
#  ⚠ 模拟器验证不了电路（这一课特别要记住）
# ─────────────────────────────────────────────────────
#
# 检查全过 ≠ 插上板子就能跑一个夏天。模拟器只跑**程序逻辑**，它看不见：
#
#   · **限流电阻** —— 报警灯、状态灯，每个 LED 都要串 220Ω~1kΩ。
#     一个长期通电的灯如果没有电阻，早晚会烧（而且可能连引脚一起烧）。
#   · **接线位置** —— 长期运行最怕的就是"接触不良"：
#     杜邦线松了、焊点虚了，程序会读到乱跳的数，你还以为是传感器坏了。
#     （真实的长期监测项目里，接线往往比代码更容易出问题。）
#   · **I2C 地址冲突** —— 一路挂好几个传感器时最容易撞：
#     两个设备同地址 → 读数时好时坏，而且是**跑一段时间之后**才开始坏，
#     特别难查。上电前 `i2cdetect -y 1` 扫一遍，把地址记下来。
#   · **传感器型号差异** —— 不同型号的读数速度、精度、坏掉时的表现都不一样。
#     有的传感器读失败会直接报错，有的是"返回一个看起来很正常的假值"
#     （比如永远 85.0）—— 后者最危险，长期跑的数据会悄悄全是错的。
#   · **散热和供电** —— 跑几个月的树莓派会热、电源会老化。
#     这不是代码问题，但它是"长期"这两个字真正的难点。
#
# ─────────────────────────────────────────────────────
#  写完之后
