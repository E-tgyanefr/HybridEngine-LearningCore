路径 = "/home/pi/长期监测.csv"


def _新派(读数为: float = 22.0):
    """一块干净的模拟树莓派，带温度传感器和报警灯。"""
    from hybridengine_light.raspi import 树莓派
    派 = 树莓派(名字="模拟树莓派")
    派.加传感器("温度", "°C", (0.0, 50.0), 读数为)
    派.接LED(17, 名字="报警灯")
    return 派


def _取函数(答案):
    if not hasattr(答案, "循环监测"):
        return None, ("还没有定义「循环监测」函数。\n"
                      "      写法：\n"
                      "          def 循环监测(派, 轮数, 路径, 上限=30.0):\n"
                      "              for 第几轮 in range(轮数):\n"
                      "                  温度 = 派.温度.读()\n"
                      "                  ...")
    if not callable(答案.循环监测):
        return None, "「循环监测」存在，但它不是函数。要用 def 定义。"
    return 答案.循环监测, ""


def _跑(函数, 轮数, 路径=路径, 上限=30.0, 读数=22.0):
    """跑一轮监测，返回 (派, 备注)。

    备注非空 = 这次调用有问题（参数不对 / 抛异常）。
    """
    派 = _新派(读数)
    try:
        函数(派, 轮数, 路径, 上限)
    except TypeError as e:
        return 派, (f"调用 循环监测(派, {轮数}, 路径) 时参数不对：{e}\n"
                    "      它应该接收四个参数：派、轮数、路径、上限（上限给默认值）：\n"
                    "          def 循环监测(派, 轮数, 路径, 上限=30.0):")
    except Exception as e:                            # noqa: BLE001
        return 派, (f"调用 循环监测(派, {轮数}, 路径) 时出错了：{type(e).__name__}: {e}\n"
                    "      常见原因：循环变量写错、把 轮数 当成了字符串、\n"
                    "      或者某一步忘了缩进进循环。")
    return 派, ""


def _行数(文本: str) -> int:
    return len([l for l in 文本.splitlines() if l.strip()])


def CHECK_函数存在(答案):
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误
    try:
        import inspect
        参数 = list(inspect.signature(函数).parameters)
    except Exception:                                 # noqa: BLE001
        return True, "循环监测 是个函数"
    if len(参数) < 2:
        return False, (f"「循环监测」现在只接收 {len(参数)} 个参数（{参数}）。\n"
                       "      它至少需要两个：派 和 轮数（还要有一个 路径）：\n"
                       "          def 循环监测(派, 轮数, 路径, 上限=30.0):\n"
                       "      轮数 是这一课的钥匙：它替掉了真实项目里的 while True，\n"
                       "      让你能说清「跑多少轮就停」。")
    if len(参数) < 3:
        return False, (f"「循环监测」还缺一个参数（现在只有 {参数}）。\n"
                       "      检查会这样调用它：循环监测(派, 5, 路径)\n"
                       "      所以签名应该是：\n"
                       "          def 循环监测(派, 轮数, 路径, 上限=30.0):")
    return True, f"循环监测(派, 轮数, 路径, 上限) 是个函数 —— 参数：{参数}"


def CHECK_能调用不报错(答案):
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误
    派, 备注 = _跑(函数, 1)
    if 备注:
        return False, 备注
    return True, "调用 循环监测(派, 1, 路径) 没有报错"


def CHECK_处理了指定轮数(答案):
    """★ 本课的核心检查：跑 N 轮，就该留下 N 条记录。

    怎么验：调用 循环监测(派, 5, 路径)，数文件里的行数。
    只处理一轮就结束（return 写在循环里、忘了写循环、
    某一步忘了缩进）都会露出来 —— 行数会停在 1。

    为什么这条最重要：一个"只读一次就退出"的监测程序，
    在真实世界里等于**没装**。它开始的那一刻是对的，
    之后再也不看第二眼。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    轮数 = 5
    派, 备注 = _跑(函数, 轮数)
    if 备注:
        return False, 备注

    内容 = 派.读文件(路径)
    行数 = _行数(内容)

    if 行数 == 0:
        return False, ("跑完了，但文件里一条记录都没有。\n"
                       "      每一轮都要记一次（第 03 课学的 派.写文件）：\n"
                       "          for 第几轮 in range(轮数):\n"
                       "              温度 = 派.温度.读()\n"
                       "              派.写文件(路径, f\"{派.时间},{温度}\\n\")\n"
                       "              派.时间推进(1.0)")
    if 行数 == 1 and 轮数 > 1:
        return False, (
            f"让程序转 {轮数} 轮，文件里却只有 **1 条**记录 —— 只处理了一轮就结束了。\n"
            f"      文件内容：\n          {内容.strip()!r}\n"
            "      也就是说：程序启动的那一刻看了一次温度，然后再也没看第二眼。\n"
            "      真实世界里这等于**没装**这个监测器。\n"
            "      三个常见原因，对号入座：\n"
            "        ① return 写在循环**里面** → 第一轮就收工了：\n"
            "               for ...:\n"
            "                   ...\n"
            "                   return ...        # ← 错，return 要在循环外面\n"
            "        ② 根本没写循环，只写了一轮的动作。\n"
            "        ③ **缩进漏了** —— 记录那一行没缩进进 for 里面，\n"
            "           所以只有最后一次的动作生效。这种最隐蔽，\n"
            "           代码看起来完全正常，一定要数一数缩进。")
    if 行数 != 轮数:
        return False, (f"让它转 {轮数} 轮，文件里却有 {行数} 条记录。\n"
                       f"      **每轮记一条**，所以应该正好 {轮数} 条。\n"
                       f"      文件内容：\n          {内容.strip()!r}\n"
                       + ("      多了说明一轮里记了不止一次（是不是把记录写在循环里又写了一遍？）\n"
                          if 行数 > 轮数 else
                          "      少了说明有的轮次没有记录 —— 检查记录那一行的缩进，\n"
                          "      以及是不是写在某个 if 里面（只在报警时才记？\n"
                          "      正常的时候也必须记，否则你永远不知道什么时候开始不正常的）。\n"))

    return True, f"转了 {轮数} 轮 → 文件里正好 {轮数} 条记录，一轮都没少"


def CHECK_读取次数跟着轮数走(答案):
    """★ 另一条核心检查：读引脚的动作次数也要等于轮数。

    为什么单独查这个：文件里的条数可能"看起来对"，
    但程序未必真的读了那么多次（比如把一个读数复制了 5 遍）。
    板子的操作日志是**硬件层面**的证据 ——
    每一次真的读了引脚、写了引脚，都会在上面留一行。这条把"假装读了"挡住。

    怎么数：只数日志里带 GPIO 或"写入"的行（那是真正的硬件/文件动作），
    不数"设为输出"这类一次性配置，也不数任何将来可能加进来的提示行。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    轮数 = 4
    派, 备注 = _跑(函数, 轮数)
    if 备注:
        return False, 备注

    动作 = [l for l in 派.日志 if ("GPIO" in l and ("高" in l or "低" in l))
            or "写入" in l]
    if len(动作) >= 轮数:
        return True, (f"转了 {轮数} 轮，板子日志上有 {len(动作)} 条真实动作 —— "
                      f"程序真的动了 {轮数} 次")

    return False, (
        f"转了 {轮数} 轮，板子的操作日志上只有 {len(动作)} 条动作 —— 少了。\n"
        f"      日志内容：\n          {派.日志文本()}\n"
        "      日志是**硬件层面**的证据：每读一次引脚、每写一次引脚都会留一行。\n"
        "      次数不够说明有的轮次根本没执行到那一步，最常见的就是缩进 ——\n"
        "      只有最后一行没缩进，它就只跑一次：\n"
        "          for 第几轮 in range(轮数):\n"
        "              温度 = 派.温度.读()      # ← 缩进在循环里\n"
        "          派.时间推进(1.0)            # ← 没缩进！这一句只跑一次")


def CHECK_轮数真的起作用(答案):
    """轮数参数必须真的控制循环次数，不能写死。

    怎么验：同一个函数，跑 3 轮和跑 6 轮各一次，记录条数必须不同
    （而且分别是 3 和 6）。
    "写死"的实现（for 第几轮 in range(5) 或者 while True 但被别的东西打断）
    两次的条数会一样。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    派小, 备注 = _跑(函数, 3)
    if 备注:
        return False, 备注
    派大, 备注 = _跑(函数, 6)
    if 备注:
        return False, 备注

    小 = _行数(派小.读文件(路径))
    大 = _行数(派大.读文件(路径))

    if 小 == 大:
        return False, (
            f"传 3 轮得到 {小} 条记录，传 6 轮也得到 {大} 条 —— **两次一样**。\n"
            "      说明循环次数不是由 轮数 决定的，而是写死了，比如：\n"
            "          for 第几轮 in range(5):      # ← 5 写死了，传进来的 轮数 没用\n"
            "      改法：用参数当循环次数：\n"
            "          for 第几轮 in range(轮数):\n"
            "      这个参数就是真实项目里 while True 的替身：\n"
            "      真实设备上那个循环是永远不停的，模拟器里用一个「跑几轮」的数替它，\n"
            "      检查才能知道你到底转了几圈。")
    if (小, 大) != (3, 6):
        return False, (f"传 3 轮得到 {小} 条，传 6 轮得到 {大} 条 —— 条数不对。\n"
                       "      每轮记一条，所以应该正好是 3 和 6。\n"
                       "      顺便检查一下每一轮是不是**只**记了一条。")

    return True, "传 3 轮得到 3 条、传 6 轮得到 6 条 —— 轮数真的在控制循环"


def CHECK_时间在往前走(答案):
    """长时间运行必须有节奏：每轮之间时间要推进。

    没有时间推进的程序会全速空转 —— 真实世界里这意味着 CPU 占满、
    日志爆掉、SD 卡很快写坏。

    怎么验：跑 5 轮之后，派.时间 至少应该是 5 秒（每轮 1 秒）。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    轮数 = 5
    派, 备注 = _跑(函数, 轮数)
    if 备注:
        return False, 备注

    if 派.时间 >= 轮数:
        return True, f"转了 {轮数} 轮，模拟时间走到了 {派.时间} 秒 —— 每轮之间有节奏"

    return False, (
        f"转了 {轮数} 轮，但模拟时间只走到了 {派.时间} 秒 —— 几乎没有等待。\n"
        "      真实程序这样写就是**全速空转**：一秒能读几万次温度，\n"
        "      CPU 占满、日志文件几小时涨到几个 G、SD 卡很快写坏（第 03 课那个坑）。\n"
        "      每轮之间让时间走一点：\n"
        "          派.时间推进(1.0)      # 相当于 time.sleep(1)\n"
        "      真实项目里「多久读一次」是个设计决定：\n"
        "        温室温度一分钟一次就够，振动和声音可能要每秒几千次。\n"
        "      读太快 = 数据垃圾多、卡损耗快；读太慢 = 错过真正的事件。\n"
        "      （真实代码里该用 time.sleep()，它还会把 CPU 让给系统里别的程序。）")


def CHECK_超标会报警(答案):
    """报警这条线也要真的工作：一直很热的话必须报警。

    怎么验：读数固定给 42°C（远超 30 的上限），跑 3 轮，
    日志里必须出现"把报警灯拉高"这一步。

    为什么放在第 04 课：一个跑一整个夏天的监测程序，
    **如果它不会报警，那它跑着也没人知道出事了** ——
    长期运行的价值就在于"出事的时候有人在管"。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    派, 备注 = _跑(函数, 3, 读数=42.0)
    if 备注:
        return False, 备注

    日志 = 派.日志文本()
    if "GPIO 17 ← 高" in 日志:
        return True, "读数 42°C 时报警灯被点亮了 —— 超标真的会报警"

    return False, (
        "读数一直给的是 42°C（远超 30 的上限），但报警灯从来没有被点亮。\n"
        f"      板子的操作日志：\n          {日志}\n"
        "      循环里要有判断这一步：\n"
        "          温度 = 派.温度.读()\n"
        "          if 温度 > 上限:\n"
        "              led.亮()                 # 报警\n"
        "          else:\n"
        "              led.灭()                 # 正常时记得关掉\n"
        "      灯要用 派.接LED(17) 拿（或者先把引脚设成输出再写）。\n"
        "      ⚠ 正常时一定要把它灭掉 —— 程序结束不会自动复位引脚，\n"
        "        报警解除了灯还亮着，人就会一直以为还在出事。")
