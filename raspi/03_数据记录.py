路径 = "/home/pi/温度记录.csv"


def _新派(读数为: float = 22.0):
    """一块干净的模拟树莓派，带一个温度传感器和一个光线传感器。

    两个传感器是为了验证「传感器是参数传进来的」——
    同一个 记录一次 应该两个都能记。
    """
    from learncode.raspi import 树莓派
    派 = 树莓派(名字="模拟树莓派")
    派.加传感器("温度", "°C", (0.0, 50.0), 读数为)
    派.加传感器("光线", "lux", (0.0, 1000.0), 300.0)
    return 派


def _取函数(答案):
    if not hasattr(答案, "记录一次"):
        return None, ("还没有定义「记录一次」函数。\n"
                      "      写法：\n"
                      "          def 记录一次(派, 传感器, 路径):\n"
                      "              读数 = 传感器.读()\n"
                      "              ...")
    if not callable(答案.记录一次):
        return None, "「记录一次」存在，但它不是函数。要用 def 定义。"
    return 答案.记录一次, ""


def _记一轮(函数, 派, 传感器, 路径=路径):
    """调一次学生的 记录一次，返回错误说明（空 = 成功）。"""
    try:
        函数(派, 传感器, 路径)
    except TypeError as e:
        return ("调用 记录一次(派, 传感器, 路径) 时参数不对：" + str(e) + "\n"
                "      它应该接收**三个**参数，顺序是：派、传感器、路径：\n"
                "          def 记录一次(派, 传感器, 路径):")
    except Exception as e:                            # noqa: BLE001
        return (f"调用 记录一次(派, 传感器, 路径) 时出错了：{type(e).__name__}: {e}\n"
                "      常见原因：传感器参数没接收（写成 派.温度 了）、\n"
                "      或者往文件里写的不是字符串（数字要先转成文字）。")
    return ""


def _行数(文本: str) -> int:
    return len([l for l in 文本.splitlines() if l.strip()])


def _数字们(文本: str) -> list[float]:
    """把一行文字里的所有数字抠出来。用来验证"记录里真的有读数"。"""
    import re
    出 = []
    for m in re.finditer(r"-?\d+(?:\.\d+)?", 文本):
        try:
            出.append(float(m.group()))
        except ValueError:                            # noqa: BLE001
            pass
    return 出


def CHECK_函数存在(答案):
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误
    try:
        import inspect
        参数 = list(inspect.signature(函数).parameters)
    except Exception:                                 # noqa: BLE001
        return True, "记录一次 是个函数"
    if len(参数) < 3:
        return False, (f"「记录一次」现在只接收 {len(参数)} 个参数（{参数}）。\n"
                       "      它需要三个：派、传感器、路径：\n"
                       "          def 记录一次(派, 传感器, 路径):\n"
                       "      为什么传感器要当参数：这样同一个函数既能记温度、\n"
                       "      也能记光线、湿度、土壤 —— 有几个传感器都不用复制代码。")
    return True, f"记录一次(派, 传感器, 路径) 是个函数 —— 参数：{参数}"


def CHECK_能调用不报错(答案):
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误
    派 = _新派()
    错误 = _记一轮(函数, 派, 派.温度)
    if 错误:
        return False, 错误
    if 派.读文件(路径) == "":
        return False, ("函数跑完了，但文件是**空的** —— 什么都没记下来。\n"
                       "      记录的动作是 派.写文件(路径, 内容)，别只 print 出来。\n"
                       "      注意内容要是**字符串**，数字得先转："
                       "派.写文件(路径, f\"{派.时间},{读数}\\n\")")
    return True, f"调用没有报错，文件里出现了 1 条记录：{派.读文件(路径)!r}"


def CHECK_是追加不是覆盖(答案):
    """★ 本课的核心检查之一：连着记 3 次，文件里必须**有 3 条**。

    怎么验：数非空行数。覆盖式写法只会留下最后一条 —— 行数是 1。
    那不是"记录"，那是"最后一次快照"：中间发生过的全丢了。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    派 = _新派()
    try:
        for 值 in (20.0, 25.5, 31.0):
            派.温度.设为(值)
            错误 = _记一轮(函数, 派, 派.温度)
            if 错误:
                return False, 错误
    except Exception as e:                            # noqa: BLE001
        return False, f"记录过程中出错了：{type(e).__name__}: {e}"

    内容 = 派.读文件(路径)
    行数 = _行数(内容)

    if 行数 == 0:
        return False, ("记了 3 次，文件里还是空的。\n"
                       "      每一轮都要真的往文件里写一次：\n"
                       "          派.写文件(路径, f\"{派.时间},{读数}\\n\")\n"
                       "      写成一行就够 —— 第 04 课要靠「行数」来数记录条数。")
    if 行数 == 1:
        return False, (
            "记了 3 次，文件里却只有 **1 行** —— 你把前面的记录覆盖掉了。\n"
            f"      文件现在的内容：\n          {内容!r}\n"
            "      记录数据必须**追加**（新内容接在后面），不能覆盖：\n"
            "        · 覆盖 → 不管跑多久，文件里永远只有**最后一条**。\n"
            "          跑了 24 小时得到 1 行数据，温度什么时候开始升高的？\n"
            "          不知道 —— 中间的全被抹掉了。那这个记录仪等于没装。\n"
            "        · 追加 → 每一条都在，按时间排好。跑得越久数据越值钱。\n"
            "      模拟器里 派.写文件() 本来就是追加语义，等于真实的 open(路径, \"a\")。\n"
            "      ⚠ 真实代码里最常见的错法是把 open(路径, \"w\") 写在循环里面 ——\n"
            "        那样每次循环都清空一次文件，和追加正好相反。")
    if 行数 < 3:
        return False, (f"记了 3 次，文件里只有 {行数} 行 —— 每次调用应该正好追加 1 行。\n"
                       f"      文件内容：\n          {内容!r}")
    if 行数 > 3:
        return False, (f"记了 3 次，文件里却有 {行数} 行 —— 一次调用写多了。\n"
                       "      一次调用写**一行**（行尾一个 \\n）：\n"
                       "          派.写文件(路径, f\"{派.时间},{读数}\\n\")")

    return True, f"记了 3 次 → 文件里正好 3 行，一条都没丢"


def CHECK_顺序是对的(答案):
    """记录必须**按发生顺序**排：文件第一行就是第一次记的那条。

    怎么验：三次的读数故意给成 20.0 → 25.5 → 31.0（递增）。
    文件里的数字也必须是递增的；如果反了，说明你在前面插入，
    或者把整份文件读出来重排了 —— 正常情况下就是往后接。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    派 = _新派()
    顺序 = (20.0, 25.5, 31.0)
    try:
        for 值 in 顺序:
            派.温度.设为(值)
            错误 = _记一轮(函数, 派, 派.温度)
            if 错误:
                return False, 错误
    except Exception as e:                            # noqa: BLE001
        return False, f"记录过程中出错了：{type(e).__name__}: {e}"

    行 = [l for l in 派.读文件(路径).splitlines() if l.strip()]
    if len(行) < 3:
        return False, f"文件里只有 {len(行)} 行，先让它能记满 3 条再看顺序。"

    # 只比较每一行里的读数：读数是我们给的，不会跟时间戳混
    每行读数 = []
    for l in 行[:3]:
        数 = _数字们(l)
        每行读数.append(数)

    是正序 = all(每行读数[i] and 每行读数[i][-1] == 顺序[i] for i in range(3))
    if 是正序:
        return True, ("三个读数 20.0 → 25.5 → 31.0 按顺序落到了第 1、2、3 行 —— "
                      "顺序正确")
    return False, (
        "文件里的顺序不对：读数是按 20.0 → 25.5 → 31.0 给的，\n"
        "      按理说第 1 行放 20.0、第 2 行放 25.5、第 3 行放 31.0。\n"
        f"      实际每一行里的数字：{每行读数}\n"
        f"      文件内容：\n          {派.读文件(路径)!r}\n"
        "      正常做法是每轮往**末尾**追加一行，顺序自然是时间顺序：\n"
        "          派.写文件(路径, f\"{派.时间},{读数}\\n\")\n"
        "      不要去读整个文件、重排、再整份写回去 —— 那样文件一大就慢得不能用了，\n"
        "      而且中间断电会丢掉全部数据。")


def CHECK_记录里真的有读数(答案):
    """★ 本课的另一个核心检查：记下来的必须是**当时的读数**，不是写死的字。

    怎么验：三次给 20.0 / 25.5 / 31.0。
    文件里必须能找到这三个数（26.5 这种自己不可能是时间戳的数字）。
    "写死"的实现（比如每次都写 "温度正常" 或者时间戳以外的一个常数）
    会出现"三次记的一模一样"→ 抓。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    派 = _新派()
    给的 = (20.0, 25.5, 31.0)
    try:
        for 值 in 给的:
            派.温度.设为(值)
            错误 = _记一轮(函数, 派, 派.温度)
            if 错误:
                return False, 错误
    except Exception as e:                            # noqa: BLE001
        return False, f"记录过程中出错了：{type(e).__name__}: {e}"

    内容 = 派.读文件(路径)
    if not 内容.strip():
        return False, "文件是空的 —— 先让它能把记录写进去。"

    # 三次读数的"指纹"：取第二个：0.0/1.0/2.0 是时间戳也可能是第一个数，
    # 所以只在文件里找这三个特征值就够了 —— 它们不可能是时间戳。
    缺的 = [v for v in 给的 if str(v) not in 内容]
    if not 缺的:
        return True, f"20.0 / 25.5 / 31.0 三个读数都出现在文件里了：{内容.strip()!r}"

    行 = [l for l in 内容.splitlines() if l.strip()]
    一模一样 = len(行) >= 2 and len(set(行)) == 1
    if 一模一样:
        return False, (
            f"三次读数分别是 20.0 / 25.5 / 31.0，但文件里三条记录**一模一样**：\n"
            f"          {行[0]!r}\n"
            "      说明你写进去的是一个**写死的字符串**，没有把读数放进去。\n"
            "      记录仪的全部价值就在于「当时那个数是多少」 —— 记一句固定的话，\n"
            "      跑一年也分析不出任何东西。\n"
            "      改法：先把读数读进变量，再拼进字符串：\n"
            "          读数 = 传感器.读()\n"
            "          派.写文件(路径, f\"{派.时间},{读数}\\n\")")
    return False, (
        f"文件里没有找到这几个读数：{缺的}\n"
        f"      记录的内容：\n          {内容.strip()!r}\n"
        "      每一行都要带上**当时读到的那个数**：\n"
        "          读数 = 传感器.读()\n"
        "          派.写文件(路径, f\"{派.时间},{读数}\\n\")\n"
        "      ⚠ 顺便记住：真实项目里记录还会带上设备名、单位、状态，\n"
        "        但「读数 + 时间」这两样是绝对不能少的。")


def CHECK_时间在往前走(答案):
    """每条记录都该有自己的时间戳 —— 时间必须真的推进了。

    怎么验：记 3 条，文件里出现过的最大数字应该至少是 2（3 条记录之间
    至少要走过 2 个时刻）。如果时间永远是 0.0，每条记录长得一样，
    那这份数据只能告诉你"发生过"，不能告诉你"什么时候"。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    派 = _新派()
    try:
        for 值 in (20.0, 25.5, 31.0):
            派.温度.设为(值)
            错误 = _记一轮(函数, 派, 派.温度)
            if 错误:
                return False, 错误
    except Exception as e:                            # noqa: BLE001
        return False, f"记录过程中出错了：{type(e).__name__}: {e}"

    if 派.时间 <= 0:
        return False, (
            "三次记录之间时间**一步都没走**（派.时间 还是 0.0）。\n"
            "      这样三条记录的时间戳全是 0.0 —— 数据只能说「发生过」，\n"
            "      没法回答「什么时候最热」、「升温用了多久」。\n"
            "      改法：每次记完之后让时间往前走一点：\n"
            "          派.时间推进(1.0)      # 相当于 time.sleep(1)\n"
            "      真实程序里这对应 time.sleep()；模拟器里它只是把时钟往前拨，\n"
            "      所以检查能一瞬间跑完 24 小时的记录。")

    内容 = 派.读文件(路径)
    最大 = max(_数字们(内容)) if _数字们(内容) else 0.0
    if 最大 < 2.0:
        return False, (
            f"时间确实在走（现在 {派.时间}），但文件里最大的数字只有 {最大} ——\n"
            "      看起来**时间戳没有写进记录**里，每条记录只写了读数。\n"
            f"      文件内容：\n          {内容.strip()!r}\n"
            "      带上时间，一行一个时刻：\n"
            "          派.写文件(路径, f\"{派.时间},{读数}\\n\")\n"
            "      一条没有时间的温度记录就是一个孤零零的数字 —— 没法画曲线、\n"
            "      没法算平均、没法找规律。")

    return True, (f"时间推进到了 {派.时间}，记录里能看到时间戳 —— "
                  f"每条数据都带着「什么时候」")


def CHECK_传感器是参数不是写死的(答案):
    """记录函数必须记"传进来的那个传感器"，而不是写死 派.温度。

    为什么考这个：同一个程序要记温度、湿度、光线、土壤……
    如果函数里写死 派.温度，你有几个传感器就得复制几份一模一样的函数。
    参数化的写法，一份就够。

    怎么验：传一个 300.0 的光线传感器进去，看文件里有没有 300.0。
    """
    函数, 错误 = _取函数(答案)
    if 函数 is None:
        return False, 错误

    派 = _新派()
    错误 = _记一轮(函数, 派, 派.光线)
    if 错误:
        return False, 错误

    内容 = 派.读文件(路径)
    if "300" in 内容:
        return True, f"传光线传感器进去，记下来的是光线读数（300.0）：{内容.strip()!r}"
    return False, (
        f"传进去的是**光线**传感器（读数 300.0lux），但文件里记的是：{内容.strip()!r}\n"
        "      看起来函数里写死了 派.温度，没用传进来的那个 传感器 参数。\n"
        "      改法（读取那一行用参数）：\n"
        "          读数 = 传感器.读()        # ← 用参数，别写 派.温度\n"
        "      这样同一个函数既能记温度、也能记光线、湿度、土壤 —— 不用改代码。\n"
        "      第 05 课的温室监测器就要同时记好几样东西，到时候你会庆幸这么写了。")
