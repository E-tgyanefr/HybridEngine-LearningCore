# 第 03 课：把数据记下来 —— 追加，而不是覆盖

# 要做：
#   写一个函数 记录一次(派, 传感器, 路径)，做这四件事：
#
#     1. 读一次当前读数：  读数 = 传感器.读()
#        （注意：传感器是**参数传进来的**，不是 派.温度 —— 这样这个函数
#          既能记温度，也能记光线、湿度，不用改一行代码）
#
#     2. 把这一条记到 路径 这个文件里，一条**占一行**，行尾加 "\n"。
#        这一行里要包含两样东西：
#            · 当时的时间  → 派.时间          （单位：秒）
#            · 刚才的读数  → 上一行读出来的那个数
#        格式随你定，例如：  f"{派.时间},{读数}\n"
#
#     3. 写文件用 **派.写文件(路径, 内容)**，它本身就是**追加**的 ——
#        调几次，文件里就有几行。这是这一课的重点，下面细讲。
#
#     4. 让时间往前走一点：派.时间推进(1.0)  （相当于 time.sleep(1)）
#        不推进时间的话，每条记录的时间戳都是 0.0 —— 数据就没法看了。
#
#   检查会这样验你：**连着调 3 次**，读数故意给成 20.0 → 25.5 → 31.0，
#   然后看文件里是不是**三行**、三行的内容是不是真的跟着那三个读数变。
#
#   两种典型的错法都会被抓：
#     · 覆盖着写 → 文件里只剩最后一条（等于把历史全丢了）
#     · 写死的字符串 → 三次记的内容一模一样，跟读数没关系

# ─────────────────────────────────────────────────────
#  发生了什么：程序第一次有了"记忆"
# ─────────────────────────────────────────────────────
#
# 前两课的程序都是**一跑完就什么都不剩**的：
# 读完温度、判断完、返回一句话，然后进程结束，一切归零。
# 你没法回答"昨天晚上最热的时候是几度"—— 因为那个数从来没被留下。
#
# 树莓派最大的优势就在这里：**它是一台完整的 Linux 小电脑，
# 有磁盘、有文件系统、有网络。** 单片机想把数据留下来要额外接一个 SD 卡模块、
# 还要自己写 FAT 文件系统的驱动；树莓派上就是一句 open() 的事。
#
# 这也是"小电脑思维"和"嵌入式思维"的第一个分水岭：
#     单片机思维：数据在内存里，断电就没了
#     树莓派思维：数据落盘 —— 文件、数据库、发到服务器
#
# ─────────────────────────────────────────────────────
#  你写的是什么：一条"追加"的日志
# ─────────────────────────────────────────────────────
#
# 打开文件写东西有两种模式，差别巨大：
#
#     覆盖（w）   把文件清空，从零开始写
#     追加（a）   保留原来的内容，新内容接在**后面**
#
# 记录数据必须用追加，理由很直白：
#
#     覆盖 →  文件里永远只有**最后一条**记录。
#             跑了 24 小时，你得到 1 行数据。
#             温度是什么时候开始升高的？不知道 —— 中间全被抹掉了。
#
#     追加 →  文件里有**每一条**记录，按时间排好。
#             跑的越久，数据越值钱。这才是"记录"这个词的意思。
#
# 打个比方：覆盖像是每写一条新日记就把整本日记本撕掉重写，
# 追加才是在本子后面接着写。
#
# 模拟器里 派.写文件() 就是**追加**语义 —— 和真实世界里
# `open(路径, "a")` 一样。所以你只要老老实实每轮都调一次，
# 记录自然就一条条攒起来了。
#
# ⚠ 一个真会咬人的坑：**每轮都重新打开文件**。
#   真实代码里正确的写法是：
#
#       打开 = open(路径, "a", encoding="utf-8")   # 循环**外面**打开一次
#       for ...:
#           打开.write(...)
#       打开.close()
#
#   如果你把 open(..., "w") 写在循环里面，那每次都会清空一次 ——
#   跟"追加"完全相反。这是新手写数据记录仪最爱犯的错。
#
# ─────────────────────────────────────────────────────
#  应该怎么写：三个新东西
# ─────────────────────────────────────────────────────
#
# ① 写文件 / 读文件
#
#     派.写文件("/home/pi/温度记录.csv", "0.0,22.5\n")   # 追加
#     派.读文件("/home/pi/温度记录.csv")                 # 把内容整个读回来
#
#   读文件是给你自己**验证**用的：写完一个程序，
#   最该做的一件事就是把文件读回来看一眼对不对。
#   检查也是这么做的。
#
# ② 时间推进
#
#     派.时间推进(1.0)      # 相当于 time.sleep(1)：模拟过了 1 秒
#     派.睡(1.0)            # 同一个东西，名字更像 Python
#
#   为什么要模拟时间而不是真的 sleep：
#     · 真的 sleep 会让检查跑得很慢（记 100 条要等 100 秒）
#     · 而且"时间"是数据的一部分 —— 没有时间戳的记录几乎没有价值
#
#   真实程序里对应的是 time.time()（拿当前时间）和 time.sleep()（等一会儿）。
#
# ③ 时间戳：记录必须带上"什么时候"
#
#     一条没有时间的温度记录 = 一个孤零零的数字，没法分析。
#     有了时间戳才能画曲线、算平均值、找"每天下午两点最热"这种规律。
#
#   真实项目里通常记成 ISO 格式："2026-05-01T14:32:01,38.5"
#   （可读、可排序、各种工具都认）。模拟器里时间是从 0.0 开始的秒数。
#
# ─────────────────────────────────────────────────────
#  顺便记住什么：CSV 和"写盘会磨损 SD 卡"
# ─────────────────────────────────────────────────────
#
# ① 为什么数据记录常用 CSV（逗号分隔）
#       0.0,22.5
#       1.0,25.1
#       2.0,31.0
#    它就是一个纯文本表格：Excel 能直接打开、Python 两行就能读、
#    出问题用记事本就能看。新手项目里 CSV 几乎永远是最好的选择。
#    （真实项目里更讲究的是 JSON Lines 或者数据库，但那是后面的事。）
#
# ② ⚠ 树莓派上"频繁写盘"是个真问题
#    这一点和单片机完全不同，值得单独记住：
#    树莓派跑在 **SD 卡**上，而 SD 卡有写入寿命（每个存储块能擦写多少次是有限的）。
#    一个每 0.1 秒就往文件里写一行的程序，跑几个月就可能把卡写坏 ——
#    而且坏起来常常是**整张卡读不出来**，系统都没了。
#
#    真实项目的做法：
#      · 降低写入频率（几秒、几分钟一条，按需要来）
#      · **先在内存里攒着，攒够一批再一次性写盘**
#      · 用 `log2ram` 之类的工具把日志放到内存里，定时再落盘
#      · 重要的长期数据发到别的机器上（树莓派只负责采）
#
#    这一课每轮都写一次是为了让你看清"追加"这件事；
#    等你自己做真项目的时候，记住"别写太勤"。
#
# ─────────────────────────────────────────────────────
#  ⚠ 模拟器验证不了电路（也验证不了真的文件系统）
# ─────────────────────────────────────────────────────
#
# 这里的"文件"只是内存里的一个替身 —— 它没有真正的磁盘、没有权限、
# 没有磁盘满了这回事。所以下面这些**模拟器全都发现不了**：
#
#   · **限流电阻** —— 这一课如果顺手接报警灯，LED 那 220Ω~1kΩ 一个都不能省
#   · **接线位置** —— 传感器接在哪几个排针上、LED 正负极有没有接反，只有你知道
#   · **I2C 地址冲突** —— 温湿度、气压、OLED 这些设备都挂在同一根 I2C 总线上，
#     地址撞了就会互相打架：读数时好时坏、甚至读到别的设备的数据。
#     上电前用 `i2cdetect -y 1` 扫一遍最省事。
#   · **传感器型号差异** —— 这一课统一用 读()，真实世界是 DHT11 要按时序读、
#     DS18B20 走单总线、BMP280 要先算补偿公式。换型号时改的是"读取那一行"，
#     "记录"这一段逻辑不用动。
#   · 还有真文件系统的那一堆：路径写错、没有写权限、
#     磁盘满了、SD 卡坏了 —— 真实项目里这些都会发生，要处理。
#
