# 一次性的修补：把课程里「引号插在中文中间」的地方换成「」。
#
# ⚠ 为什么不批量跑：自动批处理会**跨字符串边界**误伤（我在第 14 课和别人的课上
#   就是这么弄坏了两处，靠 git checkout 才恢复）。这个脚本只改**列出来的**那几处。
import io
import os

根 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

补 = [
    ("第39课_图与遍历.cs", [
        ('连通块 = "互相能走到"的最大一堆点', '连通块 = 「互相能走到」的最大一堆点'),
        ('不标记"到过"的写法会在这里转不停', '不标记「到过」的写法会在这里转不停'),
        ('到不了的点不算"最远"。', '到不了的点不算「最远」。'),
    ]),
    ("第40课_最短路.cs", [
        ('这一条同时也在验"不许打表"。', '这一条同时也验「不许打表」。'),
        ('这一课要学的就是"用堆挑最小"。', '这一课要学的就是「用堆挑最小」。'),
    ]),
    ("第35课_DFS与BFS.cs", [
        ('走(图, i, 到过, 废);      // 只借它标记"到过"', '走(图, i, 到过, 废);      // 只借它标记「到过」'),
    ]),
]

for 名, 对 in 补:
    路径 = os.path.join(根, "csharp", "cs-lessons", "Lessons", 名)
    t = io.open(路径, encoding="utf-8").read()
    for 旧, 新 in 对:
        if 旧 not in t:
            print("!! 没找到：%s  %s" % (名, 旧[:40]))
            continue
        t = t.replace(旧, 新)
    io.open(路径, "w", encoding="utf-8", newline="").write(t)
    print("修好 %s" % 名)
