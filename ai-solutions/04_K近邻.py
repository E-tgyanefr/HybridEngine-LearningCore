def 距离(a, b):
    """欧氏距离 = 勾股定理的推广。

    ⚠ 用 zip 配对，别写死 a[0]、a[1] —— 两个特征、三个特征、
      一百个特征，这段代码都不用改。
    ⚠ 别忘了开根号（** 0.5）。忘了它排序结果**大多时候**还是对的，
      但距离的大小就没意义了，以后想按距离加权时会全错。
    """
    平方和 = 0.0
    for p, q in zip(a, b):
        平方和 += (p - q) ** 2
    return 平方和 ** 0.5


def 找邻居(训练集, 查询点, k):
    """算出所有训练点的距离，排队，取前 k 个。

    返回 [(点, 标签), ...]，按距离从近到远。
    """
    带距离 = [(距离(点, 查询点), 点, 标签) for 点, 标签 in 训练集]
    带距离.sort(key=lambda t: t[0])          # 排序用标准库就够了，不必手写
    return [(点, 标签) for _d, 点, 标签 in 带距离[:k]]


def 分类(训练集, 查询点, k):
    """让最近的 k 个邻居投票。

    ⚠ 只能**数票**，不能求和/求平均 —— 标签可能是文字（"好瓜"/"坏瓜"）。
    """
    邻居 = 找邻居(训练集, 查询点, k)
    if not 邻居:
        return None
    票数 = {}
    for _点, 标签 in 邻居:
        票数[标签] = 票数.get(标签, 0) + 1
    return max(票数, key=票数.get)            # 平票时给先遇到的那个，课程允许


def 准确率(训练集, 测试集, k):
    """判对几个 ÷ 总共几个。

    ⚠ 分母是**测试集**的长度，不是训练集 ——
      用训练集考 KNN（k=1）永远是 100%，因为最近的邻居就是它自己。
    """
    if not 测试集:
        return 0.0
    对 = 0
    for 点, 正确标签 in 测试集:
        if 分类(训练集, 点, k) == 正确标签:
            对 += 1
    return 对 / len(测试集)
