"""第 01 课的参考答案。

三个函数对应"学习"的三件事：用模型（预测）、评模型（误差）、学模型（拟合）。
"""


def 预测(直线, x):
    """直线是 (斜率, 截距)，这里只是把它用在某个 x 上。"""
    斜率, 截距 = 直线
    return 斜率 * x + 截距


def 误差平方和(xs, ys, 直线):
    """给这条线打分：每个点错多少，平方，加起来。越小越好。"""
    总误差 = 0.0
    for x, y in zip(xs, ys):
        差 = 预测(直线, x) - y       # 预测值 - 真实值，有正有负
        总误差 += 差 ** 2            # 平方之后一定是正的，不会互相抵消
    return 总误差


def 拟合(xs, ys):
    """最小二乘：直接算出最好的那条线。

    两条直觉（推不出来时就想这两句）：
      ① 最好的线穿过平均点 (平均x, 平均y)
      ② 斜率 = x 和 y "一起变的程度" ÷ "x 自己变的程度"
    """
    n = len(xs)
    平均x = sum(xs) / n
    平均y = sum(ys) / n

    分子 = 0.0        # Σ dx·dy —— 一起变的程度
    分母 = 0.0        # Σ dx·dx —— x 自己变的程度
    for x, y in zip(xs, ys):
        dx = x - 平均x
        dy = y - 平均y
        分子 += dx * dy
        分母 += dx * dx

    斜率 = 分子 / 分母
    截距 = 平均y - 斜率 * 平均x       # 由直觉①倒推出来
    return 斜率, 截距
