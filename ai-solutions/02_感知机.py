def 阶跃(z):
    """放电开关：到门槛就 1，没到就 0。"""
    return 1 if z >= 0 else 0


def 预测(权重, 偏置, 输入):
    """加权求和，再过开关。

    用循环写，不用 sum()：以后输入有一百个特征，这三行一个字都不用改。
    """
    总分 = 偏置
    for i in range(len(输入)):
        总分 += 权重[i] * 输入[i]
    return 阶跃(总分)


def 训练(数据, 标签, 学习率=0.1, 最多轮数=100):
    """反复看数据，判错就改参数。返回 (权重, 偏置)。

    更新规则的直觉：**错在哪儿就往哪儿推一把。**
      误差 = 正确标签 - 预测值  只有 0 / +1 / -1 三种取值
        · 判对了（误差 0）→ 什么都不改，对的别动
        · 该说 1 却说 0（误差 +1）→ 权重变大、门槛降低，下次更容易说 1
        · 该说 0 却说了 1（误差 -1）→ 反过来
      乘 输入[i] 是因为**没投票的输入不该背锅**：输入是 0 的项乘出来还是 0。
    """
    权重 = [0.0] * len(数据[0])
    偏置 = 0.0

    for _轮 in range(最多轮数):
        这一轮错了几个 = 0
        for 输入, 正确标签 in zip(数据, 标签):
            判断 = 预测(权重, 偏置, 输入)
            误差 = 正确标签 - 判断
            if 误差 == 0:
                continue
            这一轮错了几个 += 1
            for i in range(len(权重)):
                权重[i] += 学习率 * 误差 * 输入[i]
            偏置 += 学习率 * 误差
        if 这一轮错了几个 == 0:
            break          # 全对了 —— 数据线性可分时这一天一定会来

    return 权重, 偏置
