def 数值梯度(函数, x, 步长=1e-5):
    """用中心差分估斜率：往前看一步、往后看一步，两边的偏差互相抵消大半。

    ⚠ 分母是 2 * 步长。漏掉那个 2 是这一课最常见的错，结果正好差一倍。
    ⚠ 步长别取太小（比如 1e-20）：x+步长 会和 x 变成同一个浮点数，结果算出来是 0。
    """
    return (函数(x + 步长) - 函数(x - 步长)) / (2 * 步长)


def 梯度下降(函数, 起点, 学习率=0.1, 步数=100):
    """闭着眼睛下山：摸一下最陡的方向，往反方向迈一小步，重复。

    返回**每一步**的 x（第一个是起点）—— 只看终点看不出"稳稳走到底"
    和"来回横跳"的区别，把过程留下来才看得见。
    """
    x = 起点
    脚印 = [x]
    for _ in range(步数):
        x = x - 学习率 * 数值梯度(函数, x)     # 减：梯度指向上坡，我们要下坡
        脚印.append(x)
    return 脚印
