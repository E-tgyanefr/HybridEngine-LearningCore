def 判(out, 期望):
    """返回 (是否被拒, 全过?, 命中的 ✗ 行, ✓ 数, ✗ 数)。判据见文件头。"""
    行 = [l.strip() for l in out.splitlines()]
    全过 = any("全部通过" in l for l in 行)
    叉 = [l for l in 行 if l.startswith("✗")]
    勾 = [l for l in 行 if l.startswith("✓")]
    命中 = [l for l in 叉 if 期望.strip() in l]
    return (not 全过) and bool(命中) and (len(勾) + len(叉) > 0), 全过, 命中, len(勾), len(叉)


