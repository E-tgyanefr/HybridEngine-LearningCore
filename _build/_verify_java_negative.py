def 校验表():
    问题 = []
    if not 错例:
        问题.append("错例表是空的")
    见过 = {}
    for i, 项 in enumerate(错例):
        if len(项) != 4:
            问题.append("第 %d 项的字段数不是 4（是 %d）" % (i, len(项)))
            continue
        编, 变换, 说明, 期望 = 项
        if not (len(编) == 2 and 编.isdigit()):
            问题.append("第 %d 项的课号不是两位数字：%r" % (i, 编))
            continue
        if 编 in 见过:
            问题.append("课号 %s 出现了两次（一课只留一条，账本才不会重复计）" % 编)
        见过[编] = True
        if not 说明.strip() or not 期望.strip():
            问题.append("%s 的「错在哪」或「期望被拒的检查名」是空的" % 编)
        if 编 not in 课程:
            问题.append("%s 在 %s 里找不到对应课程" % (编, 课程目录))
            continue
        if not 课程[编]["参考"]:
            问题.append("%s 没有参考答案，没法造错答案" % 编)
        # ⚠ 期望的检查名必须是这一课**真实存在**的检查名。
        #   这是最值钱的一条自检：抄错一个标点，这里就拦下来了，
        #   而不是等跑完 41 课才发现某一课永远对不上。
        if 期望.strip() not in [c.strip() for c in 课程[编]["检查名"]]:
            问题.append("%s 的期望检查名在课程里不存在：%r" % (编, 期望))
        if not 变换:
            问题.append("%s 的变换列表是空的" % 编)
        for t in 变换:
            if len(t) not in (2, 3):
                问题.append("%s 有一条变换的字段数不是 2 或 3：%r" % (编, t))
                continue
            旧, 新 = t[0], t[1]
            次要 = t[2] if len(t) == 3 else 1
            if not 旧:
                问题.append("%s 有一条变换的「旧」是空的" % 编)
                continue
            实际 = 课程[编]["参考"].count(旧)
            if 实际 != 次要:
                if 实际 == 0:
                    问题.append("%s 的变换在参考答案里**找不到**：%r"
                                "（教材改过了？这条变换已经失效）" % (编, 旧[:60]))
                else:
                    问题.append("%s 的变换在参考答案里出现了 %d 次，"
                                "表里写的是 %d 次：%r"
                                % (编, 实际, 次要, 旧[:60]))
            校验 = 应用变换(课程[编]["参考"], 变换)
            if 校验 == 课程[编]["参考"]:
                问题.append("%s 的变换没有真的改变参考答案（新旧一样？）" % 编)
    应有 = set("%02d" % i for i in range(41))
    缺 = sorted(应有 - set(见过))
    if 缺:
        问题.append("Java 共 41 课，错例表漏了：%s" % " ".join(缺))
    多 = sorted(set(见过) - 应有)
    if 多:
        问题.append("错例表里有超出 00~40 的课号：%s" % " ".join(多))
    return 问题


def 应用变换(参考, 变换):
    出 = 参考
    for t in 变换:
        旧, 新 = t[0], t[1]
        次要 = t[2] if len(t) == 3 else 1
        出 = 出.replace(旧, 新, 次要)
    return 出


