def 判(out):
    """(全过?, [√名字…], [×名字…])"""
    过, 叉 = [], []
    for l in out.splitlines():
        s = l.strip()
        if s.startswith("√ "):
            过.append(s[2:].strip())
        elif s.startswith("× "):
            叉.append(s[2:].strip())
    return ("全部通过" in out), 过, 叉


