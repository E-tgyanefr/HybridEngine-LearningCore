def 读课(编):
    """(课文件, 参考答案, [CHECK_ 名…]) —— 全部从文件里读，不手抄。"""
    课 = [f for f in os.listdir(课目录)
          if f.startswith(编 + "_") and f.endswith(".py")]
    解 = [f for f in os.listdir(解目录)
          if f.startswith(编 + "_") and f.endswith(".py")]
    if not 课 or not 解:
        return None
    课路 = os.path.join(课目录, 课[0])
    文 = io.open(课路, encoding="utf-8").read()
    参考 = io.open(os.path.join(解目录, 解[0]), encoding="utf-8").read()
    return 课路, 参考, [m.strip() for m in _检查.findall(文)]


def 应用变换(参考, 变换):
    出 = 参考
    for t in 变换:
        旧, 新 = t[0], t[1]
        次要 = t[2] if len(t) == 3 else 1
        出 = 出.replace(旧, 新, 次要)
    return 出


