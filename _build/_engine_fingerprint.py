def 主(argv) -> int:
    到stdout = "--stdout" in argv
    含Tk = "--无Tk" not in argv
    指纹 = 生成(含Tk=含Tk)
    文本 = json.dumps(指纹, ensure_ascii=False, sort_keys=True, indent=1)
