# ══════════════════════════ 自检 与 比对（判据复用这两个）══════════════
#
# ⚠⚠ 这两个函数是**一把尺子**，所以它们自己必须被验过：
#   `tests/test_engine_fingerprint.py` 里有一组"反面验证"——
#   故意篡改 / 清空指纹，**必须**能被这两个函数报出来。
#   验不过 ⇒ 判据是假绿（这个仓栽过两次）。

def 自检(指纹: dict) -> list[str]:
    """指纹**自己有没有问题**（空 / 缺项 / 声明了却没跑到）。

    ⚠⚠ 返回**问题清单**，空列表才叫通过。
      "图元总数 0 / 场景数 0" 一律判「**没跑到**」，**不是"过了"**。
    """
    问题 = []
    if not isinstance(指纹, dict):
        return ["指纹不是字典：%r" % type(指纹).__name__]
    内容 = 指纹.get("内容") or {}
    统 = 指纹.get("统计") or {}
    if not 内容:
        问题.append("场景数 = 0 —— **没跑到**（不是「过了」）")
    if int(统.get("图元总数", 0)) <= 0:
        问题.append("图元总数 = 0 —— **没跑到**（不是「过了」）")
    if not 统:
        问题.append("没有 `统计` 一节 —— 判据没法确认自己跑到了")
    #: 声明了"该有图元"却一条都没有 ⇒ 那个场景**没跑到**
    for 名, v in sorted(内容.items()):
        if not isinstance(v, dict):
            continue
        if v.get("应有图元") and int(v.get("图元数", 0)) <= 0:
            问题.append("场景 %s 声明了「该有图元」但一条都没有 —— 没跑到" % 名)
        if v.get("应有状态") and int(v.get("状态条目数", 0)) <= 0:
            问题.append("场景 %s 声明了「该有状态」但状态是空的 —— 没跑到" % 名)
        #: 钉了"每帧应该几条"的场景，逐帧核（空场景/裁剪靠它才有意义）
        if "期望每帧图元数" in v:
            期 = int(v["期望每帧图元数"])
            for n, 得 in enumerate(v.get("实测每帧图元数", [])):
                if int(得) != 期:
                    问题.append("场景 %s 第 %d 帧图元数 %s ≠ 期望 %d"
                                % (名, n, 得, 期))
    #: ⚠ "本机能开窗但指纹里没有 Tk 数据" ⇒ 覆盖漏了一块（不是"不需要"）
    if 统.get("Tk可用") and not (内容.get("Tk后端_提交item数", {})
                                .get("Tk", {}).get("可用")):
        问题.append("本机能开 tkinter 窗口，但指纹里没有 Tk 那部分 —— 覆盖漏了")
    声明的 = [k for k, v in 内容.items()
              if isinstance(v, dict) and v.get("应有图元")]
    if 声明的 and not [k for k in 声明的
                       if int(内容[k].get("图元数", 0)) > 0]:
        问题.append("所有声明该有图元的场景都是空的 —— 没跑到")
    return 问题


def _逐条走(甲, 乙, 路, 出, 上限=40):
    """递归比对，把**第一个到第 `上限` 个**差异记进 `出`（路 = JSON 路径）。"""
    if len(出) >= 上限:
        return
    if isinstance(甲, dict) and isinstance(乙, dict):
        for k in sorted(set(甲) | set(乙)):
            if k not in 甲:
                出.append("%s.%s：只在新算的里有" % (路, k))
            elif k not in 乙:
                出.append("%s.%s：只在落盘的里有" % (路, k))
            else:
                _逐条走(甲[k], 乙[k], "%s.%s" % (路, k), 出, 上限)
        return
    if isinstance(甲, list) and isinstance(乙, list):
        if len(甲) != len(乙):
            出.append("%s：长度 %d ≠ %d" % (路, len(甲), len(乙)))
            return
        for i, (a, b) in enumerate(zip(甲, 乙)):
            _逐条走(a, b, "%s[%d]" % (路, i), 出, 上限)
        return
    if 甲 != 乙:
        出.append("%s：落盘 %r → 现算 %r" % (路, 甲, 乙))


def 比对(落盘: dict, 现算: dict, *, 上限: int = 40) -> list[str]:
    """**逐条比对**两份指纹，返回问题清单（空 = 逐条相同）。

    ⚠ 只比 `内容`（可观察行为）——
      `头` 里有 Python 版本/平台，那些变了**不代表行为变了**，
      混进来会让判据在换个 Python 小版本时**假红**。
      （但 `头` 里那两个**版本号**单独由判据核 —— 它们决定
        "是 C++ 版错了"还是"指纹本来就该更新了"。）
    """
    出 = []
    _逐条走(落盘.get("内容") or {}, 现算.get("内容") or {}, "内容", 出, 上限)
    #: 统计也是指纹的一部分（它同时是非空自检的输入）
    _逐条走(落盘.get("统计") or {}, 现算.get("统计") or {}, "统计", 出, 上限)
    return 出


def 生成(含Tk: bool = True) -> dict:
    import hybridengine_light as H
