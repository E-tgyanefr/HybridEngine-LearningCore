def 能开窗() -> tuple[bool, str]:
    try:
        import tkinter as tk
        r = tk.Tk()
        r.destroy()
        return True, ""
    except Exception as e:                                   # pragma: no cover
        return False, "%s: %s" % (type(e).__name__, e)


def Tk场景() -> dict:
    """`Tk后端` 的可观察量：**提交到画布的 item 数** + 裁剪判定网格。

    ⚠ 这段**必须在独立进程里跑**（本脚本就是独立进程）。
      仓里的教训：Tk 在"多模块共用一个解释器"时会**硬崩解释器**
      （退出码 2147483651），所以判据那边是**起子进程**跑本脚本，不自己开窗。
    """
    能, 原因 = 能开窗()
    if not 能:
        return {"可用": False, "原因": 原因}

    条 = {"可用": True, "原因": ""}
    后 = None
    try:
        后 = E.Tk后端(宽=200, 高=200, size=100, 标题="指纹-Tk")
        游戏 = E.游戏(宽=200, 高=200, 尺寸=100, 标题="指纹-Tk", 后端=后)
        for i, (x, y) in enumerate([(10.0, 10.0), (50.0, 50.0), (90.0, 90.0),
                                    (0.0, 0.0), (100.0, 100.0),
                                    (-500.0, 50.0), (50.0, -500.0),
                                    (600.0, 50.0), (50.0, 600.0),
                                    (-1.0, -1.0), (-11.0, 50.0), (111.0, 50.0),
                                    (50.0, -11.0), (50.0, 111.0)]):
            o = 游戏.场景.造("点%d" % i, x, y)
            o.加(C.圆点(半径=2.0, 颜色="红"))
        游戏.一步()
        #: ⚠ Tk 每帧 `delete("all")` 后重画 ⇒ 数的是**这一帧提交了多少 item**
        条["提交item数"] = len(后._canvas.find_all())
        条["布局对象数"] = len(list(游戏.场景.遍历()))
        条["说明"] = ("同一份坐标布局：**录制后端全记**，Tk 后端按视野裁剪 "
                      "（`允许裁剪=True`，MARGIN=10 虚拟单位外扩）")

        #: 裁剪判定网格（`_在视野内` 吃的是**屏幕坐标**）—— 边界要逐点钉。
        #: ⚠ 边界值不是猜的：MARGIN=10 虚拟单位，换算成像素是 10×(200/100)=20
        #:   ⇒ 合法屏幕区间是 **[-20, 220]**。所以网格里必须有
        #:   -20.5 / -20 / 219.5 / 220 / 220.5 这几个点 ——
        #:   只铺 -1/0/100/200 那种"安全点"是**钉不住裁剪规则的**。
        格 = []
        _x们 = (-21.0, -20.5, -20.0, -19.5, 0.0, 100.0, 200.0,
                219.5, 220.0, 220.5, 221.0)
        _y们 = (-21.0, -20.0, 0.0, 200.0, 220.0, 221.0)
        for sx in _x们:
            for sy in _y们:
                格.append([码(sx), 码(sy), 码(后._在视野内(sx, sy))])
        条["在视野内网格"] = 格
        条["在视野内网格说明"] = ("屏幕坐标 [-20, 220] 为真（MARGIN×换算比）；"
                                  "两轴必须**同时**在区间内才为真")
        条["MARGIN"] = 码(E.Tk后端.MARGIN)
        条["换算比"] = [码(后.宽 / 后.size), 码(后.高 / 后.size)]
        #: Tk 把虚拟坐标翻成屏幕像素的两个比例（两个轴各用各的）
        xy = []
        for (x, y) in [(0.0, 0.0), (50.0, 50.0), (100.0, 100.0), (25.5, 75.25)]:
            a, b = 后._xy(x, y)
            xy.append([码(x), 码(y), 码(a), 码(b)])
        条["坐标换算"] = xy
    finally:
        if 后 is not None:
            try:
                后.关闭()
            except Exception:
                pass
    return 条


