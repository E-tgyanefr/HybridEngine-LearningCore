# ══════════════════════════ 数值编码 ══════════════════════════

def 码(v):
    """把一个值编码成**精确可比**的字符串。

    ⚠ 浮点走 `float.hex()` —— 十进制会盖掉末位差异（那正是移植最危险的一类错）。
    """
    if isinstance(v, bool):
        return "真" if v else "假"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if v != v:
            return "nan"
        if v == float("inf"):
            return "+inf"
        if v == float("-inf"):
            return "-inf"
        return v.hex()
    return str(v)


def 图元码(图元) -> list[str]:
    """一条绘制指令 → 一串精确字符串（**保留原顺序**）。"""
    return [码(x) for x in 图元]


def _规范文本(帧们) -> str:
    """指纹的**规范文本形式** —— 渲染哈希就是它的 sha256。

    ⚠ 这个格式是**跨语言契约的一部分**，C++ 侧必须逐字节复现：

        每帧以 `帧 <n>\\n` 开头；每个图元一行，字段用 `\\t` 分隔，行尾 `\\n`。
    """
    出 = []
    for f in 帧们:
        出.append("帧 %d\n" % f["帧"])
        for 图元 in f["图元"]:
            出.append("\t".join(图元码(图元)) + "\n")
    return "".join(出)


def 渲染哈希(帧们) -> str:
    """对规范文本求 sha256（**同算法同输入** —— 见 `docs/C++移植-行为契约.md`）。"""
    return hashlib.sha256(_规范文本(帧们).encode("utf-8")).hexdigest()


# ══════════════════════════ 取样 ══════════════════════════

def 对象状态(场景) -> list[list[str]]:
    """**遍历顺序**（按挂载顺序，不是字典序）逐对象取样。

    ⚠ 顺序本身也是契约的一部分：C++ 侧遍历顺序不同 ⇒ 图元顺序不同。
    """
    出 = []
    for o in 场景.遍历():
        p = o.变换.位置
        w = o.世界位置
        出.append([o.名字, 码(p.x), 码(p.y), 码(w.x), 码(w.y),
                   码(o.变换.缩放), 码(o.变换.旋转), 码(o.活着),
                   str(len(o.组件们)), str(len(o.子对象))])
    return 出


def 基本取样(游戏):
    return {"对象": 对象状态(游戏.场景)}


# ══════════════════════════ 跑一个场景 ══════════════════════════

def 跑(游戏, 帧数: int, *, dt=None, 每帧前=None, 取样=基本取样,
       记录状态: bool = True) -> list[dict]:
    """跑 `帧数` 个**逻辑帧**（`游戏.一步`），逐帧记录图元与状态。

    ⚠⚠ **必须用 `一步(dt)`，不能用 `跑()`.**
      实测：`游戏.跑()` 的逻辑更新次数由**墙钟**决定
      （`累积 = min(累积 + 经过, 步长*8)`）⇒ 同一份代码在快/慢机器上
      "第 N 帧画了什么"**不一样**。它**不可**作为逐位比对的基准。
      ⇒ 契约里把 `跑()` 明确列为"允许不同"（见 docs）。
    """
    帧们 = []
    for n in range(帧数):
        if 每帧前 is not None:
            每帧前(n, 游戏)
        游戏.一步(dt)
        f = {"帧": n, "图元": [图元码(d) for d in 游戏.后端.本帧()]}
        if 记录状态:
            f["状态"] = 取样(游戏)
        帧们.append(f)
    return 帧们


def 场景条(名字, 说明, 帧们, *, 应有图元: bool, 应有状态: bool = True,
           含超越函数: bool = False, 附注=None, 期望每帧图元数=None) -> dict:
    n图元 = sum(len(f["图元"]) for f in 帧们)
    #: ⚠ 状态条目数 = 每一帧取样里**所有序列型字段的元素总数**
    #:   （不只数 `对象`）—— 否则"可观察量不是对象列表"的场景会被误判成空。
    n状态 = 0
    for f in 帧们:
        for v in f.get("状态", {}).values():
            if isinstance(v, list):
                n状态 += len(v)
    条 = {
        "说明": 说明,
        "应有图元": bool(应有图元),
        "应有状态": bool(应有状态),
        "图元数": n图元,
        "状态条目数": n状态,
        "帧数": len(帧们),
        "渲染哈希": 渲染哈希(帧们),
        "帧": 帧们,
        #: ⚠ 这一条里的数**经 libm 超越函数**（cos/sin/hypot/pow/exp/sqrt）算出来
        #:   ⇒ 两个语言的 libm 允许差 1 ULP。**单独登记**，别混进"必须逐位相同"。
        "含超越函数": bool(含超越函数),
    }
    if 期望每帧图元数 is not None:
        #: 把"每帧应该画几条"钉成**精确值**（不是"大于 0"）
        #: —— 空场景、裁剪这些边界靠它才有意义。
        条["期望每帧图元数"] = int(期望每帧图元数)
        条["实测每帧图元数"] = [len(f["图元"]) for f in 帧们]
    if 附注:
        条["附注"] = 附注
    return 名字, 条


