def 去转义(s):
    """C# 字符串字面量里的转义还原成**学员看到的**字符。

    ⚠ 必须做：检查名里带引号时（`筛法真的在\\"划\\"…`），
      课程文件里是 `\\"`，而程序打出来的那一行是真正的 `"`。
      不还原 ⇒ 比对永远对不上 ⇒ 看起来像"检查没抓到"（假红）。
    """
    out, i = [], 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s):
            c = s[i + 1]
            out.append({"n": "\n", "t": "\t", "r": "\r", '"': '"',
                        "\\": "\\"}.get(c, c))
            i += 2
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def 读课(编):
    """(课文件, 参考答案, [检查名…]) —— 全部从文件里读，不手抄。"""
    匹配 = [f for f in os.listdir(课目录)
            if f.startswith("第%s课" % 编) and f.endswith(".cs")]
    if not 匹配:
        return None
    文 = io.open(os.path.join(课目录, 匹配[0]), encoding="utf-8").read()
    m = _参考.search(文)
    if not m:
        return None
    return (匹配[0], m.group(1).strip(),
            [去转义(x) for x in _检查名.findall(文)])


def 应用变换(参考, 变换):
    出 = 参考
    for t in 变换:
        旧, 新 = t[0], t[1]
        次要 = t[2] if len(t) == 3 else 1
        出 = 出.replace(旧, 新, 次要)
    return 出


def 校验表():
    """⚠ 全部校验做完再动手（这个项目的规矩：校验放写之前）。"""
    问题 = []
    见过 = {}
    for 项 in 错例:
        if len(项) != 4:
            问题.append("错例表里有一项不是 4 个字段：%r" % (项,))
            continue
        编, 变换, 说明, 期望 = 项
        if 编 in 见过:
            问题.append("课号 %s 出现了两次（一课只留一条，账本才不会重复计）" % 编)
        见过[编] = True
        if not 说明.strip() or not 期望.strip():
            问题.append("%s 的「错在哪」或「期望被拒的检查名」是空的" % 编)
        读 = 读课(编)
        if 读 is None:
            问题.append("%s 取不到课程文件或参考答案" % 编)
            continue
        _, 参考, 检查名 = 读
        if 期望.strip() not in 检查名:
            问题.append("%s 的期望检查名在课程里不存在：%r\n        这一课有：%s"
                        % (编, 期望, " · ".join(检查名)))
        if not 变换:
            问题.append("%s 的变换列表是空的" % 编)
            continue
        for t in 变换:
            if len(t) not in (2, 3):
                问题.append("%s 有一条变换的字段数不是 2 或 3：%r" % (编, t))
                continue
            旧, 新 = t[0], t[1]
            次要 = t[2] if len(t) == 3 else 1
            if not 旧:
                问题.append("%s 有一条变换的「旧」是空的" % 编)
                continue
            实际 = 参考.count(旧)
            if 实际 != 次要:
                问题.append("%s 的变换在参考答案里出现 %d 次（表里写 %d 次）：%r"
                            % (编, 实际, 次要, 旧[:70]))
        if 应用变换(参考, 变换) == 参考:
            问题.append("%s 的变换没有真的改变参考答案（新旧一样？）" % 编)
    应有 = set(本脚本的课)
    缺 = sorted(应有 - set(见过))
    多 = sorted(set(见过) - 应有)
    if 缺:
        问题.append("这 24 课漏了：%s" % " ".join(缺))
    if 多:
        问题.append("错例表里有不该由本脚本负责的课号：%s" % " ".join(多))
    return 问题


def 判(out):
    """(全过?, [通过的名字…], [没过的名字…]) —— ✓/√ 和 ✗/× 都认。"""
    过, 叉 = [], []
    for l in out.splitlines():
        s = l.strip()
        if s[:1] in ("✓", "√") and len(s) > 1:
            过.append(s[1:].strip())
        elif s[:1] in ("✗", "×") and len(s) > 1:
            叉.append(s[1:].strip())
    return ("全部通过" in out), 过, 叉


def 答题文件(编, 建=False):
    """课程程序自己建的答题文件名才是权威 —— 先让它建一次再找。"""
    if os.path.isdir(ANS):
        文件 = [f for f in os.listdir(ANS) if f.startswith(编)]
        if 文件:
            return os.path.join(ANS, 文件[0])
    if not 建:
        return None
    os.makedirs(ANS, exist_ok=True)
    跑一次(编)
    文件 = [f for f in os.listdir(ANS) if f.startswith(编)]
    return os.path.join(ANS, 文件[0]) if 文件 else None


def 跑一次(编, 源码=None, 路=None, 超时=60):
    """跑一次课程检查。

    ⚠ 用 Popen + taskkill /T：学员程序可能死循环，而它是**孙进程**
      （dotnet run → prog.exe），只杀直接子进程的话管道不放、会一直阻塞。
    """
    if 源码 is not None and 路 is not None:
        io.open(路, "w", encoding="utf-8", newline="").write(源码)
    p = subprocess.Popen([*运行, 编], cwd=ROOT, env=env,
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    try:
        out, err = p.communicate(timeout=超时)
    except subprocess.TimeoutExpired:
        subprocess.run(["taskkill", "/F", "/T", "/PID", str(p.pid)],
                       capture_output=True)
        try:
            out, err = p.communicate(timeout=10)
        except Exception:                                   # noqa: BLE001
            out, err = b"", b""
        return "\n**这一条跑了 %d 秒没停（错答案里有死循环）—— 判「没跑到」**" % 超时
    return (out + err).decode("utf-8", "replace")


def main():
    参 = sys.argv[1:]
    表问题 = 校验表()
    if 表问题:
        print("  **错例表没通过自检，一条都不跑（不动 c-answers/）**")
        for p in 表问题:
            print("    · " + p)
        return 2
    if "--列" in 参:
        print("  错例表：%d 条（自检已通过）" % len(错例))
        for 编, 变换, 说明, 期望 in 错例:
            print("    %s  %-58s 期望被拒：%s" % (编, 说明[:58], 期望[:40]))
        return 0

    筛选 = [a for a in 参 if not a.startswith("-")]
    跑到 = [x for x in 错例 if not 筛选 or x[0] in 筛选]
    if not 跑到:
        print("  **筛出来的错例是空的** —— 判为「没跑到」，不是「没过」")
        return 1

    print("═" * 70)
    print("  反面验证：C 课程 —— 错答案必须被拒（补账本里缺的 24 课）")
    print("═" * 70)
    print("  仓库根：%s" % ROOT)
    print("  错例：%d 条（每课一条）" % len(跑到))
    print()
    print("  先编译一次 csharp/c-lessons …")
    sys.stdout.flush()
    构建 = subprocess.run(["dotnet", "build", "csharp/c-lessons", "-v", "q", "--nologo"],
                          cwd=ROOT, env=env, capture_output=True, timeout=900)
    if 构建.returncode != 0:
        print("  **课程程序编译不过，一条都不跑**（退出码 %d）" % 构建.returncode)
        print((构建.stdout + 构建.stderr).decode("utf-8", "replace")[-2000:])
        return 2
    print("  编译通过。")
    print()

    shutil.rmtree(ANS, ignore_errors=True)
    os.makedirs(ANS, exist_ok=True)

    好, 假通过, 抓错项, 没跑到, 弱捕获 = 0, [], [], [], []
    t0 = time.time()
    try:
        for 编, 变换, 说明, 期望 in 跑到:
            读 = 读课(编)
            源码 = 应用变换(读[1], 变换)
            路 = 答题文件(编, 建=True)
            if 路 is None:
                没跑到.append(编)
                print("  !! %s 建不出答题文件（**没跑到**）" % 编)
                continue
            out = 跑一次(编, 源码, 路)
            if not any(l.strip()[:1] in ("✓", "√", "✗", "×") for l in out.splitlines()):
                没跑到.append(编)
                print("  !! %s 一条记号都没有（**没跑到**，不是没过）" % 编)
                continue
            全过, 过, 叉 = 判(out)
            命中 = [x for x in 叉 if x == 期望.strip()]
            对 = (not 全过) and bool(命中) and len(过) > 0
            好 += 1 if 对 else 0
            print("  %s %s [%d✓ %d✗]  %s"
                  % ("OK " if 对 else "XX ", 编, len(过), len(叉), 说明))
            if 全过:
                假通过.append(编)
                print("       **错误答案被判成通过了** —— 这一课的检查是摆设")
            elif len(过) == 0:
                弱捕获.append(编)
                print("       ⚠ **一个通过的记号都没有**：错答案让程序整个跑不起来，"
                      "每条检查都报 ✗ ⇒ 弱捕获（判失败，换一条错答案）")
            elif not 命中:
                抓错项.append(编)
                print("       报错了，但没有「%s」这一行。实际被拒的是：" % 期望.strip())
                print("         %s" % " · ".join(叉[:4]))
    finally:
        shutil.rmtree(ANS, ignore_errors=True)

    print()
    if 假通过:
        print("  **错误答案被判成通过（检查是摆设）**：%s" % " ".join(假通过))
    if 抓错项:
        print("  **报错了但没抓到期望那条检查**：%s" % " ".join(抓错项))
    if 弱捕获:
        print("  **弱捕获（判失败）**：%s" % " ".join(弱捕获))
    if 没跑到:
        print("  **没跑到（判失败）**：%s" % " ".join(没跑到))
    print("  == %d/%d 个错误答案被正确拒绝 ==" % (好, len(跑到)))
    print("  用时 %.0f 秒" % (time.time() - t0))
    print("═" * 70)
    return 0 if 好 == len(跑到) else 1


if __name__ == "__main__":
    sys.exit(main())
