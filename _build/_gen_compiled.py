def 打印行(值表达式: str) -> str:
    """把"要打印的东西"包成一句打印语句（按当前语言）。

    ⚠⚠ 这一层是被**逼出来**的 —— 同一个根因栽了三次：
      生成器里到处写着 C 的 `printf`，而它要服务四种语言。

        ① 返回 `char*` 时用 `%d` ⇒ 打出一个莫名其妙的数字
        ② 返回元组/struct 时根本没有打法 ⇒ C# 09~16 课全红
        ③ 改完值类型，骨架里**还是 printf** ⇒ C# 里"不知道 printf 是什么"

      ⇒ **"一处生成、多处使用"的代码里，语言差异必须提成抽象**，
        不能靠"用到的时候记得改一下"——上面三次都是"忘了改一处"。
    """
    if _是CSharp():
        return f"    Console.WriteLine({值表达式});\n"
    # ⚠ 用 f-string/`+` 而**不是 `%`**：值表达式里可能含 `%`
    #   （比如数组打印用 `__v%d`），`%` 运算符会把它当占位符 ⇒
    #       TypeError: not all arguments converted during string formatting
    return '    printf("%s\\n", (' + 值表达式 + ").ToString());\n"


def 打印整数(名: str, 入: str) -> str:
    """打一个整数返回值。

    ⚠⚠ **整数和小数不能用"通用打印"**（那个走 `.ToString()`）——
      **C / C++ 里没有 `.ToString()`**，只有 C# 有。
      我第一版让整数也走 `打印行()`，于是 C++ 的骨架生成了
          printf("%s\\n", (阶乘(5)).ToString());
      ⇒ `error: 'class std::__cxx11::basic_string...' has no member named...`，
         **C++ 的 12 课从全绿掉到 9/12**。
      ⇒ 判据：**"通用"只能覆盖"两种语言都有那个写法"的部分**；
        整数/小数有各自的原生格式符，就该各写各的。
    """
    值 = "%s(%s)" % (名, 入)
    if _是CSharp():
        return 打印行(值)
    # ⚠ `%d` 要用 `+` 拼进去；写 `'…"%d\n"…' % 值` 会让 Python 的 `%`
    #   把 `%d` 当占位符 ⇒ `TypeError: %d format: a real number is required, not str`
    return '    printf("%d\\n", ' + 值 + ");\n"


def 打印整数表达式(表达式: str) -> str:
    """打一个**已经是完整表达式**的整数（不是 `名(入)` 那个形状）。

    ⚠ `写了函数` 的第二个参数就是完整调用表达式（如 `阶乘(5)`），
      所以不能走 `打印整数(名, 入)`（那个会拼成 `阶乘(阶乘(5))`）。
    """
    if _是CSharp():
        return 打印行(表达式)
    return '    printf("%d\\n", ' + 表达式 + ");\n"


def 打印真假(名: str, 入: str) -> str:
    """bool 返回值。C / C++ 用三目，C# 里 bool 直接 WriteLine 就是 True/False。"""
    值 = "%s(%s)" % (名, 入)
    if _是CSharp():
        return 打印行(值)
    return '    printf("%s\\n", %s ? "True" : "False");\n' % ("%s", 值)


def 打印小数(名: str, 入: str) -> str:
    """浮点返回值。定死六位小数，和期望里写的一致。"""
    值 = "%s(%s)" % (名, 入)
    if _是CSharp():
        return 打印行('%s.ToString("F6")' % 值)
    return '    printf("%.6f\\n", %s);\n' % 值


def 打印元组(名: str, 入: str) -> str:
    """二元组。格式固定 `(A, B)`（含括号与逗号后的空格）。"""
    值 = "%s(%s)" % (名, 入)
    if _是CSharp():
        return 打印行('$"({%s.Item1}, {%s.Item2})"' % (值, 值))
    return 打印行(值)


def 跑骨架(语句: str) -> str:
    """把"调用语句"交给课程库去编译运行。

    ⚠⚠ **C 和 C# 的骨架形态完全不同**：

      · C / C++ 模式：课程库只做**字符串替换**（`/*学生代码*/` → 学员代码），
        所以骨架要自己是一个完整程序（`#include` + `int main`）。

      · **C# 模式：课程库自己会包一层入口**（学员代码放进 `学生代码` 类，
        再补 `入口` 类 + `Main`）。骨架里再写 `int main()` 就成了第二个入口：
            error CS0017: 定义了多个入口点。请使用 /main 进行编译
        ——而且错在**我方生成的骨架**上，学员看报错会以为是自己写错了。
        所以 C# 模式下骨架只给"要执行的语句"。

      ⇒ 我原来照 C 写死了 `int main(void)`，把 C# 的 09~16 课全弄红了。
        **"同一套形态服务多种语言"的地方，都要问一句"这一步谁来干"。**

    ⚠ C# 原始字符串的**结束定界符必须独占一行**：如果把它写在语句同一行，
      会报 `error CS9000: Raw string literal delimiter must be on its own line`。
      ⇒ 语句后面补一个换行，让结束符落在自己那一行。
      （这个错误我一开始看成了"内容有问题"，其实纯粹是排版规则。）

    ⚠⚠ **C# 走的是"调用点"，不是"骨架"** —— 这是我栽了好几轮才看清的：
      `编译并运行(学生代码, 骨架, 调用点)` 有**两个**可选的注入位置：

        · `骨架`   —— 整个替换掉课程库准备的容器（C / C++ 用这个）
        · `调用点` —— **库自己的容器留着，只换掉里面"要执行的那几行"**

      C# 的容器是 `学生代码` 类 + `入口` 类（含 `Main`）。
      我把调用语句当成"骨架"传进去 ⇒ **整个容器被换掉** ⇒
      而库还会再补一个 `入口`/`Main` ⇒ 两个入口：
          error CS0017: 定义了多个入口点
      报错位置指向 `Program.cs(8,20)`（库那边的文件），所以我一开始
      一直在自己的骨架里找问题 —— **方向错了三轮。**

      ⇒ C# 模式：`编译并运行(代码, null, 调用点)` —— 骨架传 `null`，
        让库用它的 `默认骨架CSharp`（里面就有 `// __调用点__` 占位符），
        库再把我们的语句替换进去。和现有 C# 课完全一致。

      ⚠ 我试过"自己拼一个骨架、把语句写进去" —— 那会绕过库的占位符机制，
        等于整个容器被换掉，于是库再补一个 `入口`/`Main` ⇒ 两个入口。
    """
    if _是CSharp():
        # 调用点 = 要执行的那几行语句。库会把它们放进 `入口.Main`。
        # ⚠ 语句里**不能**加 `学生代码.` 前缀 —— 库明确写了那会生成
        #   `() => { 学生代码.foreach(...) }` ⇒ error CS1001。
        #   方法名在同一作用域内直接可见。
        转义 = 语句.replace('"""', '\\"\\"\\"')
        return ('        var 调用点 = """\n' + 转义 + '\n""";\n'
                f'        var run = {K}.编译并运行(代码, null, {L}.限定(代码, 调用点));\n')
    return ('        var 骨架 = """\n' + 骨架头 + 语句 + '    return 0;\n}\n""";\n'
            f'        var run = {K}.编译并运行(代码, 骨架);\n')


def 逐行比对(期望列, 输入列, 提示: str) -> str:
    """逐行比对的 C# 代码。

    ⚠ 两处细节都踩过坑：
      · **C# 不允许尾随逗号**（`f(a, b,)` 报 CS1525）⇒ 用 join，不留尾逗号
      · 数组类骨架打印的是 "%d,"（带尾逗号），而期望写的是 2,3,4
        ⇒ 比较前 **TrimEnd(',')**
    """
    期望 = ",\n".join("            " + C(x) for x in 期望列)
    输入 = ",\n".join("            " + C(x) for x in 输入列)
    return (
        f'        string[] 期望 = {{\n{期望}\n        }};\n'
        f'        string[] 输入 = {{\n{输入}\n        }};\n'
        '        for (int i = 0; i < 期望.Length; i++)\n'
        '        {\n'
        '            // ⚠ 骨架打印的是 "%d,"（带尾逗号）⇒ 比较前去尾逗号\n'
        '            string 实际行 = i < run.行.Count\n'
        "                ? run.行[i].Trim().TrimEnd(',') : \"\";\n"
        '            if (i >= run.行.Count || 实际行 != 期望[i])\n'
        '            {\n'
        '                string 这是 = i < 输入.Length ? 输入[i] : \"\";\n'
        '                return ' + R + '.不过(\n'
        '                    $"输入 [{这是}] 应当是 [{期望[i]}]，" +\n'
        '                    $"实际是 [{(i < run.行.Count ? 实际行 : \"（没输出）\")}]。\\n" +\n'
        '                    ' + C(提示) + ');\n'
        '            }\n'
        '        }\n'
        '        return ' + R + '.过("每一组都对");\n')


def 形_输出逐行(说明, 参, 序):
    """学生代码是**完整程序**（自带 main）⇒ 原样编译运行，逐行比。"""
    期望 = "".join(f"            {C(x)},\n" for x in 参)

    # ⚠⚠ 第 00 课（工具链）要**多一条前置检查**：工具装好了没有。
    #   为什么必须插在最前面：没装 gcc 时，这条"编译运行"的检查会失败，
    #   而它的报错是「程序没能正常运行」—— 学员会以为是自己代码的问题。
    #   先过一条明说"这不是你代码的问题"的检查，方向才对。
    #
    #   ⚠ 我加这段的时候把 `return` 挪进了 `if` 里面 ⇒
    #     非 00 课的函数直接掉出去返回 **None**，
    #     生成时报 `TypeError: sequence item 0: expected str instance, NoneType found`。
    #     ⇒ 教训：加"特殊情况"时，**普通情况的出口不能被吃掉**。
    前缀 = ""
    序号 = f"检查_{序}"
    if 课号 == "00":
        前缀 = (头("工具链就绪（gcc 与 dotnet 都在）", f"检查_{序}a") +
                "        return {L}.工具链就绪(代码);\n" + 尾)
        序号 = f"检查_{序}b"

    return 前缀 + 头(说明, 序号) + (
        "        var run = {K}.直接运行(代码);\n"
        "        if (!run.编译通过) return {K}.编译失败说明(run);\n"
        "        string[] 期望 = {\n" + 期望 + "        };\n"
        "        var 实际 = run.行;\n"
        "        if (实际.Count != 期望.Length)\n"
        '            return {R}.不过($"应该有 {期望.Length} 行输出，实际 {实际.Count} 行。" +\n'
        '                "\\n      打印出来的：\\n        " + string.Join("\\n        ", 实际));\n'
        "        for (int i = 0; i < 期望.Length; i++)\n"
        "            if (实际[i].Trim() != 期望[i])\n"
        "                return {R}.不过(\n"
        '                    $"第 {i + 1} 行应当是「{期望[i]}」，实际是「{实际[i].Trim()}」。");\n'
        '        return {R}.过($"{期望.Length} 行输出全对");\n') + 尾


