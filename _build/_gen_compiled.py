def 形_指针用例(说明, 参, 序):
    名 = 参[0]
    对 = list(zip(参[1::2], 参[2::2]))
    # ⚠ 我上一版把这一行改成了 `"…%d…" % (i, 入, 名, i) + 打印行(…) % (i, 入, 名, i, i)`
    #   —— 第二个 `%` 又作用了一次、参数还多了 ⇒
    #       TypeError: not all arguments converted during string formatting
    #   拼接和格式化混在一行最容易出这种事，所以拆开写。
