def 预限定类型(代码: str, 类型们) -> str:
    """把 `new 类型(...)` 里的类型名换成 `new 学生代码.类型(...)`。

    ⚠⚠ 为什么要在**生成端**做这件事，而不是让课程库的 `限定()` 去补：

      课程库把学员代码放进 `public static class 学生代码`，调用点放在
      **另一个类**里，所以裸名字要补 `学生代码.` 前缀。

      但**同一条正则对"类型"和"方法"是两种效果**：

          方法：  描述(-1)         → 学生代码.描述(-1)      ✓
          类型：  成绩记录 r        → 学生代码.成绩记录 r    ✓
          类型：  **new 计数器(1)**  → new 学生代码.计数器(1)  ✗
                                     ⇒ CS0023: 运算符"."无法应用于…

      因为 `new X(...)` 后面可能跟 `.属性`：
          new 学生代码.计数器(1).值     ← 编译器把 `学生代码.计数器(1).值` 当整体
      而 `new 计数器(1)` **本来就在 `Main` 里合法**（嵌套类型可见即可 new），
      根本不需要限定。

      ⚠ 我在库那侧试过用 `(?<!new\s)` 避开，结果**更糟**（10→8，08/09/14 也红了）。
        ⇒ **事后替换分不清"类型引用"和"构造表达式"**，
          但**生成的时候我明明知道** —— 所以在这边做。
          这就是"在信息最全的地方做决定"。

    ⚠ 预限定之后，库那侧的 `(?<![\w.])` 看到前面是 `.` 就会跳过 ⇒ **幂等**，
      不会变成 `学生代码.学生代码.计数器`。
    """
    for 类型 in 类型们:
        if not 类型:
            continue
        # 只处理 `new <类型>`，且前面不是 `.`（已经被限定过）
        import re as _re
        代码 = _re.sub(r"(?<![\w.])new\s+" + _re.escape(类型) + r"\b",
                       "new 学生代码." + 类型, 代码)
    return 代码


