def C(文: str) -> str:
    """Python 字符串 → C# 字符串字面量。

    ⚠ 必须转义**换行**：数据文件里读来的多行文字若原样塞进去，
      C# 会报 CS1010: Newline in constant（栽过两次）。
    """
    出 = (文.replace("\\", "\\\\").replace('"', '\\"')
          .replace("\r\n", "\\n").replace("\n", "\\n")
          .replace("\r", "\\r").replace("\t", "\\t"))
    return '"' + 出 + '"'


