def 形_连调用(说明, 参, 序):
    """在**同一个程序里**执行一串（语句 → 打印一个表达式），逐行比期望。

    参数：**三元一组**，重复：
        `连调用|<语句>|<表达式>|<期望>|<语句>|<表达式>|<期望>|…`

    例：
        连调用||new 计数器(1).值|0||new 计数器(1).加(3).值|3
        连调用|int v1;|查到了(d, "甲", out v1) + ":" + v1|True:90|…

    `语句` 可以留空（只求值一条表达式）。语句和表达式里的**裸名字**
    由 `限定()` 补 `学生代码.` 前缀。

    ⚠⚠ 这个形态我重写了两遍，教训值得留：
      第一版是 `连调用|函数名|期望1|期望2|…` —— 只会生成
          printf("%d\\n", 函数名());
      而写课的人真正要表达的是"**任意语句 + 任意表达式**"：
          `new 学生("甲",70).报告()`、`数满足(列表, 谓词)`、
          `查到了(表, "甲", out v1) + ":" + v1`
      第二版我把参数当成"二元一组"，又错了一轮（把期望值当成了代码）。

      **判据**：形态的参数设计要能表达写课的人**真正想写的东西**，
        而且**含义要明确到不需要猜**（几元一组？谁是代码谁是期望？）。
        表达不了、或者需要猜的时候，先改形态 —— 别去改课的写法。
    """
    组 = list(zip(参[0::3], 参[1::3], 参[2::3]))
    # ⚠ 类型表是模块级常量 `_课时类型表`（和 `形_文字用例` 共用一份）
    类型们 = _课时类型表
    行 = []
    for 语句, 表达式, _ in 组:
        语句 = 预限定类型((语句 or "").strip(), 类型们)
        表达式 = 预限定类型(表达式, 类型们)
        if 语句:
            行.append("    " + 语句 + "\n")
        # ⚠ 用 `打印整数表达式()` 而不是通用的 `打印行()`：
        #   `打印行` 在 C/C++ 侧会生成 `(…).ToString()` —— 而
        #   **C / C++ 的整数没有 `.ToString()`**：
        #       error: request for member 'ToString' in '…', which is of non-class type 'int'
        #   ⇒ C++ 第 10 课（同一个函数连调 5 次看 static）从绿掉红。
        #   `打印整数表达式` 在 C/C++ 侧用 `printf("%d", …)`，正确。
        行.append(打印整数表达式(表达式))
    打印 = "".join(行)
    return 头(说明, f"检查_{序}") + 跑骨架(打印) + (
        "        if (!run.编译通过) return {K}.编译失败说明(run);\n" +
        逐行比对([期 for _, _, 期 in 组],
                [("%s ⇒ %s" % (语, 式)) if 语 else 式 for 语, 式, _ in 组],
                "      ⚠ 要把每一步都跑对 —— 中间任何一步错了，后面的结果就对不上。")) + 尾


