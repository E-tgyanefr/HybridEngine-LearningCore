// 第 05 课：scanf —— 让程序会听
// ─────────────────────────────────────────────────────
//  这一课你会学到
// ─────────────────────────────────────────────────────
//    让程序读你从键盘敲进去的数（scanf）
//
//  需要先会
//    第 02 课：变量
//
// ─────────────────────────────────────────────────────
//  先介绍：怎么从键盘读东西
// ─────────────────────────────────────────────────────
//
//     int 数;
//     scanf("%d", &数);         ← 读一个整数放进「数」
//                  ↑
//                  这个 & 是**取地址**，不能少！
//
// ⚠⚠⚠ **这一课唯一要记住的坑：scanf 必须写 `&`。**
//
//     为什么：printf 是"把值给出去"，只要值就行；
//     而 scanf 是"把读到的值**存进去**"，它必须知道**存到哪块内存**。
//     `&数` 就是"变量「数」所在的内存地址"。
//
//     写了 &  ⇒  正确
//     忘了 &  ⇒  程序**可能在运行时崩溃**（Segmentation fault），
//                也可能"看起来跑完了"但变量没被赋值 ——
//                编译器只给个警告，不报错。所以特别危险。
//
// ⚠ 格式符要和类型对上：
//     读 int      scanf("%d", &x);
//     读 double   scanf("%lf", &x);     ← ⚠ 是 %lf（有个 l），不是 %f
//     读字符      scanf("%c", &c);
//
// ─────────────────────────────────────────────────────
//  用法与例子
// ─────────────────────────────────────────────────────
//
//  ① 读一个整数：
//
//      int 数;
//      scanf("%d", &数);              程序会在这里**停下来等你敲**
//
//  ② 读进来就能用 —— 和普通变量没有区别：
//
//      printf("%d\n", 数 + 1);
//
//  ③ 一次读两个值：两个占位符，两个地址，敲的时候用空格或回车隔开。
//
//      int 甲, 乙;
//      scanf("%d %d", &甲, &乙);      输入 "3 5" ⇒ 甲=3 乙=5
//
//  ④ ⚠ 读 double 和读 int 的格式符**不一样**，这是最容易记错的一处：
//
//      int x;      scanf("%d",  &x);      /* 读整数 */
//      double y;   scanf("%lf", &y);      /* ⚠ 读小数要写 %lf */
//
//  一个完整的、能跑的例子：
//
//      #include <stdio.h>
//
//      int main(void) {
//          int 数;
//          scanf("%d", &数);           /* ⚠ 这个 & 是这一课的全部重点 */
//          printf("%d\n", 数 + 1);
//          return 0;
//      }
//
//  运行（假设你敲了 5）：
//
//      5                               ← 你敲的
//      6                               ← 程序打印的
//
//  ⚠ 界面上的「检查」会**替你敲**一个数进去，你不用手动输入。
//    但它敲几次、敲什么值，取决于这一课的检查项 ——
//    所以别写死任何前提（比如"假设用户一定输入正数"）。
//
// ─────────────────────────────────────────────────────
//  常见坑
// ─────────────────────────────────────────────────────
//
//  ⚠ 坑 1：scanf 忘了写 & —— 这一课的头号杀手
//
//      错误写法：
//          int 数;
//          scanf("%d", 数);            /* 少了 & */
//
//      你会看到什么（gcc 原文）：
//
//          main.c:4:13: warning: format '%d' expects argument of type 'int *', but argument 2 has type 'int' [-Wformat=]
//              4 │     scanf("%d", 数);
//                │            ~^   ~
//                │             │   │
//                │             │   │
//                │             │   int
//                │             int *
//
//      ⚠ 注意它说的是 `int *`（指针）而不是 `int` —— 这就是"我要的是地址"。
//      而且它只是 **warning**：编译照过，你会拿到一个 .exe。
//
//      运行时：数 仍然是个**随机垃圾值**（因为没有任何东西被写进去），
//      程序打印出一个莫名其妙的数字；某些环境下直接崩溃。
//
//      为什么：`数` 是那个变量的**值**（此刻还是随机的），
//      而 scanf 需要的是它的**地址**。scanf 会把"你给的那个数字"
//      当成地址去写 —— 写到一个几乎肯定不属于你的地方。
//      ⇒ 轻则数据没读到，重则程序崩掉。
//      ⚠ 这是本课程里最典型的"编译能过、结果一定错"的例子。
//
//  ⚠ 坑 2：读 double 用了 %f
//
//      错误写法：
//          double 数;
//          scanf("%f", &数);
//
//      你会看到什么（gcc 原文）：
//
//          main.c:4:13: warning: format '%f' expects argument of type 'float *', but argument 2 has type 'double *' [-Wformat=]
//              4 │     scanf("%f", &数);
//                │            ~^   ~~
//                │             │   │
//                │             │   │
//                │             │   double *
//                │             float *
//                │            %lf
//
//      为什么：`%f` 在 **scanf 里**只认 float，读 double 必须写 `%lf`。
//      ⚠ 而且这里有个反直觉的地方：
//          printf 打 double 用 %f（不用 l）
//          scanf  读 double 用 %lf（必须有 l）
//      两个函数的规则**不一样**，只能分别记。
//      注意 gcc 最后那行 `%lf` 就是它给的正确答案。
//
//  ⚠ 坑 3：没有把 & 忘记，但把 & 写到了不该写的地方
//
//      错误写法（假设 名字 是 `char 名字[20]`）：
//
//          char 名字[20];
//          scanf("%s", &名字);          /* 多看一个 & */
//
//      你会看到什么：
//          通常**能编译、也常常能跑对** —— 所以这个坑才难发现。
//          在打开 -Wall 时可能什么都不报，也可能报一串指针类型不匹配。
//
//      为什么：数组名**本身就已经是地址**了（第 15 课会讲透这件事），
//      再加一个 & 就是"地址的地址"，类型变成了 `char (*)[20]`。
//      C 的指针类型检查很松，所以它经常就这么混过去了。
//      ⇒ 规矩：**数组不用 &**，单个变量必须 &。
//          scanf("%d", &数);        单个 int      ✅ 要 &
//          scanf("%s", 名字);       字符数组      ✅ 不要 &
//
// ─────────────────────────────────────────────────────
//  轮到你了 —— 在下面写
