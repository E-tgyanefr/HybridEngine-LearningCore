// 第 11 课：指针 —— 改参数，外面会不会变
//
// ─────────────────────────────────────────────────────
//  先介绍：为什么需要指针
// ─────────────────────────────────────────────────────
//
// 先看一个"不生效"的函数：
//
//     void 加倍(int x) {
//         x = x * 2;            ← 改的是**拷贝**
//     }
//
//     int 数 = 5;
//     加倍(数);
//     printf("%d\n", 数);       ⇒ 还是 5！
//
// 为什么：C 的函数参数默认是**按值传递** —— 传进去的是一份**拷贝**。
// 函数里怎么改，都动不到外面那个变量。
//
// 想改到外面，就要传**地址**：
//
//     void 加倍(int *p) {       ← p 是"指向一个 int 的指针"
//         *p = *p * 2;          ← *p 是"p 指向的那个数"
//     }
//
//     int 数 = 5;
//     加倍(&数);                ← 传地址（那个 & 又出现了）
//     printf("%d\n", 数);       ⇒ 10  ✅
//
// ⚠⚠ 两个符号别搞混 —— 这是这一课唯一要记住的东西：
//
//     &数     取地址 —— "数在内存的哪里"
//     *p     取值   —— "p 指的那个地方**里面**是什么"
//
//   在**声明**里 `int *p` 的 `*` 是"这是个指针"；
//   在**表达式**里 `*p` 的 `*` 是"取出它指的东西"。同一个符号两种意思。
//
// ⚠ 第 05 课的 `scanf("%d", &数)` 就是这个道理 ——
//   它要改你那个变量，所以必须知道地址。
//
// ─────────────────────────────────────────────────────
//  用法与例子
// ─────────────────────────────────────────────────────
//
//  ① 先亲眼确认"按值传递改不到外面"（这段值得你跑一遍）：
//
//      #include <stdio.h>
//
//      void 加倍(int x) { x = x * 2; }        /* 改的是拷贝 */
//
//      int main(void) {
//          int 数 = 5;
//          加倍(数);
//          printf("%d\n", 数);                ⇒ 5   ← 没变！
//          return 0;
//      }
//
//  ② 换成指针，就改到了：
//
//      void 加倍(int *p) { *p = *p * 2; }
//
//      int main(void) {
//          int 数 = 5;
//          加倍(&数);                         /* ⚠ 传的是地址 */
//          printf("%d\n", 数);                ⇒ 10  ← 变了
//          return 0;
//      }
//
//  ③ 三个符号的读法（把这句话背下来就够用了）：
//
//      int 数 = 5;
//      int *p = &数;           p 存的是"数"的地址
//      printf("%d\n", 数);     ⇒ 5      数的值
//      printf("%d\n", *p);     ⇒ 5      p 指的那个东西的值
//      *p = 7;                 ⇒ 数 也变成 7
//
//  ④ 指针参数的意义："我要改你给我的那个变量"。
//     一个函数想"交回"多个结果时，就得靠它（第 16 课会用两个指针）。
//
//  ⚠ 为什么这一课的函数签名是 `void 加倍(int *p)`：
//    · 返回类型是 void —— 它不需要 return，结果直接写进你给的地址里；
//    · 参数是 `int *` —— 它要的是"一个 int 的地址"，不是那个 int 的值。
//  所以调用时必须写 `加倍(&数)`。写 `加倍(数)` 就类型不匹配了（坑 1）。
//
// ─────────────────────────────────────────────────────
//  常见坑
// ─────────────────────────────────────────────────────
//
//  ⚠ 坑 1：调用时忘了写 &
//
//      错误写法（函数已经有声明，main 里却传了值）：
//          void 加倍(int *p);
//
//          int main(void) {
//              int 数 = 5;
//              加倍(数);                   /* ⚠ 传的是值，不是地址 */
//              return 0;
//          }
//
//      你会看到什么（gcc 原文，函数名是中文时会被转义成 UCN 码点）：
//
//          main.c:4:10: error: passing argument 1 of '\U000052a0\U0000500d' makes pointer from integer without a cast [-Wint-conversion]
//              4 │     加倍(数);
//                │          ^~
//                │          │
//                │          int
//          main.c:4:10: note: possible fix: take the address with '&'
//              4 │     加倍(数);
//                │          ^~
//                │          &
//          main.c:1:16: note: expected 'int *' but argument is of type 'int'
//              1 │ void 加倍(int *p);
//                │           ~~~~~^
//
//      为什么：函数要的是一个"int 的地址"，你给了它一个 int 的值。
//      C 不允许把整数悄悄当成指针用 —— 所以这里是 **error**，不是 warning。
//      ⚠ 最贴心的是那条 `note: possible fix: take the address with '&'`：
//        gcc 直接把补丁画给你了。**看到它，就在那个参数前面加 &。**
//      ⚠ 还有一种更迷惑的写法：**函数没声明、也没定义在后面**时，
//        你写 `加倍(数);` 会先撞上另一条错：
//            error: implicit declaration of function '\U000052a0\U0000500d' [-Wimplicit-function-declaration]
//        那说的是"我不认识 加倍 这个名字"（第 13 课），
//        **和"忘了 &"是两回事**。分清这两条，能省很多时间。
//
//  ⚠ 坑 2：函数体里写 `p = p * 2`（少了一个星号）
//
//      错误写法：
//          void 加倍(int *p) {
//              p = p * 2;              /* ⚠ 改的是指针自己 */
//          }
//
//      你会看到什么（gcc 原文）：
//
//          main.c:2:11: error: invalid operands to binary * (have 'int *' and 'int')
//              2 │     p = p * 2;
//                │           ^
//
//      为什么：`p` 的类型是 `int *`（地址），`2` 是 `int`。
//      "地址乘 2"没有定义 ⇒ 编译直接拦下来。
//      ⚠ 这条反而是**运气好**的情况 —— 编译器替你抓到了。
//      真正危险的是下面这种：
//
//          void 加倍(int *p) {
//              p = p + 1;              /* 合法！但毫无用处 */
//          }
//
//      "地址加 1"是合法的（指针算术，第 15 课），所以它**编译零警告**，
//      可它只是把函数内部那个局部指针挪了一格 —— 外面的数一个字节都没变。
//      ⇒ 记住：**要改外面那个数，必须写 `*p`。**
//
//  ⚠ 坑 3：以为指针参数是"引用"，直接写变量名
//
//      错误写法：
//          void 加倍(int *p) {
//              数 = 数 * 2;            /* ⚠ 数 在这个函数里根本不存在 */
//          }
//
//      你会看到什么（gcc 原文，中文名会被转义）：
//
//          main.c:2:5: error: '\U00006570' undeclared (first use in this function)
//              2 │     数 = 数 * 2;
//                │     ^~
//
//      为什么：函数只能看见自己的参数和局部变量。
//      `数` 是 main 里的变量，这里只是个**错误的名字**。
//      指针参数给你的是"改外面那个变量的**通道**"，通道的名字叫 `*p`。
//      ⇒ 心里默念一句：**p 是门牌号，*p 是屋里那个人。**
//
// ─────────────────────────────────────────────────────
//  轮到你了 —— 在下面写
// ─────────────────────────────────────────────────────
