""";

    public static string 参考答案 => """
int 求和到(int n) {
    /* ⚠ 起点必须是 0 —— C 里未初始化的局部变量是随机值 */
    int 和 = 0;
    /* ⚠ i <= n 不是 i < n（少一次） */
    for (int i = 1; i <= n; i++) {
        和 += i;
    }
    return 和;
}
""";


