// 第 07 课：for —— 让程序重复做事
//
// ─────────────────────────────────────────────────────
//  先介绍：重复做一件事
// ─────────────────────────────────────────────────────
//
//     for (int i = 1; i <= 5; i++) {
//         printf("%d\n", i);
//     }
//
// for 的圆括号里有**三段**，用分号隔开：
//
//     for ( 初始化 ; 继续条件 ; 每轮之后做 )
//           int i=1   i <= 5      i++
//
//   · 初始化：循环开始前做一次
//   · 继续条件：每轮开始前检查，**为假就停**
//   · i++ 是 `i = i + 1` 的简写
//
// ⚠ 三段**都用分号隔开**，不是逗号：
//     for (int i = 1, i <= 5, i++)     ❌
//     for (int i = 1; i <= 5; i++)     ✅
//
// ⚠⚠ 这一课要记住的坑：**差一错误（off-by-one）**
//     i <= 5   跑 5 次（1,2,3,4,5）      ✅
//     i < 5    跑 4 次（1,2,3,4）        ← 少一次
//     i <= 5 但 i 从 0 开始 ⇒ 跑 6 次     ← 多一次
//   写循环时**一定要在脑子里数一遍**：第一次进循环时 i 是几？最后一次是几？
//
// 累加的套路（和 Python 一样，但**必须先初始化**）：
//     int 和 = 0;              ← ⚠ 忘了这行，和会是随机的垃圾值
//     for (...) 和 += x;
//
// ⚠ C 里未初始化的局部变量**不会自动是 0** —— 它是内存里的随机值。
//   这是 C 与 Python 的又一个大区别。
//
// ─────────────────────────────────────────────────────
//  用法与例子
// ─────────────────────────────────────────────────────
//
//  ① 数数（最典型的用法）：
//
//      for (int i = 1; i <= 5; i++) {
//          printf("%d\n", i);
//      }
//
//      输出：1 2 3 4 5（每个一行）
//
//  ② 累加：先准备一个"桶"，循环里往里加。
//
//      int 和 = 0;                         /* ⚠ 必须初始化 */
//      for (int i = 1; i <= 5; i++) {
//          和 += i;                        /* 和 = 和 + i 的简写 */
//      }
//      printf("%d\n", 和);                 ⇒ 15
//
//  ③ 从 0 开始、用来遍历数组（第 09 课就靠这个）：
//
//      for (int i = 0; i < 5; i++) {       /* ⚠ 从 0 起，条件就是 i < 5 */
//          printf("%d\n", 数据[i]);
//      }
//
//      ⚠ 这两种写法各自都对，但**不能混**：
//        「从 1 开始」配 `i <= n`
//        「从 0 开始」配 `i <  n`
//        混着写就是差一错误。
//
//  ④ 倒着数：三段都可以随便写，不一定非得加。
//
//      for (int i = 5; i >= 1; i--) { ... }        ⇒ 5 4 3 2 1
//
//  ⑤ 提前跳出：`break` 立刻结束整个循环，`continue` 跳过本轮剩下的部分。
//
//      for (int i = 1; i <= 10; i++) {
//          if (i == 4) break;              /* 到 4 就不干了 */
//      }
//
//  一个完整的、能跑的例子：
//
//      #include <stdio.h>
//
//      int 求和到(int n) {
//          int 和 = 0;
//          for (int i = 1; i <= n; i++) {
//              和 += i;
//          }
//          return 和;
//      }
//
//      int main(void) {
//          printf("%d\n", 求和到(5));      ⇒ 15
//          printf("%d\n", 求和到(1));      ⇒ 1
//          printf("%d\n", 求和到(0));      ⇒ 0
//          return 0;
//      }
//
//  ⚠ 注意 `求和到(0)`：条件 `i <= 0` 一开始就是假 ⇒ 一次都不进循环 ⇒
//    直接返回 0。这是**对的**，但它靠的是 `和 = 0` 那行初始化。
//
// ─────────────────────────────────────────────────────
//  常见坑
// ─────────────────────────────────────────────────────
//
//  ⚠ 坑 1：忘了给累加器初始化
//
//      错误写法：
//          int 求和到(int n) {
//              int 和;                     /* ⚠ 没有 = 0 */
//              for (int i = 1; i <= n; i++) {
//                  和 += i;
//              }
//              return 和;
//          }
//
//      你会看到什么：
//          gcc 可能给一条 warning: '和' may be used uninitialized [-Wmaybe-uninitialized]
//          也可能**什么都不说**（取决于优化级别）。
//          运行时 求和到(5) 返回一个莫名其妙的数（比如 -858993445），每次还可能不一样。
//
//      为什么：C 的局部变量在栈上，**不会自动清零**。`int 和;`
//      只是把栈上那块地"认领"下来，地里原来是别的函数留下的垃圾。
//      `和 += i` 等价于 `和 = 和 + i` ⇒ 从垃圾值开始加，结果当然是垃圾。
//      ⚠ 这类 bug 阴险的地方：**同一个程序，换台机器/换个编译选项，结果就变了**。
//      ⇒ 累加器、计数器、最大值、最小值——**声明时一律给初值**。
//
//  ⚠ 坑 2：for 的三段用了逗号
//
//      错误写法：
//          for (int i = 1, i <= 5, i++) { ... }
//
//      你会看到什么：
//
//          main.c:3:22: error: expected identifier or '(' before '<=' token
//
//      为什么：在 for 的圆括号里，**逗号是另一件事** ——
//      它表示"再声明一个同类型的变量"（`int i = 1, j = 2;` 是合法的）。
//      所以编译器读到 `i <= 5` 时以为你在写第二个变量名，结果撞上 `<=` 就崩了。
//      ⇒ 三段之间**只能是分号**，永远。
//
//  ⚠ 坑 3：差一错误 —— 循环次数数错了
//
//      错误写法（想求 1 到 5 的和，却写了 <）：
//          int 和 = 0;
//          for (int i = 1; i < 5; i++) {
//              和 += i;
//          }
//
//      你会看到什么：
//          ⚠ **编译零警告**，程序正常跑完，输出 `10`（而你要的是 15）。
//          算出来的数字"看起来也很正常"，所以这个错特别难被发现。
//
//      为什么：`i < 5` 在 i 变成 5 的时候就停了，最后一个 5 没加进去。
//      ⇒ 一条能救命的自检习惯：**把循环次数和边界在纸上走一遍**。
//          i 从 1 开始，条件是 i <= 5 ⇒ 最后一次进循环时 i = 5 ⇒ 恰好 5 次 ✅
//          i 从 1 开始，条件是 i <  5 ⇒ 最后一次进循环时 i = 4 ⇒ 只有 4 次 ❌
//      ⚠ 遍历数组更危险：`i <= 个数` 会**越界读一个**（第 09 课的主题）。
//
// ─────────────────────────────────────────────────────
//  轮到你了 —— 在下面写
// ─────────────────────────────────────────────────────
//   写函数：  int 求和到(int n)
//   返回 1 + 2 + ... + n
//
//   求和到(5)  ⇒ 15
//   求和到(1)  ⇒ 1
//   求和到(0)  ⇒ 0
//
// 提示：不用写 main。
//
// ⚠ 期望结果（检查会喂这四组）：
//
//      求和到(5)   ⇒ 15
//      求和到(1)   ⇒ 1
//      求和到(0)   ⇒ 0
//      求和到(100) ⇒ 5050
//
// ⚠ 0 和 1 是**边界**：它们专门用来抓"忘了初始化"和"差一错误"。
//
