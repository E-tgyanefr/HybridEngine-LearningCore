//    第 07 课：for 循环（三种排序都是两层循环）
//    第 08 课：函数（每种排序写成一个函数）
//
// ─────────────────────────────────────────────────────
//  先介绍：为什么要排序
// ─────────────────────────────────────────────────────
//
// 查分数、找最大值、去重、算中位数……背后都先要把数**排好**。
//
// ⚠ C 标准库里**没有**能直接用的排序函数（C++ 才有 std::sort）。
//   有个 qsort，但它要你会写函数指针 —— 那是很远以后的事。
//   这一课的要求就一条：**排序的循环自己写**。
//
// 三种写法，干的是同一件事，思路完全不同：
//
//   冒泡：邻居两个两个比，大的往后挪 —— 像气泡往上冒
//   插入：像理扑克牌，把新摸到的牌插进已经排好的那一段
//   选择：每一轮从剩下的里挑出最小的，放到前面
//
// ─────────────────────────────────────────────────────
//  一、三种排序共同的骨架
// ─────────────────────────────────────────────────────
//
//     for (int i = 0; i < n - 1; i++) {        外层：一共几轮
//         for (int j = ...; j < ...; j++) {    内层：这一轮比哪些
//             ...
//         }
//     }
//
// ⚠ 外层只走到 n - 1：最后一轮只剩一个元素，它本来就该在那儿。
//
// ─────────────────────────────────────────────────────
//  二、交换：三句话，一句都不能少
// ─────────────────────────────────────────────────────
//
//     int t = a[j];         ← 先存起来
//     a[j] = a[j + 1];      ← 覆盖
//     a[j + 1] = t;         ← 把存的放回去
//
// ⚠ 要交换两个格子，**必须有第三个变量**。少了 t 就变成覆盖（见下面的坑）。
//
// ─────────────────────────────────────────────────────
//  三、冒泡
// ─────────────────────────────────────────────────────
//
//     for (int i = 0; i < n - 1; i++) {
//         for (int j = 0; j < n - 1 - i; j++) {
//             if (a[j] > a[j + 1]) { 把这两个换过来 }
//         }
//     }
//
// ⚠ 内层上界写 **n - 1 - i**，不是 n - 1，更不能写 n：
//     n - 1 - i ：每走完一轮，末尾就多一个排好的，不用再比（最省）
//     n - 1     ：结果一样，只是白比几轮
//     n         ：会读到 a[n] —— **越界**，那是别人家的内存
//
// ─────────────────────────────────────────────────────
//  四、插入
// ─────────────────────────────────────────────────────
//
//     for (int i = 1; i < n; i++) {
//         int 手里 = a[i];                    ← 先把手里的牌拿出来
//         int j = i - 1;                      ← 这个位置就空出来了
//         while (j >= 0 && a[j] > 手里) {
//             a[j + 1] = a[j];                ← 比手里大的往后挪一格
//             j--;
//         }
//         a[j + 1] = 手里;                    ← 找到位置，放回去
//     }
//
// ⚠ 两处最容易写错：
//   ① `j >= 0` 必须写在 `&&` **前面**。反过来的话 j 会减到 -1 再去读 a[-1]。
//   ② 最后放回的位置是 **j + 1**，不是 j（循环退出时 j 已经又减了一次）。
//
// ─────────────────────────────────────────────────────
//  五、选择
// ─────────────────────────────────────────────────────
//
//     for (int i = 0; i < n - 1; i++) {
//         int 最小 = i;                        ← 先假设第 i 个就是最小的
//         for (int j = i + 1; j < n; j++) {
//             if (a[j] < a[最小]) 最小 = j;    ← 找到真正最小的**下标**
//         }
//         把 a[i] 和 a[最小] 换过来
//     }
//
// ⚠ 记的是**下标**，不是值。记值的话你只知道"最小是 1"，
//   却不知道它在第几个格子，没法换。
//
// ⚠ `int 最小 = i;` 里的 **= i 不能省** —— 省了就是下面这个坑。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：交换写成了覆盖
// ─────────────────────────────────────────────────────
//
// 这是排序课最典型的错，而且 **gcc 一个字都不报**：
//
//     if (a[j] > a[j + 1]) {
//         a[j] = a[j + 1];          ← 第一句把 a[j] 盖掉了
//         a[j + 1] = a[j];          ← 这句读到的已经是新的 a[j]
//     }
//
// 你会看到：编译通过、程序跑完，打出来**还是原来那串数**。
//   为什么：两个格子变成了同一个值，原来的 a[j] 已经被冲掉了。
//   ⇒ 要交换，**必须**有个第三者：int t = a[j]; a[j] = a[j+1]; a[j+1] = t;
//
// 真正会被 gcc 抓到的，是选择排序里另一个错 —— 忘了给「最小」起头：
//
//     int 最小下标;
//     for (int j = i + 1; j < n; j++)
//         if (a[j] < a[最小下标]) 最小下标 = j;
//
// $ gcc -std=c11 -O1 -Wall 选择.c -o 选择
//     选择.c:10:25: warning: '\U00006700\U00005c0f\U00004e0b\U00006807' may be used uninitialized [-Wmaybe-uninitialized]
//        10 |             if (a[j] < a[最小下标]) 最小下标 = j;
//           |                        ~^~~~~~~~~~
//
// （gcc 把中文变量名转义成了 \U00006700 这样的码点 —— 它说的就是「最小下标」，
//   不是乱码。第一次见会被吓一跳，见两次就习惯了。）
//
// ⇒ 看到 "may be used uninitialized"，第一件事就是回去找**哪个变量没给初值**。
//   （gcc 不是每次都能看出来，所以它只说 may —— 但它说的时候基本没冤枉你。）
//
// ─────────────────────────────────────────────────────
//  这一课不碰什么
// ─────────────────────────────────────────────────────
//   排序快不快（算法复杂度）→ 第 23 课专门讲
