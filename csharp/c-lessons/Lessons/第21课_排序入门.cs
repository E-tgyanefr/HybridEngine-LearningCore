#include <stdio.h>

void 打印(int a[], int n) {
    for (int i = 0; i < n; i++) {
        if (i > 0) printf(" ");
        printf("%d", a[i]);
    }
    printf("\n");
}

void 冒泡(int a[], int n) {
    for (int i = 0; i < n - 1; i++) {
        for (int j = 0; j < n - 1 - i; j++) {
            if (a[j] > a[j + 1]) {
                int t = a[j];              /* 交换必须有第三者 */
                a[j] = a[j + 1];
                a[j + 1] = t;
            }
        }
    }
}

void 插入(int a[], int n) {
    for (int i = 1; i < n; i++) {
        int 手里 = a[i];
        int j = i - 1;
        while (j >= 0 && a[j] > 手里) {
            a[j + 1] = a[j];
            j--;
        }
        a[j + 1] = 手里;                   /* ⚠ 是 j + 1，不是 j */
    }
}

void 选择(int a[], int n) {
    for (int i = 0; i < n - 1; i++) {
        int 最小 = i;                      /* ⚠ = i 不能省 */
        for (int j = i + 1; j < n; j++) {
            if (a[j] < a[最小]) 最小 = j;
        }
        int t = a[i];
        a[i] = a[最小];
        a[最小] = t;
    }
}

int main(void) {
    int 甲[6] = {5, 3, 8, 1, 9, 2};
    int 乙[7] = {7, 7, 1, 4, 1, 9, 0};
    int 副本[7];

    for (int i = 0; i < 6; i++) 副本[i] = 甲[i];
    冒泡(副本, 6);
    printf("冒泡 第一组："); 打印(副本, 6);

    for (int i = 0; i < 7; i++) 副本[i] = 乙[i];
    冒泡(副本, 7);
    printf("冒泡 第二组："); 打印(副本, 7);

    for (int i = 0; i < 6; i++) 副本[i] = 甲[i];
    插入(副本, 6);
    printf("插入 第一组："); 打印(副本, 6);

    for (int i = 0; i < 7; i++) 副本[i] = 乙[i];
    插入(副本, 7);
    printf("插入 第二组："); 打印(副本, 7);

    for (int i = 0; i < 6; i++) 副本[i] = 甲[i];
    选择(副本, 6);
    printf("选择 第一组："); 打印(副本, 6);

    for (int i = 0; i < 7; i++) 副本[i] = 乙[i];
    选择(副本, 7);
    printf("选择 第二组："); 打印(副本, 7);

    return 0;
}
""";


