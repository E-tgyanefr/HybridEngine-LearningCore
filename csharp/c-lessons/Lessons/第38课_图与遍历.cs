    public static string 参考答案 => """
#include <stdio.h>

#define 点数 6

int 连[点数][点数];
int 访问过[点数];
int 要打印 = 1;              /* ⚠ 数连通块的时候要把它关掉 */

void 加边(int a, int b) {
    连[a][b] = 1;
    连[b][a] = 1;                      /* ⚠ 无向边，两边都要 */
}

void dfs(int 点) {
    if (要打印) printf("%d ", 点);      /* 数块的时候不打印 */
    访问过[点] = 1;
    for (int j = 0; j < 点数; j++) {
        if (连[点][j] && !访问过[j]) dfs(j);   /* 邻居从小到大 */
    }
}

void bfs(int 起点) {
    int 队[点数 * 点数];
    int 队头 = 0, 队尾 = 0;

    队[队尾] = 起点;
    队尾++;
    访问过[起点] = 1;                      /* ⚠ 入队的同时就标记 */

    while (队头 < 队尾) {
        int 点 = 队[队头];
        队头++;
        printf("%d ", 点);

        for (int j = 0; j < 点数; j++) {
            if (连[点][j] && !访问过[j]) {
                访问过[j] = 1;             /* 先标记 */
                队[队尾] = j;               /* 再入队 */
                队尾++;
            }
        }
    }
}

int 数连通块(void) {
    for (int i = 0; i < 点数; i++) 访问过[i] = 0;    /* ⚠ 一定要清零 */
    int 块数 = 0;
    要打印 = 0;              /* ⚠ 关掉打印，否则会串到上一行后面去 */
    for (int i = 0; i < 点数; i++) {
        if (!访问过[i]) {
            块数++;
            dfs(i);                    /* 把这一伙全标上（但不打印） */
        }
    }
    要打印 = 1;
    return 块数;
}

int main(void) {
    加边(0, 1);
    加边(0, 2);
    加边(1, 2);
    加边(1, 3);
    加边(2, 3);
    加边(4, 5);

    printf("DFS: ");
