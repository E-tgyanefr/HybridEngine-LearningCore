    public static string 参考答案 => """
int 爬楼梯(int n) {
    int 表[50];                      /* ⚠ 比用得到的最大下标再大一点 */
    表[1] = 1;                       /* 走到第 1 级：1 种 */
    表[2] = 2;                       /* 走到第 2 级：1+1 和 2，共 2 种 */
    for (int i = 3; i <= n; i++) {
        表[i] = 表[i - 1] + 表[i - 2];   /* 最后一步走 1 级，或者走 2 级 */
    }
    return 表[n];
}

int 斐波那契(int n) {
    int 表[50];
    表[0] = 0;                       /* ⚠ 初始值：0 和 1 */
    表[1] = 1;
    for (int i = 2; i <= n; i++) {
        表[i] = 表[i - 1] + 表[i - 2];
    }
    return 表[n];
}
""";


