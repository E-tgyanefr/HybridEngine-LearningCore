//  这一课你会学到
// ─────────────────────────────────────────────────────
//    递推：从最小的答案出发，一步一步**从前往后**推出更大的答案
//
//  需要先会
//    第 09 课：数组（递推表就是数组）
//    第 07 课：for 循环
//    第 19 课：递归（这一课正好是它的反面）
//
// ─────────────────────────────────────────────────────
//  先介绍：和第 19 课的递归比一比
// ─────────────────────────────────────────────────────
//
// 第 19 课写过这个斐波那契：
//
//     int 斐波那契(int n) {
//         if (n <= 1) return n;
//         return 斐波那契(n - 1) + 斐波那契(n - 2);     ← 算 fib(45) 要等很久
//     }
//
// 慢的原因第 19 课说过：**同一个答案被重复算了无数遍**。
//
// 换个方向想：既然要算到 fib(45)，那就**从 fib(0) 开始一个一个往上算**，
// 每算出一个就记在表里 —— 每个答案只算一次，一次也不浪费：
//
//     表[0] = 0
//     表[1] = 1
//     表[2] = 表[1] + 表[0] = 1
//     表[3] = 表[2] + 表[1] = 2
//     表[4] = 表[3] + 表[2] = 3
//     ...
//
// 这就是**递推**：从已知的最小的答案出发，一步一步推出更大的答案。
//
// ─────────────────────────────────────────────────────
//  一、递推的两个零件
// ─────────────────────────────────────────────────────
//
// ① **初始值** —— 表里最小的那几项，手写死
// ② **递推式** —— 表[i] 怎么由前面几项算出来
//
//     int 表[50];
//     表[0] = 0;                          ← ① 初始值
//     表[1] = 1;                          ← ① 初始值
//     for (int i = 2; i <= n; i++) {
//         表[i] = 表[i - 1] + 表[i - 2];  ← ② 递推式
//     }
//     return 表[n];
//
// ⚠ 初始值写错，后面**全错** —— 而且错得很像"对的"。这是本课的坑。
//
// ─────────────────────────────────────────────────────
//  二、爬楼梯：最后一步倒着想
// ─────────────────────────────────────────────────────
//
// 题目：一次只能走 1 级或 2 级，走到第 n 级有多少种走法？
//
//   走到第 1 级：1 种（1）
//   走到第 2 级：2 种（1+1、2）
//   走到第 3 级：3 种（1+1+1、1+2、2+1）
//
// ⇒ 想**最后一步**：到第 n 级，只能是从第 n-1 级走了 1 级上来，
//   或者从第 n-2 级走了 2 级上来。**没有第三种可能。**
//
//     表[n] = 表[n - 1] + 表[n - 2]        初始值：表[1] = 1，表[2] = 2
//
// ⚠ 它和斐波那契是**同一个递推式**，只是初始值不同：
//
//     斐波那契：表[0] = 0，表[1] = 1    ⇒ 0 1 1 2 3 5 8 13 …
//     爬楼梯  ：表[1] = 1，表[2] = 2    ⇒ 1 2 3 5 8 13 21 …
//
//   整整差了**一号**。所以爬楼梯不能照抄斐波那契的初始值。
//
// ─────────────────────────────────────────────────────
//  三、为什么递推这么快
// ─────────────────────────────────────────────────────
//
//     递归版 fib(45)：函数调用自己大约**十亿次**
//     递推版 fib(45)：循环 **45 次**
//
// 这就是第 23 课的复杂度：一个涨得像爆炸，一个是老老实实的 O(n)。
// 同一道题，换个写法，从"算不出来"变成"眨眼就好"。
//
// ─────────────────────────────────────────────────────
//  四、表要开多大，答案能装多大
// ─────────────────────────────────────────────────────
//
// 表开多大？**比你会用到的最大下标再大一点**：
//
//     int 表[50];        要算到 表[45] ⇒ 开 50 够用（下标 0..49）
//
// ⚠ 宁可多开几个。开小了就是越界写 —— 而**越界写通常不会报错**，
//   只会让程序里别的地方莫名其妙地出错，最难查。
//
// 还有答案本身能装多大：
//
//     fib(45) = 1134903170      装得下
//     fib(46) = 1836311903      也装得下（int 最大约 21 亿）
//     fib(47) = 2971215073      ✗ **装不下了**
//
// ⇒ 想算更大的，把 int 换成 **long long**，printf 也要跟着换成 **%lld**。
//   忘换格式符的话，gcc 会明确告诉你（这条警告很有用，别忽略）：
//
// $ gcc -std=c11 -O1 -Wall 爬楼.c -o 爬楼
//     爬楼.c:8:27: warning: format '%d' expects argument of type 'int', but argument 2 has type 'long long int' [-Wformat=]
//         8 |     printf("爬到第90级有 %d 种走法\n", 爬楼[90]);
//           |                          ~^            ~~~~~~~~
//           |                           |                |
//           |                           int              long long int
//           |                          %lld
//
// ⇒ gcc 甚至在最后一行告诉你"应该用 %lld"。看到 %format= 就去改格式符。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：初始值差一号，后面全错
// ─────────────────────────────────────────────────────
//
// 斐波那契写顺了手，写爬楼梯时容易直接照抄：
//
//     int 表[50];
//     表[0] = 0;                  ← 爬楼梯用不到表[0]
//     表[1] = 1;                  ← 对
//     表[2] = 1;                  ← ✗ 错！爬楼梯是 2 种，不是 1 种
//     for (int i = 3; i <= n; i++) 表[i] = 表[i-1] + 表[i-2];
//     return 表[n];
//
// 你会看到：**编译通过、不崩、不报错，结果全小了一号**：
//
//     爬楼梯(1) = 1      （碰巧对）
//     爬楼梯(2) = 1      （错，应该 2）
//     爬楼梯(5) = 5      （错，应该 8）
//
// 为什么：递推是"从前往后推"，**起点错了，后面每一步都跟着错**。
//   递归至少还会在某个基准情形上停一下，递推是错得整整齐齐。
