//
//  需要先会
//    第 10 课：字符串（文件名就是一个字符串）
//    第 18 课：while（读文件是"读到读不动为止"）
//
// ─────────────────────────────────────────────────────
//  先介绍：程序关了，东西还在吗
// ─────────────────────────────────────────────────────
//
// 到目前为止，程序里算出来的东西都是**内存里**的 ——
// 程序一退出，全没了。想让成绩表、日记、存档留下来，就得写进**文件**。
//
// C 里操作文件要用一个特殊的"把手"：**FILE ***。
// 你可以把它想成"一根通向那个文件的管子"：
//
//     FILE *文件 = fopen("out.txt", "w");     ← 打开管子
//     fprintf(文件, "内容");                  ← 通过管子往里写
//     fclose(文件);                           ← 关掉管子
//
// ⚠ 文件名和模式都是**字符串**，用双引号。
//
// ─────────────────────────────────────────────────────
//  一、四个函数，就这四个
// ─────────────────────────────────────────────────────
//
//  FILE *fopen(名字, 模式)       打开文件，返回"管子"；**失败返回 NULL**
//  int   fclose(管子)            关掉。写完**必须**关，不然可能还没落盘
//  int   fprintf(管子, ...)      和 printf 一模一样，只是多一个"往哪写"
//  char *fgets(缓冲, 大小, 管子) 读**一行**；读到文件尾返回 NULL
//
// 模式（第二个参数）：
//
//     "r"   只读。**文件必须已经存在**，不存在就返回 NULL
//     "w"   只写。文件不存在就新建；**存在就清空**（⚠ 这个很危险）
//     "a"   追加。写在文件末尾，不清空
//
// ⚠ `"w"` 会**清空**已有的文件。想留着原来的内容，就用 `"a"`。
//
// ─────────────────────────────────────────────────────
//  二、写文件的固定套路
// ─────────────────────────────────────────────────────
//
//     FILE *文件 = fopen("out.txt", "w");
//     if (文件 == NULL) {                  ← ⚠ 这一步不能省
//         printf("打不开文件\n");
//         return 1;
//     }
//     fprintf(文件, "第一行\n");            ← \n 要自己写
//     fprintf(文件, "第二行\n");
//     fclose(文件);
//
// ⚠ fprintf **不会**自己加换行（和 puts 不一样），想要换行就写 \n。
//
// ─────────────────────────────────────────────────────
//  三、读文件的固定套路
// ─────────────────────────────────────────────────────
//
//     FILE *文件 = fopen("out.txt", "r");
//     if (文件 == NULL) { ... }
//
//     char 行[100];
//     while (fgets(行, sizeof(行), 文件) != NULL) {
//         printf("读到：%s", 行);           ← ⚠ 这里的 \n 是 fgets 带回来的
//     }
//     fclose(文件);
//
// 逐句读：
//
//     fgets(行, sizeof(行), 文件)
//       · 从文件里读**一行**，放进 行 这个数组
//       · 第二个参数是"最多能装多少字节"，**别写错**（写大了就越界）
//       · 读到文件末尾（或者出错）⇒ 返回 NULL
//
// ⇒ `while (fgets(...) != NULL)` 就是"能读一行就读一行，读不动了就停"。
//   这是 C 里读文本文件**最标准**的写法。
//
// ⚠ fgets **会把行尾的换行符也读进来**（它就是这一行的一部分）。
//   所以 printf("%s") 打出来天然就换行了 —— **别再自己加一个 \n**，
//   加了就会出现空行。
//
// ⚠ fgets 读的字节数到了上限也会停（行太长会被截成两半）。
//   所以缓冲区（行[100]）要开得比最长的一行大。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：fopen 失败了要当场停住
// ─────────────────────────────────────────────────────
//
// **打开文件是会失败的**，而且失败的理由全都是日常的：
//
//     文件不存在（"r" 模式最常见）
//     路径写错、目录不存在
//     没有权限（在别人的目录里写东西）
//     文件正被别的程序占着
//
// 失败时 fopen 返回 **NULL**，而不是"一个不能用的管子"。
// 你要是**不看**，拿着 NULL 继续往下用：
//
//     FILE *文件 = fopen("没有这个目录/笔记.txt", "r");
//     char 行[100];
//     fgets(行, sizeof(行), 文件);          ← 文件是 NULL
//     printf("%s", 行);
//
// 你会看到：**程序不一定当场崩** —— 更常见的是打出一堆**乱码**，
//   而且退出码还是 0。因为 fgets 失败了，什么都没往 `行` 里写，
//   `行` 里是上次留下的垃圾，printf 就把垃圾打出来了。
//
// ⚠ 比崩溃更难查：崩溃至少告诉你"出事了"，乱码让你以为**文件里就是这些乱码**。
//
// 另一个最常见的写法错：模式写成**单引号**（'w' 而不是 "w"）——
//   这个 gcc 会当场拦住你：
//
// $ gcc -std=c11 -O1 -Wall 文件.c -o 文件
//     文件.c:5:35: error: passing argument 2 of 'fopen' makes pointer from integer without a cast [-Wint-conversion]
//         5 |     FILE *文件 = fopen("out.txt", 'w');
//           |                                   ^~~
//           |                                   |
//           |                                   int
//     note: expected 'const char * restrict' but argument is of type 'int'
//
// 读法：fopen 的第二个参数要的是**字符串**（const char *），你给的是**一个字符**（int）。
// ⇒ 报错里看到 "expected ... but argument is of type"，就去对**参数类型**。
//
// ⇒ 记法：**打开之后第一件事就是问一句"打开了吗"。**
//     if (文件 == NULL) { 说一声，然后 return 或退出这段逻辑 }
//   这三个字母 NULL 是本课最该背下来的东西。
//
// ─────────────────────────────────────────────────────
//  这一课不碰什么
// ─────────────────────────────────────────────────────
//   二进制文件（fread / fwrite / "wb"）→ 不涉及
//   在文件里跳来跳去（fseek / ftell）→ 不涉及
//   文件编码（UTF-8 / GBK）、换行符跨平台 → 不涉及
//
// ─────────────────────────────────────────────────────
