#include <stdio.h>

int main(void) {
    const char *文件名 = "out.txt";

    /* ── 写：三行 ── */
    FILE *写 = fopen(文件名, "w");
    if (写 == NULL) {                      /* ⚠ 这一步不能省 */
        printf("打不开文件：%s\n", 文件名);
        return 1;
    }
    fprintf(写, "第一行\n");
    fprintf(写, "第二行\n");
    fprintf(写, "第三行\n");
    fclose(写);

    /* ── 读：一行一行读回来 ── */
    FILE *读 = fopen(文件名, "r");
    if (读 == NULL) {                      /* ⚠ 这一步不能省 */
        printf("打不开文件：%s\n", 文件名);
        return 1;
    }

    char 行[100];
    int 第几行 = 1;
    while (fgets(行, sizeof(行), 读) != NULL) {
        printf("读到第 %d 行：%s", 第几行, 行);   /* 行尾的 \n 是 fgets 带回来的 */
        第几行++;
    }
    fclose(读);

    printf("一共读了 %d 行\n", 第几行 - 1);
    return 0;
}
""";


    [检查说明("三行都写进去又读回来了")]
    public static CheckResult 检查_1(string 代码)
    {
        var run = CppCheck.直接运行(代码);
        if (!run.编译通过) return CppCheck.编译失败说明(run);
        string[] 要找 = {
            "读到第 1 行：第一行",
            "读到第 2 行：第二行",
            "读到第 3 行：第三行",
        };
        var 实际 = run.行;
        int 从这 = 0;
        for (int i = 0; i < 要找.Length; i++)
        {
            int 找到 = -1;
            for (int j = 从这; j < 实际.Count; j++)
                if (实际[j].Trim() == 要找[i]) { 找到 = j; break; }
            if (找到 < 0)
                return CheckResult.不过(
                    $"输出里找不到这一行：\n        {要找[i]}\n" +
                    "      打印出来的：\n        " + string.Join("\n        ", 实际));
            从这 = 找到 + 1;      // 下一行必须在这之后
        }
        return CheckResult.过($"{要找.Length} 行都按顺序出现了");
    }

