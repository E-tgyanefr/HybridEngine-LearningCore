                    $"输出里找不到这一行：\n        {要找[i]}\n" +
                    "      打印出来的：\n        " + string.Join("\n        ", 实际));
            从这 = 找到 + 1;      // 下一行必须在这之后
        }
        return CheckResult.过($"{要找.Length} 行都按顺序出现了");
    }

