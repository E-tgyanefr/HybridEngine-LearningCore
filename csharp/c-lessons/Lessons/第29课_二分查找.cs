//     再猜 …
//
//     100 → 50 → 25 → 13 → 7 → 4 → 2 → 1
//     最多 **7 次**就猜中。
//
// ⇒ 这就是二分查找：**每次都从正中间下手，一步砍掉一半。**
//
// 一百万个数里找一个，二分最多 20 次（2 的 20 次方约等于 100 万）。
// 一个一个找要一百万次 —— 快 5 万倍。
//
// ─────────────────────────────────────────────────────
//  一、前提：数组必须是**有序**的
// ─────────────────────────────────────────────────────
//
// ⚠ 二分查找**只对排好序的数组有效**。
//
//   为什么：二分是靠"中间这个数比目标小 ⇒ 目标一定在右半边"来砍的。
//   数组要是乱的，右半边也可能有更小的数，这句话就不成立，
//   被砍掉的那一半里可能正藏着答案 —— 于是**结果静悄悄地错**。
//
// ⇒ 所以排序和二分是一对搭档（第 21 课先排好，这一课才好查）。
//
// ⚠ 用之前问自己一句：**这个数组保证有序吗？**
//
// ─────────────────────────────────────────────────────
//  二、怎么写：三个变量
// ─────────────────────────────────────────────────────
//
// 把"还有可能藏着答案的那一段"用两个下标框住：
//
//     左 = 0            ← 可能区间的开头（含）
//     右 = n - 1        ← 可能区间的结尾（**也含**）
//     中 = (左 + 右) / 2
//
// 然后看 a[中]：
//
//     a[中] == 目标   ⇒ 找到了，返回 中
//     a[中] <  目标   ⇒ 答案在右半边 ⇒ 左 = 中 + 1
//     a[中] >  目标   ⇒ 答案在左半边 ⇒ 右 = 中 - 1
//
// 一直做到这段区间**空了**（左 > 右）⇒ 整个数组都没有 ⇒ 返回 -1。
//
//     int 二分查找(int a[], int n, int 目标) {
//         int 左 = 0;
//         int 右 = n - 1;
//         while (左 <= 右) {                    ← ⚠ 是 <=，不是 <
//             int 中 = (左 + 右) / 2;
//             if (a[中] == 目标) return 中;
//             if (a[中] < 目标) 左 = 中 + 1;    ← ⚠ 有 +1
//             else              右 = 中 - 1;    ← ⚠ 有 -1
//         }
//         return -1;                            ← ⚠ 别忘
//     }
//
// ─────────────────────────────────────────────────────
//  三、边界到底怎么写才对
// ─────────────────────────────────────────────────────
//
// 这一课唯一"绕"的地方就是那三个 ⚠。逐个说清楚：
//
//   ① `while (左 <= 右)` 里的 **= 不能少**。
//      区间里只剩一个数（左 == 右）时，那个数**还没被检查过**，必须再看一眼。
//      写成 `左 < 右` 的话，最后那一个数会被漏掉 ——
//      症状是"明明有的数却查不到"。
//
//   ② `左 = 中 + 1`、`右 = 中 - 1` 里的 **+1 / -1 不能少**。
//      a[中] 已经确认不是答案了，它不该留在区间里。
//      写成 `左 = 中` 的话，区间不会缩小 ⇒ **死循环**
//      （程序卡住不动，最后被检查工具当成超时杀掉）。
//
//   ③ `return -1` 不能忘。
//      "找不到"必须有明确的返回值。忘了写 gcc 会警告，
//      但不拦你 —— 程序会返回一个**垃圾值**（见下面的坑）。
//
// ⚠ 还有个习惯：`中 = 左 + (右 - 左) / 2` 比 `(左 + 右) / 2` 更稳。
//   两个下标都很大时，`左 + 右` 可能超过 int 装得下的范围（第 23 课那种溢出）。
//   这一课的数很小，两种写法都对；但**先减后除**的习惯值得早点养成。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：忘了写"找不到"的返回值
// ─────────────────────────────────────────────────────
//
//     int 二分查找(int a[], int 左, int 右, int 目标) {
//         while (左 <= 右) {
//             int 中 = (左 + 右) / 2;
//             if (a[中] == 目标) return 中;
//             if (a[中] < 目标) 左 = 中 + 1;
//             else 右 = 中 - 1;
//         }
//         /* 找不到的时候该返回什么？—— 没写 */
//     }
//
// gcc 会明确警告你（而且只有加上 -Wall 才会说）：
//
// $ gcc -std=c11 -O1 -Wall 二分.c -o 二分
//     二分.c:12:1: warning: control reaches end of non-void function [-Wreturn-type]
//        12 | }
//           | ^
//
// 读法：`control reaches end of non-void function` =
//   "程序有一条路能走到函数结尾，可这个函数**不是 void**（它答应要返回一个 int）"。
//
// ⇒ 看到这句话，就去找**哪条分支忘了 return**（这里就是"找不到"那条）。
//
// ⚠ 它只是**警告**，不是错误 —— 程序照样能编译、能跑。
//   跑起来会返回一个**谁也不知道是什么的垃圾值**，于是：
//
//     本该返回 -1 表示"找不到"，它却可能返回 3 —— 你就去打了 a[3]，
//     看着像找到了，其实是错的。
//
// ⇒ 这类"能跑但答案错"的东西比报错难查得多。
//   **凡是说好要返回 int 的函数，每条走出去的路都得有 return。**
//
// ─────────────────────────────────────────────────────
//  这一课不碰什么
// ─────────────────────────────────────────────────────
//   二分答案（在答案本身上二分）→ 竞赛里的重头戏，但不是这一课
