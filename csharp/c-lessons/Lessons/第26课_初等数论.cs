//  先介绍：三个词
// ─────────────────────────────────────────────────────
//
//   · **整除**：`a % b == 0` 就是 b 能整除 a，一点不剩。
//   · **因数**：能整除 n 的正整数。比如 12 的因数有 1 2 3 4 6 12。
//   · **质数**（素数）：**只有 1 和它自己**两个因数的数。
//       2 3 5 7 11 13 17 19 … 都是质数
//       1 **不是**质数（它只有一个因数）
//       4 = 2×2 不是，9 = 3×3 不是，6 = 2×3 不是
//
// ⚠ 「1 不是质数」是初学最容易忘的一条 —— 它不是硬性规定，而是因为
//   "只有 1 和它自己两个因数"这句话，1 不满足（它只有一个）。
//
// ─────────────────────────────────────────────────────
//  一、数因数：从 1 试到 n
// ─────────────────────────────────────────────────────
//
// 判断 i 是不是 n 的因数，就是问一句 `n % i == 0`。全都试一遍就数完了：
//
//     int 个数 = 0;
//     for (int i = 1; i <= n; i++) {
//         if (n % i == 0) 个数++;
//     }
//
// ⚠ 从 **1** 开始试，不是 2 —— 因为 1 是所有数的因数。
//
// ─────────────────────────────────────────────────────
//  二、判断质数：试到 根号n 就够了
// ─────────────────────────────────────────────────────
//
// 笨办法是"数一数因数是不是正好两个"。但判断 1000003 要试一百万次。
// 其实只要试到 **√n**：
//
//     int 是质数(int n) {
//         if (n < 2) return 0;               ← ⚠ 0 和 1 不是质数
//         for (int i = 2; i * i <= n; i++) {
//             if (n % i == 0) return 0;      ← 找到一个因数就不是质数
//         }
//         return 1;
//     }
//
// 为什么只试到 √n：
//
//     如果 n = a × b 且 a ≤ b，那么一定有 a ≤ √n。
//     换句话说，**n 只要有因数，小的那个一定不超过 √n**。
//     所以试完 √n 还没找到，就真的没有了。
//
// ⚠ 写 `i * i <= n`，别写 `i <= sqrt(n)`：
//     · 不用 #include <math.h>，全程整数
//     · 不怕 sqrt 算出来的小数有误差（差一点点就可能漏判）
//   这一课的检查会看源码里有没有 `i * i <=`，就用这个写法。
//
// ─────────────────────────────────────────────────────
//  三、质因数分解：从小到大一直除
// ─────────────────────────────────────────────────────
//
//     360 = 2 × 2 × 2 × 3 × 3 × 5
//
// 做法：从 2 开始，**能除就一直除**，除不动了再换下一个数：
//
//     int 剩 = n;
//     for (int i = 2; i * i <= 剩; i++) {
//         while (剩 % i == 0) {
//             printf("%d ", i);          ← i 就是一个质因数
//             剩 /= i;
//         }
//     }
//     if (剩 > 1) printf("%d ", 剩);     ← ⚠ 这一句别忘
//
// ⚠ 两个关键点：
//
//   ① 用 **while** 不是 if —— 同一个质因数可能要除好几次（360 里 2 出现 3 次）。
//   ② 最后那个 `if (剩 > 1)` **不能省**。看 360：
//        除完 2 剩 45，除完 3 剩 5；这时 i 已经试过 √5，循环停了，
//        可 5 还是个质因数，得单独补上。
//      漏了它，360 就被分解成 "2 2 2 3 3"，少一个。
//
// ⚠ 循环条件是 `i * i <= 剩`（跟着剩一起变小），不是 `<= n`。
//   写 `<= n` 结果也对，只是白试很多次。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：== 写成了 =
// ─────────────────────────────────────────────────────
//
//     for (int i = 2; i * i <= n; i++) {
//         if (n % i = 0) return 0;          ← 少写了一个 =
//     }
//
// 幸运的是，这个错 gcc **一定会当场拦住**：
//
// $ gcc -std=c11 -O1 -Wall 质数.c -o 质数
//     质数.c:8:19: error: lvalue required as left operand of assignment
//         8 |         if (n % i = 0) { 是质数 = 0; break; }
//           |                   ^
//
// 读法：`lvalue` 是"能装东西的格子"（left value，能放在等号左边的值）。
//   `n % i` 是**算出来的一个临时结果**，不是一个格子 ——
//   给临时结果赋值没有意义，所以 gcc 说"等号左边不是一个左值"。
//
// ⇒ 看到 **lvalue required as left operand of assignment**，
//   先去看那一行的 `=`：**是不是该写 `==`？**（九成是。）
//
// ⚠ 这也是 C 比 Python 危险的地方：Python 里 `if a = 1` 直接报语法错，
//   而 C 里 `if (a = 1)` 是**合法**的（把 1 赋给 a，再判断 1 真不真）——
//   只有像 `n % i = 0` 这种"左边根本不是格子"的情况才会被拦下。
