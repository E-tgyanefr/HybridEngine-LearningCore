    public static string 参考答案 => """
int 是质数(int n) {
    if (n < 2) return 0;                 /* ⚠ 0 和 1 都不是质数 */
    for (int i = 2; i * i <= n; i++) {   /* 试到 根号n 就够 */
        if (n % i == 0) return 0;        /* 找到一个因数就不是质数 */
    }
    return 1;
}

int 因数个数(int n) {
    int 个数 = 0;
    for (int i = 1; i <= n; i++) {       /* ⚠ 从 1 开始 */
        if (n % i == 0) 个数++;
    }
    return 个数;
}

int 质因数个数(int n) {
    int 个数 = 0;
    for (int i = 2; i * i <= n; i++) {
        while (n % i == 0) {             /* ⚠ while：同一个质因数要数好几遍 */
            个数++;
            n /= i;
        }
    }
    if (n > 1) 个数++;                   /* ⚠ 最后可能还剩一个大的质因数 */
    return 个数;
}
""";


