// 第 06 课：if —— 让程序做选择
//
// ─────────────────────────────────────────────────────
//  先介绍：if 让程序分岔
// ─────────────────────────────────────────────────────
//
//     if (条件) {
//         条件成立时做的事
//     } else {
//         不成立时做的事
//     }
//
// ⚠ C 的 if 有**两处括号**，都要写：
//     if (分数 >= 90) {        ← 条件外面那对圆括号不能少
//         ...
//     }                        ← 花括号也别忘
//
// 比较运算符：
//     ==  等于      ⚠⚠ **两个等号**！一个等号是赋值
//     !=  不等于
//     >   大于      >=  大于等于
//     <   小于      <=  小于等于
//
// ⚠⚠ 最常见的错：
//     if (分数 = 90)           ❌ 这是**赋值**！把 90 塞进分数，然后判断 90 是不是真
//     if (分数 == 90)          ✅
//     而且 `if (分数 = 90)` **不一定报错** —— 它会永远成立（90 非 0 = 真）。
//     这就是最难查的一类错。看到 if 里只有一个等号，立刻改掉。
//
// ⚠ 判断的顺序很重要（和 Python 一样）：
//     if (分数 >= 60) return 2;
//     else if (分数 >= 90) return 3;   ← 到不了这里！
//   95 分在第一行就满足了。⇒ **从最严格的往最宽松的写**。
//
// ⚠ C 里没有"真/假"类型（C99 之前），约定：**0 是假，非 0 是真**。
//
// ─────────────────────────────────────────────────────
//  用法与例子
// ─────────────────────────────────────────────────────
//
//  ① 只有一种情况要处理，用不带 else 的 if：
//
//      if (分数 >= 60) {
//          printf("及格\n");
//      }
//
//  ② 两种情况，用 if / else：
//
//      if (分数 >= 60) {
//          printf("及格\n");
//      } else {
//          printf("不及格\n");
//      }
//
//  ③ 多种情况，用 else if 串起来 —— **从最严格写到最宽松**：
//
//      if (分数 >= 90) {
//          return 3;
//      } else if (分数 >= 60) {
//          return 2;
//      } else {
//          return 1;
//      }
//
//  ④ 组合条件：`&&` 是"并且"，逻辑或运算符 是"或者"，`!` 是"不"。
//
//      if (分数 >= 60 && 出勤 >= 0.8) { ... }
//      if (分数 < 0 逻辑或运算符 分数 > 100) { ... }        /* 分数不合法 */
//
//  ⑤ C 的"真假"约定：**0 是假，非 0 是真**。
//     所以 `if (分数)` 的意思是"分数不为 0 就成立"，
//     而 `if (分数 == 1)` 才是"分数等于 1"。两回事。
//
//  一个完整的、能跑的例子：
//
//      #include <stdio.h>
//
//      int 判等级(int 分) {
//          if (分 >= 90) {
//              return 3;
//          } else if (分 >= 60) {
//              return 2;
//          } else {
//              return 1;
//          }
//      }
//
//      int main(void) {
//          printf("%d\n", 判等级(95));      ⇒ 3
//          printf("%d\n", 判等级(90));      ⇒ 3
//          printf("%d\n", 判等级(60));      ⇒ 2
//          printf("%d\n", 判等级(59));      ⇒ 1
//          return 0;
//      }
//
//  ⚠ 上面四个数就是这一课要过的那四条边界 ——
//    95 和 90 都是 3（>= 不是 >）、60 是 2、59 是 1。
//    写 if 的时候**一定要拿边界值各走一遍**。
//
// ─────────────────────────────────────────────────────
//  常见坑
// ─────────────────────────────────────────────────────
//
//  ⚠ 坑 1：把 == 写成了 =
//
//      错误写法：
//          int x = 5;
//          if (x = 0) {
//              printf("真\n");
//          }
//
//      你会看到什么（gcc 原文，只是 warning）：
//
//          main.c:5:9: warning: suggest parentheses around assignment used as truth value [-Wparentheses]
//              5 │     if (x = 0) { printf("真\n"); }
//                │         ^
//
//      运行时：`真` **不会**被打印（因为 x 被赋成 0，而 0 是假）——
//      但你的 x 已经被**悄悄改成了 0**！
//
//      为什么：`=` 是赋值，它的"结果"就是赋进去的那个值。
//      所以 `if (x = 0)` 走的是"把 0 存进 x，然后判断 0 是不是真"。
//      如果写成 `if (x = 1)`，条件就**永远成立**，而且 x 被改成了 1。
//      ⚠ 编译器那条 warning 的措辞很难懂，但它的意思是"你是不是想写 =="。
//      ⇒ **看到 if 的括号里只有一个等号，立刻停下来改。**
//
//  ⚠ 坑 2：判断顺序写反，后面的分支永远到不了
//
//      错误写法：
//          if (分 >= 60) {
//              return 2;
//          } else if (分 >= 90) {      /* ⚠ 永远走不到这里 */
//              return 3;
//          }
//
//      你会看到什么：
//          ⚠ **编译器不会给你任何提示**，一个 warning 都没有。
//          运行时 95 分返回 2，和 60 分一模一样。
//
//      为什么：if / else if 是**从上往下**挨个试的，第一个成立的就进去了。
//      95 满足 `>= 60`，所以它在第一个分支就返回了，
//      第二个条件再好也没有机会被看一眼。
//      ⇒ 写多分支时把条件**从最严格往最宽松**排，
//        或者干脆让每个条件互不重叠（比如 `分 >= 90` 和 `分 >= 60 && 分 < 90`）。
//
//  ⚠ 坑 3：if 后面多写了一个分号，分支体被架空
//
//      错误写法：
//          if (分数 >= 60);            /* ⚠ 多了一个分号 */
//          {
//              printf("及格\n");
//          }
//
//      你会看到什么：
//          gcc 通常会警告（`-Wempty-body`）：warning: suggest braces around empty body in an 'if' statement
//          运行结果：**不管多少分都打印「及格」**。
//
//      为什么：C 里 `;` 本身就是一个"空语句"。
//      `if (条件);` 的意思是"条件成立时，做一件空事"。
//      后面那个 `{ ... }` 跟 if 已经没有关系了，它只是一段**无条件执行**的代码块。
//      ⇒ 这类错的共同特征：**条件看起来完全正确，行为却不受条件影响**。
//        一旦出现"判断不生效"，先数 if 后面有没有多余的分号。
//
// ─────────────────────────────────────────────────────
//  轮到你了 —— 在下面写
// ─────────────────────────────────────────────────────
//   写一个函数（写在 main **外面**）：
//
//       int 判等级(int 分) {
//           ...
//       }
//
//   90 分及以上 → 返回 3
//   60 分及以上 → 返回 2
//   其他        → 返回 1
//
// 提示：本课只考这个函数，**不用写 main**（课程会提供）。
//
// ⚠ 期望结果（检查会喂这四组边界）：
//
//      判等级(95) ⇒ 3      判等级(90) ⇒ 3
//      判等级(60) ⇒ 2      判等级(59) ⇒ 1
//
// ⚠ 注意 90 是 3、60 是 2 —— 所以要用 `>=`，不是 `>`。
