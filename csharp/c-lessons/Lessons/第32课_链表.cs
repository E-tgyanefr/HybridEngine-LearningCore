//
//     int 学号[30];
//
// 可插进来一个转学生，要按学号排在第 3 位：
//
//     [10][20][30][40][50] ...
//               ↑ 要插 25 在这里
//
// 数组里**没地方塞** —— 只能把 30 之后的每一个人**统统往右挪一格**，
// 再把人放进去。插 1 个人，动 30 个人。
//
// 更要命的是：数组的大小是**写代码的时候**定死的。
// 你不知道会来多少人 —— 写 100 怕不够，写 1000000 又浪费。
//
// 链表就是来解决这两件事的：**要一个就申请一个，插进去不用挪别人。**
//
// ─────────────────────────────────────────────────────
//  一、节点：值 + 「下一个在哪」
// ─────────────────────────────────────────────────────
//
//     struct 节点 {
//         int 值;
//         struct 节点 *下一个;        ← 指向同一种结构体的指针
//     };
//
//     typedef struct 节点 节点;        ← 省得每次都写 struct
//
// 一条链就是这样连起来的（最后一个的「下一个」是 NULL）：
//
//     [10| •] → [20| •] → [30| NULL]
//      头                    尾
//
// ⚠ 数组和链表的区别一句话：**数组的元素是挨着的，链表的元素谁在哪都行**，
//   它们靠指针互相认得。所以链表里没有「第 3 个元素在哪」的公式，
//   想找第 3 个，只能从**头**一个一个走过去。
//
// ─────────────────────────────────────────────────────
//  二、造一个节点：malloc + 填空
// ─────────────────────────────────────────────────────
//
//     节点 *新 = malloc(sizeof(节点));
//     新->值 = 42;
//     新->下一个 = NULL;
//
// ⚠ sizeof(节点) 是**整个结构体多大**（int + 指针，通常 16 字节），
//   不是 4。写成 malloc(4) 会只给你 4 字节 —— 编译不报错，
//   程序**跑着跑着**才崩，而且崩的位置和出错的位置隔得很远。
//
// ─────────────────────────────────────────────────────
//  三、遍历：一定要有「会走路的指针」
// ─────────────────────────────────────────────────────
//
//     for (节点 *走 = 头; 走 != NULL; 走 = 走->下一个) {
//         printf("%d ", 走->值);
//     }
//
// ⚠⚠ **绝对不能拿「头」本身去走**：
//
//     while (头 != NULL) { printf("%d ", 头->值); 头 = 头->下一个; }    ✗
//
//   走完一遍，头就变成 NULL 了 —— 你**永远找不回这条链了**，
//   而且那几十个节点也**再也没法 free**（内存泄漏）。
//   ⇒ 遍历永远用一个临时指针，头原地不动。
//
// ─────────────────────────────────────────────────────
//  四、头部插入：三步，顺序会咬人
// ─────────────────────────────────────────────────────
//
//     新->下一个 = 头;        ① 新节点先拉住原来那条链
//     头 = 新;                ② 再把「头」挪到新节点上
//
// ⚠ ①②**不能换顺序**。先写「头 = 新」的话，原来那条链的地址
//   就丢了（新->下一个 还是 NULL）—— 结果链表里永远只剩一个节点。
//
//   这个错误特别典型：**程序不崩、编译不报，就是打印出来只剩一个数。**
//
// ─────────────────────────────────────────────────────
//  五、删除：先接上，再放手
// ─────────────────────────────────────────────────────
//
// 要删「值 == 20」的那个节点：
//
//     前一个->下一个 = 要删->下一个;      ← 先让链条跨过去
//     free(要删);                        ← 再放掉内存
//
// 两种位置要分开处理：
//
//     要删的是**头**   →  头 = 头->下一个; 再 free
//     要删的在**中间** →  用一个「前一个」指针追在后面
//
// ⚠ 「前一个」的意义就是「我要删的那个的**前一个**」——
//   因为改链条要改**前一个**的下一个，不是改自己的。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：free 完还去用那个指针
// ─────────────────────────────────────────────────────
//
//     free(前一个->下一个);
//     printf("%d\n", 前一个->下一个->值);       ← 那块内存已经不是你的了
//
// gcc 会给你一句（我在本机 gcc 16.1.0 真编译出来的）：
//
//     warning: pointer 'p' used after 'free' [-Wuse-after-free]
//         8 |     printf("%d\n", p->值);
//           |     ^~~~~~~~~~~~~~~~~~~~~
//         7 |     free(p);
//           |     ^~~~~~~
//         note: call to 'free' here
//
// ⚠ 注意这只是 **warning**，不是 error —— 程序照样编译出来、照样跑。
//   跑出来你可能看到 42（内存还没被人踩），
//   也可能看到 6029409 这种莫名其妙的数字（**我实测跑出来就是 6029409**）。
//   ⇒ 这叫「用已经还给系统的内存」，结果完全看运气。
//
// ⇒ 铁律：**free 完立刻把指针设成 NULL**；免费之后要继续走，
//   必须**先把下一个存下来**：
//
//     节点 *下一个 = 走->下一个;
