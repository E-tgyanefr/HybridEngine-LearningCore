    public static string 参考答案 => """
#include <stdio.h>
#include <stdlib.h>

typedef struct 节点 {
    int 值;
    struct 节点 *下一个;
} 节点;

节点 *造节点(int 值) {
    节点 *新 = malloc(sizeof(节点));
    if (新 == NULL) return NULL;
    新->值 = 值;
    新->下一个 = NULL;
    return 新;
}

void 打印链表(节点 *头) {
    节点 *走 = 头;                       /* ⚠ 不拿「头」本身去走 */
    int 先 = 1;
    while (走 != NULL) {
        if (!先) printf(" ");            /* 行尾不留空格 */
        printf("%d", 走->值);
        先 = 0;
        走 = 走->下一个;
    }
    printf("\n");
}

/* 头部插入：先让新节点拉住链条，再挪头 */
void 头插(节点 **头, int 值) {
    节点 *新 = 造节点(值);
    新->下一个 = *头;
    *头 = 新;
}

/* 删除第一个值等于 目标 的节点，返回新的头 */
节点 *删值(节点 *头, int 目标) {
    if (头 == NULL) return NULL;

    if (头->值 == 目标) {                /* 要删的是头 */
        节点 *新的头 = 头->下一个;
        free(头);
        return 新的头;
    }

    节点 *前 = 头;                        /* 前 = 要删的那个的前一个 */
    while (前->下一个 != NULL) {
        if (前->下一个->值 == 目标) {
            节点 *要删 = 前->下一个;
            前->下一个 = 要删->下一个;    /* 先接上 */
            free(要删);                   /* 再放手 */
            return 头;
        }
        前 = 前->下一个;
    }
    return 头;
}

int main(void) {
    节点 *头 = NULL;

    头插(&头, 30);                        /* 空链表也能插 */
    头插(&头, 20);
    头插(&头, 10);
    打印链表(头);                        /* 10 20 30 */

    头插(&头, 5);
    打印链表(头);                        /* 5 10 20 30 */

    头 = 删值(头, 20);
    打印链表(头);                        /* 5 10 30 */

    while (头 != NULL) {                  /* 一个不剩地还回去 */
        节点 *下一个 = 头->下一个;        /* ⚠ 先存下来，再 free */
        free(头);
        头 = 下一个;
    }
    return 0;
}
""";


    [检查说明("链表真的是串起来的、顺序对（头部插入的次序别搞反）")]
    public static CheckResult 检查_1(string 代码)
    {
        var run = CppCheck.直接运行(代码);
        if (!run.编译通过) return CppCheck.编译失败说明(run);
        string[] 要找 = {
            "10 20 30",
            "5 10 20 30",
            "5 10 30",
        };
        var 实际 = run.行;
        int 从这 = 0;
        for (int i = 0; i < 要找.Length; i++)
        {
            int 找到 = -1;
            for (int j = 从这; j < 实际.Count; j++)
                if (实际[j].Trim() == 要找[i]) { 找到 = j; break; }
            if (找到 < 0)
                return CheckResult.不过(
                    $"输出里找不到这一行：\n        {要找[i]}\n" +
                    "      打印出来的：\n        " + string.Join("\n        ", 实际));
            从这 = 找到 + 1;      // 下一行必须在这之后
        }
        return CheckResult.过($"{要找.Length} 行都按顺序出现了");
    }

    [检查说明("真的用 malloc 造了节点")]
    public static CheckResult 检查_2(string 代码)
    {
        string 去注释 = 去掉注释(代码);
        if (!去注释.Contains("malloc("))
