#include <stdio.h>

#define 容量 100

int 括号匹配(const char *s) {
    char 栈[容量];                  /* 栈：数组 + 一个栈顶 */
    int 栈顶 = 0;
    int i = 0;

    while (s[i] != '\0') {
        char 字 = s[i];
        if (字 == '(' || 字 == '[') {
            栈[栈顶] = 字;           /* push */
            栈顶++;
        } else {
            if (栈顶 == 0) return 0; /* ⚠ 空栈：右括号多出来了 */
            栈顶--;                   /* pop */
            char 顶 = 栈[栈顶];
            if (字 == ')' && 顶 != '(') return 0;
            if (字 == ']' && 顶 != '[') return 0;
        }
        i++;
    }
    return 栈顶 == 0;                /* ⚠ 左括号多出来了 */
}

int main(void) {
    /* ── 1. 栈 ── */
    int 栈[容量];
    int 栈顶 = 0;
    for (int 值 = 1; 值 <= 3; 值++) {   /* push */
        栈[栈顶] = 值;
        栈顶++;
    }
    while (栈顶 > 0) {                  /* pop */
        栈顶--;
        printf("弹出 = %d\n", 栈[栈顶]);
    }

    /* ── 2. 队列 ── */
    int 队[容量];
    int 队头 = 0, 队尾 = 0;
    for (int 值 = 1; 值 <= 3; 值++) {   /* 入队 */
        队[队尾] = 值;
        队尾++;
    }
    while (队头 < 队尾) {               /* 出队 */
        printf("出队 = %d\n", 队[队头]);
        队头++;
    }

    /* ── 3. 括号匹配 ── */
    const char *例子[3] = {"([])", "([)]", "(("};
    for (int i = 0; i < 3; i++) {
        printf("%s %s\n", 例子[i], 括号匹配(例子[i]) ? "匹配" : "不匹配");
    }

    return 0;
}
""";


