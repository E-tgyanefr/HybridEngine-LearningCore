//
//     dp[0] = 0
//     dp[1] = 2
//     dp[2] = max(2, 0+7)   = 7        偷第 2 家
//     dp[3] = max(7, 2+9)   = 11       偷第 1、3 家
//     dp[4] = max(11, 7+3)  = 11       不偷第 4 家
//     dp[5] = max(11, 11+1) = 12       偷第 1、3、5 家
//
// 答案 12 = 2 + 9 + 1。
//
// ⚠ 常见的错：把 dp[i] 定义成「**第 i 家必须偷**能得多少」。
//   那也能做，但最后要再扫一遍数组取最大值 —— 定义不同，写法就不同。
//   这一课统一用「只考虑前 i 家」。
