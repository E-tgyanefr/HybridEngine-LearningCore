// ─────────────────────────────────────────────────────
//
// 有 n 级台阶，一次只能上 1 级或 2 级。问：走到第 n 级有多少种走法？
//
// 笨办法：把所有走法都试一遍。n = 30 的时候，走法有 1346269 种 ——
// 一个一个试，电脑也要算好一会儿。n = 50 就是**几百亿**种，算到天亮。
//
// 但换个角度想：**站在第 n 级台阶上往回看** ——
// 我能到这儿，只可能是两种来法：
//
//     从第 n-1 级跨 1 级上来
//     从第 n-2 级跨 2 级上来
//
// 所以「到第 n 级的走法数」=「到第 n-1 级的走法数」+「到第 n-2 级的走法数」。
//
//     f(1) = 1                                       1
//     f(2) = 2                                       1+1 / 2
//     f(3) = f(2) + f(1) = 3                         1+1+1 / 1+2 / 2+1
//     f(4) = f(3) + f(2) = 5
//     f(5) = f(4) + f(3) = 8                          ← 就是斐波那契
//
// 这个「往回看一步、用前面的答案算后面的答案」就是**动态规划**。
//
// ⚠ 它和递归的关系：递归是**从上往下问**（f(5) 去问 f(4)），
//   DP 是**从下往上填**（先算 f(1)，再 f(2)，一路填到 f(5)）。
//   DP 快在「**每个答案只算一次，算完就记在数组里**」——
//   而傻递归会把 f(3) 重复算好几遍（n 一大就慢得离谱）。
//
// ─────────────────────────────────────────────────────
//  一、DP 的三步套路（这三步每道题都一样）
// ─────────────────────────────────────────────────────
//
//     ① **定义 dp[i] 是什么意思**      ← 最关键，含糊了后面全错
//     ② **写递推式**（dp[i] 怎么由前面的算出来）
//     ③ **定初值**（最小的那几个，递推推不出来的）
//
// 爬楼梯这道题：
//
//     ① dp[i] = 走到第 i 级台阶的走法数
//     ② dp[i] = dp[i-1] + dp[i-2]
//     ③ dp[1] = 1, dp[2] = 2
//
// ⚠ 第 ③ 步最容易出错的地方：**初值必须真的自己数一遍**，不能想当然。
//   dp[2] = 2（不是 1）—— 因为「1+1」和「2」是两种走法。
//
// ─────────────────────────────────────────────────────
//  二、打家劫舍：不能连着偷两家
// ─────────────────────────────────────────────────────
//
// 一条街上的房子，钱装在数组里：{2, 7, 9, 3, 1}。
// 不能偷相邻的两家（会报警）。问最多能偷多少？
//
//     ① dp[i] = **只考虑前 i 家**能偷到的最多钱
//     ② 到了第 i 家，两个选择，取大的那个：
