//           不偷它 → 金额 = dp[i-1]
//        dp[i] = max(dp[i-1], dp[i-2] + 钱[i])
//     ③ dp[0] = 0（一家都没考虑，0 元）
//        dp[1] = 钱[1]
//
// ⚠ 注意 dp[0] = 0 这个「空」的状态**很有用**：它让 dp[2] 也能套同一个式子，
//   不用为前两家单独写一段。这就是为什么很多 DP 会故意**多开一格**。
//
