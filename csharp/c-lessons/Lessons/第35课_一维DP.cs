//
//     ① dp[j] = **容量为 j** 的背包能装到的最大价值
//     ② 一个个看东西。看第 i 件时：
//           dp[j] = max(dp[j], dp[j - 重量[i]] + 价值[i])
//                  └ 不拿这件   └ 拿这件（腾出它的重量）
//     ③ dp[全部] = 0（什么都装不下就是 0 元）
//
// ⚠⚠ 这里有个**必须记住**的细节：内层循环要**从大往小**走：
//
//     for (int j = 容量; j >= 重量[i]; j--)        ✓ 倒着走
//     for (int j = 重量[i]; j <= 容量; j++)        ✗ 正着走
