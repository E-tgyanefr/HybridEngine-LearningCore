    public static string 参考答案 => """
#include <stdio.h>

int 爬楼梯(int n) {
    if (n <= 0) return 0;
    if (n == 1) return 1;
    if (n == 2) return 2;
    int dp[100] = {0};              /* ⚠ 一定要初始化 */
    dp[1] = 1;
    dp[2] = 2;
    for (int i = 3; i <= n; i++) {
        dp[i] = dp[i - 1] + dp[i - 2];
    }
    return dp[n];
}

int 打家劫舍(int 钱[], int 家数) {
    if (家数 <= 0) return 0;
    int dp[100] = {0};
    dp[0] = 0;                      /* 一家都不考虑：0 元 */
    dp[1] = 钱[0];
    for (int i = 2; i <= 家数; i++) {
        int 偷 = dp[i - 2] + 钱[i - 1];
        int 不偷 = dp[i - 1];
        dp[i] = 偷 > 不偷 ? 偷 : 不偷;
    }
    return dp[家数];
}

int 背包(int 重量[], int 价值[], int 件数, int 容量) {
    if (件数 <= 0 || 容量 <= 0) return 0;
    int dp[1000] = {0};
    for (int i = 0; i < 件数; i++) {
        /* ⚠ 从大往小 —— 正着走会让同一件东西被拿两次 */
        for (int j = 容量; j >= 重量[i]; j--) {
            int 拿 = dp[j - 重量[i]] + 价值[i];
            if (拿 > dp[j]) dp[j] = 拿;
        }
    }
    return dp[容量];
}
""";


