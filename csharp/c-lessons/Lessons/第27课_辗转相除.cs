    public static string 参考答案 => """
int gcd(int a, int b) {
    while (b != 0) {
        int 余数 = a % b;      /* ⚠ 先把余数接住 */
        a = b;                 /* 再换 a */
        b = 余数;              /* 最后换 b —— 顺序不能动 */
    }
    return a;                  /* b 变成 0 时，a 就是最大公约数 */
}

int lcm(int a, int b) {
    return a / gcd(a, b) * b;  /* ⚠ 先除后乘：a * b 可能先溢出 */
}
""";


