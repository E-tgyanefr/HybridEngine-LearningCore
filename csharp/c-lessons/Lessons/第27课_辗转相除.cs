// ─────────────────────────────────────────────────────
//  这一课你会学到
// ─────────────────────────────────────────────────────
//    欧几里得算法：用取余把两个数越缩越小，最后剩下的就是最大公约数
//
//  需要先会
//    第 18 课：while（辗转相除的循环版就是 while）
//    第 19 课：递归（递归版只有两行）
//    第 26 课：因数、质数
//
// ─────────────────────────────────────────────────────
//  先介绍：最大公约数
// ─────────────────────────────────────────────────────
//
// 12 的因数：1 2 3 4 6 12
// 18 的因数：1 2 3 6 9 18
// 两边都有的：1 2 3 6 —— 最大的那个是 **6**。
//
//     6 就是 12 和 18 的最大公约数，写作 gcd(12, 18) = 6
//     （gcd = greatest common divisor）
//
// 顺带一个：**最小公倍数 lcm**，就是能同时被两个数整除的最小的数：
//
//     lcm(4, 6) = 12      （12 能被 4 整除，也能被 6 整除，没有更小的了）
//
// ─────────────────────────────────────────────────────
//  一、硬做的办法：从大到小一个个试
// ─────────────────────────────────────────────────────
//
//     int gcd(int a, int b) {
//         int 小 = (a < b) ? a : b;
//         for (int i = 小; i >= 1; i--) {
//             if (a % i == 0 && b % i == 0) return i;
//         }
//         return 1;
//     }
//
// ⚠ 它**是对的**，但慢：gcd(1000000000, 999999999) 要试十亿次。
//   两千多年前欧几里得就想出了快得多的办法 —— 而且只用取余。
//
// ─────────────────────────────────────────────────────
//  二、欧几里得算法（辗转相除）
// ─────────────────────────────────────────────────────
//
// 一句话：**gcd(a, b) = gcd(b, a % b)**，一直换到余数是 0 为止。
//
// 看 gcd(100, 75) 怎么一步步缩小：
//
//     gcd(100, 75)    100 % 75 = 25   ⇒ 换成 gcd(75, 25)
//     gcd(75, 25)     75 % 25  = 0    ⇒ 换成 gcd(25, 0)
//     gcd(25, 0)      余数是 0 ⇒ **答案就是 25**
//
// 写成代码（循环版，推荐）：
//
//     int gcd(int a, int b) {
//         while (b != 0) {           ← 只要还有余数就继续
//             int 余数 = a % b;      ← ⚠ 先把余数接住
//             a = b;
//             b = 余数;
//         }
//         return a;                  ← b 变成 0 时，a 就是答案
//     }
//
// ⚠⚠ 那三行的**顺序不能动**：
//
//     a = b;
//     b = a % b;         ← ✗ 这里的 a 已经是 b 了，算出来的不是要的东西
//
//   必须先借一个临时变量**把余数记下来**，再改 a 和 b。
//   这和排序里交换两个变量要借第三个变量是同一回事（第 21 课）。
//
// 递归版（学过第 19 课的话，这个更短）：
//
//     int gcd(int a, int b) {
//         if (b == 0) return a;      ← 基准情形
//         return gcd(b, a % b);      ← ⚠ 两个参数都要传
//     }
//
// 两版完全等价。递归版看着漂亮，但循环版**不会栈溢出**，
// 比赛里一般写循环版。
//
// ─────────────────────────────────────────────────────
//  三、为什么这样就能求出最大公约数
// ─────────────────────────────────────────────────────
//
// 关键在一句话：**a % b 的余数，能被 a 和 b 的任何公因数整除。**
//
//     a = q × b + r        （q 是商，r 就是 a % b）
//
//   如果 d 能整除 a，也能整除 b，那么它一定能整除 r = a - q×b。
//   反过来说：a 和 b 的公因数，正好就是 b 和 r 的公因数。
//   ⇒ 两边的**公因数集合完全一样** ⇒ 最大公约数当然一样。
//
// ⇒ 所以 gcd(a, b) 和 gcd(b, a % b) 是同一个数，可以放心换。
//   而每次换完两个数都在**变小**（r < b），早晚缩到 0 —— 循环一定会停。
//
// ─────────────────────────────────────────────────────
//  四、最小公倍数：先除后乘
// ─────────────────────────────────────────────────────
//
// 有个现成的公式：
//
//     lcm(a, b) = a × b ÷ gcd(a, b)
//
// 但直接照着写很危险：
//
//     return a * b / gcd(a, b);      ← ✗ a * b 可能先溢出
//
// ⚠ 比如 a = b = 100000：a * b = 10000000000，早就超过 int 的 21 亿了 ——
//   而正确答案才 100000。**先乘再除，中间那一步会炸。**
//
// ⇒ 正确写法是**先除后乘**：
//
//     return a / gcd(a, b) * b;      ← ✓ 先除一定是整除，不会丢精度
//
// 为什么可以：gcd(a, b) 一定整除 a，所以 a / gcd 是整除，没有小数。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：递归调用少传了一个参数
// ─────────────────────────────────────────────────────
//
//     int gcd(int a, int b) {
//         if (b == 0) return a;
//         return gcd(b);              ← 只传了一个
//     }
//
// 这个错 gcc 会当场指出来，而且说得很清楚：
//
// $ gcc -std=c11 -O1 -Wall gcd.c -o gcd
//     gcd.c:6:12: error: too few arguments to function 'gcd'; expected 2, have 1
//         6 |     return gcd(b);
//           |            ^~~
//     gcd.c:4:5: note: declared here
//         4 | int gcd(int a, int b) {
//           |     ^~~
//
// 读法：`expected 2, have 1` = 这个函数要 2 个参数，你给了 1 个。
//   `note: declared here` 告诉你它是在哪儿定义的 —— 直接跳过去看参数表。
//
// ⇒ 看到 **too few arguments**，就去数一数参数个数。
//   （别改函数定义，该改的是调用它的那一行。）
//
// ⚠ 同一个坑的另一个版本（gcc 抓不到，只能自己小心）：
//
//     int 余数 = a % b;
//     b = 余数;
//     a = b;                 ← ✗ a 和 b 的更新顺序反了
//
//   这样 a 最后会等于"上一次的余数"，答案错得莫名其妙。
//   记法：**先把余数接住，再 a = b，最后 b = 余数**。顺序照抄就好。
//
// ─────────────────────────────────────────────────────
//  这一课不碰什么
// ─────────────────────────────────────────────────────
//   扩展欧几里得（求 ax + by = gcd 的那组解）→ 不涉及
//   同余方程、逆元 → 不涉及
