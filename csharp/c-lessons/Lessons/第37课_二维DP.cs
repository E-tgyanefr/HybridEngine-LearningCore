//
// ⚠ 第一行 / 第一列**必须**单独填成 1，不能让递推式去算 ——
//   dp[0][0] 的上面和左边都越界了。这类「边界单独处理」是二维 DP 的固定动作。
//
// ─────────────────────────────────────────────────────
//  二、最长公共子序列（LCS）：两个字符串比一比
// ─────────────────────────────────────────────────────
//
// 「子序列」= 从原串里**挑若干个字符出来、保持原来的先后顺序**（可以不连续）。
//
//     串 A = 1 2 3 4 5
//     串 B = 1 3 5
//     公共子序列有：1、3、5、13、15、35、135 ……
//     最长的那个是 135，长度 3
//
// ⚠ 别和「子串」搞混：**子串必须连着**，子序列可以不连着。
//   135 是 A 的子序列，但不是 A 的子串。
//
// 怎么用 DP 求最长长度：
//
//     ① dp[i][j] = A 的**前 i 个**字符 和 B 的**前 j 个**字符 的最长公共子序列长度
//     ② 看 A[i-1] 和 B[j-1] 这两个字符（注意下标差 1！）：
