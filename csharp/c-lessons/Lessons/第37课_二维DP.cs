    public static string 参考答案 => """
#include <stdio.h>
#include <string.h>

int 路径数(int 行, int 列) {
    if (行 <= 0 || 列 <= 0) return 0;
    int dp[100][100] = {0};             /* ⚠ 二维表必须整张清零 */

    for (int j = 0; j < 列; j++) dp[0][j] = 1;    /* 第一行只能一路往右 */
    for (int i = 0; i < 行; i++) dp[i][0] = 1;    /* 第一列只能一路往下 */

    for (int i = 1; i < 行; i++) {
        for (int j = 1; j < 列; j++) {
            dp[i][j] = dp[i - 1][j] + dp[i][j - 1];   /* 上面 + 左边 */
        }
    }
    return dp[行 - 1][列 - 1];
}

int 最长公共子序列(const char *a, const char *b) {
    int n = (int)strlen(a), m = (int)strlen(b);
    int dp[100][100] = {0};             /* 第 0 行 / 第 0 列天然是 0 */

    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= m; j++) {
            if (a[i - 1] == b[j - 1]) {
                dp[i][j] = dp[i - 1][j - 1] + 1;      /* ⚠ 别忘了 +1 */
            } else {
                int 上 = dp[i - 1][j];
                int 左 = dp[i][j - 1];
                dp[i][j] = 上 > 左 ? 上 : 左;
            }
        }
    }
    return dp[n][m];
}
""";


