//   很多人会写成 dp[i-1][j-1]（忘了 +1）—— 结果永远是 0。
//
// 拿 A = 1 2 3 4 5、B = 1 3 5 填一遍（整张表）：
//
//            ""   1    3    5
//     ""     0   0    0    0
//     1      0   1    1    1
//     2      0   1    1    1
//     3      0   1    2    2
//     4      0   1    2    2
//     5      0   1    2    3      ← 答案 3
//
// ⚠ 下标差 1 这件事**必须自己盯住**：
//   dp 的第 i 行说的是「前 i 个字符」，而字符串的下标是从 0 开始的。
//   所以第 i 个字符是 A[i-1]，dp 表要比字符串**多一行一列**。
//   这是二维 DP 最常见的「差一格」bug 来源。
