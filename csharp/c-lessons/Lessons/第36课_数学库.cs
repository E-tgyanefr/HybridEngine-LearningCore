//
// 数学函数住在标准库的「数学那一册」里，链接的时候要把它连上：
//
//     Linux / macOS ：  gcc 程序.c -o 程序 -lm      ← 要加 -lm
//     MinGW（Windows）：gcc 程序.c -o 程序           ← **不用加**
