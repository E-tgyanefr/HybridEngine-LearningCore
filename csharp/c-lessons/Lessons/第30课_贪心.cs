#include <stdio.h>

int main(void) {
    /* ── 一、找零：币值从大到小，能拿就一直拿 ── */
    int 币值[4] = {25, 10, 5, 1};
    int 剩 = 63;
    int 枚数 = 0;
    printf("找 63 元：");
    for (int i = 0; i < 4; i++) {
        while (剩 >= 币值[i]) {          /* ⚠ while 不是 if */
            printf("%d ", 币值[i]);
            剩 -= 币值[i];
            枚数++;
        }
    }
    printf("\n一共 %d 枚\n", 枚数);

    /* ── 二、贪心不灵的例子：4 3 1 找 6 ── */
    int 怪币[3] = {4, 3, 1};
    int 剩2 = 6;
    int 枚2 = 0;
    printf("币值 4 3 1 找 6 元，贪心给：");
    for (int i = 0; i < 3; i++) {
        while (剩2 >= 怪币[i]) {
            printf("%d ", 怪币[i]);
            剩2 -= 怪币[i];
            枚2++;
        }
    }
    printf("\n贪心用了 %d 枚，可最少只要 2 枚（3 + 3）\n", 枚2);

    /* ── 三、区间调度：选结束最早的 ── */
    int 开始[8] = {1, 3, 0, 5, 3, 8, 8, 12};
    int 结束[8] = {4, 5, 6, 7, 9, 11, 12, 16};
    int 上个结束 = -1;                   /* 第一个区间随便选 */
    int 选的个数 = 0;
    printf("选中的区间：");
    for (int i = 0; i < 8; i++) {
        if (开始[i] >= 上个结束) {       /* ⚠ >= ：接着上没事 */
            printf("%d-%d ", 开始[i], 结束[i]);
            上个结束 = 结束[i];
            选的个数++;
        }
    }
    printf("\n一共选了 %d 个\n", 选的个数);

    return 0;
}
""";


