// 题目：一堆活动都要占用同一间教室，每个活动有开始和结束时间，
// 怎么选才能**参加最多的活动**（活动之间不能重叠）？
//
// 贪心策略：**每次选结束时间最早、而且不和已选的冲突的那个。**
//
//     已选活动的结束时间记作 上个结束（一开始是 -1，表示第一个随便选）
//     按结束时间从早到晚扫一遍：
//         开始 >= 上个结束 ⇒ 选它，把 上个结束 更新成它的结束时间
//         否则跳过
//
// 代码：
//
//     int 上个结束 = -1;
//     for (int i = 0; i < 8; i++) {
//         if (开始[i] >= 上个结束) {          ← ⚠ 是 >=，不是 >
