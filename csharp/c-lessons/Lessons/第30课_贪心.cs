//     25 能拿 ⇒ 再拿一个，剩 13
//     10 能拿 ⇒ 拿一个，剩 3
//     5  拿不了（比 3 大）
//     1  能拿 ⇒ 拿一个，剩 2 …… 再拿，再拿 ⇒ 剩 0
//
//     结果：25 25 10 1 1 1，一共 6 枚。
//
// 代码：
//
//     int 币值[4] = {25, 10, 5, 1};
//     int 剩 = 63, 枚数 = 0;
//     for (int i = 0; i < 4; i++) {
//         while (剩 >= 币值[i]) {        ← ⚠ while 不是 if
//             printf("%d ", 币值[i]);
//             剩 -= 币值[i];
//             枚数++;
//         }
//     }
//
