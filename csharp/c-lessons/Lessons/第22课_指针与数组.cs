#include <stdio.h>

int main(void) {
    int a[5] = {5, 3, 8, 1, 9};

    /* a[i] 和 *(a + i) 是同一个东西 —— 打印两遍，值必须一样 */
    for (int i = 0; i < 5; i++) {
        printf("a[%d] 和 *(a+%d) 都是 %d %d\n", i, i, a[i], *(a + i));
    }

    /* 用指针自己走：p 指着哪个格子，*p 就是哪个格子的值 */
    printf("指针走一遍：");
    int *p = a;
    while (p < a + 5) {
        printf("%d", *p);
        p++;                       /* ⚠ 挪的是"一个 int"，不是"一个字节" */
        if (p < a + 5) printf(" ");
    }
    printf("\n");

    return 0;
}
""";


