//   卡住了看答案（先自己写一遍）—— 命令在「怎么自己测」那一节。
//
// ─────────────────────────────────────────────────────
//  这一课你会学到
// ─────────────────────────────────────────────────────
//    怎么一眼看出"这段代码快不快"：数它的循环要跑多少次
//
//  需要先会
//    第 07 课：for 循环（复杂度就是数循环）
//    第 02 课：int 装得下多少（这一课的坑就在这里）
//
// ─────────────────────────────────────────────────────
//  先介绍：同一件事，快慢能差一亿倍
// ─────────────────────────────────────────────────────
//
// 假设一台电脑每秒能跑一亿次循环体。同一个问题，两种写法：
//
//     n = 100000
//
//     写法甲：一层循环，跑 n 次            ⇒ 十万次    ⇒ 0.001 秒
//     写法乙：两层循环，跑 n × n 次        ⇒ 一百亿次  ⇒ **100 秒**
//
// 两次。不是快 10%，是快**十万倍**。
// 而两者只差一层 for —— 这就是这一课要练的眼力。
//
// ⚠ 考试里（GESP、NOI 都一样）**超时就是零分**。
//   想不出更快的写法，写得再对也没用。所以复杂度不是"讲究"，
//   它是"能不能交卷"的问题。
//
// ─────────────────────────────────────────────────────
//  一、大 O 记号：只看"涨得多快"
// ─────────────────────────────────────────────────────
//
// 我们不数"跑了几纳秒"（那要看电脑），只数**循环体跑了几次**
// 和 n 是什么关系：
//
//     O(1)     跑的次数**和 n 无关**，永远是那么多
//     O(n)     n 翻一倍，次数翻一倍
//     O(n^2)   n 翻一倍，次数翻**四倍**
//
// 写法读作"大 O 多少"：O 后面括号里写"次数随 n 怎么涨"。
//
// ⚠ 大 O 是"大概"：O(2n)、O(n + 5)、O(n/2) 都写成 **O(n)**。
//   因为它关心的是"n 大起来以后谁涨得凶"，常数倍数不重要。
//
// ─────────────────────────────────────────────────────
//  二、三种最常见的复杂度，怎么一眼认出来
// ─────────────────────────────────────────────────────
//
//  O(1) —— 没有和 n 有关的循环
//
//     int 和 = a[0] + a[1];        ← 就几句，n 再大也是这几句
//     printf("%d\n", a[n - 1]);
//
//  O(n) —— **一层**和 n 有关的循环
//
//     for (int i = 0; i < n; i++) 计数++;
//     for (int i = 0; i < n; i++) 和 += a[i];
//
//  O(n^2) —— **两层**都和 n 有关的循环
//
//     for (int i = 0; i < n; i++)
//         for (int j = 0; j < n; j++) 计数++;
//
// ⚠ 判据是**嵌套**，不是"有两个 for"：
//
//     for (int i = 0; i < n; i++) ...        }  两个循环**并排**，
//     for (int i = 0; i < n; i++) ...        }  一共跑 2n 次 ⇒ 还是 O(n)
//
// ⇒ 问自己一句：**内层循环每转一圈，外层要带着它转几次？**
//   并排：各转各的 ⇒ 加起来 ⇒ O(n)
//   嵌套：内层要被外层带着转 n 遍 ⇒ 乘起来 ⇒ O(n^2)
//
// ─────────────────────────────────────────────────────
//  三、数循环次数的方法
// ─────────────────────────────────────────────────────
//
// 真拿不准的时候，就**数一遍**：
//
//     int 计数 = 0;
//     for (int i = 0; i < n; i++)
//         for (int j = 0; j < n; j++) 计数++;
//     printf("跑了 %d 次\n", 计数);
//
// ⚠ 这个办法只能用在**小 n** 上（比如 n = 10）。
//   拿 n = 100000 去数 O(n^2)，你会等一百秒 —— 这一课不干这事。
//
// 更大的 n，直接**用乘法算**：
//
//     n = 100000
//     O(n)   的次数 = 100000
//     O(n^2) 的次数 = 100000 × 100000 = 10000000000     ← 一百亿
//
// ─────────────────────────────────────────────────────
//  四、为什么 n=100000 时 O(n²) 不能用
// ─────────────────────────────────────────────────────
//
//     一百亿次。每秒一亿次的话，要跑 **100 秒**。
//
// 而考试通常只给 1 秒。（有些题目给 2 秒。）
//
// ⇒ 看到题目里写着 n ≤ 100000，就该知道：
//   **O(n^2) 的写法一定超时**，必须想出 O(n) 或 O(n log n) 的办法。
//
// 反过来的经验（很好用）：
//
//     n ≤ 10          O(n!) 都行
//     n ≤ 1000        O(n^2) 可以
//     n ≤ 100000      O(n^2) 不行，要 O(n)
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：10 的 10 次方装不进 int
// ─────────────────────────────────────────────────────
//
// 一百亿比 int 能装的最大值（2147483647，约 21 亿）还大。
// 拿 int 去装，你会得到一个**负的、莫名其妙的数**：
//
//     int 总次数 = 100000 * 100000;
//     printf("%d\n", 总次数);            ⇒ 1410065408        （错的）
//
// $ gcc -std=c11 -O1 -Wall 复杂度.c -o 复杂度
//     复杂度.c:5:25: warning: integer overflow in expression of type 'int' results in '1410065408' [-Woverflow]
//         5 |     int 总次数 = 100000 * 100000;
//           |                         ^
//
// ⚠ 如果两边写的是**变量**（大 * 大），gcc 连这句警告都给不出来 ——
//   它算不出变量的值，于是**一声不吭地给你一个错的数**。这更危险。
//
// ⇒ 数循环次数、算 n × n 这种大数，一律用 **long long**，打印用 **%lld**：
//
//     long long 大 = 100000;
//     printf("%lld\n", 大 * 大);         ⇒ 10000000000      （对的）
//
// ⇒ 复习第 02 课的容量表：int 大约到 21 亿，long long 到 9 后面 18 个零。
//
// ─────────────────────────────────────────────────────
//  这一课不碰什么
// ─────────────────────────────────────────────────────
//   O(n log n)、O(log n)（二分是下一段的事）→ 第 29 课会见到 O(log n)
//   空间复杂度（内存够不够）→ 不涉及
//   怎么把 O(n²) 的算法改快 → 那是算法课的正题，这里只教"看得出来"
//
