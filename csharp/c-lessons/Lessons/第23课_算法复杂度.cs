    public static string 参考答案 => """
#include <stdio.h>

int main(void) {
    int n = 10;
    long long 常 = 0, 线 = 0, 方 = 0;

    /* O(1)：就一句，跟 n 没关系 */
    常 = 常 + 1;

    /* O(n)：一层循环 */
    for (int i = 0; i < n; i++) 线 = 线 + 1;

    /* O(n^2)：两层嵌套 */
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) 方 = 方 + 1;
    }

    printf("n = %d\n", n);
    printf("O(1) 跑了 %lld 次\n", 常);
    printf("O(n) 跑了 %lld 次\n", 线);
    printf("O(n^2) 跑了 %lld 次\n", 方);

    /* ⚠ 一百亿 —— 这里只能算，不能真跑：用 long long，别用 int */
    long long 大 = 100000;
    printf("n = 100000 时，O(n) 要跑 %lld 次\n", 大);
    printf("n = 100000 时，O(n^2) 要跑 %lld 次\n", 大 * 大);
    printf("n 变成 10000 倍，O(n^2) 就变成 %lld 倍\n", 大 * 大 / 方);

    return 0;
}
""";


