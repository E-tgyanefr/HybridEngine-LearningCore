#include <stdio.h>

#define 点数 5
#define 边数 7
#define 无穷 1000000000

int 边U[边数] = {0, 2, 2, 1, 0, 1, 3};
int 边V[边数] = {1, 1, 3, 4, 2, 3, 4};
int 边W[边数] = {4, 1, 5, 9, 1, 4, 1};
int 距离[点数];

void 最短路(void) {
    for (int i = 0; i < 点数; i++) 距离[i] = 无穷;
    距离[0] = 0;                  /* ⚠ 源点自己是 0 */

    // 松 点数-1 遍：每一遍把所有边都扫一次
    //   如果 距离[u] + 边权 < 距离[v] 就改小它
