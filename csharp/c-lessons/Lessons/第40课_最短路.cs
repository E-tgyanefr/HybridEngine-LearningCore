    public static string 参考答案 => """
#include <stdio.h>

#define 点数 5
#define 边数 7
#define 无穷 1000000000        /* ⚠ 别用 INT_MAX：加一下就溢出了 */

int 边U[边数] = {0, 2, 2, 1, 0, 1, 3};
int 边V[边数] = {1, 1, 3, 4, 2, 3, 4};
int 边W[边数] = {4, 1, 5, 9, 1, 4, 1};
int 距离[点数];

void 最短路(void) {
    for (int i = 0; i < 点数; i++) 距离[i] = 无穷;
    距离[0] = 0;                       /* ⚠ 忘了这句，全表都是无穷 */

    /* 最多松 点数-1 遍。一条最短路最多用 点数-1 条边。 */
    for (int 遍 = 1; 遍 <= 点数 - 1; 遍++) {
        for (int i = 0; i < 边数; i++) {
            int u = 边U[i], v = 边V[i], w = 边W[i];
            if (距离[u] == 无穷) continue;        /* 还走不到 u，松也没用 */
            if (距离[u] + w < 距离[v]) {          /* ⚠ 找到更短的才换 */
                距离[v] = 距离[u] + w;
            }
        }
    }
}

int main(void) {
    最短路();
    for (int i = 0; i < 点数; i++) {
        printf("dist[%d] = %d\n", i, 距离[i]);
    }
    return 0;
}
""";


