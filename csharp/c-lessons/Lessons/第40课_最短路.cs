//
// ─────────────────────────────────────────────────────
//  先介绍：一条边能「省多少路」
// ─────────────────────────────────────────────────────
//
// 五个点，七条**有向边**（箭头表示方向，数字是长度）：
//
//     0 ──4──→ 1          0 ──1──→ 2          2 ──1──→ 1
//     1 ──4──→ 3          2 ──5──→ 3          3 ──1──→ 4
//     1 ──9──→ 4
//
// 从 0 到 1：
//
//     直接走      0 → 1              长度 4
//     绕一下      0 → 2 → 1          长度 1 + 1 = 2        ← 更短！
//
// ⚠ 这一课的全部内容就是这一句话：
//   **「绕一下会不会更短」这件事，要反复问好几遍才问得完。**
//
// ─────────────────────────────────────────────────────
//  一、核心动作：松弛（relax）
// ─────────────────────────────────────────────────────
//
// 我先记住「0 到 1 是 4」。然后看见边 2 → 1：
//
//     如果 0 到 2 已经知道是 1，那从 2 再走 1 步到 1 就是 1 + 1 = 2。
//     2 < 4 ⇒ **把记录改成 2**。
//
// 这个「要不要改小」的动作就叫**松弛**，代码只有两行：
//
//     if (距离[u] + 边权 < 距离[v])
//         距离[v] = 距离[u] + 边权;
//
// ⚠ 那两行看起来平平无奇，但它是**整个算法唯一的动作**。
//   Bellman-Ford 干的事就是：**把所有边都松一遍，再松一遍，再松一遍……**
//   直到一整遍下来一条边都没改（松不动了）。
//
// ─────────────────────────────────────────────────────
//  二、要松几遍：最多 点数-1 遍
// ─────────────────────────────────────────────────────
//
// 一条最短路最多经过「点数-1」条边（再多就绕圈子了，绕圈子只会更长）。
// 每松一遍，至少能把一条边的最短路确定下来 —— 所以最多松 点数-1 遍。
//
//     for (遍 = 1; 遍 <= 点数 - 1; 遍++)
//         for (每条边 (u, v, w))
//             松弛;
//
// ⚠ 为什么要「反复」松，一遍不行吗？题目里那 7 条边就是**故意排成这样**的：
//   顺序是 (0→1) (2→1) (2→3) (1→4) (0→2) (1→3) (3→4)
//
//     开始：距离 = [0, ∞, ∞, ∞, ∞]
//
//     第 1 遍，一条一条扫过去：
//         边(0,1,4) → 距离[1] = 4
//         边(2,1,1) → 距离[2] 还是 ∞，**什么都松不动**      ← 关键就在这
//         边(2,3,5) → 一样，松不动
//         边(1,4,9) → 距离[4] = 4 + 9 = 13
//         边(0,2,1) → 距离[2] = 1                        ← 到这一条，2 才被算出来
//         边(1,3,4) → 距离[3] = 4 + 4 = 8
//         边(3,4,1) → 距离[4] = min(13, 8+1) = 9
//
//     第 1 遍结束：距离 = [0, 4, 1, 8, 9]
//
// ⚠ 看着挺像回事，但**全是偏大的**：正确答案是 [0, 2, 1, 6, 7]。
//   为什么？因为 (2→1) 排在 (0→2) **前面** —— 扫到它的时候距离[2] 还是 ∞，
//   白白错过了这一遍的机会，只能等下一遍。
//
//     第 2 遍：(2,1,1) 这次距离[2] = 1 了 → 距离[1] = 2
//              后面几条也跟着改小……
//     第 3、4 遍：再改，直到一条都改不动
//
// ⇒ 记住这句话：**最短路越长，要松的遍数越多。**
//   而且**答案对不对，跟输入里边的顺序有关系** —— 这也是
//   「只松一遍」这个 bug 特别难查的原因：换个顺序它可能就对了。
//
// ─────────────────────────────────────────────────────
//  三、∞ 怎么表示：用一个足够大的数
// ─────────────────────────────────────────────────────
//
//     const int 无穷 = 1000000000;          /* 10 亿 */
//     for (int i = 0; i < 点数; i++) 距离[i] = 无穷;
//     距离[源点] = 0;
//
// ⚠ 两个坑：
//
//   ① **不能用 int 的最大值 2147483647。**
//      因为你要算 距离[u] + 边权，而 10 亿 + 10 亿 < 21 亿，不会溢出；
//      21 亿 + 1 就**溢出成负数**了 —— 负数比什么都小，于是
//      「绕一下更短」的判断会被一个**假的**负数骗过去。
//      10 亿这个数就很好：够大（比任何真实路径都长），又留了余量。
//
//   ② **距离[源点] 必须是 0**，而且要在松弛之前设好。
//      忘了设的话，全表都是 10 亿，怎么松都松不动，最后打印出一排 1000000000。
//
// ⚠ 还有个小技巧：如果 距离[u] == 无穷 就别松了（u 根本还没走到）。
//   不判也不会错（10 亿 + 边权 < 10 亿 是假的，不会赋值），
//   但判一下意图更清楚。
//
// ─────────────────────────────────────────────────────
//  四、它比 Dijkstra 好在哪
// ─────────────────────────────────────────────────────
//
// 最短路还有个更出名的算法叫 **Dijkstra**，它更快，但**要求所有边权都不能是负数**。
//
// ⚠ 为什么 Dijkstra 怕负数：它的思路是「每次挑当前距离最小的那个点，
//   然后宣布它的距离**再也不会变了**」。可要是有负边，
//   后面绕一圈回来反而可能更短 —— 那个「宣布」就宣布错了。
//
// Bellman-Ford 没这个毛病：它只是**一遍遍把所有边重新问一遍**，
//   所以负边照样能处理。（代价是要扫 点数 遍所有边。）
//
// ⚠ 小图两者差不多，边多的时候 Bellman-Ford 更慢。
//   但这一课选它的理由不是快，是**写得快**：
//   它只有两个嵌套的 for，不需要优先队列、不需要堆、不需要任何数据结构。
//
// ⚠ 顺带一提：Bellman-Ford 还能**查负环** ——
//   正常松 点数-1 遍就该停了。你要是**再多松一遍**，发现还能改小，
//   说明图里有个圈能把路越绕越短（负环），那就不存在最短路。
//   这一课的程序不用管它，但这个性质很有名，见到就知道。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：只松一遍 / 松弛写反
// ─────────────────────────────────────────────────────
//
// 坑一：外层只松一遍。
//
//     for (每条边) 松弛;          ← 只有一遍
//
// 你会看到：**编译通过、程序跑完、不报任何错**，只是有几个点的距离偏大。
//   而且**偏得很讲道理** —— 它不是乱数，它是「沿着输入里边的顺序
//   能一路顺下来的那部分路」，看着完全像正确答案。
//
//   这就是这一课最难查的 bug：**它不崩、不报错、答案只是「不够短」。**
//   唯一的办法是**换个顺序的输入再试一遍**（检查里就是这么干的）。
//
// 坑二：松弛的比较写反。
//
//     if (距离[u] + 边权 > 距离[v])        ← 写成了大于
//         距离[v] = 距离[u] + 边权;
//
// 那距离只会**越来越大**，最后每个点都绕成一个巨大的数。
//   ⇒ 记法：**松弛永远是「找到更短的，就换掉」**，
//     所以 if 里一定是 <，一定是「新的比旧的小」。
//
// ⚠ 还有个更隐蔽的写法错误：把 距离[v] 和 距离[u] 写混 ——
//
//     if (距离[v] + 边权 < 距离[u])         ← u 和 v 反了
//
//   它**照样能编译、照样能跑**，在链状的图上甚至还能碰巧对几段。
//   记住这行代码的读法：**「从 u 出发，走到 v，会不会更近」**
//   —— 所以是 距离[u] + 边权（从 u 出来）和 距离[v]（到 v 去）比。
//
// ─────────────────────────────────────────────────────
//  这一课不碰什么
// ─────────────────────────────────────────────────────
//   Dijkstra（优先队列 / 堆）→ 不涉及。
//   Floyd-Warshall（求所有点对之间的最短路）→ 不涉及。
//   负环检测、把路径打印出来 → 不涉及（只提了一句原理）。
//   无向图 → 这一课是**有向图**（边有方向），无向边就是两条反向边。
//
// ─────────────────────────────────────────────────────
//  轮到你了 —— 在下面写
// ─────────────────────────────────────────────────────
//
// 写一个**完整程序**（自己写 #include 和 main）。四件事：
//
// 1. 图有 5 个点、7 条有向边，骨架里已经用三个数组存好了：
//
//        0 → 1  长 4          1 → 3  长 4
//        0 → 2  长 1          1 → 4  长 9
//        2 → 1  长 1          2 → 3  长 5
//        3 → 4  长 1
//
