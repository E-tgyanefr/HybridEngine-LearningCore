//   直接走 0→1→4 是 13。
//
// ⚠ 检查会盯两件事：五个距离对不对，**以及你是不是真写了「松 点数-1 遍」**。
//   只松一遍的写法在这里会算出 `dist[1] = 4`（甚至 8、9），当场露馅；
