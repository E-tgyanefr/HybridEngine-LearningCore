int 数位和(int 数) {
    int 和 = 0;
    /* ⚠ 条件写 数 > 0：数变成 0 就不进循环了（输入是 0 时直接返回 0，正确） */
    while (数 > 0) {
        和 += 数 % 10;      /* 拿走最后一位 */
        数 /= 10;            /* ⚠⚠ 这一行是"让循环往前走"的关键 —— 删了它必死循环 */
    }
    return 和;
}

int 至少做一次(int 数) {
    int 和 = 0;
    /* do-while：先做一次再判断。
       这个题目里它和 while 结果一样（因为 0 加不加都是 0），
       但换个题目就不一样了 —— 比如"至少问用户一次"。 */
    do {
        和 += 数 % 10;
        数 /= 10;
    } while (数 > 0);       /* ⚠ 末尾这个分号不能少 */
    return 和;
}
""";


