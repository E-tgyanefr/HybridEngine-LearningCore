//
//     对每个数都调一次 是质数  ⇒ 一百万次调用，每次还要试到 √n
//                              ⇒ 慢，而且每个合数都被反复试除
//
// 埃拉托色尼（公元前 3 世纪的希腊人）想了个完全不同的办法：
// **不要去"判断"每个数，而是把合数一个个"划掉"。**
//
// ─────────────────────────────────────────────────────
//  一、筛子的想法
// ─────────────────────────────────────────────────────
//
// 拿 1..30 举例。先假设**所有数都是质数**，然后：
//
//     2 是质数 ⇒ 把 2 的倍数全划掉：4 6 8 10 12 …
//     3 是质数 ⇒ 把 3 的倍数全划掉：6 9 12 15 …
//     4 已经被划掉了 ⇒ 跳过（它的倍数早被 2 划过了）
//     5 是质数 ⇒ 划掉 10 15 20 …
//     …
//
// 走完之后，**没被划掉的就是质数**。
//
// 为什么对：一个合数一定能写成 a × b（都大于 1），所以它一定是
//   某个更小的质数的倍数 —— 那个质数走的时候**一定会把它划掉**。
//
// ─────────────────────────────────────────────────────
//  二、代码怎么写
// ─────────────────────────────────────────────────────
//
//     int 标记[101];              ← 0 = 还没被划掉，1 = 被划掉了
//
//     for (int i = 2; i * i <= 100; i++) {   ← ① 只需要走到 √100 = 10
//         if (标记[i] == 0) {                ← ② 只拿质数去划
//             for (int j = i * i; j <= 100; j += i) {   ← ③ 从 i*i 开始
//                 标记[j] = 1;
//             }
//         }
//     }
//
// 三个地方都有讲究：
//
//   ① **外层只走到 √n**：比 √n 大的质数，它的平方已经超过 n 了，
//      在 n 以内根本没有"它的倍数"要划。
//
//   ② **只拿质数去划**：i 已经被划掉说明它是合数，
//      它的倍数早被更小的质数划过了，再划一遍是白干。
//
//   ③ **内层从 i * i 开始，不是 2 * i**：
//      i × 2、i × 3 … i × (i-1) 这些，前面更小的质数早就划过了
//      （比如 3 × 2 = 6 在 i=2 时就划掉了）。从 i × i 开始才是新的。
//
// ⚠ 这三条都是**优化**，去掉也能出正确答案，只是白干活。
//   但这一课要数"划了多少次"，所以请**照上面写**，数字才对得上。
//
// ─────────────────────────────────────────────────────
//  三、数组开多大、开在哪
// ─────────────────────────────────────────────────────
//
// 要筛到 n，表就得有 n + 1 个格子（下标 0 到 n 都用得到）：
//
//     int 标记[101];              ← 筛 1..100
//
// ⚠ 为什么是 101 不是 100：下标从 0 开始，`标记[100]` 也得有地方放。
