    public static string 参考答案 => """
#include <stdio.h>

int 标记[101];                 /* 全局数组：0 = 没被划掉，1 = 划掉了 */

int main(void) {
    /* ── 埃氏筛 ── */
    int 划掉次数 = 0;
    for (int i = 2; i * i <= 100; i++) {       /* ① 只走到 √100 = 10 */
        if (标记[i] == 0) {                    /* ② 只拿质数去划 */
            for (int j = i * i; j <= 100; j += i) {   /* ③ 从 i*i 开始 */
                标记[j] = 1;
                划掉次数++;
            }
        }
    }

    /* ── 没被划掉的就是质数 ── */
    printf("1 到 100 的质数：");
    int 个数 = 0;
    for (int i = 2; i <= 100; i++) {
        if (标记[i] == 0) {
            printf("%d ", i);
            个数++;
        }
    }
    printf("\n");
    printf("一共 %d 个\n", 个数);
    printf("筛法一共划掉了 %d 次\n", 划掉次数);

    /* ── 试除法：第 26 课那种，一个个判 ── */
    int 试除次数 = 0;
    int 试除质数 = 0;
    for (int n = 2; n <= 100; n++) {
        int 是 = 1;
        for (int i = 2; i * i <= n; i++) {
            试除次数++;                        /* ⚠ 先数，再判断 */
            if (n % i == 0) { 是 = 0; break; }
        }
        if (是) 试除质数++;
    }
    printf("试除法一共试了 %d 次，也数出 %d 个质数\n", 试除次数, 试除质数);

    return 0;
}
""";


