//     写在所有函数**外面**（全局）就放在另一块大得多的地方，没事。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：C 里 const int 不能当数组长度
// ─────────────────────────────────────────────────────
//
// 想"开大一点好改"，很自然会写：
//
//     const int 上限 = 1000000;
//     int 标记[上限 + 1];          ← 在 C 里这样写不行
//
// $ gcc -std=c11 -O1 -Wall 筛.c -o 筛
//     筛.c:5:5: error: variably modified '\U00006807\U00008bb0' at file scope
//         5 | int 标记[上限 + 1];
//           |     ^~~~
//
// （`\U00006807\U00008bb0` 就是「标记」两个字，gcc 把中文名转义了。
//   `file scope` = 文件作用域，说的是"这行写在所有函数外面"。）
//
// 为什么：**C 里的 const 变量不是"编译期常量"**（这一点和 C++ 不一样！）。
//   编译器要在"读代码的时候"就知道数组多大，而 const int 它不肯当成已知数，
//   于是把它当成了"长度要到运行时才定的数组"（变长数组），
//   而变长数组**不允许写在函数外面**。
//
// ⇒ 两种改法，都对：
//
//     #define 上限 1000000             ← 宏，预处理时直接替换成数字
//     int 标记[上限 + 1];
//
//     int 标记[1000001];               ← 或者干脆写死数字
//
// ⇒ 记法：**数组长度要么写数字，要么用 #define。别用 const int。**
//   （在函数**里面**，`int 表[n]` 这种写法 C 是允许的 —— 但那是另一回事，
