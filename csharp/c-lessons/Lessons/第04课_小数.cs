//
//     float    单精度    大约 7 位有效数字
//     double   双精度    大约 15 位      ← **默认选它**
//
// ⚠ 日常写代码**一律用 double**：
//   float 省的那点内存现在毫无意义，而精度不够会在累加很多次之后露出来。
