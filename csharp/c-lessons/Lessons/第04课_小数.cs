//  用法与例子
// ─────────────────────────────────────────────────────
//
//  ① 声明：类型写 double，值里带小数点。
//
//      double 圆周率 = 3.14159;
//
//  ② 打印：%f 打 double。想要几位小数就在 % 和 f 之间写 `.位数`。
//
