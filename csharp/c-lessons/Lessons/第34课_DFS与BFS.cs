// 那同一个格子会被**好几个邻居各入队一次**，队列里的量会爆炸式增长
// （一个 1000×1000 的迷宫能塞进几百万个重复格子）。
//
// 更坏的情况是这样：A 和 B 互相是邻居，两个都还没访问过 →
// A 把 B 入队，B 又把 A 入队，A 又看见 B……队列**永远清不空**。
//
// 你会看到：程序**编译通过、不崩、不报错，就是一直不出结果**，
// 界面上的「检查」最后告诉你：**运行超时**。
//
// ⇒ 铁律：**入队的那一瞬间就标记「访问过」**，不要等到出队才标。
//
//     访问过[新行][新列] = 1;
//     队[队尾] = 新行 * 列数 + 新列;       ← 这两行**必须挨着写**
//     队尾++;
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：用 DFS 去回答「最少几步」
// ─────────────────────────────────────────────────────
