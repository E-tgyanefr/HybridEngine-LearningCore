//
// ─────────────────────────────────────────────────────
//  一、DFS：一条路走到黑，撞墙再回头
// ─────────────────────────────────────────────────────
//
// DFS 的规矩简单到一句话：**能往前就往前，走不动就退回来换一条。**
//
//     走(行, 列) {
//         ① 越界了？是墙？已经走过了？  → 返回「不行」
//         ② 到终点了？                  → 返回「行」
//         ③ 把这一格标记成「走过了」
//         ④ 从这一格往四个方向各递归着试一次
//         ⑤ 四个方向都不行              → 返回「不行」
//     }
//
