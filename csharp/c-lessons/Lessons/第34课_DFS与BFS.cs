//     (0,0) 试右 → (0,1) 可以，进去
//                    (0,1) 试右 → (0,2) 可以，进去
//                                   (0,2) 试下 → (1,2) 可以，进去
//                                                  (1,2) 试下 → (2,2) **到了** ✓
//
// ⚠ 第 ③ 步「标记走过了」**不能漏**。漏了的话：
//   从 (0,1) 走回 (0,0)，再从 (0,0) 走回 (0,1)……
//   **两个格子互相来回，永远出不来。**
//
