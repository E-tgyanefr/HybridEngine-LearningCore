//   递归函数用的就是系统给你准备的栈，一路深入就是一路压栈，
//   撞墙回头就是弹栈。
//
// ─────────────────────────────────────────────────────
//  二、BFS：一层层往外铺，像水面上的波纹
// ─────────────────────────────────────────────────────
//
// BFS 的规矩也一句话：**先看离起点 1 步的所有格子，再看 2 步的，再看 3 步的。**
//
// 石头扔进水里，波纹是一圈一圈扩大的 —— BFS 就是那个波纹。
//
// ⚠ 所以**第一次碰到终点的时候，走的一定是最少步数** ——
//   因为你是按「1 步的、2 步的、3 步的」这个顺序铺过去的，
//   不可能有一条更短的路被你漏在后面。
//
// 怎么保证「1 步的都比 2 步的先处理」？—— **用队列。**
//
//     把起点放进队列，步数记 0
//     while (队列不空) {
//         从队头取出一个格子
//         如果它就是终点 → 它的步数就是答案，收工
//         把它上下左右四个**还没访问过**的格子**入队**，步数 = 自己 + 1
//     }
//
// ⚠ 出队是「先进先出」：先入队的（离起点近的）先被处理。
//   这就是 BFS 能算最短路的全部秘密，也是第 31 课那道队列在这里的用处。
//
// ─────────────────────────────────────────────────────
//  三、BFS 的那个经典错法：入队太晚
// ─────────────────────────────────────────────────────
//
// 很多人写成这样：
//
//     while (队列不空) {
//         取出 当前;
//         for (四个方向) {
//             if (能走 && !访问过) {
//                 队列[队尾] = 邻居;           ← 入队了
//                 队尾++;
//             }                                ← 但没标记「访问过」
//         }
//     }
