//  先介绍：变量 = 给一个值起个名字
// ─────────────────────────────────────────────────────
//
//     int 年龄 = 18;
//     ↑   ↑     ↑
//    类型  名字  值
//
// ⚠⚠ **C 和 Python 最大的区别就在这里：C 必须先说类型。**
//
//     Python：  年龄 = 18              不用写类型
//     C：       int 年龄 = 18;         必须写 int
//
// 为什么：C 是**编译型**语言，编译时要为每个变量分配固定的内存大小，
// 所以它必须知道你打算装什么。这也让 C 跑得很快。
//
// 这一课只用 int（整数）。小数（float/double）在第 04 课。
//
// ⚠ 常见的错：
//     年龄 = 18;              ❌ 没写类型 ⇒ 报 undeclared identifier
//     int 年龄 = 18           ❌ 漏了分号 ⇒ 报 expected ';'
//     int 年龄 = 18;          ✅
//
// 打印变量和打印常量一样，都是 printf：
//     printf("%d\n", 年龄);   ← %d 是"这里放一个整数"的占位符
//
// ─────────────────────────────────────────────────────
//  用法与例子
// ─────────────────────────────────────────────────────
//
//  ① 声明并赋值（这一课只用这一种写法）：
//
//      int 年龄 = 18;          声明的同时给初值
//
//  ② 声明和赋值也可以分开写：
//
//      int 年龄;               先声明
//      年龄 = 18;              后赋值
//
//      ⚠ 中间那一小段时间里，年龄是**未初始化的**，
//        它的值是内存里的随机垃圾（第 07 课会专门讲这个）。
//        ⇒ 能一行写完就一行写完。
//
//  ③ 变量可以参与运算，也可以被重新赋值：
//
//      int 甲 = 17;
//      甲 = 甲 + 1;            ⇒ 18     右边先算，再存回左边
//
//  ④ 打印变量：格式符要和类型对上，int 就用 %d。
//
//      printf("%d\n", 年龄);
//
//  一个完整的、能跑的例子：
//
//      #include <stdio.h>
//
//      int main(void) {
//          int 年龄 = 18;
//          int 学号 = 7;
