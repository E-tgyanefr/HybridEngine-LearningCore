//          main.c:2:5: error: '\U00005e74\U00009f84' undeclared (first use in this function)
//              2 │     年龄 = 18;
//                │     ^~~~
//          main.c:2:5: note: each undeclared identifier is reported only once for each function it appears in
//
//      为什么：`\U00005e74\U00009f84` 就是「年龄」两个字的 Unicode 码点 ——
//      gcc 在报错信息里把非 ASCII 名字转义了，**它说的就是你的变量名**。
//      "undeclared" = 我没见过这个名字 ⇒ 因为你没告诉它类型。
//      ⚠ 看报错时不要被 `\U...` 吓到，把它当成你写的中文名字读。
//
//  ⚠ 坑 2：漏了分号 —— 而且报错会指向**下一行**
//
//      错误写法：
//          int 年龄 = 18
//          printf("%d\n", 年龄);
//
//      你会看到什么（gcc 原文）：
//
//          main.c:3:17: error: expected ';' before 'printf'
//              3 │     printf("%d\n", 年龄);
//                │                 ^
//                │                 ;
//
//      为什么：编译器一路读下去，直到撞见 `printf` 才发现
//      "上一句还没结束"。所以它**在第 3 行报错，错在第 2 行**。
