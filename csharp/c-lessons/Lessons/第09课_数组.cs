    public static string 参考答案 => """
int 求和(int 数们[], int 个数) {
    /* ⚠ 起点 0 —— C 未初始化的局部变量是随机值 */
    int 和 = 0;
    /* ⚠ i < 个数 不是 i <= 个数（那会越界读一个） */
    for (int i = 0; i < 个数; i++) {
        和 += 数们[i];
    }
    return 和;
}
""";


