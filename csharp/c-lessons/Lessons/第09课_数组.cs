//
// ─────────────────────────────────────────────────────
//  先介绍：一排连续的格子
// ─────────────────────────────────────────────────────
//
//     int 成绩[5];                 ← 声明 5 个格子
//     int 成绩[5] = {90, 75, 60, 45, 88};
//
//     成绩[0]   ⇒ 90        ⚠ 下标**从 0 开始**
//     成绩[4]   ⇒ 88        最后一个
//
// ⚠⚠⚠ **这一课唯一要记住的坑：C 的数组不检查越界。**
//
//     成绩[5]   ← 越界了！但 C **不报错**，它会读/写到别的内存去。
//                 写越界可能让你后面完全不相干的变量莫名其妙变值，
//                 或者程序直接崩（Segmentation fault）。
//
//   为什么：C 追求速度，不做运行时检查。数组名本质上只是一个地址，
//   `成绩[5]` 被算成"地址 + 5 个格子"，它不问你是不是超出去了。
//   ⇒ **下标的正确性是你自己的责任。**
//
// ⚠ 数组**没有长度信息**：用 `sizeof(数组)/sizeof(数组[0])` 只能算
//   **在同一个函数内**声明的数组。传进函数的数组会"退化"成指针，
//   所以**必须另外传一个"个数"参数** —— 这就是这一课的函数有两个参数的原因。
//
//     int 求和(int 数们[], int 个数)     ← 个数必须自己传
//
// ─────────────────────────────────────────────────────
//  用法与例子
// ─────────────────────────────────────────────────────
//
//  ① 声明并给初值：花括号里按顺序填。
//
//      int 成绩[5] = {90, 75, 60, 45, 88};
//
//  ② 只给一部分，剩下的自动是 0：
//
//      int 数们[5] = {1, 2};           ⇒ 1, 2, 0, 0, 0
//
//  ③ 让编译器自己数长度（推荐，不会写错）：
//
//      int 数们[] = {1, 2, 3, 4, 5};   ⇒ 长度自动是 5
//
//  ④ 读写单个格子：用 `名字[下标]`，下标从 **0** 到 **长度减一**。
//
//      数们[0] = 10;                  写
//      printf("%d\n", 数们[0]);       读
//
//  ⑤ 遍历：下标从 0 开始，条件写 `i < 长度`。
//
//      for (int i = 0; i < 5; i++) {
//          printf("%d\n", 数们[i]);
//      }
//
//      ⚠ 是 `< 长度`，不是 `<= 长度` —— 后者会越界读一个。
//
//  ⑥ 在**同一个函数内**想知道数组有几个元素：
//
//      int 个数 = sizeof(数们) / sizeof(数们[0]);      ⇒ 5
//
//      ⚠ 这一招**只在同一个函数里有效**，传进函数就失灵了（坑 1）。
//
//  一个完整的、能跑的例子：
//
//      #include <stdio.h>
//
//      int 求和(int 数们[], int 个数) {
//          int 和 = 0;
//          for (int i = 0; i < 个数; i++) {
//              和 += 数们[i];
//          }
//          return 和;
//      }
//
//      int main(void) {
//          int 数据[] = {1, 2, 3, 4, 5};
//          printf("%d\n", 求和(数据, 5));      ⇒ 15
//          return 0;
//      }
//
//  ⚠ 注意调用时**必须自己把 5 传进去** —— 函数那边是算不出长度的。
//
// ─────────────────────────────────────────────────────
//  常见坑
// ─────────────────────────────────────────────────────
//
//  ⚠ 坑 1：在函数里用 sizeof 算传进来的数组长度
//
//      错误写法：
//          int 求和(int 数们[]) {
//              int 个数 = sizeof(数们) / sizeof(数们[0]);   /* ⚠ 这里算错了 */
//              ...
//          }
//
//      你会看到什么（gcc 原文）：
//
//          main.c:3:32: warning: 'sizeof' on array function parameter '数们' will return size of 'int *' [-Wsizeof-array-argument]
//              3 │     int 个数 = sizeof(数们) / sizeof(数们[0]);
//                │                                ^
//          main.c:2:15: note: declared here
//              2 │ int 求和(int 数们[]) {
//                │           ~~~~^~~~~~
//
//      运行结果：个数 变成 1（64 位机器上 sizeof(int*) 是 8，sizeof(int) 是 4）
//      ⇒ 你的函数永远只加第一个元素。
//
//      为什么：**数组作为参数会"退化"成指针**。函数里的 `数们` 类型是 `int *`，
//      `sizeof(int *)` 是"一个指针占几字节"，跟数组有几个元素毫无关系。
//      ⚠ 这条同时也是理解第 15 课的钥匙。
//      ⇒ 唯一正确的做法：**长度另外传一个参数**。
//
//  ⚠ 坑 2：下标写错一位 —— 经典的越界
//
//      错误写法（想给 5 个格子赋值）：
//          int 数据[5];
//          for (int i = 1; i <= 5; i++) {
//              数据[i] = i;            /* ⚠ 数据[5] 越界了 */
//          }
//
//      你会看到什么：
//          ⚠ **gcc 这一次一声不吭，-Wall 也不报。** 编译通过、程序照跑。
//          但 `数据[5]` 已经写到了数组外面 —— 它可能踩坏了旁边某个变量，
//          也可能什么都没发生（这次运气好）。
//
//      为什么：C 把 `数据[i]` 算成"首地址 + i × 每格大小"，**不做范围检查**。
//      这套写法错在两个地方：
//        ① 下标应该从 0 开始（你从 1 开始了）；
//        ② 5 个格子合法的下标是 0 到 4，`<= 5` 会碰到 数据[5]。
//      ⇒ 遍历数组就用这一个模板，背下来：
//          for (int i = 0; i < 长度; i++)
//      ⚠ 越界写是**最难查**的一类 bug：报错的地方往往离出错的地方很远。
//
//  ⚠ 坑 3：以为数组可以整体赋值、整体比较
//
//      错误写法：
//          int 甲[3] = {1, 2, 3};
//          int 乙[3];
//          乙 = 甲;                    /* ❌ */
//          if (甲 == 乙) { ... }       /* ❌ */
//
//      你会看到什么：
//
//          main.c:3:7: error: assignment to expression with array type
//
//      为什么：C 的数组**不是"值"**，它只是一个地址（第 15 课）。
//      地址不能被赋值，两个地址比较也不会去看内容。
//      ⇒ 想复制就一个个搬（`for` 循环），想比较就一个个比。
//      ⚠ 字符串（char 数组）是例外中的例外 —— 它有 `strcpy` 和 `strcmp`
//        这两个现成的函数，但那也是"函数帮你循环"，不是语言支持。
