#include <stdio.h>

#define 最大N 20

long long C[最大N + 1][最大N + 1];      /* 全局的，自动全是 0 */

void 填表(void) {
    C[0][0] = 1;
    for (int n = 1; n <= 最大N; n++) {
        C[n][0] = 1;                    /* 一个都不挑：1 种 */
        for (int k = 1; k <= n; k++) {  /* ⚠ 只填到 k = n */
            C[n][k] = C[n - 1][k - 1] + C[n - 1][k];
        }
    }
}

long long 组合数(int n, int k) {
    if (k < 0 || k > n) return 0;
    return C[n][k];
}

int main(void) {
    填表();

    /* 2. 杨辉三角前 5 行 */
    for (int n = 0; n <= 4; n++) {
        for (int k = 0; k <= n; k++) {
            if (k > 0) printf(" ");
            printf("%lld", C[n][k]);
        }
        printf("\n");
    }

    /* 3. 组合数 */
    printf("C(5,2) = %lld\n", 组合数(5, 2));
    printf("C(6,3) = %lld\n", 组合数(6, 3));
    printf("C(10,4) = %lld\n", 组合数(10, 4));
    printf("C(20,10) = %lld\n", 组合数(20, 10));
    return 0;
}
""";


