void 统计(int 数们[], int 个数, int *最大, int *最小) {
    /* ⚠ 空数组要特判，否则 数们[0] 就越界读了 */
    if (个数 <= 0) {
        return;
    }
    /* ⚠ 初值从第一个元素起 —— 写 0 的话全负数就错了 */
    int 大 = 数们[0];
    int 小 = 数们[0];
    for (int i = 1; i < 个数; i++) {
        if (数们[i] > 大) 大 = 数们[i];
        if (数们[i] < 小) 小 = 数们[i];
    }
    *最大 = 大;              /* ⚠ *最大 才是"写进调用者的变量" */
    *最小 = 小;
}
""";


