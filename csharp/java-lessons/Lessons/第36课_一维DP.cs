// 参考答案 —— 一维动态规划（只写方法，不用写 class / main / import）
//
// 三个方法都是同一个套路：开一张 dp 表 → 写死初始值 → 从前往后填 → 返回最后一格。

// 1. 爬楼梯：dp[i] = 走到第 i 级有几种走法
//    转移：最后一步要么从 i-1 迈 1 级，要么从 i-2 迈 2 级
static long 爬楼梯(int n) {
    if (n == 0) {
        return 1;                        /* 站在原地不动 —— 算一种"走法" */
    }
    long[] dp = new long[n + 1];
    dp[0] = 1;
    dp[1] = 1;
    for (int i = 2; i <= n; i++) {
        dp[i] = dp[i - 1] + dp[i - 2];
    }
    return dp[n];
}

// 2. 打家劫舍：dp[i] = 只考虑前 i 家能偷到的最大值
//    ⚠ dp[i] 说的是"前 i 家"（个数），所以第 i 家的金额是 金额[i-1]
static long 打家劫舍(int[] 金额) {
    int 家数 = 金额.length;
    if (家数 == 0) {
        return 0;
    }
    long[] dp = new long[家数 + 1];
    dp[0] = 0;
    dp[1] = 金额[0];                      /* 只有一家 ⇒ 就偷它 */
    for (int i = 2; i <= 家数; i++) {
        long 偷这家 = 金额[i - 1] + dp[i - 2];   /* 偷了它，i-1 家就不能偷 */
        long 不偷 = dp[i - 1];
        dp[i] = 偷这家 > 不偷 ? 偷这家 : 不偷;
    }
    return dp[家数];
}

// 3. 01 背包：dp[j] = 容量为 j 时能装下的最大价值
//    ⚠ 内层容量必须**从大到小** —— 从小到大等于同一件东西拿了多次（那是完全背包）
static int 背包(int[] 重量, int[] 价值, int 容量) {
    int[] dp = new int[容量 + 1];         /* 初始全 0：容量 0 装不下任何东西 */
    for (int i = 0; i < 重量.length; i++) {
        for (int j = 容量; j >= 重量[i]; j--) {
            int 拿这件 = 价值[i] + dp[j - 重量[i]];
            if (拿这件 > dp[j]) {
                dp[j] = 拿这件;
            }
        }
    }
    return dp[容量];
}
""";

