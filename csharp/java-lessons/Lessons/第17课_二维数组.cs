    public static JavaCheckResult 检查_每行最大(string 代码)
    {
        var run = 跑一次(代码);
        string 停 = 先别急着比(run);
        if (停.Length > 0) return JavaCheckResult.不过(停);
        return 比(run,
            ("行最大甲|", "9", "每行最大的数(甲, 0)　甲 的第 0 行是 {9,8,7,6}"),
            ("行最大戊|", "99", "每行最大的数(戊, 1)　⚠ 第 1 行是 {2,4,99}，比别的行长 —— 拿第 0 行的长度就会漏掉那个 99"));
    }

