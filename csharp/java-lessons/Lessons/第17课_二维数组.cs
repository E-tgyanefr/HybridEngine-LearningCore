    // 一次检查会给每个检查方法各跑一次，而它们的输入是同一份代码 ——
    // 编译一次就够了（每次编译要起一次 javac，一两秒）。
    private static string 上次的代码 = "";
    private static JavaRun 上次的运行;

    private static JavaRun 跑一次(string 代码)
    {
        if (上次的运行 != null && 上次的代码 == 代码) return 上次的运行;
        上次的代码 = 代码;
        var 包 = JavaCheck.编译并运行(代码, 骨架, 调用点);
        // ⚠ 编译不过时不缓存 —— 那说明还没跑到"比结果"这一步。
        上次的运行 = 包.编译通过 ? 包 : null;
        return 包;
    }

    /// <summary>空串 = 可以接着比结果；非空 = 这条检查到此为止的说明。</summary>
    private static string 先别急着比(JavaRun run)
    {
        if (run.Raw.CompileFailed)
        {
            string 停 = 编译失败的说明(run);
            return 停.Length > 0 ? 停 : JavaCheck.编译失败说明(run).Detail;
        }
        if (run.Raw.Error != null) return "程序没跑完就退出了：\n      " + run.Raw.Error;
        return "";
    }

    /// <summary>
    /// 把几条「学生最容易撞上、但 javac 说不清楚」的编译错误翻译成本课的话。
    /// 认不出来就返回空串，交给统一的 编译失败说明。
    /// </summary>
    private static string 编译失败的说明(JavaRun run)
    {
        string 信息 = run.编译信息;
        if (信息.Contains("ArrayIndexOutOfBounds"))
            return "下标越界了：\n      " + JavaRunner.FirstError(信息) + "\n" +
                   "      列下标只能取 0 ~ 格[i].length-1 —— 是**这一行**的长度。";
        if (信息.Contains("Index") && 信息.Contains("out of bounds"))
            return "下标越界了：\n      " + JavaRunner.FirstError(信息);
        return "";
    }

    /// <summary>比一批「标记|值」。同一个标记要在调用点里出现几次就给几组。</summary>
    private static JavaCheckResult 比(JavaRun run, params (string 标记, string 期望, string 说明)[] 用例们)
    {
        var 错 = new List<string>();
        foreach (var (标记, 期望, 说明) in 用例们)
        {
            string 得到 = 看看(run, 标记);
            if (得到.Length == 0) 错.Add("      " + 说明 + "：没有找到这个标记的输出");
            else if (!一样(得到, 期望))
                错.Add("      " + 说明 + "：得到「" + 得到 + "」，应该是「" + 期望 + "」");
        }
        if (错.Count == 0) return JavaCheckResult.过($"这几组都对（{用例们.Length} 组）");

        return JavaCheckResult.不过(
            "结果不对：\n" + string.Join("\n", 错) + "\n" +
            "      表格的两种走法：\n" +
            "          按行  外层 i（行）、内层 j（列），取 格[i][j]\n" +
            "          按列  外层 j（列）、内层 i（行），**还是**取 格[i][j]\n" +
            "      ⚠ Java 的每一行可以不一样长，所以长度要问**那一行**：格[i].length。\n" +
            "        拿 格[0].length 当所有行的长度，长方形数据上看着全对，\n" +
            "        换成锯齿数据不是漏算就是越界崩溃。");
    }

    /// <summary>取「标记|」之后到行尾的内容。</summary>
    private static string 看看(JavaRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int 位 = 行.IndexOf(标记, System.StringComparison.Ordinal);
            if (位 >= 0) return 行.Substring(位 + 标记.Length).Trim();
        }
        return "";
    }

    /// <summary>把连续空白折成一个空格再比 —— 学生多打一个空格不该判错。</summary>
    private static bool 一样(string 甲, string 乙) =>
        Regex.Replace(甲.Trim(), @"\s+", " ") == Regex.Replace(乙.Trim(), @"\s+", " ");

    /// <summary>去掉注释，免得注释里的字样骗过文本检查。</summary>
    private static string 去掉注释(string s)
    {
        var o = new System.Text.StringBuilder();
        bool 块 = false;
        for (int i = 0; i < s.Length; i++)
        {
            if (!块 && i + 1 < s.Length && s[i] == '/' && s[i + 1] == '/')
            { while (i < s.Length && s[i] != '\n') i++; o.Append('\n'); continue; }
            if (!块 && i + 1 < s.Length && s[i] == '/' && s[i + 1] == '*') { 块 = true; i++; continue; }
            if (块 && i + 1 < s.Length && s[i] == '*' && s[i + 1] == '/') { 块 = false; i++; continue; }
            if (!块) o.Append(s[i]);
        }
        return o.ToString();
    }
