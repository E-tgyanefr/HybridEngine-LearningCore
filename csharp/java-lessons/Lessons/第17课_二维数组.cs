//
// ══ 这一课要教什么 ══
// 一排格子装不下「班级成绩」「棋盘」「地图」这类**表格**，于是要「格子排成行、
// 每行又是一排格子」：二维数组 int[][]。
//
// 这一课真正要建立的是两件事：
//   ① **两层循环的方位感** —— 按行走（外层 i、内层 j）和按列走（外层 j、内层 i）
//      都要会，而且方括号里**永远是 格[i][j]**，一次都不变。
//   ② Java 独有的那条：**二维数组是「数组的数组」**，所以每一行可以不一样长。
//      这是 Java 和 C++ 最大的一处差别（C++ 那边列数必须写死在参数类型里）。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**按列走的时候必须问每一行自己有多长**（格[i].length），
//   不能拿第 0 行的长度当所有行的长度。
//   为什么它是核心：喂一份**锯齿**数据（各行 2 / 3 / 1 个元素）时，
//   照着 格[0].length 写死的循环要么越界崩溃、要么漏算 ——
//   而同一份代码在长方形数据上**一字不差地正确**。
//   所以检查里两份数据都喂：甲/乙/丙/丁 是长方形的，戊 是锯齿的。
// 第二条防线：**每一组都换一份数据**（甲/乙/丙/丁/负/戊 六份）。
//   把答案写死的、或者只对某一份凑出来的，换一份立刻错。
//   矩阵最大 里特意放了**整张表全是负数**的 负 —— 初值写 0 的话这里会错成 0。
//
// ⚠ 这一课的学生代码**只写方法**，不写 class、不写 main、不写 import ——
//   骨架（见下面的 骨架）会把它们塞进 class Main 里，并替学生调用和打印。
//   所以参考答案也必须是「一串方法」，绝不能带上 public class Main
