    public static string 参考答案 => """
// 参考答案 —— 二维数组（只写方法，不用写 class / main / import）
//
// 这一课的正题就是下面这几处 `格[i].length`：
// 内层循环要问每一行自己的长度，按列求和也要问 —— 问的对象永远是**那一行**，
// 不是第 0 行，也不是外面传进来的某个固定数字。

// 1. 按行求和，拼成 [25,34,24]
static String 每行和(int[][] 格, int 行数) {
    StringBuilder 结果 = new StringBuilder("[");
    for (int i = 0; i < 行数; i++) {
        int 和 = 0;
        for (int j = 0; j < 格[i].length; j++) {   /* ⚠ 不是 格[0].length */
            和 = 和 + 格[i][j];
        }
        if (i > 0) {
            结果.append(",");
        }
        结果.append(和);
    }
    结果.append("]");
    return 结果.toString();
}

// 2. 第 列号 列的和：行不够长就跳过那一行（不能去读它）
static int 列和(int[][] 格, int 行数, int 列号) {
    int 和 = 0;
    for (int i = 0; i < 行数; i++) {
        if (列号 < 格[i].length) {                  /* ⚠ 问的是第 i 行 */
            和 = 和 + 格[i][列号];
        }
    }
    return 和;
}

// 3. 主对角线：两个下标一起走，走到最短那一行用完为止
static int 主对角线和(int[][] 格) {
    int 最短 = 格.length;
    for (int i = 0; i < 格.length; i++) {
        if (格[i].length < 最短) {
            最短 = 格[i].length;
        }
    }
    int 和 = 0;
    for (int i = 0; i < 最短; i++) {
        和 = 和 + 格[i][i];
    }
    return 和;
}

// 4. 全表最大：⚠ 初值必须取一个**表里真的有**的数 ——
//    写成 0 的话，整张表全是负数时会返回一个根本不存在的 0
static int 矩阵最大(int[][] 格) {
    if (格.length == 0) {
        return 0;
    }
    int 最大 = 格[0][0];
    for (int i = 0; i < 格.length; i++) {
        for (int j = 0; j < 格[i].length; j++) {
            if (格[i][j] > 最大) {
                最大 = 格[i][j];
            }
        }
    }
    return 最大;
}

// 5. 第 行号 行里最大的数
static int 每行最大的数(int[][] 格, int 行号) {
    int 最大 = 格[行号][0];
    for (int j = 1; j < 格[行号].length; j++) {
        if (格[行号][j] > 最大) {
            最大 = 格[行号][j];
        }
    }
    return 最大;
}
