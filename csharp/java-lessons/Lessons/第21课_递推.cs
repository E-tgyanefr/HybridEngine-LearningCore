// 参考答案 —— 递推（只写方法，不用写 class / main / import）
//
// 两个方法的骨架一模一样，唯一的区别是**起点**：
//   斐波那契：表[0] = 0、表[1] = 1
//   爬楼梯　：表[0] = 1、表[1] = 1
// 认出「爬楼梯就是斐波那契」是这一课的另一半功夫。

// 1. 斐波那契：从 0 往后填表，每个 i 只算一次
static long 斐波那契(int n) {
    if (n < 2) {
        return n;                     /* 0 → 0，1 → 1 */
    }
    long[] 表 = new long[n + 1];      /* ⚠ 长度是 n+1：下标 0..n 都要装得下 */
    表[0] = 0;
    表[1] = 1;
    for (int i = 2; i <= n; i++) {
        表[i] = 表[i - 1] + 表[i - 2];   /* 前两个早就算好了，直接拿 */
    }
    return 表[n];
}

// 2. 爬楼梯：同一个递推，起点不同
//    走法(0) = 1（站在原地也算一种走法），走法(1) = 1
static long 爬楼梯(int n) {
    if (n == 0) {
        return 1;
    }
    long[] 表 = new long[n + 1];
    表[0] = 1;
    表[1] = 1;
    for (int i = 2; i <= n; i++) {
        表[i] = 表[i - 1] + 表[i - 2];
    }
    return 表[n];
}
""";

