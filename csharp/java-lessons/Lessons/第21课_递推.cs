    [Java检查说明("递推的写法对：表开了、循环也从前往后走了")]
    public static JavaCheckResult 检查_是递推写法(string 代码)
    {
        string 净 = 去掉注释(代码);
        string 体 = 函数体(净, "斐波那契");
        if (体 == null)
            return JavaCheckResult.不过("没找到 斐波那契 的函数体 —— 先确认这个方法写全了（花括号配对）。");

        var 缺 = new List<string>();
        if (!Regex.IsMatch(体, @"\bfor\b|\bwhile\b")) 缺.Add("      斐波那契：函数体里没有循环");
        if (!体.Contains("[")) 缺.Add("      斐波那契：没有看到数组（递推表）");
        if (缺.Count == 0)
            return JavaCheckResult.过("斐波那契用了递推：开表 + 从前往后填");

        return JavaCheckResult.不过(
            "斐波那契 看起来不像递推：\n" + string.Join("\n", 缺) + "\n" +
            "      递推的样子是「先摆好前两个，再一个个往后填」：\n" +
            "          long[] 表 = new long[n + 1];\n" +
            "          表[0] = 0;\n" +
            "          表[1] = 1;\n" +
