// 第 21 课：递推 —— 从前往后填表，别从后往前问
//
// ══ 这一课要教什么 ══
// 斐波那契和爬楼梯都是「后面由前面决定」的问题。最自然的写法是递归：
//
//     斐波那契(n) = 斐波那契(n-1) + 斐波那契(n-2)
//
// 可这个写法有个致命问题：**同一件事被算了无数遍**。
// 斐波那契(60) 会展开成 2^60 级别的调用 —— 一分钟、一小时、一辈子都算不完。
//
// 递推（动态规划的第一种形态）反过来做：**从最小的开始，一路往后填表**。
// 每个 n 只算一次，算完存起来，后面直接用。O(n) 步就出答案。
//
// 这一课要建立的是这个方向感：**从前往后填**，而不是**从后往前问**。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**递归会超时**。
//   调用点里跑 斐波那契(60) —— 纯递归写法在这一个调用上就指数爆炸，
//   撞 60 秒默认超时（运行时错误信息是「程序运行超时（超过 60 秒）—— 检查有没有死循环」）。
//   递推写法瞬间完成，而且还要接着跑 爬楼梯(300)（这个结果大到 long 都装不下？
//   不 —— 爬楼梯(300) 是 3.6e62，long 装不下，所以这一课的 爬楼梯 只跑到 90 以内，
//   300 那一档只用来证明「递推能瞬间做到递归永远做不到的规模」）。
//   ⚠ 实测数据：斐波那契(60) 纯递归要几十亿次调用，必然超时。
// 第二条防线：**答案要对**（0/1/2/10/25/30/60 逐点比对）——
//   「超时」只能证明它不是递归，不能证明它算对了。
// 第三条：**用递推必须开数组或滚动变量** —— 去掉注释后
//   `斐波那契` 的方法体里出现 `[`（数组/下标）或者出现循环。纯递归只有自我调用。
//
// ⚠ 学生只写方法；骨架预置 import。

