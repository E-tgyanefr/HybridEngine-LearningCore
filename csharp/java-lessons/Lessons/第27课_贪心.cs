// 参考答案 —— 贪心（只写方法，不用写 class / main / import）

// 1. 找零：从大到小尽量拿（这套面额下贪心是最优的）
static String 找零(int 金额) {
    int[] 面额 = {100, 50, 20, 10, 5, 1};
    StringBuilder 结果 = new StringBuilder();
    int 剩 = 金额;
    for (int i = 0; i < 面额.length; i++) {
        int 张数 = 剩 / 面额[i];
        if (张数 > 0) {
            if (结果.length() > 0) {
                结果.append("+");
            }
            结果.append(面额[i]).append("*").append(张数);
            剩 = 剩 - 张数 * 面额[i];
        }
    }
    if (结果.length() == 0) {
        return "无";                       /* 金额 ≤ 0 时什么都拿不到 */
    }
    return 结果.toString();
}

// 2. 最少硬币：⚠ 动态规划，不是贪心
//    贪心在 {4,3,1} 找 6 上会给出 4+1+1（3 枚），而最优是 3+3（2 枚）。
//    递推式：最少[i] = min(最少[i - c] + 1)，c 遍历所有币值
static int 最少硬币(int[] 币值, int 金额) {
    if (金额 < 0) {
        return -1;
    }
    int 到不了 = 金额 + 1;                  /* 一个"比任何合法答案都大"的数，当无穷用 */
    int[] 最少 = new int[金额 + 1];
    Arrays.fill(最少, 到不了);
    最少[0] = 0;                            /* 凑 0 元要 0 枚 —— 递推的起点 */
    for (int i = 1; i <= 金额; i++) {
        for (int c : 币值) {
            if (c <= i && 最少[i - c] + 1 < 最少[i]) {
                最少[i] = 最少[i - c] + 1;   /* 用一枚 c，剩下的 i-c 早就算好了 */
            }
        }
    }
    if (最少[金额] == 到不了) {
        return -1;                          /* 真的凑不出来 */
    }
    return 最少[金额];
}

// 3. 区间调度：按**结束时间**排序，然后能选就选
//    为什么按结束时间：结束得越早，留给后面的空间越大。
//    ⚠ 按开始时间最早选、按长度最短选，都是错的。
static int 区间调度(int[][] 区间) {
    int[][] 副本 = new int[区间.length][];
    for (int i = 0; i < 区间.length; i++) {
        副本[i] = new int[]{区间[i][0], 区间[i][1]};
    }
    /* 按结束时间（第 1 列）从小到大排 */
    Arrays.sort(副本, (a, b) -> a[1] - b[1]);

    int 选了几个 = 0;
    int 上次结束 = Integer.MIN_VALUE;        /* 第一个活动之前，什么都不冲突 */
    for (int i = 0; i < 副本.length; i++) {
        if (副本[i][0] >= 上次结束) {         /* 开始时间不早于上次结束 ⇒ 不重叠 */
            选了几个 = 选了几个 + 1;
            上次结束 = 副本[i][1];
        }
    }
    return 选了几个;
}
""";

