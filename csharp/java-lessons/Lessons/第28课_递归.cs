    [Java检查说明("★ 汉诺塔的每一步顺序对（n=1/2/3 的全部输出逐个比）")]
    public static JavaCheckResult 检查_顺序对(string 代码)
    {
        // ⚠ 核心检查点之二：把打印挪到递归前面，步数可能还是 2^n-1，但顺序全错。
        //   n=1/2/3 一共 1+3+7 = 11 行，全比最稳。
        var run = 跑一次(代码);
        string 停 = 先别急着比(run);
        if (停.Length > 0) return JavaCheckResult.不过(停);

        string 实际 = 看看(run, "1起|", "1止|") + "\n"
                    + 看看(run, "2起|", "2止|") + "\n"
                    + 看看(run, "3起|", "3止|");
        string[] 期望行 = {
            "把1从A移到C",
            "把1从A移到B", "把2从A移到C", "把1从B移到C",
            "把1从A移到C", "把2从A移到B", "把1从C移到B", "把3从A移到C",
            "把1从B移到A", "把2从B移到C", "把1从A移到C",
        };
        var 行们 = 实际.Trim().Length == 0
            ? new string[0]
            : Regex.Split(实际.Trim(), @"[\r\n]+");
        if (行们.Length == 期望行.Length)
        {
            bool 全同 = true;
            for (int i = 0; i < 行们.Length; i++)
                if (行们[i].Trim() != 期望行[i]) { 全同 = false; break; }
            if (全同) return JavaCheckResult.过("n=1、2、3 的每一步顺序全对（一共 11 步）");
        }

        string 第一处 = $"步数不对：得到 {行们.Length} 行，应当是 {期望行.Length} 行";
        for (int i = 0; i < System.Math.Min(行们.Length, 期望行.Length); i++)
            if (行们[i].Trim() != 期望行[i])
            { 第一处 = $"第 {i + 1} 步：得到「{行们[i].Trim()}」，应该是「{期望行[i]}」"; break; }
        string 归一 = string.Join(" ", 行们).Trim();
        string 期望归 = string.Join(" ", 期望行);

        return JavaCheckResult.不过(
            "汉诺塔的步骤顺序不对：\n      " + 第一处 + "\n" +
            $"      期望（n=1、2、3 连起来一共 11 步）：\n        {期望归}\n" +
            $"      实际：\n        {归一}\n" +
            "      ⇒ 三行的顺序必须是：\n" +
            "          ① 汉诺塔(n-1, 从, 借, 到);     先搬上面的盘子（挪到借用的柱子）\n" +
            "          ② 打印「把n从从移到到」           最大的那个搬到位\n" +
            "          ③ 汉诺塔(n-1, 借, 到, 从);     上面的盘子再挪到目的地\n" +
            "      ⚠ 顺序反了的话，步数可能还是 2^n-1，但每一步都错位。");
    }

