// 第 28 课：递归 —— 函数自己调用自己
//
// ══ 这一课要教什么 ══
// 递归看起来像魔法：一个函数"自己调用自己"，怎么会停下来？
// 答案是两件事必须同时具备：
//   ① **基准情形**（base case）：小到可以直接回答的那一步，它不再调用自己
//   ② **每一步都在变小**：每次递归的参数都比上一次更接近基准情形
// 少任何一条，程序就变成一个停不下来的机器（或者更快地报栈溢出）。
//
// 这一课用汉诺塔来讲 —— 它是递归最漂亮的例子：**抛开"怎么搬"，
// 只描述"如果 n-1 个已经搬好了，那么第 n 个怎么搬"**。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**必须自己调用自己**。
//   学生很容易用循环算出 2^n - 1 和一堆打印来冒充 ——
//   去掉注释后切开 `汉诺塔` 的方法体，里面必须出现 `汉诺塔(`。
// 核心检查点二：**递归的顺序必须是「先搬上层、再搬底层、最后搬上层」**。
//   汉诺塔的步数和第一条移动是**唯一确定的**：
//     n=1 ⇒ 1 步、A→C
//     n=2 ⇒ 3 步：把1从A移到B / 把2从A移到C / 把1从B移到C
//     n=3 ⇒ 7 步，第一步「把1从A移到B」、最后一步「把1从B移到C」
//   把「先打印再递归」写反了的实现，步数可能是 2^n-1 而**第一条移动就错了** ——
//   所以检查里逐行比对 n=1、n=2、n=3 的全部输出（7 行很短，全比最稳）。
// 第三条：**大 n 上要瞬间出答案**（汉诺塔步数(60) 只算数不搬盘子）。
//   如果学生在 步数 里也去"模拟搬盘子"，60 个盘子是 2^60 步 —— 必然超时。
//
// ⚠ 学生只写方法；骨架预置 import。

