    public static string 参考答案 => """
// 参考答案 —— 递归（只写方法，不用写 class / main / import）

// 1. 步数 = 2^n - 1。用递推算，绝不去模拟搬盘子
//    （n = 60 时是 1.15e18 步 —— 真搬的话宇宙都结束了）
static long 汉诺塔步数(int n) {
    long 步 = 0;
    for (int i = 0; i < n; i++) {
        步 = 步 * 2 + 1;               /* 递推式：步数(n) = 2 × 步数(n-1) + 1 */
    }
    return 步;
}

// 2. 汉诺塔：三行的顺序就是全部
//    ① 上面 n-1 个从「从」搬到「借」（把「到」借给它当暂存）
//    ② 第 n 个（最大的那个）从「从」搬到「到」—— 这时它下面是空的
//    ③ 那 n-1 个再从「借」搬到「到」（这回借「从」当暂存）
static void 汉诺塔(int n, char 从, char 到, char 借) {
    if (n == 0) {
        return;                        /* 基准情形：没有盘子要搬了 —— 少了这一行就栈溢出 */
    }
    汉诺塔(n - 1, 从, 借, 到);          /* ① 把上层挪到借用的柱子上 */
    System.out.println("把" + n + "从" + 从 + "移到" + 到);   /* ② 最大的那个搬到位 */
    汉诺塔(n - 1, 借, 到, 从);          /* ③ 把上层挪到目的地 */
}

// 3. 阶乘：递归最直白的例子（n 大了会溢出，n 到 20 为止）
static long 阶乘(int n) {
    if (n <= 1) {
        return 1;                      /* 基准情形：0! = 1、1! = 1 */
    }
    return n * 阶乘(n - 1);             /* 每次参数都变小 ⇒ 一定到得了基准情形 */
}
""";

