    public static string 参考答案 => """
// 参考答案 —— 二维 DP（只写方法，不用写 class / main / import）

// 1. 网格路径数：dp[i][j] = 走到 (i,j) 的走法数
//    转移：只能从上面 (i-1,j) 或者左边 (i,j-1) 过来
static long 网格路径数(int 行数, int 列数) {
    if (行数 <= 0 || 列数 <= 0) {
        return 0;
    }
    long[][] dp = new long[行数][列数];
    for (int i = 0; i < 行数; i++) {
        dp[i][0] = 1;                     /* ⚠ 第一列：只能一路往下走 ⇒ 1 种 */
    }
    for (int j = 0; j < 列数; j++) {
        dp[0][j] = 1;                     /* ⚠ 第一行：只能一路往右走 ⇒ 1 种 */
    }
    for (int i = 1; i < 行数; i++) {
        for (int j = 1; j < 列数; j++) {
            dp[i][j] = dp[i - 1][j] + dp[i][j - 1];   /* 上面 + 左边 */
        }
    }
    return dp[行数 - 1][列数 - 1];
}

// 2. 最长公共子序列：dp[i][j] = 甲的前 i 个、乙的前 j 个 的 LCS 长度
//    ⚠ "两个末字符不同"时必须取 max（扔掉甲的一个 或 扔掉乙的一个），
//      只抄左上角会偏小
static int 最长公共子序列(String 甲, String 乙) {
    int 甲长 = 甲.length();
    int 乙长 = 乙.length();
    /* ⚠ 表要比字符串长一格：dp[i][j] 说的是"前 i 个"，i 要到 length() */
    int[][] dp = new int[甲长 + 1][乙长 + 1];

    for (int i = 1; i <= 甲长; i++) {
        for (int j = 1; j <= 乙长; j++) {
            if (甲.charAt(i - 1) == 乙.charAt(j - 1)) {   /* ⚠ 第 i 个字符的下标是 i-1 */
                dp[i][j] = dp[i - 1][j - 1] + 1;
            } else {
                int 扔甲 = dp[i - 1][j];
                int 扔乙 = dp[i][j - 1];
                dp[i][j] = 扔甲 > 扔乙 ? 扔甲 : 扔乙;      /* ⚠ 这一支不能少 */
            }
        }
    }
    return dp[甲长][乙长];
}
""";

