// ══ 这一课要教什么 ══
// 第 36 课的 dp 是一维的（dp[i]）。这一课升到二维：**dp[i][j]**。
//
// 什么时候需要两维？当答案由**两个"进度"共同决定**的时候：
//   · 网格路径：走到第 i 行、第 j 列有几种走法        （行、列 两个进度）
//   · 最长公共子序列：甲串前 i 个、乙串前 j 个的最长公共子序列有多长
//
// 一旦把状态想成"一张表"，整个算法就变成**填表**：
// 从左上往右下填，每格的答案由它**上边、左边、左上角**那几格推出来。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**网格路径只能往右/往下走** —— 这个"方向限制"就是递推式的来源。
//   检查里喂 (10,10)、(3,7)、(1,8)、(20,20) 四组不同尺寸，
//   以及 **i=0 或 j=0 的整行整列**（那时只有 1 种走法）。
//   写成"两维都用 dp[i-1][j-1] * 2"之类的凑法在边界上立刻错。
//   另外 (20,20) 的答案是 35345263800 —— **超出 int**，所以返回 long
//   （返回值写成 int 的话，这里会得到一个负数）。
// 核心检查点二：**LCS 的三种情况必须分清**（这一课真正的新知识）：
//     dp[i][j] = dp[i-1][j-1] + 1                       两个末字符相同
//     dp[i][j] = max(dp[i-1][j], dp[i][j-1])            不同
//   只在"相同"时加 1、不同时忘了取 max 的写法，
//   在 "abcde"/"ace"（答案 3）这种"夹杂着跳字符"的输入上会**偏小**。
//   检查里喂了四组，其中 `"abcde" / "ace"` 是专抓这一点的。
// 第三条：不能是暴力递归 —— (20,20) 那一组和长度 60 的串会让指数级写法跑不完。
//
