                "程序**跑不完**（超时）—— 这通常说明你写的是暴力递归。\n" +
                "      检查里的规模：20×20 的网格、长度 60 的字符串。\n" +
                "      暴力递归在网格上是「每一步分叉成两个方向」⇒ 指数级；\n" +
                "      LCS 上是「每个字符都比一遍」⇒ 也是指数级。\n" +
                "      ⇒ 换成**二维填表**：\n" +
                "          网格   dp[i][j] = dp[i-1][j] + dp[i][j-1]，第一行第一列填 1\n" +
                "          LCS    dp[i][j] = 相同 ? dp[i-1][j-1]+1 : max(dp[i-1][j], dp[i][j-1])\n" +
                "      每个格子只算一次 ⇒ 20×20 就是 400 次运算。");
        string 停 = 先别急着比(run);
        if (停.Length > 0) return JavaCheckResult.不过(停);
        return 比(run,
            ("长串|", "30", "长度 60 的两个固定字符串的 LCS 长度（按 (i*7+3)%4 和 (i*5+1)%4 生成）　⚠ 递归写法在这里跑不完"),
            ("长网|", "true", "20×20 的网格也算出来了"));
    }

