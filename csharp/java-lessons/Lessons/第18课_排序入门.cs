//
// ══ 这一课要教什么 ══
// 排序是「两层循环」最经典的一次实战。这一课要手写三种：
//     冒泡（比相邻两个，大的往后冒）
//     选择（每轮挑出剩下里最小的，放到前面）
//     插入（把新来的数插到前面已经排好的那一段里）
//
// 三种写法的思路完全不同，但**都必须练** —— 因为：
//   · 它们的复杂度都是 O(n²)，是第 20 课「复杂度」那一课的活教材；
//   · 插入排序天然**稳定**，冒泡写对也稳定，选择排序**不稳定**
//     —— 第 19 课讲稳定性时要回头看这一课；
//   · 考场上 Arrays.sort 不一定让用，手写是基本功。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**不许用现成的排序函数交差**。
//   学生最省事的做法是 `Arrays.sort(数)` —— 输出完全正确，
//   但这一课要练的是「两层循环怎么控制边界」，调库等于没学。
//   防法：去掉注释后看源码文本，出现 Arrays.sort / Collections.sort / .sort( 就判不过。
// 核心检查点二：**三个函数体内各自必须有循环**。
//   光禁库函数还不够 —— 学生可以把答案抄成三行 `数[0]=…; 数[1]=…;`（对固定用例能蒙对）。
//   防法：按函数名切开源码、取各自的花括号，在**这个函数体里**找 for / while。
