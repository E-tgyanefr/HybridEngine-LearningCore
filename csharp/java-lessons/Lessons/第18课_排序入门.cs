    [Java检查说明("长度是 0 和 1 的时候不能崩（循环边界最容易在这里写错）")]
    public static JavaCheckResult 检查_空数组和单元素(string 代码)
    {
        var run = 跑一次(代码);
        string 停 = 先别急着比(run);
        if (停.Length > 0) return JavaCheckResult.不过(停);
        return 比(run,
            ("冒泡空|", "[]", "冒泡排序({}, 0)　长度 0 时什么都不用做"),
            ("选择空|", "[]", "选择排序({}, 0)"),
            ("插入空|", "[]", "插入排序({}, 0)"),
            ("冒泡单|", "[42]", "冒泡排序({42}, 1)　长度 1 时什么都不用做"),
            ("选择单|", "[42]", "选择排序({42}, 1)"),
            ("插入单|", "[42]", "插入排序({42}, 1)"));
    }

