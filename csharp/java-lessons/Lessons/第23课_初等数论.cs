// 参考答案 —— 初等数论（只写方法，不用写 class / main / import）
//
// 三个方法共用同一个观察：**因数是一对一对出现的**，
// 所以试到 √n 就够了 —— 循环条件写 (long) i * i <= n。

// 1. 数因数：每找到一个 i，就同时找到了 n/i 两个
static int 因数个数(int n) {
    if (n <= 0) {
        return 0;                          /* 0 和负数的因数有无限多个，不算 */
    }
    int 个数 = 0;
    for (int i = 1; (long) i * i <= n; i++) {
        if (n % i == 0) {
            个数 = 个数 + 1;                /* i 是一个因数 */
            if (i != n / i) {
                个数 = 个数 + 1;            /* n/i 是另一个（完全平方数时它俩相等，只算一次） */
            }
        }
    }
    return 个数;
}

// 2. 判断质数：⚠ 第一行的 n < 2 是这个方法最要紧的一句
//    少了它，n = 1 时循环一次都不进，直接 return true —— 1 就被当成了质数
static boolean 是质数(int n) {
    if (n < 2) {
        return false;                      /* 1、0、负数都不是质数 */
    }
    for (int i = 2; (long) i * i <= n; i++) {
        if (n % i == 0) {
            return false;                  /* 找到了 1 和自己以外的因数 */
        }
    }
    return true;
}

// 3. 质因数分解：从小到大，能除就除
static String 质因数分解(int n) {
    if (n < 2) {
        return "" + n;                     /* 1、0、负数原样返回 */
    }
    StringBuilder 结果 = new StringBuilder();
    int 剩 = n;
    for (int i = 2; (long) i * i <= 剩; i++) {
        while (剩 % i == 0) {               /* ⚠ while 不是 if：同一个质因数可能有好几个 */
            if (结果.length() > 0) {
                结果.append("*");
            }
            结果.append(i);
            剩 = 剩 / i;
        }
    }
    if (剩 > 1) {                           /* ⚠ 剩下那个本身就是质数（质数输入全靠这一步） */
        if (结果.length() > 0) {
            结果.append("*");
        }
        结果.append(剩);
    }
    return 结果.toString();
}
""";

