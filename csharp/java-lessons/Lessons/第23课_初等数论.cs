//
// ══ 这一课要教什么 ══
// 「整除」是整数世界的基本关系，围绕它长出一整套最基本的算法：
//   · 数一个数有几个因数
//    · 判断一个数是不是质数
//    · 把一个数拆成质因数的乘积
//
// 三个算法共用同一个观察：**因数是一对一对出现的**。
// 如果 d 是 n 的因数，那 n/d 也是 —— 而且这两个里必有一个 ≤ √n。
// 于是「试到 √n 就够了」，不用试到 n。这是这一课真正要带走的东西。
//
// 另外这一课要练**边界**：1 是不是质数？（不是。）0 呢？负数呢？
// 这三个问题的答案不是背出来的，是从定义里推出来的。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**边界值**。质数判断是「能输出对但没学到东西」的重灾区：
//   只写 `for (int i = 2; i < n; i++) if (n % i == 0) return false;` 的写法
//   在 2、3、5 这些正数上全对，唯独把 **1 判成质数**（循环一次都不进，直接 return true）。
//   所以检查里 1 / 0 / -7 三个边界都喂，而且分开报错（指出是哪一种边界错了）。
// 第二条：**因数个数也要按 √n 那一套数** —— 用 `i <= n` 的写法在
//   360 这种数上是对的（只是慢），所以这条不靠"错"来抓，靠
//   **分解要真的分解**：质因数分解的输出必须能乘回原数（检查里拿 360 和 97 两个极端：
//   一个是合数要拆成 2*2*2*3*3*5，一个是质数只能输出自己）。
// 第三条：`是质数` 里出现 `i <= n` / `i < n` 这类"试到 n"的写法也不判错（结果对就行，
