// 第 34 课：二叉排序树 —— 会自己排好序的树
//
// ══ 这一课要教什么 ══
// 上一课的二叉树可以长成任何形状。加上一条规矩，它就变成一件有用的工具：
//
//     左子树里所有数 <  根 <  右子树里所有数
//
// 这就是**二叉排序树**（BST）。规矩一立，两件事立刻变得极快：
//   · **查找**：比根小就往左、比根大就往右 —— 每次砍掉一半，O(log n)
//   · **中序遍历**：出来的正好是**从小到大排好序**的（上一课埋的伏笔）
//
// 插入也是顺着这条规矩走：比根小就往左、比根大就往右，走到空位就放下去。
// 每个新结点都落在**叶子位置**，所以插入不会打乱已有结构。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**`最小值` 必须一路往左走**，不能遍历整棵树找最小。
//   为什么它值得当核心：BST 里"最小"有一个**结构性**的答案 ——
//   它一定在最左下角。用遍历找最小虽然结果对，但说明学生没把 BST 的规矩用起来。
//   防法（两层，都是实测过的）：
//     ① 文本：`最小值` 的方法体里必须出现 `.左`
//     ② **数据**：调用点先插入一棵**根不是最小**的树（20, 10, 30, 5, 15），
//        再 `最小值`。返回 5 才对 —— 返回 20（根）或者别的都不对。
//        ⚠ 更狠的一点：插入顺序改成递增（1,2,3,4,5）时，树退化成一条右链，
//        最小值就是根 —— 这时候"返回根"的写法会**碰巧对**。
//        所以两棵树都要喂：一棵根最小、一棵根不是最小。
// 核心检查点二：**`查找` 要走 BST 的规矩**（比大小决定往左还是往右），
//   不许"遍历所有结点找有没有这个值"。文本检查里要求出现 `.左` 和 `.右`。
// 核心检查点三：**`插入` 必须真的递归**（方法体里出现 `插入(`）——
//   学生很容易写"把所有值收进数组 → Arrays.sort → 重建树"，
//   那样树虽然"对"，但完全没学到 BST 的插入规矩。
//
// ⚠ 学生只写 `static class 结点` + 三个方法。

