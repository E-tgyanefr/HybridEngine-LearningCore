// 参考答案 —— 二叉排序树（只写一个类 + 三个方法）

static class 结点 {
    int 值;
    结点 左;
    结点 右;

    结点(int 值) {
        this.值 = 值;
    }
}

// 插入：比根小往左、比根大往右；走到空位就把新结点放在那儿
// ⚠ 新结点是靠 `根.左 = 插入(根.左, 值);` 这个**赋值**挂上去的
//   —— 忘了接住返回值，插入就会静默失败
static 结点 插入(结点 根, int 值) {
    if (根 == null) {
        return new 结点(值);              /* 找到空位了 */
    }
    if (值 < 根.值) {
        根.左 = 插入(根.左, 值);
    } else if (值 > 根.值) {
        根.右 = 插入(根.右, 值);
        /* 值相等时不插（这一课的规定）：BST 里一般不放重复的键 */
    }
    return 根;                            /* 把（可能变了的）子树根交还给上一层 */
}

// 查找：顺着大小关系**只往一边走** —— 一次比较扔掉一半的树
static boolean 查找(结点 根, int 值) {
    if (根 == null) {
        return false;                     /* 走到空位 ⇒ 树里没有这个值 */
    }
    if (值 == 根.值) {
        return true;
    }
    if (值 < 根.值) {
        return 查找(根.左, 值);            /* ⚠ 只往左边找 */
    }
    return 查找(根.右, 值);                /* ⚠ 只往右边找 */
}

// 最小值：一路往左走到底。这就是 BST 的规矩给的**结构性答案**
// （对称地，最大值就是一路往右）
static int 最小值(结点 根) {
    if (根 == null) {
        return -1;                        /* 空树，题目约定返回 -1 */
    }
    while (根.左 != null) {
        根 = 根.左;
    }
    return 根.值;
}
""";

