                "          return 查找(根.右, 值);\n" +
                "      一次比较就扔掉一半的树 —— 这就是 BST 查找快的原因。\n" +
                "      ⚠ 两边都递归（左找完右也找）结果也对，但那是遍历所有结点，O(n)。");

        return 比(run,
            ("找有根|", "true", "查找(甲, 20)　根"),
            ("找有左|", "true", "查找(甲, 10)"),
            ("找有右|", "true", "查找(甲, 30)"),
            ("找有深|", "true", "查找(甲, 5)　最左下角那个"),
            ("找有深二|", "true", "查找(甲, 15)"),
            ("找无小|", "false", "查找(甲, 2)　比最小还小"),
            ("找无大|", "false", "查找(甲, 99)　比最大还大"),
            ("找无中|", "false", "查找(甲, 17)　落在 15 和 20 之间，但树里没有"),
            ("找空|", "false", "查找(null, 5)　空树"),
            ("找单有|", "true", "查找(单个结点 42, 42)"),
            ("找单无|", "false", "查找(单个结点 42, 7)"),
            ("找负|", "true", "查找(丙, -7)"));
    }

    [Java检查说明("★ 插入真的递归（不是收进数组排序再重建）")]
    public static JavaCheckResult 检查_插入递归(string 代码)
    {
        string 净 = 去掉注释(代码);
        string 体 = 函数体(净, "插入");
        if (体 == null)
            return JavaCheckResult.不过("没找到 插入 的函数体 —— 先确认这个方法写全了（花括号配对）。");

        if (!体.Contains("插入("))
            return JavaCheckResult.不过(
                "插入 的函数体里**没有调用自己** —— 这一课要练的是 BST 的插入规矩。\n" +
                "          if (根 == null) return new 结点(值);\n" +
                "          if (值 < 根.值)      根.左 = 插入(根.左, 值);\n" +
                "          else if (值 > 根.值) 根.右 = 插入(根.右, 值);\n" +
                "          return 根;\n" +
                "      ⚠ 「把所有值收进数组 → Arrays.sort → 重建一棵树」也能让中序输出变有序，\n" +
                "        但那不是 BST 的插入 —— 规矩（比大小定方向）一点都没用到。");

        if (!体.Contains("new 结点"))
            return JavaCheckResult.不过(
                "插入 里没看到 `new 结点(...)` —— 碰到空位时要新建一个结点放下去：\n" +
                "          if (根 == null) { return new 结点(值); }");

        if (!体.Contains("return 根"))
            return JavaCheckResult.不过(
                "插入 里没看到 `return 根;`。\n" +
                "      递归往回走的时候，每一层都要把（可能变了的）子树根**交还给上一层** ——\n" +
                "      新结点就是靠 `根.左 = 插入(根.左, 值);` 这个赋值挂上去的。\n" +
                "      忘了返回/接住，新结点会被 new 出来但没人指着它，插入静默失败。");

        return JavaCheckResult.过("插入 是递归的，新结点也是 new 出来的");
    }

    [Java检查说明("插入真的插进去了（中序输出是递增的 = 这棵树确实是 BST）")]
    public static JavaCheckResult 检查_中序递增(string 代码)
    {
        var run = 跑一次(代码);
        string 停 = 先别急着比(run);
        if (停.Length > 0) return JavaCheckResult.不过(停);
        return 比(run,
            ("中序甲|", "5 10 15 20 30", "⚠ 甲 的中序遍历必须是**递增**的 —— 这正说明它是一棵合法的 BST"),
            ("中序乙|", "1 2 3 4 5", "乙（递增插入）的中序"),
            ("中序丙|", "-7 -3 0 4 9", "丙 的中序"),
            ("个数甲|", "5", "甲 里应当有 5 个结点（插入一个都没丢）"));
    }

