    public static string 参考答案 => """
// 参考答案 —— 二维数组
// 骨架已经 #include 了 <iostream>，所以这里直接用 std::cout。

// 1. 按行：外层走行、内层走列 —— 和内存顺序一致，最自然
void 打印每行(int 格[][4], int 行数) {
    for (int i = 0; i < 行数; i++) {
        for (int j = 0; j < 4; j++) {
            std::cout << 格[i][j] << ' ';
        }
        std::cout << '\n';          /* 一行打完换行 */
    }
}

// 2. 按列：外层走列、内层走行
//    ⚠ 变的只是循环的次序，方括号里**永远是 格[i][j]**
void 打印每列(int 格[][4], int 行数) {
    for (int j = 0; j < 4; j++) {
        for (int i = 0; i < 行数; i++) {
            std::cout << 格[i][j] << ' ';   /* 不是 格[j][i]！ */
        }
        std::cout << '\n';
    }
}

// 3. 主对角线：格[0][0]、格[1][1]、格[2][2] … 两个下标一起走
int 主对角线和(int 格[][4], int 行数, int 列数) {
    int 短边 = 行数 < 列数 ? 行数 : 列数;   /* 对角线的长度是行、列里小的那个 */
    int 和 = 0;
    for (int i = 0; i < 短边; i++) {
        和 += 格[i][i];
    }
    return 和;
}

// 4. 最大值：初值取左上角那一格，比写一个"很大的数"更稳
//    （-1 是哨兵值，不能当初值 —— 否则整张表都是 -1 时会返回一个不存在的数）
int 矩阵最大(int 格[][4], int 行数, int 列数) {
    int 最大 = 格[0][0];
    for (int i = 0; i < 行数; i++) {
        for (int j = 0; j < 列数; j++) {
            if (格[i][j] > 最大) {
                最大 = 格[i][j];
            }
        }
    }
    return 最大;
}
""";

