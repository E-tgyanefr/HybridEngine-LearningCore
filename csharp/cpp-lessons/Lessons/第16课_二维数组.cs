// 第 16 课：二维数组 —— 一张表格，行和列
//
// ══ 这一课要教什么 ══
// 前面几课的「一排格子」只能装一行数据。班级成绩、棋盘、地图、矩阵 —— 这些
// 都是**一张表格**，于是需要「格子排成行、每行又是一排格子」：二维数组。
//
// 这一课真正要建立的是**两层循环的方位感**：
//     for (i 走遍每一行)  for (j 走遍这一行的每一列)
// 以及那个**几乎人人都会写反**的地方：把「第 i 行第 j 列」写成 格[j][i]。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**按列遍历**（外层 j、内层 i，取 格[i][j]）。
// 为什么它是核心：按行遍历学生闭着眼都能写对（外层 i、内层 j，正好和内存顺序一致），
// 但按列遍历必须**故意把两个下标倒过来**，写成 格[j][i] 一样能编译、一样有输出，
// 只是数字全错 —— 这是本课最容易"看着对、其实全错"的地方。
// 第二条防线是**换一份数据再算一遍**（3×3 与 3×4 两份不同矩阵）：
// 把答案写死的、或者只对某一份数据凑出来的，第二份就露馅。
//
// ⚠ 给维护者：
//   · g++ 会把诊断信息里的中文标识符转义成 \U0000683c，
//     所以下面的报错识别只匹配 ASCII 片段（multidimensional array / bounds）。
//   · 所有输出都用「标记|值」的格式（照第 06/07 课），学生自己加打印也不会冲散对答案。

