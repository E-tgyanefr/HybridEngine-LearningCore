    // 一次检查会给每一课的所有检查方法各跑一次，而它们的输入是同一份代码 ——
    // 编译一次就够了（每次编译要起一次 g++，一两秒）。
    private static string 上次的代码;
    private static CppRun 上次的运行;

    private static CppRun 跑一次(string 代码)
    {
        if (上次的运行 != null && 上次的代码 == 代码) return 上次的运行;
        上次的代码 = 代码;
        上次的运行 = 编译并运行(代码, null, 调用点);
        return 上次的运行;
    }

    /// <summary>
    /// 编译并运行，**环境抽风时重试一次**。
    ///
    /// ⚠ 为什么需要它（实测踩到的）：运行器每次在一个全新的临时目录里编译，
    ///   而 `CppRunner.清理旧目录` 会把**别的进程**留下的 run* 目录删掉 ——
    ///   这台机器上同时有好几个助手在跑各自的课程检查，于是刚建出来的目录
    ///   会被别人的检查顺手删掉，g++ 报：
    ///       ld.exe: cannot open output file …prog.exe: No such file or directory
    ///       cc1plus.exe: fatal error: …main.cpp: No such file or directory
    ///   这是**环境**问题（而且常常只发生在一次检查的第一次编译上），不是学生
    ///   代码的问题。同一份代码重跑一次就好了 —— 不重试的话，学生看到的是
    ///   「编译没能通过」，会一头雾水地去改本来没错的代码。
    /// </summary>
    private static CppRun 编译并运行(string 代码, string 骨架, string 调用点)
    {
        // ⚠ 这里必须写 `CppCheck.编译并运行`（课程库的那个）。
        //   我加这层包装时把这一行也顺手替换掉了，于是它**调用自己** ——
        //   一跑就栈溢出、程序直接消失。教训：批量替换要看清自己改的是谁。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (run.编译通过) return run;
        if (!环境抽风(run)) return run;                 // 真的是学生的错，别重试
        System.Threading.Thread.Sleep(300);
        var 再来 = CppCheck.编译并运行(代码, 骨架, 调用点);
        return 再来.编译通过 ? 再来 : run;
    }

    private static bool 环境抽风(CppRun run) =>
        run.编译信息.Contains("No such file or directory") ||
        run.编译信息.Contains("cannot open output file");

    private static string 先别急着比(CppRun run)
    {
        if (run.Raw.CompileFailed)
        {
            if (run.编译信息.Contains("multidimensional array"))
                return
                    "二维数组当参数时**列数必须写出来**。g++ 的原话是：\n" +
                    "          error: declaration of '…' as multidimensional array\n" +
                    "                 must have bounds for all dimensions except the first\n" +
                    "      意思是：除第一维以外每一维的格数都要写。改成：\n" +
                    "          void 打印每行(int 格[][4], int 行数)      ← 4 是列数，不能省\n" +
                    "      为什么：格[i][j] 要靠「一行几格」才能算出第 i 行从哪儿开始。";
            return CppCheck.编译失败说明(run).Detail;
        }
        if (run.Raw.Error != null)
            return
                "程序没跑完就退出了：" + run.Raw.Error + "\n" +
                "      这一课最容易让程序崩的是**下标越界**：\n" +
                "          行下标只能取 0 ~ 行数-1，列下标只能取 0 ~ 3（这一课固定 4 列）。\n" +
                "      另外 主对角线和 只对**正方形**才走到 格[i][i]，长方形要取行、列里小的那个。";
        return null;
    }

    /// <summary>
    /// 比一批「标记|值」。
    ///
    /// ⚠⚠ 这里的取法**不看换行落在哪儿** —— 这是本课检查最关键的一处设计。
    ///   我第一版按「第几行」去对答案，结果被学生的换行位置坑了：
    ///   调用点把同一个打印函数连打几遍（`"行1|"; 打印每行(甲,3); "行2|"; …`），
    ///   而打印函数自己会在末尾换行 —— 于是 `行2|` 到底和上一行的 `6 6 6 6`
    ///   同处一行、还是另起一行，**取决于学生把换行打在哪一层循环里**。
    ///   两种写法都对，但按行取就只能认其中一种。
    ///
    ///   ⇒ 现在：标记**前后各出现一次**（`"行1|" … "行1|"`），
    ///     取两个标记中间的内容；比较前先把连续空白折成一个空格。
    ///     学生多打一个空格、少打一个空格、换行打在哪一层，都不影响判断。
    /// </summary>
    private static CheckResult 比一比(CppRun run, params (string 标记, int 第几段, string 期望, string 说明)[] 用例们)
    {
        var 错 = new List<string>();
        foreach (var (标记, 第几段, 期望, 说明) in 用例们)
        {
            string 得到 = 取一段(run, 标记, 第几段);
            if (得到 == null) 错.Add("      " + 说明 + "：程序没有给出这一段的输出");
            else if (!一样(得到, 期望))
                错.Add("      " + 说明 + "：得到 " + 显示(得到) + "，应该是 " + 显示(期望));
        }
        if (错.Count == 0) return CheckResult.过("这几组都对");

        return CheckResult.不过(
            "结果不对：\n" + string.Join("\n", 错) + "\n" +
            "      二维数组的两种走法：\n" +
            "          按行  外层 i（行）、内层 j（列），取 格[i][j]\n" +
            "          按列  外层 j（列）、内层 i（行），**还是**取 格[i][j]\n" +
            "      ⚠ 最容易错的就是把按列写成 格[j][i] —— 能编译、有输出，数字全错。\n" +
            "      对着上面那几组用例想一遍：你的第 1 列，取到的是哪几个格子？");
    }

    /// <summary>
    /// 取「标记|」之后、**下一个标记之前**的那一段内容。
    /// 「第几段」= 这个标记在输出里第几次出现（从 0 数）。
    ///
    /// ⚠ 右边界用的是「**任意**标记的下一次出现」：
    ///   打印类的那几组标记前后各写了一次（`"行1|" … "行1|"`），
    ///   而算出来的值只有一次（`"对角甲|" << …`）—— 两种都能一刀切在下一个标记上。
    ///   第一版我拿"自己的下一次出现"当右边界，只有重复写了标记的那几组能用。
    /// </summary>
    private static string 取一段(CppRun run, string 标记, int 第几段)
    {
        // ⚠ 折成一个字符串再找标记：换行在哪儿、有几处，都不影响标记的位置。
        string 全部 = string.Join(" ", run.行);
        var 本标记 = 找标记(全部, 标记);
        if (本标记.Count <= 第几段) return null;

        int 起 = 本标记[第几段] + 标记.Length;      // 标记自带末尾那条竖线，往后才是内容
        // ⚠ 右边界 = **严格大于 起** 的最近一个标记。
        //   少了"严格大于"这一条，会把**自己**（同一个标记、同一个位置）当成边界，
        //   于是取出一段空串 —— 这一处我改了两次。
        int 止 = 全部.Length;
        foreach (var 名 in 所有标记)
        {
            foreach (var p in 找标记(全部, 名))
            {
                if (p > 起 && p < 止) 止 = p;
            }
        }
        return 全部.Substring(起, 止 - 起).Trim();
    }

    /// <summary>这一课调用点里用到的全部标记。</summary>
    private static readonly string[] 所有标记 = {
        "行1|", "行2|", "行3|", "行小|",
        "列1|", "列2|", "列3|", "列4|", "列小|",
        "对角甲|", "对角乙|", "对角丙|", "对角单|",
        "最大甲|", "最大丙|", "最大负|", "最大一|",
    };

    /// <summary>找出 标记 在 全部 里每一次出现的位置（必须是开头或前面有空白）。</summary>
    private static List<int> 找标记(string 全部, string 标记)
    {
        var 位置 = new List<int>();
        for (int i = 全部.IndexOf(标记, System.StringComparison.Ordinal);
             i >= 0;
             i = 全部.IndexOf(标记, i + 1, System.StringComparison.Ordinal))
        {
            if (i == 0 || 全部[i - 1] == ' ' || 全部[i - 1] == '\t') 位置.Add(i);
        }
        return 位置;
    }

    /// <summary>把连续空白折成一个空格再比 —— 空格多一个少一个、换行打在哪儿，都不该影响对错。</summary>
    private static bool 一样(string 甲, string 乙) =>
        System.Text.RegularExpressions.Regex.Replace(甲.Trim(), @"\s+", " ") ==
        System.Text.RegularExpressions.Regex.Replace(乙.Trim(), @"\s+", " ");

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);

    /// <summary>编译信息里报的是"某个函数名不认识" —— 那是没写这个函数。</summary>
    private static bool 报的是没写函数(CppRun run, string 函数名)
    {
        string 信息 = run.编译信息;
        return 信息.Contains(函数名) &&
               (信息.Contains("was not declared") || 信息.Contains("not declared"));
    }

    /// <summary>去掉注释，免得注释里的字样骗过文本检查。</summary>
    private static string 去掉注释(string s)
    {
        var o = new System.Text.StringBuilder();
        bool 块 = false;
        for (int i = 0; i < s.Length; i++)
        {
            if (!块 && i + 1 < s.Length && s[i] == '/' && s[i + 1] == '/')
            { while (i < s.Length && s[i] != '\n') i++; o.Append('\n'); continue; }
            if (!块 && i + 1 < s.Length && s[i] == '/' && s[i + 1] == '*') { 块 = true; i++; continue; }
            if (块 && i + 1 < s.Length && s[i] == '*' && s[i + 1] == '/') { 块 = false; i++; continue; }
            if (!块) o.Append(s[i]);
        }
        return o.ToString();
    }

    /// <summary>取某个函数的「{ … }」内容（配对花括号）。找不到返回 null。</summary>
    private static string 函数体(string 净源码, string 函数名)
    {
        int 名 = 净源码.IndexOf(函数名 + "(", System.StringComparison.Ordinal);
        if (名 < 0) return null;
        int 起 = 净源码.IndexOf('{', 名);
        if (起 < 0) return null;
        int 深 = 0;
        for (int i = 起; i < 净源码.Length; i++)
        {
            if (净源码[i] == '{') 深++;
            else if (净源码[i] == '}')
            {
                深--;
                if (深 == 0) return 净源码.Substring(起 + 1, i - 起 - 1);
            }
        }
        return null;
    }

    private static bool 有循环(string 体) =>
        体.Contains("for") || 体.Contains("while") || 体.Contains("do ");
