    [检查说明("真的是两层的循环（不是把答案写死）")]
    public static CheckResult 检查_是两层循环(string 代码)
    {
        string 净 = 去掉注释(代码);
        string 行体 = 函数体(净, "打印每行");
        string 列体 = 函数体(净, "打印每列");
        if (行体 == null || 列体 == null)
            return CheckResult.不过("没能找到「打印每行」或「打印每列」的函数体 —— 先确认这两个函数写全了（有花括号）。");

        var 缺 = new List<string>();
        if (!有循环(行体)) 缺.Add("      打印每行：一个循环都没找到");
        if (!有循环(列体)) 缺.Add("      打印每列：一个循环都没找到");
        if (缺.Count == 0)
            return CheckResult.过("两个函数里都有循环 —— 表格是一格一格走出来的");

        return CheckResult.不过(
            "检查了去掉注释后的源码，发现问题：\n" + string.Join("\n", 缺) + "\n" +
            "      这一课要练的正是**两层循环的方位感**：\n" +
            "          按行  for (int i = 0; i < 行数; i++)\n" +
            "                    for (int j = 0; j < 列数; j++)  用 格[i][j]\n" +
            "          按列  for (int j = 0; j < 列数; j++)\n" +
            "                    for (int i = 0; i < 行数; i++)  还是 格[i][j]\n" +
            "      如果输出是几个写死的 std::cout 拼出来的，数字碰巧对也不算学会 ——\n" +
            "      换一张表格（检查里就换了）立刻就错了。");
    }

