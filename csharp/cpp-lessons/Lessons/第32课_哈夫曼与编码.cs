            "        ① 把所有频次放进一个「每次都能拿到最小的」容器（优先队列）\n" +
            "        ② 挑出**最小的两个**，合并成一个新结点（频次 = 两者之和）\n" +
            "        ③ 直到只剩一个结点，它的**深度**就是最长编码长度\n" +
            "      ⚠ 如果结果**偏大**，最常见的原因是「没有真的挑最小的两个」——\n" +
            "        比如按输入顺序拿前两个合并。那样树会长得很偏：\n" +
            "          频 {2,2,2,2}：正确是 2，按顺序合并会得到 3\n" +
            "          六种频次：正确是 3，按顺序合并会得到 5\n" +
            "      ⚠ {9}（只有一个字符）返回 1 —— 它也得占 1 位，不能是 0。\n" +
            "      ⚠ 空输入返回 0。");
    }

    [检查说明("空的和只有一个字符的频次要单独处理")]
    public static CheckResult 检查_边界(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 空 = 取值(run, "空");
        string 单 = 取值(run, "长5");

        var 错 = new List<string>();
        if (空 == null || 空 != "0")
            错.Add("      最长码长({}) 得到 " + 显示(空) + "，应当是 0（一个字符都没有）");
        if (单 == null || 单 != "1")
            错.Add("      最长码长({9}) 得到 " + 显示(单) + "，应当是 1（只有一种字符也得占 1 位）");

        if (错.Count == 0) return CheckResult.过("空输入返回 0、单个字符返回 1");

        return CheckResult.不过(
            "边界情况不对：\n" + string.Join("\n", 错) + "\n" +
            "      这两种情况都要在开头单独挡一下：\n" +
            "          if (频.empty()) return 0;          // 没有字符\n" +
            "          if (频.size() == 1) return 1;      // 只有一个字符\n" +
            "      ⚠ 第二种容易漏：只有一个字符时，循环 `while (堆.size() > 1)` 一次都不进，\n" +
            "        直接返回堆顶的深度 —— 那是 0，而正确答案是 1。\n" +
            "      ⚠ 第一种更要挡：空的时候 `堆.top()` 是在**空堆**上取，会直接崩。");
    }

    [检查说明("★ 核心：格雷码 —— 相邻两个必须只差一位")]
    public static CheckResult 检查_格雷码(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 格 = 取值(run, "格");
        const string 期望 = "01326754";

        if (格 == 期望)
            return CheckResult.过("前 8 个格雷码是 0,1,3,2,6,7,5,4 —— 和公式对得上");

        if (格 == "01234567")
            return CheckResult.不过(
                "「格雷码」返回的是 0,1,2,3,4,5,6,7 —— 那是**普通的二进制序号**，不是格雷码。\n" +
                "      自己看相邻两个：1 是 001、2 是 010，从 001 到 010 **变了两位**（低位和中位）。\n" +
                "      格雷码要求**每次只变一位**，正确的序列是：\n" +
                "          k :  0    1    2    3    4    5    6    7\n" +
                "          码: 000  001  011  010  110  111  101  100\n" +
                "      公式只有一行：\n" +
                "          格雷码(k) = k ^ (k >> 1)\n" +
                "      （`^` 是按位异或、`>>` 是右移。验一个：k=2 是 010，k>>1 是 001，\n" +
                "        异或得 011 —— 正是表里第 2 个。）\n" +
                "      为什么在意「只变一位」：实际电路里多位同时翻转，可能瞬间读到一个\n" +
                "      谁都认不出的中间值；每次只变一位就不会。");

        return CheckResult.不过(
            "格雷码不对：\n" +
            "      期望前 8 个是 " + 期望 + "（也就是 0,1,3,2,6,7,5,4）\n" +
            "      实际 " + 显示(格) + "\n" +
            "      公式：格雷码(k) = k ^ (k >> 1)\n" +
            "      3 位格雷码表：\n" +
            "          k :  0    1    2    3    4    5    6    7\n" +
            "          码: 000  001  011  010  110  111  101  100\n" +
            "      自己核一遍相邻两项的异或结果，应当**只有一位是 1**。");
    }

    [检查说明("★ 核心：这个位数的格雷码序列真的相邻只差一位")]
    public static CheckResult 检查_相邻差一位(string 代码)
    {
        // 验证性的一问：格雷码的**定义性质**就是"相邻只差一位"。
        // 学生如果随便编一张表、或者公式写错，这一问会给出 0。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 位 = 取值(run, "位");
        if (位 == "11111")
            return CheckResult.过("1/2/3/4/6 位的格雷码序列都满足「相邻只差一位」");

        return CheckResult.不过(
            "「格雷相邻差一位」的结果不对：\n" +
            "      期望 11111（1、2、3、4、6 位都应当是 1）\n" +
            "      实际 " + 显示(位) + "\n" +
            "      这一问是在**验证格雷码的定义性质**：一整个序列里，\n" +
            "      每相邻两个二进制表示**恰好只有一位不同**。\n" +
            "      判法：把相邻两个异或起来，结果里应当**只有一位是 1**。\n" +
            "          int 差 = 格雷码(i) ^ 格雷码(i - 1);\n" +
            "          if ((差 & (差 - 1)) != 0) return 0;   // 不止一位 ⇒ 不合格\n" +
            "      为什么 `(差 & (差 - 1)) == 0` 能判「只有一位是 1」：\n" +
            "        例如 差 = 00100（只有一位）⇒ 差-1 = 00011 ⇒ 与起来是 0 ✓\n" +
            "            差 = 00110（两位）  ⇒ 差-1 = 00101 ⇒ 与起来是 00100 ≠ 0 ✗\n" +
            "      ⚠ 如果这里直接 `return 1;` 蒙过去，上面那条检查_格雷码 还是会\n" +
            "        抓住你的 格雷码 函数 —— 两问合起来才完整。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
}
