// 第 32 课参考答案：哈夫曼最长码长 + 格雷码

int 最长码长(std::vector<int> 频) {
    if (频.empty()) return 0;
    if (频.size() == 1) return 1;          // 只有一个字符，也得给 1 位

    // ⚠ 优先队列：小的排在最前面（默认是大的在前，所以要加 std::greater）
    std::priority_queue<std::pair<int, int>,
                        std::vector<std::pair<int, int>>,
                        std::greater<std::pair<int, int>>> 堆;

    for (int f : 频) 堆.push({f, 0});      // {频次, 深度}

    while (堆.size() > 1) {
        // 每次挑**最小的两个**——这是哈夫曼的关键，随便拿两个就错了
        auto [频1, 深1] = 堆.top(); 堆.pop();
        auto [频2, 深2] = 堆.top(); 堆.pop();
        // 新结点比两个孩子各深一层，所以落在它里面的路都加 1
        堆.push({频1 + 频2, std::max(深1, 深2) + 1});
    }
    return 堆.top().second;                // 树根的深度 = 最长编码长度
}

int 格雷码(int k) {
    return k ^ (k >> 1);                   // 一行公式
}

int 格雷相邻差一位(int 位数) {
    int 个数 = 1 << 位数;                  // 2 的 位数 次方
    for (int i = 1; i < 个数; i++) {
        int 差 = 格雷码(i) ^ 格雷码(i - 1);
        if ((差 & (差 - 1)) != 0) return 0;    // 差里不止一位 ⇒ 不是只差一位
    }
    return 1;
}
""";

