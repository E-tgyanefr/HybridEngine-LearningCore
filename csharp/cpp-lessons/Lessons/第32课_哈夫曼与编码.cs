// ══ 这一课要教什么 ══
// 哈夫曼编码解决的是「怎么给字符分配长短不一的 01 串，让总长度最短」：
// **出现得多的字符给短码，出现得少的给长码**。做法是每次挑两个**最小频次**
// 合并成一棵新树，直到只剩一棵 —— 这就是贪心。
//
// 学生必须真的用「取最小的两个」这一步。不取最小、随便拿前两个合并，
// 树会变得很偏，最长码长明显变大（实测：频 {2,2,2,2} 正确是 2，随便合并是 3；
// 六种频次里错三种）。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：检查_最长码长 —— 六组频次，其中三组（{2,2,2,2}、六种频次、
//   {9}）能把"不取最小"的解法区分出来。数组顺序也特意不都是升序/降序，
//   堵死「照输入顺序合并」这条路。
// 核心检查点二：检查_格雷码相邻差一位 —— 这是**验证性**的一问：
//   格雷码的定义性质就是"相邻两个只差一位"。学生如果直接 return k（二进制
//   序号）或者随便编一张表，这一问会给出 0。
