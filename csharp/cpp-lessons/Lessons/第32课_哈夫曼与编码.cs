            ("长2", "{1,1,2,3,5}",          "4"),
            ("长3", "{2,2,2,2}",            "2"),
            ("长4", "{7,8,9,10,11,12}",     "3"),
            ("长5", "{9}",                  "1"),
            ("长6", "{1,2}",                "1"),
        };

