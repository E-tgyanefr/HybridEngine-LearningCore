// ─────────────────────────────────────────────────────
//  先介绍：为什么要"变长"
// ─────────────────────────────────────────────────────
//
// 想存一段文字，每个字符用几位二进制？
//
// 定长：字母表 8 个字符 ⇒ 每个 3 位（000, 001, …, 111）。不管出现几次都 3 位。
//
// 但如果 'a' 出现了 1000 次、'h' 只出现 3 次呢？给两者都留 3 位太浪费了。
//
// 变长：**常用的短一点，少用的长一点**。假设一段文字里字符出现次数是：
//
//     a:5   b:2   c:2   d:1   e:1   f:3
//
// 定长要 3 位 × 14 个字符 = 42 位。
// 哈夫曼给出的编码（下面会算）是：
//
//     f:00   a:01   d:100   e:101   b:110   c:111
//
// 总长 = 5×2 + 3×2 + 2×3 + 2×3 + 1×3 + 1×3 = 10+6+6+6+3+3 = **34 位**
// ⇒ 比定长的 42 位省了 8 位（约 19%）。文字越长省得越多。
//
// ⚠ 变长编码有个必须解决的问题：**怎么知道该在哪里断**？
//   比如 `01` 和 `010` 都是合法前缀，读到一个 0 之后不知道要继续读还是停。
//   哈夫曼编码的保证是「**没有哪个编码是另一个的前缀**」（这叫前缀码）——
//   一读到某个完整编码就立刻能断。这个性质不是碰巧来的，下面会说清为什么。
//
// ─────────────────────────────────────────────────────
//  一、哈夫曼树怎么建：每次合并最小的两个
// ─────────────────────────────────────────────────────
//
// 把每个字符看成一个只有频次的叶子结点，重复做这件事：
//
//     从所有还没合并的结点里**挑出频次最小的两个**，
//     把它们合成一个新结点（频次 = 两者之和）。
//
// 直到只剩一个结点 —— 它就是树根。
//
// 拿 a:5 b:3 c:2 d:2 e:1 f:1 走一遍（按频次从小到大）：
//
//     一开始：{5, 3, 2, 2, 1, 1}
//     挑 1,1 → 合并成 2     现在 {5, 3, 2, 2, 2}
//     挑 2,2 → 合并成 4     现在 {5, 3, 4, 2}      （挑两个 2，随便哪两个都行）
//     挑 2,3 → 合并成 5     现在 {5, 4, 5}
//     挑 4,5 → 合并成 9     现在 {5, 9}
//     挑 5,9 → 合并成 14    只剩一个 ⇒ 树根是 14
//
// 建出来的树（左边走 0，右边走 1）：
//
//                        14
//                      /    \
//                     5      9
//                    / \    / \
//                   f   a  4   5
//                          / \  / \
//                         d  e b   c
//                        (2)(1)(3)(2)   ← 这层的数字只是示意，别死记
//
// 从根走到每个叶子的路径就是它的编码：**左 0 右 1**。
// 频率越低 ⇒ 被合并得越早 ⇒ 埋在越深 ⇒ 码越长。这正是我们想要的。
//
// ⚠ 「前缀码」是**自动成立**的：每个字符都在**叶子上**（不在中间结点上），
//   所以没有任何一个编码是别人的前半段。
//
// ─────────────────────────────────────────────────────
//  二、代码怎么写：优先队列（每次都能 O(log n) 拿到最小的）
// ─────────────────────────────────────────────────────
//
// 「每次都拿最小的两个」如果每次都去扫描一遍数组，要 O(n)；
// 用**优先队列**（priority_queue，底层是二叉堆）只要 O(log n)：
//
//     #include <queue>
//
//     std::priority_queue<std::pair<int, int>,
//                         std::vector<std::pair<int, int>>,
//                         std::greater<std::pair<int, int>>> 堆;
//
// 这一长串的意思是「**小的排在最前面**的堆」（默认是大的在前，
// 加 `std::greater` 才是小的在前）。push / top / pop 三个操作：
//
//     堆.push({频次, 深度});
//     堆.top()     → 最小的那个（**只读不清**）
//     堆.pop()     → 扔掉最小的那个（**不返回东西**）
//
// 整个算法只有十几行：
//
//     for (每个字符) 堆.push({它的频次, 0});
//     while (堆.size() > 1) {
//         取出最小的两个（频1,深1）和（频2,深2）；
//         堆.push({频1 + 频2, max(深1, 深2) + 1});
//     }
//     堆.top() 的深度就是**最长码长**
//
// ⚠ 为什么用 `max(深)+1`：新结点比它的两个孩子各深一层，所以
//   落在它里面最深的那条路又长了一层。树根那个结点的深度就是最大深度 ——
//   也就是最长编码的长度（边数 = 编码位数）。
//
// ─────────────────────────────────────────────────────
//  三、复杂度：把数字算出来
// ─────────────────────────────────────────────────────
//
//     字符种类数 n     扫描数组的做法        优先队列的做法
//          8           8×8   ≈ 64 步         8×3   ≈ 24 步
//         26          26×26 ≈ 676 步        26×5  ≈ 130 步
//        256        256×256 = 65,536 步    256×8  = 2,048 步
//       1000       1000×1000 = 100 万步     1000×10 = 1 万步
//
// ⇒ 1000 个字符种类时，优先队列大约只要 1 万步，扫描数组要 100 万步。
//   差距就是 O(n²) 和 O(n log n)。
//   （字符集最大也就几万个「种类」，两种都能跑，但习惯要一开始就养对。）
//
// ─────────────────────────────────────────────────────
//  四、格雷编码：相邻两个只差一位
// ─────────────────────────────────────────────────────
//
// 格雷码是另一种编码。它的定义性质只有一条：
//
//     **相邻两个编码，二进制下恰好只有一位不同。**
//
// 3 位格雷码：
//
//     编号 k :  0    1    2    3    4    5    6    7
//     格雷码 : 000  001  011  010  110  111  101  100
//               ↑    ↑    ↑    ↑    ↑    ↑    ↑    ↑
