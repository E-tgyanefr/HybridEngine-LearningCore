    public static string 模板 => """
// 第 10 课：作用域与生命周期 —— 变量从哪儿来、什么时候死
//
// 先介绍：两个经常被混在一起的问题
//
//     **作用域**（scope）    —— 这个名字在**哪几行代码**里能用？
//     **生命周期**（lifetime）—— 这个变量在**什么时候**存在？
//
//  它们相关，但不是一回事。这一课的两个例子正好把它俩分开：
//
//     · 局部变量：作用域是那个 `{}`，生命周期也是那个 `{}`
//     · static 局部变量：作用域**还是**那个 `{}`，但生命周期是**整个程序**
//
// ─────────────────────────────────────────────────────
//  一、作用域：花括号就是边界
// ─────────────────────────────────────────────────────
//
//     #include <iostream>
//
//     int 数 = 100;                    // ← 全局：这个文件里到处都能用
//
//     int main() {
//         std::cout << 数 << "\n";     // 100
//         int 数 = 5;                  // ← 局部：**遮蔽**了全局那个
//         std::cout << 数 << "\n";     // 5    ← 现在这个名字指局部的
//         {
//             int 数 = 7;              // ← 再遮蔽一层
//             std::cout << 数 << "\n"; // 7
//         }
//         std::cout << 数 << "\n";     // 5    ← 内层那个已经死了
//     }
//
// ⚠⚠ **名字遮蔽（shadowing）是 C++ 里一个安静的坑**：
//   编译器**不会警告**（除非开了特定选项），
//   于是你以为在改全局那个，其实改的是局部那个。
//
//   典型症状："我在函数里把它改了，出来怎么没变？"
//   ⇒ 先看一眼**函数里是不是重新声明了一个同名的变量**。
//
// ⚠ 再强调一次第 11 课会正式讲的事：
//   C++ 的参数是**按值传递** —— 函数里的形参是**另一个**变量，
//   改它不会影响调用方。这和"遮蔽"是两种不同的"改了没生效"。
//
// ─────────────────────────────────────────────────────
//  二、生命周期：`{}` 一结束，局部变量就死了
// ─────────────────────────────────────────────────────
//
//     int* 造一个() {
//         int 数 = 42;
//         return &数;          // ⚠⚠ 返回局部变量的地址
//     }
//
//  函数一返回，`数` 待的那块内存就被回收了。
//  你拿到的地址**还在**，但它指向的东西已经没了 —— 这叫**悬垂指针**。
//  用它读出来的值是**随机的**，写进去可能破坏别的数据。
//
//  ⚠⚠ 这是 C++ 里最难查的一类 bug：**它常常"看起来是对的"**。
//    程序可能正常跑完、输出也对，只是偶尔崩在别的地方。
//    （这门课不会让你写这种代码，但你必须认识它。）
//
// ─────────────────────────────────────────────────────
//  三、`static` 局部变量：作用域不变，但活得更久
// ─────────────────────────────────────────────────────
//
//     int 计数器() {
//         static int 次数 = 0;      // ← 注意这个 static
//         次数++;
//         return 次数;
//     }
//
//  普通局部变量每次调用都**重新出生**（值回到初值）。
//  加了 `static` 之后：
//
//     · **只初始化一次**（整个程序运行期间就那一次）
//     · 函数返回之后它**不消失**，下次调用还是上次那个值
//     · 但**名字还是只有函数里能看见**（作用域没变）
//
//     计数器()  → 1
//     计数器()  → 2      ← 记住上一次了
//     计数器()  → 3
//
// ⚠ 和全局变量比：`static` 局部变量**不会污染全局名字空间** ——
//   别的文件、别的函数看不到它。这是它比全局变量好的地方。
//
// ⚠ 和全局变量共有的坑：**它让函数有了"记忆"**，
//   于是同一个函数调两次结果不一样 —— 测起来、读起来都更麻烦。
//   真实项目里它常用于：调用计数、只初始化一次的资源、随机数种子。
//   但**能不用就不用**，因为它是一种隐藏状态。
//
// ─────────────────────────────────────────────────────
//  轮到你了 —— 在下面写
// ─────────────────────────────────────────────────────
//   ① int 影子()
//      在函数**里面**声明一个叫 `数` 的局部变量并赋值为 5，返回它。
//      （文件顶部已经有一个全局 `数 = 100`，你会亲眼看到名字被遮蔽。）
//
//   ② int 计数器()
//      用一个 `static int` 局部变量，每调一次加一，返回当前值。
//      第一次返回 1，第二次返回 2，依此类推。
//
// 提示：不用写 main。

// ── 在下面写你的两个函数 ──

""";

    public static string 参考答案 => """
/* ⚠ 全局变量：文件里到处都能用（这一课用它演示"遮蔽"） */
int 数 = 100;

int 影子() {
    /* ⚠ 这里**重新声明**了一个同名的 数 —— 它遮蔽了全局那个。
       函数里所有 `数` 指的都是这一个（值是 5）。
       全局那个 100 **一点没变**。 */
    int 数 = 5;
    return 数;
}

int 计数器() {
    /* ⚠ static 的两层意思：
         ① 只初始化一次（不是每次调用都变回 0）
         ② 函数返回之后它**不消失**
       但它的名字仍然只有这个函数里能看见 —— 作用域没变。 */
    static int 次数 = 0;
    次数++;
    return 次数;
}
""";


