/* ⚠ 全局变量：文件里到处都能用（这一课用它演示"遮蔽"） */
int 数 = 100;

int 影子() {
    /* ⚠ 这里**重新声明**了一个同名的 数 —— 它遮蔽了全局那个。
       函数里所有 `数` 指的都是这一个（值是 5）。
       全局那个 100 **一点没变**。 */
    int 数 = 5;
    return 数;
}

int 计数器() {
    /* ⚠ static 的两层意思：
         ① 只初始化一次（不是每次调用都变回 0）
         ② 函数返回之后它**不消失**
       但它的名字仍然只有这个函数里能看见 —— 作用域没变。 */
    static int 次数 = 0;
    次数++;
    return 次数;
}
""";


