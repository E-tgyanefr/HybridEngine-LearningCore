// ══ 这一课要教什么 ══
// 三个数论里的基本动作，竞赛和 GESP 五级都绕不开：
//     ① 数因数有几个      ② 判断一个数是不是质数      ③ 把它拆成质因数
//
// 这一课的核心不是"会写"，而是**知道只需要试到 √n**：
//   如果 n 有一个大于 √n 的因数，那它一定配着一个小于 √n 的因数 ——
//   所以大于 √n 的那些根本不用试。
//   本机实测：判 999999937（大质数）试到 √n 是 **0 毫秒**，一个个试到 n 是 **2527 毫秒**。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**`是质数` 必须试到 √n 为止**。
//   朴素写法（`for (i = 2; i < n; i++)`）在 n 接近 10^9 时是 2.5 秒起，
//   而且调用点里喂了两个大质数 ⇒ 60 秒超时。超时的提示里直接讲清楚为什么 √n 就够。
//   同时配一条**文本兜底**：函数体里出现 `i < n` / `i <= n` 这种"试到 n 为止"的条件就提醒
//   （因为等超时要等 60 秒，太慢）。
// 核心检查点二：**防写死**。`是质数` 喂了 999983、999999937、1000003 三个大质数
//   和它们的合数邻居；`质因数乘积` 要求把质因数乘起来 —— 写死一个 return 过不了。
//
// ⚠ 给维护者：`sqrt` 不要用 —— 浮点开方有精度风险，教 `i * i <= n` 或 `i <= n / i`。

