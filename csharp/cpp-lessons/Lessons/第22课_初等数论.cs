    [检查说明("★ 是质数不许一个个试到 n（试到 √n 就够）")]
    public static CheckResult 检查_试到根号n(string 代码)
    {
        // ⚠ 文本兜底：等超时要等 60 秒，太慢。这里直接看循环条件。
        //   判据故意宽松：只要**没有**"试到 n 为止"的形状就算过。
        string 净 = 去掉注释(代码);
        string 体 = 函数体(净, "是质数");
        if (体 == null)
            return CheckResult.不过("找不到「是质数」的函数体 —— 花括号配对了吗？");

        // ⚠ 判据要挑**只可能出现在"试到 n"那种写法里**的形状：`i < n` / `i <= n`。
        //   第一版我只写了 `< n;` 和 `< n)`，于是**参考实现里的 `i * i <= 剩余` 里
        //   那个 `<= 剩余` 不匹配、可 `n % i` 那一行也不是 for** —— 可它还是误报了：
        //   因为 `for (int i = 2; (long long)i * i <= n; i++)` 里有 `<= n;`。
        //   ⇒ 先排除掉带 `* i` / `/ i`（那是在跟平方根比），再判。
        var 坏 = new List<string>();
        foreach (var 行 in 体.Split('\n'))
        {
            string s = 行.Trim();
            if (!s.StartsWith("for") && !s.StartsWith("while")) continue;
            if (s.Contains("* i") || s.Contains("i *") || s.Contains("/ i") || s.Contains("i /")) continue;
            if (s.Contains("< n;") || s.Contains("<= n;") || s.Contains("< n)") || s.Contains("<= n)"))
                坏.Add("      " + s);
        }
        if (坏.Count == 0)
            return CheckResult.过("循环上界不是 n —— 是试到 √n 的写法");

        return CheckResult.不过(
            "「是质数」里的循环是**试到 n 为止**的：\n" + string.Join("\n", 坏) + "\n" +
            "      这一课最该记住的一句话：**试到 √n 就够了**。\n" +
            "      为什么：如果 n 有个因数 d 大于 √n，那 n/d 一定**小于** √n，\n" +
            "        而 n/d 也是 n 的因数 —— 它在前面那一趟里已经被试过了。\n" +
            "        ⇒ 大于 √n 的因数不可能单独出现，不用试。\n" +
            "      本机实测（判 999999937 这个大质数）：\n" +
            "          试到 √n        0 毫秒\n" +
            "          试到 n         2527 毫秒        ← 慢了几万倍\n" +
            "      改成：\n" +
            "          for (int i = 2; (long long)i * i <= n; i++)\n" +
            "      ⚠ 别用 sqrt(n) —— 它返回浮点数，大数时会算不准；\n" +
            "        `i * i <= n` 全程整数，不会错（记得转 long long，免得 i*i 溢出）。");
    }

