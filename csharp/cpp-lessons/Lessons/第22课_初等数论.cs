    public static string 参考答案 => """
// 参考答案 —— 初等数论

// 1. 因数个数：成对地找 —— 试到 √n，每找到一个就记两个
//    ⚠ 完全平方数（比如 36 = 6×6）的那个 √n 只能算一个
int 因数个数(int n) {
    int 个数 = 0;
    for (int i = 1; (long long)i * i <= n; i++) {     /* ⚠ 转 long long，免得 i*i 溢出 */
        if (n % i == 0) {
            个数 += (i * i == n) ? 1 : 2;
        }
    }
    return 个数;
}

// 2. 是质数：1 和小于 1 的都不是；然后试到 √n
bool 是质数(int n) {
    if (n < 2) {
        return false;
    }
    for (int i = 2; (long long)i * i <= n; i++) {
        if (n % i == 0) {
            return false;
        }
    }
    return true;
}

// 3. 质因数个数（按重数）：从最小的质数开始反复除
//    12 → 除 2 两次剩 3 → 除 3 一次剩 1 ⇒ 一共 3 个
int 质因数个数(int n) {
    int 个数 = 0;
    int 剩 = n;
    for (int i = 2; (long long)i * i <= 剩; i++) {
        while (剩 % i == 0) {
            个数++;
            剩 /= i;
        }
    }
    if (剩 > 1) {          /* ⚠ 剩下的这个自己就是质数（比如 2×999999937 里的那个大的） */
        个数++;
    }
    return 个数;
}

// 4. 最大质因数：分解过程中记下最后一个除掉的质数
int 最大质因数(int n) {
    if (n < 2) {
        return 1;          /* 题目约定：n = 1 时返回 1 */
    }
    int 最大 = 1;
    int 剩 = n;
    for (int i = 2; (long long)i * i <= 剩; i++) {
        while (剩 % i == 0) {
            最大 = i;
            剩 /= i;
        }
    }
    if (剩 > 1) {          /* 剩下的这个大质数才是最大的那个 */
        最大 = 剩;
    }
    return 最大;
}
""";

