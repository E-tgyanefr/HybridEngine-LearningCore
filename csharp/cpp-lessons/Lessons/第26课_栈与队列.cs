// 第 26 课：栈与队列 —— 后进先出和先进先出
//
// ══ 这一课要教什么 ══
// 栈和队列是两种**限制存取的容器**：栈只能从一头进出（后进先出 LIFO），
// 队列一头进另一头出（先进先出 FIFO）。学生要会用 std::stack / std::queue，
// 也要知道它们用数组怎么手写出来（因为 CCF GESP 六级的题常常不给你 STL）。
//
// 真正要建立的直觉是：**「括号匹配合不合法」和「嵌套有多深」是两个问题**。
//   合不合法 → 看栈最后空不空
//   嵌套多深 → 看栈**曾经**到过多高
// 这正是「能输出对但没学到东西」的解法最容易露馅的地方。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：检查_最大深度。题目只给「配对是否合法」的话，
// 学生写个左右括号计数器（甚至 if (s == "(())") return 0;）就能过；
// 一旦要求同时给出**最大嵌套深度**，计数器就死了，必须真的维护一个栈。
// 三组反面解法都验过（见文件末尾的「反面测试」注释）：
//   ① 写死答案         → 深度错（(()()) 会给出 0）
//   ② 只数左右括号个数  → ")(" 判成合法（它数出来左右都是 1）
//   ③ 深度写死 2        → "((((" 应当是 4
// ⚠ 「必须真的用栈」那一条是文本检查，故意放宽到「std::stack 或 自己写的 push/pop」——
//   手写数组栈也算学会（题目允许），但纯计数器过不了。

