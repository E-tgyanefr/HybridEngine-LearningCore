    [检查说明("★ 核心：括号是否配对（含 )( 这种顺序错的）")]
    public static CheckResult 检查_是否配对(string 代码)
    {
        // ⚠ 这一条专抓「只数左右括号个数」的解法：
        //   它会把 ) ( 判成合法（左右各一个），但顺序其实是错的。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 用例 = new (string 标记, string 括号, string 期望)[]
        {
            ("ok",      "(())",   "0"),
            ("bad",     "(()",    "1"),
            ("empty",   "",       "0"),
            ("deep",    "((()))", "0"),
            ("cross",   ")(",     "1"),
            ("mix",     "()()",   "0"),
            ("more",    "(()())", "0"),
            ("extra",   "())",    "1"),
            ("onlyOpen","((((",   "1"),
        };

        var 错 = new List<string>();
        foreach (var (标记, 括号, 期望) in 用例)
        {
            string 得到 = 取值(run, 标记);
            if (得到 == null || 得到.Length < 1)
