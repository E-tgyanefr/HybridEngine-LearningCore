    [检查说明("★ 核心：最大嵌套深度（深度写死 2 会被抓住）")]
    public static CheckResult 检查_最大深度(string 代码)
    {
        // ⚠ 这一条是本课的第二道闸门：光判"配不配"太容易蒙，
        //   加上"最深到过几层"就必须维护一个真的栈。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 用例 = new (string 标记, string 括号, string 期望)[]
        {
            ("ok",      "(())",   "2"),
            ("bad",     "(()",    "2"),
            ("empty",   "",       "0"),
            ("deep",    "((()))", "3"),
            ("cross",   ")(",     "1"),
            ("mix",     "()()",   "1"),
            ("more",    "(()())", "2"),
            ("extra",   "())",    "1"),
            ("onlyOpen","((((",   "4"),
        };

        var 错 = new List<string>();
        foreach (var (标记, 括号, 期望) in 用例)
        {
            string 得到 = 取值(run, 标记);
            if (得到 == null || 得到.Length < 2)
            {
                错.Add("      " + 括号 + "：程序没有给出第 2 个元素（可能中途崩了）");
                continue;
            }
            string 实际 = 得到.Substring(1);
            if (实际 != 期望)
                错.Add("      处理括号(\"" + 括号 + "\") 的最大深度是 " + 显示(实际) +
                       "，应该是 " + 期望);
        }

        if (错.Count == 0)
            return CheckResult.过("9 组的最大嵌套深度都对（((( 是 4 层，()() 只有 1 层）");

        return CheckResult.不过(
            "最大嵌套深度有错：\n" + string.Join("\n", 错) + "\n" +
            "      深度记的是**扫描过程中栈到过的最高层数**，不是最后剩下的层数：\n" +
            "          ( ( ) )       到过 2 层（第二次 push 之后）\n" +
            "          ( ) ( )       到过 1 层（每次 push 完马上就被 pop 掉了）\n" +
            "          ( ( ( (       到过 4 层（一直没关上）\n" +
            "      ⇒ 每次 push 完，拿**当前**栈的大小跟记录比一比：\n" +
            "          if ((int)栈.size() > 最大深度) { 最大深度 = (int)栈.size(); }\n" +
            "      ⚠ 顺序很重要：必须在 push **之后**比。\n" +
            "        写成 push 之前比，`(())` 会算成 1（少一层）。");
    }

    [检查说明("空串要返回 {0, 0}，不能崩、不能返回错个数")]
    public static CheckResult 检查_空串(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 得到 = 取值(run, "empty");
        if (得到 == null)
            return CheckResult.不过(
                "处理括号(\"\") 没有给出结果 —— 程序可能崩了。\n" +
                "      空串是**必须处理**的一种输入：一个括号都没有，等于配对成功、深度 0。\n" +
                "      检查你循环里有没有在空栈上 top() / pop()。");
        if (得到 == "00")
            return CheckResult.过("空串给出 {0, 0}：配对成功、深度 0");

        return CheckResult.不过(
            "处理括号(\"\") 给的是 " + 显示(得到) + "，应该是 00（即 {0, 0}）。\n" +
            "      空串里一个括号都没有：没有任何括号没关上 ⇒ 配对成功（0）；\n" +
            "      一个 '(' 都没见过 ⇒ 最大深度 0。\n" +
            "      如果你返回的是 1，多半是把「栈是空的」当成了失败信号 ——\n" +
            "      空栈只在**碰到 ')' 的时候**才是失败。");
    }

    [检查说明("真的用了栈（std::stack，或自己写的 push/pop）")]
    public static CheckResult 检查_用了栈(string 代码)
    {
        // 文本检查。故意放宽：手写数组栈也算（题目允许），
        // 但"只数左右括号个数"那种写法一个 push 都没有。
        if (代码.Contains("std::stack") || 代码.Contains("stack<"))
            return CheckResult.过("用了 std::stack");

        if (System.Text.RegularExpressions.Regex.IsMatch(代码, @"\bpush\b") &&
            System.Text.RegularExpressions.Regex.IsMatch(代码, @"\bpop\b"))
            return CheckResult.过("自己实现了 push / pop —— 手写栈也算");

        return CheckResult.不过(
            "代码里没看到栈的痕迹（既没有 std::stack，也没有 push / pop）。\n" +
            "      括号匹配之所以必须用栈，是因为它要回答的问题是：\n" +
            "          **这个 ')' 该抵消哪一个 '('？**\n" +
            "      答案永远是「最近那个还没被抵消的 '('」—— 这正是栈顶。\n" +
            "      「最近」这两个字就是栈存在的全部理由：队列给你的是最早那个，\n" +
            "      数组给你的是任意一个，都不对。\n" +
            "      两种都行：\n" +
            "          std::stack<char> 栈;   栈.push(c);   栈.top();   栈.pop();\n" +
            "          —— 或者用数组：int 数据[100]; int 顶 = 0;  数据[顶++] = c; 顶--;");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
