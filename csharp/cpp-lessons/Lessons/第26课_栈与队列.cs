        return CheckResult.不过(
            "配对判断有错：\n" + string.Join("\n", 错) + "\n" +
            "      最容易漏掉的是「顺序」这一类：\n" +
            "          ) (     左右括号个数一样多，但**顺序是错的** —— 不合法\n" +
            "          ( ) )   多了一个右括号 —— 不合法\n" +
            "      判据只有一条：**每个 ')' 都要抵消掉一个还没关上的 '('**。\n" +
