//     队.push(1);        从**队尾**进      ⇒ 队里 {1}
//     队.push(2);        ⇒ {1, 2}
//     队.front()         看**队头**        ⇒ 1
//     队.pop()           从**队头**拿走    ⇒ {2}
//     队.back()          看队尾            ⇒ 2
//     队.empty()         空不空
//
// ⚠ queue 的 pop() 也是 void，而且它拿掉的是 front 不是 back。
//
