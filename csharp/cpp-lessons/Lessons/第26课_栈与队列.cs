    public static string 参考答案 => """
// 第 26 课参考答案：括号匹配 + 最大嵌套深度
std::vector<int> 处理括号(std::string s) {
    std::stack<char> 栈;      // 存那些"还没关上"的 '('
    int 配不上 = 0;           // 一旦发现不合法就置 1，**不清零**
    int 最大深度 = 0;         // 扫描过程中，栈到过的最高层数

    for (char c : s) {
        if (c == '(') {
            栈.push(c);
            // ⚠ 深度要在 push **之后**比 —— 比完栈就浅下去了，回不来
            if ((int)栈.size() > 最大深度) {
                最大深度 = (int)栈.size();
            }
        } else if (c == ')') {
            if (栈.empty()) {
                // 这个 ')' 没有对应的 '(' —— 就像 )( 的第一个字符
                配不上 = 1;
            } else {
                栈.pop();     // 关掉一个还没关的
            }
        }
    }
    if (!栈.empty()) {
        配不上 = 1;           // 还有没关上的，比如 ((
    }
    return {配不上, 最大深度};
}
""";

