//                  栈不空 → 弹出栈顶（关掉它）
//
// 扫完之后：
//
//     栈空  → 全关上了 ⇒ **配对成功**
//     栈不空 → 还有没关的 ⇒ **配对失败**
//
// 自己走一遍 `(())`：
//
//     读到 '('   栈 { ( }       深度 1
//     读到 '('   栈 { (, ( }    深度 2   ← 到目前为止最高是 2
//     读到 ')'   栈 { ( }       深度 1
//     读到 ')'   栈 { }         深度 0
//     扫完，栈空 ⇒ 成功，最大深度 2
//
// 再走一遍 `)(`：
//
//     读到 ')'   栈是空的！⇒ **立刻判失败**（不能等扫完）
//     读到 '('   栈 { ( }
//     扫完，栈不空 ⇒ 也失败
//
// ⚠ 第二种失败**必须当场记下来**：`)(` 的最后栈深度是 1，但
//   如果你只判「扫完栈空不空」，`)(` 会走到 `(` 那一步，栈里留一个 `(` ⇒
//   恰好也判失败。看起来没问题？试试 `)()`：扫完栈是空的（`()` 配掉了），
//   可它明明错了 —— **开头那个 `)` 是当场就该抓住的**。
//
// ─────────────────────────────────────────────────────
//  五、最大嵌套深度是个**单独的**问题
// ─────────────────────────────────────────────────────
//
// `()()` 的最大深度是 **1**，`(())` 的最大深度是 **2**。
