//
//     栈  stack    像一摞盘子：**后放上去的先拿走**
//                  只能碰最上面那个（LIFO，后进先出）
//
//     队列 queue   像排队买饭：**先来的先走**
//                  只能从队尾进、从队头出（FIFO，先进先出）
//
