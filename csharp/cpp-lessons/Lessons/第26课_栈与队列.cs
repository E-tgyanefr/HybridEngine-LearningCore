//
//     int 配不上 = 0;       一旦发现有问题的括号，置 1（不清零）
//     int 最大深度 = 0;     每次 push 之后，跟当前 size() 比一比
//
// ⚠ 深度要在 **push 之后**比 —— 比完栈就浅下去了，回不到那个高度。
