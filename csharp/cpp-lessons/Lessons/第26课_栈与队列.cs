//
// ─────────────────────────────────────────────────────
//  一、std::stack 的四个操作
// ─────────────────────────────────────────────────────
//
//     #include <stack>
//
//     std::stack<int> 栈;
//     栈.push(3);        放一个上去        ⇒ 栈里 {3}
//     栈.push(5);        再放一个          ⇒ 栈里 {3, 5}（5 在上面）
