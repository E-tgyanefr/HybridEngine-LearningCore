// 第 11 课：递归 —— 函数调用自己
//
// 先介绍：把一个问题的答案，说成"小一号的同一个问题"的答案
//
//     阶乘 n! = 1 × 2 × 3 × ... × n
//
//     用循环写（你已经会了）：
//         int 结果 = 1;
//         for (int i = 2; i <= n; i++) 结果 *= i;
//
//     用递归写 —— 换个说法：
//         n! = n × (n-1)!
//         "n 的阶乘 = n 乘上「n-1 的阶乘」"
//
//     int 阶乘(int n) {
//         if (n <= 1) return 1;      ← ① 什么时候停
//         return n * 阶乘(n - 1);    ← ② 用"小一号的答案"拼出答案
//     }
//
//  这个函数里出现了自己的名字 —— 这就是递归。
//  它不会无限循环下去，因为每一层的 n 都比上一层**小一号**。
//
// ─────────────────────────────────────────────────────
//  ⚠⚠ 递归必须有的两样东西
// ─────────────────────────────────────────────────────
//
//   ① **基准情形**（base case）—— 什么时候**不再**调用自己，直接给答案。
//        上面那行 `if (n <= 1) return 1;` 就是它。
//
//   ② **每次都在变小** —— 参数必须朝着基准情形走。
//        `阶乘(n - 1)` 比 `阶乘(n)` 小一号 ⇒ 早晚会到 1。
//
//   ⚠⚠⚠ **缺了任何一样，程序会崩 —— 而且崩法很难看。**
//
//      int 阶乘(int n) {
//          return n * 阶乘(n - 1);      /* 没有基准情形 */
//      }
//
//   它会一直调用下去，每调一次就在内存里压一层（叫"调用栈"），
//   直到把栈用完 ⇒ 崩溃。这个错叫**栈溢出**（stack overflow）。
//
//   ⚠ 在 Windows 上你看到的多半是程序直接消失、退出码不是 0，
//     而不是一句好看的报错。
//     **这就是递归最需要小心的地方：它不会好好告诉你哪里错了。**
//
// ─────────────────────────────────────────────────────
//  为什么值得学：有些问题用递归写短得多
// ─────────────────────────────────────────────────────
//
//  阶乘用循环写就挺好，递归没占到便宜。但下面这类问题：
//
//     · 文件夹里还有文件夹，一层套一层 —— 怎么数所有文件？
//     · 一棵树，每个节点还有子树 —— 怎么遍历？
//     · 汉诺塔、走迷宫、表达式求值
//
//  **它们本身就是递归定义的**，用循环写要自己造一个"栈"来记住位置，
//  用递归写则几乎是直译。这一课先在小问题上把套路练熟。
//
// ─────────────────────────────────────────────────────
//  ⚠ 一个反例：斐波那契**不该**用这种递归写
// ─────────────────────────────────────────────────────
//
//      fib(n) = fib(n-1) + fib(n-2)
//
//  按这个式子直接写成递归：
//
//      int 斐波那契(int n) {
//          if (n <= 1) return n;
//          return 斐波那契(n - 1) + 斐波那契(n - 2);   ← 能算对，但极慢
//      }
//
//  ⚠⚠ 它**能算出正确答案**，但算 fib(40) 要调用自己上**亿**次。
//     为什么：算 fib(5) 要 fib(4) 和 fib(3)，而 fib(4) 又要 fib(3) ——
//     **同一个 fib(3) 被重复算了无数遍**。这叫"重叠子问题"。
//
//  这一课仍然让你这么写，因为**它最能训练"递归思维"**，
//  而且检查只喂到 n ≤ 20（够快）。但你要记住：
//
//     ⚠ **能写出递归，不等于该用递归。**
//       判断依据是"有没有大量重复计算"，不是"写起来短不短"。
//
//  （正式的做法叫"记忆化"：把算过的答案存起来，下次直接查表。）
//
// ─────────────────────────────────────────────────────
//  ⚠ 顺便认识一个 C++ 特有的坑：递归深度
// ─────────────────────────────────────────────────────
//
//  就算基准情形写对了，递归**太深**照样崩 ——
//  因为每层都要占一块栈内存，栈是**有限**的（通常几 MB）。
//
//     阶乘(10)      10 层，没问题
//     阶乘(100000)  十万层 ⇒ **栈溢出**
//
//  ⇒ 递归适合"层数不深"的问题。要处理很深的层级时，
//    要么改成循环，要么显式用一个容器当栈。
//
// ─────────────────────────────────────────────────────
// ─────────────────────────────────────────────────────
// ─────────────────────────────────────────────────────
//  用法与例子
// ─────────────────────────────────────────────────────
//  ① 阶乘：一层层展开着看
//
//      阶乘(4) = 4 × 阶乘(3) = 4 × (3 × 阶乘(2)) = 4 × (3 × (2 × 阶乘(1)))
//              = 4 × (3 × (2 × 1))          ← 到基准情形了，开始往回算
//              = 24
//
//   写递归时脑子里要能这样展开，不然很容易漏掉基准情形。
//
//  ② 斐波那契：基准情形**有两个**
//
//      int 斐波那契(int n) {
//          if (n <= 0) { return 0; }      ← 基准情形 ①
//          if (n == 1) { return 1; }      ← 基准情形 ②
//          return 斐波那契(n - 1) + 斐波那契(n - 2);
//      }
//
//      fib(0)=0  fib(1)=1  fib(2)=1  fib(3)=2  fib(4)=3  fib(5)=5
//
//  ⚠ 为什么两个都要：n 每次减 1 或减 2，只写 n == 0 的话，
//    n = 1 时会掉到 斐波那契(-1)、斐波那契(-2) 去（见常见坑 2）。
//
//  ③ 怎么读一个递归函数：先找基准情形
//
//     第一步：哪一行**没有**调用自己？     → 那就是出口
//     第二步：参数每次怎么变？变小了吗？ → 那决定它会不会走到出口
//
//  ⚠ 一个反例：斐波那契用这种递归写能算对，但很慢 ——
//    同一个 fib(3) 会被重复算无数遍（这叫「重叠子问题」）。
//    这一课仍然让你这么写，因为它最能训练递归思维，检查也只喂到 n <= 20。
//    但请记住：**能写出递归，不等于该用递归。**

//  常见坑
// ─────────────────────────────────────────────────────
// ⚠ 坑 1：没有基准情形
//
//     int 阶乘(int n) { return n * 阶乘(n - 1); }      ← 永远不停
//
// 你会看到：**编译完全通过**（语法没问题），一跑起来 ——
//   程序**直接消失**，屏幕上什么输出都没有。实测退出码是 **-1073741571**
//   （也就是 0xC00000FD，栈溢出），大约两秒后进程就没了。
// 为什么：每调一次自己就要在调用栈上压一层。栈是有限的（通常几 MB），
//   压满了就崩 —— 这不是「报错」，是进程被系统干掉。
// ⇒ 写递归时，**第一件事就是写下基准情形**。
//
// ⚠ 坑 2：基准情形少写一个（斐波那契只写了 n <= 0）
//
//     int 斐波那契(int n) {
//         if (n <= 0) { return 0; }
//         return 斐波那契(n - 1) + 斐波那契(n - 2);      ← n=1 时没有出口
//     }
//
// 你会看到：和坑 1 一模一样 —— 程序消失，退出码 -1073741571（实测同一个码）。
// 为什么：n = 1 时走的是 n-1 = 0（能停）和 n-2 = -1（停不下来）——
//   负数越走越小，碰不到别的出口。
// ⇒ 两个基准情形都要写：n <= 0 和 n == 1。
//
// ⚠ 坑 3：参数没有变小
//
//     int 阶乘(int n) {
//         if (n <= 1) { return 1; }
//         return n * 阶乘(n);            ← 传进去的还是 n
//     }
//
// 你会看到：基准情形明明写了，程序照样消失，退出码还是 -1073741571（实测）。
// 为什么：基准情形管的是「什么时候停」，**参数变小**管的是「能不能走到那里」。
//   两样缺一不可 —— n 一直不变，那个 if 永远等不到 n <= 1。
// ⇒ 每次调用都必须朝着基准情形**迈一步**。
//
// ⚠ 坑 4：以为递归能装下任意大的结果
//
//     阶乘(12)  ⇒ 479001600     ← 刚好还装得下
//     阶乘(13)  ⇒ 1932053504    ← 实测就是这个数，可真实值是 6227020800
//
// 你会看到：**没有任何警告**，只有一个「看着挺正常」的正数。
// 为什么：int 最大只到 2147483647，13! 早就超了，多出来的位被丢掉。
// ⇒ 检查只喂到 n <= 10，就是为了避开这件事。

//  轮到你了 —— 在下面写
// ─────────────────────────────────────────────────────
//   写两个**递归**函数（不许用循环）：
