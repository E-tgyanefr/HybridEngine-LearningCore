//     少了任何一样，检查会看到程序崩溃。
//
//   ⚠ `阶乘(13)` 就已经超出 int 的范围了（13! ≈ 62 亿 > 21 亿），
//     所以检查只喂到 n ≤ 10 —— 这不是你写错了，是 int 装不下。
