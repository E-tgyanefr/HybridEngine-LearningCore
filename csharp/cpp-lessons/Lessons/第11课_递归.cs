    public static string 参考答案 => """
int 阶乘(int n) {
    /* ⚠ ① 基准情形：到这儿就停，直接给答案 */
    if (n <= 1) {
        return 1;
    }
    /* ⚠ ② 参数比原来小一号 ⇒ 早晚会碰到基准情形 */
    return n * 阶乘(n - 1);
}

int 斐波那契(int n) {
    /* ⚠ 基准情形**有两个**（n=0 和 n=1），少一个就会掉到负数去 */
    if (n <= 0) {
        return 0;
    }
    if (n == 1) {
        return 1;
    }
    /* ⚠ 这样写能算对，但**极慢** ——
       斐波那契(3) 在算 斐波那契(6) 的过程中会被重复计算好几遍。
       这一课先练"递归思维"，效率的事以后再说。 */
    return 斐波那契(n - 1) + 斐波那契(n - 2);
}
""";


