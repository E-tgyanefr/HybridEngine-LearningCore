    [检查说明("★ 求和：长度是 0 时必须返回 0（最容易漏掉的边界）")]
    public static CheckResult 检查_求和_长度是0(string 代码)
    {
        // ⚠ 这一条是本课的核心检查点。
        var run = 跑一次(代码);
        string 停 = 先别急着比(run);
        if (停 != null) return CheckResult.不过(停);

        string 得到 = 取值(run, "求和0");
        if (得到 == null) return CheckResult.不过(查不到说明("求和0"));
        if (得到 == "0")
            return CheckResult.过("求和(甲, 0) 交出了 0 —— 边界处理对了");

        return CheckResult.不过(
            "求和(甲, 0) 得到的是 " + 显示(得到) + "，应该是 0。\n" +
            "      甲 里确实装着 {5, 6, 7, 8}，但**长度参数是 0** ——\n" +
            "      它的意思是「这一次一个数都不要加」，所以答案只能是 0。\n" +
            "      最常见的错法，是先把第一格塞进结果里：\n" +
            "          int 和 = 数[0];                   ✗ 长度是 0 时，这一步已经越界了\n" +
            "          for (int i = 1; i < 长度; i++) 和 += 数[i];\n" +
            "      它之所以还能跑出 " + 显示(得到) + " 而不是报错，正是因为这个：\n" +
            "          **数组越界不一定会崩** —— C++ 只是安静地读到了那一格。\n" +
            "      正确写法是从 0 开始、从 0 累加：\n" +
            "          int 和 = 0;\n" +
            "          for (int i = 0; i < 长度; i++) 和 += 数[i];\n" +
            "      这样长度是 0 时循环一次都不进，直接交出 0。\n" +
            "      顺便记住：**边界（0 个、1 个、最后一个）是最容易出错的地方**，\n" +
            "                自己写函数时先想一遍「长度是 0 会怎样」。");
    }

