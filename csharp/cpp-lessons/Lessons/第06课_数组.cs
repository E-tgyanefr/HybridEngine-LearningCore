    public static string 参考答案 => """
// 参考答案 —— 数组和向量

// 1. 数组版求和：数组自己不知道有多长，所以长度必须**另外传进来**
int 求和(int 数[], int 长度) {
    int 和 = 0;                        // ← 初值 0 不能忘（C++ 不会帮你清零）
    for (int i = 0; i < 长度; i++) {   // ← 是 < 不是 <=
        和 += 数[i];
    }
    return 和;                         // 长度是 0 时循环一次都不进，直接交出 0
}

// 2. 向量版求和：vector 自己知道长度，不用额外传参数
int 求和向量(std::vector<int> 数) {
    int 和 = 0;
    for (int i = 0; i < (int)数.size(); i++) {
        和 += 数[i];
    }
    return 和;
}

// 3. 安全取：越界时自己拦下来（C++ 不会帮你拦）
int 安全取(std::vector<int> 数, int 下标) {
    if (下标 < 0 || 下标 >= (int)数.size()) {
        return -1;                     // 越界：按题目约定交出 -1
    }
    return 数[下标];
}
""";

