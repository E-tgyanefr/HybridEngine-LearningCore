// 第 06 课：数组与向量 —— 一排格子，和一个会自己变长的格子
//
// ══ 这一课要教什么 ══
// 一次装很多个数：`int 甲[3]` 是固定三格的数组，`std::vector<int>` 是能自己变长的向量。
//
// 这一课真正要记住的不是语法，而是一件**很危险**的事：
//
//     **数组下标越界，C++ 不一定会崩。**
//
// 实测（本机 g++ 16.1.0，就是学生用的那个编译器）：
//     int a[3] = {1, 2, 3};
//     std::cout << a[10];        // 程序正常退出，打印出 51 —— 一个垃圾值
// Python 会抛 IndexError、C# 会抛异常，C++ 什么都不做：它读到了别的内存，
// 不报错、不崩溃，只是**结果莫名其妙地不对**。这是最难查的一类 bug。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**长度参数是 0 时（一个数都不加）必须返回 0**。
// 学生最容易写成「先把 数[0] 塞进结果，再从 1 开始循环」——
// 长度是 0 的时候那一步就已经越界了，而**越界不一定崩**，
// 于是它会安静地返回 数[0]（我实测得到 5，题目期望 0），只有边界用例能暴露它。
// 另外数组长度是**另外传进来**的：忽略它、改用 sizeof(数)/sizeof(数[0]) 的写法
// 在我这台机器上恰好等于 2，会蒙对「长度 2」那一组 —— 所以用例里
// 特意放了长度 1、4、0 三组，让它蒙不过去。
//
// ⚠ 给维护者：g++ 会把诊断信息里的中文标识符转义成 \U000053cc，
//   所以下面只匹配 ASCII 的报错片段（cannot convert / was not declared 等）。

