    // 一次检查会给每一课的所有用例各调用一次检查方法，而它们的输入是同一份代码 ——
    // 编译一次就够了（每次编译要起一次 g++，一两秒）。
    private static string 上次的代码;
    private static CppRun 上次的运行;

    private static CppRun 跑一次(string 代码)
    {
        if (上次的运行 != null && 上次的代码 == 代码) return 上次的运行;
        上次的代码 = 代码;
        上次的运行 = CppCheck.编译并运行(代码, null, 调用点);
        return 上次的运行;
    }

    /// <summary>编译没过、或者程序半路崩了 → 返回给学生看的说明；一切正常 → null。</summary>
    private static string 先别急着比(CppRun run)
    {
        if (run.Raw.CompileFailed)
        {
            // 三个函数的签名是这一课最容易写错的地方，单独认一下
            if (run.编译信息.Contains("cannot convert"))
                return
                    "函数的参数类型和题目要求对不上。这一课要三个函数，签名是：\n" +
                    "          int 求和(int 数[], int 长度)          ← 数组：长度要另外传\n" +
                    "          int 求和向量(std::vector<int> 数)      ← 向量：不用传长度\n" +
                    "          int 安全取(std::vector<int> 数, int 下标)\n" +
                    "      「数组」和「向量」是两种不同的东西，不能混用：\n" +
                    "          数组   int 数[]        自己不知道长度 → 必须再传一个长度\n" +
                    "          向量   std::vector<int> 自己知道长度 → 用 数.size()";
            return CppCheck.编译失败说明(run).Detail;
        }
        if (run.Raw.Error != null)
            return
                "程序没跑完就退出了：" + run.Raw.Error + "\n" +
                "      这一课的函数会去碰数组/向量的下标。**越界读写可能直接崩** ——\n" +
                "      检查循环的边界（是 i < 长度，不是 i <= 长度）和 安全取 里的判断。";
        return null;
    }

    private static CheckResult 比一比(CppRun run, params (string 标记, string 期望, string 说明)[] 用例们)
    {
        var 错 = new List<string>();
        foreach (var (标记, 期望, 说明) in 用例们)
        {
            string 得到 = 取值(run, 标记);
            if (得到 == null) 错.Add("      " + 说明 + "：程序没有给出这一行的结果");
            else if (得到 != 期望) 错.Add("      " + 说明 + "：得到 " + 显示(得到) + "，应该是 " + 显示(期望));
        }
        if (错.Count == 0) return CheckResult.过("这几组都对");

        return CheckResult.不过(
            "结果不对：\n" + string.Join("\n", 错) + "\n" +
            "      对着想一遍：这个长度（或下标）下，你的循环跑了几次？每次加的是哪一格？\n" +
            "      数组版请确认用的是**传进来的长度**，而不是 sizeof —— 数组进了函数以后，\n" +
            "      sizeof(数)/sizeof(数[0]) 算出来是「指针大小 / int 大小」= 2，不是真实长度。");
    }

    private static string 查不到说明(string 标记) =>
        "没能从程序输出里找到「" + 标记 + "」这一行的结果 —— 函数可能没被调用到，或者程序中途崩了。";

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s.Length == 0 ? "（空）" : s;
