    [检查说明("判断相等写的是 == 还是 =（写成一个等号程序也会照跑）")]
    public static CheckResult 检查_等号有没有写错(string 代码)
    {
        // ⚠ 这一条是本课的核心检查点。
        //
        // 怎么用行为抓住它，而不是去猜源码：
        //   if (猜 = 42) 会把 42 赋值给 猜，而赋值表达式的值**就是 42**（非零）
        //   → 条件恒为真 → "对了"这个分支每次都走。
        // 于是拿两个**都不该**判对的输入一测就现形：
        //   猜数字(10) 和 猜数字(50) 都返回"对了" —— 一个数不可能既小于又大于 42。
        var run = CppCheck.编译并运行(代码, null,
            "    std::cout << 猜数字(10) << \"\\n\";\n" +
            "    std::cout << 猜数字(50) << \"\\n\";\n");

        if (!run.编译通过) return CppCheck.编译失败说明(run);
        if (run.行.Count < 2)
            return CheckResult.不过(
                "猜数字() 没有用 return 返回字符串，所以拿不到结果。\n" +
                "      这一课的函数要**返回**字符串：\n" +
                "          std::string 猜数字(int 猜) {\n" +
                "              if (猜 == 42) return \"对了\";\n" +
                "              ...\n" +
                "          }\n" +
                "      而不是在函数里 std::cout << \"对了\";");

        string 小 = run.行[0].Trim();
        string 大 = run.行[1].Trim();

        if (小 == "小了" && 大 == "大了")
            return CheckResult.过("判断用的是 ==：10 判「小了」、50 判「大了」，两个分支分得开");

        bool 源码里有赋值当条件 = 条件里有赋值(代码);

        if (小 == "对了" && 大 == "对了")
            return CheckResult.不过(
                (源码里有赋值当条件
                    ? "我在你的代码里看到了形如 if (… = …) 的写法 —— 问题就在这里。\n"
                    : "") +
                "猜数字(10) 给的是「" + 小 + "」，猜数字(50) 给的也是「" + 大 + "」。\n" +
                "      10 小于 42、50 大于 42，两个结果**不可能一样** ——\n" +
                "      出现这种「所有输入都走同一个分支」的现象，几乎就是把 == 写成了 =。\n" +
                "          if (猜 == 42)   // 判断：猜 和 42 相等吗？\n" +
                "          if (猜 = 42)    // 赋值：把 42 存进 猜，再拿这个值当条件\n" +
                "      赋值表达式的值就是刚存进去的 42 —— 非零，所以条件**永远为真**。\n" +
                "      ⚠ 最坑的是：这**不是编译错误**。g++ 只给一句警告（-Wparentheses），\n" +
                "        程序照跑、照样出结果，错得一点提示都没有。\n" +
                "      改法：判断相等用两个等号 ==。\n" +
                "      防身技巧：把常量写在左边 —— if (42 == 猜)。手滑写成 = 会直接编译不过，\n" +
                "                编译器当场拦住你，而不是让你带着 bug 跑完全程。");

        return CheckResult.不过(
            $"猜数字(10) 应该是「小了」，你的函数给的是「{小}」；\n" +
            $"      猜数字(50) 应该是「大了」，给的是「{大}」。\n" +
            "      想清楚这两件事：\n" +
            "        · 判断相等要用==（两个等号），一个 = 是赋值\n" +
            "        · 三个分支的**顺序**和**条件**要对：先判等于，再判小于/大于\n" +
            "      可以写成：if (猜 == 42) ... else if (猜 < 42) ... else ...");
    }

    [检查说明("&& 和 || 有没有真的用上（这一课要练的就是它俩）")]
    public static CheckResult 检查_用上逻辑运算符(string 代码)
    {
        // 为什么用"看源码"而不是"看行为"：
        // 闰年用嵌套 if 也能写对（行为一样），但那就绕过了本课要练的 && / ||。
        // 这是**有意**的一条"练到了没有"的检查 —— 题目里已经写明了要用它俩。
        // 为了不被注释骗过去，先把注释去掉再找。
        string 净 = 去掉注释(代码);
        bool 有与 = 净.Contains("&&");
        bool 有或 = 净.Contains("||");

        if (有与 && 有或)
            return CheckResult.过("&& 和 || 都用上了");

        if (!有与 && !有或)
            return CheckResult.不过(
                "代码里没有找到 && 和 ||。\n" +
                "      闰年这一题用嵌套 if 也能写对，但这一课要练的就是把条件**连起来**：\n" +
                "          &&  两边都为真，结果才为真     （并且）\n" +
                "          ||  只要有一个为真，结果就为真 （或者）\n" +
                "      闰年的条件正好两样都要用，写成**一个** if：\n" +
                "          if ((年 % 4 == 0 && 年 % 100 != 0) || 年 % 400 == 0) { ... }\n" +
                "      读作：「能被 4 整除 且 不能被 100 整除」 或者 「能被 400 整除」。");

        return CheckResult.不过(
            (有与 ? "代码里只找到了 &&，没有找到 ||。\n" : "代码里只找到了 ||，没有找到 &&。\n") +
            "      闰年的条件需要两个一起用：\n" +
            "          if ((年 % 4 == 0 && 年 % 100 != 0) || 年 % 400 == 0) { ... }\n" +
            "      拆开看是两个条件，用 || 连起来：\n" +
            "          ① 年 % 4 == 0 && 年 % 100 != 0     ← 普通闰年（1900 不满足）\n" +
            "          ② 年 % 400 == 0                    ← 整百年份的例外（2000 满足）\n" +
            "      顺便记住优先级：&& 比 || 先算，所以上面那层的括号其实可以省，\n" +
            "      但**写上更好读** —— 半年后回来看，你会感谢自己。");
    }

