//
// ══ 这一课要教什么 ══
// 到上一课为止，程序只会一条道走到黑。这一课让它**分岔**：同一个函数，
// 不同的输入走不同的分支 —— 这是"程序开始像在思考"的第一步。
//
// 但 C++ 在这里埋了一个臭名昭著的坑，而且它**不是编译错误**：
//     if (猜 == 42)   // 判断：猜 和 42 相等吗
//     if (猜 = 42)    // 赋值：把 42 存进 猜，再拿这个值当条件
// 第二个写法 g++ 只给一句警告，程序照跑 —— 而且因为 42 非零，
// 条件**永远为真**，那个分支每次都会走。所以这一课有一条专门盯它的检查。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点是第 5 条（把 == 写成 =）。它靠**行为**抓，不靠看源码：
//   if (猜 = 42) 会让"猜对了"分支恒为真，于是 猜数字(10) 和 猜数字(50)
//   会返回同一个结果 —— 一个数不可能既小于 42 又大于 42。
//   源码扫描只是拿来把提示说得更准（"我在你代码里看到 if (… = …)"），不作为判据。
//
// 另外三条：
//   · 第 2/3/4 条用 逐个用例，多组输入一起测 —— 一组蒙对不算过。
//     第 3 条的边界值（90/89/60/59/±越界）专门抓 >= 写成 > 这类边界错。
//   · 第 6 条要求源码里真的出现 && 和 ||：闰年用嵌套 if 也能写对，
//     但那就绕过了这一课要练的逻辑运算符。这是**有意**的一条"练到了没有"的检查。

