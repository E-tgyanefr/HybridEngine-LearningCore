    public static string 参考答案 => """
// 第 34 课参考答案：两个二维 DP

int 路径数(int 行, int 列) {
    if (行 <= 0 || 列 <= 0) return 0;
    const int 模 = 1000000007;

    // 第一行和第一列都只有 1 条路（只能一路往右 / 一路往下）
    // ⇒ 干脆整张表都初始化成 1，然后从 [1][1] 开始推
    std::vector<std::vector<int>> dp(行, std::vector<int>(列, 1));

    for (int i = 1; i < 行; i++) {
        for (int j = 1; j < 列; j++) {
            // 走到 (i,j) 的最后一步：从上面来 + 从左边来
            dp[i][j] = (dp[i - 1][j] + dp[i][j - 1]) % 模;
            // ⚠ 每加一次就取模。等最后再取就晚了 —— 20×20 早就溢出 int 了
        }
    }
    return dp[行 - 1][列 - 1];        // 表是 行×列，最后一个格子的下标是 [行-1][列-1]
}

int 最长公共子序列(std::string a, std::string b) {
    int n = (int)a.size();
    int m = (int)b.size();

    // ⚠ 要多开一行一列：dp[0][*] 和 dp[*][0] 表示「前 0 个字符」（空串）
    std::vector<std::vector<int>> dp(n + 1, std::vector<int>(m + 1, 0));

    for (int i = 1; i <= n; i++) {
        for (int j = 1; j <= m; j++) {
            if (a[i - 1] == b[j - 1]) {
                // ⚠ 是 a[i-1] / b[j-1] —— dp 的下标比字符串的下标大 1
                dp[i][j] = dp[i - 1][j - 1] + 1;
            } else {
                // 至少有一个字符用不上：扔掉一边，取大的那个
                dp[i][j] = std::max(dp[i - 1][j], dp[i][j - 1]);
            }
        }
    }
    return dp[n][m];
}
""";

