            "        int 上限是 2147483647，20×20 的真值是 35345263555 —— 早就溢出了。\n" +
            "        **每加一次就要取一次模**，不能等最后。\n" +
            "      ⚠ 1×N 和 N×1 的答案都是 1（只有一条直路），1×1 也是 1。\n" +
            "      ⚠ 如果是**超时**而不是算错，看上面的说明（暴力递归跑不完）。");
    }

    [检查说明("★ 核心：最长公共子序列 —— 不能写成「最长公共子串」")]
    public static CheckResult 检查_最长公共子序列(string 代码)
    {
        // ⚠ 第二个核心检查点。ABCBDAB / BDCABA 这一对是关键：
        //   最长公共**子序列**是 4，最长公共**子串**只有 2。
        //   而 "abcde"/"ace" 这一对两种写法都是…… 子串写法给 1、正确是 3，
        //   所以它也能抓。两对一起用，跑不掉。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 得 = 取值(run, "子");
        const string 期望 = "3,3,0,0,4,2,6";

        if (得 == 期望)
            return CheckResult.过("七组都对，包括 ABCBDAB/BDCABA = 4 和两个空串的情况");

        return CheckResult.不过(
            "最长公共子序列不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(得) + "\n" +
            "      （依次是 (\"abcde\",\"ace\")、(\"abc\",\"abc\")、(\"abc\",\"def\")、\n" +
            "        (\"\",\"abc\")、(\"ABCBDAB\",\"BDCABA\")、(\"aaaa\",\"aa\")、\n" +
            "        (\"abcdef\",\"abcdef\")）\n" +
            "      两条转移规则（看两个串的**最后一个字符**）：\n" +
            "          a[i-1] == b[j-1]  ⇒  dp[i][j] = dp[i-1][j-1] + 1\n" +
            "          不相等            ⇒  dp[i][j] = max(dp[i-1][j], dp[i][j-1])\n" +
            "      ⚠ 如果 ABCBDAB/BDCABA 给出的是 **2**，那是写成了「最长公共**子串**」——\n" +
            "        子串要求**连续**，子序列**不要求**。\n" +
            "        这对字符串的最长公共子序列是 4（例如 B C A B），\n" +
            "        最长公共子串只有 2。\n" +
            "        判据：只有「字符相等时 +1」这一条、没有「不相等时扔掉一边」\n" +
            "        那一句，就是子串写法。\n" +
            "      ⚠ 如果全都差 1 或者越界崩了：检查 dp 是不是开了 **(n+1)×(m+1)**。\n" +
            "        dp 的第 0 行/列表示「前 0 个字符」，所以循环是 i=1..n、\n" +
            "        而取字符时要用 **a[i-1]**（下标差 1 是这个算法最容易错的地方）。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
