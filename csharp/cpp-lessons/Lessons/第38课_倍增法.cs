    public static string 参考答案 => """
// 第 38 课参考答案：快速幂 + 2^k 跳跃

long long 快速幂(long long 底, long long 指) {
    long long 果 = 1;
    while (指 > 0) {
        if (指 % 2 == 1) {
            果 *= 底;          // 这一位是 1 ⇒ 把当前的底乘进去
        }
        底 *= 底;              // 底 → 底²（⚠ 别忘了那个 =）
        指 /= 2;               // 指数右移一位（⚠ 也别忘了 =）
    }
    return 果;
    // 指 = 0 时循环不进 ⇒ 返回 1，正确。
}

int 快速幂次数(long long 指) {
    int 次数 = 0;
    while (指 > 0) {
        次数++;
        指 /= 2;               // 每除一次 2，就是二进制少一位
    }
    return 次数;
    // 10 亿只需要循环 30 次 —— 这就是"倍增"省下来的东西。
}

int 跳到的位置(std::vector<int> 跳跃, long long 步) {
    int 当 = 0;                 // 从 0 号位置出发
    while (步 > 0) {
        if (步 % 2 == 1) {
            当 = 跳跃[当];               // 这一位要跳 ⇒ 跳一次
        }
        // 把表原地升级：现在 跳跃[i] 表示"从 i 跳**两次**到哪"
        跳跃[当] = 跳跃[跳跃[当]];
        步 /= 2;
    }
    return 当;
    // 和快速幂是同一个骨架：一个是"乘进结果"，一个是"跳过去"。
}
""";

