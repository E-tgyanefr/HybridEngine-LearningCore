// ══ 这一课要教什么 ══
// 「倍增」的想法：**每一步把规模翻一倍**，于是 n 步能覆盖 2ⁿ 的范围；
// 反过来，要处理 n 那么大的范围，只要 log₂n 步。
// 两个例子：
//   · 快速幂：把指数不断除以 2、底不断平方 ⇒ 2^1000000 只要 20 步而不是 100 万步
//   · 2^k 跳跃：预先算出「跳 2 步、跳 4 步…会到哪」，然后按指数的二进制位跳
//
// ══ 检查设计说明（给维护者）══
// 核心检查点有两个，因为"一层一层乘"那种写法**输出完全一样**，
// 光比答案抓不住它（实测：2^62、7^15 两种写法都对）：
//   ① 检查_是倍增（源码文本）：快速幂的循环体里必须有 `指 /= 2`
//      （或 `指 >>= 1`、`指 % 2`、`指 & 1`）。一层一层乘的写法一个都没有。
//   ② 检查_复杂度（计时）：连做 20 次 `快速幂(1, 2000000000)`。
//      倍增版约 0.02 秒；一层一层乘的版本实测 **9.7 秒**（约 480 倍差距），
//      超过 2 秒的预算就判不过。基数是 1 ⇒ 结果永远是 1，不会溢出。
//      ⚠ 计时阈值 2000 毫秒留了 100 倍余量，慢机器上不会误判。
// 反面测试（都跑过）：
//   · 一层一层乘（O(指)）→ 输出全对，但被 ① 和 ② 抓住（快 = 1,0）

