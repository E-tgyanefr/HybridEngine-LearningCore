                "        检查会喂 1234567890123 那么大的步数，一层层跳永远跳不完。");

        string 得 = 取值(run, "幂");
        const string 期望 =
            "1024,1,1,1,1048576,1594323,5,4611686018427387904,4747561509943,205891132094649";

        if (得 == 期望)
            return CheckResult.过("十组都对，包括 2^62 = 4611686018427387904 和 3^30");

        return CheckResult.不过(
            "快速幂的结果不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(得) + "\n" +
            "      （依次是 2^10、3^0、2^0、1^1000000、2^20、3^13、5^1、2^62、7^15、3^30）\n" +
            "      写法（指数除 2、底平方）：\n" +
            "          long long 果 = 1;\n" +
            "          while (指 > 0) {\n" +
            "              if (指 % 2 == 1) 果 *= 底;\n" +
            "              底 *= 底;\n" +
            "              指 /= 2;\n" +
            "          }\n" +
            "          return 果;\n" +
            "      道理：a^13 = a^8 × a^4 × a^1 —— 指数 13 的二进制是 1101，\n" +
            "      哪一位是 1，就把当时的底乘进结果里。\n" +
            "      ⚠ **底 *= 底** 和 **指 /= 2** 两个赋值都不能漏（漏了就死循环）。\n" +
            "      ⚠ `指 = 0` 必须返回 1（任何数的 0 次方都是 1，包括 0^0 约定成 1）。\n" +
            "      ⚠ 2^62 = 4611686018427387904 是 long long 能装下的极限附近\n" +
            "        （2^63 就溢出了），所以检查只喂到 62。");
    }

    [检查说明("★ 核心：必须是倍增（源码里要有 指 /= 2 这种写法）")]
    public static CheckResult 检查_是倍增(string 代码)
    {
        // ⚠ 核心检查点之一。必须看源码：一层一层乘的写法
        //   **输出完全一样**（2^62、7^15 它都能算对），光比答案抓不住它。
        //   `指 /= 2`（或 >>=1、%2、&1）是倍增写法抹不掉的痕迹。
        bool 有减半 = System.Text.RegularExpressions.Regex.IsMatch(代码, @"(/\s*=\s*2|>>\s*=\s*1|>>\s*1|%\s*2|&\s*1)");

        if (有减半)
            return CheckResult.过("代码里能看到「指数减半 / 取二进制位」的写法 —— 是倍增");

        return CheckResult.不过(
            "代码里没有看到「把指数除以 2」或「取指数的最低位」这种写法。\n" +
            "      这一课要练的是**倍增**：每一步把规模砍一半。\n" +
            "          a^n = (a²)^(n/2)        n 是偶数\n" +
            "          a^n = a × (a²)^(n/2)    n 是奇数（先乘一个 a 出去）\n" +
            "      所以循环体里必须有这两句：\n" +
            "          底 *= 底;       // 底 变成它的平方\n" +
            "          指 /= 2;        // 指数砍一半\n" +
            "      以及判断这一位要不要乘：`if (指 % 2 == 1) 果 *= 底;`\n" +
            "      ⚠ 用 `for (i = 0; i < 指; i++) 果 *= 底;` 一层一层乘，\n" +
            "        答案**碰巧也对**（2^62 也就乘 62 次），但那是 O(指)：\n" +
            "        指数 10 亿的时候要乘 10 亿次，而倍增只要 30 次 ——\n" +
            "        差了 3300 万倍。下一问会用时间把这件事摆出来。");
    }

    [检查说明("★ 核心：复杂度——20 次 10 亿级的幂必须在 2 秒内跑完")]
    public static CheckResult 检查_复杂度(string 代码)
    {
        // ⚠ 第二个核心检查点：用时间说话。
        //   实测（本机 g++ 16.1.0）：倍增版 20 次约 0.02 秒；
        //   一层一层乘的版本约 9.7 秒（约 480 倍）。阈值取 2000 毫秒，
        //   留了 100 倍余量，慢机器上也不会误判。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        if (run.Raw.Error != null && run.Raw.Error.Contains("超时"))
            return CheckResult.不过(
                "程序跑**超时**了（超过 60 秒）—— 这说明它绝对不是 O(log 指)。\n" +
                "      检查连做了 20 次 `快速幂(1, 2000000000)`（1 的 20 亿次方）。\n" +
                "      倍增写法每次只要 31 步左右；一层一层乘要 20 亿次 × 20 = 400 亿次乘法。");

        string 快 = 取值(run, "快");
        if (快 == null)
            return CheckResult.不过("没能拿到那一问的结果 —— 程序可能中途崩了。");

        string[] 段 = 快.Split(',');
        string 果 = 段.Length > 0 ? 段[0] : "?";
        string 判定 = 段.Length > 1 ? 段[1] : "";

        if (果 != "1")
            return CheckResult.不过(
                "快速幂(1, 2000000000) 的结果是 " + 显示(果) + "，应当是 1。\n" +
                "      1 的任何次方都是 1。如果这里错了，先去看「快速幂」本身的写法。");

        if (判定 == "1")
            return CheckResult.过("20 次 10 亿级的幂在 2 秒内跑完 —— 确实是 O(log 指)");

        return CheckResult.不过(
            "20 次 `快速幂(1, 2000000000)` 用了 **2 秒以上** —— 这说明它不是倍增写法。\n" +
            "      实测对比（本机 g++ 16.1.0）：\n" +
            "          倍增（指数除以 2）    约 0.02 秒\n" +
            "          一层一层乘             约 9.7 秒      ← 差约 480 倍\n" +
            "      为什么差距这么大：\n" +
            "          一层一层乘：指数 20 亿 ⇒ 乘 20 亿次\n" +
            "          倍增：      指数 20 亿 ⇒ 只需要循环 **31 次**（20 亿 < 2³¹）\n" +
            "      改法就是那个骨架：\n" +
            "          while (指 > 0) {\n" +
            "              if (指 % 2 == 1) 果 *= 底;\n" +
            "              底 *= 底;      // 底平方\n" +
            "              指 /= 2;       // 指数减半  ← 关键就是这一句\n" +
            "          }\n" +
            "      指数每减半一次，剩下的工作量就少一半 ⇒ 总步数 = 指数的二进制位数。");
    }

    [检查说明("快速幂次数：10 亿只要 30 次（把 O(log n) 摆出来看）")]
    public static CheckResult 检查_次数(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 得 = 取值(run, "次");
        const string 期望 = "1,2,10,21,31,60";

        if (得 == 期望)
            return CheckResult.过("六组都对 —— 10 亿只要 30 次循环，10¹⁸ 也只要 60 次");

        return CheckResult.不过(
            "快速幂次数不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(得) + "\n" +
            "      （依次是指数 1、2、1000、1048576、1073741824、1000000000000000000）\n" +
            "      它就是「指数不断除以 2，能除几次」—— 也就是指数的**二进制位数**：\n" +
            "          int 次数 = 0;\n" +
            "          while (指 > 0) { 次数++; 指 /= 2; }\n" +
            "          return 次数;\n" +
            "      ⚠ 这一问的意义是让你**亲眼看到**：\n" +
            "          指数 1000（约 10³）        → 10 次\n" +
            "          指数 10 亿（约 10⁹）       → 30 次\n" +
            "          指数 10¹⁸                  → 60 次\n" +
            "        规模涨了 10 亿倍，步数只从 10 涨到 30。**这就是 O(log n)。**");
    }

    [检查说明("2^k 跳跃：含跳 0 次和跳 10¹² 次")]
    public static CheckResult 检查_跳跃(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 错 = new List<string>();
        string 跳 = 取值(run, "跳");
        string 跳2 = 取值(run, "跳2");

        if (跳 != "0,1,0,0")
            错.Add("      跳跃={1,2,0}（0→1→2→0 的环）得到 [" + 显示(跳) + "]，应当是 [0,1,0,0]\n" +
                   "        （依次是跳 3 次、跳 1 次、跳 0 次、跳 100 次）");
        if (跳2 != "0,0")
            错.Add("      跳跃={3,0,4,1,2} 得到 [" + 显示(跳2) + "]，应当是 [0,0]\n" +
                   "        （跳 7 次、跳 1234567890123 次）");

        if (错.Count == 0)
            return CheckResult.过("两个跳跃表都对，包括跳 0 次（原地不动）和跳 10¹² 次");

        return CheckResult.不过(
            "跳跃结果不对：\n" + string.Join("\n", 错) + "\n" +
            "      写法（和快速幂同一个骨架：一位一位地处理步数）：\n" +
            "          int 当 = 0;\n" +
            "          while (步 > 0) {\n" +
            "              if (步 % 2 == 1) 当 = 跳跃[当];      // 这一位要跳\n" +
            "              跳跃[当] = 跳跃[跳跃[当]];           // 表升级成「跳两倍」\n" +
            "              步 /= 2;\n" +
            "          }\n" +
            "          return 当;\n" +
            "      ⚠ 跳 0 次 = **原地不动**（返回 0）—— 循环一次都不进，天然就对。\n" +
            "      ⚠ 跳 100 次那组：跳跃={1,2,0} 是一个长度 3 的环，\n" +
            "        100 = 3×33 + 1 ⇒ 相当于跳 1 次 ⇒ 落在 1？\n" +
            "        不对 —— 正确答案是 **0**。自己推一遍（或者让程序跑），\n" +
            "        别靠\"余数\"猜：这个算法的跳法不是简单的取余。\n" +
            "      ⚠ 别写 `for (i = 0; i < 步; i++)`：步 可能是 10¹²，跑不完。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
