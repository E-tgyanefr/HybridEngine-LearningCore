//
// 先分清两个原理 —— 后面所有公式都是从它们推出来的：
//
//     **加法原理**：做一件事有「几类」办法，各类之间**互不重叠** ⇒ 加起来
//         从家到学校：坐公交 3 条线路，坐地铁 2 条线路
//         ⇒ 一共 3 + 2 = 5 种走法（每条线路都是"一整条完成方案"）
//
//     **乘法原理**：做一件事要「分几步」，每步都要做 ⇒ 乘起来
//         上衣 3 件、裤子 2 条 ⇒ 3 × 2 = 6 套搭配
//         （先选上衣再选裤子，"两步"必须都做）
//
// 判据一句话：**"或者"用加法，"然后"用乘法。**
//
// ─────────────────────────────────────────────────────
//  一、排列 P(n,k)：挑出来还要排队
// ─────────────────────────────────────────────────────
//
// 从 n 个不同的东西里挑 k 个，**排成一排**（顺序算不同）：
//
//     第 1 个位置：n 种选法
//     第 2 个位置：剩 n-1 个 ⇒ n-1 种
//     …
//     第 k 个位置：剩 n-k+1 个 ⇒ n-k+1 种
//
// 每一步都必须做 ⇒ **乘法原理**：
//
//     P(n, k) = n × (n-1) × (n-2) × … × (n-k+1)
//             = n! / (n-k)!
//
// 算几个：
//
//     P(5,2)  = 5 × 4 = 20
//     P(5,5)  = 5×4×3×2×1 = 120（也就是 5!，全排列）
//     P(5,0)  = 1（一个都不挑，"空着"也是一种方案）
//     P(10,3) = 10 × 9 × 8 = 720
//     P(12,3) = 12 × 11 × 10 = 1320
//
// ⚠ `P(n,0) = 1` 不是笔误 —— **"什么都不选"永远算 1 种方案**。
//   这条规矩让很多公式（比如杨辉三角）能统一写出来，务必记住。
//
// ⚠ 代码里**不要真的去算阶乘再相除**：
//
//     P(n,k) = 阶乘(n) / 阶乘(n-k)        ✗ n=21 时 21! 就超出 long long 了
//
//   直接乘那 k 个数就行（省事、也不会溢出得那么早）：
//
//     long long 果 = 1;
//     for (int i = 0; i < k; i++) 果 *= (n - i);
//
// ─────────────────────────────────────────────────────
//  二、组合 C(n,k)：挑出来不排队
// ─────────────────────────────────────────────────────
//
// 从 n 个里挑 k 个，**不管顺序**（{a,b} 和 {b,a} 是同一种）。
//
// 先按排列数 P(n,k) 数：那是"挑出来再排队"的总数。
// 每一种"挑法"，它的 k 个元素自己可以排出 k! 种顺序。
// ⇒ 每一种挑法被数了 k! 遍，除掉就得到挑法数：
//
//     C(n, k) = P(n, k) / k! = n! / (k! × (n-k)!)
//
// 算几个（这一列值得记熟）：
//
//     C(5,2)   = 10
//     C(10,3)  = 120
//     C(20,10) = 184,756
//     C(30,15) = 155,117,520
//     C(50,25) = 126,410,606,437,752      ← 12 万亿，long long 装得下
//
// 几条常用性质：
//
//     C(n, 0) = C(n, n) = 1          空着 / 全都要，都只有 1 种
//     C(n, k) = C(n, n-k)            挑走的和留下的是一回事
//     C(n, k) = C(n-1, k-1) + C(n-1, k)      ← 这就是杨辉三角的递推（见下）
//
// ⚠⚠ **组合数绝不能用「阶乘相除」写**。这是本课最容易踩的坑：
//
//     long long 组合数(int n, int k) {
//         return 阶乘(n) / (阶乘(k) * 阶乘(n - k));      ✗
//     }
//
//   实测：n=20、k=10 时它能给出正确的 184756（因为 20! ≈ 2.4×10¹⁸
//   还在 long long 的范围里）；但换成 **n=30** 就给出 **9**、
//   **n=50** 给出 **0** —— 因为 30! 和 50! 早就溢出了，
//   溢出之后再相除，得到的是一个**毫无意义的数**。
//
//   正确写法是**边乘边除**，让中间结果一直保持在答案附近：
//
//     long long 组合数(int n, int k) {
//         if (k < 0 || k > n) return 0;
//         if (k > n - k) k = n - k;         // 用小的那一半，少乘几次
//         long long 果 = 1;
//         for (int i = 0; i < k; i++) {
//             果 = 果 * (n - i) / (i + 1);   // ⚠ 先乘后除
//         }
//         return 果;
//     }
//
//   ⚠ 为什么「先乘后除」不能反：`果 / (i+1)` 往往**除不尽**
//     （整数除法会把小数丢掉），误差越滚越大。
//     而「先乘再除」是**整除**的 —— 数学上保证
//     `果 × (n-i)` 一定能被 `(i+1)` 整除（这是组合数的一条性质）。
//     拿 n=5,k=2 验一遍：
//         i=0: 果 = 1 * 5 / 1 = 5
//         i=1: 果 = 5 * 4 / 2 = 10            ✓ C(5,2) = 10
//     反过来先除：i=1 时 5/2 = 2（丢掉了 .5）⇒ 最后得到 8，错了。
//
//   ⚠ `if (k > n - k) k = n - k;` 是在用 C(n,k) = C(n,n-k)：
//     C(50,25) 要乘 25 次，C(50,25) 换成 C(50,25) 还是 25 次；
//     但 C(1000, 3) 用它就只乘 3 次而不是 997 次。
//
// ─────────────────────────────────────────────────────
//  三、杨辉三角：每一格是上面两个的和
// ─────────────────────────────────────────────────────
//
//                 1                ← 第 0 行
//               1   1              ← 第 1 行
//             1   2   1            ← 第 2 行
//           1   3   3   1          ← 第 3 行
//         1   4   6   4   1        ← 第 4 行
//       1   5  10  10   5   1      ← 第 5 行
//
// 规矩：**每个数 = 它左上角那个 + 右上角那个**（边上没有的当 0，所以边上都是 1）。
//
// 为什么它和组合数是一回事：`第 n 行第 k 个数 = C(n, k)`。验一下第 5 行：
//
//     C(5,0)=1  C(5,1)=5  C(5,2)=10  C(5,3)=10  C(5,4)=5  C(5,5)=1   ✓
//
// 而「每个数 = 上面两个之和」正是 C(n,k) = C(n-1,k-1) + C(n-1,k)。
//
// 代码：**只用一维数组**，从右往左更新（这样用到的左上是**旧值**）：
//
//     std::vector<long long> 行 = {1};               // 第 0 行
//     for (int i = 0; i < n; i++) {                  // 再推 n 行
//         行.push_back(0);                            // 末尾补一个 0（新的右边界）
//         for (int j = (int)行.size() - 1; j >= 1; j--) {
//             行[j] = 行[j] + 行[j - 1];              // 自己(旧) + 左边(旧)
//         }
//     }
//     // 此时 行 就是第 n 行
//
// 推一行看看（从 {1} 推到第 3 行）：
//
//     开始          行 = {1}
//     i=0: 补 0 ⇒ {1,0}；j=1: 行[1] = 0+1 = 1 ⇒ {1,1}
//     i=1: 补 0 ⇒ {1,1,0}；j=2: 0+1=1；j=1: 1+1=2 ⇒ {1,2,1}
//     i=2: 补 0 ⇒ {1,2,1,0}；j=3: 0+1=1；j=2: 1+2=3；j=1: 2+1=3 ⇒ {1,3,3,1}  ✓
//
// ⚠ **必须倒着更新（j 从大到小）**。正着更新的话，`行[j-1]` 已经被这一轮
//   改成了新值，你加的是「新值 + 旧值」，结果全错。
//   （这和 0/1 背包那个逆序是同一类道理：**别用这一轮刚写进去的数**。）
