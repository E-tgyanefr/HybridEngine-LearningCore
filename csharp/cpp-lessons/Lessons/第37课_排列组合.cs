            "        上面这个写法天然就对（循环一次都不进 ⇒ 返回 1）。\n" +
            "      ⚠ P(n,n) = n!：全部排队。P(5,5) = 120、P(6,6) = 720。\n" +
            "      ⚠ 别用 `阶乘(n) / 阶乘(n-k)` —— 阶乘长得极快，n 一大就溢出。\n" +
            "        直接乘那 k 个数，中间结果小得多。");
    }

    [检查说明("★ 核心：组合数喂到 C(50,25) —— 阶乘相除会溢出")]
    public static CheckResult 检查_组合数(string 代码)
    {
        // ⚠ 本课的核心检查点。C(20,10) 用「阶乘相除」也是对的（20! 刚好装得下），
        //   所以**必须**喂 C(30,15) 和 C(50,25) 才区分得出来。
        //   实测阶乘版：C(30,15) 给 9、C(50,25) 给 0。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 得 = 取值(run, "C");
        const string 期望 = "10,184756,1,1,1,120,0,126410606437752,155117520";

        if (得 == 期望)
            return CheckResult.过("九组都对，包括 C(50,25)=126410606437752 和 C(30,15)=155117520");

        // 单独看一下两组大的是不是崩的 —— 那是"阶乘相除"的典型症状
        string[] 段 = (得 ?? "").Split(',');
        string 大 = 段.Length >= 9 ? (段[7] + " / " + 段[8]) : "（拿不到）";

        return CheckResult.不过(
            "组合数不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(得) + "\n" +
            "      （依次是 C(5,2) C(20,10) C(5,0) C(5,5) C(6,6) C(10,3) C(3,5)\n" +
            "        C(50,25) C(30,15)；最后两组你给的是 " + 大 + "）\n" +
            "      ⚠ 如果 **C(20,10) 对了、C(30,15) 和 C(50,25) 错了**，\n" +
            "        那几乎肯定是写成了「阶乘相除」：\n" +
            "            阶乘(n) / (阶乘(k) * 阶乘(n - k))       ✗\n" +
            "        20! ≈ 2.43 × 10¹⁸ 刚好还在 long long 范围内（上限约 9.22 × 10¹⁸），\n" +
            "        但 21! 就超了 ⇒ 30! 和 50! 早就溢出成垃圾，相除得到的当然是垃圾\n" +
            "        （实测 n=30 给出 9、n=50 给出 0）。\n" +
            "      正确写法是**边乘边除**，让中间结果一直贴着答案：\n" +
            "          if (k < 0 || k > n) return 0;\n" +
            "          if (k > n - k) k = n - k;              // C(n,k)=C(n,n-k)，用小的那半\n" +
            "          long long 果 = 1;\n" +
            "          for (int i = 0; i < k; i++)\n" +
            "              果 = 果 * (n - i) / (i + 1);        // ⚠ 先乘后除\n" +
            "          return 果;\n" +
            "      ⚠ **先乘后除**不能反：反过来的话 `果 / (i+1)` 常常除不尽，\n" +
            "        整数除法把小数丢掉，误差越滚越大。\n" +
            "        （n=5,k=2 验一下：先乘后除 1*5/1=5、5*4/2=10 ✓；\n" +
            "          先除后乘 1/1=1、5*4=20 再 /2=10 也碰巧对 —— 但换个 n 就错了。）\n" +
            "      ⚠ C(n,0) = C(n,n) = 1；k > n 时返回 0。");
    }

    [检查说明("★ 核心：杨辉行喂到第 20 行（数字大到不可能写死）")]
    public static CheckResult 检查_杨辉行(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 行 = 取值(run, "行");
        const string 期望 =
            "1,;1,1,;1,2,1,;1,3,3,1,;1,4,6,4,1,;1,5,10,10,5,1,;1,6,15,20,15,6,1," +
            "|1,10,45,120,210,252,210,120,45,10,1," +
            "|1,20,190,1140,4845,15504,38760,77520,125970,167960,184756,167960," +
            "125970,77520,38760,15504,4845,1140,190,20,1,";

        if (行 == 期望)
            return CheckResult.过("第 0~6、10、20 行全对（第 20 行有 21 个数，最大 184756）");

        return CheckResult.不过(
            "杨辉行不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(行) + "\n" +
            "      （格式是「第 0 行;第 1 行;…;第 6 行|第 10 行|第 20 行」，每个数后面带逗号）\n" +
            "      一句话：**每个数 = 它左上角 + 右上角**（边上没有的当 0 ⇒ 边上都是 1）。\n" +
            "      用一维数组、从右往左更新：\n" +
            "          std::vector<long long> 行 = {1};\n" +
            "          for (int i = 0; i < n; i++) {\n" +
            "              行.push_back(0);\n" +
            "              for (int j = (int)行.size() - 1; j >= 1; j--)\n" +
            "                  行[j] = 行[j] + 行[j - 1];\n" +
            "          }\n" +
            "          return 行;\n" +
            "      ⚠ **必须倒着更新**。正着更新的话，`行[j-1]` 已经被这一轮改成新值了，\n" +
            "        你加的是「新 + 旧」⇒ 结果全错。\n" +
            "        （和 0/1 背包那个逆序是同一类道理：**别用这一轮刚写进去的数**。）\n" +
            "      ⚠ 第 n 行有 **n+1** 个数：第 0 行 1 个、第 20 行 21 个。\n" +
            "      ⚠ 第 20 行第 10 个数是 C(20,10) = 184756 —— 这就是它和组合数的关系。\n" +
            "      ⚠ 类型要用 long long：第 20 行的和是 2²⁰ = 1048576，个别数到 184756，\n" +
            "        虽然还没超 int，但再往下几行（第 30 行最大 155117520）就很危险了。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
}
