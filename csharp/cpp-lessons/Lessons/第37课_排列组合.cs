    public static string 参考答案 => """
// 第 37 课参考答案：排列、组合、杨辉三角

long long 排列数(int n, int k) {
    // P(n,k) = n × (n-1) × … × (n-k+1)，一共乘 k 个数
    long long 果 = 1;
    for (int i = 0; i < k; i++) {
        果 *= (n - i);
    }
    return 果;          // k = 0 时循环不进 ⇒ 返回 1（空着也算 1 种），正确
}

long long 组合数(int n, int k) {
    if (k < 0 || k > n) return 0;      // 挑不出 k 个
    if (k > n - k) k = n - k;          // C(n,k) = C(n,n-k)：用小的那一半，少乘几次

    long long 果 = 1;
    for (int i = 0; i < k; i++) {
        // ⚠ 先乘后除，顺序不能反 —— 先除往往除不尽（整数除法丢小数）
        果 = 果 * (n - i) / (i + 1);
    }
    return 果;
    // ⚠ 不能写成 阶乘(n) / (阶乘(k) * 阶乘(n-k))：
    //   30! 和 50! 早就超出 long long，溢出之后再相除得到的是垃圾
    //   （实测 n=50 给出 0、n=30 给出 9）。
}

std::vector<long long> 杨辉行(int n) {
    std::vector<long long> 行 = {1};          // 第 0 行
    for (int i = 0; i < n; i++) {             // 再往下推 n 行
        行.push_back(0);                       // 末尾补一个 0（新的右边界）
        // ⚠ 必须**倒着**更新：这样 行[j-1] 用到的还是上一行的旧值
        for (int j = (int)行.size() - 1; j >= 1; j--) {
            行[j] = 行[j] + 行[j - 1];
        }
    }
    return 行;
}
""";

