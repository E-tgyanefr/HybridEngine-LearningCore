// 第 25 课：二分查找 —— 在有序数组里一次砍掉一半
//
// ══ 这一课要教什么 ══
// 在一排**已经排好序**的数里找一个数，最笨的办法是从头看到尾（O(n)）。
// 二分查找的样子完全不同：看中间那个，比目标大就往左半边找、小就往右半边找 ——
// 每次把范围**砍掉一半**，100 万个数的数组只要 20 次比较。
//
// 这一课的难点不在"看懂"，而在**边界**：
//   · `while (低 <= 高)` 还是 `while (低 < 高)`？
//   · `低 = 中` 还是 `低 = 中 + 1`？
// 写错任何一个，轻则答案偏一格，重则**死循环**（本机实测：编译通过、没有警告，
// 然后程序永远卡在那儿，运行器 60 秒后报超时）。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**必须是真二分，不许从头到尾线性扫。**
//   计时抓不住线性扫（10 万个元素也就几百微秒），所以用两条腿：
//     ① 文本：函数体里必须有折半的形状（`/ 2` 或 `>> 1`）—— 抓"明显没折半"的；
//     ② 行为：**返回到第一个**的下标（`下界` 语义）—— 顺手把边界写对。
//   另外喂了空数组、单元素、目标在两端、目标比全都小/全都大这几组，
//   把"差一格"的错误全逼出来。
// 核心检查点二：**不许调库**（std::lower_bound / binary_search / bsearch）——
//   这一课练的就是手写那段 while。
//
// ⚠ 给维护者：`中 = 低 + (高 - 低) / 2` 比 `(低 + 高) / 2` 安全
//   （后者在两个数都接近 int 上限时会溢出成负数）—— 模板里讲了，但不强制。

