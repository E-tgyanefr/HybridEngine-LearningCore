    [检查说明("★ 必须是真二分：函数体里要有「折半」的写法")]
    public static CheckResult 检查_真的二分(string 代码)
    {
        // ⚠ 核心检查点之一。计时抓不住线性扫（10 万个数也就几百微秒），
        //   所以这一条看源码形状：折半一定会有 `/ 2` 或 `>> 1`。
        //   判据故意宽松 —— 只抓"明显没折半"的实现。
        string 净 = 去掉注释(代码);
        var 缺 = new List<string>();
        foreach (var 名 in new[] { "二分查找", "下界" })
        {
            string 体 = 函数体(净, 名);
            if (体 == null) { 缺.Add("      " + 名 + "：找不到函数体（花括号配对了吗？）"); continue; }
            bool 折半 = 体.Contains("/ 2") || 体.Contains("/2") || 体.Contains(">> 1") || 体.Contains(">>1");
            if (!折半) 缺.Add("      " + 名 + "：函数体里没有看到折半的写法（`/ 2`）");
        }
        if (缺.Count == 0)
            return CheckResult.过("两个函数里都有折半 —— 是二分");

        return CheckResult.不过(
            "检查了去掉注释后的源码：\n" + string.Join("\n", 缺) + "\n" +
            "      二分的灵魂就是**每次把范围砍掉一半**：\n" +
            "          int 中 = 低 + (高 - 低) / 2;      ← 取中间\n" +
            "          … 根据 数[中] 和 目标 比大小，扔掉一半 …\n" +
            "      如果是从头到尾扫一遍（`for (i = 0; i < 长度; i++)`），\n" +
            "      答案虽然也对，但那不是二分 —— 100 万个数时它要 100 万次，\n" +
            "      二分只要 20 次。这一课要练的正是「砍一半」这个想法。");
    }

    [检查说明("★ 不许用 std::lower_bound / binary_search 交差")]
    public static CheckResult 检查_没用库函数(string 代码)
    {
        // ⚠ 核心检查点之二：`std::lower_bound` 就是标准库替你写的这一课，
        //   调它答案全对，但边界那一课就白上了。
        string 净 = 去掉注释(代码);
        var 用了 = new List<string>();
        foreach (var 名 in new[] { "std::lower_bound", "lower_bound(", "std::upper_bound", "upper_bound(",
                                   "std::binary_search", "binary_search(", "bsearch", "equal_range" })
        {
            if (净.Contains(名)) 用了.Add(名);
        }
        if (用了.Count == 0)
            return CheckResult.过("源码里没有现成的二分 —— 是自己写的");

        return CheckResult.不过(
            "源码里用到了现成的二分：" + string.Join("、", 用了) + "\n" +
            "      `std::lower_bound(数, 数 + 长度, 目标)` 返回的是**位置（指针）**，\n" +
            "      要 `lower_bound(...) - 数` 才是下标；全都比目标小时它返回 `数 + 长度`。\n" +
            "      这些正是这一课要你自己想清楚的东西 —— 先手写一遍，\n" +
            "      知道边界为什么是那样，以后用库函数才不会用错。");
    }

