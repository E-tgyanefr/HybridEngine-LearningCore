    public static string 参考答案 => """
// 参考答案 —— 手写二分

// 1. 二分查找：返回**第一次出现**的下标（等价于 std::lower_bound 的语义）
//    写法：命中时别停，继续往左缩 —— 这样等循环结束时 低 就是第一个位置
//    区间约定：**[低, 高)**，两头分别是 0 和 长度
int 二分查找(const int 数[], int 长度, int 目标) {
    int 低 = 0, 高 = 长度;
    while (低 < 高) {
        int 中 = 低 + (高 - 低) / 2;      /* ⚠ 不用 (低+高)/2，免得两个大数相加溢出 */
        if (数[中] < 目标) {
            低 = 中 + 1;                  /* ⚠ 是 中 + 1，写成 中 会死循环 */
        } else {
            高 = 中;                      /* 数[中] >= 目标 ⇒ 答案在左边（含 中 自己） */
        }
    }
    if (低 < 长度 && 数[低] == 目标) {
        return 低;                        /* 找到了：低 就是第一次出现的位置 */
    }
    return -1;                            /* 低 == 长度，或者 数[低] > 目标 ⇒ 没有 */
}

// 2. 下界：第一个 ≥ 目标 的位置；全都比目标小就返回 长度
//    和上面几乎是同一段 —— 区别只在于**不检查"相等"**
int 下界(const int 数[], int 长度, int 目标) {
    int 低 = 0, 高 = 长度;
    while (低 < 高) {
        int 中 = 低 + (高 - 低) / 2;
        if (数[中] < 目标) {
            低 = 中 + 1;
        } else {
            高 = 中;
        }
    }
    return 低;
}
""";

