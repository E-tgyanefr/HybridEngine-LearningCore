            "      头插的三步（顺序不能换）：\n" +
            "          结点* 新结点 = new 结点(值);\n" +
            "          新结点->下一个 = 头;        ← 先接上老的链子\n" +
            "          头 = 新结点;                ← 再改头指针\n" +
            "      ⚠ 参数必须是 `结点*& 头`（指针的引用）。\n" +
            "        写成 `结点* 头` 的话，函数里改的只是一份副本，\n" +
            "        外面的头还是 nullptr —— **转数组会得到空的结果**，而且一个警告都没有。\n" +
            "      转数组就是顺着走一圈：\n" +
            "          for (结点* p = 头; p != nullptr; p = p->下一个) 出.push_back(p->值);\n" +
            "      ⚠ 循环条件用 `p != nullptr`，别写成 `p->下一个 != nullptr`（那会漏掉最后一个）。");
    }

    [检查说明("查找：链里有的、没有的、空链")]
    public static CheckResult 检查_查找(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 错 = new List<string>();
        string 一 = 取值(run, "找2");
        string 二 = 取值(run, "查30");

        if (一 != "10")
            错.Add("      查找(头,2) 和 查找(头,9) 得到 [" + 显示(一) + "]，应该是 [10] ——\n" +
                   "        2 在链里（返回 1），9 不在（返回 0）");
        if (二 != "11")
            错.Add("      链 30→20→10 里查 30 和 10 得到 [" + 显示(二) + "]，应该是 [11] ——\n" +
                   "        两个都在链里");

        if (错.Count == 0) return CheckResult.过("查找在「有 / 没有」两种情况下都对");

        return CheckResult.不过(
            "查找的结果不对：\n" + string.Join("\n", 错) + "\n" +
            "      查找要**走完整条链**，走到 nullptr 才算没有：\n" +
            "          for (结点* p = 头; p != nullptr; p = p->下一个)\n" +
            "              if (p->值 == 值) return true;\n" +
            "          return false;\n" +
            "      ⚠ 常见错法：循环条件写成 `p->下一个 != nullptr`，\n" +
            "        那样**最后一个结点永远不会被查到**（10 在链尾，就会查不到）。");
    }

    [检查说明("★ 核心：删值——删中间、删头、删不存在的、删空链")]
    public static CheckResult 检查_删值(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 错 = new List<string>();
        string 一 = 取值(run, "删2");
        string 二 = 取值(run, "删后");
        string 三 = 取值(run, "删头");
        string 四 = 取值(run, "删头后");
        string 五 = 取值(run, "清空");
        string 六 = 取值(run, "空表删");
        string 七 = 取值(run, "单个删");

        if (一 != "10")
            错.Add("      链 1→2→3 上删两次 2，返回 [" + 显示(一) + "]，应该是 [10] ——\n" +
                   "        第一次删到了（1），第二次链里已经没有 2 了（0）");
        if (二 != "1,3,")
            错.Add("      删掉 2 之后链应该是 [1,3,]，实际 [" + 显示(二) + "]");
        if (三 != "1")
            错.Add("      删头结点 1 应当返回 1，实际 [" + 显示(三) + "]");
        if (四 != "3,")
            错.Add("      删掉头结点之后链应该只剩 [3,]，实际 [" + 显示(四) + "] ——\n" +
                   "        删的正好是头的时候，要改的是**头指针本身**");
        if (五 != "11")
            错.Add("      删掉最后一个结点后，头应当变成 nullptr，实际 [" + 显示(五) + "]");
        if (六 != "0")
            错.Add("      在**空链**上删值应当返回 0（什么都没删），实际 [" + 显示(六) + "]");
        if (七 != "11")
            错.Add("      只有一个结点的链，删掉它之后头应当是 nullptr，实际 [" + 显示(七) + "]");

        if (错.Count == 0)
            return CheckResult.过("删值六种情况都对：删中间、删头、删尾、删不存在的、空链、单结点链");

        return CheckResult.不过(
            "删值的结果不对：\n" + string.Join("\n", 错) + "\n" +
            "      删一个结点要有**两个指针**一起走：前一个、当前。\n" +
            "      找到之后分两种情况：\n" +
            "          前一个 == nullptr  ⇒ 删的正是头结点 ⇒ 头 = 当前->下一个;\n" +
            "          否则              ⇒ 前一个->下一个 = 当前->下一个;\n" +
            "      然后才 delete 当前;（⚠ 先挪链子再 delete，顺序反了就是访问已释放的内存）\n" +
            "      走到底没找到 ⇒ return false，链子一个字节都不动。\n" +
            "      空链上删：`头` 是 nullptr，循环一次都不进 ⇒ 直接 return false —— 不能崩。");
    }

    [检查说明("★ 核心：真的用了指针（不能拿数组假装链表）")]
    public static CheckResult 检查_用了指针(string 代码)
    {
        // 这一条只能看源码：数组下标模拟的解法**输出逐字节正确**，
        // 但一个指针都没用 —— 这一课就白上了。
        bool 有指针 = 代码.Contains("->") || 代码.Contains("nullptr") || 代码.Contains("*&");
        bool 有new = System.Text.RegularExpressions.Regex.IsMatch(代码, @"\bnew\b");

        if (有指针 && 有new) return CheckResult.过("用了结点指针和 new —— 是真的在链内存上操作");
        if (有指针) return CheckResult.过("用了结点指针（-> / nullptr）");

        return CheckResult.不过(
            "代码里没看到结点指针的痕迹（既没有 `->` 也没有 `nullptr`）。\n" +
            "      这一课要练的是**用指针把分开的小块串起来**这件事本身。\n" +
            "      用数组加下标（`数据[i]` 前移后移）能算出一样的输出，\n" +
            "      但那练的是数组，不是链表 —— 而且它把链表的优点全丢了：\n" +
            "          数组在下标 0 处插一个，要把**后面所有元素**往后搬\n" +
            "          链表在头部插一个，只改**两根指针**\n" +
            "      写法：\n" +
            "          结点* 新结点 = new 结点(值);\n" +
            "          新结点->下一个 = 头;\n" +
            "          头 = 新结点;\n" +
            "      ⚠ `->` 是「顺着指针去找那个结构体里的成员」，\n" +
            "        相当于 `(*新结点).下一个` —— 指针用 `.` 会编译不过。");
    }

    [检查说明("★ 核心：删掉结点时要 delete（只挪指针会内存泄漏）")]
    public static CheckResult 检查_记得delete(string 代码)
    {
        // ⚠ 这一条也只能看源码：只挪指针不 delete 的版本
        //   **输出跟正确解一模一样**，-O1 -Wall 也一句警告都没有（我实测过）。
        //   但每删一个结点就泄漏一块内存 —— 这是真的 bug，不该判过。
        if (System.Text.RegularExpressions.Regex.IsMatch(代码, @"\bdelete\b"))
            return CheckResult.过("删结点时用到了 delete —— 没有泄漏内存");

        return CheckResult.不过(
            "代码里没有 delete。\n" +
            "      `new` 借来的内存要**自己还**。只把链子跨过去、不 delete 那个结点，\n" +
            "      程序会照常跑、输出也完全正确 —— 但每删一个结点就漏掉一块内存。\n" +
            "      这就是所谓的**内存泄漏**：跑得越久，占的内存越多，最后被系统杀掉。\n" +
            "      ⚠ 编译器**不会**提醒你这件事：-O1 -Wall 一句警告都没有。\n" +
            "      （我实测过一个只挪指针不 delete 的版本，输出跟正确解逐字节相同。）\n" +
            "      正确顺序是**先挪链子，再 delete**：\n" +
            "          前一个->下一个 = 当前->下一个;   // 先把链子跨过去\n" +
            "          delete 当前;                     // 再还内存\n" +
            "      反过来写（先 delete 再读 当前->下一个）就是访问已经还回去的内存。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
}
