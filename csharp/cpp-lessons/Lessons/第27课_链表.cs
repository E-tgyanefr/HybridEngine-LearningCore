    public static string 参考答案 => """
// 第 27 课参考答案：单链表

void 头插(结点*& 头, int 值) {
    结点* 新结点 = new 结点(值);      // ① 造一块新的
    新结点->下一个 = 头;              // ② 新块的链子接到**原来的头**上
    头 = 新结点;                      // ③ 头指针改指向新块
    // ⚠ 参数是 `结点*&`：头指针本身要被改，得让调用方看得见
}

bool 删值(结点*& 头, int 值) {
    结点* 前一个 = nullptr;           // 头结点没有前一个，所以从 nullptr 开始
    结点* 当前 = 头;
    while (当前 != nullptr) {
        if (当前->值 == 值) {
            if (前一个 == nullptr) {
                头 = 当前->下一个;    // 删的是头：改头指针本身
            } else {
                前一个->下一个 = 当前->下一个;   // 把链子跨过"当前"
            }
            delete 当前;              // ⚠ 挪完链子再 delete，顺序不能反
            return true;
        }
        前一个 = 当前;
        当前 = 当前->下一个;
    }
    return false;                     // 走到底都没找到
}

bool 查找(结点* 头, int 值) {
    for (结点* p = 头; p != nullptr; p = p->下一个) {
        if (p->值 == 值) return true;
    }
    return false;
}

std::vector<int> 转数组(结点* 头) {
    std::vector<int> 出;
    for (结点* p = 头; p != nullptr; p = p->下一个) {
        出.push_back(p->值);
    }
    return 出;
}
""";

