//
// ─────────────────────────────────────────────────────
//  先介绍：数组和链表，差在哪
// ─────────────────────────────────────────────────────
//
//   数组：   [10][20][30][40]       四个格子**挨着**摆在内存里
//           找第 3 个 → 首地址 + 3 × 4 字节，一步就算出来
//           往中间插一个 → **后面的全都要往后搬**
//
//   链表：   [10|*]→[20|*]→[30|*]→[40|/]     四个小块**散布**在内存里
//           找第 3 个 → 得从头一个一个走
//           往中间插一个 → **只改两根指针**，别的一个都不用动
//
// 一句话：**数组擅长「按下标找」，链表擅长「在中间插和删」**。
//
// ─────────────────────────────────────────────────────
//  一、结点长什么样
// ─────────────────────────────────────────────────────
//
//     struct 结点 {
//         int   值;       存数据
//         结点* 下一个;   存「下一个结点在哪」  ← 链子就是它
//     };
//
// ⚠ 这个 struct 里出现了「结点」自己的名字。C++ **允许**这样写，
//   因为 `结点*` 只是一个地址，多大都是 8 字节，编译器不需要先知道完整大小。
//   （写成 `结点 下一个;` 就不行 —— 那会变成无限大的东西。见下面那个坑。）
//
// 链表用「头指针」表示整条链：
//
//     结点* 头 = nullptr;       nullptr = 空链（一个结点都没有）
//
// 最后一个结点的 `下一个` 是 **nullptr**，它就是「链到头了」的标志。
//
// ─────────────────────────────────────────────────────
//  二、头插：把新结点放到最前面
// ─────────────────────────────────────────────────────
//
//     void 头插(结点*& 头, int 值) {
//         结点* 新结点 = new 结点(值);    ① 造一个新块
//         新结点->下一个 = 头;            ② 新块的链子指向**原来的头**
//         头 = 新结点;                    ③ 头指针改指向新块
//     }
//
// ⚠ ③ 必须在 ② **之后**。反过来的话你先丢了原来的头，那条链就再也找不到了。
//
// ⚠ 参数是 `结点*&`（指针的引用）而不是 `结点*`：
//   头插会**改变头指针本身**，得让调用方也看到这个改动。
//   写 `结点* 头` 的话，函数里改的只是副本，外面那条链一点没变 ——
//   这是本课最隐蔽的一类错（见下面那个坑）。
//
// 三步走一遍（头 = nullptr，插 3、2、1）：
//
//     插 3：新(3)->下一个 = nullptr；  头 = 新(3)       链：3
//     插 2：新(2)->下一个 = 3；        头 = 新(2)       链：2 → 3
//     插 1：新(1)->下一个 = 2；        头 = 新(1)       链：1 → 2 → 3
//
// ⇒ 头插是「后插的在前」—— 想要 1,2,3 的顺序，就得**倒着**插。
//
// ─────────────────────────────────────────────────────
//  三、删值：改链子要顾**两头**
// ─────────────────────────────────────────────────────
//
// 要删掉「值 == 目标」的那个结点，得知道它的**前一个**在哪：
//
//     前一个->下一个 = 当前->下一个;     把链子从当前身上**跨过去**
//     delete 当前;                       再释放这一块
//
// ⚠ 顺序不能反：先 delete 之后再读 `当前->下一个`，读的是已经还回去的内存。
//
// 有两种特殊情况要分开处理：
//
//     ① 删的是**头结点** → 没有「前一个」，得改头指针本身：头 = 当前->下一个;
//     ② 链里**没有**这个值 → 走到底也没找到，返回 false，什么都不动
//
// 用「前一个 / 当前」两个指针一起走的写法：
//
//     结点* 前一个 = nullptr;
//     结点* 当前 = 头;
//     while (当前 != nullptr) {
//         if (当前->值 == 值) { ...; return true; }
//         前一个 = 当前;
//         当前 = 当前->下一个;
//     }
//     return false;      走到这儿说明没找到
//
// ─────────────────────────────────────────────────────
//  四、遍历：顺着链子走到底
// ─────────────────────────────────────────────────────
//
//     for (结点* p = 头; p != nullptr; p = p->下一个) {
//         // 用 p->值
//     }
//
// ⚠ 循环条件是 `p != nullptr`，**不是** `p->下一个 != nullptr` ——
//   后者会漏掉最后一个结点。
//
// ─────────────────────────────────────────────────────
//  五、双链表：多一根往回指的链子
// ─────────────────────────────────────────────────────
//
//     struct 双结点 {
//         int     值;
//         双结点* 前一个;
//         双结点* 下一个;
//     };
//
// 好处：给一个结点，能**往回走**（单链表不能）。
// 代价：每次插入/删除要改**四根**指针而不是两根，漏一根链子就断了。
// 本课不要求写双链表，知道「拿空间换能往回走」就够了。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：参数漏了那个 &（改的是副本）
// ─────────────────────────────────────────────────────
//
//     void 头插(结点* 头, int 值) {        ← 少了一个 &
//         结点* 新结点 = new 结点(值);
//         新结点->下一个 = 头;
//         头 = 新结点;
//     }
//
// 你会看到：**编译完全通过、没有任何警告、程序也不崩** ——
//   但主程序里的 `头` 永远是 nullptr，转数组出来是**空的**。
//
// 为什么：C++ 默认**按值传参**。`头` 传进去的是那个地址的一份**副本**，
//   函数里 `头 = 新结点;` 改的是副本；函数一返回，副本就没了，
//   外面那个 `头` 一个字节都没动。而 `new` 出来的那块内存**再也找不到**了
//   （这叫内存泄漏）。
//
// ⇒ 凡是「要改调用方那个指针本身」的函数，参数写 `结点*&`（指针的引用）。
//   只读不改的（查找、转数组）写 `结点*` 就够了。
//
// ─────────────────────────────────────────────────────
