// 第 27 课：链表 —— 用指针把一个个结点串起来
//
// ══ 这一课要教什么 ══
// 数组的每个格子是**挨在一起**的，靠下标找；链表是**一个个分开的小块**，
// 靠指针找。所以链表插入不用搬家（数组要挪后面所有元素），
// 但丢掉头指针就丢掉整条链。
//
// 这一课真正要建立的是「**改链子的时候要顾两头**」这个动作：
//   删掉 p 要先把**前一个结点**的指针改到 p 的后继，再 delete p。
//   顺序反了（先 delete 再改）就是访问已经释放的内存。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：检查_非写死 —— 结点值故意用 4/7 这种「不在 1~3 里」的数，
// 而且三组输入的头插结果各不相同。写死 1、2、3 的解法当场露馅。
// 另一条 检查_用了指针 防「拿数组假装链表」：那解法输出**完全正确**，
// 但一个指针、一次 new 都没有 —— 这一课就白上了。
// 反面测试（都跑过）：
//   · 数组下标模拟（输出全对，但 new/delete/-> 一个都没有）→ 被 检查_用了指针 抓住
//   · 删值只挪指针不 delete（输出全对，内存泄漏）→ 被 检查_记得delete 抓住
//     ⚠ 这一条只能靠文本看：-O1 -Wall 对内存泄漏一点反应都没有。
//       我实测过一个只挪指针不 delete 的版本，输出跟正确解**逐字节相同**。

