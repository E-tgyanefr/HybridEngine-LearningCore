                        "没有找到「" + 名 + "」这个函数。\n" +
                        "      本课要的两个签名是：\n" +
                        "          std::vector<int> 最短路(std::vector<std::vector<std::pair<int,int>>> 图, int 起)\n" +
                        "          int 单点最短路(std::vector<std::vector<std::pair<int,int>>> 图, int 起, int 终)\n" +
                        "      ⚠ 图的类型是**两层 vector 套 pair**：\n" +
                        "        `vector<vector<pair<int,int>>>` —— 每个邻居还要带一条边长。");
            }
            return CppCheck.编译失败说明(run);
        }
        return CheckResult.过("两个函数都能正常调用");
    }

    [检查说明("★ 核心：七张图的整张距离表（权重不能忽略）")]
    public static CheckResult 检查_距离表(string 代码)
    {
        // ⚠ 核心检查点。图5（0→1 直接边 10，绕道 0→2→1 只要 4）和图1
        //   （0→3 直接边 10，绕道 6）是专门抓「忽略权重」那种写法的：
        //   实测忽略权重的版本给出 图1=0,1,2,3、图5=0,1,1。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 用例 = new (string 标记, string 说明, string 期望)[]
        {
            ("图1",  "4 个点的环，0→3 直接边 10 但绕道只有 6", "0,1,3,6"),
            ("图2",  "5 个点的图",                            "0,2,1,4,7"),
            ("图3",  "两块互不相通（0-1 一块、2-3 一块）",   "0,5,-1,-1"),
            ("图4",  "一条 0-1-2-3-4-5 的链",                "0,1,2,3,4,5"),
            ("图4b", "同一条链，从 5 出发（反着走）",        "5,4,3,2,1,0"),
            ("图5",  "0→1 直接边是 10，但绕道 0→2→1 只要 4", "0,4,3"),
            ("图6",  "只有一个点，没有边",                   "0"),
        };

        var 错 = new List<string>();
        foreach (var (标记, 说明, 期望) in 用例)
        {
            string 得到 = 取值(run, 标记);
            if (得到 == null)
            {
                错.Add("      " + 说明 + "：程序没有给出结果（多半是崩了）");
                continue;
            }
            if (得到 != 期望)
                错.Add("      " + 说明 + "：得到 [" + 显示(得到) + "]，应当是 [" + 期望 + "]");
        }

        if (错.Count == 0)
            return CheckResult.过("七张图的整张距离表都对（含不连通图的 -1、反着走的链）");

        return CheckResult.不过(
            "最短距离不对：\n" + string.Join("\n", 错) + "\n" +
            "      ⚠ 如果结果**偏小、而且正好等于「边数」**（比如图1 给出 0,1,2,3、\n" +
            "        图5 给出 0,1,1），那是把**边权丢掉了** —— 用的是第 30/35 课的 BFS。\n" +
            "        BFS 的「每条边算 1 步」只在**无权图**上成立。\n" +
            "        本课图5 的例子：0→1 直接边是 10，绕道 0→2→1 只要 3+1=4，\n" +
            "        正确答案是 **4** 而不是 1。\n" +
            "      Dijkstra 的骨架：\n" +
            "          const int 无穷 = 1000000000;\n" +
            "          std::vector<int> 距(n, 无穷);  距[起] = 0;\n" +
            "          // 小根堆，first 放距离\n" +
            "          std::priority_queue<std::pair<int,int>, std::vector<std::pair<int,int>>,\n" +
            "                              std::greater<std::pair<int,int>>> 堆;\n" +
            "          堆.push({0, 起});\n" +
            "          while (!堆.empty()) {\n" +
            "              auto [d, u] = 堆.top(); 堆.pop();\n" +
            "              if (d > 距[u]) continue;            // ⚠ 跳过过期记录\n" +
            "              for (auto [v, w] : 图[u])\n" +
            "                  if (d + w < 距[v]) { 距[v] = d + w; 堆.push({距[v], v}); }\n" +
            "          }\n" +
            "      ⚠ 走不到的点最后要换成 **-1**（图3 里 2、3 号点就是这样）。\n" +
            "      ⚠ 「无穷」别用 int 最大值：最大值 + 边权会**溢出成负数**，\n" +
            "        那个走不到的点会突然变成「最近的」，把答案全带歪。");
    }

    [检查说明("单点最短路：绕道比直达近、走不到要 -1")]
    public static CheckResult 检查_单点(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 错 = new List<string>();
        string 单 = 取值(run, "单");
        string 绕道 = 取值(run, "绕道");

        if (单 != "7,-1,-1,0")
            错.Add("      四组得到 [" + 显示(单) + "]，应当是 [7,-1,-1,0]\n" +
                   "        （图2 的 0→4、图3 的 0→3（走不到）、图3 的 0→2（走不到）、\n" +
                   "          图6 的 0→0（自己到自己，0 步））");
        if (绕道 != "4")
            错.Add("      0→1 绕道那一问得到 [" + 显示(绕道) + "]，应当是 4\n" +
                   "        （0→1 直接边是 10，绕道 0→2→1 只要 3+1 = 4）");

        if (错.Count == 0)
            return CheckResult.过("单点最短路都对（含绕道更近、走不到 -1、自己到自己 0）");

        return CheckResult.不过(
            "单点最短路不对：\n" + string.Join("\n", 错) + "\n" +
            "      最直接的写法是直接调用你写的 最短路：\n" +
            "          return 最短路(图, 起)[终];\n" +
            "      ⚠ **走不到要返回 -1**，不是 0、不是无穷大。\n" +
            "      ⚠ **起点就是终点要返回 0**（原地不动也是 0）。\n" +
            "      ⚠ 如果直达的答案对了、绕道的错了：检查你有没有真的比较\n" +
            "        `距[u] + w` 和 `距[v]` —— 那是「绕道会不会更近」的判断。");
    }

    [检查说明("★ 核心：用了优先队列（O(V²) 线性扫描不算过关）")]
    public static CheckResult 检查_用了堆(string 代码)
    {
        // ⚠ 第二个核心检查点。"每轮线性扫描找最小"的写法**结果全对**
        //   （实测与参考解逐字节相同），但它不是这一课要考的写法，
        //   而且在 1000 个点上慢 10 倍、10000 个点上慢 300 倍。
        if (代码.Contains("priority_queue"))
            return CheckResult.过("用了 std::priority_queue —— O((V+E) log V)");

        bool 自己写堆 = System.Text.RegularExpressions.Regex.IsMatch(代码, @"(上浮|下沉|sift|堆化|build_heap|push_heap|pop_heap|make_heap)");
        if (自己写堆)
            return CheckResult.过("自己实现了堆操作（push_heap / make_heap 等）");

        return CheckResult.不过(
            "代码里没看到优先队列。\n" +
            "      这一课要练的是「**每次 O(log n) 挑出距离最小的点**」：\n" +
            "          std::priority_queue<std::pair<int,int>,\n" +
            "                              std::vector<std::pair<int,int>>,\n" +
            "                              std::greater<std::pair<int,int>>> 堆;\n" +
            "          // pair 先比 first ⇒ 把**距离**放在 first、结点号放 second\n" +
            "          堆.push({0, 起});\n" +
            "          while (!堆.empty()) {\n" +
            "              auto [d, u] = 堆.top(); 堆.pop();\n" +
            "              if (d > 距[u]) continue;      // 跳过过期记录\n" +
            "              ...松弛图[u]的每条边...\n" +
            "          }\n" +
            "      ⚠ 如果你的写法是「每一轮扫描一遍所有点，找 距 最小的那个」，\n" +
            "        答案**是对的**，但那是 O(V²)：\n" +
            "            10 个点、20 条边         100 次操作\n" +
            "            1000 个点、10000 条边    100 万次\n" +
            "            10000 个点、20000 条边   1 亿次      ← 而堆只要约 28 万次\n" +
            "        竞赛题的规模基本都要求堆版本，所以这一课就把它练熟。\n" +
            "      ⚠ 另外那个 `if (d > 距[u]) continue;` 不能省 ——\n" +
            "        同一个点可能被 push 好几次（每次改小了就 push 一条），\n" +
            "        少了这一句，旧的（更长的）距离会把新的覆盖掉。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
