    public static string 参考答案 => """
// 第 39 课参考答案：Dijkstra（优先队列版）

std::vector<int> 最短路(std::vector<std::vector<std::pair<int,int>>> 图, int 起) {
    int n = (int)图.size();
    // ⚠ 「无穷」取 10 亿，不要用 int 最大值 —— 最大值 + 边权会溢出成负数
    const int 无穷 = 1000000000;

    std::vector<int> 距(n, 无穷);
    距[起] = 0;

    // 小根堆：pair 先比 first（距离），所以把**距离**放在 first
    std::priority_queue<std::pair<int,int>,
                        std::vector<std::pair<int,int>>,
                        std::greater<std::pair<int,int>>> 堆;
    堆.push({0, 起});

    while (!堆.empty()) {
        auto [d, u] = 堆.top();
        堆.pop();
        // ⚠ 过期的旧记录：我们已经有更短的了，跳过
        if (d > 距[u]) continue;

        for (auto [v, w] : 图[u]) {          // 松弛每一条边
            if (d + w < 距[v]) {
                距[v] = d + w;
                堆.push({距[v], v});          // 改小了就往堆里放一条新的
            }
        }
    }

    // 走不到的点换成 -1（题目要的表示法）
    for (int i = 0; i < n; i++) {
        if (距[i] == 无穷) 距[i] = -1;
    }
    return 距;
}

int 单点最短路(std::vector<std::vector<std::pair<int,int>>> 图, int 起, int 终) {
    return 最短路(图, 起)[终];
}
""";

