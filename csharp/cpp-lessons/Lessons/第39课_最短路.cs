//   （`auto [v, w]` 是"结构化绑定"，把 pair 拆成两个名字，C++17 的写法。）
//
// ─────────────────────────────────────────────────────────────────
//  二、Dijkstra 的想法：每次挑当前最近的那个点
// ─────────────────────────────────────────────────────────────────
//
// 维护一个数组 `距[i]` = 「目前知道的、从起点到 i 的最短距离」。
// 一开始只有起点是 0，其他都是「无穷大」（表示"还不知道怎么去"）。
//
// 然后反复做一件事：
//
//     **从还没确定的点里，挑出 `距` 最小的那个 u，把它确定下来；
//       然后用 u 去"松弛"它的每条边：**
//           if (距[u] + w < 距[v]) 距[v] = 距[u] + w;
//
// 「松弛」这个词的意思就是：**试试绕道 u 会不会更近，近了就改。**
//
// 为什么这样是对的（这是全课最该想明白的一句）：
//
//     所有边长都是**非负**的。所以「当前距最小的那个点，
//     它的距离不可能再被别的路改小了 —— 绕任何别的点过来，
//     都要先走到那个点（距离已经 ≥ 它），再加上一段非负的边，只会更大。」
//
// ⇒ 于是它一旦被"确定"，就永远不用再看它。每个点只确定一次。
//
// 手工走一遍上面那张图（起点 0，∞ 表示无穷）：
//
//     初始：距 = [0, ∞, ∞, ∞]
//     挑最小的 0 ⇒ 松弛 0 的边：距[1] = 0+1 = 1；距[3] = 0+10 = 10
//              距 = [0, 1, ∞, 10]
//     挑最小的 1 ⇒ 松弛 1 的边：距[2] = 1+2 = 3；距[0] 不变（0 < 1+1）
//              距 = [0, 1, 3, 10]
//     挑最小的 2 ⇒ 松弛 2 的边：距[3] = min(10, 3+3=6) = **6**   ← 改小了！
//              距 = [0, 1, 3, 6]
//     挑最小的 3 ⇒ 松弛 3 的边：距[0] = min(0, 6+10) = 0，不变
//     ⇒ 答案 [0, 1, 3, 6]
//
// ⚠ 注意第 4 步：如果一开始就把 0→3 的 10 **确定**下来，就再也改不成 6 了。
//   所以「确定」必须发生在**它真的是当前最小**的时候。
//
// ─────────────────────────────────────────────────────────────────
//  三、用优先队列实现：每次 O(log n) 拿到最小的
// ─────────────────────────────────────────────────────────────────
//
// 「每次都挑最小的」如果每次扫描一遍数组，要 O(n)；用**优先队列**只要 O(log n)：
//
//     #include <queue>
//
//     // 小根堆：距离小的排在最前面
//     std::priority_queue<std::pair<int,int>,
//                         std::vector<std::pair<int,int>>,
//                         std::greater<std::pair<int,int>>> 堆;
//     堆.push({距离, 结点号});
//     堆.top();    // 距离最小的那一对（只读）
//     堆.pop();    // 扔掉它（不返回东西）
//
// ⚠ pair 的比较规则是「先比 first，相同再比 second」，所以 first 放**距离**，
//   second 放**结点号** —— 这样堆顶天然就是"距离最小的那个点"。
//
// ⚠ 我们**不删除**旧的记录，而是让同一个点可能进堆好几次：
//   每次改小了 距[v] 就 push 一条新的。于是堆里会有过期的旧记录。
//   处理时加一句判断，把过期的丢掉：
//
//          auto [d, u] = 堆.top(); 堆.pop();
//          if (d > 距[u]) continue;      // 这是一条过期记录（我们已经有更短的了）
//
//   这一句不能省 —— 少了它，旧的（更长的）距离会覆盖新的（更短的）。
//
// ⚠ 每个点可能进堆多次，所以堆里最多有 **E 条**记录 ⇒ 总复杂度
//   **O((V + E) log V)**。把数字摆出来（V = 点数，E = 边数）：
//
//         图                        线性扫描 O(V²)     优先队列 O((V+E)logV)
//         10 个点、20 条边            100                约 20 × 4 = 80
//         100 个点、300 条边          10,000             约 300 × 7 = 2,100
//         1000 个点、10000 条边       1,000,000          约 10000 × 10 = 100,000
//         10000 个点、20000 条边      100,000,000        约 20000 × 14 = 280,000
//
//   ⇒ 1000 个点 10000 条边时，扫描法约 100 万次操作，优先队列约 10 万次 ——
//     差 10 倍；点再多差距还要拉开。所以竞赛里默认都写优先队列版本。
//
// ─────────────────────────────────────────────────────────────────
//  四、为什么**不能有负边**（这一节是本课的重点）
// ─────────────────────────────────────────────────────────────────
//
// Dijkstra 的全部依据是那句话：「当前距最小的点，不可能再被改小」。
// 而这句话依赖「**绕过去只会更远**」—— 也就是边长非负。
//
// 找一个负边就破功的例子（3 个点、3 条边，起点 0）：
//
//          (0) ---2--- (1)
//           |           |
//           5          -10
//           |           |
//          (2) <--------
//
//     距 初始 : [0, ∞, ∞]
//     挑 0：松弛 ⇒ 距[1] = 2，距[2] = 5       距 = [0, 2, 5]
//     挑 1（当前最小是 2）：松弛 ⇒ 1→2 的边是 **-10**
//              ⇒ 距[2] = min(5, 2 + (-10) = -8) = **-8**     ← 居然改小了！
//     挑 2（现在是 -8）：松弛 2 的边…
//     ⇒ 最终 [0, 2, -8]
//
// ⚠ **问题不在于结果错了**（这个例子恰好还能改对），而在于：
//   如果 2 号点在 1 号点之前就被"确定"了，`距[2] = 5` 就写死了，
//   后面那条 -10 的边**再也没有机会改它** —— 结果就是错的。
//   换句话说：**"确定了就不会再变"这个前提被负边打破了。**
//
// ⇒ 记住这条界线：
//     **非负边** ⇒ Dijkstra（O((V+E)logV)，最快）
//     **有负边** ⇒ 得用 Bellman-Ford / SPFA（慢一些，约 O(V×E)）
//     有**负环**（绕一圈总长是负的）⇒ 根本不存在最短路（可以一直绕下去）
//
//   本课的检查**只喂非负边**，不考负边怎么算 —— 但你必须知道为什么不能用。
//
// ─────────────────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：把"无穷大"当成能参与运算的数
// ─────────────────────────────────────────────────────────────────
//
//     const int 无穷 = 1000000000;
//     ...
//     if (距[u] + w < 距[v])          ← 距[u] 可能就是无穷
//
//     int 无穷 = 2147483647;          ← int 的最大值
//     if (距[u] + w < 距[v])          ← 无穷 + w **溢出变成负数**
//
// 你会看到（第二种）：一个走不到的点**突然变成了"很近"**，
//   因为 `2147483647 + 5` 溢出成了 `-2147483644` —— 一个极大的负数，
