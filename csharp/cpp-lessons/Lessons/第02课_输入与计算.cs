    [检查说明("数字是从输入读进来的，还是写死在代码里的")]
    public static CheckResult 检查_读的是输入(string 代码)
    {
        // 换一组输入再跑：真读了输入 → 结果跟着变；写死答案 → 结果不变。
        var (读入有问题, 读入说明) = 读入方式不对(代码);
        if (读入有问题) return 读入说明;

        var run = 跑(代码, "10 4");
        if (run.Raw.CompileFailed) return CppCheck.编译失败说明(run);
        if (run.Raw.Error != null)
            return CheckResult.不过("输入 10 4 时程序没能正常跑完：\n      " + 缩进(run.Raw.Error));

        string 输出 = 看得见的输出(run);
        string 商 = 取标签(输出, "商");
        string 平均 = 取标签(输出, "平均数");

        if (商.Length == 0 || 平均.Length == 0)
            return CheckResult.不过(
                "没有按要求的格式打印。\n" +
                $"      输入 10 4 时你的程序打印的是：\n{缩进(空则(输出))}\n" +
                "      期望是按标签写字的两行：\n" +
                "          商=2\n" +
                "          平均数=7\n" +
                "      即 std::cout << \"商=\" << ... << std::endl;");

        if (商.Trim() == "2" && 数值等于(平均, 7.0))
            return CheckResult.过("输入 10 4 得到 商=2、平均数=7 —— 数字确实来自输入");

        // 10 和 4 却算出 7 和 2 的结果 → 典型的"答案写死"
        if (商.Trim() == "3" || 数值等于(平均, 4.5))
            return CheckResult.不过(
                $"输入的是 10 4，你的程序却给出 商={商.Trim()}、平均数={平均.Trim()} —— 那是 7 和 2 的结果。\n" +
                "      也就是说数字**没从输入读进来**，是写死在代码里的。\n" +
                "      改法：让变量的值来自输入，再拿变量去算：\n" +
                "          int 甲 = 0, 乙 = 0;\n" +
                "          std::cin >> 甲 >> 乙;\n" +
                "          std::cout << \"商=\" << 甲 / 乙 << std::endl;");

        return CheckResult.不过(
            $"输入 10 4 时应该是 商=2、平均数=7，你的程序给的是 商={商.Trim()}、平均数={平均.Trim()}。\n" +
            "      检查两件事：\n" +
            "        · 两个数是不是都读进来了（std::cin >> 甲 >> 乙;）\n" +
            "        · 算的时候用的是这两条输入，还是别的数字");
    }

    [检查说明("整数除法算对了没有（7 ÷ 2 在 C++ 里是 3）")]
    public static CheckResult 检查_整数除法(string 代码)
    {
        var (读入有问题, 读入说明) = 读入方式不对(代码);
        if (读入有问题) return 读入说明;

        var run = 跑(代码, "7 2");
        if (run.Raw.CompileFailed) return CppCheck.编译失败说明(run);
        if (run.Raw.Error != null)
            return CheckResult.不过("程序没能正常跑完：\n      " + 缩进(run.Raw.Error));

        string 输出 = 看得见的输出(run);
        string 商 = 取标签(输出, "商");
        if (商.Length == 0)
            return CheckResult.不过(
                "没有找到「商=...」这一行。\n" +
                $"      输入 7 2 时你的程序打印的是：\n{缩进(空则(输出))}\n" +
                "      要打印成 std::cout << \"商=\" << 甲 / 乙 << std::endl; 的样子。");

        if (商.Trim() == "3")
            return CheckResult.过("7 / 2 = 3，整数除法算对了");

        if (数值等于(商, 3.5))
            return CheckResult.不过(
                "你的商是 3.5 —— 那是**平均数**，不是整数商。\n" +
                "      两个 int 相除，C++ 会自动把小数部分**丢掉**：7 / 2 就是 3。\n" +
                "      所以 商 这一行直接写 std::cout << 甲 / 乙; 就行，\n" +
                "      不要在前面加 double —— 加了就变成 3.5 了。\n" +
                "      （这一课就是要把这两个结果摆在一起看：同一个 7 / 2，\n" +
                "        int 版是 3，小数版是 3.5。）");

        return CheckResult.不过(
            $"输入 7 2 时，商应该是 3，你的程序给的是 {商.Trim()}。\n" +
            "      两个 int 相除的规则：**小数部分直接丢掉**（不是四舍五入）。\n" +
            "          7 / 2  →  3\n" +
            "          9 / 2  →  4\n" +
            "      顺便记住：只有除号两边**至少有一个是小数**时，才会得到小数结果。");
    }

    [检查说明("平均数是不是真的带小数（这里藏着整数除法的陷阱）")]
    public static CheckResult 检查_平均数是小数(string 代码)
    {
        // ⚠ 这一条是本课的核心检查点。
        //
        // 只测一组输入的话，把 4.5 写死也能过 —— 所以用两组。
        var (读入有问题, 读入说明) = 读入方式不对(代码);
        if (读入有问题) return 读入说明;

        var 通过 = new System.Collections.Generic.List<string>();

        foreach (var (输入, 期望) in new[] { ("7 2", 4.5), ("1 2", 1.5) })
        {
            var run = 跑(代码, 输入);
            if (run.Raw.CompileFailed) return CppCheck.编译失败说明(run);
            if (run.Raw.Error != null)
                return CheckResult.不过($"输入 {输入} 时程序没能正常跑完：\n      " + 缩进(run.Raw.Error));

            string 输出 = 看得见的输出(run);
            string 平均 = 取标签(输出, "平均数");
            if (平均.Length == 0)
                return CheckResult.不过(
                    "没有找到「平均数=...」这一行。\n" +
                    $"      输入 {输入} 时你的程序打印的是：\n{缩进(空则(输出))}\n" +
                    "      要打印成 std::cout << \"平均数=\" << 平均数变量 << std::endl; 的样子。");

            if (!数值等于(平均, 期望))
                return CheckResult.不过(
                    $"输入 {输入} 时，平均数应该是 {期望}，你的程序给的是 {平均.Trim()}。\n" +
                    "      ⚠ 十有八九踩了**整数除法**这个坑：\n" +
                    "          (甲 + 乙) / 2         // 两个 int 相除 → 小数被丢掉，9 / 2 得 4\n" +
                    "          (甲 + 乙) / 2.0       // ← 右边写成小数，才有小数结果\n" +
                    "          (double)(甲 + 乙) / 2 // ← 或者把左边转成 double\n" +
                    "      ⚠ 特别注意这一种写法**也是错的**：\n" +
                    "          double 平均数 = (甲 + 乙) / 2;\n" +
                    "      右边先按整数算出 4，再存进 double —— 存进去的仍然是 4。\n" +
                    "      记住一句话：**除号两边至少要有一个是小数，除法才按小数算。**");

            通过.Add($"{输入} → {平均.Trim()}");
        }

        return CheckResult.过($"两组输入都是小数结果（{string.Join("、", 通过)}）");
    }

    [检查说明("输入不是数字时，程序有没有发现（cin 会静默失败）")]
    public static CheckResult 检查_非法输入被拦住(string 代码)
    {
        // ⚠ 这一条是本课的核心检查点。
        //
        // 学生以为"输入了就是对的"。实际上 std::cin >> 甲 读到 abc 时：
        //   · 不抛异常、不打印任何东西、程序也不停 —— 只是把 cin 标成失败状态
        //   · int 变量会被写成 0（C++11 起的规则），所以你会拿着 0 继续算
        //   · 更麻烦的是：一旦失败，后面所有的 >> 全都**什么都不做**
        // 不检查的结果就是拿 0 去做除法 —— C++ 里整数除以 0 直接崩。
        var (读入有问题, 读入说明) = 读入方式不对(代码);
        if (读入有问题) return 读入说明;

        foreach (var 输入 in new[] { "abc", "7 abc" })
        {
            var run = 跑(代码, 输入);
            if (run.Raw.CompileFailed) return CppCheck.编译失败说明(run);

            string 可见 = 看得见的输出(run);
            string 商 = 取标签(可见, "商");

            if (run.Raw.Error != null && 是除零崩溃(run))
            {
                if (可见.Contains("输入无效"))
                    return CheckResult.不过(
                        $"输入“{输入}”时，你打印了「输入无效」，但**没有停下来**。\n" +
                        "      程序接着用 0 去做除法 —— C++ 里整数除以 0 会直接崩。\n" +
                        "      改法：打印之后加一句 return 0;（或者把后面的计算放进 else 里）：\n" +
                        "          if (!(std::cin >> 甲 >> 乙)) {\n" +
                        "              std::cout << \"输入无效\" << std::endl;\n" +
                        "              return 0;      // ← 这一句不能少\n" +
                        "          }");

                return CheckResult.不过(
                    $"输入“{输入}”时程序**崩溃**了。\n" +
                    "      原因正是这一课要讲的那个坑：\n" +
                    "        std::cin 读到非数字时**不报错、不停止** ——\n" +
                    "        它只是把 cin 标记成失败状态，把 int 变量写成 0，然后让程序继续跑。\n" +
                    "        你的程序于是拿着 0 去做除法，而 C++ 里整数除以 0 会直接崩掉。\n" +
                    "      改法：读完**立刻检查**有没有成功：\n" +
                    "          if (!(std::cin >> 甲 >> 乙)) {\n" +
                    "              std::cout << \"输入无效\" << std::endl;\n" +
                    "              return 0;\n" +
                    "          }\n" +
                    "      也可以用 std::cin.fail() 判断，效果一样。\n" +
                    "      （注意“7 abc”这种一半对一半错的情况：第一个数读到了，第二个没有。）");
            }

            if (可见.Contains("输入无效") && 商.Length == 0)
                continue;                       // 这一组输入过关，测下一组

            if (可见.Contains("输入无效") && 商.Length > 0)
                return CheckResult.不过(
                    $"输入“{输入}”时你打印了「输入无效」，但**还是把结果也算出来了**（商={商.Trim()}）。\n" +
                    "      无效输入就该到此为止：打印之后 return 0;，不要再往下算。");

            return CheckResult.不过(
                $"输入“{输入}”时，程序应该发现这不是数字并打印「输入无效」，\n" +
                $"      但你的程序打印的是：\n{缩进(空则(可见))}\n" +
                "      这就是 cin 最坑的地方：**读失败它不吭声** ——\n" +
                "        · 不抛异常、不打印任何提示，程序照常往下跑\n" +
                "        · int 变量会被写成 0（你以为读到了用户输入，其实拿到的是 0）\n" +
                "        · 而且一旦失败，后面的 >> 全都什么都不做\n" +
                "      改法：读完立刻检查：\n" +
                "          if (!(std::cin >> 甲 >> 乙)) {\n" +
                "              std::cout << \"输入无效\" << std::endl;\n" +
                "              return 0;\n" +
                "          }");
        }

        return CheckResult.过("两组非法输入都被拦住了，程序打印「输入无效」后没有再算");
    }

    // ══════════════════ 工具 ══════════════════

    /// <summary>
    /// 把学生代码里的 std::cin 换成**预置好内容的假输入流**，然后整程序编译运行。
    ///
    /// 为什么要替换，而不是真的从终端喂输入：
    ///   ① 检查必须全自动 —— 不能要求学生在跑检查时手动敲 7 2；
    ///   ② CppRunner 不重定向子进程的 stdin，真读终端会把检查卡到 60 秒超时。
    ///
    /// 替换掉名字以后，`std::cin >> 甲` 变成 `假输入 >> 甲`，
    /// 而 istringstream 的失败语义和 cin **完全一样**（失败置位、变量写 0、
    /// 后续 >> 不再生效）—— 所以这一课要考的"静默失败"照样考得出来。
    /// </summary>
    private static CppRun 跑(string 代码, string 输入)
    {
        string 改过 = Regex.Replace(代码, @"std\s*::\s*cin", "假输入");
        改过 = Regex.Replace(改过, @"\bcin\b", "假输入");
        return CppCheck.直接运行(
            "#include <sstream>\n" +
            "static std::istringstream 假输入(" + Cpp字符串(输入) + ");\n\n" + 改过);
    }

    /// <summary>没有任何读入语句时，别去运行 —— 先告诉学生要用 std::cin。</summary>
    private static (bool 有问题, CheckResult 结果) 读入方式不对(string 代码)
    {
        if (Regex.IsMatch(代码, @"\bcin\b")) return (false, CheckResult.过(""));

        if (Regex.IsMatch(代码, @"\b(scanf|getchar|gets|fgets)\b"))
            return (true, CheckResult.不过(
                "你的程序用的是 scanf 之类的 C 函数读输入，这一课要练的是 **std::cin**。\n" +
                "      改法（把 scanf(\"%d\", &甲); 换成）：\n" +
                "          int 甲 = 0;\n" +
                "          std::cin >> 甲;\n" +
                "      为什么非要换：cin 读到不对的类型**不会报错**，只把变量写成 0 ——\n" +
                "      这个「静默失败」正是这一课的重点，scanf 的坑不一样。"));

        return (true, CheckResult.不过(
            "代码里没有找到 std::cin —— 这一课要求数字**由程序读进来**，不能写在代码里。\n" +
            "      写法：\n" +
            "          int 甲 = 0;\n" +
            "          std::cin >> 甲;        // >> 的方向是「从 cin 流进 甲」\n" +
            "      注意：cin 在 std 命名空间里，要么写 std::cin，\n" +
            "      要么在文件开头写一行 using namespace std;"));
    }

    /// <summary>程序崩了而且崩在整数除零上（Windows 下退出码 -1073741676）。</summary>
    private static bool 是除零崩溃(CppRun run)
    {
        string e = run.Raw.Error ?? "";
        return e.Contains("-1073741676") || e.Contains("0xC0000094")
               || e.Contains("3221225620") || e.Contains("Floating point");
    }

    /// <summary>
    /// 找出「标签=数字」里的数字（= 也可以写成 : 、： 或空格）。
    ///
    /// 为什么不用整行严格比对：那样学生把 商=3 写成 商 = 3 就会失败，
    /// 而这一课要考的是**算得对不对**，不是空格打得对不对。
    /// </summary>
    private static string 取标签(string 输出, string 标签)
    {
        var m = Regex.Match(输出, Regex.Escape(标签) + @"\s*[=:：]?\s*(-?\d+(?:\.\d+)?)");
        return m.Success ? m.Groups[1].Value : "";
    }

    private static bool 数值等于(string 文本, double 期望) =>
        double.TryParse(文本.Trim(), System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out double v)
        && Math.Abs(v - 期望) < 1e-9;

    /// <summary>程序崩溃时 run.行 是空的，真正的输出要去 Raw.RunOutput 里找。</summary>
    private static string 看得见的输出(CppRun run) =>
        run.行.Count > 0 ? run.全部输出 : run.Raw.RunOutput;

    private static string Cpp字符串(string s) =>
        "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n") + "\"";

    private static string 空则(string s) => s.Trim().Length == 0 ? "（没有任何输出）" : s.Trim();

    /// <summary>把多行文本缩进成适合嵌进提示里的样子。</summary>
    private static string 缩进(string s) => s.Trim().Replace("\n", "\n      ");
