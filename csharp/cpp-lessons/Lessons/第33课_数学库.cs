    public static string 参考答案 => """
// 第 33 课参考答案：<cmath> 常用函数

double 幂(double 底, int 指) {
    double 果 = 1.0;
    for (int i = 0; i < 指; i++) {
        果 *= 底;
    }
    return 果;            // 指 = 0 时循环一次都不进 ⇒ 返回 1.0，正确
}

double 两点距离(double x1, double y1, double x2, double y2) {
    double 横差 = x2 - x1;
    double 纵差 = y2 - y1;
    // 两个差各自平方、相加，再开根号（勾股定理）
    return std::sqrt(横差 * 横差 + 纵差 * 纵差);
}

int 向下取整(double x) {
    return (int)std::floor(x);       // ⚠ 不是 (int)x —— 负数时两者不同
}

int 向上取整(double x) {
    return (int)std::ceil(x);
}

bool 近似相等(double a, double b) {
    // ⚠ 本课的重点：**绝不能**写成 return a == b;
    //   0.1 + 0.2 的值是 0.30000000000000004，跟 0.3 不相等。
    return std::fabs(a - b) < 1e-9;  // 1e-9 就是 0.000000001
}
