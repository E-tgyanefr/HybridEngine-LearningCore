        return CheckResult.不过(
            "迷宫步数不对：\n" + string.Join("\n", 错) + "\n" +
            "      ⚠ 如果只是**偏大**（比如 6 算成 8），那几乎可以肯定是用**栈/递归**做了 DFS。\n" +
