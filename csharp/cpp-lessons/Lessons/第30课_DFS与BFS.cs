    public static string 参考答案 => """
// 第 30 课参考答案：BFS 求迷宫最少步数
int 迷宫最少步数(std::vector<std::vector<int>> 图, int 起x, int 起y, int 终x, int 终y) {
    int 行 = (int)图.size();
    if (行 == 0 || 图[0].empty()) return -1;          // 空图
    int 列 = (int)图[0].size();

    // 起点或终点是墙 ⇒ 根本没法谈
    if (图[起x][起y] != 0 || 图[终x][终y] != 0) return -1;

    // 步数表：-1 表示"还没走到过"
    std::vector<std::vector<int>> 步(行, std::vector<int>(列, -1));
    步[起x][起y] = 0;

    // ⚠ 必须是**队列**：先进先出 ⇒ 一圈一圈往外扩 ⇒ 第一次碰到就是最短
    std::queue<std::pair<int, int>> 队;
    队.push({起x, 起y});

    int 方向[4][2] = {{1, 0}, {-1, 0}, {0, 1}, {0, -1}};

    while (!队.empty()) {
        auto [x, y] = 队.front();      // ⚠ 队用 front()，栈用 top()
        队.pop();

        if (x == 终x && y == 终y) return 步[x][y];   // 第一次走到终点就是最少步数

        for (int k = 0; k < 4; k++) {
            int nx = x + 方向[k][0];
            int ny = y + 方向[k][1];

            if (nx < 0 || nx >= 行 || ny < 0 || ny >= 列) continue;  // 越界
            if (图[nx][ny] != 0) continue;                           // 是墙
            if (步[nx][ny] != -1) continue;                          // 已经到过，别再走

            步[nx][ny] = 步[x][y] + 1;                               // 多走一步
            队.push({nx, ny});
        }
    }
    return -1;      // 队列空了还没碰到终点 ⇒ 走不到
}
""";

