            "        它钻进长管子要一路退回来，退回来时格子早被标上步数了，\n" +
            "        于是 `步[...] != -1` 直接跳过，**再也没机会改小**。\n" +
            "        求最少步数**必须用队列**：一圈一圈往外扩，第一次碰到就是最短。\n" +
            "      如果**走不到时返回的不是 -1**，检查循环结束后的那句 return。\n" +
            "      如果**原地不动返回的不是 0**，检查有没有在处理之前就返回了。\n" +
            "      如果**崩了**，检查起点/终点是墙的情况，以及 `步` 的下标越界。");
    }

    [检查说明("★ 核心：整张步数表都对（DFS 冒充 BFS 在这里露馅）")]
    public static CheckResult 检查_距离表(string 代码)
    {
        // ⚠ 本课最硬的一条：把 16 个格子的最少步数全打出来比。
        //   只比终点那一个数，DFS 有相当大概率蒙对；
        //   整张表它蒙不过去（实测 DFS 在第 12 格给出 8，正确答案是 9）。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 表 = 取值(run, "表");
        const string 期望 = "0,1,2,3,-1,-1,-1,4,8,7,6,5,9,-1,-1,6,";

        if (表 == null)
            return CheckResult.不过("没能拿到步数表 —— 程序可能在某一步崩了。");

        if (表 == 期望)
            return CheckResult.过("16 个格子的步数表全对 —— 每个格子都是真正的最少步数");

        return CheckResult.不过(
            "从 (0,0) 出发的整张步数表不对：\n" +
            "      应当是 " + 期望 + "\n" +
            "      实际是 " + 显示(表) + "\n" +
            "      这张表长这样（起点 (0,0)，# 是墙）：\n" +
            "             列  0  1  2  3\n" +
            "          行 ┌──────────────┐\n" +
            "           0 │ 0  1  2  3   │\n" +
            "           1 │ #  #  #  4   │\n" +
            "           2 │ 8  7  6  5   │\n" +
            "           3 │ 9  #  #  6   │\n" +
            "             └──────────────┘\n" +
            "      ⚠ 只有 BFS（队列）能给出「每个格子都是最少步数」。\n" +
            "        用栈/递归的 DFS 会给出「某一条路走出来的步数」，\n" +
            "        最大的区别在 (3,0) 那一格：正确答案 9（要先下到第 2 行、\n" +
            "        再往左走到底、再下一步），DFS 常常给 8（它从右边绕过去的）。\n" +
            "      ⚠ 还有一处常见错：忘了 `if (步[nx][ny] != -1) continue;`\n" +
            "        那样程序会绕圈绕到超时，或者给出乱七八糟的数。");
    }

    [检查说明("★ 用的是队列（BFS），不是栈或递归")]
    public static CheckResult 检查_用了队列(string 代码)
    {
        // 用栈 + 反复修正也能算出正确步数（那是 Bellman-Ford 的思路），
        // 但这一课要考的是 BFS —— 而且那条路在 1000×1000 的图上会慢到跑不动。
        if (代码.Contains("std::queue") || 代码.Contains("queue<"))
            return CheckResult.过("用了 std::queue —— 是宽度优先");

        bool 有栈 = 代码.Contains("std::stack") || 代码.Contains("stack<");
        if (有栈)
            return CheckResult.不过(
                "代码里用的是 **std::stack** —— 那是深度优先（DFS）。\n" +
                "      DFS 能判断「走不走得到」，但**不能求最少步数**：\n" +
                "        它一路往深处钻，钻进一条长管子后要一路退回来，\n" +
                "        退回来时那个格子早被标上步数了，于是再也没机会改小。\n" +
                "        实测同一张 4×4 的图：(0,0)→(3,3) 用栈给出 8，正确答案是 6。\n" +
                "      改法只有两处（其他代码一字不差）：\n" +
                "          std::stack<...> 容器;   ⇒   std::queue<...> 队列;\n" +
                "          容器.top() 容器.pop()   ⇒   队列.front() 队列.pop()\n" +
                "      为什么换了就对：队列是先进先出 ⇒ 先处理「近的」再处理「远的」\n" +
                "      ⇒ 一圈一圈往外扩 ⇒ **第一次碰到某个格子，那一定是最少步数**。");

        return CheckResult.不过(
            "代码里没看到队列。\n" +
            "      这一课要练的是**宽度优先搜索（BFS）**：用队列把「下一步能到的格子」\n" +
            "      排好队，先来的先处理 —— 这样就是一圈一圈往外扩。\n" +
            "          std::queue<std::pair<int,int>> 队;\n" +
            "          队.push({起x, 起y});\n" +
            "          while (!队.empty()) {\n" +
            "              auto [x, y] = 队.front();\n" +
            "              队.pop();\n" +
            "              ...\n" +
            "          }\n" +
            "      ⚠ 或者自己用数组 + 两个下标（头 head、尾 tail）手写一个先进先出的队列也行。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
}
