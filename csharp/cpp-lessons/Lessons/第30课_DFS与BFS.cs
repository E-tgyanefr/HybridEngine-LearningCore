// 第 30 课：DFS 与 BFS —— 两种走迷宫的办法
//
// ══ 这一课要教什么 ══
// 深度优先（DFS）和宽度优先（BFS）是搜索的两条腿，差别**只在用栈还是用队列**：
//   · DFS 用栈（或者递归）→ 一路走到底再回头 → **只能判「有没有路」**
//   · BFS 用队列          → 一圈一圈向外扩     → **能求「最少几步」**
// 学生最容易犯的错是「用 DFS 求最短步数」—— 它在很多迷宫上碰巧对，
// 在「必须先退回来才能走通」的迷宫上就给出偏大的数。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点有两个：
//   ① 检查_距离表：把**整张步数表**（16 个格子）打出来比。
//      这一条是「DFS 冒充 BFS」的照妖镜 —— 只比终点那一个数，
//      DFS 有相当大概率蒙对；整张表它蒙不过去（实测：DFS 给出
//        0,1,2,3,-1,-1,-1,4,8,7,6,5,8,-1,-1,6 而 BFS 是 …5,9…
//      即 (3,0) 那格 DFS 说 8、正确答案是 9）。
//   ② 检查_用了队列：BFS 必须用队列（或自己手写的先进先出）。
//      用栈/递归 + 「取最小」也能算出正确距离，但那不是 BFS 的思路。
// 迷宫形状是特意凑的：
//   形状一 4×4 要绕一大圈；形状二「只有一条长绕路」逼 DFS 走冤枉路；
//   形状三 一整堵墙把终点隔开（走不到必须返回 -1）；形状五 起点就是墙。
// 反面测试（都跑过）：
//   · 换成 std::stack → 形状一给出 8（答案 6）、形状二给出 8（答案 -1）
//   · 写死答案        → 形状二立刻错

