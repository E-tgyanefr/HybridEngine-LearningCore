    public static string 参考答案 => """
// 第 35 课参考答案：连通块 + 最短步数

int 连通块数(std::vector<std::vector<int>> 图) {
    int 结点数 = (int)图.size();
    std::vector<int> 去过(结点数, 0);     // 0 = 没来过
    int 块 = 0;

    for (int i = 0; i < 结点数; i++) {
        if (去过[i]) continue;            // 已经属于前面数过的某一块
        块++;                             // 新的一块，从 i 开始把整块走完
        std::vector<int> 栈 = {i};
        去过[i] = 1;                      // ⚠ 标记要放在"进栈时"，不是"出栈时"
        while (!栈.empty()) {
            int u = 栈.back();
            栈.pop_back();
            for (int v : 图[u]) {
                if (!去过[v]) {
                    去过[v] = 1;
                    栈.push_back(v);
                }
            }
        }
    }
    return 块;
}

int 最短步数(std::vector<std::vector<int>> 图, int 起, int 终) {
    int 结点数 = (int)图.size();
    std::vector<int> 距离(结点数, -1);    // -1 = 还没走到（顺便就是"走不到"的答案）
    距离[起] = 0;

    // ⚠ 队列（BFS）：先处理近的 → 第一次给某个点写上距离时，那就是最短的
    std::queue<int> 队;
    队.push(起);

    while (!队.empty()) {
        int u = 队.front();
        队.pop();
        if (u == 终) return 距离[u];      // 提前收工（不加这句也对，只是多跑一会儿）
        for (int v : 图[u]) {
            if (距离[v] < 0) {            // ⚠ 这一句必须在，否则有环就死循环
                距离[v] = 距离[u] + 1;
                队.push(v);
            }
        }
    }
    return 距离[终];                      // 走不到 ⇒ 还是 -1
}
""";

