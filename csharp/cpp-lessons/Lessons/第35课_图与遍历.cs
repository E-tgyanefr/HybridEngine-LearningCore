        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 块 = 取值(run, "块");
        string 链 = 取值(run, "链");
        string 辨 = 取值(run, "辨");

        var 错 = new List<string>();
        if (块 != "121121")
            错.Add("      六张图的连通块数得到 [" + 显示(块) + "]，应当是 [121121]\n" +
                   "        依次是 {{1,2},{0},{0,3},{2}}（1 块）、{{1},{0},{3},{2}}（2 块）、\n" +
                   "        {{}}（1 块）、{{1,2,3},{0},{0},{0,4},{3}}（1 块）、\n" +
                   "        {{1},{0},{2,3},{2}}（2 块）、{{1,2},{0,2},{0,1}}（1 块）");
        if (链 != null && !链.EndsWith("|1"))
            错.Add("      0-1-2-…-7 这条长链是一整块（答案是 1），实际 [" + 显示(链) + "]");
        if (辨 != null && !辨.EndsWith(",1"))
            错.Add("      分辨用的那张图也是连通的（答案是 1），实际 [" + 显示(辨) + "]");

        if (错.Count == 0)
            return CheckResult.过("六张图 + 长链 + 分辨图，块数都对");

        return CheckResult.不过(
            "连通块数不对：\n" + string.Join("\n", 错) + "\n" +
            "      算法只有一句话：**挨个点看，没来过的就从一个新块开始走一遍**。\n" +
            "          int 块 = 0;\n" +
            "          for (int i = 0; i < 结点数; i++) {\n" +
            "              if (去过[i]) continue;\n" +
            "              块++;\n" +
            "              ...从 i 出发，把能走到的点全部标上「去过」...\n" +
            "          }\n" +
            "      ⚠ 「孤立点」自己算**一块** —— {{}} 的答案是 1，不是 0。\n" +
            "      ⚠ 别用「有几个点没有邻居」来数块：一条链上每个点都有邻居，\n" +
            "        那样会得到 0，而正确答案是 1。必须真的**走进图里**去。\n" +
            "      ⚠ 标记 `去过` 要放在**进栈/进队的时候**，不能等出栈才标 ——\n" +
            "        否则同一个点会被重复压进去，大图上会爆内存。");
    }

    [检查说明("★ 核心：整张距离表 —— 每一步都必须是真正的最少步数")]
    public static CheckResult 检查_距离表(string 代码)
    {
        // ⚠ 本课最硬的一条。那张「长链 + 抄近路」的图专治用栈的写法：
        //   实测栈版本给出 0,1,5,4,3,2,1（6 离 0 被标成 5 步），
        //   正确是 0,1,2,3,3,2,1。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 表 = 取值(run, "表");
        string 长 = 取值(run, "长");

        var 错 = new List<string>();
        if (表 != "0,1,1,2,2,2")
            错.Add("      六点图的距离表得到 [" + 显示(表) + "]，应当是 [0,1,1,2,2,2]\n" +
                   "        （那张图：0 连着 1 和 2；1 连着 3 和 4；2 连着 3 和 5）");
        if (长 == null)
            错.Add("      「长链 + 抄近路」那张图没有给出结果（程序可能崩了）");
        else
        {
            string[] 段 = 长.Split('|');
            if (段.Length < 1 || 段[0] != "0,1,2,3,3,2,1")
                错.Add("      长链图从 0 出发的距离表得到 [" + 显示(段.Length > 0 ? 段[0] : null) + "]，\n" +
                       "        应当是 [0,1,2,3,3,2,1] —— 注意 6 离 0 只有 **1 步**\n" +
                       "        （0-1-2-3-4-5 是长链，同时 5-6 和 0-6 都有边）");
            if (段.Length < 2 || !段[1].StartsWith("1,"))
                错.Add("      长链图上 最短步数(图,0,6) 应当是 1（有直接边），\n" +
                       "        实际 [" + 显示(段.Length > 1 ? 段[1] : null) + "]");
        }

        if (错.Count == 0)
            return CheckResult.过("两张图的整张距离表都是真正的最少步数 —— 用的是队列（BFS）");

        return CheckResult.不过(
            "距离不对：\n" + string.Join("\n", 错) + "\n" +
            "      ⚠ 如果只是**偏大**，几乎肯定是用了**栈/递归**（DFS）。\n" +
            "        实测那张长链图：栈给出 0,1,5,4,3,2,1，队列给出 0,1,2,3,3,2,1。\n" +
            "        为什么：栈会一头扎进长链，走到 6 时给它标上 5；\n" +
            "        之后发现「0-6 有直接边」也没用了 —— `距离[6] < 0` 已经不成立，\n" +
            "        **再也没机会改小**。\n" +
            "      ⚠ 求最少步数只能用**队列**：先处理近的、再处理远的，\n" +
            "        这样第一次给某个点写上距离时，那一定就是最短的。\n" +
            "      ⚠ 如果程序**超时**：检查 `if (距离[v] < 0)` 这一层在不在。\n" +
            "        少了它，0 把 1 放进队列、1 又把 0 放进去……无限循环，永远跑不完。");
    }

    [检查说明("最短步数：走不到的、起等于终的都要对")]
    public static CheckResult 检查_边界(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 步 = 取值(run, "步");
        const string 期望 = "2,-1,2,0,-1,0,2,1";

        if (步 == 期望) return CheckResult.过("八组都对（含走不到 -1、起等于终 0、反着走也对）");

        return CheckResult.不过(
            "最短步数不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(步) + "\n" +
            "      （依次是 链图 0→3、两块图 0→3、星形图 0→4、两块图 0→0、\n" +
            "        两块图 0→3、孤立点 0→0、链图 3→0、三角形 1→2）\n" +
            "      ⚠ **起 == 终 要返回 0**（原地不动也是 0 步），不是 -1、也不是 1。\n" +
            "      ⚠ **走不到要返回 -1** —— 距离数组初始化成 -1 之后，\n" +
            "        没被更新过的点天然就是 -1，所以最后直接用 `距离[终]` 当答案就行。\n" +
            "      ⚠ 无向图是**双向**的：0→3 和 3→0 的步数必须一样。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
}
