// 第 20 课：递推 —— 从前往后一格一格填
//
// ══ 这一课要教什么 ══
// 第 11 课那个斐波那契递归：写得漂亮，但算 fib(45) 要调用自己上亿次，几十秒。
// 这一课换一种说法：**从最小的那格开始，一格一格往后填**。
//
//     表[0] = 0;  表[1] = 1;
//     for (int i = 2; i <= n; i++) { 表[i] = 表[i-1] + 表[i-2]; }
//
// 同一件事，一遍循环就完了。这就是「递推」：
// **把「答案」按从小到大的顺序存在表里，每一步用前面已经算好的格子。**
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**不许用指数级递归**。
//   学生把第 11 课的递归原样搬过来，小 n 的用例全对 —— 看不出问题。
//   防法：另喂一个稍大的 n（斐波那契(38)、爬楼梯(35)）。
//   朴素递归算 fib(38) 要几秒、fib(45) 要几十秒（运行器 60 秒超时），
//   一遍循环是瞬时的 —— 超时就是"你用了递归"的信号，提示里直说。
//   同时用文本检查：函数体里不许出现对自己的调用，必须有数组/vector 和 for。
//
// ⚠ 给维护者：标记一律「前后各出现一次」，取值只读开头标记之后到下一根竖线之前。

