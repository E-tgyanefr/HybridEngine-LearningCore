    [检查说明("★ 四个都必须是从前往后填表（数组 + 循环），不许用递归")]
    public static CheckResult 检查_没用递归(string 代码)
    {
        // ⚠ 核心检查点。第 11 课刚教完递归，学生最自然的做法就是把它搬过来 ——
        //   小 n 的用例全对，看不出任何问题。这里切开每个函数体检查：
        //   ① 有 for（填表一定是一遍循环）
        //   ② 函数体里没有对自己的调用（递归）
        string 净 = 去掉注释(代码);
        var 问题 = new List<string>();
        foreach (var 名 in new[] { "爬楼梯", "斐波那契", "斐波那契取模", "铺地砖" })
        {
            string 体 = 函数体(净, 名);
            if (体 == null) { 问题.Add("      " + 名 + "：找不到函数体（花括号配对了吗？）"); continue; }
            if (!体.Contains("for") && !体.Contains("while"))
                问题.Add("      " + 名 + "：函数体里没有循环，看不出是「从前往后填表」");
            if (体.Contains(名 + "("))
                问题.Add("      " + 名 + "：函数体里调用了自己 —— 那是递归，这一课要的是递推");
        }
        if (问题.Count == 0)
            return CheckResult.过("四个函数都是填表（有循环、没递归）");

        return CheckResult.不过(
            "检查了去掉注释后的源码：\n" + string.Join("\n", 问题) + "\n" +
            "      ⚠ 这一课的关键就是把第 11 课那个递归**换一种写法**：\n" +
            "          递归    斐波那契(n) 去问 斐波那契(n-1) 和 斐波那契(n-2) —— 同一格被反复算\n" +
            "          递推    表[i] = 表[i-1] + 表[i-2] —— 每格只算一次，从前往后\n" +
            "      写法固定是三段：\n" +
            "          ① 开一张够大的表（long long 表[64] = {0};）\n" +
            "          ② 手动填最小的那一两格（表[0]、表[1]）\n" +
            "          ③ 一个 for 从第 3 格填到第 n 格\n" +
            "      这样算 fib(45) 是瞬时的；用递归要几十秒（检查里就喂了 45）。");
    }

