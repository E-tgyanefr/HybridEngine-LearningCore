// 参考答案 —— 递推（四个都是"从前往后填表"，一遍循环）

// 1. 爬楼梯：最后一步要么从 n-1 走 1 级，要么从 n-2 走 2 级
//    ⇒ f(n) = f(n-1) + f(n-2)，f(0)=1（什么都不走也是一种走法）、f(1)=1
long long 爬楼梯(int n) {
    long long 表[64] = {0};
    表[0] = 1;
    表[1] = 1;
    for (int i = 2; i <= n; i++) {
        表[i] = 表[i - 1] + 表[i - 2];
    }
    return 表[n];
}

// 2. 斐波那契：同样的填表，只是最小的两格换成 0 和 1
long long 斐波那契(int n) {
    long long 表[64] = {0};
    表[0] = 0;
    表[1] = 1;
    for (int i = 2; i <= n; i++) {
        表[i] = 表[i - 1] + 表[i - 2];
    }
    return 表[n];
}

// 3. 斐波那契取模：每一步都取模，这样数就不会长大
//    ⚠ 加法的两个数都小于 1000000007，和最大约 2×10^9，long long 装得下
long long 斐波那契取模(int n) {
    long long 表[1005] = {0};
    表[0] = 0;
    表[1] = 1;
    for (int i = 2; i <= n; i++) {
        表[i] = (表[i - 1] + 表[i - 2]) % 1000000007;
    }
    return 表[n];
}

// 4. 铺地砖：最左边要么竖着放一块（剩 2×(n-1)），要么横着叠两块（剩 2×(n-2)）
//    ⇒ 又是 f(n) = f(n-1) + f(n-2)，铺地砖(0)=1
long long 铺地砖(int n) {
    long long 表[64] = {0};
    表[0] = 1;
    表[1] = 1;
    for (int i = 2; i <= n; i++) {
        表[i] = 表[i - 1] + 表[i - 2];
    }
    return 表[n];
}
""";

