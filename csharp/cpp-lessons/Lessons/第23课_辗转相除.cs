// 第 23 课：辗转相除 —— 求最大公约数的老办法
//
// ══ 这一课要教什么 ══
// 求两个数的最大公约数（gcd），最笨的办法是"从小的那个往下试"——
// 而两千多年前欧几里得就发现了一条捷径：
//
//     gcd(a, b) = gcd(b, a % b)        一直到 b 变成 0，答案就是 a
//
// 这一课要让学生**亲手写出这段**，并且真的相信它为什么对：
//   如果 d 能整除 a 和 b，那它一定也能整除 a % b（因为 a % b = a - k×b）——
//   反过来也一样。所以 {a, b} 和 {b, a % b} 的**公约数集合完全相同**，
//   最大公约数自然也一样。每次把两个数换小，最后必然停。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**不许用现成的库函数**（`std::gcd` / `__gcd`）。
//   调库答案全对，但这一课练的就是"手写这段递归/循环"。
//   防法：去掉注释后的源码里出现 gcd 的库调用就判不过。
// 核心检查点二：**`最小公倍数` 必须先除后乘**（`a / gcd * b`）。
//   写成 `a * b / gcd` 在 a、b 都是 10^9 量级时会溢出成负数 ——
//   检查里特意喂了一组 `long long` 装得下、`int` 装不下的数
//   （1000000007 与 1000000009，乘积约 1.0×10^18）。
//
// ⚠ 给维护者：约数的边界（0,0）(0,5)(5,0) 和负数都进用例 ——
//   特别是 `a % 0` 会崩（整数除零），这是本课最容易踩的运行时错误。

