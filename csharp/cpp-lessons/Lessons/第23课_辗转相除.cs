// ─────────────────────────────────────────────────────
//
// 「12 和 18 的最大公约数」= 6 —— 能同时整除 12 和 18 的最大的数。
// 约分（12/18 = 2/3）、分数运算、周期问题都靠它。
//
// 笨办法：从小往大试，或者从小的那个往下试。数字一大（比如都是 10^9）
// 就慢得不能用。辗转相除几行就搞定，而且快得多。
//
// ─────────────────────────────────────────────────────
//  一、辗转相除：两行递归
// ─────────────────────────────────────────────────────
//
//     long long 最大公约数(long long a, long long b) {
//         if (b == 0) { return a; }              ← 出口：除数是 0 时，答案就是被除数
//         return 最大公约数(b, a % b);            ← 换小一号：大数换小数、小数换余数
//     }
//
// 拿 (12, 18) 走一遍：
//
//     gcd(12, 18) → gcd(18, 12) → gcd(12, 6) → gcd(6, 0) → 6
//                   18%12=6      12%6=0
//
// 写成循环是同一个意思：
//
//     while (b != 0) { long long 余 = a % b; a = b; b = 余; }
//     return a;
//
// ─────────────────────────────────────────────────────
//  二、为什么它对（这一课最值得想清楚的一步）
// ─────────────────────────────────────────────────────
//
// 设 d 是 a 和 b 的公约数。那么 a % b = a - k×b（k 是整除的商）——
//   a 能被 d 整除、k×b 也能被 d 整除 ⇒ **它们的差 a % b 也能被 d 整除**。
// 反过来：d 能整除 b 和 a % b ⇒ d 也能整除 a = k×b + (a % b)。
//
// ⇒ **{a, b} 的公约数和 {b, a % b} 的公约数一模一样**，
//   最大公约数当然也一模一样。
//
// 而每次换过去，两个数都在**变小**（a % b < b）⇒ 早晚会到 b = 0。
// 到那一步时 gcd(a, 0) = a —— 因为任何数都能整除 0，a 就是最大公约数。
//
// ⚠ 顺带记住：**每一步至少缩小一半**，所以循环次数是 O(log n) ——
//   哪怕 a、b 是 10^18，也就几十步。
//
// ─────────────────────────────────────────────────────
//  三、最小公倍数：先除后乘
// ─────────────────────────────────────────────────────
//
//     a × b = gcd(a, b) × lcm(a, b)          ← 这个是数学事实
//     ⇒ lcm(a, b) = a / gcd(a, b) * b
//
// ⚠⚠ **必须先除后乘**。写成 `a * b / gcd(a, b)` 在 a、b 都是 10^9 量级时，
//   a * b 是 10^18 量级 —— 虽然 long long 装得下，但如果用 int 就会溢出，
//   而且先除后乘**在数学上完全等价**、还更安全，没有理由不这么写。
//
//   （`a / gcd(a, b)` 一定除得尽 —— 因为 gcd 就是 a 的因数。）
//
// ⚠ 边界：a 或 b 是 0 时，"最小公倍数"没有意义（0 乘任何数都是 0，
