    public static string 参考答案 => """
// 参考答案 —— 辗转相除

// 1. 递归版：两行就够。b == 0 时答案就是 a（这一行是出口，不能省）
long long 最大公约数(long long a, long long b) {
    if (a < 0) { a = -a; }              /* 负数按绝对值算 */
    if (b < 0) { b = -b; }
    if (b == 0) {
        return a;                       /* ⚠ 少了这一行，a % 0 会让程序直接崩 */
    }
    return 最大公约数(b, a % b);
}

// 2. 最小公倍数：**先除后乘**（a / gcd 一定除得尽）
//    ⚠ 写成 a * b / gcd 在 int 下会溢出；先除后乘数学上等价、还更安全
long long 最小公倍数(long long a, long long b) {
    if (a == 0 || b == 0) {
        return 0;                       /* 题目约定：有一个是 0 就返回 0 */
    }
    long long 约 = 最大公约数(a, b);
    return a / 约 * b;
}

// 3. 三个数：先求前两个，再拿结果和第三个求 —— 这一步可以一路推广到 n 个数
long long 三个数的最大公约数(long long a, long long b, long long c) {
    return 最大公约数(最大公约数(a, b), c);
}
""";

