// 第 08 课：指针与引用 —— 「改了参数，外面会不会变？」
//
// ══ 这一课要教什么 ══
// 这一课只回答一个问题，但它是 C++ 里最容易被误解的问题：
//
//      **函数里改了参数，外面到底会不会变？**
//
// 答案完全取决于参数类型，和函数体怎么写没关系：
//
//     void f(int  n)   值传递   —— 外面**不变**（函数拿到的是复制品）
//     void f(int& n)   引用     —— 外面**会变**（n 就是外面那个变量）
//     void f(int* p)   指针     —— 要用 *p 才会变（p 装的是地址）
//
// 学生的直觉通常是「传进去了，改了当然会变」—— 这一课就是要让他**亲手把
// 三个版本都跑一遍**，亲眼看到值传递改了等于没改。
//
// 顺带讲清野指针：`int* p;` 里装的是随机地址，`*p` 可能读到任何地方；
// `int* p = nullptr;` 才是「明确地什么都没指」，用之前还能判断一下。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**值传递改不动外面**（还有它的镜像：引用传递必须改得动）。
// 这两条是一对，缺一不可：
//   · 只查「引用能改外面」，学生把三个函数全写成引用也能过；
//   · 只查「值传递改不动」，学生把三个函数全写成值传递也能过。
// 所以三个函数各自有一组「调用 → 再看外面那个变量的值」的用例，
// 互相咬死。偷懒解法（把参数类型写错）必然在其中一个上翻车。
//
// 另一条防线：调用点用 `&变量` 传指针、直接传变量给引用 —— 签名写错会**编译不过**，
// 于是"类型写错"这件事根本进不到运行阶段（下面 先别急着比 里有定向提示）。
//
// ⚠ 给维护者：g++ 会把诊断信息里的中文标识符转义（\U00004e01），
//   所以只匹配 ASCII 报错片段（cannot bind / invalid conversion）。

