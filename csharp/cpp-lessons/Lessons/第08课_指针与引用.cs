    private static string 上次的代码;
    private static CppRun 上次的运行;

    private static CppRun 跑一次(string 代码)
    {
        if (上次的运行 != null && 上次的代码 == 代码) return 上次的运行;
        上次的代码 = 代码;
        上次的运行 = CppCheck.编译并运行(代码, null, 调用点);
        return 上次的运行;
    }

    private static string 先别急着比(CppRun run)
    {
        if (run.Raw.CompileFailed)
        {
            // 「引用 / 指针」这一对最容易把签名写反 —— 写反了根本编译不过，
            // 编译器会说 int* 和 int& 绑不到一起。这句提示直接给对照表。
            if (run.编译信息.Contains("cannot bind")
                || run.编译信息.Contains("invalid conversion")
                || run.编译信息.Contains("invalid initialization of reference"))
                return
                    "函数签名和题目要求对不上（编译器说：类型绑不到一起）。\n" +
                    "      这一课要四个函数，签名分别是：\n" +
                    "          void 翻倍_值(int n)              值传递\n" +
                    "          void 翻倍_引用(int& n)           引用\n" +
                    "          void 翻倍_指针(int* p)           指针\n" +
                    "          int 安全取值(int* p, int 备用值)  指针\n" +
                    "      最容易混的是**引用和指针**：\n" +
                    "          int& n   引用 —— 接的是「变量本身」，调用时不加 &： 翻倍_引用(乙)\n" +
                    "          int* p   指针 —— 接的是「地址」，调用时要加 &：    翻倍_指针(&乙)\n" +
                    "      两个都写成 int* 或都写成 int&，就编译不过了。";
            return CppCheck.编译失败说明(run).Detail;
        }
        if (run.Raw.Error != null)
            return
                "程序没跑完就退出了：" + run.Raw.Error + "\n" +
                "      这一课会跟指针打交道，最常见的原因是**解引用了空指针或野指针**：\n" +
                "          int* p;              ✗ 野指针（里面是随机地址）\n" +
                "          int* p = nullptr;    ✓ 空指针，用之前能判断\n" +
                "          if (p == nullptr) return 备用值;\n" +
                "      安全取值 里一定要先判断 p 是不是 nullptr，再去读 *p。";
        return null;
    }

    private static CheckResult 比一比(CppRun run, params (string 标记, string 期望, string 说明)[] 用例们)
    {
        var 错 = new List<string>();
        foreach (var (标记, 期望, 说明) in 用例们)
        {
            string 得到 = 取值(run, 标记);
            if (得到 == null) 错.Add("      " + 说明 + "：程序没有给出这一行的结果");
            else if (得到 != 期望) 错.Add("      " + 说明 + "：得到 " + 显示(得到) + "，应该是 " + 显示(期望));
        }
        if (错.Count == 0) return CheckResult.过("这两组都对");

        return CheckResult.不过(
            "结果不对：\n" + string.Join("\n", 错) + "\n" +
            "      **空指针绝对不能解引用** —— 读了它程序会立刻崩：\n" +
            "          int* p = nullptr;\n" +
            "          std::cout << *p;         // 崩（Windows 上退出码 0xC0000005）\n" +
            "      正确写法是先问一句：\n" +
            "          if (p == nullptr) return 备用值;\n" +
            "          return *p;\n" +
            "      顺便记住：**未初始化的指针是野指针**（int* p; 里面是随机地址），\n" +
            "                所以指针变量一定要初始化 —— 不知道指哪就先写 nullptr。");
    }

    private static string 查不到说明(string 标记) =>
        "没能从程序输出里找到「" + 标记 + "」这一行的结果 —— 函数可能没被调用到，或者程序中途崩了。";

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
}
