    n = n * 2;              // 改的是复制品；函数一结束它就没了
}

// 2. 引用传递：n 就是外面那个变量本身，改它等于改外面
void 翻倍_引用(int& n) {
    n = n * 2;              // 注意 & —— 少了它就退化成值传递
}

// 3. 指针：p 装的是地址，*p 才是那个变量
void 翻倍_指针(int* p) {
    if (p != nullptr) {     // 指针用之前先确认它不是空
        *p = *p * 2;        // *p：按地址找到那个变量，然后改它
    }
}

// 4. 安全取值：空指针绝不解引用，而是交出备用值
int 安全取值(int* p, int 备用值) {
    if (p == nullptr) {
        return 备用值;
    }
    return *p;
}
