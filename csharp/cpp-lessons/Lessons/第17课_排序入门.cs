    private static string 上次的代码;
    private static CppRun 上次的运行;

    private static CppRun 跑一次(string 代码)
    {
        if (上次的运行 != null && 上次的代码 == 代码) return 上次的运行;
        上次的代码 = 代码;
        上次的运行 = 编译并运行(代码, null, 调用点);
        return 上次的运行;
    }

    /// <summary>
    /// 编译并运行，**环境抽风时重试一次**。
    ///
    /// ⚠ 为什么需要它（实测踩到的）：运行器每次在一个全新的临时目录里编译，
    ///   而 `CppRunner.清理旧目录` 会把**别的进程**留下的 run* 目录删掉 ——
    ///   这台机器上同时有好几个助手在跑各自的课程检查，于是刚建出来的目录
    ///   会被别人的检查顺手删掉，g++ 报：
    ///       ld.exe: cannot open output file …prog.exe: No such file or directory
    ///       cc1plus.exe: fatal error: …main.cpp: No such file or directory
    ///   这是**环境**问题（而且常常只发生在一次检查的第一次编译上），不是学生
    ///   代码的问题。同一份代码重跑一次就好了 —— 不重试的话，学生看到的是
    ///   「编译没能通过」，会一头雾水地去改本来没错的代码。
    /// </summary>
    private static CppRun 编译并运行(string 代码, string 骨架, string 调用点)
    {
        // ⚠ 这里必须写 `CppCheck.编译并运行`（课程库的那个）。
        //   加这层包装时我顺手把这一行也替换了，于是它**调用自己** ⇒ 栈溢出、程序消失。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (run.编译通过) return run;
        if (!环境抽风(run)) return run;                 // 真的是学生的错，别重试
        System.Threading.Thread.Sleep(300);
        var 再来 = CppCheck.编译并运行(代码, 骨架, 调用点);
        return 再来.编译通过 ? 再来 : run;
    }

    private static bool 环境抽风(CppRun run) =>
        run.编译信息.Contains("No such file or directory") ||
        run.编译信息.Contains("cannot open output file");

    private static string 先别急着比(CppRun run)
    {
        if (run.Raw.CompileFailed)
        {
            if (run.编译信息.Contains("array-bounds"))
                return
                    "编译器发现了**数组越界**的隐患：\n" +
                    CppCheck.编译失败说明(run).Detail + "\n" +
                    "      检查一下插入排序的 `while (j >= 0 && 数[j] > 拿着)`：\n" +
                    "      `j >= 0` **必须写在前面**，否则 j 变成 -1 时会先去读 数[-1]。";
            return CppCheck.编译失败说明(run).Detail;
        }
        if (run.Raw.Error != null)
            return
                "程序没跑完就退出了：" + run.Raw.Error + "\n" +
                "      这一课最容易让程序崩的是**下标越界**：\n" +
                "          冒泡  内层是 j < 长度 - 1 - i（取到 数[j+1]，最后一格正好是 长度-1）\n" +
                "          选择  内层从 i + 1 开始、到 长度-1 结束\n" +
                "          插入  内层 while 的条件里 `j >= 0` 要写在最前面\n" +
                "      另外 长度 可能是 0 —— 那时一个循环都不该进去。";
        return null;
    }

    private static CheckResult 比一比(CppRun run, params (string 标记, string 期望, string 说明)[] 用例们)
    {
        var 错 = new List<string>();
        foreach (var (标记, 期望, 说明) in 用例们)
        {
            string 得到 = 取一段(run, 标记, 0);
            if (得到 == null) 错.Add("      " + 说明 + "：程序没有给出这一组的输出");
            else if (!一样(得到, 期望))
                错.Add("      " + 说明 + "：得到 " + 显示(得到) + "，应该是 " + 显示(期望));
        }
        if (错.Count == 0) return CheckResult.过("这几组都对");

        return CheckResult.不过(
            "结果不对：\n" + string.Join("\n", 错) + "\n" +
            "      三件事按顺序想一遍：\n" +
            "        ① 每一轮该比哪两个下标？\n" +
            "        ② 内层循环的上界对不对（长度 是 0、1 时会怎样）？\n" +
            "        ③ 交换是不是真的换到了外面那份数组（少写临时变量就白换）？");
    }

    /// <summary>
    /// 取「标记|」后面那一格内容。
    ///
    /// ⚠⚠ 这一课我在这个函数上栽了四次，教训值得写下来：
    ///   调用点是 `"冒泡1|" → 排一遍 → 把结果一个个打出来 → "冒泡1| "`，
    ///   所以**第一段一定是标记、第二段才是内容**。
    ///
    ///   前面三版分别错在：
    ///     · 按「第几行」取 —— 打印函数自己会换行，`冒泡2|` 和上一行最后一个数
    ///       同处一行还是另起一行，取决于学生把换行打在哪一层，两种写法都对；
    ///     · 用"内容里的空格"当右边界 —— 内容本身就是空格分隔的（`1 2 4 5 8`），
    ///       只取到 `1`；
    ///     · 用"下一个标记的位置"当右边界 —— 空内容的那些组（长度是 0 时什么都不打）
    ///       恰好和**闭标记**挨在一起（`冒泡空|冒泡空|`），边界差一格。
    ///
    ///   ⇒ 现在按**竖线**切：竖线只在标记里出现，切出来的第 0 段是标记名、
    ///     第 1 段就是内容。学生的空格怎么打、换行加在哪一层，全都不影响。
    /// </summary>
    private static string 取一段(CppRun run, string 标记, int 第几段)
    {
        // 标记是「冒泡1|」，但**开头的那个标记没有末尾竖线**（`"冒泡1|" << 内容 << "冒泡1| "`）
        // ⇒ 找的时候用「冒泡1」这个名字去找。
        string 名 = 标记.TrimEnd('|');
        int 见到 = 0;
        foreach (var 行 in run.行)
        {
            int 起 = 行.IndexOf(名, System.StringComparison.Ordinal);
            while (起 >= 0)
            {
                // 名字必须落在开头或者空白后面，否则会把别的词的一部分当成标记
                if (起 == 0 || 行[起 - 1] == ' ' || 行[起 - 1] == '\t')
                {
                    int 头 = 起 + 名.Length;
                    if (头 >= 行.Length || 行[头] != '|') { 起 = 行.IndexOf(名, 起 + 1, System.StringComparison.Ordinal); continue; }
                    头++;                                                    // 跳过开头那根竖线
                    int 尾 = 行.IndexOf(标记, 头, System.StringComparison.Ordinal);    // **闭标记**在哪儿
                    if (尾 < 0)
                    {
                        // 没写闭标记：退而求其次，取到这一行末尾，把末尾的竖线砍掉
                        尾 = 行.Length;
                        if (尾 > 头 && 行[尾 - 1] == '|') 尾--;
                    }
                    string 这一段 = 行.Substring(头, 尾 - 头);
                    if (起 > 0) 这一段 = " " + 这一段;                        // 前面那个分隔空格
                    if (见到++ == 第几段) return 这一段.Trim();
                    break;                                                  // 这一行只算第一次出现
                }
                起 = 行.IndexOf(名, 起 + 1, System.StringComparison.Ordinal);
            }
        }
        return null;
    }

    private static bool 一样(string 甲, string 乙) =>
        System.Text.RegularExpressions.Regex.Replace(甲.Trim(), @"\s+", " ") ==
        System.Text.RegularExpressions.Regex.Replace(乙.Trim(), @"\s+", " ");

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);

    private static bool 报的是没写函数(CppRun run, string 函数名)
    {
        string 信息 = run.编译信息;
        return 信息.Contains(函数名) &&
               (信息.Contains("was not declared") || 信息.Contains("not declared"));
    }

    private static string 去掉注释(string s)
    {
        var o = new System.Text.StringBuilder();
        bool 块 = false;
        for (int i = 0; i < s.Length; i++)
        {
            if (!块 && i + 1 < s.Length && s[i] == '/' && s[i + 1] == '/')
            { while (i < s.Length && s[i] != '\n') i++; o.Append('\n'); continue; }
            if (!块 && i + 1 < s.Length && s[i] == '/' && s[i + 1] == '*') { 块 = true; i++; continue; }
            if (块 && i + 1 < s.Length && s[i] == '*' && s[i + 1] == '/') { 块 = false; i++; continue; }
            if (!块) o.Append(s[i]);
        }
        return o.ToString();
    }

    /// <summary>取某个函数的「{ … }」内容（配对花括号）。找不到返回 null。</summary>
    private static string 函数体(string 净源码, string 函数名)
    {
        int 名 = 净源码.IndexOf(函数名 + "(", System.StringComparison.Ordinal);
        if (名 < 0) return null;
        int 起 = 净源码.IndexOf('{', 名);
        if (起 < 0) return null;
        int 深 = 0;
        for (int i = 起; i < 净源码.Length; i++)
        {
            if (净源码[i] == '{') 深++;
            else if (净源码[i] == '}')
            {
                深--;
                if (深 == 0) return 净源码.Substring(起 + 1, i - 起 - 1);
            }
        }
        return null;
    }

    private static bool 有循环(string 体) =>
        体.Contains("for") || 体.Contains("while");
