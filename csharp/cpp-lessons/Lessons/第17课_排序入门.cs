//
// ─────────────────────────────────────────────────────
//  先介绍：排序就是「反复比较、反复交换」
// ─────────────────────────────────────────────────────
//
// 把 {5, 1, 4, 2} 排成 {1, 2, 4, 5}，计算机不会一眼看出来。
// 它只会做两件事：**比两个数**、**换两个数**。
// 排序算法就是"按什么顺序去比、去换"的一套规矩。
//
// ─────────────────────────────────────────────────────
//  一、交换两个数：三行，顺序不能错
// ─────────────────────────────────────────────────────
//
//     int 临时 = 数[i];
//     数[i] = 数[j];
//     数[j] = 临时;
//
// ⚠ 直接写 `数[i] = 数[j]; 数[j] = 数[i];` 是**错的**：
//   第一行执行完，数[i] 原来的值就没了，两个都变成原来 数[j] 的值。
//   这就是为什么需要一个"临时"变量先把它存起来。
//
// ─────────────────────────────────────────────────────
//  二、冒泡排序：比相邻的两个，大的往后冒
// ─────────────────────────────────────────────────────
//
//     for (int i = 0; i < 长度 - 1; i++) {
//         for (int j = 0; j < 长度 - 1 - i; j++) {
//             if (数[j] > 数[j + 1]) { 交换(数[j], 数[j + 1]); }
//         }
//     }
//
// 内层每走完一轮，**最大的那个一定被推到了末尾**；所以下一轮可以少看一格
//   —— 这就是 `- i` 的来历。少写它也能排对，只是白跑很多次。
//
// ─────────────────────────────────────────────────────
//  三、选择排序：每轮挑出最小的，放到前面
// ─────────────────────────────────────────────────────
//
//     for (int i = 0; i < 长度 - 1; i++) {
//         int 最小 = i;                                  ← 先假设第 i 个最小
//         for (int j = i + 1; j < 长度; j++) {
//             if (数[j] < 数[最小]) { 最小 = j; }         ← 只记下标，不急着换
//         }
//         交换(数[i], 数[最小]);                          ← 一轮结束才换一次
//     }
//
// ⚠ 内层找的是**下标**（记在 最小 里），不是值 —— 找到位置最后才交换。
//
// ─────────────────────────────────────────────────────
//  四、插入排序：像理扑克牌
// ─────────────────────────────────────────────────────
//
//     for (int i = 1; i < 长度; i++) {
//         int 拿着 = 数[i];                       ← 把这张牌拿在手里
