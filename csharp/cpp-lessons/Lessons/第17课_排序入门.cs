// 第 17 课：排序入门 —— 自己动手把一排数排好
//
// ══ 这一课要教什么 ══
// 排序是「两层循环」最经典的一次实战。这一课要手写三种：
//     冒泡（比相邻两个，大的往后冒）
//     选择（每轮挑出剩下里最小的，放到前面）
//     插入（把新来的数插到前面已经排好的那一段里）
//
// 三种写法的思路完全不同，但**必须都练** —— 因为：
//   · 它们的复杂度都是 O(n²)，是第 19 课"复杂度"那一课的活教材；
//   · 插入排序天然**稳定**，冒泡写对也稳定，选择排序**不稳定**
//     —— 第 18 课讲稳定性时要回头看这一课；
//   · 考场上 `std::sort` 不一定让用，手写是基本功。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**不许用现成的排序函数交差**。
//   学生最省事的做法是 `std::sort(数, 数 + 长度)` —— 输出完全正确，
//   但这一课要练的是"两层循环怎么控制边界"，调库等于没学。
//   防法：去掉注释后看源码文本，出现 sort / stable_sort / qsort 就判不过。
// 核心检查点二：**三个函数体内各自必须有循环**。
//   光禁 sort 还不够 —— 学生可以把答案抄成三行 `数[0]=…; 数[1]=…;`（对固定用例能蒙对）。
//   防法：按函数名切开源码、取各自的花括号，在**这个函数体里**找 for / while。
// 另外喂了含重复元素的用例（{7,3,7,1,3}）：三种排序对重复元素的处理不同，
// 把"其实没比较"的假实现挡在外面。
//
// ⚠ 给维护者：所有输出都用「标记|值」的格式（照第 06/07 课），
//   比较时把连续空白折成一个空格 —— 学生多打一个空格不该判错。

