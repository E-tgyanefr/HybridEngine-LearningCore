    public static string 参考答案 => """
// 参考答案 —— 三种手写排序
//
// ⚠ 三个函数都把数组**就地**排好（void，不返回新数组）。
//   长度是 0 或 1 时，所有循环都不进去，自然什么都不做 —— 这就是对的。

// 1. 冒泡：比相邻两个，大的往后冒
//    内层每走完一轮，最大的就被推到末尾，所以下一轮少看一格（- i）
void 冒泡排序(int 数[], int 长度) {
    for (int i = 0; i < 长度 - 1; i++) {
        for (int j = 0; j < 长度 - 1 - i; j++) {
            if (数[j] > 数[j + 1]) {
                /* 交换三行 —— 顺序不能错 */
                int 临时 = 数[j];
                数[j] = 数[j + 1];
                数[j + 1] = 临时;
            }
        }
    }
}

// 2. 选择：每轮挑出剩下里最小的，和第 i 个换
void 选择排序(int 数[], int 长度) {
    for (int i = 0; i < 长度 - 1; i++) {
        int 最小 = i;                      /* 先假设第 i 个最小 */
        for (int j = i + 1; j < 长度; j++) {
            if (数[j] < 数[最小]) {
                最小 = j;                  /* 只记下标，一轮结束才换 */
            }
        }
        if (最小 != i) {
            int 临时 = 数[i];
            数[i] = 数[最小];
            数[最小] = 临时;
        }
    }
}

// 3. 插入：像理扑克牌 —— 前 i 个已经排好，把第 i 个插进去
void 插入排序(int 数[], int 长度) {
    for (int i = 1; i < 长度; i++) {
        int 拿着 = 数[i];                  /* 把这张牌拿在手里 */
        int j = i - 1;
        /* ⚠ j >= 0 必须写在前面 —— 否则 j 变成 -1 时先去读了 数[-1] */
        while (j >= 0 && 数[j] > 拿着) {
            数[j + 1] = 数[j];             /* 比它大的往右挪一格 */
            j--;
        }
        数[j + 1] = 拿着;                  /* 放进空出来的位置 */
    }
}
""";

