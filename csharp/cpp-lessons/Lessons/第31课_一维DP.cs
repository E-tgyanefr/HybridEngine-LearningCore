            return CheckResult.过("n=1,2,3,5,10,35,45 都对，而且在 60 秒内跑完了");

        return CheckResult.不过(
            "爬楼梯的结果不对：\n" +
            "      期望 " + 期望 + "（对应 n = 1,2,3,5,10,35,45）\n" +
            "      实际 " + 显示(楼梯) + "\n" +
            "      递推关系是：\n" +
            "          走法(n) = 走法(n-1) + 走法(n-2)\n" +
            "      起点：走法(0) = 1、走法(1) = 1（然后 2, 3, 5, 8, 13… 就是斐波那契）\n" +
            "      ⚠ 如果只有少数几个对，多半是把答案写死了 —— 检查喂了 7 个 n。\n" +
            "      ⚠ n=45 的答案是 1836311903（还没超 int 上限 2147483647），\n" +
            "        这就是本课只喂到 45 的原因。");
    }

    [检查说明("打家劫舍：相邻不能同偷，六组数据")]
    public static CheckResult 检查_打家劫舍(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 劫 = 取值(run, "劫");
        const string 期望 = "12,4,5,0,32,10";

        if (劫 == 期望)
            return CheckResult.过("六组都对（含空数组、只有一家、{5,5,5}）");

        return CheckResult.不过(
            "打家劫舍的结果不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(劫) + "\n" +
            "      （依次是 {2,7,9,3,1} {1,2,3,1} {5} {} {2,1,4,9,3,7,2,8,3,6} {5,5,5}）\n" +
            "      两条路取大的：\n" +
            "          偷这一家  ⇒ 上一家不能偷 ⇒ 钱[i] + 最多(i-2)\n" +
            "          不偷      ⇒ 最多(i-1)\n" +
            "      用两个变量滚就够：\n" +
            "          int 隔一家 = 0, 上一家 = 0;\n" +
            "          for (int x : 钱) { int 当 = std::max(上一家, 隔一家 + x); 隔一家 = 上一家; 上一家 = 当; }\n" +
            "          return 上一家;\n" +
            "      ⚠ 空数组必须返回 0（循环一次都不进 ⇒ 上一家还是 0，天然就对）。\n" +
            "      ⚠ 别以为「隔一家偷一家」就行 —— {2,7,9,3,1} 的最佳选择是 7+3+1=11 吗？\n" +
            "        不是，是 9+3=12（或者 7+9 不能同时，所以是 2+9+1=12）。");
    }

    [检查说明("★ 核心：0/1 背包 —— 容量那层必须逆序")]
    public static CheckResult 检查_简单背包(string 代码)
    {
        // ⚠ 第二个核心检查点。最后两组数据是**专门为逆序/正序设计的**：
        //     重{3,4} 价{30,50} 容量 8   → 0/1 是 80（3+4=7 装得下）
        //                                  正序会给出 100（把 4 那件拿两次）
        //     重{4,5,6} 价{5,6,7} 容量 10 → 0/1 是 12，正序也是 12 —— 这组两组同分，
        //        所以真正的照妖镜是上一组。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 包 = 取值(run, "包");
        const string 期望 = "7,8,0,11,80,12";

        if (包 == 期望)
            return CheckResult.过("六组都对 —— 每件确实只拿了一次");

        return CheckResult.不过(
            "简单背包的结果不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(包) + "\n" +
            "      （依次是 重{2,3,4}价{3,4,5}容量5、重{1,2,3}价{1,5,8}容量3、\n" +
            "        重{5}价{9}容量3、重{2,2,3,1}价{3,4,5,2}容量6、\n" +
            "        重{3,4}价{30,50}容量8、重{4,5,6}价{5,6,7}容量10）\n" +
            "      ⚠ 如果**偏大**（尤其第 5 组给出 100 而不是 80），那是**逆序**写成**正序**了：\n" +
            "          for (int c = 容量; c >= 重[i]; c--)      ✓ 每件最多一次\n" +
            "          for (int c = 重[i]; c <= 容量; c++)      ✗ 同一件能拿无数次\n" +
            "        为什么：正序时算 dp[c] 的那一刻，`dp[c - 重[i]]` **刚被这一轮改过**，\n" +
            "        里面已经含了第 i 件 ⇒ 第 i 件会被反复放进去。\n" +
            "        逆序时它还是「没放第 i 件」的旧值 ⇒ 只会放一次。\n" +
            "        拿第 5 组验一下：重{3,4} 价{30,50} 容量 8 ——\n" +
            "          每件一次：3+4=7 ≤ 8 ⇒ 30+50 = 80\n" +
            "          随便拿  ：4 那件拿两次（重 8）⇒ 50+50 = 100\n" +
            "      ⚠ 如果**偏小或为 0**：检查 `dp` 是不是开了 `容量 + 1` 个格子（下标 0..容量）。\n" +
            "        开成 `dp(容量)` 就差最后一格，`dp[容量]` 是越界的。\n" +
            "      ⚠ 状态转移是 dp[c] = max(dp[c], dp[c - 重[i]] + 价[i])，\n" +
            "        外层一定要遍历**每一件物品**，别只算一件。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
}
