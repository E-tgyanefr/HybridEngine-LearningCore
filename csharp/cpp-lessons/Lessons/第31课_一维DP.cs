    public static string 参考答案 => """
// 第 31 课参考答案：三个一维 DP

int 爬楼梯(int n) {
    if (n <= 0) return 0;
    int 前2 = 1;          // 走法(0)：不走也是一种走法
    int 前1 = 1;          // 走法(1)
    for (int i = 2; i <= n; i++) {
        int 当 = 前1 + 前2;      // 状态转移：走法(i) = 走法(i-1) + 走法(i-2)
        前2 = 前1;               // 往前滚一格
        前1 = 当;
    }
    return 前1;
    // ⚠ 只用了两个变量 ⇒ O(1) 空间、O(n) 时间。
    //   递归写法算 n=45 要十亿次以上调用，这里只要循环 44 次。
}

int 打家劫舍(std::vector<int> 钱) {
    int 隔一家 = 0;      // 处理到「上上家」为止能偷到的最多
    int 上一家 = 0;      // 处理到「上一家」为止能偷到的最多
    for (int x : 钱) {
        // 偷这一家 ⇒ 上一家不能偷 ⇒ 用「上上家」的答案
        int 当 = std::max(上一家, 隔一家 + x);
        隔一家 = 上一家;
        上一家 = 当;
    }
    return 上一家;
}

int 简单背包(std::vector<int> 重, std::vector<int> 价, int 容量) {
    std::vector<int> dp(容量 + 1, 0);        // ⚠ 容量+1 个格子，全部填 0
    for (int i = 0; i < (int)重.size(); i++) {
        // ⚠⚠ 容量**必须从大到小**：
        //   这样 dp[c - 重[i]] 还是"没放第 i 件"的旧值 ⇒ 每件最多放一次
        for (int c = 容量; c >= 重[i]; c--) {
            dp[c] = std::max(dp[c], dp[c - 重[i]] + 价[i]);
        }
    }
    return dp[容量];
}
""";

