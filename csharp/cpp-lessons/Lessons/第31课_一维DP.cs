// ══ 这一课要教什么 ══
// 动态规划的第一步是「**别重复算**」：爬楼梯如果用第 11 课那种递归，
// 算 45 级要调用自己上**百亿**次（永远跑不完）；记住中间结果之后，
// 45 次循环就够了。学生要亲手体会这个落差。
//
// 第二个重点是 0/1 背包那个**逆序**循环 —— 它是整门课最容易写错的一行：
//   逆序 ⇒ dp[c - 重[i]] 还是「没放第 i 件」的旧值 ⇒ 每件最多放一次
//   正序 ⇒ 它已经是「放过第 i 件」的新值     ⇒ 同一件能被拿无数次
// 两种写法**都能跑、都输出一个合理数字**，只有喂对数据才分得出来。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：检查_爬楼梯里同时喂 n=10 和 n=45。
//   纯递归写法算 n=45 会超出 60 秒的运行上限（实测这个递推要 10^9 次以上调用），
//   于是「没记住中间结果」这件事会以**超时**的形式暴露出来。
//   同时喂 n=35、n=45 也堵死了「写死几个答案」的路。
// 核心检查点二：检查_简单背包里有两组数据是专门为「逆序/正序」设计的：
//   重{3,4} 价{30,50} 容量 8   → 0/1 是 50（只能拿一件 4），拿两件是 80
//   重{4,5,6} 价{5,6,7} 容量 10 → 0/1 是 11，正序会给出 12（4+6 两件 5+7）
//   实测：正序版本给出 7,8,0,12,100,12 而正确解是 7,8,0,11,80,12。
// 反面测试（都跑过）：
//   · 背包正序（完全背包）→ 被抓住（两组数据不同）
//   · 把答案写死成查表     → n=35、n=45 立刻错

