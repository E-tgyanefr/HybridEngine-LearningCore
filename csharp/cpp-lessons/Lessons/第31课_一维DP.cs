//     不偷      ⇒ 保持（处理到 i-1 家为止的最多）
//
//     最多(i) = max( 最多(i-1),  钱[i] + 最多(i-2) )
//
// 同样可以用两个变量滚（一个表示 i-1 的答案、一个表示 i-2 的答案）：
//
//     [2, 7, 9, 3, 1]  →  12
//     推法：2 → max(2, 7)=7 → max(7, 9+2)=11 → max(11, 3+7)=11 → max(11, 1+9)=12
//
// ⚠ 注意这个数**不一定比总和的一半大** —— 别去猜规律，老老实实推。
//
// ─────────────────────────────────────────────────────
//  三、0/1 背包：dp 数组 + 那个**逆序**
// ─────────────────────────────────────────────────────
//
// 有若干件物品，每件有**重**量和**价**值；背包容量固定。
// 每件**最多拿一次**，求能装走的最大价值。
//
//     dp[c] = 「只用已经考虑过的那几件，容量 c 最多能装多少价值」
//
// 加进第 i 件物品：
//
//     不拿它 ⇒ dp[c] 不变
//     拿它   ⇒ dp[c - 重[i]] + 价[i]
//
//     dp[c] = max( dp[c], dp[c - 重[i]] + 价[i] )
//
// ⚠⚠ 但容量那一层循环必须**从大到小**：
//
//     for (int c = 容量; c >= 重[i]; c--)        ✓ 0/1 背包
//     for (int c = 重[i]; c <= 容量; c++)        ✗ 那是"每件能拿无数次"
//
// 为什么？看 dp[c] = max(dp[c], dp[c - 重[i]] + 价[i]) 这一行：
//
//     逆序：算 dp[c] 时，dp[c - 重[i]] **还没被这一轮改过**
//           ⇒ 用的是「没放第 i 件」的旧值 ⇒ 第 i 件只会被放进去一次 ✓
//     正序：算 dp[c] 时，dp[c - 重[i]] **刚刚被这一轮改过了**
