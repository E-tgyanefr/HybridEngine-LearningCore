                    (run.编译信息.Contains("not declared") || run.编译信息.Contains("was not declared")))
                    return CheckResult.不过(
                        "没有找到「" + 名 + "」这个函数。\n" +
                        "      本课要的三个签名是：\n" +
                        "          int  找根(std::vector<int>& 父, int x)\n" +
                        "          bool 合并(std::vector<int>& 父, int a, int b)\n" +
                        "          int  最小生成树(int 点数, std::vector<std::vector<int>> 边)\n" +
                        "      ⚠ 前两个的第一个参数是 `std::vector<int>&`（引用）——\n" +
                        "        并查集要**就地改**那个数组，少了 & 改的只是副本。");
            }
            return CppCheck.编译失败说明(run);
        }
        return CheckResult.过("三个函数都能正常调用");
    }

    [检查说明("★ 核心：六张图的最小生成树（含不连通、乱序的边）")]
    public static CheckResult 检查_最小生成树(string 代码)
    {
        // ⚠ 核心检查点。第 6 张图的边**故意乱序**（7,3,1,1,5,2,1,9）：
        //   不排序、按输入顺序贪心的写法会得到 17（正确 8）。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 用例 = new (string 说明, string 期望)[] { };
        string 树 = 取值(run, "树");
        const string 期望 = "6,10,-1,0,2,8";

        if (树 == 期望)
            return CheckResult.过("六张图都对（含两块不连通返回 -1、单个点返回 0、乱序边的那张）");

        // 判断一下是不是"没排序"那种症状
        bool 像没排序 = 树 != null && 树.EndsWith(",17");

        return CheckResult.不过(
            "最小生成树不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(树) + "\n" +
            "      （依次是 4 点 5 边、5 点 6 边、4 点 2 边（不连通）、1 个点、\n" +
            "        3 点全 1 的三角形、6 点 8 边（边是乱序给的））\n" +
            (像没排序
                ? "      ⚠ 最后一张图给出 17，而正确答案是 8 —— **这是没有排序的症状**。\n" +
                  "        Kruskal 的第一步（也是灵魂）就是「把边按长度从小到大排序」：\n" +
                  "            std::sort(边.begin(), 边.end(),\n" +
                  "                      [](const std::vector<int>& a, const std::vector<int>& b) {\n" +
                  "                          return a[2] < b[2];      // 第 3 个数是边长\n" +
                  "                      });\n" +
                  "        就算边给进来的时候恰好是升序的，也必须排序 —— 检查喂的就是乱序的。\n"
                : "") +
            "      算法：排序后一条条试，两端还没连通就加进去（用并查集判断），\n" +
            "      最后凑够 **点数-1** 条才算连成一棵树。\n" +
            "      ⚠ 凑不够 ⇒ 原图不连通 ⇒ 返回 **-1**（第 3 张图就是这个情况）。\n" +
            "      ⚠ 只有一个点时返回 **0**（不需要任何边）。\n" +
            "      ⚠ 如果结果是**偏大**：多半是「合并没有判是不是已经连通」，\n" +
            "        于是加了会绕圈的边（并查集那一问会一起错）。");
    }

    [检查说明("★ 核心：并查集 —— 已经连通的两点再合并必须返回 false")]
    public static CheckResult 检查_并查集(string 代码)
    {
        // ⚠ 第二个核心检查点。实测「合并永远返回 true」的版本给出 11111，
        //   正确答案是 11101（第 4 次合并 0,2 时它们已经连通了）。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 错 = new List<string>();
        string 并 = 取值(run, "并");
        string 根 = 取值(run, "根");

        if (并 != "11101")
            错.Add("      依次 合并(0,1)、合并(2,3)、合并(1,3)、合并(0,2)、合并(4,5)\n" +
                   "        得到 [" + 显示(并) + "]，应当是 [11101] ——\n" +
                   "        第 4 次（0,2）时它们已经通过 0-1-3-2 连通了，**必须返回 0**");
        if (根 == null || !根.EndsWith("|10"))
            错.Add("      找根：0/1/2/3 应当同根（说明 0-1-3-2 连通），4 和 0 应当不同根。\n" +
                   "        得到 [" + 显示(根) + "]，应当是 [3333|10]（根的具体编号不要求一致，\n" +
                   "        但「0 和 3 同根 = 1、0 和 4 不同根 = 0」必须是 10）");

        if (错.Count == 0)
            return CheckResult.过("并查集正确：能合并的合并了，已经连通的如实返回 0");

        return CheckResult.不过(
            "并查集不对：\n" + string.Join("\n", 错) + "\n" +
            "      正确的写法：\n" +
            "          int 找根(std::vector<int>& 父, int x) {\n" +
            "              while (父[x] != x) { 父[x] = 父[父[x]]; x = 父[x]; }   // 路径压缩\n" +
            "              return x;\n" +
            "          }\n" +
            "          bool 合并(std::vector<int>& 父, int a, int b) {\n" +
            "              int 根a = 找根(父, a), 根b = 找根(父, b);\n" +
            "              if (根a == 根b) return false;      // ⚠ 这一句是关键\n" +
            "              父[根a] = 根b;\n" +
            "              return true;\n" +
            "          }\n" +
            "      ⚠ `if (根a == 根b) return false;` 不是可选的优化 ——\n" +
            "        Kruskal 完全靠这个返回值决定「这条边要不要」。\n" +
            "        少了它，会给已经连通的点再加一条边 ⇒ **绕圈** ⇒ 总价偏大、\n" +
            "        边数虚高 ⇒ 连「图通不通」都判错（实测那个版本对所有图都返回 -1）。\n" +
            "      ⚠ `找根` 里那句 `父[x] = 父[父[x]]` 是**路径压缩**：\n" +
            "        把路上的点直接挂到根上，树越来越扁，后面查得越来越快。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
