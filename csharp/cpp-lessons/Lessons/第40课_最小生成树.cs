//         while (父[x] != x) x = 父[x];              // 一路往上找，直到自己是自己的父亲
//         return x;
//     }
//
//     ⇒ a 和 b 连通 ⟺ 找根(a) == 找根(b)
//
// 合并就是把一伙的根挂到另一伙的根下面：
//
