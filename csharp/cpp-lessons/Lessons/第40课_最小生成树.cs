    public static string 参考答案 => """
// 第 40 课参考答案：Kruskal + 并查集

// 找 x 所在那一伙的代表（根）。顺手做**路径压缩**：把路上的点直接挂到根上。
int 找根(std::vector<int>& 父, int x) {
    while (父[x] != x) {
        父[x] = 父[父[x]];      // 让 x 指向"爷爷"——树越来越扁，后面越来越快
        x = 父[x];
    }
    return x;
}

// 合并 a、b 两伙。返回值 = 「这次合并有没有真的改变什么」
bool 合并(std::vector<int>& 父, int a, int b) {
    int 根a = 找根(父, a);
    int 根b = 找根(父, b);
    if (根a == 根b) {
        return false;           // ⚠ 本来就在一伙里 —— 加了这条边就会绕圈
    }
    父[根a] = 根b;
    return true;
}

int 最小生成树(int 点数, std::vector<std::vector<int>> 边) {
    if (点数 <= 0) return 0;
    if (点数 == 1) return 0;                 // 一个点不需要修路

    std::vector<int> 父(点数);
    for (int i = 0; i < 点数; i++) 父[i] = i;    // 一开始每个点自成一伙

    // ⚠ 关键第一步：按**边长**从小到大排序
    //   （默认的 sort 是按整个 vector 比的，不是按第 3 个数）
    std::sort(边.begin(), 边.end(),
              [](const std::vector<int>& a, const std::vector<int>& b) {
                  return a[2] < b[2];
              });

    int 总价 = 0;
    int 用了几条 = 0;
    for (auto& e : 边) {
        if (合并(父, e[0], e[1])) {          // 两端还没连通 ⇒ 这条边有用
            总价 += e[2];
            用了几条++;
        }
        // 已经连通 ⇒ 跳过（加了会绕圈）
    }

    // n 个点连成一棵树恰好要 n-1 条边；凑不到 ⇒ 原图本来就不连通
    if (用了几条 != 点数 - 1) return -1;
    return 总价;
}
""";

