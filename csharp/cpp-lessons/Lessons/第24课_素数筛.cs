//
// ─────────────────────────────────────────────────────
//  一、埃氏筛：把合数划掉
// ─────────────────────────────────────────────────────
//
// 想法的转变：**不要问"这个数是不是质数"，而要说"这个数是质数，那它的倍数全不是"**。
//
//     static bool 合数[1000001];        ← 合数[i] == true 表示 i 是合数
//     for (int i = 2; i <= n; i++) {
