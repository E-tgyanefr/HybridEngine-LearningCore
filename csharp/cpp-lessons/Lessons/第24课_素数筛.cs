// 第 24 课：素数筛 —— 一次把一千万以内的质数全标出来
//
// ══ 这一课要教什么 ══
// 第 22 课的试除法是"给一个数、判它是不是质数"。
// 可要是问「1 到 100 万里面有几个质数」，试除法就要把每个数都试一遍 ——
// 本机实测：到 100 万约 50 秒，比赛里直接超时。
//
// 这一课换一个方向想：**不要一个个去判，而是"从最小的质数开始，把它的倍数全划掉"**。
//   2 是质数 → 4、6、8…全划掉
//   3 是质数 → 6、9、12…全划掉
//   5 是质数 → 10、15…全划掉
// 一趟下来，没被划掉的就是质数。这就是埃氏筛（埃拉托斯特尼筛）。
//
// 本机实测（同一台机器、同一个编译器）：
//     埃氏筛到 100 万     2 毫秒
//     试除法到 100 万     约 50 秒        ← 差两万多倍
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**`素数个数(1000000)` 必须在时限内算完。**
//   试除法是 O(n√n)，100 万时约 50 秒 —— 运行器 60 秒就判超时，
//   学生看到的"超时"正是这一课要他记住的对比。
//   同时配一条**文本兜底**：切开函数体，看是不是"两个嵌套循环 + 标记数组"的形状
//   （等超时要等很久，太慢）。
// 另一条：`是质数` 单独判一个数时用试除法就行 —— 这一课不要求它也走筛。
//
// ⚠ 给维护者：`bool 合数[1000001];` 写在函数里（非 static）会爆栈 ——
//   本机实测程序直接崩、没有任何输出。模板里专门讲这个坑。

