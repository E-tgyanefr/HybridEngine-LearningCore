//             for (long long j = (long long)i * i; j <= n; j += i) {
//                 合数[j] = true;       ← 把 i 的倍数全划掉
//             }
//         }
//     }
//     数一数 !合数[i] 的个数（从 2 到 n）
//
// 两个细节：
//
//   ⚠ 内层从 `i * i` 开始，不是 `i + i`。
//     因为比 i*i 小的那些倍数（2i、3i…）**已经被更小的质数划过了** ——
//     比如 i = 5 时，10 早被 2 划过、15 早被 3 划过，从 25 开始才不重复。
//
//   ⚠ `j` 要写成 `long long`：i 接近 10^6 时 i*i 是 10^12，int 装不下，
//     溢出成负数之后循环条件 `j <= n` 立刻成立，会写坏内存。
//
// ─────────────────────────────────────────────────────
//  二、速度对照（本机实测，同一台机器）
// ─────────────────────────────────────────────────────
//
//     做法                          到 100 万
//     试除法（每个数试到 √i）        约 50 秒        ← 超时
//     埃氏筛                        2 毫秒          ← 快两万多倍
//
//
// 为什么差这么多：试除法是「n 个数 × 每个数试 √n 次」= O(n√n)；
//   筛法是「每个质数划一遍它的倍数」，总的划的次数约 n log log n ——
//   几乎就是线性的。**同一道题，换个想法，快两万倍。**
