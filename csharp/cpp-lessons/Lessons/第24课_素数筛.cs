    public static string 参考答案 => """
// 参考答案 —— 埃氏筛

// 标记数组放在所有函数外面（全局）。
// ⚠ 放在函数里不加 static 会**爆栈**（100 万个 bool ≈ 1 MB，栈装不下）。
static bool 合数[1000005];

// 素数个数：埃氏筛 + 数一遍
int 素数个数(int n) {
    if (n < 2) {
        return 0;
    }
    // ⚠ 每次都清干净 —— 这是全局数组，上一次调用的结果还留在里面
    for (int i = 0; i <= n; i++) {
        合数[i] = false;
    }

    for (int i = 2; i <= n; i++) {
        if (!合数[i]) {                        /* i 没被划掉 ⇒ i 是质数 */
            /* ⚠ 从 i*i 开始划（比它小的倍数已经被更小的质数划过了）
               ⚠ j 用 long long：i 接近 10^6 时 i*i 是 10^12，int 装不下 */
            for (long long j = (long long)i * i; j <= n; j += i) {
                合数[j] = true;
            }
        }
    }

    int 个数 = 0;
    for (int i = 2; i <= n; i++) {
        if (!合数[i]) {
            个数++;
        }
    }
    return 个数;
}

// 是质数：单独判一个数时，试除法（试到 √n）就够快
bool 是质数(int n) {
    if (n < 2) {
        return false;
    }
    for (int i = 2; (long long)i * i <= n; i++) {
        if (n % i == 0) {
            return false;
        }
    }
    return true;
}
""";

