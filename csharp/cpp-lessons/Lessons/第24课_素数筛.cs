    [检查说明("★ 素数个数里要真的是筛法（嵌套循环 + 标记数组）")]
    public static CheckResult 检查_是筛法(string 代码)
    {
        // ⚠ 文本兜底：等超时要等 50 秒以上，太慢。
        //   判据故意宽松 —— 只抓"明显是试除法"的形状（一个循环 + %），
        //   绝不把正确写法判错。
        string 净 = 去掉注释(代码);
        string 体 = 函数体(净, "素数个数");
        if (体 == null)
            return CheckResult.不过("找不到「素数个数」的函数体 —— 花括号配对了吗？");

        bool 有嵌套 = 体.Contains("for") &&
                      (体.Contains("+= i") || 体.Contains("+= p") || 体.Contains("+ i") ||
                       体.Contains("i * i") || 体.Contains("= true") || 体.Contains("= 1"));
        if (有嵌套)
            return CheckResult.过("函数体里是「划掉倍数」的形状 —— 用的是筛法");

        return CheckResult.不过(
            "「素数个数」的函数体看起来不像筛法。\n" +
            "      筛法的形状是**两层循环 + 一个标记数组**：\n" +
            "          for (int i = 2; i <= n; i++)\n" +
            "              if (!合数[i])                                  ← i 是质数\n" +
            "                  for (long long j = i*i; j <= n; j += i)     ← 把倍数划掉\n" +
            "                      合数[j] = true;\n" +
            "      关键的一句话：**不要一个个去「判」质数，而是把合数一个个「划」掉。**\n" +
            "      如果写的是「对每个 i 试除到 √i」，答案虽然也对，\n" +
            "      但到 100 万要 50 秒（检查里就喂了 100 万）—— 那不是这一课要教的。");
    }

