// 第 29 课参考答案：二叉排序树

void 插入(树结点*& 根, int 值) {
    if (根 == nullptr) {
        根 = new 树结点(值);          // 找到空位，住下
        return;
    }
    if (值 < 根->值) {
        插入(根->左, 值);             // 小的往左
    } else if (值 > 根->值) {
        插入(根->右, 值);             // 大的往右
    }
    // 相等：什么都不做（BST 里不放重复值）
}

bool 存在(树结点* 根, int 值) {
    while (根 != nullptr) {
        if (值 == 根->值) return true;
        根 = (值 < 根->值) ? 根->左 : 根->右;   // 每次只朝一边走
    }
    return false;
}

bool 删除(树结点*& 根, int 值) {
    if (根 == nullptr) return false;                 // 空树，没得删

    if (值 < 根->值) return 删除(根->左, 值);        // 继续往左找
    if (值 > 根->值) return 删除(根->右, 值);        // 继续往右找

    // 找到了，就是要删的这个结点
    树结点* 被删 = 根;
    if (根->左 == nullptr) {
        根 = 根->右;                                 // 没有左孩子：右孩子顶上
    } else if (根->右 == nullptr) {
        根 = 根->左;                                 // 没有右孩子：左孩子顶上
    } else {
        树结点* 后继 = 摘最小(根->右);              // 两个孩子：右子树里最小的
        后继->左 = 根->左;
        后继->右 = 根->右;
        根 = 后继;
    }
    delete 被删;                                     // ⚠ 最后才 delete
    return true;
}

void 中序(树结点* 根, std::vector<int>& 出) {
    if (根 == nullptr) return;
    中序(根->左, 出);
    出.push_back(根->值);
    中序(根->右, 出);
}
