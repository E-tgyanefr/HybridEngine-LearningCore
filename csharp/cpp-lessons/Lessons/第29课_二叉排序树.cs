// ══ 这一课要教什么 ══
// 二叉排序树（BST）只加了一条规矩：**左子树全比我小，右子树全比我大**。
// 就这一条规矩，把「查找」从「走遍所有结点」变成了「每比一次砍掉一半」。
//
// 这一课的难点不是插入和查找（都很短），而是**删除**：
// 被删的结点有两个孩子时，要用「右子树里最小的那个」（中序后继）来顶替它。
// 学生最常见的错法是压根没接后继 —— 树看着还在，中序却乱了。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：检查_插入后中序有序 —— 喂 **4 组顺序完全不同**的插入序列
//   （乱序、顺序、倒序、另一种乱序），每一组都要求中序是升序。
//   「插入不比较大小、直接挂右边」的解法会当场露馅（中序等于插入顺序）。
// 核心检查点二：检查_删除后仍有序 —— 删完再走一遍中序，中序必须还是升序且
//   **不多不少**。这条同时抓住「删不干净」和「删多了」。
//   ⚠ 只验证「查找返回了 true」抓不住删除的错：一个什么都不做的删除
//     也能让查找返回 true —— 必须看**删完之后整棵树的中序**。
// 反面测试（都跑过）：
//   · 插入不比较大小（变一条链）→ 中序乱序，15 处不同，被抓住
//   · 删除不接后继（结构断了）→ 重复删返回 110、中序少值，5 处不同，被抓住
