//
// 二叉排序树（也叫二叉搜索树、BST）多了一条规矩：
//
//     对**每一个**结点：左子树里所有值都**比它小**，右子树里所有值都**比它大**
//
// 例（依次插入 8、3、10、1、6、14、4、7、13）：
//
//                8
//              /   \
//             3     10
//            / \      \
//           1   6      14
//              / \    /
//             4   7  13
//
// 看一眼就明白规矩怎么用的：想找 7 —— 从 8 开始，
//   7 < 8 ⇒ 只可能在左边；到 3，7 > 3 ⇒ 只可能在右边；到 6，7 > 6 ⇒ 往右；到 7，命中。
