//
//     一个个挨着找（线性查找）   平均 500,000 次比较
//     排好序的数组 + 二分查找    约 20 次比较（但**插入**一个要搬动后面所有元素）
//     二叉排序树                约 20 次比较，而且插入/删除也只要约 20 步
