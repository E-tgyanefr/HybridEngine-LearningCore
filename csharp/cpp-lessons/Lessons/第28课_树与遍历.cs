    [检查说明("★ 核心：三种遍历在一棵一般树上都要对")]
    public static CheckResult 检查_三种遍历(string 代码)
    {
        // ⚠ 本课的核心检查点：喂**形状完全不同**的树。
        //   "中序用 sort 交差""后序抄先序"这类解法在斜树/单结点树上
        //   碰巧能蒙对，一到一般树就露馅。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 用例 = new (string 标记, string 形状, string 名字, string 期望)[]
        {
            ("一先序", "一般树", "先序", "1,2,4,5,3,6,"),
            ("一中序", "一般树", "中序", "4,2,5,1,6,3,"),
            ("一后序", "一般树", "后序", "4,5,2,6,3,1,"),
            ("二先序", "斜树",   "先序", "1,2,3,"),
            ("二中序", "斜树",   "中序", "1,2,3,"),
            ("二后序", "斜树",   "后序", "3,2,1,"),
            ("三先序", "单结点", "先序", "7,"),
            ("三中序", "单结点", "中序", "7,"),
            ("三后序", "单结点", "后序", "7,"),
        };

        var 错 = new List<string>();
        foreach (var (标记, 形状, 名字, 期望) in 用例)
        {
            string 得到 = 取值(run, 标记);
            if (得到 == null)
            {
                错.Add("      " + 形状 + "的" + 名字 + "：程序没有给出结果（多半是崩了 —— 检查有没有判 nullptr）");
                continue;
            }
            if (得到 != 期望)
                错.Add("      " + 形状 + "的" + 名字 + "得到 [" + 显示(得到) + "]，应该是 [" + 期望 + "]");
        }

        if (错.Count == 0)
            return CheckResult.过("一般树、斜树、单结点树上的三种遍历全对（9 组）");

        return CheckResult.不过(
            "遍历结果不对：\n" + string.Join("\n", 错) + "\n" +
            "      三份代码**只有一行位置不同**：\n" +
            "          先序：  出.push_back(根->值);  先序(左);  先序(右);\n" +
            "          中序：  中序(左);  出.push_back(根->值);  中序(右);\n" +
            "          后序：  后序(左);  后序(右);  出.push_back(根->值);\n" +
            "      拿参考树推一遍（根 1，左 2(左4,右5)，右 3(左6)）：\n" +
            "          先序 1,2,4,5,3,6   中序 4,2,5,1,6,3   后序 4,5,2,6,3,1\n" +
            "      两个自查的办法：\n" +
            "        · 先序的**第一个**必须是根；后序的**最后一个**必须是根\n" +
            "        · 三个结果都必须是 6 个数（每个结点恰好一次）—— 数目不对说明漏走或重复走了\n" +
            "      ⚠ 中序**不是**「从小到大排一遍」。碰巧在某些树上一样，\n" +
            "        换一棵（比如 1-2-3 的斜树）就完全不同了。");
    }

    [检查说明("空树和结点数：nullptr 不能崩")]
    public static CheckResult 检查_空树与结点数(string 代码)
    {
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 空 = 取值(run, "空");
        if (空 == null)
            return CheckResult.不过(
                "传一棵**空树**（根是 nullptr）进去，程序就崩了。\n" +
                "      空树是一种完全合法的输入：一个结点都没有的树。\n" +
                "      每个递归函数的第一行都要挡住它：\n" +
                "          if (根 == nullptr) return;      // 遍历\n" +
                "          if (根 == nullptr) return 0;    // 结点数\n" +
                "      ⚠ 缺了它，走到叶子之后会顺着**空指针**去找成员，\n" +
                "        程序会直接消失（实测退出码 -1073741819，0xC0000005）。");

        var 错 = new List<string>();
        if (空 != "0000")
            错.Add("      空树：三种遍历都该什么都不输出、结点数该是 0，实际得到 [" + 显示(空) + "]");

        string 数1 = 取值(run, "一结点数");
        string 数2 = 取值(run, "二结点数");
        string 数3 = 取值(run, "三结点数");
        if (数1 != "6") 错.Add("      一般树的结点数得到 [" + 显示(数1) + "]，应该是 6");
        if (数2 != "3") 错.Add("      斜树的结点数得到 [" + 显示(数2) + "]，应该是 3");
        if (数3 != "1") 错.Add("      单结点树的结点数得到 [" + 显示(数3) + "]，应该是 1");

        if (错.Count == 0) return CheckResult.过("空树不崩，三棵树的结点数都对（6 / 3 / 1）");

        return CheckResult.不过(
            "结点数或空树处理不对：\n" + string.Join("\n", 错) + "\n" +
            "      递归写法一眼就能看出来对不对劲：\n" +
            "          空树 0 个；否则 = 1（自己）+ 左子树的结点数 + 右子树的结点数\n" +
            "      三种情况都要想到：空树（0）、只有自己（1）、左右都有。");
    }

    [检查说明("★ 核心：中序不是「从小到大排序」——顺序真的按树走")]
    public static CheckResult 检查_中序不是排序(string 代码)
    {
        // 这一条专抓「中序就是输出升序」这种误会：
        //   给一棵**值本身不是升序排列**的树（根 50，左 9（左 80、右 1），右 7），
        //   "排序交差"和"真的中序遍历"会给出完全不同的结果。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 用例 = new (string 标记, string 名字, string 期望)[]
        {
            ("四先序", "先序", "50,9,80,1,7,"),
            ("四中序", "中序", "80,9,1,50,7,"),
            ("四后序", "后序", "80,1,9,7,50,"),
        };

        var 错 = new List<string>();
        foreach (var (标记, 名字, 期望) in 用例)
        {
            string 得到 = 取值(run, 标记);
            if (得到 != 期望)
                错.Add("      " + 名字 + "得到 [" + 显示(得到) + "]，应该是 [" + 期望 + "]");
        }

        if (错.Count == 0)
            return CheckResult.过("在「值不是升序」的树上，三种遍历也都对 —— 顺序是真按树走的");

        return CheckResult.不过(
            "换一棵值乱序的树（根 50，左 9（左 80、右 1），右 7）之后遍历不对：\n" +
            string.Join("\n", 错) + "\n" +
            "      这棵树的形状是：\n" +
            "               50\n" +
            "              /  \\\n" +
            "             9    7\n" +
            "            / \\\n" +
            "          80   1\n" +
            "      按「先自己 / 左 / 右」的顺序推一遍就有答案了，**跟值的大小毫无关系**。\n" +
            "      ⚠ 中序 ≠ 排序。只有在**二叉排序树**（第 29 课）上，\n" +
            "        中序才碰巧等于从小到大 —— 那是那棵树的性质，不是遍历的性质。\n" +
            "        把 中序 写成「先收齐再 sort」在这棵树上就错了。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
}
