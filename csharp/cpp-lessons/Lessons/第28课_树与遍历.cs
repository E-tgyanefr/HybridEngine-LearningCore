    public static string 参考答案 => """
// 第 28 课参考答案：三种遍历 + 结点数
// ⚠ 三份遍历**只有一行位置不同** —— 就是 push_back 那一行。

void 先序(树结点* 根, std::vector<int>& 出) {
    if (根 == nullptr) return;        // 基准情形：空树
    出.push_back(根->值);             // ① 自己
    先序(根->左, 出);                 // ② 左
    先序(根->右, 出);                 // ③ 右
}

void 中序(树结点* 根, std::vector<int>& 出) {
    if (根 == nullptr) return;
    中序(根->左, 出);                 // ① 左
    出.push_back(根->值);             // ② 自己（在中间）
    中序(根->右, 出);                 // ③ 右
}

void 后序(树结点* 根, std::vector<int>& 出) {
    if (根 == nullptr) return;
    后序(根->左, 出);                 // ① 左
    后序(根->右, 出);                 // ② 右
    出.push_back(根->值);             // ③ 自己（在最后）
}

int 结点数(树结点* 根) {
    if (根 == nullptr) return 0;      // 空树 0 个
    return 1 + 结点数(根->左) + 结点数(根->右);
    //      ↑自己  ↑左子树那几个  ↑右子树那几个
}
""";

