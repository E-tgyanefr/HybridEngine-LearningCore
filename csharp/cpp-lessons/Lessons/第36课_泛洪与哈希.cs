// 第 36 课参考答案：泛洪数岛屿 + 哈希表数不同字符

// 从 (x, y) 出发，把相连的一整片陆地全部淹掉（1 变成 2）
void 淹(std::vector<std::vector<int>>& 图, int x, int y) {
    int 行 = (int)图.size();
    int 列 = (int)图[0].size();

    if (x < 0 || x >= 行 || y < 0 || y >= 列) return;   // ① 出界
    if (图[x][y] != 1) return;                           // ② 不是陆地（水，或者已经淹过）

    图[x][y] = 2;                                        // ③ **先标记**再来

    // ④ 只走**上下左右**四个方向 —— 斜对角不算相连
    淹(图, x + 1, y);
    淹(图, x - 1, y);
    淹(图, x, y + 1);
    淹(图, x, y - 1);
}

int 数岛屿(std::vector<std::vector<int>> 图) {
    if (图.empty() || 图[0].empty()) return 0;           // 空图

    int 行 = (int)图.size();
    int 列 = (int)图[0].size();
    int 个数 = 0;

    for (int i = 0; i < 行; i++) {
        for (int j = 0; j < 列; j++) {
            if (图[i][j] == 1) {
                // 能找到还是 1 的格子，说明它属于一座**还没被数过**的岛
                个数++;
                淹(图, i, j);        // 把整座岛淹掉，免得后面重复数
            }
        }
    }
    return 个数;
}

int 不同字符数(std::string s) {
    // 哈希表：键是字符，值是出现次数
    std::unordered_map<char, int> 次数;
    for (char c : s) {
        次数[c]++;               // 没见过就自动新建一格（值从 0 开始）
    }
    return (int)次数.size();      // 有几个键 = 有几种不同的字符
    // ⚠ 等价写法：开一个 int 见过[128] 的数组打勾最后数 ——
    //   字符的范围小，那样也行；键是字符串或大整数时才非哈希表不可。
}
""";

