                "      ⚠ 第一张图 {{1,1,0},{0,1,0},{1,0,1}} 的正确答案是 **3**，\n" +
                "        而你给出的是 1 —— 这是把**斜对角**也当成相连了。\n" +
                "        图上这三个 1 是这样的：\n" +
                "            1 1 .\n" +
                "            . 1 .        ← 中间这个跟左下、右下都是**斜着**挨着的\n" +
                "            1 . 1\n" +
                "        题目的规矩是**只算上下左右四个方向**：\n" +
                "            (0,0)-(0,1)-(1,1) 连成一座（这三个是上下/左右挨着的）\n" +
                "            (2,0) 自己一座（它跟 (1,1) 斜着，不算）\n" +
                "            (2,2) 自己一座\n" +
                "      ⚠ 别写 `for (dx = -1..1) for (dy = -1..1)` —— 那会把对角也算进去。\n" +
                "        四个方向就是：`x±1,y` 和 `x,y±1` 这四种。");

        return CheckResult.不过(
            "岛数不对：\n" +
            "      期望 " + 期望 + "\n" +
            "      实际 " + 显示(岛) + "\n" +
            "      （依次是 {{1,1,0},{0,1,0},{1,0,1}}、全 1 的 3×3、全 0、一行 1,0,1,0,1、\n" +
            "        3×4 一张、单个 {{1}}）\n" +
            "      算法：**从一块陆地出发，把相连的整片都淹掉**。\n" +
            "          void 淹(图, x, y) {\n" +
            "              if (出界) return;\n" +
            "              if (图[x][y] != 1) return;      // 水、或者已经淹过\n" +
            "              图[x][y] = 2;                   // ⚠ **先标记**再来\n" +
            "              淹(图, x+1, y); 淹(图, x-1, y); 淹(图, x, y+1); 淹(图, x, y-1);\n" +
            "          }\n" +
            "      外面数「还能找到几个 1」，就是几座岛。\n" +
            "      ⚠ 如果**程序崩了**：检查两句出口（出界 / 不是陆地）在不在，\n" +
            "        以及标记是不是放在了递归**之前**。少任何一样都会无限递归。\n" +
            "      ⚠ 全水（全 0）的答案是 0；{{1}} 的答案是 1；空图 {{}} 也要返回 0。");
    }

    [检查说明("★ 核心：不同字符数 —— 重复字符和带空格的都要对")]
    public static CheckResult 检查_不同字符数(string 代码)
    {
        // ⚠ 核心检查点之二。"zzzz"（答案 1）和 "hello world"（答案 8，含空格）
        //   是专门用来压"把几个例子的答案写死"那种解法的。
        var run = CppCheck.编译并运行(代码, 骨架, 调用点);
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        string 字 = 取值(run, "字");
        const string 期望 = "3,0,6,1,8";

        if (字 == 期望) return CheckResult.过("五组都对（含空串、只重复一种字符、带空格的句子）");

        return CheckResult.不过(
            "不同字符数不对：\n" +
            "      期望 " + 期望 + "（依次是「aabbbcc」、「」（空串）、「abcdef」、「zzzz」、「hello world」）\n" +
            "      实际 " + 显示(字) + "\n" +
            "      哈希表的写法（键是字符，值是出现次数）：\n" +
            "          std::unordered_map<char, int> 次数;\n" +
            "          for (char c : s) 次数[c]++;      // 没见过会自动新建一格\n" +
            "          return (int)次数.size();          // 有几个键 = 几种字符\n" +
            "      ⚠ `次数[c]++` 这一句里藏着一个很好用的规矩：\n" +
            "        用 `[]` 访问一个**不存在的键**时，unordered_map 会**自动新建**它，\n" +
            "        并把值初始化成 0 —— 所以不用先判断「在不在」。\n" +
            "      ⚠ 空串返回 0（表里一个键都没有）。\n" +
            "      ⚠ 「zzzz」返回 **1**，不是 4 —— 问的是「几种」，不是「几个」。\n" +
            "      ⚠ 「hello world」返回 **8**：h,e,l,o,空格,w,r,d —— 那个空格也算一种。");
    }

    [检查说明("用了哈希表（unordered_map）或桶计数数组")]
    public static CheckResult 检查_用了哈希(string 代码)
    {
        if (代码.Contains("unordered_map") || 代码.Contains("map<"))
            return CheckResult.过("用了 unordered_map —— 按键直接找");

        bool 有计数数组 = System.Text.RegularExpressions.Regex.IsMatch(代码, @"\[\s*\d+\s*\]\s*=\s*\{\s*0\s*\}")
                          || System.Text.RegularExpressions.Regex.IsMatch(代码, @"见过|计数|桶");
        if (有计数数组)
            return CheckResult.过("用了计数数组（桶计数）—— 字符范围小的时候这也够");

        return CheckResult.不过(
            "代码里没看到哈希表，也没看到计数数组。\n" +
            "      这一课要学的是「**给每个键准备一个格子，见过就打勾**」这个想法。\n" +
            "      最直接的写法：\n" +
            "          std::unordered_map<char, int> 次数;\n" +
            "          for (char c : s) 次数[c]++;\n" +
            "          return (int)次数.size();\n" +
            "      为什么它比「两个两个比」强：\n" +
            "          两个两个比（对每个字符回头看前面有没有出现过）是 O(n²) ——\n" +
            "            1 万个字要比 1 亿次；\n" +
            "          哈希表平均 O(1) 一次查找 —— 1 万个字只要约 1 万次。\n" +
            "      ⚠ 哈希表为什么能一步找到：先用**哈希函数**把键算成一个整数，\n" +
            "        再拿它取余得到「桶号」，直接跳到那个桶里去。\n" +
            "      ⚠ 字符的种数很少（最多 128 个 ASCII），所以开一个\n" +
            "        `int 见过[128]` 的数组打勾也完全可以 —— 那也是哈希的思想。");
    }

    private static string 取值(CppRun run, string 标记)
    {
        foreach (var 行 in run.行)
        {
            int i = 行.IndexOf('|');
            if (i > 0 && 行.Substring(0, i).Trim() == 标记) return 行.Substring(i + 1).Trim();
        }
        return null;
    }

    private static string 显示(string s) => s == null ? "（没拿到）" : (s.Length == 0 ? "（空）" : s);
}
