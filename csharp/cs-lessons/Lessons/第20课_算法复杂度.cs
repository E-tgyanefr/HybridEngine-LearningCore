    [检查说明("★ 冒泡并计数里没有现成排序（背公式 + Array.Sort 交差的会在这里露馅）")]
    public static CheckResult 检查_没用现成排序(string 代码)
    {
        string 净 = 课工具.去掉注释(代码);
        string 体 = 课工具.函数体(净, "冒泡排序并计数");
        if (体 == null)
            return CheckResult.不过("没找到「冒泡排序并计数」的方法体 —— 花括号写全了吗？");
        if (课工具.含(体, "Array.Sort", "OrderBy", "Sort("))
            return CheckResult.不过(
                "「冒泡排序并计数」里出现了现成的排序。\n" +
                "      这一课要的**不是排序结果**，是**亲手数出比较次数**：\n" +
                "          for (int i = 0; i < 数.Length - 1; i++)\n" +
                "              for (int j = 0; j < 数.Length - 1 - i; j++) {\n" +
                "                  比较次数++;                    ← 计数器在这里\n" +
                "                  if (数[j] > 数[j + 1]) { 交换 }\n" +
                "              }\n" +
                "      `Array.Sort(数); return n*(n-1)/2;` 的次数也对，可你没数过任何一次。");
        if (!课工具.含(体, "for", "while"))
            return CheckResult.不过("「冒泡排序并计数」里一个循环都没有 —— 那次数是从哪儿来的？");
        return CheckResult.过("是自己写的冒泡 + 计数器");
    }

