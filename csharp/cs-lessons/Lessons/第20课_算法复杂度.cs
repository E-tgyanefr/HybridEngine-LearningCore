    public static string 参考答案 => """
// 参考答案 —— 把「要跑多少次」数出来

// 1. 顺序查找：找到就停，找不到就是比完了整个数组
static int 线性查找(int[] 数, int 目标, out long 比较次数)
{
    比较次数 = 0;
    for (int i = 0; i < 数.Length; i++)
    {
        比较次数++;                    // 每比一次加一
        if (数[i] == 目标)
        {
            return i;
        }
    }
    return -1;                         // ⚠ 这条路上 比较次数 已经是 数.Length
}

// 2. 冒泡 + 计数：计数器跟着最内层的比较走
//    循环跑完，次数应当正好是 n(n-1)/2
static long 冒泡排序并计数(int[] 数)
{
    long 比较次数 = 0;
    for (int i = 0; i < 数.Length - 1; i++)
    {
        for (int j = 0; j < 数.Length - 1 - i; j++)
        {
            比较次数++;                // 这一次比较不管成不成立都算
            if (数[j] > 数[j + 1])
            {
                int 临时 = 数[j];
                数[j] = 数[j + 1];
                数[j + 1] = 临时;
            }
        }
    }
    return 比较次数;
}

// 3. 折半：n 每次变成「一半向上取整」，直到 1
static long 折半次数(long n)
{
    long 次数 = 0;
    while (n > 1)
    {
        n = (n + 1) / 2;               // 向上取整：3 → 2 → 1（2 次）
        次数++;
    }
    return 次数;
}
""";

