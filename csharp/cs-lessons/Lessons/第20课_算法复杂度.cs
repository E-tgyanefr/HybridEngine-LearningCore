// 第 20 课：算法复杂度 —— O(1) / O(n) / O(n²)，n=100000 时谁不能用
//
// ══ 这一课要教什么 ══
// 前几课写了循环、排了序，但一直没问过一句最要紧的话：**这个写法要跑多久**？
// 这一课要把「快不快」从感觉变成**可以数出来的东西** —— 比较次数。
//   取第一个元素          O(1)      跟 n 无关
//   顺序查找              O(n)      n 个数最多看 n 次
//   冒泡排序              O(n²)     n(n-1)/2 次比较
// 并且亲手算清那个让初学者吃亏的数字：n=100000 时冒泡要 **50 亿**次比较，
// 而顺序查找只要 10 万次 —— 差 5 万倍。这就是「复杂度」为什么要提前想。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**比较次数必须一次不差**。学生最容易在「找不到」时少算一次
//   （循环提前退出），所以专门喂了目标不在数组里的用例。
// 核心检查点二：**冒泡排序并计数必须真的排序**。
//   偷懒解法 `Array.Sort(数); return (long)数.Length * (数.Length - 1) / 2;`
//   输出和参考答案一模一样 —— 所以除了次数，还要检查数组真的被排好了，
//   并且（第三条）源码里不许出现 Array.Sort / OrderBy。
// 折半次数用 0/1/2/3/4/1000/1000000 七组：它把 O(log n) 的直觉钉死
//   （100 万只要 20 次）。

