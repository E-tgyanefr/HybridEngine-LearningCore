// 第 36 课的状态是一个数（一维数组）；这一课的状态是**两个**（一张表）：
//     网格路径数   dp[i, j] = dp[i-1, j] + dp[i, j-1]    从上面或左边过来
//     最长公共子序列 LCS
//                  dp[i, j] = 相同 ? dp[i-1, j-1] + 1
//                                   : max(dp[i-1, j], dp[i, j-1])
