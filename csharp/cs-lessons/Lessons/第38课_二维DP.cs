    public static string 参考答案 => """
// 参考答案 —— 二维 DP：一张表从左上填到右下

// 1. 路径数：每一格的路数 = 上面那格 + 左边那格
static long 路径数(int 行, int 列)
{
    long[,] dp = new long[行, 列];
    dp[0, 0] = 1;                        // 起点：站着不动算 1 条路
    for (int i = 0; i < 行; i++)
    {
        for (int j = 0; j < 列; j++)
        {
            if (i == 0 && j == 0)
            {
                continue;
            }
            long 从上来 = (i > 0) ? dp[i - 1, j] : 0;   // 第一行没有上面
            long 从左来 = (j > 0) ? dp[i, j - 1] : 0;   // 第一列没有左边
            dp[i, j] = 从上来 + 从左来;
        }
    }
    return dp[行 - 1, 列 - 1];
}

// 2. 有障碍：障碍那格的路数是 0；起点/终点是障碍就整体 0
static long 路径数有障碍(int[,] 格)
{
    int 行 = 格.GetLength(0);
    int 列 = 格.GetLength(1);
    if (格[0, 0] == 1 || 格[行 - 1, 列 - 1] == 1)
    {
        return 0;                        // ⚠ 必须先判，不然 dp[0,0] = 1 会顶出错误答案
    }
    long[,] dp = new long[行, 列];
    dp[0, 0] = 1;
    for (int i = 0; i < 行; i++)
    {
        for (int j = 0; j < 列; j++)
        {
            if (i == 0 && j == 0)
            {
                continue;
            }
            if (格[i, j] == 1)
            {
                dp[i, j] = 0;            // 障碍：走到这里没有路
                continue;
            }
            long 从上来 = (i > 0) ? dp[i - 1, j] : 0;
            long 从左来 = (j > 0) ? dp[i, j - 1] : 0;
            dp[i, j] = 从上来 + 从左来;
        }
    }
    return dp[行 - 1, 列 - 1];
}

// 3. 最长公共子序列：表比字符串**大一圈**（第 0 行/列表示空串）
static int 最长公共子序列(string 甲, string 乙)
{
    int n = 甲.Length, m = 乙.Length;
    int[,] dp = new int[n + 1, m + 1];   // dp[i, j] = 甲前 i 个 与 乙前 j 个 的 LCS
    for (int i = 1; i <= n; i++)
    {
        for (int j = 1; j <= m; j++)
        {
            if (甲[i - 1] == 乙[j - 1])          // ⚠ 下标错开一位
            {
                dp[i, j] = dp[i - 1, j - 1] + 1; // 这个字符能接上
            }
            else
            {
                dp[i, j] = Math.Max(dp[i - 1, j], dp[i, j - 1]);   // 扔掉一边
            }
        }
    }
    return dp[n, m];
}
""";

