//
// ══ 这一课要教什么 ══
// 贪心 = 每一步都选「当下看起来最好」的那个，不回头。它有时对、有时错：
//   · 找零（面额 25/10/5/1）：每次拿最大的 —— 对
//   · 区间调度：**按结束时间最早**的挑 —— 对；按开始时间最早 —— 错
// 这一课的重点是第二个：**同一道题，「贪什么」决定对错**，
// 而看出该贪什么正是这一课要练的眼力。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**区间调度必须按结束时间贪**。
//   数据是刻意设计过的：{1,4},{3,5},{0,6},{5,7},{3,9},{5,9},{6,10},{8,11},{8,12},{2,14},{12,16}
//     按结束时间 ⇒ 4 个（{1,4},{5,7},{8,11},{12,16}）
//     按开始时间 ⇒ 只有 3 个（{0,6},{6,10},{12,16}）
//   第三组 {1,10},{2,3},{4,5} 同样：按结束是 2，按开始是 1。
//   排序键写错的人拿到 3 / 1，被抓住 —— 而「结果看着也挺合理」，
//   不做对照数据是抓不出来的。
// 第二条：找零要处理「面额比金额大」（张数 0）和金额 0。
// 第三条（文本）：`最多活动` 里要出现排序（这一课的另一半是「先排序再贪」）。

