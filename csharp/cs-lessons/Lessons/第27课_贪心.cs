    [检查说明("最多活动里真的排了序（这一课的另一半是「先排序再贪」）")]
    public static CheckResult 检查_排过序(string 代码)
    {
        string 净 = 课工具.去掉注释(代码);
        string 体 = 课工具.函数体(净, "最多活动");
        if (体 == null)
            return CheckResult.不过("没找到「最多活动」的方法体 —— 花括号写全了吗？");
        if (!课工具.含(体, "OrderBy", "Array.Sort", "Sort("))
            return CheckResult.不过(
                "「最多活动」里没看到排序。\n" +
                "      区间调度必须先排序（按**结束时间**），再「能接就接」：\n" +
                "          var 排好的 = 区间.OrderBy(段 => 段[1]).ToList();\n" +
                "          foreach (var 段 in 排好的) if (段[0] >= 上次结束) { … }\n" +
                "      不排序直接遍历的话，结果取决于数据给的顺序 —— 检查里换一组就错。");
        return CheckResult.过("确实先排序再贪心");
    }

