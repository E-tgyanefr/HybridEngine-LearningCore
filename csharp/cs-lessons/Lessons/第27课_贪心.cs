    public static string 参考答案 => """
// 参考答案 —— 两处贪心：一处直白，一处要靠「按结束时间」

// 1. 找零：能拿大的就拿大的
static int[] 找零(int 金额, int[] 面额)
{
    int[] 张数 = new int[面额.Length];
    for (int i = 0; i < 面额.Length; i++)
    {
        张数[i] = 金额 / 面额[i];        // 这个面额能拿几张
        金额 = 金额 % 面额[i];           // 剩下的钱交给小面额
    }
    return 张数;
}

// 2. 区间调度：**先按结束时间排序**，再能接就接
static int 最多活动(int[][] 区间)
{
    // ⚠ 排序键是 段[1]（结束时间），不是 段[0]（开始时间）
    var 排好的 = 区间.OrderBy(段 => 段[1]).ToList();
    int 个数 = 0;
    int 上次结束 = int.MinValue;         // 第一个活动一定能接
    foreach (var 段 in 排好的)
    {
        if (段[0] >= 上次结束)            // 上一个结束后才开始 ⇒ 能参加
        {
            个数++;
            上次结束 = 段[1];
        }
    }
    return 个数;
}
""";

