    [检查说明("★ 三个手写排序里没有现成排序，而且都有你自己写的循环")]
    public static CheckResult 检查_没用现成排序(string 代码)
    {
        string 净 = 课工具.去掉注释(代码);
        var 缺 = new List<string>();
        foreach (var 名 in new[] { "冒泡排序", "选择排序", "插入排序" })
        {
            string 体 = 课工具.函数体(净, 名);
            if (体 == null) { 缺.Add("      " + 名 + "：没找到方法体（花括号写全了吗）"); continue; }
            if (课工具.含(体, "Array.Sort", "OrderBy", "Sort(", "List.Sort"))
                缺.Add("      " + 名 + "：里面出现了现成的排序 —— 这一课要自己写两层循环");
            else if (!课工具.含(体, "for", "while", "foreach"))
                缺.Add("      " + 名 + "：一个循环都没有 —— 排序是靠循环比出来的");
        }
        if (缺.Count == 0) return CheckResult.过("三个都是自己写的循环排序");

        return CheckResult.不过(
            "检查了去掉注释后的源码，发现问题：\n" + string.Join("\n", 缺) + "\n" +
            "      这一课要练的是**两层循环的边界**：\n" +
            "          冒泡  for (i) for (j < 长度-1-i)  比 数[j] 和 数[j+1]\n" +
            "          选择  for (i) for (j = i+1)      记最小的**下标**，一轮换一次\n" +
            "          插入  for (i) while (j >= 0 && 数[j] > 拿着) 往右挪\n" +
            "      `Array.Sort(数);` 输出确实对，但那是第 18 课**要学的东西**，不是答案。\n" +
            "      （`用库排` 那个方法里用 Array.Sort 是**对的** —— 它是留给你的对照。）");
    }

