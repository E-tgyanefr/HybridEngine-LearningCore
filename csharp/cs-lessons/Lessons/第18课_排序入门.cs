// 第 18 课：排序入门 —— 冒泡、选择、插入，和 Array.Sort 的对照
//
// ══ 这一课要教什么 ══
// 排序是「两层循环」最经典的一次实战。这一课要手写三种：
//     冒泡（比相邻两个，大的往后冒）  选择（每轮挑出最小的放前面）
//     插入（把新来的插进前面已排好的那一段）
// 三种思路完全不同，但**必须都练**：它们的复杂度都是 O(n²)（第 20 课的活教材），
// 插入天生**稳定**、选择**不稳定**（第 19 课回头要用），而考场不一定让调库。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**不许用现成的排序交差**。学生最省事的做法是 `Array.Sort(数)`，
//   输出完全正确，但这一课练的是「两层循环怎么控制边界」 —— 调库等于没学。
//   防法：去掉注释后按函数名切开源码，**三个手写函数体里**都不许出现
//   Array.Sort / OrderBy / Sort(；而且每个函数体里得有循环。
//   第二个防线是**七组数据**（重复元素、负数、已排序、逆序、长度 0/1）：
//   把答案抄成 `数[0]=1; 数[1]=2;` 的人只有一组能蒙对。
//   第 6 条检查是「用库排」的正面对照：`Array.Sort` 要排在**副本**上，原数组不许动。
//
// ⚠ 给维护者：学生写的是 void 就地排序 ⇒ 调用点用 `造语句调用点`（先调、再取值）。

