//
// 把 {5, 1, 4, 2} 排成 {1, 2, 4, 5}，计算机不会一眼看出来。
// 它只会做两件事：**比两个数**、**换两个数**。排序算法就是「按什么顺序去比、去换」。
//
// ─────────────────────────────────────────────────────
//  一、交换两个数：三行，顺序不能错
// ─────────────────────────────────────────────────────
//
//     int 临时 = 数[i];
//     数[i] = 数[j];
//     数[j] = 临时;
