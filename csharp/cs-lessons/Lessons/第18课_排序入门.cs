//         for (int j = i + 1; j < 数.Length; j++) {
//             if (数[j] < 数[最小]) { 最小 = j; }     ← 只记下标，不急着换
//         }
//         交换(数[i], 数[最小]);                      ← 一轮结束才换一次
//     }
//
// ⚠ 内层找的是**下标**（记在 最小 里），不是值。
//
// ─────────────────────────────────────────────────────
