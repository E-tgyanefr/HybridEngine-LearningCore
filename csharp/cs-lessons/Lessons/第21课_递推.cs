// 有 n 级台阶，每次只能上 1 级或 2 级，一共有几种上法？
//
//     爬楼梯(0) = 1      （一级都不上，也算一种「上法」）
//     爬楼梯(1) = 1      （1）
//     爬楼梯(2) = 2      （1+1、2）
//     爬楼梯(3) = 3      （1+1+1、1+2、2+1）
