    [检查说明("★ 爬楼梯 / 斐波那契 不许递归（这一课练的是从前往后填表）")]
    public static CheckResult 检查_不许递归(string 代码)
    {
        string 净 = 课工具.去掉注释(代码);
        var 递归了 = new List<string>();
        foreach (var 名 in new[] { "爬楼梯", "斐波那契" })
        {
            string 体 = 课工具.函数体(净, 名);
            if (体 == null) { 递归了.Add("      " + 名 + "：没找到方法体"); continue; }
            if (体.Contains(名 + "("))
                递归了.Add("      " + 名 + "：函数体里调用了自己（递归）");
        }
        if (递归了.Count == 0) return CheckResult.过("两个都是从前往后算的循环写法");

        return CheckResult.不过(
            "检查了去掉注释后的源码，发现问题：\n" + string.Join("\n", 递归了) + "\n" +
            "      这一课练的是**递推**（从前往后填表）：\n" +
            "          long 前前 = 起点1, 前 = 起点2;\n" +
            "          for (int i = 2; i <= n; i++) { 今 = 前前 + 前; 前前 = 前; 前 = 今; }\n" +
            "      同一条式子写成递归，n=45 要十几秒、n=90 要 10^18 次调用 —— 算不完。\n" +
            "      ⚠ 递归本身没错（第 28 课专门讲它），但这一课要你学会「先想能不能从前往后填」。");
    }

