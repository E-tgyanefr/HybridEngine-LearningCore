    public static string 参考答案 => """
// 参考答案 —— 递推：一张表从前往后填
//
// ⚠ 这一课的关键不是「写出来」，而是「**不递归**」：
//   同一条式子写成递归，n=90 就算不完了。

// 1. 爬楼梯：最后一步要么跨 1 级、要么跨 2 级
//    ⇒ 爬楼梯(n) = 爬楼梯(n-1) + 爬楼梯(n-2)，且 爬楼梯(0) = 1、爬楼梯(1) = 1
static long 爬楼梯(int n)
{
    if (n <= 1)
    {
        return 1;                    // 0 级也算 1 种；1 级只有一种上法
    }
    // 只要最后一项，两个变量滚动就够，不必开数组
    long 前前 = 1;                   // 爬到第 0 级的方法数
    long 前 = 1;                     // 爬到第 1 级的方法数
    for (int i = 2; i <= n; i++)
    {
        long 今 = 前前 + 前;
        前前 = 前;
        前 = 今;
    }
    return 前;
}

// 2. 斐波那契：同样的写法，只是起点是 0 和 1
static long 斐波那契(int n)
{
    if (n == 0)
    {
        return 0;                    // ⚠ 先拦掉 n=0，免得 表[1] 越界
    }
    if (n == 1)
    {
        return 1;
    }
    long 表前前 = 0;
    long 表前 = 1;
    for (int i = 2; i <= n; i++)
    {
        long 今 = 表前前 + 表前;
        表前前 = 表前;
        表前 = 今;
    }
    return 表前;
}

// 3. 斐波那契表：这一次真的把表填出来（看得见「从前往后」这件事）
static int[] 斐波那契表(int n)
{
    int[] 表 = new int[n];
    if (n == 0)
    {
        return 表;                   // 空数组（长度 0），不是 null
    }
    表[0] = 0;
    if (n == 1)
    {
        return 表;
    }
    表[1] = 1;
    for (int i = 2; i < n; i++)
    {
        表[i] = 表[i - 1] + 表[i - 2];   // 每个格子只算一次
    }
    return 表;
}
""";

