// 第 19 课：排序稳定性与 IComparer<T> —— 比较器怎么写、稳定为什么重要
//
// ══ 这一课要教什么 ══
// 排序不只是「把数从小到大排」。真实的问题几乎都是**按某个东西比较**：
// 成绩按分数、文件按修改时间、商品按价格。C# 把这个「怎么比」抽出来叫
// `IComparer<T>` —— 你写一个类，回答"这两个谁在前"。
// 这一课要建立两个概念：
//   · 比较器**只回答一个问题**（分数相同就必须返回 0，不许偷偷再比名字）；
//   · **稳定性**：分数相同的两个人，排完还保持原来的先后。
//     `OrderBy` 是稳定排序，`Array.Sort` / `List.Sort` 不是 —— 用哪个是有后果的。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**比较器在「同分」时必须返回 0**。
//   偷懒解法是「顺手把名字也比了」：
//     Compare = 甲.分数 != 乙.分数 ? 乙.分数.CompareTo(甲.分数)
//                                  : string.CompareOrdinal(甲.名字, 乙.名字);
//   它的输出**完全正确**（名字列表看起来一样），可它把「稳定性」这件事
//   从排序算法手里抢走了 —— 这一课要讲的正是「同分交给排序算法，比较器别多管」。
//   防法：调用点直接问 `Math.Sign(Compare(甲90, 乙90))`，它必须是 0。
// 第二条：**稳定性看得出来** —— 同一批分数、两种不同的输入先后，
//   输出顺序必须跟着输入变（`OrderBy` 稳定；换了 `List.Sort` 就对不上）。

