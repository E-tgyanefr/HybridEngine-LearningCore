    public static string 参考答案 => """
// 参考答案 —— 比较器 + 稳定性

record 成绩(string 名字, int 分数);

// 2. 比较器：**只回答「谁在前」**
//    ⚠ 分数相同要返回 0 —— 同分怎么排是排序算法的事（稳定性），不是比较器的事
class 按分数降序 : IComparer<成绩>
{
    public int Compare(成绩 甲, 成绩 乙)
    {
        // 乙在前 ⇒ 返回正数；甲在前 ⇒ 返回负数。降序就是「分数大的排前面」
        return 乙.分数.CompareTo(甲.分数);
    }
}

// 3. 同样的写法，比 int
class 按数值降序 : IComparer<int>
{
    public int Compare(int 甲, int 乙) => 乙.CompareTo(甲);
}

// 4. 排序用 OrderBy + 比较器：**OrderBy 是稳定排序**
static List<string> 降序名字(List<成绩> 们)
{
    return 们.OrderBy(项 => 项, new 按分数降序())
             .Select(项 => 项.名字)
             .ToList();
}

// 5. 就地降序：Array.Sort 的第二个参数就是比较器
static void 原地降序(int[] 数)
{
    Array.Sort(数, new 按数值降序());
}
""";

