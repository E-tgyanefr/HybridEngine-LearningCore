    public static string 参考答案 => """
// 参考答案 —— 三个一维 DP

// 1. 爬楼梯：f(n) = f(n-1) + f(n-2)
static long 爬楼梯(int n)
{
    if (n <= 1)
    {
        return 1;
    }
    long[] f = new long[n + 1];          // dp[i] = 到第 i 级的走法数
    f[0] = 1;                            // 边界：一级都不上也算一种
    f[1] = 1;
    for (int i = 2; i <= n; i++)
    {
        f[i] = f[i - 1] + f[i - 2];
    }
    return f[n];
}

// 2. 打家劫舍：偷 / 不偷，取大的
static long 打家劫舍(int[] 房)
{
    if (房.Length == 0)
    {
        return 0;
    }
    // 状态：dp[i] = 只考虑**前 i 家**能拿到的最多钱
    // 多留一格 dp[0] = 0，这样 i=1 时 dp[i-2] 不会越界
    long[] dp = new long[房.Length + 1];
    dp[0] = 0;
    for (int i = 1; i <= 房.Length; i++)
    {
        long 不偷 = dp[i - 1];
        // ⚠ i == 1 时没有"上一家"，dp[i-2] 会越界 ⇒ 单独给它 0
        long 偷 = (i >= 2 ? dp[i - 2] : 0) + 房[i - 1];   // 偷了它，上一家就不能偷
        dp[i] = Math.Max(不偷, 偷);
    }
    return dp[房.Length];
}

// 3. 01 背包：容量**倒着**遍历
static long 背包(int[] 重, int[] 值, int 容量)
{
    long[] dp = new long[容量 + 1];        // dp[j] = 容量 j 能装的最大价值
    for (int i = 0; i < 重.Length; i++)
    {
        // ⚠ 倒着走：保证 dp[j - 重[i]] 还是「没放第 i 件」时的值
        for (int j = 容量; j >= 重[i]; j--)
        {
            dp[j] = Math.Max(dp[j], dp[j - 重[i]] + 值[i]);
        }
    }
    return dp[容量];
}
""";

