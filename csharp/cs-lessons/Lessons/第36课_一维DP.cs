// 第 36 课：一维 DP —— 爬楼梯、打家劫舍、01 背包
//
// ══ 这一课要教什么 ══
// 动态规划（DP）就三步：**定义状态 → 写转移式 → 定初值/边界**。
// 这一课三个题都是「一维」的（一个数组从头填到尾）：
//     爬楼梯    f(n) = f(n-1) + f(n-2)          第 21 课已经见过（那叫递推）
//     打家劫舍  f(i) = max(f(i-1), f(i-2) + 房[i])   相邻不能都偷
//     01 背包   dp[j] = max(dp[j], dp[j-重] + 值)    容量**倒着**遍历
// 01 背包里「容量倒着遍历」这一条是本课的核心：正着遍历会让同一件物品被拿多次，
// 那就变成了**完全背包** —— 而它照样能过一部分数据，只有专门的数据能抓出来。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**01 背包只能拿一次**。
//   两条判据：`重{3} 值{5} 容量9` ⇒ **5**（完全背包会得 15）；
//             `重{2,3} 值{3,4} 容量6` ⇒ **7**（完全背包会得 9：拿三件重 2 的）。
//   只对第一组做判据是不够的（有人正着遍历却在第一组上碰巧对）。
// 第二条：打家劫舍的「相邻不能都偷」（{2,1,4,9} ⇒ 11，不能 4+9）。
// 边界：空数组、只有一家、容量 0、没有物品。

