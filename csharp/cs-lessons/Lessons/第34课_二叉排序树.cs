    [检查说明("★ 查找用的是 BST 的性质（不许把整棵树收进 List 再找）")]
    public static CheckResult 检查_查找用性质(string 代码)
    {
        string 净 = 课工具.去掉注释(代码);
        string 体 = 课工具.函数体(净, "查找");
        if (体 == null)
            return CheckResult.不过("没找到「查找」的方法体 —— 花括号写全了吗？");
        if (课工具.含(体, "List", "foreach", "中序", "先序", "后序", "ToArray"))
            return CheckResult.不过(
                "「查找」里把整棵树收集起来了（出现了 List / foreach / 中序…）。\n" +
                "      那样查找是 **O(n)**，而 BST 的全部意义就是**一次扔掉一半**：\n" +
                "          while (当前 != null) {\n" +
                "              if (值 == 当前.值) return true;\n" +
                "              if (值 < 当前.值) 当前 = 当前.左;   // 小 ⇒ 只可能在左边\n" +
                "              else              当前 = 当前.右;\n" +
                "          }\n" +
                "          return false;\n" +
                "      收集再找的输出也对，但那是「把树当数组用」，不是这一课要学的。");
        return CheckResult.过("查找是沿着一棵树往下走的");
    }

