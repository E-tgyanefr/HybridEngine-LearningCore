    public static string 参考答案 => """
// 参考答案 —— 二叉排序树：插入与查找

class 树结点
{
    public int 值;
    public 树结点 左;
    public 树结点 右;
    public 树结点(int 值)
    {
        this.值 = 值;
    }
}

// 插入：比大小往下走，走到空位就放；值已存在就不插
static 树结点 插入(树结点 根, int 值)
{
    if (根 == null)
    {
        return new 树结点(值);            // 空位 —— 新结点就放这里
    }
    if (值 == 根.值)
    {
        return 根;                        // 已经有了，什么都不做
    }
    if (值 < 根.值)
    {
        根.左 = 插入(根.左, 值);          // ⚠ 返回值一定要接住
    }
    else
    {
        根.右 = 插入(根.右, 值);
    }
    return 根;
}

// 查找：小往左、大往右 —— 每次扔掉一半
static bool 查找(树结点 根, int 值)
{
    树结点 当前 = 根;
    while (当前 != null)
    {
        if (值 == 当前.值)
        {
            return true;
        }
        if (值 < 当前.值)
        {
            当前 = 当前.左;
        }
        else
        {
            当前 = 当前.右;
        }
    }
    return false;
}

// 中序：左 → 自己 → 右。在 BST 上它就是**从小到大**
static List<int> 中序(树结点 根)
{
    var 出 = new List<int>();
    收(根, 出);
    return 出;
}

static void 收(树结点 根, List<int> 出)
{
    if (根 == null)
    {
        return;
    }
    收(根.左, 出);
    出.Add(根.值);
    收(根.右, 出);
}

// 高度：左右取大的 + 1
static int 高度(树结点 根)
{
    if (根 == null)
    {
        return 0;
    }
    int 左 = 高度(根.左);
    int 右 = 高度(根.右);
    return (左 > 右 ? 左 : 右) + 1;
}
""";

