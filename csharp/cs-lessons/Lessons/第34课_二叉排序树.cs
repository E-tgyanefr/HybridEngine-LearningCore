// 第 34 课：二叉排序树 —— 插入与查找
//
// ══ 这一课要教什么 ══
// 给二叉树加一条规矩，它就从「随便一棵树」变成**能查的树**：
//     **左子树上的都比我小，右子树上的都比我大**
// 于是查找不用把整棵树看一遍：比当前结点小就往左、大就往右，
// 一次扔掉一半 —— 和二分查找（第 26 课）是同一个想法，只是长在树上了。
// 代价是：如果按**从小到大**的顺序插入，树会退化成一条链（深度 n），
// 查找也退化成 O(n) —— 这是这一课必须看见的最坏情况。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**中序遍历必须严格升序**（而且重复值只出现一次）。
//   插入写错（比如该往左的往右）会立刻在这里露馅 —— 而且检查喂了四组插入序列：
//   普通、含重复、已排序（退化成链）、空树插入。
// 核心检查点二：**查找要用 BST 的性质往下走**（文本判据：函数体里不许出现
//   `List` / `foreach` / `中序` / `先序` / `后序`）。
//   把整棵树收进 List 再 Contains 的输出也完全正确，但那不是「能查的树」 ——
//   那样查找是 O(n)，这一课白上。
// 边界：空树插入、空树查找、重复值不重复插入（中序里不能出现两个 5）。

