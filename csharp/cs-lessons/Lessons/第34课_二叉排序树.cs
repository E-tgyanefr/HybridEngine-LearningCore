//
// 这一课讲一件事：**给树加一条规矩，它就能用来找东西**。
// ─────────────────────────────────────────────────────
//  这一课你会学到
// ─────────────────────────────────────────────────────
//    二叉排序树（BST）的插入与查找；为什么它会退化
//
//  需要先会
//    第 33 课：二叉树与三种遍历；第 26 课：二分查找（同一个想法）
//
// ─────────────────────────────────────────────────────
//  先介绍：一条规矩
// ─────────────────────────────────────────────────────
//
//     左子树上所有结点都比根小，右子树上所有结点都比根大。
//
// 依次插入 5, 3, 8, 1, 4, 7, 9 得到：
//
//                 5
//               /   \
//              3     8
//             / \   / \
//            1   4 7   9
//
// 它的**中序**正好是 1,3,4,5,7,8,9 —— **排好序的**。
// 这不是巧合：中序是「左 → 自己 → 右」，而规矩就是「左小右大」。
//
// ─────────────────────────────────────────────────────
//  一、查找：比大小，一次扔掉一半
// ─────────────────────────────────────────────────────
//
//     static bool 查找(树结点 根, int 值) {
//         while (根 != null) {
//             if (值 == 根.值) return true;
//             if (值 < 根.值) 根 = 根.左;        ← 小 ⇒ 只可能在左边
//             else            根 = 根.右;
//         }
//         return false;
//     }
//
// 7 个结点的树最多比 3 次（树的深度）。这和二分查找（第 26 课）是同一个想法：
//   **每次都把不可能的半边扔掉**。
//
// ⚠ 前提是树是「平衡」的 —— 见下面第三节。
//
// ─────────────────────────────────────────────────────
//  二、插入：一路比下去，走到空位就放
//   ─────────────────────────────────────────────────────
//
//     static 树结点 插入(树结点 根, int 值) {
//         if (根 == null) return new 树结点(值);        ← 空位：放这里
//         if (值 == 根.值) return 根;                   ← 已经有了：什么都不做
//         if (值 < 根.值) 根.左 = 插入(根.左, 值);
//         else            根.右 = 插入(根.右, 值);
//         return 根;                                    ← ⚠ 返回根
//     }
//
// ⚠ 为什么「返回新的根」而不是用 `ref`：根结点本身也可能被替换
//   （往**空树**里插第一个值时就是这种情况）。C# 里让插入返回根是最省事的写法：
//
//         根 = 插入(根, 值);
//
// ─────────────────────────────────────────────────────
//  三、最坏情况：插入顺序决定树的形状
// ─────────────────────────────────────────────────────
//
// 按 1, 2, 3, 4 的顺序插入：
//
//         1
//          \
//           2
//            \
//             3
//              \
//               4          ← 退化成一条链，深度 4、查找要 4 次
//
//     普通顺序（5,3,8,…）7 个结点深度 3
//     已排序顺序         n 个结点深度 **n**
//
// ⇒ 平均 O(log n)，最坏 O(n)。工程上的解法是「平衡树」（AVL / 红黑树）——
//   .NET 的 `SortedDictionary` 底层就是红黑树，这一课不涉及，但你要知道**有这回事**。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：`根.左 = 插入(根.左, 值);` 忘了接回去
// ─────────────────────────────────────────────────────
//
//     static 树结点 插入(树结点 根, int 值) {
//         if (根 == null) return new 树结点(值);
//         if (值 < 根.值) 插入(根.左, 值);       ← 返回值没接住
//         else            插入(根.右, 值);
//         return 根;
//     }
//
// 你会看到：**编译通过、不报错**，可是往空树里插第一个值之后，根还是 null ——
//   后面插入的一切都**丢进了临时对象里**，中序出来是空的。
//
// 为什么：`插入(根.左, 值)` 新建了一个结点并**返回**它，可你没把它挂回 `根.左`。
//   ⇒ 递归函数的返回值**必须接住**：`根.左 = 插入(根.左, 值);`
//
// 顺便：往空树插入时 `根` 是 null，只能靠返回值把新根交出去，所以
//   调用点也得写成 `根 = 插入(根, 值);`。
//
