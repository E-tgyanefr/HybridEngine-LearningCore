// 第 35 课：DFS 与 BFS —— 用 int[,] 表示迷宫，BFS 找最短步数
//
// ══ 这一课要教什么 ══
// 迷宫就是一张 `int[,]`（0 通路、1 墙），"走迷宫"是**图上的遍历**在网格上的样子。
// 两种走法：
//     DFS（深度优先）用栈/递归：一条路走到黑，撞墙再回头 —— 能回答「能不能到」
//     BFS（广度优先）用队列：一圈一圈往外扩 —— 能回答「**最少几步**到」
// 为什么「最少步数」必须用 BFS：BFS 是**按步数分层**扩展的，
// 第一次碰到终点时走的步数就是最少的；DFS 找到的第一条路可能绕了很远。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**不可达要返回 -1**（迷宫丙、戊）。
//   返回 0、返回 int.MaxValue、或者把 -1 和 0 混起来的人会被抓住
//   （0 步的意思是「起点就是终点」，那是另一回事）。
// 核心检查点二：**必须绕路的迷宫（己）**：直线走不通，得沿蛇形长廊绕一大圈（12 步）。
//   只朝一个方向走、或者忘了标记「访问过」（会在两个格子之间来回转）的写法算不出来。
// 核心检查点三：**可达格子数**（甲 11、乙 7、己 32）—— 数重了会偏大，
//   这也是「访问过要标记」的第二个证据。
// 边界：1×1 的迷宫、起点是墙、起点即终点。

