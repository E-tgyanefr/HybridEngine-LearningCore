// 它找到的第一条路可能绕了一大圈 —— 想拿 DFS 求最短路，就得把所有路都试一遍再取最小。
//
// ⚠ 所以：**「能不能到」两个都行；「最少几步」用 BFS。**
//
// ─────────────────────────────────────────────────────
//  三、四个方向：写成两个小数组最省事
