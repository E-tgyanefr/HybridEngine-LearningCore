    public static string 参考答案 => """
// 参考答案 —— 网格上的 BFS

// 1. 最短步数：BFS 一圈一圈往外扩，第一次碰到终点就是最少步数
static int 最短步数(int[,] 迷宫, int 起行, int 起列, int 止行, int 止列)
{
    int 行数 = 迷宫.GetLength(0);
    int 列数 = 迷宫.GetLength(1);
    if (迷宫[起行, 起列] == 1 || 迷宫[止行, 止列] == 1)
    {
        return -1;                                  // 起点或终点是墙
    }

    int[,] 步 = new int[行数, 列数];
    for (int i = 0; i < 行数; i++)
        for (int j = 0; j < 列数; j++)
            步[i, j] = -1;                          // -1 = 还没到过
    步[起行, 起列] = 0;                              // 起点用了 0 步

    var 队 = new Queue<(int 行, int 列)>();
    队.Enqueue((起行, 起列));

    int[] 行移 = { -1, 1, 0, 0 };                    // 上 下 左 右
    int[] 列移 = { 0, 0, -1, 1 };

    while (队.Count > 0)
    {
        var (行, 列) = 队.Dequeue();
        for (int d = 0; d < 4; d++)
        {
            int 新行 = 行 + 行移[d];
            int 新列 = 列 + 列移[d];
            // ⚠ 先判界，再访问数组
            if (新行 < 0 || 新行 >= 行数 || 新列 < 0 || 新列 >= 列数) continue;
            if (迷宫[新行, 新列] == 1) continue;      // 是墙
            if (步[新行, 新列] != -1) continue;       // ⚠ 已经到过 —— 少了这句会死循环
            步[新行, 新列] = 步[行, 列] + 1;
            队.Enqueue((新行, 新列));
        }
    }
    return 步[止行, 止列];                           // 没到过就是 -1
}

// 2. 可达格子数：同一套 BFS，数一数走了几格
static int 可达格子数(int[,] 迷宫, int 起行, int 起列)
{
    int 行数 = 迷宫.GetLength(0);
    int 列数 = 迷宫.GetLength(1);
    if (迷宫[起行, 起列] == 1)
    {
        return 0;                                   // 起点就是墙
    }

    bool[,] 到过 = new bool[行数, 列数];
    到过[起行, 起列] = true;
    int 个数 = 1;                                    // 含起点自己

    var 队 = new Queue<(int 行, int 列)>();
    队.Enqueue((起行, 起列));
    int[] 行移 = { -1, 1, 0, 0 };
    int[] 列移 = { 0, 0, -1, 1 };

    while (队.Count > 0)
    {
        var (行, 列) = 队.Dequeue();
        for (int d = 0; d < 4; d++)
        {
            int 新行 = 行 + 行移[d];
            int 新列 = 列 + 列移[d];
            if (新行 < 0 || 新行 >= 行数 || 新列 < 0 || 新列 >= 列数) continue;
            if (迷宫[新行, 新列] == 1) continue;
            if (到过[新行, 新列]) continue;            // 每格只数一次
            到过[新行, 新列] = true;
            个数++;
            队.Enqueue((新行, 新列));
        }
    }
    return 个数;
}
""";

