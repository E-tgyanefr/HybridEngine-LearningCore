    public static string 参考答案 => """
// 参考答案 —— Math + 浮点误差的三个坑

// 1. 两点距离：勾股定理
static double 两点距离(double x1, double y1, double x2, double y2)
{
    double 横 = x1 - x2;
    double 纵 = y1 - y2;
    return Math.Sqrt(横 * 横 + 纵 * 纵);
}

// 2. 圆面积：π 用 Math.PI（别自己写 3.14）
static double 圆面积(double 半径)
{
    return Math.PI * 半径 * 半径;
}

// 3. 几乎相等：**容差**，绝不拿 == 比小数
static bool 几乎相等(double 甲, double 乙)
{
    return Math.Abs(甲 - 乙) < 1e-9;
}

// 4. 四舍五入：Math.Floor(x + 0.5)
//    ⚠ Math.Round(2.5) 是 2（银行家舍入），不是课本里的四舍五入
static double 四舍五入(double x)
{
    return Math.Floor(x + 0.5);
}

// 5. 整数平方根：Math.Sqrt 起步 + 上下修正
static long 整数平方根(long n)
{
    if (n <= 0)
    {
        return 0;
    }
    long r = (long)Math.Sqrt(n);          // 起步（可能差 1）
    // ⚠ 用 r <= n / r 而不是 r * r <= n：十亿级别的 r*r 会溢出 long
    while ((r + 1) <= n / (r + 1))
    {
        r++;                              // 往上顶
    }
    while (r > 0 && r > n / r)
    {
        r--;                              // 往下压
    }
    return r;
}
""";

