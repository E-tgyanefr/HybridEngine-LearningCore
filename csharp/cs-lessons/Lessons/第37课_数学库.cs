// ══ 这一课要教什么 ══
// .NET 的数学工具都在 `Math` 里：`Sqrt / Pow / Abs / Floor / Ceiling / Round / Max / Min`
// 和常量 `Math.PI`。但这一课真正要建立的是**对 double 的不信任感**：
//   · `0.1 + 0.2` **不等于** `0.3`（差 5.5e-17）—— 所以比小数要用**容差**
//   · `Math.Round` 用的是**银行家舍入**：`Math.Round(2.5)` 是 **2**，不是 3
//   · `Math.Sqrt` 本身有误差：`Math.Sqrt(999999999999999999)` 返回 1000000000，
//     而真正的 ⌊√n⌋ 是 999999999 —— 所以要「起步 + 上下修正」
// 这三条都是**真会算错结果**的，而且不会报错。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**几乎相等(0.1 + 0.2, 0.3) 必须是真**。
//   写成 `甲 == 乙` 的人在浮点上必输（0.1+0.2 = 0.30000000000000004）。
// 核心检查点二：**四舍五入(2.5) = 3**，而 `Math.Round(2.5)` 是 **2**。
//   正确写法是 `Math.Floor(x + 0.5)`。
// 核心检查点三：**整数平方根(999999999999999999) = 999999999**。
//   直接 `(long)Math.Sqrt(n)` 会返回 1000000000（本机实测），所以要修正。
// ⚠ double 的结果一律用 `ToString("F6")` 比字符串，**不拿 double 直接 ==**
