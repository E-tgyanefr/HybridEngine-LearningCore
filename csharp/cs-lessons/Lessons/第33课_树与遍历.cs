// 第 33 课：树与遍历 —— 二叉树的三种遍历（递归）
//
// ══ 这一课要教什么 ══
// 链表每个结点只有一个「下一站」，树有**两个**（左、右）—— 于是就有了「顺序」这件事：
//     先序  自己 → 左 → 右       （先处理自己）
//     中序  左 → 自己 → 右       （二叉排序树里它就是**从小到大**，第 34 课用）
//     后序  左 → 右 → 自己       （最后处理自己，算深度/释放资源常用）
// 三种遍历的代码只差一行，可结果是三份不同的序列 —— 而它们全靠**递归**。
// 这一课也是「自引用类型」的第二次练习（第一次是链表）。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**三种序必须互不相同、而且各自正确**。
//   把先序写成中序（或者三个都返回同一种）是很容易发生的「看着对」 ——
//   因为单独看一个列表，你不知道它对应哪种遍历。同一棵树给三份输出就能对上。
// 核心检查点二：**空树**（null）。三种遍历返回空列表、深度 0 ——
//   递归没有基准情形的人在这里抛 NullReferenceException。
// 数据：甲（完整三层）、乙（单结点）、丙（只用左孩子的斜树，深度 4）、丁（null）。
// ⚠ `树结点` 的字段必须是 public（调用点用对象初始值设定项建树）。

