    [检查说明("★ 三种遍历确实互不相同（把三个都写成同一种会被抓住）")]
    public static CheckResult 检查_三种不一样(string 代码)
    {
        var run = 课工具.跑一次(代码, 调用点());
        if (!run.编译通过) return CppCheck.编译失败说明(run);
        string 先 = 课工具.取标记(run, "甲先");
        string 中 = 课工具.取标记(run, "甲中");
        string 后 = 课工具.取标记(run, "甲后");
        if (先 == null || 中 == null || 后 == null)
            return CheckResult.不过("三组输出没齐 —— 先看看前面那条三种遍历的检查。");
        if (先 == 中 && 中 == 后)
            return CheckResult.不过(
                "先序 / 中序 / 后序 给出的是**同一份**序列（" + 先 + "）。\n" +
                "      三种遍历只差一行 `出.Add(根.值)` 的位置：\n" +
                "          先序  出.Add → 左 → 右\n" +
                "          中序  左 → 出.Add → 右\n" +
                "          后序  左 → 右 → 出.Add\n" +
                "      甲树的三份答案应当是 1,2,4,5,3 / 4,2,5,1,3 / 4,5,2,3,1。");
        return CheckResult.过("三份输出不同 —— 三种遍历是真分开写的");
    }

