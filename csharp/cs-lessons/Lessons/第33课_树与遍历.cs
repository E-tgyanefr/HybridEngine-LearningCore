    public static string 模板 => """
// 第 33 课：树与遍历 —— 二叉树的三种遍历（递归）
// ─────────────────────────────────────────────────────
//  怎么读这一课
// ─────────────────────────────────────────────────────
//
//   先从头读一遍讲解，再照着最后的「轮到你了」写。
//   卡住了看答案（先自己写一遍）—— 命令在「怎么自己测」那一节。
//
// 这一课讲一件事：**每个结点有两个「下一站」** —— 于是「先看哪个」变成了一门学问。
// ─────────────────────────────────────────────────────
//  这一课你会学到
// ─────────────────────────────────────────────────────
//    二叉树结点、先序 / 中序 / 后序遍历（递归）、深度
//
//  需要先会
//    第 28 课：递归（三种遍历都是递归）；第 32 课：链表（自引用类型）
//
// ─────────────────────────────────────────────────────
//  先介绍：从链表到树
// ─────────────────────────────────────────────────────
//
// 链表的结点长这样：`[值 | 下]` —— 一条线。
// 二叉树的结点长这样：`[值 | 左 | 右]` —— 分岔：
//
//                 1
//               /   \
//              2     3
//             / \
//            4   5
//
// 为什么要有树：**分岔的结构**到处都是 —— 目录、表达式、家族关系、
// 二叉排序树（第 34 课）、堆（第 40 课的优先队列底层）。
//
// ─────────────────────────────────────────────────────
//  一、结点类：两个「下一个」
// ─────────────────────────────────────────────────────
//
//     class 树结点 {
//         public int 值;
//         public 树结点 左;         ← 左孩子（没有就是 null）
//         public 树结点 右;
//         public 树结点(int 值) { this.值 = 值; }
//     }
//
// 一棵树 = 一个根结点（`树结点 根 = …`）。**空树就是 null**。
//
// 调用点是这样建树的（对象初始值设定项，第 07 课的写法）：
//
//     var 甲 = new 树结点(1) {
//         左 = new 树结点(2) { 左 = new 树结点(4), 右 = new 树结点(5) },
//         右 = new 树结点(3)
//     };
//
// ─────────────────────────────────────────────────────
//  二、三种遍历：代码只差一行的位置
// ─────────────────────────────────────────────────────
//
//     static void 先序(树结点 根, List<int> 出) {
//         if (根 == null) return;          ← 基准情形（空树什么都不做）
//         出.Add(根.值);                    ← 自己
//         先序(根.左, 出);                  ← 左
//         先序(根.右, 出);                  ← 右
//     }
//
// 把 `出.Add(根.值)` 挪到中间就是**中序**（左 → 自己 → 右），
// 挪到最后就是**后序**（左 → 右 → 自己）。
//
// 上面那棵树的结果（**三种完全不同**，自己对着树数一遍）：
//
//     先序  1, 2, 4, 5, 3
//     中序  4, 2, 5, 1, 3
//     后序  4, 5, 2, 3, 1
//
// ─────────────────────────────────────────────────────
//  三、深度：左右取大的那个，再加一
// ─────────────────────────────────────────────────────
//
//     static int 深度(树结点 根) {
//         if (根 == null) return 0;                       ← 空树深度 0
//         int 左 = 深度(根.左);
//         int 右 = 深度(根.右);
//         return (左 > 右 ? 左 : 右) + 1;                  ← ⚠ 别忘了 +1（自己这一层）
//     }
//
// 上面那棵树的深度是 **3**；只用左孩子的斜树 1-2-3-4 深度是 **4**。
//
// ⚠ 别写成 `左 + 右 + 1` —— 那是**结点总数**，不是深度。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：忘了判 null（基准情形）
// ─────────────────────────────────────────────────────
//
//     static List<int> 先序(树结点 根) {
//         var 出 = new List<int>();
//         出.Add(根.值);                  ← 根是 null 时炸在这里
//         先序(根.左);
//         先序(根.右);
//         return 出;
//     }
//
// 你会看到运行时异常：
//
//     NullReferenceException: Object reference not set to an instance of an object.
//
// 每一个叶子结点的 左/右 都是 null —— 递归一定会走到它们身上。
//   ⇒ **`if (根 == null) return …;` 必须是第一句**（这一课和链表课是同一个道理）。
//
// 另一个真会撞上的编译错（csc 原话）：
//
//     static int 深度(树结点 根) { if (根 == null) return 0; }   ← 少了最后的 return
//     error CS0161: "深度(树结点)": 并非所有代码路径都返回值
//
// ─────────────────────────────────────────────────────
//  这一课不碰什么
// ─────────────────────────────────────────────────────
//   二叉**排序**树的插入与查找 → 第 34 课。
//   层序遍历（用队列，一行一行打）→ 第 35 课的 BFS 会讲同样的思路。
//
// ─────────────────────────────────────────────────────
//  ══ 轮到你了 ══
// ─────────────────────────────────────────────────────
//
//   在下面写这些：
//
//    1. class 树结点
//         public int 值;  public 树结点 左;  public 树结点 右;
//         构造方法 树结点(int 值)
//         ⚠ 字段必须 **public**（调用点要直接给 左 / 右 赋值）
//
//    2. static List<int> 先序(树结点 根)     自己 → 左 → 右
//    3. static List<int> 中序(树结点 根)     左 → 自己 → 右
//    4. static List<int> 后序(树结点 根)     左 → 右 → 自己
//    5. static int 深度(树结点 根)           空树 → 0
//
//   ⚠ 空树是 null：三种遍历返回**空列表**（不是 null）、深度是 0。
//   ⚠ 可以用上面那个 `先序(根, 出)` 的私有辅助方法，也可以直接在方法里收集。
//
// ─────────────────────────────────────────────────────
//  怎么自己测
// ─────────────────────────────────────────────────────
//     点界面上的「检查」。卡住了看答案（先自己写一遍）。
//
// ── 在下面写 ──
""";

    public static string 参考答案 => """
// 参考答案 —— 二叉树的三种遍历 + 深度

class 树结点
{
    public int 值;                  // ⚠ public：调用点要直接读写
    public 树结点 左;
    public 树结点 右;
    public 树结点(int 值)
    {
        this.值 = 值;
    }
}

// 先序：自己 → 左 → 右
static List<int> 先序(树结点 根)
{
    var 出 = new List<int>();
    收先(根, 出);
    return 出;
}

static void 收先(树结点 根, List<int> 出)
{
    if (根 == null)
    {
        return;                     // ⚠ 基准情形：空树什么都不做
    }
    出.Add(根.值);                   // 自己
    收先(根.左, 出);                 // 左
    收先(根.右, 出);                 // 右
}

// 中序：左 → 自己 → 右
static List<int> 中序(树结点 根)
{
    var 出 = new List<int>();
    收中(根, 出);
    return 出;
}

static void 收中(树结点 根, List<int> 出)
{
    if (根 == null)
    {
        return;
    }
    收中(根.左, 出);                 // 左
    出.Add(根.值);                   // 自己
    收中(根.右, 出);                 // 右
}

// 后序：左 → 右 → 自己
static List<int> 后序(树结点 根)
{
    var 出 = new List<int>();
    收后(根, 出);
    return 出;
}

static void 收后(树结点 根, List<int> 出)
{
    if (根 == null)
    {
        return;
    }
    收后(根.左, 出);
    收后(根.右, 出);
    出.Add(根.值);                   // 自己放在最后
}

// 深度：左右取大的，再加自己这一层
static int 深度(树结点 根)
{
    if (根 == null)
    {
        return 0;                   // 空树深度 0
    }
    int 左 = 深度(根.左);
    int 右 = 深度(根.右);
    return (左 > 右 ? 左 : 右) + 1;  // ⚠ 别写成 左 + 右 + 1（那是结点数）
}
""";

