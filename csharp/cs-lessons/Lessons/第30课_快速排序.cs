// 第 30 课：快速排序 —— 手写 partition，最坏情况
//
// ══ 这一课要教什么 ══
// 快排是另一种分治，但它和归并的区别很关键：**分完再合**（归并）变成
// **先分好，合的时候什么都不用做**（快排）。核心是 `分区`（partition）：
// 选一个基准（pivot），把比它小的挪到左边、大的挪到右边，返回基准的最终位置；
// 然后左右两段各自再分。平均 O(n log n)，而且**原地**、不用额外数组。
// 但它有个真实的弱点：**基准选得不好会退化成 O(n²)** ——
// Lomuto 写法固定取最右边的元素当基准，遇到「已经排好序」的输入，
// 每次分区都只切掉一个元素，n=100000 时递归 n 层、比较约 50 亿次。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**分区语义**（不指定学生内部怎么换）。
//   调用点把返回下标 p 和数组内容都打出来，检查方法自己验证：
//   ① 数[p] == 原来的 数[右]（基准放对了） ② 左边都 ≤ 它、右边都 ≥ 它
//   ③ 元素一个没丢（多重集相同）。「直接排序整个数组」或返回错下标都会挂。
//   还喂了一段**子区间** `分区(数, 1, 4)`：区间外的元素不许动 ——
//   递归排序靠的就是「只在 [左,右] 里分区」。
// 核心检查点二：**20 万个随机数要在 3 秒内排完**（快排只需几十毫秒）。
//   拿冒泡/选择排序交差的人这里要几十秒。
//   ⚠ 阈值宽松（本机实测快排几毫秒到几十毫秒），而且失败提示里写明实测毫秒。
//   ⚠ 特意**不用「已排序输入」当判据** —— Lomuto 遇到有序数组本来就慢，
//     那是这一课要讲的「最坏情况」，不是判错的理由。
// 文本判据：`快速排序` / `分区` 里不许出现 Array.Sort / OrderBy。

