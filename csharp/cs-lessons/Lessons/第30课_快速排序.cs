    [检查说明("★ 分区语义：基准放对了、左边都 ≤ 它、右边都 ≥ 它、元素一个没丢")]
    public static CheckResult 检查_分区语义(string 代码)
    {
        var run = 课工具.跑一次(代码, 调用点());
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 错 = new List<string>();
        // (标记, 原数组, 左, 右) —— 期望值不是写死的数组，而是**语义**
        var 用例 = new (string 标记, int[] 原, int 左, int 右)[]
        {
            ("分甲", new[] { 3, 1, 4, 2 }, 0, 3),
            ("分乙", new[] { 5, 5, 1, 5 }, 0, 3),
            ("分丙", new[] { 2, 1 }, 0, 1),
            ("分丁", new[] { 9, 3, 1, 4, 2, 8 }, 1, 4),
        };
        foreach (var (标记, 原, 左, 右) in 用例)
        {
            string 得到 = 课工具.取标记(run, 标记);
            if (得到 == null) { 错.Add("      " + 标记 + "：没有输出"); continue; }
            if (得到.StartsWith("崩溃", StringComparison.Ordinal))
            { 错.Add("      " + 标记 + "：抛异常了（" + 得到 + "）"); continue; }

            var 段 = 得到.Split('|');
            if (段.Length != 2) { 错.Add("      " + 标记 + "：输出格式不对（" + 得到 + "）"); continue; }
            if (!int.TryParse(段[0], out int p))
            { 错.Add("      " + 标记 + "：返回的不是个整数（" + 段[0] + "）"); continue; }
            int[] 现在;
            try { 现在 = 段[1].Length == 0 ? new int[0] : 段[1].Split(' ').Select(int.Parse).ToArray(); }
            catch { 错.Add("      " + 标记 + "：数组内容看不懂（" + 段[1] + "）"); continue; }

            if (现在.Length != 原.Length)
            { 错.Add("      " + 标记 + "：数组长度从 " + 原.Length + " 变成了 " + 现在.Length); continue; }
            if (p < 左 || p > 右)
            { 错.Add("      " + 标记 + "：返回的下标 " + p + " 不在 [" + 左 + "," + 右 + "] 里"); continue; }
            if (现在[p] != 原[右])
            { 错.Add("      " + 标记 + "：数[" + p + "] 应当是基准 " + 原[右] + "，实际是 " + 现在[p]); continue; }

            bool 左好 = true, 右好 = true;
            for (int k = 左; k < p; k++) if (现在[k] > 现在[p]) 左好 = false;
            for (int k = p + 1; k <= 右; k++) if (现在[k] < 现在[p]) 右好 = false;
            if (!左好) { 错.Add("      " + 标记 + "：左边有比基准大的（下标 " + 左 + ".." + (p - 1) + "）"); continue; }
            if (!右好) { 错.Add("      " + 标记 + "：右边有比基准小的（下标 " + (p + 1) + ".." + 右 + "）"); continue; }

            // 区间外不许动
            bool 外面动了 = false;
            for (int k = 0; k < 原.Length; k++)
                if ((k < 左 || k > 右) && 现在[k] != 原[k]) 外面动了 = true;
            if (外面动了) { 错.Add("      " + 标记 + "：动了 [" + 左 + "," + 右 + "] **外面**的元素"); continue; }

            // 元素一个没丢
            var 原排 = 原.OrderBy(x => x).ToArray();
            var 现排 = 现在.OrderBy(x => x).ToArray();
            if (!原排.SequenceEqual(现排))
                错.Add("      " + 标记 + "：元素丢了或者多出来了（原 " + string.Join(" ", 原排) +
                       "，现 " + string.Join(" ", 现排) + "）");
        }
        if (错.Count == 0) return CheckResult.过("四组的分区语义都对");

        return CheckResult.不过(
            "分区不对：\n" + string.Join("\n", 错) + "\n" +
            "      Lomuto 分区（以 数[右] 为基准）：\n" +
            "          int 基准 = 数[右]; int i = 左 - 1;\n" +
            "          for (int j = 左; j < 右; j++)\n" +
            "              if (数[j] <= 基准) { i++; 交换 数[i] 与 数[j]; }\n" +
            "          交换 数[i + 1] 与 数[右];  return i + 1;\n" +
            "      ⚠ 返回的必须是**基准最终所在的下标**，而且只许动 [左, 右] 这一段。");
    }

