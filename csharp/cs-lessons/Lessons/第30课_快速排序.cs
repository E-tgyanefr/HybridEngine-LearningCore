    public static string 参考答案 => """
// 参考答案 —— 快排：难点全在分区

// 1. Lomuto 分区：以 数[右] 为基准，小的往左扔，返回基准的最终位置
static int 分区(int[] 数, int 左, int 右)
{
    int 基准 = 数[右];
    int i = 左 - 1;                       // i 是「小于等于基准」那一段的末尾
    for (int j = 左; j < 右; j++)
    {
        if (数[j] <= 基准)
        {
            i++;
            int 临时 = 数[i];             // 把它扔到小段里去
            数[i] = 数[j];
            数[j] = 临时;
        }
    }
    int 临时2 = 数[i + 1];                // 基准放到分界线上
    数[i + 1] = 数[右];
    数[右] = 临时2;
    return i + 1;                         // 这就是基准最终的位置
}

// 2. 快速排序：分区 → 左右两段各自排
static void 快速排序(int[] 数)
{
    排段(数, 0, 数.Length - 1);
}

static void 排段(int[] 数, int 左, int 右)
{
    if (左 >= 右)
    {
        return;                           // 0 或 1 个元素，天然有序
    }
    int p = 分区(数, 左, 右);
    排段(数, 左, p - 1);                  // ⚠ 不含 p（它已经在最终位置上了）
    排段(数, p + 1, 右);                  // ⚠ 从 p + 1 开始
}
""";

