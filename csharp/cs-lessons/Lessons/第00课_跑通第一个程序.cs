    //   也就不会和库追加的 `入口` 类撞车（那会报 CS0017 两个入口点）。
    private static CppRun 调用(string 代码, string 调用点)
    {
        return CppCheck.编译并运行(代码, null, CppLesson.限定(代码, 调用点));
    }
