    [检查说明("这一课能跑起来的前提：.NET SDK 装好了")]
    public static CheckResult 检查_工具链(string 代码)
    {
        return CppLesson.工具链就绪(代码);
    }

    [检查说明("三行都打印了，顺序也对")]
    public static CheckResult 检查_三行(string 代码)
    {
        var run = 调用(代码, "跑通();");
        if (run.Raw.CompileFailed)
            return CppCheck.编译失败说明(run);

        string[] 期望 = { "工具链就绪", "我准备好学 C# 了", "第一步：编译，第二步：运行" };
        for (int i = 0; i < 期望.Length; i++)
        {
            string 实际 = i < run.行.Count ? run.行[i].Trim() : "";
            if (i >= run.行.Count || 实际 != 期望[i])
            {
                return CheckResult.不过(
                    $"第 {i + 1} 行应当是 [{期望[i]}]，" +
                    $"实际是 [{(i < run.行.Count ? 实际 : "（没输出）")}]。\n" +
                    "      ⚠ 三行的顺序别改 —— 检查按顺序比对。");
            }
        }
        return CheckResult.过("三行都对");
    }

    [检查说明("用的是 Console.WriteLine（不是别的打印方式）")]
    public static CheckResult 检查_用对打印(string 代码)
    {
        if (!代码.Contains("Console.WriteLine"))
            return CheckResult.不过(
                "没看到 `Console.WriteLine`。\n" +
                "      ⚠ C# 的打印是 Console.WriteLine(\"...\") —— " +
                "不是 print，也不是 printf。");
        return CheckResult.过();
    }

