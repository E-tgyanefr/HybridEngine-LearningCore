    [检查说明("★ 汉诺塔：步数 2^n-1，而且每一步都合法（模拟三根柱子逐步验证）")]
    public static CheckResult 检查_汉诺塔(string 代码)
    {
        var run = 课工具.跑一次(代码, 调用点());
        if (!run.编译通过) return CppCheck.编译失败说明(run);

        var 错 = new List<string>();
        foreach (int n in new[] { 0, 1, 2, 3, 4 })
        {
            string 步数 = 课工具.取标记(run, "汉" + n + "数");
            if (步数 == null) { 错.Add("      汉诺塔(" + n + ")：没有输出"); continue; }
            if (步数.StartsWith("崩溃", StringComparison.Ordinal))
            { 错.Add("      汉诺塔(" + n + ") 抛异常了（" + 步数 + "）"); continue; }

            int 期望 = (1 << n) - 1;
            if (步数 != 期望.ToString())
            { 错.Add("      汉诺塔(" + n + ") 应当 " + 期望 + " 步，你输出的是 " + 步数 + " 步"); continue; }

            var 步们 = new List<string>();
            string 头 = "汉" + n + "步|";
            foreach (var l in run.行)
            {
                string s = l.Trim();
                if (s.StartsWith(头, StringComparison.Ordinal)) 步们.Add(s.Substring(头.Length).Trim());
            }
            if (步们.Count != 期望)
            { 错.Add("      汉诺塔(" + n + ")：说好 " + 步数 + " 步，实际只列出 " + 步们.Count + " 条"); continue; }

            string 问题 = 验合法(n, 步们);
            if (问题 != null) 错.Add("      汉诺塔(" + n + ")：" + 问题);
        }
        if (错.Count == 0) return CheckResult.过("步数和每一步的合法性都对（n=0..4）");

        return CheckResult.不过(
            "汉诺塔不对：\n" + string.Join("\n", 错) + "\n" +
            "      正确思路（把 n 个从 起 挪到 到，借用 中）：\n" +
            "          ① 搬(n-1, 起, 到, 中)      上面 n-1 个先挪到中转柱\n" +
            "          ② 记录.Add(起 + \"->\" + 到) 最大的那个直接过去\n" +
            "          ③ 搬(n-1, 中, 起, 到)      再把 n-1 个挪到目的柱\n" +
            "      ⚠ ①③ 里**柱子的角色换了位置** —— 这是汉诺塔最容易写错的地方。\n" +
            "      ⚠ 步数是 2^n - 1：1、3、7、15；n=0 时是**空列表**。");
    }

