    public static string 参考答案 => """
// 参考答案 —— 递归：先写基准情形，再把自己变小

// 1. 阶乘：n! = n × (n-1)!，0! = 1
static long 阶乘(int n)
{
    if (n <= 0)
    {
        return 1;                     // ⚠ 基准情形，第一句就要写
    }
    return n * 阶乘(n - 1);           // 交给自己一次，n 变小了
}

// 2. 汉诺塔：把 n-1 个挪到中转柱，动最大的，再把 n-1 个挪到目的柱
static List<string> 汉诺塔(int n)
{
    var 记录 = new List<string>();
    搬(n, 'A', 'B', 'C', 记录);
    return 记录;
}

// 真正干活的那个递归：起 → 到，中间借用 中
static void 搬(int n, char 起, char 中, char 到, List<string> 记录)
{
    if (n == 0)
    {
        return;                       // 基准情形：没有盘子，什么都不用做
    }
    搬(n - 1, 起, 到, 中, 记录);       // ① 上面 n-1 个：起 → 中（借用 到）
    记录.Add(起 + "->" + 到);          // ② 最大的那个：起 → 到
    搬(n - 1, 中, 起, 到, 记录);       // ③ n-1 个：中 → 到（借用 起）
}

// 3. 数字和：每次拿走最后一位，剩下的继续问自己
static int 数字和(long n)
{
    n = Math.Abs(n);                  // 负数按绝对值
    if (n < 10)
    {
        return (int)n;                // 基准情形：一位数就是它自己
    }
    return (int)(n % 10) + 数字和(n / 10);
}
""";

