// 第 28 课：递归 —— 基准情形、调用栈、汉诺塔
//
// ══ 这一课要教什么 ══
// 递归 = 函数调用自己。它把「一个大问题」变成「同样形状的小问题」：
//     n 的阶乘 = n × (n-1) 的阶乘
// 但递归有两件必须做对的事：
//   · **基准情形**（最小的那种情况直接给答案，不再往下问）——
//     漏了它 = 无限递归 = `StackOverflowException`，而且**进程直接死，抓不住**
//   · 每一层都要「更接近基准」（n 每次减 1）
// 汉诺塔是递归的经典：**移动 n 个盘子 = 先移动 n-1 个、再动最大的、再移动 n-1 个**，
// 步数正好是 2^n - 1（n=4 是 15 步、n=10 是 1023 步）。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**汉诺塔的每一步必须合法**。检查方法自己模拟三根柱子：
//   每一步都得是从某根柱子**顶上**拿走、放到空柱或更大的盘子上，最后全部到 C。
//   只输出 2^n-1 条假步骤（比如全打 "A->C"）在这里露馅。
// 核心检查点二：**基准情形**。阶乘(0) = 1、数字和(0) = 0、汉诺塔(0) 是空列表 ——
//   漏掉基准的人这三种情况要么崩、要么给出错答案。
// 第三条（文本）：阶乘 / 汉诺塔 的函数体里要有**对自己的调用** ——
//   这一课就是递归课，用循环写出来不算学会（第 21 课已经练过循环版了）。

