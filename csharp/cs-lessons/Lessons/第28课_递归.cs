    /// <summary>
    /// 模拟三根柱子，逐步验证：返回第一条问题（没问题返回 null）。
    /// ⚠ 这是这一课的核心 —— 光数步数挡不住「打 2^n-1 条假步骤」的解法。
    /// </summary>
    private static string 验合法(int n, List<string> 步们)
    {
        var 柱 = new Dictionary<char, List<int>>
        {
            ['A'] = new List<int>(), ['B'] = new List<int>(), ['C'] = new List<int>(),
        };
        // 大盘子在底下：列表末尾是**顶上**那个，所以从 n 到 1 依次压入
        for (int i = n; i >= 1; i--) 柱['A'].Add(i);

        for (int i = 0; i < 步们.Count; i++)
        {
            string 步 = 步们[i];
            if (步.Length != 4 || 步[1] != '-' || 步[2] != '>')
                return "第 " + (i + 1) + " 步的写法不对（要像 A->C 这样四个字符）：" + 步;
            char 起 = 步[0], 到 = 步[3];
            if (!柱.ContainsKey(起) || !柱.ContainsKey(到))
                return "第 " + (i + 1) + " 步用了 A/B/C 之外的柱子：" + 步;
            if (起 == 到)
                return "第 " + (i + 1) + " 步把盘子挪到了同一根柱子上：" + 步;
            if (柱[起].Count == 0)
                return "第 " + (i + 1) + " 步从**空柱子** " + 起 + " 上拿盘子：" + 步;
            int 盘 = 柱[起][柱[起].Count - 1];
            if (柱[到].Count > 0 && 柱[到][柱[到].Count - 1] < 盘)
                return "第 " + (i + 1) + " 步把大盘子 " + 盘 + " 压在了小盘子 " +
                       柱[到][柱[到].Count - 1] + " 上：" + 步;
            柱[起].RemoveAt(柱[起].Count - 1);
            柱[到].Add(盘);
        }
        if (柱['C'].Count != n)
            return "走完之后 C 柱上只有 " + 柱['C'].Count + " 个盘子（应该是 " + n + " 个）";
        for (int i = 0; i < 柱['C'].Count; i++)
            if (柱['C'][i] != n - i) return "走完之后 C 柱上的盘子顺序不对";
        if (柱['A'].Count != 0 || 柱['B'].Count != 0)
            return "走完之后 A / B 柱上还有盘子";
        return null;
    }
