// 参考答案 —— 栈与队列

// 1. 配对：左括号进栈，右括号找栈顶要「另一半」
static bool 配对(string s)
{
    var 栈 = new Stack<char>();
    foreach (char c in s)
    {
        if (c == '(' || c == '[' || c == '{')
        {
            栈.Push(c);
        }
        else if (c == ')' || c == ']' || c == '}')
        {
            if (栈.Count == 0)
            {
                return false;             // ⚠ 先判空：右括号比左括号多
            }
            char 顶 = 栈.Pop();
            if (c == ')' && 顶 != '(') return false;
            if (c == ']' && 顶 != '[') return false;
            if (c == '}' && 顶 != '{') return false;
        }
    }
    return 栈.Count == 0;                 // ⚠ "((" 在这里才被抓到
}

// 2. 处理括号：一边扫一边记「最大的那一次」
static int[] 处理括号(string s)
{
    var 栈 = new Stack<char>();
    int 配不上 = 0;                       // 一旦失败就置 1，**不清零**
    int 最大深度 = 0;
    foreach (char c in s)
    {
        if (c == '(')
        {
            栈.Push(c);
            // ⚠ 深度要在 Push **之后**比 —— 比完栈就浅下去了，回不来
            if (栈.Count > 最大深度)
            {
                最大深度 = 栈.Count;
            }
        }
        else if (c == ')')
        {
            if (栈.Count == 0)
            {
                配不上 = 1;               // 这个 ')' 没有对应的 '('，比如 ")("
            }
            else
            {
                栈.Pop();
            }
        }
    }
    if (栈.Count > 0)
    {
        配不上 = 1;                       // 还有没关上的，比如 "(("
    }
    return new int[] { 配不上, 最大深度 };
}

// 3. 约瑟夫环：用队列转圈
static int 约瑟夫(int n, int k)
{
    var 队 = new Queue<int>();
    for (int i = 1; i <= n; i++)
    {
        队.Enqueue(i);                    // 1..n 排成一圈
    }
    while (队.Count > 1)
    {
        for (int i = 1; i < k; i++)
        {
            队.Enqueue(队.Dequeue());     // 前 k-1 个人从队头转到队尾
        }
        队.Dequeue();                     // 第 k 个人出列
    }
    return 队.Dequeue();
}
""";

