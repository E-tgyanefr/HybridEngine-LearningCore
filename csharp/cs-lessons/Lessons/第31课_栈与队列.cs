// ══ 这一课要教什么 ══
// 两个「只能从一头进出」的容器，分别对应两类问题：
//     Stack<T>  后进先出（LIFO）—— **最近的还没配对的东西**：括号匹配、撤销、递归
//     Queue<T>  先进先出（FIFO）—— **按顺序排队**：报数出列、BFS 的队列（第 35 课）
// 括号匹配是栈的教科书例子，也是这一课唯一要写的算法。
// 而它藏着一个真实的坑：**空栈上 `Pop()` 会抛 `InvalidOperationException`** ——
// C++ 的 `std::stack::top()` 是「未定义行为」，C# 这里是**明确抛异常**，
// 所以「先判 `Count > 0`」不是保险，是正确性的一部分。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**空栈不许 Pop**（用 `")("` 和 `""` 两组数据）。
//   不判空的人会抛 `InvalidOperationException`，调用点每组各自 try/catch，
//   所以那一组打印 `崩溃:InvalidOperationException`，检查把它翻译成
//   「遇到 `)` 时栈是空的 —— 弹出之前要先判 Count」。
// 第二条：**最大深度要在 push 之后比**（`"(())"` → 2、`"((()))"` → 3）——
//   写成「最后栈里剩几个」的人全错。
// 第三条：约瑟夫环用 `Queue<int>`（文本检查函数体里有没有 `Queue<int>`）。

