// 第 25 课：素数筛 —— 埃氏筛，和试除法的速度对照
//
// ══ 这一课要教什么 ══
// 第 23 课的「判断一个数是不是质数」是 O(√n)。要**列出 1..n 的所有质数**时，
// 对每个数都判一遍就是 O(n√n) —— n=5000 万时几千万次除法。
// 埃氏筛换个思路：**不判断，去划掉**。
//     先把 2..n 全标成「可能是质数」，然后从 2 开始：
//     遇到一个质数 p，就把 p 的 2 倍、3 倍……全部划掉。
// 每个合数只会被它最小的质因数划掉一次 ⇒ 总工作量约 n log log n。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**计时**。n=50,000,000 时：
//     筛法      约 340 毫秒（本机实测 Debug）
//     逐个数试除 约 14 秒（本机实测：n=10,000,000 就要 2.8 秒）
//   阈值取 **3000 毫秒** —— 离筛法 8 倍以上、离试除法 4 倍以上，两边都安全。
//   ⚠ 这类「计时判据」只在机器**明显**分得开时才用；失败提示里要写实测毫秒数，
//     不然学生以为是自己机器慢。
// 第二条：**素数表/素数个数要精确**（0/1/2/10/100/1000/10000/100000 各组）。
// 第三条（文本）：筛法要有 `bool[]` —— 这一课的工具就是标记数组。

