    public static string 参考答案 => """
// 参考答案 —— 埃氏筛
//
// ⚠ 三个方法都从同一张标记表出发。真实代码里会把 筛 的结果传下去，
//   但这一课为了签名简单，各自建一次表 —— 它们都是 O(n log log n)，够快。

// 1. 筛：先把 2..n 全标成质数，再从 2 开始把质数的倍数划掉
static bool[] 筛(int n)
{
    bool[] 是质数 = new bool[n + 1];                 // n < 2 时长度也不小于 1
    if (n < 2)
    {
        return 是质数;                                // 全是 false —— 0 和 1 都不是质数
    }
    for (int i = 2; i <= n; i++)
    {
        是质数[i] = true;                             // 先都当成质数
    }
    for (long i = 2; i * i <= n; i++)                 // ⚠ 用 long：i*i 可能溢出 int
    {
        if (是质数[i])
        {
            for (long j = i * i; j <= n; j += i)      // 从 i*i 开始，比它小的倍数早划过了
            {
                是质数[j] = false;
            }
        }
    }
    return 是质数;
}

// 2. 素数表：扫一遍表，把 true 的挑出来
static int[] 素数表(int n)
{
    bool[] 是质数 = 筛(n);
    var 出 = new List<int>();
    for (int i = 2; i <= n; i++)
    {
        if (是质数[i])
        {
            出.Add(i);
        }
    }
    return 出.ToArray();
}

// 3. 素数个数：同一张表，数一数
static int 素数个数(int n)
{
    bool[] 是质数 = 筛(n);
    int 个 = 0;
    for (int i = 2; i <= n; i++)
    {
        if (是质数[i])
        {
            个++;
        }
    }
    return 个;
}
""";

