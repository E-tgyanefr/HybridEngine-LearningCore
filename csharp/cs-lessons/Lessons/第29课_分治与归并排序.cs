    public static string 参考答案 => """
// 参考答案 —— 分治：归并排序 + 逆序对

// 1. 合并两个有序数组：两个手指比大小
static int[] 合并(int[] 甲, int[] 乙)
{
    int[] 出 = new int[甲.Length + 乙.Length];
    int i = 0, j = 0, k = 0;
    while (i < 甲.Length && j < 乙.Length)
    {
        // ⚠ 用 <=：相等时先取左半边的 —— 这就是归并排序稳定的原因
        if (甲[i] <= 乙[j]) 出[k++] = 甲[i++];
        else                出[k++] = 乙[j++];
    }
    while (i < 甲.Length) 出[k++] = 甲[i++];      // 剩下的直接搬
    while (j < 乙.Length) 出[k++] = 乙[j++];
    return 出;
}

// 2. 归并排序：切两半 → 各自排好 → 合起来
static void 归并排序(int[] 数)
{
    排段(数, 0, 数.Length - 1);
}

static void 排段(int[] 数, int 左, int 右)
{
    if (左 >= 右)
    {
        return;                                  // 基准情形：0 或 1 个元素天然有序
    }
    int 中 = 左 + (右 - 左) / 2;
    排段(数, 左, 中);                             // 左半边
    排段(数, 中 + 1, 右);                         // 右半边
    合并段(数, 左, 中, 右);                       // 合起来
}

static void 合并段(int[] 数, int 左, int 中, int 右)
{
    int[] 临时 = new int[右 - 左 + 1];            // ⚠ 必须借一块临时地方
    int i = 左, j = 中 + 1, k = 0;
    while (i <= 中 && j <= 右)
    {
        if (数[i] <= 数[j]) 临时[k++] = 数[i++];
        else                临时[k++] = 数[j++];
    }
    while (i <= 中) 临时[k++] = 数[i++];
    while (j <= 右) 临时[k++] = 数[j++];
    for (int t = 0; t < 临时.Length; t++)
    {
        数[左 + t] = 临时[t];                     // ⚠ 一定要写回原数组
    }
}

// 3. 逆序对：在合并那一步顺手数
static long 逆序对(int[] 数)
{
    int[] 副本 = new int[数.Length];
    for (int i = 0; i < 数.Length; i++) 副本[i] = 数[i];   // 不许改调用方传进来的数组
    return 数段(副本, 0, 副本.Length - 1);
}

static long 数段(int[] 数, int 左, int 右)
{
    if (左 >= 右)
    {
        return 0;                                // 一个元素里没有逆序对
    }
    int 中 = 左 + (右 - 左) / 2;
    long 共 = 数段(数, 左, 中) + 数段(数, 中 + 1, 右);

    int[] 临时 = new int[右 - 左 + 1];
    int i = 左, j = 中 + 1, k = 0;
    while (i <= 中 && j <= 右)
    {
        if (数[i] <= 数[j])
        {
            临时[k++] = 数[i++];
        }
        else
        {
            // ⚠ 关键一句：右段的 数[j] 比左段 数[i..中] **每一个都小**
            //   ⇒ 一次加 中 - i + 1 个逆序对
            共 += 中 - i + 1;
            临时[k++] = 数[j++];
        }
    }
    while (i <= 中) 临时[k++] = 数[i++];
    while (j <= 右) 临时[k++] = 数[j++];
    for (int t = 0; t < 临时.Length; t++) 数[左 + t] = 临时[t];
    return 共;
}
""";

