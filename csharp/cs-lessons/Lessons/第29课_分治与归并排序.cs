// 第 29 课：分治与归并排序 —— 手写归并，和 Array.Sort 的对照
//
// ══ 这一课要教什么 ══
// 分治 = 把问题**切成两半**，各自解决，再把两个答案**合起来**。
// 归并排序就是它最标准的例子：
//     排序 n 个数 = 排好左半边 + 排好右半边 + 把两个有序段并起来
// 复杂度从 O(n²)（第 18 课的三种）降到 **O(n log n)**：一百万个数的比较次数
// 从 5×10^11 降到约 2×10^7。
// 顺带一个只有分治才做得漂亮的题：**逆序对** —— 求「前面比后面大的对数」，
// 双重循环是 O(n²)；在归并的「合并」那一步顺手数，就是 O(n log n)。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**归并排序 / 合并里不许出现现成排序**（文本判据）。
//   `Array.Sort(数)` 的输出完全正确 —— 但这一课练的是「切两半 + 合起来」。
// 核心检查点二：**逆序对必须自己递归**（函数体里出现对自己的调用）。
//   双重 for 循环的写法输出也对，可它的复杂度是 O(n²)，正是这一课要摆脱的东西。
//   10 万个从大到小的数（逆序对 = 4999950000）只做「规模测试」，
//   不当时间判据 —— O(n²) 的实现慢就慢，由文本判据负责抓。
// 边界：空数组、一个元素、重复元素、已经有序、完全逆序。

