//         while (b != 0) {
//             long 余 = a % b;
//             a = b;
//             b = 余;
//         }
//         return a;
//     }
//
// 为什么对：`a % b` 是「a 里去掉若干个 b 之后剩下的」。
//   任何能同时整除 a 和 b 的数，也一定能整除 a % b —— 所以两边的公约数**完全一样**。
//   不断把大的换成小的，最后 b 变成 0，剩下的 a 就是最大公约数。
//
