    public static string 参考答案 => """
// 参考答案 —— 辗转相除

// 1. 最大公约数：gcd(a, b) = gcd(b, a % b)，到 b == 0 为止
static long 最大公约数(long a, long b)
{
    a = Math.Abs(a);                 // ⚠ 约定：gcd 永远非负
    b = Math.Abs(b);
    while (b != 0)
    {
        long 余 = a % b;
        a = b;
        b = 余;
    }
    return a;                        // gcd(0,0) 也走这条路，返回 0
}

// 2. 最小公倍数：**先除后乘**
static long 最小公倍数(long a, long b)
{
    if (a == 0 || b == 0)
    {
        return 0;
    }
    long g = 最大公约数(a, b);
    // ⚠ 写成 a * b / g 会溢出：4e9 * 4e9 = 1.6e19 > long 的上限 9.2e18
    return a / g * b;
}

// 3. 约分：分子分母同除 gcd；负号统一放在分子上
static string 约分(long 分子, long 分母)
{
    long g = 最大公约数(分子, 分母);
    if (g == 0)
    {
        g = 1;                       // 分子分母都是 0 时别除以 0
    }
    long 上 = 分子 / g;
    long 下 = 分母 / g;
    if (下 < 0)
    {
        上 = -上;                     // 分母不留负号：6/-8 也要写成 -3/4
        下 = -下;
    }
    return 上 + "/" + 下;
}
""";

