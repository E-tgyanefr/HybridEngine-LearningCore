// ══ 这一课要教什么 ══
// 求最大公约数有两条路：从 1 试到 min(a,b)（O(n)），
// 或者**辗转相除**（O(log n)）—— 两千三百年前欧几里得就写下来了：
//     gcd(a, b) = gcd(b, a % b)，到 b == 0 时 a 就是答案
// 这一课还要顺手教会两件真实代码里天天出事的细节：
//   · 负数要取绝对值（gcd(-12, 18) 也是 6）
//   · 最小公倍数要**先除后乘**，因为 `a * b` 会溢出 long
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**最大公约数的函数体里必须有 `%`**。
//   「从 1 试到 min(a,b)」 的写法在 gcd(1000000007, 998244353) 上要跑十亿次 ——
//   这一课要的是辗转相除，所以这条用**文本判据**（只看有没有 `%`，不管递归还是循环）。
// 核心检查点二：**lcm(4000000000, 4000000000) = 4000000000**。
//   写成 `a * b / max公约数` 的人先乘就溢出了（得到负数）。
// 边界：gcd(0,5)=5、gcd(5,0)=5、gcd(0,0)=0、负数取绝对值、约分(0,5)="0/1"。

