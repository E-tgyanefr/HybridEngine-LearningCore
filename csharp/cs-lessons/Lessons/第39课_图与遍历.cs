//   以及一个 **200 个点的环** —— 最后这个同时是「**已访问标记**」的判据：
//   不标记的写法会在这条环上转不停（跑到超时）。
// 核心检查点二：**访问顺序**。DFS 和 BFS 在同一张图上顺序不同
//   （甲：DFS 是 0,1,3,2；BFS 是 0,1,2,3），把两个写成同一个会被抓住。
