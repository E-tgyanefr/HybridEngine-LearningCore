    public static string 参考答案 => """
// 参考答案 —— 邻接表上的 DFS / BFS

// 1. 深度优先：一条路走到黑（递归）
static List<int> 深度优先(List<List<int>> 图, int 起)
{
    var 出 = new List<int>();
    if (图.Count == 0)
    {
        return 出;
    }
    bool[] 到过 = new bool[图.Count];
    走(图, 起, 到过, 出);
    return 出;
}

static void 走(List<List<int>> 图, int 点, bool[] 到过, List<int> 出)
{
    到过[点] = true;                 // ⚠ 进入时就标记（不然环上会来回走）
    出.Add(点);
    foreach (int 邻 in 图[点])        // 邻接表的顺序就是走的顺序
    {
        if (!到过[邻])
        {
            走(图, 邻, 到过, 出);
        }
    }
}

// 2. 广度优先：一圈一圈往外扩（队列）
static List<int> 广度优先(List<List<int>> 图, int 起)
{
    var 出 = new List<int>();
    if (图.Count == 0)
    {
        return 出;
    }
    bool[] 到过 = new bool[图.Count];
    var 队 = new Queue<int>();
    到过[起] = true;                 // ⚠ 入队时就标记
    队.Enqueue(起);
    while (队.Count > 0)
    {
        int 点 = 队.Dequeue();
        出.Add(点);
        foreach (int 邻 in 图[点])
        {
            if (!到过[邻])
            {
                到过[邻] = true;
                队.Enqueue(邻);
            }
        }
    }
    return 出;
}

// 3. 连通块：每个「没到过」的点都开一块，走完它能到的全部
static int 连通块数(List<List<int>> 图)
{
    bool[] 到过 = new bool[图.Count];
    int 块数 = 0;
    for (int i = 0; i < 图.Count; i++)
    {
        if (!到过[i])
        {
            块数++;
            var 废 = new List<int>();
            走(图, i, 到过, 废);      // 只借它标记"到过"
        }
    }
    return 块数;
}

// 4. 最远距离：BFS 的层数
static int 最远距离(List<List<int>> 图, int 起)
{
    if (图.Count == 0)
    {
        return -1;                   // 空图没有点
    }
    int[] 层 = new int[图.Count];
    for (int i = 0; i < 层.Length; i++)
    {
        层[i] = -1;                  // -1 = 没到过
    }
    层[起] = 0;
    var 队 = new Queue<int>();
    队.Enqueue(起);
    int 最大 = 0;
    while (队.Count > 0)
    {
        int 点 = 队.Dequeue();
        foreach (int 邻 in 图[点])
        {
            if (层[邻] == -1)
            {
                层[邻] = 层[点] + 1;
                if (层[邻] > 最大)
                {
                    最大 = 层[邻];
                }
                队.Enqueue(邻);
            }
        }
    }
    return 最大;                     // 到不了的点没进过队，自然不算
}
""";

