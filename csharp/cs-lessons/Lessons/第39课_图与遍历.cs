// ══ 这一课要教什么 ══
// 前面所有的结构都是「排成一条线」或「分岔成树」；图是**随便连**：
// 5 号可以连着 0 号，也可以连着 100 号，还可以成环。
// 存图最常用的办法是**邻接表**：`List<List<int>> 图`，
// `图[i]` 就是「和 i 直接相连的那些点」。
// 有了它，第 35 课在网格上学的两套走法（DFS/BFS）可以直接搬过来 ——
// 网格只是「每个格子最多 4 个邻居」的特例。
//
// ══ 检查设计说明（给维护者）══
