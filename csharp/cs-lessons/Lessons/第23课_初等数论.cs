// 第 23 课：初等数论 —— 因数、质数判断、质因数分解
//
// ══ 这一课要教什么 ══
// 三个最常用的整数问题：一个数有哪些因数、它是不是质数、它由哪些质数乘出来。
// 表面上是三道小题，实际上练的是**同一件事**：把试除的循环上限从 n 收到 √n。
//   · 因数成对出现（d 和 n/d）⇒ 试到 √n 就能找齐所有因数
//   · 是质数只需要试除到 √n ⇒ 判断 10 亿级别的数只要 3 万次除法
//   · 质因数分解就是把因数一个个除干净
//
// ══ 检查设计说明（给维护者）══
// 核心检查点：**是质数(999962000357) 必须是假**（= 999983 × 999979，两个大质数之积）。
//   只试除到 1000 的人会说它是质数 —— 这一条逼学生把上限写到 √n。
//   配一个反方向的：是质数(1000000007) 必须是真的（大质数，试到 √n 才敢下结论）。
// 第二条：**1、0、负数都不是质数**（忘了拦 1 是最常见的错）。
// 第三条：**质因数(360) = 2,2,2,3,3,5** —— 重复的因子一个都不能少
//   （只除一次的人会给出 2,3,5）。
// ⚠ 大数只出现在这两条检查里：试除到 n 的写法在大数上要跑几秒（不判超时，
//   但别让每条检查都跑一遍）。

