    public static string 参考答案 => """
// 参考答案 —— 三个问题，一个技巧：试除到 √n

// 1. 因数们：因数成对出现，小的一半不超过 √n
static List<int> 因数们(int n)
{
    var 小 = new List<int>();
    var 大 = new List<int>();               // 大的一半先存着（最后要倒过来）
    for (int d = 1; (long)d * d <= n; d++)
    {
        if (n % d == 0)
        {
            小.Add(d);
            int 另 = n / d;
            if (另 != d)
            {
                大.Add(另);                 // ⚠ d == n/d 时（比如 6×6）只记一次
            }
        }
    }
    大.Reverse();                           // 大的一半是倒序收进来的
    小.AddRange(大);
    return 小;
}

// 2. 是质数：试到 √n 就够 —— 除不尽才敢说它是质数
static bool 是质数(long n)
{
    if (n < 2)
    {
        return false;                       // ⚠ 0、1、负数都不是质数
    }
    for (long d = 2; d * d <= n; d++)       // ⚠ 用 long，别让 d*d 溢出
    {
        if (n % d == 0)
        {
            return false;
        }
    }
    return true;
}

// 3. 质因数：从小到大，能除就除干净
static List<long> 质因数(long n)
{
    var 出 = new List<long>();
    long 剩 = n;
    for (long d = 2; d * d <= 剩; d++)
    {
        while (剩 % d == 0)                 // ⚠ 是 while，不是 if
        {
            出.Add(d);
            剩 /= d;
        }
    }
    if (剩 > 1)
    {
        出.Add(剩);                         // 最后剩下的本身就是质数
    }
    return 出;
}
""";

