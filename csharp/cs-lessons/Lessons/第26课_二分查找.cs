    [检查说明("★ 三个方法里没有 Array.BinarySearch / Math.Sqrt（这一课要手写）")]
    public static CheckResult 检查_没用现成的(string 代码)
    {
        string 净 = 课工具.去掉注释(代码);
        var 缺 = new List<string>();
        foreach (var 名 in new[] { "手写二分", "左边界" })
        {
            string 体 = 课工具.函数体(净, 名);
            if (体 == null) { 缺.Add("      " + 名 + "：没找到方法体"); continue; }
            if (课工具.含(体, "Array.BinarySearch", "List.BinarySearch", ".BinarySearch("))
                缺.Add("      " + 名 + "：用了现成的 BinarySearch —— 这一课要手写二分");
        }
        string 根体 = 课工具.函数体(净, "整数平方根");
        if (根体 == null) 缺.Add("      整数平方根：没找到方法体");
        else if (根体.Contains("Math.Sqrt"))
            缺.Add("      整数平方根：用了 Math.Sqrt —— 这一课的题目是**用二分猜**");

        if (缺.Count == 0) return CheckResult.过("三个都是手写的二分");
        return CheckResult.不过(
            "检查了去掉注释后的源码，发现问题：\n" + string.Join("\n", 缺) + "\n" +
            "      这一课练的是二分，不是调用二分：\n" +
            "          手写二分  int 左 = 0, 右 = 数.Length - 1;  while (左 <= 右) { 中 = …; }\n" +
            "          左边界     int 左 = 0, 右 = 数.Length;      while (左 < 右) { 右 = 中; }\n" +
            "          整数平方根 对**答案**二分：0..n 之间猜，判 中 <= n / 中");
    }

