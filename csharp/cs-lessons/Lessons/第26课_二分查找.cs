// 第 26 课：二分查找 —— Array.BinarySearch 与手写二分（边界怎么写才对）
//
// ══ 这一课要教什么 ══
// 第 20 课算出「顺序查找是 O(n)」，这一课给出 O(log n) 的答案：**每次砍掉一半**。
// 但二分的难点从来不是「中间取哪个」，而是**边界**：
//   · 找到就返回（`Array.BinarySearch` 能做）
//   · **第一个** ≥ 目标的位置（左边界 / lower_bound）—— `Array.BinarySearch` 做不到，
//     因为它只保证「找到一个匹配的」，重复元素时返回哪一个不确定
// 第三个任务 `整数平方根` 把二分用在「答案」上（不是用在数组上）：
// 求 ⌊√n⌋ 不去开方，而是二分「猜」一个数再验证。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**左边界在重复元素下必须返回第一个**
//   （{1,3,3,3,5,7} 找 3 ⇒ 1）。用 `Array.BinarySearch` 交差的人这里必挂 ——
//   它可能返回 1、2、3 里的任何一个。文本判据再补一刀：三个函数体里
//   不许出现 Array.BinarySearch / List.BinarySearch / Math.Sqrt。
// 核心检查点二：**整数平方根(10^18) 要秒出**（二分 60 次就够）。
//   从 1 试到 n 的写法在这里跑到超时 —— 这一课要的是二分。
//   ⚠ 大数只在这一条检查里出现。
// 边界：空数组、目标比所有数小 / 大、重复元素、n=0 和 n=1。

