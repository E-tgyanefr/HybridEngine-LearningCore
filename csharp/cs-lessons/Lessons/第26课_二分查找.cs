    public static string 参考答案 => """
// 参考答案 —— 二分：难点全在边界

// 1. 手写二分：闭区间 [左, 右]
static int 手写二分(int[] 数, int 目标)
{
    int 左 = 0;
    int 右 = 数.Length - 1;
    while (左 <= 右)                          // ⚠ 闭区间 ⇒ 带等号
    {
        int 中 = 左 + (右 - 左) / 2;
        if (数[中] == 目标)
        {
            return 中;
        }
        if (数[中] < 目标)
        {
            左 = 中 + 1;                      // 目标在右半边
        }
        else
        {
            右 = 中 - 1;
        }
    }
    return -1;
}

// 2. 左边界：第一个 ≥ 目标 的位置（右边界取「长度」，答案可能就是它）
static int 左边界(int[] 数, int 目标)
{
    int 左 = 0;
    int 右 = 数.Length;                       // ⚠ 不是 Length - 1
    while (左 < 右)                           // ⚠ 没有等号
    {
        int 中 = 左 + (右 - 左) / 2;
        if (数[中] < 目标)
        {
            左 = 中 + 1;                      // 中太小，答案一定在右边
        }
        else
        {
            右 = 中;                          // ⚠ 中本身可能就是答案，不能 -1
        }
    }
    return 左;                                // 全都小于目标 ⇒ 等于 数.Length
}

// 3. 整数平方根：对「答案」二分 —— 答案在 0..n 之间
static long 整数平方根(long n)
{
    long 左 = 0;
    long 右 = n;
    while (左 < 右)
    {
        long 中 = 左 + (右 - 左 + 1) / 2;     // ⚠ 取上中位，否则 左 不动会死循环
        if (中 <= n / 中)                     // 等价于 中*中 <= n，但不会溢出
        {
            左 = 中;
        }
        else
        {
            右 = 中 - 1;
        }
    }
    return 左;
}
""";

