// 第 40 课：最短路 —— Dijkstra 与 PriorityQueue<T, TPriority>
//
// ══ 这一课要教什么 ══
// 图上每条边有「代价」（距离、时间、花费），求从起点到每个点的最小代价。
// Dijkstra 的做法是**贪心 + 松弛**：
//     每次从「还没确定的点」里挑**当前最近**的那个，定下来，
//     再用它去更新邻居（`到邻居 > 到它 + 边长` 就更新）。
// 挑最近的那个如果每次扫一遍全部点，就是 O(n²)；用**优先队列**（小根堆）就是
// O(m log n) —— .NET 6 起自带 `PriorityQueue<T, TPriority>`，这一课就用它。
// ⚠ 它要求**边权非负**（有负边要用 Bellman-Ford）。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**无向边两个方向都要加**。只加单向的人从起点出发「看着对」，
//   换个起点就全 -1（检查里专门从 4 号点又跑了一遍）。
// 核心检查点二：**不可达是 -1**（不是 0、不是 long.MaxValue）。
// 核心检查点三：**不许打表**。除了三张小图，还喂了一张 50 个点、100 条边的
//   生成图（边按 `(i*37+11)%50` 和 `i+1` 连，权由公式算）。
//   期望值是作者在 python 里先算好、写死在检查里的 —— 学生打不了这个表。
// 文本判据：`最短路` 里要出现 `PriorityQueue`（这一课的另一半是学会用它）。
// 数据里的 0 号点那组（dij0 = 0,7,9,20,20,11）是经典例子，手算也能核对。

