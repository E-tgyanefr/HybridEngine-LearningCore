    public static string 参考答案 => """
// 参考答案 —— Dijkstra + 优先队列
//
// ⚠ 一句话记住这一课：**无向边加两次，取堆顶时判「过时」。**

static long[] 最短路(int 点数, int[][] 边, int 起)
{
    // 1. 建邻接表（无向 ⇒ 两个方向都要加）
    var 图 = new List<List<(int 到, int 权)>>();
    for (int i = 0; i < 点数; i++)
    {
        图.Add(new List<(int 到, int 权)>());
    }
    foreach (int[] 条 in 边)
    {
        int 甲 = 条[0], 乙 = 条[1], 权 = 条[2];
        图[甲].Add((乙, 权));            // ⚠ 方向一
        图[乙].Add((甲, 权));            // ⚠ 方向二（漏了它，换个起点就全 -1）
    }

    // 2. 距离表：-1 表示「还不知道」
    long[] 距离 = new long[点数];
    for (int i = 0; i < 点数; i++)
    {
        距离[i] = -1;
    }
    距离[起] = 0;

    // 3. 小根堆：优先级是距离
    var 队 = new PriorityQueue<int, int>();
    队.Enqueue(起, 0);
    while (队.Count > 0)
    {
        队.TryDequeue(out int 点, out int 当前);
        if (当前 > 距离[点])
        {
            continue;                    // ⚠ 堆里的旧记录，跳过
        }
        foreach (var (到, 权) in 图[点])
        {
            long 新 = 距离[点] + 权;
            if (距离[到] == -1 || 新 < 距离[到])
            {
                距离[到] = 新;            // 松弛：发现更近的路就改掉记录
                队.Enqueue(到, (int)新);
            }
        }
    }
    return 距离;                          // 没被更新过的还是 -1
}
""";

