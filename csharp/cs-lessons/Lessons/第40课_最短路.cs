//
// 这一课讲一件事：**带权图上的最短路** —— 以及「每次挑最近的」为什么要用堆。
// ─────────────────────────────────────────────────────
//  这一课你会学到
//   ─────────────────────────────────────────────────────
//    Dijkstra 算法、松弛、PriorityQueue（优先队列）
//
//  需要先会
//    第 39 课：邻接表与 BFS（这一课是「带权的 BFS」）；第 27 课：贪心
//
// ─────────────────────────────────────────────────────
//  先介绍：从「几步」到「多少代价」
//   ─────────────────────────────────────────────────────
//
// 第 39 课的 BFS 求的是「最少几条边」。可现实里每条路长度不同：
//
//     0 —7— 1 —15— 3        从 0 到 3：直接走 0→1→3 = 22，
//     |    / |               可 0→2→3 = 9+11 = 20，更短
//     9  10  11
//     | /    |
//     2 —2— 5 —9— 4
//
// ⇒ BFS 不管用了（它只看「几条边」）。要看**代价**，就得换算法：Dijkstra。
//
// ─────────────────────────────────────────────────────
//  一、Dijkstra 的三句话
//   ─────────────────────────────────────────────────────
//
//     ① 起点距离 0，其它点「还不知道」（-1）
//     ② 每轮挑出**还没定下来的、当前距离最小**的点
//     ③ 用它去「松弛」邻居：`到邻居 > 到它 + 边长` 就更新
//
// 「松弛」（relax）这个词听着玄，其实就是：**发现一条更近的路，就改掉原来的记录**。
//
// ⚠ 它要求**边权非负**：有负边时「当前最近的」不一定真的最近（要换 Bellman-Ford）。
//
// ─────────────────────────────────────────────────────
//  二、为什么用优先队列（堆）
//   ─────────────────────────────────────────────────────
//
// 「挑当前距离最小的点」如果每次扫一遍所有点：
//
//     点数 50        ⇒ 无所谓
//     点数 100000    ⇒ 每轮扫 10 万，一共 10 万轮 = **10^10 次**，太慢
//
// 用**小根堆**（优先队列）就只要「取出堆顶」：
//
//     var 队 = new PriorityQueue<int, int>();       ← <元素, 优先级>
//     队.Enqueue(点, 距离);                          ← 优先级小的先出来
//     队.TryDequeue(out int 点, out int 距离);       ← 取出堆顶
//     队.Count
//
// `PriorityQueue` 是 .NET 6 起自带的（比 `SortedSet` 省事，也允许重复）。
//
// ─────────────────────────────────────────────────────
//  三、代码骨架
//   ─────────────────────────────────────────────────────
//
//     long[] 距离 = new long[点数];
//     全部设成 -1;  距离[起] = 0;
//     var 队 = new PriorityQueue<int, int>();
//     队.Enqueue(起, 0);
//     while (队.Count > 0) {
//         队.TryDequeue(out int 点, out int 当前);
//         if (当前 > 距离[点]) continue;      ← ⚠ 过时的记录，跳过
//         foreach (边) {
//             long 新 = 距离[点] + 权;
//             if (距离[邻] == -1 || 新 < 距离[邻]) { 距离[邻] = 新; 队.Enqueue(邻, (int)新); }
//         }
//     }
//
// ⚠ `if (当前 > 距离[点]) continue;` 这一行**必须有**：同一个点可能被入队很多次，
//   堆里躺着的是**旧的距离**，用它去松弛会算出偏大的值。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：无向图只加了一个方向的边
//  ─────────────────────────────────────────────────────
//
//     foreach (int[] 条 in 边) {
//         图[条[0]].Add(...);                 ← 只加了 甲 → 乙
//     }
//
// 你会看到：从 0 号点出发**看着全对**，但是换个起点（比如 4 号）就一片 -1 ——
//   因为那些边只有「正着」能用。
//
// ⇒ 无向边要加两次：
//
//     图[甲].Add((乙, 权));
//     图[乙].Add((甲, 权));
//
// 顺便：`PriorityQueue` 里**允许重复的元素**（同一个点可以入队多次）——
//   这不是 bug，是 Dijkstra 的常规写法（所以上面那一行 `if (当前 > 距离[点])` 才必要）。
//
// ─────────────────────────────────────────────────────
//  这一课不碰什么
//   ─────────────────────────────────────────────────────
//   负权边（Bellman-Ford）、多源最短路、A* → 本课程不涉及。
//   最小生成树（Prim / Kruskal）→ 本课程不涉及。
//
// ─────────────────────────────────────────────────────
//  ══ 轮到你了 ══
