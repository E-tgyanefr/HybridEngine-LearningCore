//   卡住了看答案（先自己写一遍）—— 命令在「怎么自己测」那一节。
//
// 这一课讲一件事：**数据不一定要挤在一起** —— 用「下一站在哪儿」串起来。
// ─────────────────────────────────────────────────────
//  这一课你会学到
// ─────────────────────────────────────────────────────
//    手写单链表（结点 + 反转），以及 .NET 的 LinkedList<T>
//
//  需要先会
//    第 07 课：类与对象（字段、构造方法）；第 12 课：List
//
// ─────────────────────────────────────────────────────
//  先介绍：数组 vs 链表
// ─────────────────────────────────────────────────────
//
// 数组 `int[] 数 = new int[5]` 是**一整块连续内存**：
// 找第 i 个只要 `数[i]`（一步），但「在中间插一个」要把后面全部往右挪。
//
// 链表是**一个个结点**，每个结点记住「下一个是谁」：
//
//     [1|→] → [2|→] → [3|→] → null
//
// 找第 i 个要从头走 i 步，但「插一个」只要改两根指针。
//
// ─────────────────────────────────────────────────────
//  一、结点类：一个值 + 一个「下一个」
// ─────────────────────────────────────────────────────
//
//     class 结点 {
//         public int 值;            ← 数据
//         public 结点 下;           ← 下一个结点（null 表示到头了）
//         public 结点(int 值) { this.值 = 值; }
//     }
//
// ⚠ `下` 的类型是**结点自己** —— 这叫「自引用类型」，链表和树都靠它。
// ⚠ `this.值 = 值;` 里的 `this` 不能省：右边那个 值 是参数，不是字段。
//
// ─────────────────────────────────────────────────────
//  二、建表：尾插法（记住尾巴，别每次都从头找）
// ─────────────────────────────────────────────────────
//
//     static 结点 建表(int[] 数) {
//         if (数.Length == 0) return null;              ← 空数组 ⇒ 空链表
//         结点 头 = new 结点(数[0]);
//         结点 尾 = 头;
//         for (int i = 1; i < 数.Length; i++) {
//             尾.下 = new 结点(数[i]);
//             尾 = 尾.下;                                ← 尾巴往后挪
//         }
//         return 头;
//     }
//
// ─────────────────────────────────────────────────────
//  三、遍历：`while (当前 != null)`
// ─────────────────────────────────────────────────────
//
//     int 长度(结点 头) {
//         int n = 0;
//         for (结点 当前 = 头; 当前 != null; 当前 = 当前.下) n++;
//         return n;
//     }
//
// ⚠ 循环条件一定是 **`!= null`**：写成 `当前.下 != null` 会少算最后一个，
//   写成死循环（忘了 `当前 = 当前.下`）会转不停。
//
// ─────────────────────────────────────────────────────
//  四、反转：三个指针一起往前挪
// ─────────────────────────────────────────────────────
//
//     前 = null;  当前 = 头;
//     while (当前 != null) {
//         后 = 当前.下;          ← ① 先记住下一站（不然改完指针就找不到了）
//         当前.下 = 前;          ← ② 掉头
//         前 = 当前;             ← ③ 前、当前 各往前一格
//         当前 = 后;
//     }
//     return 前;                 ← 前 就是新的头
//
// 走一遍 1→2→3：
//
//     开始      前=null 当前=1
//     第一轮    后=2，1.下=null，前=1，当前=2      ⇒ null←1  2→3
//     第二轮    后=3，2.下=1，   前=2，当前=3      ⇒ null←1←2  3
//     第三轮    后=null，3.下=2，前=3，当前=null   ⇒ null←1←2←3
//     返回 前 = 3                                   ⇒ 3→2→1
//
// ⚠ 顺序不能换：**先存 后，再改 下**。反了就把「下一站」弄丢了。
//
// ─────────────────────────────────────────────────────
//  ⚠ 这一课唯一要记住的坑：忘了「先存下一站」
// ─────────────────────────────────────────────────────
//
//     while (当前 != null) {
//         当前.下 = 前;              ← 先把指针掉头
//         前 = 当前;
//         当前 = 当前.下;            ← ⚠ 现在 当前.下 已经是 前 了！
//     }
//
// 你会看到：反转结果**只有最后一个结点**，或者两个结点来回指（然后死循环）。
//   原因：改完 `当前.下` 之后，原来的「下一站」再也找不到了 ——
//   所以必须**第一件事就是把它存进 后**。
//
