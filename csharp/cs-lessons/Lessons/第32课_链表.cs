// 第 32 课：链表 —— 自己写 结点，和 LinkedList<T> 的对照
//
// ══ 这一课要教什么 ══
// 数组是一整块连续的内存，链表则是**一个个结点用「下一站在哪儿」串起来**。
// 这一课要手写那个结点类（`class 结点 { public int 值; public 结点 下; }`），
// 并且练会链表上最经典、也最容易写错的一步：**反转** ——
// 三个指针（前、当前、后）在循环里整体往前挪一格，指针接错就丢结点。
// 最后用 .NET 自带的 `LinkedList<T>` 做一次对照：库里的链表长什么样。
//
// ══ 检查设计说明（给维护者）══
// 核心检查点一：**反转不许借助容器**（文本判据：函数体里不许出现
//   `new List<` / `new int[` / `Stack<` / `Queue<` / `LinkedList<`）。
//   把值抄进 List 再重新建一条链，输出**完全正确**，但这一课练的正是指针怎么改。
// 核心检查点二：**不许丢结点** —— 反转前后长度必须一样、反转两次要回到原样。
//   指针接错的典型症状就是「只剩最后一个结点」或者「最后两个来回指」。
// 边界：null（空链表）、只有一个结点、反转 null。
// ⚠ `结点` 的字段必须是 public（调用点要直接读 值 / 下）。

