    public static string 参考答案 => """
// 参考答案 —— 单链表

// 1. 结点：一个值 + 一个「下一个」
class 结点
{
    public int 值;                 // ⚠ public：调用点要直接读
    public 结点 下;
    public 结点(int 值)
    {
        this.值 = 值;              // ⚠ this 不能省
    }
}

// 2. 建表：尾插（记住尾巴，别每次都从头找）
static 结点 建表(int[] 数)
{
    if (数.Length == 0)
    {
        return null;               // 空数组 ⇒ 空链表
    }
    结点 头 = new 结点(数[0]);
    结点 尾 = 头;
    for (int i = 1; i < 数.Length; i++)
    {
        尾.下 = new 结点(数[i]);
        尾 = 尾.下;                 // 尾巴往后挪
    }
    return 头;
}

// 3. 长度：走一遍，数几步
static int 长度(结点 头)
{
    int n = 0;
    for (结点 当前 = 头; 当前 != null; 当前 = 当前.下)
    {
        n++;
    }
    return n;
}

// 4. 反转：三个指针一起往前挪
static 结点 反转(结点 头)
{
    结点 前 = null;
    结点 当前 = 头;
    while (当前 != null)
    {
        结点 后 = 当前.下;          // ① 先记住下一站（顺序不能换！）
        当前.下 = 前;               // ② 掉头
        前 = 当前;                  // ③ 往前挪一格
        当前 = 后;
    }
    return 前;                     // 前 就是新的头
}

// 5. 打出："1->2->3"
static string 打出(结点 头)
{
    if (头 == null)
    {
        return "空";
    }
    var 出 = new List<string>();
    for (结点 当前 = 头; 当前 != null; 当前 = 当前.下)
    {
        出.Add(当前.值.ToString());
    }
    return string.Join("->", 出);
}

// 6. 对照：.NET 自带的 LinkedList<T> —— 每个新元素插到最前面就是反转
static List<int> 用库反转(List<int> 数)
{
    var 链 = new LinkedList<int>();
    foreach (int x in 数)
    {
        链.AddFirst(x);             // 一个个插到头部 ⇒ 顺序自然反了
    }
    var 出 = new List<int>();
    foreach (int x in 链)
    {
        出.Add(x);
    }
    return 出;
}
""";

