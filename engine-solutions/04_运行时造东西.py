from hybridengine_light import pyengine as E
from hybridengine_light.pyengine import components as C


def 搭一个游戏(后端):
    游戏 = E.游戏(后端=后端, 尺寸=100, 宽=400, 高=400)
    场景 = 游戏.场景
    发射器 = 场景.造("发射器", 50, 50)
    计数 = {"n": 0}

    def 发一颗(宿主, 第几次):
        计数["n"] += 1
        p = 宿主.世界位置
        新 = E.场景对象(f"子弹{计数['n']}", p.x, p.y)
        新.加(C.圆点(半径=1, 颜色="黄"), C.生命周期(寿命=0.3))
        # ⚠ 必须 `延后加根` —— 我们正在每帧遍历里（见课程里的说明）
        场景.延后加根(新)

    发射器.加(C.圆点(半径=3, 颜色="白"),
             C.计时器(间隔=0.1, 回调=发一颗))
    return 游戏
