# 第 13 课：字典 —— 按名字找东西

# ─────────────────────────────────────────────────────
#  先介绍：列表不够用的时候
# ─────────────────────────────────────────────────────
#
# 列表按**位置**取：`成绩[0]`、`成绩[1]`。
# 可有些东西你不想问"第几个"，只想问"叫什么"：
#
#     苹果还有几个？        香蕉呢？
#
# 列表里你就得记住苹果在第几位 —— 而且商品一多就记不住了。
#
# 字典按**名字**取：
#
#     库存 = {"苹果": 3, "香蕉": 5}
#             ↑      ↑
#             键     值
#
#     库存["苹果"]      ⇒  3
#
# ─────────────────────────────────────────────────────
#  什么时候用列表、什么时候用字典
# ─────────────────────────────────────────────────────
#
#     你要问「**第几个**」   ⇒  列表     成绩[0]、成绩[1]
#     你要问「**叫什么**」   ⇒  字典     库存["苹果"]
#
#   ⚠ 一句话记法：**一排格子用列表，一堆抽屉用字典。**
#
# ─────────────────────────────────────────────────────
#  三种常用操作
# ─────────────────────────────────────────────────────
#
#     库存 = {"苹果": 3}
#
#   ① 加 / 改（写法一样 —— 有就改，没有就加）
#        库存["香蕉"] = 5         ⇒  {"苹果": 3, "香蕉": 5}
#        库存["苹果"] = 10        ⇒  {"苹果": 10, "香蕉": 5}
#
#   ② 查
#        库存["苹果"]            ⇒  10
#        库存["橘子"]            ❌ KeyError: '橘子'
#
#   ③ 遍历
#        for 名 in 库存:                  遍历的是**键**
#        for 名, 数 in 库存.items():      同时拿键和值 ← 最常用
#
#   ⚠ `.items()` 那对括号不能省 —— 少了就变成遍历一个方法对象。
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课唯一要记住的坑：查不存在的键会崩
# ─────────────────────────────────────────────────────
#
#     库存["橘子"]                ❌ KeyError
#
#   而"查一个没有的商品"是**正常情况**，不该让程序崩。
#   两种写法：
#
#     ① 用 get（推荐，最短）
#          库存.get("橘子", 0)     ⇒  0        第二个参数是"没有时给什么"
#          库存.get("苹果", 0)     ⇒  3
#
#     ② 先问在不在
#          if "橘子" in 库存:
#              return 库存["橘子"]
#          return 0
#
#   ⇒ 一句话：**不确定键在不在，就用 `.get(键, 默认值)`。**
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课只讲字典的取值、赋值、遍历。集合（set）用到再说，先不碰。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 定义字典 库存，至少 3 样商品（键是文字，值是整数，数量要有差别）
#   2. 写一个函数 查数量(库存表, 商品名)：返回数量，**没有这样商品就返回 0**
#   3. 写一个函数 总件数(库存表)：返回所有数量之和
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 13


def CHECK_库存字典(答案):
    if not hasattr(答案, "库存"):
        return False, ("还没有定义「库存」字典。\n"
                       "      写法：库存 = {'苹果': 3, '香蕉': 5}\n"
                       "      ⚠ **花括号**，键和值之间用**冒号**。")
    v = 答案.库存
    if not isinstance(v, dict):
        return False, (f"「库存」应当是字典，现在是 {type(v).__name__}。\n"
                       f"      ⚠ 方括号 [] 是列表，花括号 {{}} 才是字典。")
    if len(v) < 3:
        return False, f"「库存」里只有 {len(v)} 样商品，至少要 3 样。"
    if not all(isinstance(k, str) for k in v):
        return False, "字典的**键**应当是商品名（文字，要加引号）。"
    if not all(isinstance(x, int) and not isinstance(x, bool) for x in v.values()):
        return False, "字典的**值**应当是数量（整数，不加引号）。"
    if len(set(v.values())) == 1:
        return False, "所有商品数量都一样 —— 那样看不出函数算得对不对，请让数量有差别。"
    return True, f"{len(v)} 样商品：{v}"


def CHECK_查数量(答案):
    if not hasattr(答案, "查数量"):
        return False, "还没有定义「查数量」函数。写法：def 查数量(库存表, 商品名): ..."
    if not callable(答案.查数量):
        return False, "「查数量」不是函数。"
    表 = {"苹果": 3, "香蕉": 5}
    if 答案.查数量(表, "苹果") != 3:
        return False, (f"查数量(表, '苹果') 应当是 3，实际是 {答案.查数量(表, '苹果')!r}。\n"
                       f"      是不是**用参数**查的？还是写死了？")
    try:
        得 = 答案.查数量(表, "橘子")
    except KeyError:
        return False, ("查一个**没有的商品**时抛了 KeyError —— 这正是这一课要避免的。\n"
                       "      ⚠ 写法一（最短）：\n"
                       "          return 库存表.get(商品名, 0)\n"
                       "        写法二：\n"
                       "          if 商品名 in 库存表:\n"
                       "              return 库存表[商品名]\n"
                       "          return 0")
    except Exception as e:                                      # noqa: BLE001
        return False, f"查不存在的商品时出错了：{type(e).__name__}: {e}"
    if 得 != 0:
        return False, (f"查一个没有的商品应当返回 **0**，实际返回 {得!r}。\n"
                       f"      ⚠ 返回 None 也不行 —— 调用者拿去做加法会崩。")
    if 答案.查数量({}, "任何") != 0:
        return False, "空字典里查任何东西都应当返回 0。"
    return True, "查得到 / 查不到 / 空字典 都对"


def CHECK_总件数(答案):
    if not hasattr(答案, "总件数"):
        return False, "还没有定义「总件数」函数。"
    if not callable(答案.总件数):
        return False, "「总件数」不是函数。"
    for 表, 期望 in (({"a": 1, "b": 2}, 3), ({}, 0), ({"x": 10}, 10), ({"a": -1, "b": 1}, 0)):
        try:
            得 = 答案.总件数(表)
        except Exception as e:                                  # noqa: BLE001
            return False, f"总件数({表}) 出错了：{type(e).__name__}: {e}"
        if 得 != 期望:
            return False, (f"总件数({表}) 应当是 {期望}，实际是 {得!r}。\n"
                           f"      ⚠ 遍历字典拿到的是**键**。要拿值得用 `.values()` 或 `.items()`：\n"
                           f"          for 名, 数 in 表.items():\n"
                           f"              和 += 数")
    return True, "四组都对（含空字典）"


def CHECK_用了get或in(答案):
    """⚠ 这一课的核心：查不存在的键不能崩 —— 要看得出你用对了工具。"""
    import io
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    i = 源码.find("def 查数量")
    段 = 源码[i:i + 400] if i >= 0 else ""
    if ".get(" not in 段 and " in " not in 段:
        return False, ("「查数量」里没有用 `.get(...)` 或 `in`。\n"
                       "      ⚠ 直接写 `库存表[商品名]` 在键不存在时会抛 KeyError。\n"
                       "        要用 `库存表.get(商品名, 0)`，或者先 `if 商品名 in 库存表:`")
    return True, "用了 .get() 或 in 来避免 KeyError"
