def _取(答案, 名字):
    f = 答案.__dict__.get(名字)
    return f if callable(f) else None


def CHECK_造连接(答案):
    f = _取(答案, "造连接")
    if f is None:
        return False, ("还没有定义「造连接」。它要返回 [(前, 后, 权重), …]："
                       "前 80% 权重 +0.09、后 20% 权重 -0.35，"
                       "每一对以 连接概率 连边、不给自己连")
    try:
        a = f(120, 0.08, 12345)
        b = f(120, 0.08, 12345)
        c = f(120, 0.08, 54321)
    except Exception as e:                                     # noqa: BLE001
        return False, "造连接(120, 0.08, 12345) 出错了：%s: %s" % (type(e).__name__, e)

    if not isinstance(a, list) or not a:
        return False, "造连接 要返回一个**非空**的列表，得到 %r" % (a,)
    坏形状 = [e for e in a[:50]
              if not (isinstance(e, tuple) and len(e) == 3)]
    if 坏形状:
        return False, ("每条边都要写成三元组 (前, 后, 权重)，"
                       "这几条不对：%r" % (坏形状[:3],))
    自环 = [e for e in a if e[0] == e[1]]
    if 自环:
        return False, ("不该给自己连边，出现了 %d 条自环，例如 %r" % (len(自环), 自环[0]))
    越界 = [e for e in a if not (0 <= e[0] < 120 and 0 <= e[1] < 120)]
    if 越界:
        return False, "神经元编号要在 0~119 之间，出现了 %r" % (越界[:2],)

    if a != b:
        return False, ("同一个种子必须生成**同一张网**，两次结果不一样。"
                       "检查一下是不是用了全局 random —— 要用 random.Random(f\"{种子}-连接\")")
    if a == c:
        return False, ("换了种子还是同一张网 —— 种子没起作用，"
                       "检查一下 random.Random 的种子参数是不是写死了")
    权 = {round(e[2], 3) for e in a}
    #  ⚠ 抑制性的权重是**负**的（-0.35）。这里要比的是 {-0.35, +0.09} 这个集合，
    #    第一版写成 `权 & {抑制权重}`（正数）⇒ 永远不匹配 ⇒ **正确答案也会被判错**。
    if not ({round(兴奋权重, 3), round(-抑制权重, 3)} <= 权):
        return False, ("权重应当只有两种：兴奋性 %s（正）、抑制性 %s（负）；"
                       "实际出现的是 %s" % (兴奋权重, -抑制权重, sorted(权)[:6]))
    数 = len(a)
    期望 = 120 * 119 * 0.08
    if not (0.5 * 期望 <= 数 <= 1.6 * 期望):
        return False, ("边数和连接概率对不上：120 个神经元、概率 0.08，"
                       "期望约 %.0f 条，实际 %d 条" % (期望, 数))
    兴奋边 = sum(1 for e in a if e[2] > 0)
    if not 0 < 兴奋边 < 数:
        return False, ("兴奋边和抑制边都要有，实际兴奋边 %d / 共 %d" % (兴奋边, 数))
    return True, ("边数 %d（期望约 %.0f）、同种子一致、换种子不同、"
                  "两种权重都在、无自环、编号没越界" % (数, 期望))


def CHECK_步进(答案):
    f = _取(答案, "步进")
    if f is None:
        return False, ("还没有定义「步进」。它要返回 (新膜电位列表, 发放的编号列表)："
                       "v = v * 漏电 + 输入；v >= 阈值 ⇒ 记发放、**v 清零**")
    try:
        新, 发 = f([0.0, 0.5, 2.0], [0.0, 0.0, 0.0], 0.85, 1.0)
    except Exception as e:                                     # noqa: BLE001
        return False, "步进([0.0, 0.5, 2.0], [0,0,0], 0.85, 1.0) 出错了：%s: %s" % (
            type(e).__name__, e)
    if not isinstance(新, list) or len(新) != 3:
        return False, "第一个返回值要是和输入一样长的**列表**，得到 %r" % (新,)
    if not isinstance(发, list):
        return False, "第二个返回值要是**发放编号的列表**，得到 %r" % (发,)
    if 发 != [2]:
        return False, ("输入是 [0.0, 0.5, 2.0]、阈值 1.0 ⇒ 只有 2 号到阈值、应当发放；"
                       "实际发放的是 %r" % (发,))
    if abs(新[2]) > 1e-9:
        return False, ("**发放之后必须清零**：2 号已经发放了，新电位应当是 0，"
                       "实际是 %r。忘了清零的话它会每一步都发放" % (新[2],))
    if abs(新[0]) > 1e-9:
        return False, "没有输入时电位应当漏成 0，实际 0 号是 %r" % (新[0],)
    if not (新[1] < 0.5):
        return False, ("没有输入时电位只会**变小**（漏电 0.85）："
                       "0.5 应当变成约 0.425，实际 %r" % (新[1],))

    # 分两次给输入，应当攒起来（不是"一次没到就永远到不了"）
    try:
        第1次, 发1 = f([0.0], [0.6], 0.85, 1.0)
        第2次, 发2 = f(第1次, [0.6], 0.85, 1.0)
    except Exception as e:                                     # noqa: BLE001
        return False, "连续两步给 0.6 的输入时出错：%s: %s" % (type(e).__name__, e)
    if 发1 != []:
        return False, "只给 0.6（低于阈值 1.0）不该发放，实际发放了 %r" % (发1,)
    if 发2 != [0]:
        return False, ("连着给两步 0.6：第一步 0.6，第二步 0.6*0.85+0.6=1.11 ≥ 1.0 ⇒ "
                       "第二步该发放，实际发放 %r（电位 %r）" % (发2, 第2次))
    return True, "没输入会漏、没到阈值不发放、攒够了才发放、发放后清零 —— 都对"


def CHECK_跑仿真(答案):
    f = _取(答案, "跑仿真")
    if f is None:
        return False, ("还没有定义「跑仿真」。它要返回 (平均放电率, 每步放电数)："
                       "用你自己写的 造连接 和 步进 把网络跑起来")
    try:
        率, 每步 = f(240, 0.08, 120, 20261014)
    except Exception as e:                                     # noqa: BLE001
        return False, "跑仿真(240, 0.08, 120, 20261014) 出错了：%s: %s" % (type(e).__name__, e)
    if not isinstance(每步, list) or len(每步) != 120:
        return False, ("每步放电数要和步数一样长（120 步 ⇒ 120 个数），"
                       "得到 %s 长度 %s" % (type(每步).__name__,
                                            len(每步) if isinstance(每步, list) else "无"))
    if any((not isinstance(x, int)) or x < 0 for x in 每步):
        return False, "每步放电数应当是非负整数，出现了 %r" % (每步[:5],)
    if not isinstance(率, float):
        return False, ("平均放电率要是**小数**（0.054 这种），得到 %r。"
                       "别忘了除以 (神经元数 × 步数)" % (率,))
    if 率 <= 0:
        return False, ("一个都不发放 —— 网络没被点着。检查一下："
                       "外部输入是不是加了？权重是不是传下去了？")
    if 率 >= 0.5:
        return False, ("平均放电率 %r 太高了（超过一半的神经元每步都在发放）—— "
                       "整张网烧起来了。最常见的原因：**发放之后忘了把电位清零**，"
                       "或者抑制性的负权重没生效" % (率,))
    if not (放电率下限 <= 率 <= 放电率上限):
        return False, ("平均放电率 %.4f 不在合理区间 [%.2f, %.2f]。"
                       "这张网实测稳定在 %.3f 左右"
                       % (率, 放电率下限, 放电率上限, 0.054))

    try:
        率2, 每步2 = f(240, 0.08, 120, 20261014)
        率3, _ = f(240, 0.08, 120, 777)
    except Exception as e:                                     # noqa: BLE001
        return False, "再跑一次时出错：%s: %s" % (type(e).__name__, e)
    if 每步2 != 每步:
        return False, ("同种子必须得到**一模一样**的结果，两次不一样。"
                       "检查 random.Random 的种子，别用全局 random")
    if 率3 == 率:
        return False, ("换了种子结果还是同一个数 —— 随机没起作用，种子是不是写死了")

    # ⚠ 「边到底有没有被用上」——这是最容易蒙混过去的一条。
    #
    #   造了边却**从不把权重传给下游**的实现，放电率照样落在那条区间里
    #   （外部输入自己就能把神经元敲响），光看区间抓不住它。
    #   ⇒ 把**连接概率**从 0.08 调到 0.30（网络密了近四倍），结果必须变；
    #     没有传播的实现两次会**一模一样**（边根本没参与）。
    try:
        率稀, _ = f(240, 0.08, 150, 20261014)
        率密, _ = f(240, 0.30, 150, 20261014)
    except Exception as e:                                     # noqa: BLE001
        return False, "换连接概率再跑时出错：%s: %s" % (type(e).__name__, e)
    if max(率稀, 率密) <= 0:
        return False, "两种连接概率下一次都没发放"
    相差 = abs(率密 - 率稀) / max(率稀, 率密)
    if 相差 < 0.15:
        return False, ("把连接概率从 0.08 换成 0.30（网络密了近四倍），结果几乎没变："
                       "%.4f vs %.4f。这说明**边造了却没被用上** —— "
                       "检查一下：上一步发放的神经元，有没有沿出边把权重加到下游的输入里？"
                       % (率稀, 率密))
    return True, ("150 步都在，平均放电率 %.4f（区间 [%.2f, %.2f]）、"
                  "同种子逐位一致、换种子不同、连接概率 0.08→0.30 时结果确实变了"
                  "（%.4f→%.4f，边真的在起作用）"
                  % (率, 放电率下限, 放电率上限, 率稀, 率密))


def CHECK_用现成的(答案):
    f = _取(答案, "用现成的")
    if f is None:
        return False, ("还没有定义「用现成的」。它要调 "
                       "`hybridengine_light.果蝇.仿真(...)` 并把结果对象原样返回")
    try:
        结 = f(神经元数=240, 连接概率=0.08, 仿真步数=120, 种子=20261014)
    except Exception as e:                                     # noqa: BLE001
        return False, ("用现成的(神经元数=240, 连接概率=0.08, 仿真步数=120, 种子=20261014) "
                       "出错了：%s: %s" % (type(e).__name__, e))
    for 名 in ("平均放电率", "每步放电数", "步数"):
        if not hasattr(结, 名):
            return False, ("返回的应当是一个**结果对象**（有 .平均放电率 / "
                           ".每步放电数 / .步数），现在的 %r 上没有 %s"
                           % (type(结).__name__, 名))
    if 结.步数 != 120 or len(结.每步放电数) != 120:
        return False, ("要的是 120 步，结果是 %r 步" % (结.步数,))
    if not (放电率下限 <= 结.平均放电率 <= 放电率上限):
        return False, ("现成模块给的放电率 %.4f 不在合理区间 [%.2f, %.2f]"
                       % (结.平均放电率, 放电率下限, 放电率上限))
    结2 = f(神经元数=240, 连接概率=0.08, 仿真步数=120, 种子=20261014)
    if 结2.每步放电数 != 结.每步放电数:
        return False, "现成模块也要**同种子同结果**，两次不一样 —— 是不是调用姿势不对"
    return True, ("会用现成的模块了：120 步、放电率 %.4f、同种子同结果"
                  % 结.平均放电率)


def CHECK_抑制真的压住了兴奋(答案):
    f = _取(答案, "用现成的")
    if f is None:
        return False, ("这一条要你先写好「用现成的」（它调 "
                       "`hybridengine_light.果蝇.仿真`），再拿它做对照实验")
    try:
        有 = f(神经元数=240, 连接概率=0.08, 仿真步数=200, 种子=20261014, 抑制强度=1.0)
        无 = f(神经元数=240, 连接概率=0.08, 仿真步数=200, 种子=20261014, 抑制强度=0.0)
    except Exception as e:                                     # noqa: BLE001
        return False, "做抑制对照时出错：%s: %s" % (type(e).__name__, e)
    if 有.平均放电率 <= 0:
        return False, "有抑制时一个都不发放 —— 抑制不该把网络压死"
    if 无.平均放电率 <= 有.平均放电率:
        return False, ("**关掉抑制之后放电率反而没上去**：有抑制 %.4f、没抑制 %.4f。"
                       "抑制性神经元的权重是**负**的，它应当把下游往回拉；"
                       "检查一下负权重有没有真的加到输入里"
                       % (有.平均放电率, 无.平均放电率))
    倍数 = 无.平均放电率 / 有.平均放电率
    if 倍数 < 1.5:
        return False, ("抑制压得不够狠：有抑制 %.4f、没抑制 %.4f，只差 %.2f 倍"
                       "（这一课实测约 8 倍）。检查抑制权重是不是被改小了"
                       % (有.平均放电率, 无.平均放电率, 倍数))
    if 无.平均放电率 < 0.15:
        return False, ("关掉抑制之后也没烧起来（%.4f）—— 这说明兴奋太弱，"
                       "「抑制是刹车」这件事就演示不出来了"
                       % (无.平均放电率,))
    return True, ("抑制真的压住了兴奋：有抑制 %.4f → 没抑制 %.4f，"
                  "**%.1f 倍**（同一张网、同一份输入，只改了抑制这一件事）"
                  % (有.平均放电率, 无.平均放电率, 倍数))
