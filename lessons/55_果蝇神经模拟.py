# 第 55 课：果蝇神经模拟 —— 让一群神经元自己放电
# ─────────────────────────────────────────────────────
#  这一课你会学到
# ─────────────────────────────────────────────────────
#    一个神经元就是「一个会漏水的桶」：有输入就往上涨，涨到阈值就放电、
#    然后清零重来。把几百个这样的桶按概率连起来，网络自己就会放电 ——
#    而**抑制**是它的刹车。
#
#  需要先会
#    第 05 课：列表（这一课的膜电位就是一串数）
#    第 28 课：递归 / 第 29 课：分治（不是因为用到，是因为到这一课你该不怕长了）
#    第 16 课：模块与 random（要 import 别人的东西）
#
# ─────────────────────────────────────────────────────
#  怎么读这一课
# ─────────────────────────────────────────────────────
#
#   先从头读一遍讲解，再照着最后的「轮到你了」写。
#   卡住了看答案（先自己写一遍）—— 命令在「怎么自己测」那一节。
#
# ─────────────────────────────────────────────────────
#  先介绍：为什么学习内核只做果蝇
# ─────────────────────────────────────────────────────
#
# 这一条线的规格是「**学习内核只能运行果蝇神经模拟**」。这不是做不到人脑，
# 是**有意这么分的**：
#
#     果蝇   约 10 万个神经元      ← 学习内核（你在这里）
#     人脑   约 860 亿个神经元      ← 那是另一条线的事
#
# 三个理由，都很实在：
#     ① **看得懂**：每个神经元都能给个编号、画在纸上；
#        860 亿个画不出来，只能讲抽象的平均量。
#     ② **跑得动**：这一课默认 240 个神经元、200 步，零点几秒就跑完，
#        你改一个参数立刻能看到变化。同样「逐细胞」地跑人脑，
#        差的不是快慢，是**十个数量级** —— 根本做不到。
#     ③ **果蝇本来就是神经科学的模式动物**：它是少数几个
#        **全脑连接组被完整测出来**的动物之一，讲神经计算有真数据撑腰。
#
# ─────────────────────────────────────────────────────
#  一、一个神经元 = 一个会漏水的桶
# ─────────────────────────────────────────────────────
#
# 给每个神经元记一个数 `v`（膜电位）。每一步做两件事：
#
#     ① 往桶里倒水：v = v * 漏电 + 输入
#     ② 满了就洒掉：如果 v >= 阈值，就记一次「发放」，然后 v = 0
#
# `漏电` 是个小于 1 的数（这一步用 0.85）。它的意思是
# **不给输入的话，电位会自己慢慢漏光** —— 这就是 leaky 那个词。
# 没有漏电，电位只涨不消，攒够一次就永远在发放了。
#
# 「放电」就是神经元在说话。我们数的是**每步有几个神经元在放电**。
#
# ─────────────────────────────────────────────────────
#  二、把神经元连起来：一张有方向的网
# ─────────────────────────────────────────────────────
#
# 光有一堆孤立的桶什么也不会发生。要连起来：
#
#     任意两个神经元 甲 → 乙，以 `连接概率` 的概率连一条边
#
# 注意方向：甲→乙 和 乙→甲 是**两条不同的边**。甲放电时，
# 乙的输入里就多一份甲的权重；反过来不影响。
#
# 这一步用 `random.Random(种子)` 而不是全局的 `random` ——
# 它给你一条**自己的**随机数流。好处是：同一个种子必然生成同一张网，
# 而且不会和别处的随机数互相干扰。
#
# ─────────────────────────────────────────────────────
#  三、兴奋和抑制：油门和刹车
# ─────────────────────────────────────────────────────
#
# 神经元分两种，靠**权重的正负**区分：
#
#     兴奋性（前 80%）  权重是**正**的 ⇒ 把下游往阈值上推（油门）
#     抑制性（后 20%）  权重是**负**的 ⇒ 把下游往回拉（刹车）
#
# 没有刹车会怎样？实测：这张网会**烧起来** ——
# 平均放电率从 5% 飙到 43%（八个多倍），几乎整张网一起放电。
# 有了刹车，网络稳定在稀疏放电（少数神经元在说话）——
# 真实大脑也是这个状态：**少数人在说，多数人在听**。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：忘了「发放之后要清零」
# ─────────────────────────────────────────────────────
#
#     if v >= 阈值:
#         发放.append(k)          ← 只记了一笔，**没把 v 清掉**
# 后果：下一个输入只要再补一点点，它又满一次。于是这个神经元
# **每一步都在发放**，放电率被它一个人拉高，而且看不出是哪错了 ——
# 结果「看起来也在跑」，只是数字不对。
# ⇒ 发放之后一定要 `v = 0`，让它从零开始重新攒。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   真实连接组、突触可塑性、树突、多巴胺、学习规则 —— 都不是这一课。
#   这一课只讲「会漏水的桶 + 按概率连起来 + 抑制是刹车」。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
