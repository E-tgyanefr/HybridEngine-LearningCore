#: 「平均放电率」的合理区间。**这不是随便定的**：
#:   实测这张网稳定在 5.4% 左右 —— 少数神经元在发放。
#:   低于 1% 说明网络根本没被点着；高于 25% 说明刹车坏了（烧起来了）。
放电率下限 = 0.01
