# ─────────────────────────────────────────────────────
#  先介绍：列表有两个毛病
# ─────────────────────────────────────────────────────
#
#   ① 有些东西是**一整套**的，本来就不该被改：坐标、日期、一年十二个月
#   ② 想知道「有没有重复」，得自己写循环一个个查
# 元组解决 ①，集合解决 ② —— 两个的写法都很短，难的是**记住该用哪个**。
# ─────────────────────────────────────────────────────
#  一、元组：不能改的列表
# ─────────────────────────────────────────────────────
#
#    坐标 = (3, 5)
#    坐标[0]        ⇒ 3           取值、len()、遍历，都和列表一样
#    坐标[-1]       ⇒ 5           负数从后往前
#    坐标[0] = 9    ❌ TypeError: 'tuple' object does not support item assignment
#
#   ⚠ 改不了是**设计**（一整套坐标就该锁住）；元组还能当字典的键，
#   因为**键不能被改**，而列表能改，所以列表不能当键：
#    座位 = {(1, 2): '小明'}        ← 第 1 排第 2 座
#    座位[(1, 2)]     ⇒ '小明'
#    {[1, 2]: '小明'} ❌ TypeError: unhashable type: 'list'
#
# ─────────────────────────────────────────────────────
#  二、集合：一堆不重复的东西
# ─────────────────────────────────────────────────────
#
#    水果 = {'苹果', '香蕉', '苹果'}     ⇒ {'苹果', '香蕉'}   重复的自动没了
#    甲 = {1, 2, 3}      乙 = {2, 3, 4}
#    甲 & 乙  交集 ⇒ {2, 3}        甲 | 乙  并集 ⇒ {1, 2, 3, 4}
#    甲 - 乙  差集 ⇒ {1}           只在甲、不在乙
#
#   ⚠ 记号别记混：`&` 是**都**要，`|` 是**都收**，`-` 是**扣掉**。
#    s = set()        ← ⚠ 空集合只能写 set()；`{}` 是空**字典**（第 13 课）
#    s.add(7)         ⇒ {7}        s.discard(9) ⇒ set()（没有 9 也不报错）
#
#   去重、查重、判存在 —— 先想到 set：集合里 `in` 一步到位，列表要一个个比。
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：单元素元组那个逗号
# ─────────────────────────────────────────────────────
#
#   只有一个元素的元组，**逗号不能省**：
#
#     甲 = (7,)   ⇒ (7)   是元组，len 是 1
#     乙 = (7)    ⇒ 7     只是加了括号的数字
#
#     len(乙)   ❌ TypeError: object of type 'int' has no len()
#     乙 + 1    ⇒ 8     ← 它真是个数字，不报错，所以更隐蔽
#
#  ⇒ 记住：**元组靠逗号，不靠括号**：`3, 5` 就是元组，单个必须写 `(7,)`。
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   只讲元组和集合怎么用。推导式（`{x for x in ...}`）是第 19 课。
