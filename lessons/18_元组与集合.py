def CHECK_坐标和单元素(答案):
    if not hasattr(答案, "坐标"):
        return False, "还没有定义「坐标」。写法：坐标 = (3, 5)   ← 圆括号，两个整数"
    if not isinstance(答案.坐标, tuple) or len(答案.坐标) != 2:
        return False, (f"「坐标」应当是 2 个数的元组，现在是 "
                       f"{type(答案.坐标).__name__}：{答案.坐标!r}\n"
                       f"      ⚠ 方括号 [] 是列表，圆括号 () 才是元组。")
    if not all(isinstance(x, int) and not isinstance(x, bool) for x in 答案.坐标):
        return False, f"「坐标」应当是 2 个整数，现在是 {答案.坐标!r}。"
    if not hasattr(答案, "单元素"):
        return False, "还没有定义「单元素」。写法：单元素 = (7,)   ← ⚠ 这个逗号不能省"
    if not isinstance(答案.单元素, tuple) or len(答案.单元素) != 1:
        return False, (f"「单元素」应当是只有 1 个元素的元组，现在是 "
                       f"{type(答案.单元素).__name__}：{答案.单元素!r}\n"
                       f"      ⚠ (7) 只是个加了括号的数字，**(7,) 才是元组**。")
    return True, f"坐标={答案.坐标!r} 单元素={答案.单元素!r}"


def CHECK_去重(答案):
    if not hasattr(答案, "带重复"):
        return False, "还没有定义「带重复」。写法：带重复 = [1, 2, 2, 3, 3, 3]"
    v = 答案.带重复
    if not isinstance(v, list):
        return False, f"「带重复」应当是列表，现在是 {type(v).__name__}。"
    if len(set(v)) == len(v):
        return False, (f"「带重复」里没有重复：{v!r} —— 那样看不出 set() 有没有用。\n"
                       f"      请让它**至少有重复的元素**，例如 [1, 2, 2, 3, 3, 3]。")
    if not hasattr(答案, "去重"):
        return False, "还没有定义「去重」。写法：去重 = set(带重复)"
    s = 答案.去重
    if not isinstance(s, set) or s != set(v):
        return False, (f"「去重」应当是 {set(v)!r}（一个**集合**），现在是 "
                       f"{type(s).__name__}：{s!r}\n"
                       f"      ⚠ set(列表) 给出的才是集合。")
    return True, f"带重复={v!r} → 去重={s!r}"


def CHECK_交集和差集(答案):
    交 = 答案.__dict__.get("共同")
    差 = 答案.__dict__.get("只在我这")
    if not callable(交) or not callable(差):
        return False, ("「共同」和「只在我这」都要写成函数。写法：\n"
                       "          def 共同(甲, 乙):\n"
                       "              return 甲 & 乙      ← `&` 是交集\n"
                       "          def 只在我这(甲, 乙):\n"
                       "              return 甲 - 乙      ← `-` 是差集")
    for 甲, 乙 in (({1, 2, 3}, {2, 3, 4}), ({1, 2}, {3}), (set(), {1}), ({1}, {1})):
        try:
            得交, 得差 = set(交(甲, 乙)), set(差(甲, 乙))
        except Exception as e:                                  # noqa: BLE001
            return False, f"共同/只在我这({甲!r}, {乙!r}) 出错：{type(e).__name__}: {e}"
        if 得交 != 甲 & 乙:
            return False, (f"共同({甲!r}, {乙!r}) 应当是 {甲 & 乙!r}，得到 {得交!r}。\n"
                           f"      ⚠ 两个集合**都有**的元素 —— 写法是 甲 & 乙")
        if 得差 != 甲 - 乙:
            return False, (f"只在我这({甲!r}, {乙!r}) 应当是 {甲 - 乙!r}，得到 {得差!r}。\n"
                           f"      ⚠ 顺序有讲究：要把**乙里也有的扣掉**，写成 乙 - 甲 就反了。")
    return True, "交集、差集各四组都对（含空集合）"


def CHECK_座位用元组当键(答案):
    if not hasattr(答案, "座位"):
        return False, ("还没有定义「座位」字典。写法：座位 = {(1, 2): '小明'}\n"
                       "      ⚠ 键要用**元组**（不能改），列表当键会报 unhashable。")
    v = 答案.座位
    if not isinstance(v, dict) or len(v) < 2:
        return False, (f"「座位」应当是有至少 2 个键的字典，"
                       f"现在是 {type(v).__name__}：{v!r}")
    非元组 = [type(k).__name__ for k in v if not isinstance(k, tuple)]
    if 非元组:
        return False, (f"「座位」的键应当都是**元组**，现在有 {非元组}。\n"
                       f"      ⚠ 键不能被改 ⇒ 列表当键会报 TypeError: unhashable type: 'list'")
    if not all(len(k) == 2 for k in v):
        return False, f"每个座位键应当是两个数（第几排、第几号），现在是：{list(v)}"
    return True, f"{len(v)} 个座位：{v}"
