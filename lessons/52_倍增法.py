# ─────────────────────────────────────────────────────
#  先介绍：一步一步太慢，那就翻着倍走
# ─────────────────────────────────────────────────────
#
# 要找的东西在 100 万个数里的最后一个，一步一步走要 100 万步。可是如果允许你
# 「先跳 1 步、再跳 2 步、再跳 4 步……」，20 步就能跨过 100 万 —— 因为 2^20 = 1048576。
#
# 这就是**倍增**：每一步的步长都是上一步的两倍。这一课就讲它的两个用法。
#
# ─────────────────────────────────────────────────────
#  一、快速幂：把 999 次乘法变成 16 次
# ─────────────────────────────────────────────────────
#
# 算 2^1000，朴素写法要乘 999 次。换条路：先把指数写成二进制
#
#     1000 = 1111101000₂ = 512 + 256 + 128 + 64 + 32 + 8
#
# 于是 2^1000 = 2^512 × 2^256 × 2^128 × 2^64 × 2^32 × 2^8 —— 只要把底数**反复平方**
# 就能备好这些 2 的幂，再把需要的挑出来乘进结果：
#
#     def 幂(底, 指数):
#         结果 = 1                       ← ⚠ 必须是 1，不是 0
#         while 指数 > 0:
#             if 指数 % 2 == 1: 结果 *= 底
#             底 *= 底                    ← 平方：底 依次变成 底²、底⁴、底⁸…
#             指数 = 指数 // 2            ← 指数右移一位（丢一位就够）
#         return 结果
#
# 数一数 2^1000：1000 的二进制有 **10 位**（10 次平方），其中有 **6 个 1**
# （6 次乘进结果）—— 一共 **16 次乘法**，而不是 999 次。
#
# ⚠ 指数很大时结果会是个天文数字：2^1000 有 302 位，3^997 有 476 位。所以竞赛里
#   几乎总是配合取模：`幂取模(底, 指数, 模)`，每一步乘法后都 % 模。
#
# ─────────────────────────────────────────────────────
#  二、2^k 跳跃：在有序表里找位置
# ─────────────────────────────────────────────────────
#
# 有序表里找「第一个不小于 目标 的位置」，挨着扫是 O(n)。倍增是这么跳的：
#
#     位置 = 0，跳 = 1、2、4、8…（先放大到 ≥ 表长，再从大到小试）
#     只要「位置 + 跳 还在表内」且「跳过去的那格仍小于目标」，就跳过去
#
#     表 = [1, 2, 3, 4, 5]，目标 = 3：
#       跳 8、4：跳过去那格（4）不小于 3，不跳
#       跳 2：表[1] = 2 < 3，跳 ⇒ 位置 = 2
#       跳 1：表[2] = 3 不小于 3，不跳   ⇒  答案 2
#
# ⚠ 表长 100 万时，跳的步长最多到 2^20，所以整个查找**最多 20 次左右**的判断。
#
# ─────────────────────────────────────────────────────
#  三、为什么 O(n) 能降到 O(log n)
# ─────────────────────────────────────────────────────
#
#     量级        一步一步          翻倍走
#     10          10 次            4 次（2^4 = 16）
#     1000        1000 次          10 次
#     100 万      100 万次         20 次
#
# 关键在这句：**n 每翻一倍，步数只多 1**。所以 n 长得再快，步数也几乎不动。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：跳之前没问「还在表内吗」
# ─────────────────────────────────────────────────────
#
#     while 起 + 跳 < len(表) and 表[起 + 跳] < 目标:    ❌ 差一位
#
# 起 + 跳 正好等于表长时，表[起 + 跳] 就越界了：
#     → IndexError: list index out of range
#
# ⇒ 跳之前先问「跳过去还在表内吗」（起 + 跳 <= len(表)），取元素用 表[起 + 跳 - 1]。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   倍增求最近公共祖先、ST 表、矩阵快速幂 —— 那些要先会树，这一课先不碰。
