def _喂(函数, 名字, 用例们, 提示):
    for 用例 in 用例们:
        *参数们, 想 = 用例
        try:
            得 = 函数(*参数们)
        except Exception as e:                                  # noqa: BLE001
            return False, f"{名字}{tuple(参数们)} 出错：{type(e).__name__}: {e}｜{提示}"
        if 得 != 想:
            return False, f"{名字}{tuple(参数们)} 应当是 {想!r}，得到 {得!r}｜{提示}"
    return True, f"{len(用例们)} 组都对"


def CHECK_快速幂(答案):
    f = 答案.__dict__.get("幂")
    if not callable(f):
        return False, ("还没有定义「幂」。要点：结果从 1 起；指数是奇数就 结果 *= 底；"
                       "然后 底 *= 底、指数 //= 2，直到指数变成 0")
    return _喂(f, "幂", ((2, 10, 1024), (2, 0, 1), (0, 0, 1), (5, 1, 5), (3, 5, 243),
                       (0, 5, 0), (1, 10 ** 6, 1), (2, 1000, pow(2, 1000))),
               "结果要从 **1** 起（从 0 起的话乘什么都还是 0）；指数 0 一律返回 1，"
               "包括 0 ** 0；2^1000 要和 Python 自带的 pow 一样")


def CHECK_快速幂取模(答案):
    f = 答案.__dict__.get("幂取模")
    if not callable(f):
        return False, ("还没有定义「幂取模」。和 幂 一样写，只是每一步乘法后都 "
                       "% 模 —— 别等乘完再取模，那时候数已经大得算不动了")
    return _喂(f, "幂取模", ((2, 10, 1000, 24), (3, 0, 7, 1), (5, 3, 7, 6), (10, 5, 1, 0),
                          (2, 1000, 10 ** 9 + 7, pow(2, 1000, 10 ** 9 + 7)),
                          (123456, 789, 97, pow(123456, 789, 97))),
               "2^10 = 1024，对 1000 取模是 24；模是 1 时一切都是 0；"
               "每一步都要取模，最后才取模会算出一个几千位的大数")


def CHECK_倍增找位置(答案):
    f = 答案.__dict__.get("第一个不小于")
