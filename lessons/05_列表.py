# ─────────────────────────────────────────────────────
#  先介绍：为什么需要列表
# ─────────────────────────────────────────────────────
#
# 要存 5 个分数，用变量就得这样：
#
#     分数1 = 90
#     分数2 = 75
#     分数3 = 60
#     ...
#
# 一百个分数就要一百个变量名 —— 而且没法用循环处理它们。
#
# 列表把一堆东西装进**一个**变量里：
#
#     成绩 = [90, 75, 60, 45, 88]
#            ↑                 ↑
#            方括号            逗号分隔
#
# ─────────────────────────────────────────────────────
#  按下标取 —— 下标从 0 开始
# ─────────────────────────────────────────────────────
#
#     成绩 = [90, 75, 60, 45, 88]
#              ↑   ↑   ↑   ↑   ↑
#     下标     0   1   2   3   4
#
#     成绩[0]    ⇒  90        第一个
#     成绩[2]    ⇒  60        第三个（不是第二个！）
#     成绩[-1]   ⇒  88        最后一个（负数从右边数）
#     成绩[-2]   ⇒  45        倒数第二个
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课唯一要记住的坑：下标从 0 开始
# ─────────────────────────────────────────────────────
#
#     "第 1 个" 是 成绩[0]
#     "第 3 个" 是 成绩[2]
#
#   ⇒ 规律：**第 n 个元素的下标是 n - 1**。
#
#   为什么容易错：数数是从 1 开始的习惯太深了。
#   而且写错下标有两种后果：
#     · 取到了**别的**元素   —— 不报错，结果是错的（最难查）
#     · 下标**超出范围**     —— IndexError: list index out of range
#
# ─────────────────────────────────────────────────────
#  另外三个常用操作
# ─────────────────────────────────────────────────────
#
#     len(成绩)     有几个元素          ⇒  5
#     sum(成绩)     加起来              ⇒  358
#     max(成绩)     最大的              ⇒  90
#     min(成绩)     最小的              ⇒  45
#
#   ⚠ 这三个是 Python **自带的函数**，不用自己写循环。
#     （但第 08 课会请你用循环写一遍 —— 先会自己写，再用现成的。）
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   往列表里**加东西、删东西**是第 06 课；
#   用循环处理列表是第 08 课。这一课只练"取"。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 定义列表 成绩，放 5 个分数（整数，要有大有小）
#   2. 定义变量 第一个，值是 成绩 的第 1 个元素
#   3. 定义变量 第三个，值是 成绩 的第 3 个元素      ← ⚠ 想清楚下标是几
#   4. 定义变量 最后一个，值是 成绩 的最后一个元素
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 05


def CHECK_成绩列表(答案):
    if not hasattr(答案, "成绩"):
        return False, ("还没有定义「成绩」列表。\n"
                       "      写法：成绩 = [90, 75, 60, 45, 88]\n"
                       "      ⚠ **方括号**，元素之间用逗号。")
    v = 答案.成绩
    if not isinstance(v, list):
        return False, (f"「成绩」应当是列表，现在是 {type(v).__name__}。\n"
                       f"      ⚠ 圆括号 () 是元组、花括号 {{}} 是字典 —— 列表用方括号 []。")
    if len(v) < 5:
        return False, f"「成绩」里只有 {len(v)} 个元素，要求 5 个。"
    if not all(isinstance(x, int) and not isinstance(x, bool) for x in v):
        return False, (f"「成绩」里应当都是整数 —— 加了引号的 '90' 是文字。\n"
                       f"      现在有：{v}")
    if len(set(v)) == 1:
        return False, "5 个分数都一样 —— 那样看不出下标有没有取对。"
    return True, f"成绩 = {v}"


def CHECK_第一个(答案):
    if not hasattr(答案, "第一个"):
        return False, "还没有定义「第一个」。写法：第一个 = 成绩[0]"
    if not hasattr(答案, "成绩") or not 答案.成绩:
        return False, "先定义好「成绩」列表。"
    期望 = 答案.成绩[0]
    if 答案.第一个 != 期望:
        if 答案.成绩 and 答案.第一个 == 答案.成绩[-1]:
            return False, (f"「第一个」取到的是最后一个元素 {答案.第一个}。\n"
                           f"      ⚠ 负数下标是从右边数的：成绩[-1] 是最后一个。\n"
                           f"        第一个要用 成绩[0]。")
        return False, f"「第一个」应当是 {期望}（成绩[0]），现在是 {答案.第一个!r}。"
    return True, f"第一个 = {期望}（下标 0）"


def CHECK_第三个(答案):
    if not hasattr(答案, "第三个"):
        return False, ("还没有定义「第三个」。\n"
                       "      ⚠ 提示：**第 3 个元素的下标是 2**，不是 3。\n"
                       "        写法：第三个 = 成绩[2]")
    if not hasattr(答案, "成绩") or len(答案.成绩) < 3:
        return False, "先定义好「成绩」列表（至少 3 个元素）。"
    期望 = 答案.成绩[2]
    if 答案.第三个 != 期望:
        if len(答案.成绩) > 3 and 答案.第三个 == 答案.成绩[3]:
            return False, (f"「第三个」取到的是 {答案.第三个} —— 那是**第 4 个**元素。\n"
                           f"      ⚠⚠ 下标从 0 开始：\n"
                           f"         第 1 个 ⇒ 成绩[0]\n"
                           f"         第 2 个 ⇒ 成绩[1]\n"
                           f"         第 3 个 ⇒ 成绩[2]      ← 你要的是这个\n"
                           f"         **第 n 个元素的下标是 n - 1。**")
        return False, f"「第三个」应当是 {期望}（成绩[2]），现在是 {答案.第三个!r}。"
    return True, f"第三个 = {期望}（下标 2，不是 3）"


def CHECK_最后一个(答案):
    if not hasattr(答案, "最后一个"):
        return False, ("还没有定义「最后一个」。\n"
                       "      两种写法都对：\n"
                       "        最后一个 = 成绩[-1]              ← 推荐（长度变了也不用改）\n"
                       "        最后一个 = 成绩[len(成绩) - 1]")
    if not hasattr(答案, "成绩") or not 答案.成绩:
        return False, "先定义好「成绩」列表。"
    期望 = 答案.成绩[-1]
    if 答案.最后一个 != 期望:
        return False, (f"「最后一个」应当是 {期望}，现在是 {答案.最后一个!r}。\n"
                       f"      ⚠ 最省事的写法是 成绩[-1] —— 负数就是从右边数。\n"
                       f"        用 成绩[5] 这种写死下标的做法，列表一变长就错了。")
    return True, f"最后一个 = {期望}（成绩[-1]）"
