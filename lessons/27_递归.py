        try:
            得 = f(数字们)
        except RecursionError:
            return False, (f"递归求和({数字们[:6]}{'…' if len(数字们) > 6 else ''}) "
                           f"报了 RecursionError —— 停不下来。\n"
                           f"      ⚠ 空列表就是基准情形：`if not 数字们: return 0`。")
