def CHECK_递归求和(答案):
    f = 答案.__dict__.get("递归求和")
    if not callable(f):
        return False, ("还没有定义函数「递归求和」。\n"
                       "      写法：def 递归求和(数字们):\n"
                       "                if not 数字们:\n"
                       "                    return 0\n"
                       "                return 数字们[0] + 递归求和(数字们[1:])")
