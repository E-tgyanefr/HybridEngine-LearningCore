# ─────────────────────────────────────────────────────
#  先介绍：有些问题的答案，就是「小一号的自己」
# ─────────────────────────────────────────────────────
#
# 数学里 n 的阶乘是这样定义的：
#
#     n! = n × (n-1)!        ← 右边又出现了「!」
#
# 这种「自己里还有自己」的式子，写成函数就是**递归**：
#
#     阶乘(4) = 4 × 阶乘(3) = 4 × 3 × 阶乘(2) = … = 24
#
# 好处是代码和数学式子长得几乎一样，写完不容易错；代价是它吃内存、有层数上限。
#
# ─────────────────────────────────────────────────────
#  一、最小的递归：自己叫自己，但事情变小了
# ─────────────────────────────────────────────────────
#
#     def 倒着数(n):
#         if n <= 0:              ← ① **基准情形**：到这儿就停，不再往下叫
#             print('走完啦')
#             return
#         print(n)
#         倒着数(n - 1)           ← ② 自己叫自己，但参数**变小**了
#
#     倒着数(3)      ⇒ 3 2 1 走完啦
#
# ⚠ 递归必须有这两件事，缺一件就永远停不下来：
#
#     ① 基准情形（什么问题不用再递归，直接给答案）
#     ② 每次调用**规模变小**（朝着基准情形走）
#
#     def 下去(n):
#         return 下去(n + 1)      ← 参数没变小，反而变大
#
#     下去(0)
#     ⇒ RecursionError: maximum recursion depth exceeded
#
# Python 默认最多 1000 层。`import sys; sys.setrecursionlimit(5000)` 能改上限，
# 但别急着改 —— 真需要几千层的写法，通常用循环更合适。
#
# ─────────────────────────────────────────────────────
#  二、调用栈：递归是「先一路往下，再一路往上算」
# ─────────────────────────────────────────────────────
#
# 算 阶乘(4) 的时候，每一层都在等下一层的结果，谁也没算完：
#
#     阶乘(4)
#       └─ 4 × 阶乘(3)
#            └─ 3 × 阶乘(2)
#                 └─ 2 × 阶乘(1)
#                      └─ 阶乘(0) = 1      ← 到底了！开始一层层往回算
#
# 往回算的顺序：1 → 1×2 = 2 → 2×3 = 6 → 6×4 = **24**
#
# 这些「等着下一层的函数」摞在一起，就叫**调用栈**。
# 摞得太高就 RecursionError：栈是有限的，不是无限的。
#
# ─────────────────────────────────────────────────────
#  三、三个必须会的递归（都能当模板背下来）
# ─────────────────────────────────────────────────────
#
#  ① 阶乘：n! = n × (n-1)!
#
#         def 阶乘(n):
#             if n == 0:              ← 基准情形。0! = 1（不是 0）
#                 return 1
#             return n * 阶乘(n - 1)
#
#  ② 斐波那契：0, 1, 1, 2, 3, 5, 8, 13…（每个数 = 前两个之和）
#
#         def 斐波那契(n):
#             if n < 2:               ← 基准情形：fib(0)=0、fib(1)=1
#                 return n
#             return 斐波那契(n - 1) + 斐波那契(n - 2)
#
#     ⚠ 这个写法能算对，但**慢得吓人**（实测）：
#         n=25 → 0.005 秒    n=30 → 0.06 秒    n=35 → 0.66 秒
#         n=40 → 8.3 秒      n=50 → 十几分钟
#       因为 fib(3) 这样的值被反复算了几百万遍。第 28 课用递推解决它。
#
#  ③ 汉诺塔：n 个盘子要搬 2ⁿ − 1 次
#
#         def 汉诺塔(盘子数):
#             if 盘子数 == 0:         ← 没有盘子要搬
#                 return 0
#             return 汉诺塔(盘子数 - 1) * 2 + 1
#
#     为什么是 ×2 + 1：先把上面 n−1 个搬到中转柱（汉诺塔(n−1) 次），
#     再搬最大的那个（1 次），最后把那 n−1 个搬过去（又 汉诺塔(n−1) 次）。
#
# ─────────────────────────────────────────────────────
#  四、写递归的三步（照着这个顺序想，不要脑内展开十层）
# ─────────────────────────────────────────────────────
#
#     ① 最小的情况是什么？        ⇒ 写成基准情形，直接 return
#     ② 大问题怎么变成小一号的？  ⇒ 写成「自己调用自己，但参数更小」
#     ③ 相信小一号那次能算对      ⇒ 别在脑子里一层层展开，越展开越乱
#
# ⚠ 第 ③ 条是新手最过不去的坎。递归的写法是**声明式**的：
#   你只要保证「本层用对了下一层的答案」，剩下的交给同一段代码。
#
# ─────────────────────────────────────────────────────
#  五、什么时候别用递归
# ─────────────────────────────────────────────────────
#
#     用递归：问题本身就是「小一号的自己」    汉诺塔、树、快排
#     用循环：一眼能看出次数的              求和、找最大值、数数
#
# ⚠ Python 没有「尾递归优化」（有些语言有）：递归多少层，就真的摞多少层。
#   所以 Python 里深度超过几百层的活，请优先用循环（第 28 课就是干这个的）。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：忘了基准情形，或者参数没变小
# ─────────────────────────────────────────────────────
#
#     def 下去(n):
#         return 下去(n + 1)
#
#     下去(0)
#     ⇒ RecursionError: maximum recursion depth exceeded
#
# ⚠ 它不会「跑很久」，而是**几毫秒就报错** —— 因为 1000 层很快就摞满了。
#   看到这个报错，先查两件事（顺序别反）：
#     ① 基准情形写了吗？写得**到得了**吗？（比如 n == 0，可你一直在 n + 1）
#     ② 每次调用参数真的变小了吗？（`n - 1` 写成了 `n` 也是常见手滑）
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   回溯、分治、记忆化、递归转循环、递归的复杂度分析 —— 用到再说。
#   这一课只讲：基准情形 + 规模变小，以及三个经典例子。
#
