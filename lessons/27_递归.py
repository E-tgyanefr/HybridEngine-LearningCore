import io


def _源码段(答案, 函数名, 长度=500):
    """取学员源码里某个函数后面的一段 —— 用来确认「真的用了递归」。"""
    if not hasattr(答案, "__file__"):
        return None
    try:
        源码 = io.open(答案.__file__, encoding="utf-8").read()
    except OSError:
        return None
    i = 源码.find("def " + 函数名)
    return 源码[i:i + 长度] if i >= 0 else ""


def _必须递归(答案, 函数名):
    """返回 (是否可以继续, 失败说明)。函数体里必须出现自己。"""
    段 = _源码段(答案, 函数名)
    if 段 is None:
        return True, ""
    if not 段:
        return True, ""
    # def 阶乘(n): 之后要再出现一次 阶乘(
    if 段.count(函数名 + "(") < 2:
        return False, (f"「{函数名}」里没有调用自己 —— 这一课要求**用递归**写。\n"
                       f"      递归的样子：函数体里出现 {函数名}(…)，而且参数更小。\n"
                       f"      用循环虽然也能算对，但这一课练的就是递归。")
    return True, ""


def CHECK_阶乘(答案):
    f = 答案.__dict__.get("阶乘")
    if not callable(f):
        return False, ("还没有定义函数「阶乘」。\n"
                       "      写法：def 阶乘(n):\n"
                       "                if n == 0:\n"
                       "                    return 1\n"
                       "                return n * 阶乘(n - 1)")
    行不行, 说明 = _必须递归(答案, "阶乘")
    if not 行不行:
        return False, 说明
    for n, 想 in ((0, 1), (1, 1), (3, 6), (5, 120), (10, 3628800)):
        try:
            得 = f(n)
        except RecursionError:
            return False, (f"阶乘({n}) 报了 RecursionError —— 一直往下递归没停。\n"
                           f"      ⚠ 检查基准情形：是不是写成了 `if n == 0: return 1`？")
        except Exception as e:                              # noqa: BLE001
            return False, f"阶乘({n}) 出错了：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"阶乘({n}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 两个常见错：0! 写成 0（应当是 1）；"
                           f"忘了 `return n * 阶乘(n - 1)` 里的乘号。")
    return True, "五组都对（含 0! = 1 和 10! 这种大数），而且是递归写的"


