def CHECK_购物最终内容(答案):
    if not hasattr(答案, "购物"):
        return False, "还没有定义「购物」列表。写法：购物 = ['苹果']"
    if not isinstance(答案.购物, list):
        return False, f"「购物」应当是列表，现在是 {type(答案.购物).__name__}。"
    # 期望：['牛奶']（苹果删了、香蕉弹出了、牛奶插在最前）
    期望 = ["牛奶"]
    if 答案.购物 != 期望:
        return False, (f"最后「购物」应当是 {期望}，实际是 {答案.购物!r}。\n"
                       f"      按顺序做一遍：\n"
                       f"        购物 = ['苹果']                 ⇒ ['苹果']\n"
                       f"        购物.append('香蕉')             ⇒ ['苹果', '香蕉']\n"
                       f"        购物.insert(0, '牛奶')          ⇒ ['牛奶', '苹果', '香蕉']\n"
                       f"        购物.remove('苹果')             ⇒ ['牛奶', '香蕉']\n"
                       f"        购物.pop()                      ⇒ ['牛奶']   （香蕉被弹出）\n"
                       f"      ⚠ 哪一步对不上，就单独看那一步。")
    return True, f"购物 = {答案.购物}"


def CHECK_弹出的(答案):
    if not hasattr(答案, "弹出的"):
        return False, ("还没有定义「弹出的」。\n"
                       "      写法：弹出的 = 购物.pop()\n"
                       "      ⚠ pop() **既删掉又还给你** —— 这就是它和 remove 的区别。")
    if 答案.弹出的 != "香蕉":
        return False, (f"「弹出的」应当是 '香蕉'（最后那个），实际是 {答案.弹出的!r}。\n"
                       f"      ⚠ pop() 不带参数时弹**最后一个**；\n"
                       f"        pop(0) 才是弹第一个。")
    return True, "弹出的 = '香蕉'（pop 不写参数 = 最后一个）"


def CHECK_用了三个方法(答案):
    """⚠ 这一课要练的是三个具体方法，不是「结果碰巧对了」。"""
    import io
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    缺 = [m for m in ("append", "insert", "remove", "pop") if m not in 源码]
    if 缺:
        return False, (f"这几样没用到：{'、'.join(缺)}\n"
                       f"      这一课就是要练这四个动作：\n"
                       f"        append(x)      加到末尾\n"
                       f"        insert(i, x)   插到下标 i 的位置\n"
                       f"        remove(x)      按**值**删\n"
                       f"        pop()          按下标弹出（不写参数 = 最后一个）")
    return True, "append / insert / remove / pop 都用上了"
