# ─────────────────────────────────────────────────────
#  先介绍：列表是「活的」
# ─────────────────────────────────────────────────────
#
# 第 05 课只讲了「取」。但列表真正的用处是**一边跑一边变**：
# 记分、排队、购物车 —— 都是往列表里加、从列表里减。
#
# ─────────────────────────────────────────────────────
#  四个动作
# ─────────────────────────────────────────────────────
#
#     购物 = [「苹果」]
#
#   ① 加一个到**末尾**
#        购物.append(「香蕉」)        ⇒  [「苹果」, 「香蕉」]
#
#   ② 插到**指定位置**
#        购物.insert(0, 「牛奶」)     ⇒  [「牛奶」, 「苹果」, 「香蕉」]
#                                     ↑ 插在下标 0 的位置，原来的往后挪
#
#   ③ 按**值**删掉一个
#        购物.remove(「苹果」)        ⇒  [「牛奶」, 「香蕉」]
#                                     ⚠ 值不存在会 KeyError 之外 —— 是 ValueError
#
#   ④ 按下标**弹出**（删掉并拿到它）
#        得 = 购物.pop()            ⇒  得 = 「香蕉」，购物变成 [「牛奶」]
#        得 = 购物.pop(0)           ⇒  得 = 「牛奶」，购物变成 []
#
#   ⚠ 还有一个直接改：
#        购物[0] = 「果汁」            ⇒  把第 0 个换掉
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课唯一要记住的坑：边遍历边删会漏元素
# ─────────────────────────────────────────────────────
#
#     for x in 分数表:
#         if x < 60:
#             分数表.remove(x)        # ← ❌ 错！
#
#   为什么错：删掉一个之后，**后面的元素整体往前挪一格**，
#   而 `for` 的下标已经走过去了 —— 于是紧挨着被删元素的那一项
#   **永远检查不到**。
#
#   看个例子（[50, 30, 90] 想删掉不及格的）：
#
#     第 1 轮：下标 0，值是 50 ⇒ 删掉。列表变成 [30, 90]
#     第 2 轮：下标 1，值是 90 ⇒ 30 被跳过了！**没删掉**
#
#   ⇒ 结果 [30, 90] —— 30 还在，而程序**不报错**。
#
#   正确做法有两种：
#
#     ① 造一个新列表（推荐，最不容易错）
#          出 = []
#          for x in 分数表:
#              if x >= 60:
#                  出.append(x)
#          return 出
#
#     ② 从后往前删（倒着遍历就不会被"前移"影响）
#          for i in range(len(分数表) - 1, -1, -1):
#              if 分数表[i] < 60:
#                  分数表.pop(i)
#
#   ⚠ 第 ① 种还有个好处：**不改调用者的列表**。
#     调用者手里的数据莫名其妙变少，是很讨厌的一件事。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   循环（for）是第 08 课。这一课先用**最简单的** for 来演示那个坑，
#   你只要记住「别边遍历边删」就行，不用现在就精通循环。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 定义列表 购物 = [「苹果」]
#   2. 用 append 加一个 「香蕉」
#   3. 用 insert 在下标 0 插入 「牛奶」
#   4. 用 remove 删掉 「苹果」
#   5. 定义变量 弹出的，值是 购物.pop() 的结果
#
