# ─────────────────────────────────────────────────────
#  先介绍：字符串是「一串」，不是「一个」
# ─────────────────────────────────────────────────────
#
# 前面用过字符串，但只当它是一整块。其实它是**一串字符**，
# 所以能像列表那样按下标取、切片、遍历。这一课把它的家底过一遍。
#
#   字符串 = 一串字符，**按下标访问**，但**不可改**
#
# ⚠ 「不可改」是它和列表最大的区别 —— 凡是「改」它的方法，都是**返回新串**：
#
#     s = "hello"
#     s.upper()            ← 返回 "HELLO"，但 s 还是 "hello"
#     s = s.upper()        ← 要把返回值**接住**才算改
#
# ─────────────────────────────────────────────────────
#  一、取字符、切片（和列表一模一样）
# ─────────────────────────────────────────────────────
#
#     s = "abcdef"
#
#     s[0]        ⇒ 'a'        第 0 个（从 0 开始）
#     s[-1]       ⇒ 'f'        最后一个（负数是"从后往前"）
#     s[1:4]      ⇒ 'bcd'      从 1 到 4 **之前**（含 1 不含 4）
#     s[:3]       ⇒ 'abc'      从头到 3 之前
#     s[3:]       ⇒ 'def'      从 3 到末尾
#     s[::2]      ⇒ 'ace'      每隔一个取一个
#     s[::-1]     ⇒ 'fedcba'   **倒过来**（这个写法很常用，记住它）
#
# ⚠ 切片**越界不报错**（和下标不同）：
#
#     s[10]       ❌ IndexError: string index out of range
#     s[10:20]    ⇒ ''          ← 切片给个空串，不报错
#
# ─────────────────────────────────────────────────────
#  二、最常用的一批方法（都带括号）
# ─────────────────────────────────────────────────────
#
#     s = "  Hello, World  "
#
#     s.strip()                'Hello, World'    去掉**两头**空白
#     s.lstrip() / s.rstrip()  只去左边 / 只去右边
#     s.upper() / s.lower()    全大写 / 全小写
#     s.title()                '  Hello, World  ' → 每个词首字母大写
#
#     s.split(',')             ['  Hello', ' World  ']   按分隔符**切开**成列表
#     s.split()                ['Hello,', 'World']       不给参数＝按空白切（**自动去多余空格**）
#
#     '-'.join(['a', 'b', 'c'])   ⇒ 'a-b-c'      把列表**粘**成一个字符串
#
#     s.find('World')          7      第一次出现的下标；**找不到返回 -1**
#     s.count('l')             3      出现几次
#     s.replace('l', 'L')      '  HeLLo, WorLd  '    全部替换（返回**新串**）
#     s.startswith('  He')     True
#     s.endswith('  ')         True
#     s.isdigit()              False  全是数字吗
#
# ─────────────────────────────────────────────────────
#  三、split 和 join 是一对（这一课最实用的两个）
# ─────────────────────────────────────────────────────
#
#     "3,5,7".split(',')            ⇒ ['3', '5', '7']    字符串 → 列表
#     ','.join(['3', '5', '7'])     ⇒ '3,5,7'            列表 → 字符串
#
# ⚠ 典型用法：读进来一行数字，变成数字列表：
#
#     文字 = "3 5 7"
#     数字们 = [int(x) for x in 文字.split()]        ⇒ [3, 5, 7]
#
#   这一行在刷题时几乎每道都要写。第 19 课会细讲方括号里那个写法（列表解析）。
#
# ⚠ join 的调用顺序**和直觉相反**：分隔符在前，列表在后。
#
#     ','.join(列表)      ✅
#     列表.join(',')      ❌ AttributeError: 'list' object has no attribute 'join'
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：改了字符串却没接住返回值
# ─────────────────────────────────────────────────────
#
#     s = "  hello  "
#     s.strip()
#     print(s)              ⇒ "  hello  "     ← 空格还在！
#
# 你会看到：什么都不报，只是**改动没了**。这一类错不会崩，只会悄悄不对。
#
# 为什么：**字符串不可改**（immutable）。`.strip()` 不会改 s 本身，
#   它造一个**新字符串**交给你 —— 你不接住，它就被丢掉了。
#
#   ⚠ 对照列表（第 06 课）：`列表.append(x)` 会**当场改列表本身**，不用接。
#     两者行为不一样，别把直觉带过来。
#
# ⇒ 两条：
#
#     ① 要改，就接住：s = s.strip()
#     ② 或者一步到位：print(s.strip())
#
#   ⚠ 判断口诀：**这个方法返回的是一个新值，还是「就地改」？**
#     字符串的方法全是「返回新值」；列表的 append / sort 是「就地改」。
#
