def CHECK_原句和干净(答案):
    if not hasattr(答案, "原句"):
        return False, ("还没有定义「原句」。\n"
                       "      写法：原句 = '  你好，世界  '   ← 前后各有**两个空格**")
    if not hasattr(答案, "干净"):
        return False, ("还没有定义「干净」。\n"
                       "      写法：干净 = 原句.strip()\n"
                       "      ⚠ strip() 返回的是**新字符串** —— 要接住它。")
    if not isinstance(答案.原句, str):
        return False, f"「原句」应当是文字，现在是 {type(答案.原句).__name__}。"
    if 答案.原句 == 答案.干净:
        return False, ("「干净」和「原句」一样 —— strip() 的结果没接住。\n"
                       "      ⚠ 要写成 `干净 = 原句.strip()`，不是只写 `原句.strip()`。")
    if 答案.干净 != 答案.原句.strip():
        return False, (f"「干净」应当是去掉两头空格之后的原句，"
                       f"现在是 {答案.干净!r}。")
    return True, f"原句={答案.原句!r} → 干净={答案.干净!r}"


def CHECK_切开和粘回去(答案):
    if not hasattr(答案, "切开的"):
        return False, ("还没有定义「切开的」。\n"
                       "      写法：切开的 = '苹果,香蕉,橘子'.split(',')")
    if not hasattr(答案, "粘回去"):
        return False, ("还没有定义「粘回去」。\n"
                       "      写法：粘回去 = '-'.join(切开的)\n"
                       "      ⚠ join 是**分隔符在前、列表在后**。")
    v = 答案.切开的
    if not isinstance(v, list):
        return False, (f"「切开的」应当是列表，现在是 {type(v).__name__}。\n"
                       f"      ⚠ split() 返回列表。")
    if len(v) != 3:
        return False, (f"「切开的」应当有 3 个元素，现在有 {len(v)} 个：{v!r}\n"
                       f"      ⚠ 分隔符要用英文逗号 ','。")
    if 答案.粘回去 != "-".join(v):
        return False, (f"「粘回去」应当是用 '-' 粘起来的，现在是 {答案.粘回去!r}。")
    return True, f"切开的={v!r} 粘回去={答案.粘回去!r}"


def CHECK_数一数(答案):
    f = 答案.__dict__.get("数一数")
    if not callable(f):
        return False, ("还没有定义函数「数一数」。\n"
                       "      写法：def 数一数(文字, 要找的):\n"
                       "                return 文字.count(要找的)")
    for 文字, 要找的, 想 in (("banana", "a", 3), ("banana", "na", 2),
                            ("hello", "z", 0), ("", "a", 0)):
        try:
            得 = f(文字, 要找的)
        except Exception as e:                                  # noqa: BLE001
            return False, f"数一数({文字!r}, {要找的!r}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"数一数({文字!r}, {要找的!r}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 用 文字.count(要找的) 一行就够。")
    return True, "四组都对"


def CHECK_倒过来(答案):
    f = 答案.__dict__.get("倒过来")
    if not callable(f):
        return False, ("还没有定义函数「倒过来」。\n"
                       "      写法：def 倒过来(文字):\n"
                       "                return 文字[::-1]      ← 切片步长写 -1")
    for 文字, 想 in (("abc", "cba"), ("", ""), ("中", "中"), ("你好", "好你")):
        try:
            得 = f(文字)
        except Exception as e:                                  # noqa: BLE001
            return False, f"倒过来({文字!r}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"倒过来({文字!r}) 应当是 {想!r}，得到 {得!r}。\n"
                           f"      ⚠ 想一想 文字[::-1] 为什么能倒过来。")
    return True, "四组都对"


