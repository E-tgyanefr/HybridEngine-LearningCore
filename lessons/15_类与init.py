# ─────────────────────────────────────────────────────
#  先介绍：为什么需要「类」
# ─────────────────────────────────────────────────────
#
# 到现在你的数据和方法是**分开**的：
#
#     余额 = 0
#     def 存(n):
#         global 余额             ← 要声明 global，丑
#         余额 += n
#
# 问题是「余额」这个数据和「怎么改余额」这件事**离得很远**，
# 而且 `余额` 是个谁都能改的全局变量。
#
# 类把**数据**和**操作数据的方法**放进同一个地方：
#
#     class 存钱罐:
#         def __init__(self, 初值=0):
#             self.余额 = 初值
#
#         def 存(self, n):
#             self.余额 += n
#
#     罐 = 存钱罐(100)          ← 造一个
#     罐.存(50)                 ← 用它的方法
#     罐.余额                   ⇒ 150
#
# ─────────────────────────────────────────────────────
#  `__init__` 是什么
# ─────────────────────────────────────────────────────
#
# 它是「**造对象时自动跑一次**」的方法，用来把东西准备好：
#
#     class 计数器:
#         def __init__(self, 初值=0):
#             self.值 = 初值
#
#     计数器(5)         ⇒  造对象时自动调用 __init__，把 值 设成 5
#
#   ⚠ 名字是**前后各两个下划线**：`__init__`
#     写成 `_init_`（一个）或 `__int__`（少了 i）都不会报错，
#     但它就只是个普通方法，造对象时**不会被调用** ——
#     于是你会奇怪「为什么属性不存在」。
#
#   ⚠ `__init__` **不该写 return**（它负责准备，不负责交结果）。
#
# ─────────────────────────────────────────────────────
#  `self` 是什么
# ─────────────────────────────────────────────────────
#
#      def 存(self, n):
#          self.余额 += n
#          ↑
#          "我自己"
#
#   `self.余额` 是**这个对象自己的**余额。
#   如果写成 `余额`（没有 self.），那是一个**局部变量**，
#   跟对象毫无关系 —— 新手最常混这一点。
#
#   ⚠ 调用时**不用传 self**：
#        定义：def 存(self, n):
#        调用：罐.存(50)            ← Python 自己把「罐」塞进 self
#
# ─────────────────────────────────────────────────────
#  ⚠ 类名后面的括号别忘
# ─────────────────────────────────────────────────────
#
#     罐 = 存钱罐           ❌ 这只是给**类**起了个别名，没造对象
#     罐 = 存钱罐()         ✅ 这一对括号才是「造一个」
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   封装（把规则关进方法里、不让外面乱改）是第 16 课。
#   这一课只要「能造出一个带属性的对象」就够了。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   写一个类 学生：
#     · 造出来时接收 姓名
#     · 属性 `姓名` 存住它
#     · 方法 `问好()` 返回 f"我是{姓名}"
#
#   ⚠ 就这些。不用检查余额、不用管规则 —— 那是第 16 课。
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 15


def CHECK_学生类(答案):
    if not hasattr(答案, "学生"):
        return False, "还没有定义「学生」类。写法：class 学生: ..."
    类 = 答案.学生
    if not isinstance(类, type):
        return False, f"「学生」应当是**类**，现在是 {type(类).__name__}。"
    return True, "学生 是个类"


def CHECK_能造出对象带姓名(答案):
    if not hasattr(答案, "学生"):
        return False, "还没有定义「学生」类。"
    类 = 答案.学生
    try:
        a = 类("小明")
    except TypeError as e:
        return False, (f"`学生('小明')` 造不出来：{e}\n"
                       f"      ⚠ 检查 `__init__`：\n"
                       f"         · 名字是**前后各两个下划线**：__init__（写成 _init_ 就不算）\n"
                       f"         · 第一个参数是 self，第二个才是 姓名\n"
                       f"         · 要写 `self.姓名 = 姓名` —— 少了 self. 外面看不到")
    except Exception as e:                                      # noqa: BLE001
        return False, f"`学生('小明')` 出错了：{type(e).__name__}: {e}"
    if not hasattr(a, "姓名"):
        return False, ("造出来的对象上没有 `.姓名`。\n"
                       "      ⚠ 一定要写 `self.姓名 = 姓名`：\n"
                       "         只写 `姓名 = 姓名` 是给**局部变量**赋值，对象上没有这个属性。")
    if a.姓名 != "小明":
        return False, f"`.姓名` 应当是 '小明'，实际是 {a.姓名!r}。"
    # ⚠ 两个对象互不影响
    b = 类("小红")
    if b.姓名 != "小红" or a.姓名 != "小明":
        return False, (f"两个对象互相影响了：a.姓名={a.姓名!r}，b.姓名={b.姓名!r}。\n"
                       f"      ⚠ 属性要写在 `__init__` 里用 `self.` 赋值 ——\n"
                       f"        写在类里（不用 self）就成了**所有对象共用的类属性**。")
    return True, "两个学生各自记住自己的姓名"


def CHECK_问好(答案):
    if not hasattr(答案, "学生"):
        return False, "还没有定义「学生」类。"
    类 = 答案.学生
    try:
        a = 类("小明")
    except Exception as e:                                      # noqa: BLE001
        return False, f"造学生失败：{type(e).__name__}: {e}"
    if not hasattr(a, "问好"):
        return False, ("对象上没有 `问好()` 方法。\n"
                       "      写法（注意缩进，它在类里面）：\n"
                       "          def 问好(self):\n"
                       "              return f'我是{self.姓名}'")
    if not callable(a.问好):
        return False, "`问好` 不是方法。"
    try:
        得 = a.问好()
    except Exception as e:                                      # noqa: BLE001
        return False, (f"问好() 出错了：{type(e).__name__}: {e}\n"
                       f"      ⚠ 方法里要用 `self.姓名`，不能只写 `姓名`。")
    if 得 != "我是小明":
        return False, (f"问好() 应当是 '我是小明'，实际是 {得!r}。\n"
                       f"      ⚠ 用 `self.姓名` 取自己的姓名。\n"
                       f"        （如果报 NameError: name '姓名' is not defined，\n"
                       f"          就是漏了 `self.`。）")
    # 换个对象，应当返回另一个名字（证明真的用了 self）
    b = 类("小红")
    if b.问好() != "我是小红":
        return False, (f"换一个学生，问好() 返回的还是 {b.问好()!r} ——\n"
                       f"      说明里面把名字写死了，没有用 `self.姓名`。")
    return True, "两个学生的问好() 各自正确（真的用了 self）"
