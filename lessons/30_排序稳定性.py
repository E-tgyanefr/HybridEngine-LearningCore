# ─────────────────────────────────────────────────────
#  先介绍：分数一样时，谁在前面
# ─────────────────────────────────────────────────────
#
# 看这份名单（按交卷先后排好的）：
#
#     名单 = [('小明', 90), ('小红', 90), ('小刚', 80)]
#
# 现在要按分数从高到低排名次。小明和小红都是 90 分 —— 谁在前？
#
#     ✅ 稳定：[('小明', 90), ('小红', 90), ('小刚', 80)]   小明本来在前面，还在前面
#     ❌ 不稳：[('小红', 90), ('小明', 90), ('小刚', 80)]   两人被调了个个儿
#
# 两种结果**都算「按分数排好了」**，可老师看到第二种会以为程序出错了。
# 这个「值相等的元素，排完之后还保持原来的先后」的性质，就叫**稳定性**。
#
# ─────────────────────────────────────────────────────
#  一、稳定性有什么用（两个真实场景）
# ─────────────────────────────────────────────────────
#
#   ① 先按交卷时间排，再按分数排名次
#      同分的应当保持交卷顺序 —— 不然「同分不同命」，说不清道理。
#
#   ② 游戏排行榜：同分按「谁先打到这个分」排
#      先按时间排一遍，再按分数**稳定地**排一遍，同分自然就按时间了。
#
#   ⚠ 这就是稳定性的用法：**连续排两次，后一次不影响前一次排好的次序。**
#     要是排序不稳定，第二次就会把第一次的成果搅乱。
#
# ─────────────────────────────────────────────────────
#  二、哪些排序稳定（考试常考这一格）
# ─────────────────────────────────────────────────────
#
#     排序方式              稳定吗      为什么
#     ──────────────────  ────────  ──────────────────────────────
#     Python 的 sorted      ✅ 稳定    官方文档明确保证
#     list.sort()           ✅ 稳定    同上
#     冒泡排序              ✅ 稳定    只在**严格大于**时才交换
#     插入排序              ✅ 稳定    相等的牌不往前插
#     选择排序              ❌ 不稳定  长距离交换，会把同分的顺序翻乱
#
# ⚠ 三种手写排序里，只有**选择排序不稳定** —— 考试就爱问这一句。
#   原因：它把第 i 格和「最小那一格」直接对调，隔着老远一换，
#   原本排在后面的同分元素就可能被甩到前面。
#
# ─────────────────────────────────────────────────────
#  三、Python 的 sorted：key 和 reverse
# ─────────────────────────────────────────────────────
#
#     sorted([3, 1, 2])                          ⇒ [1, 2, 3]
#     sorted([3, 1, 2], reverse=True)            ⇒ [3, 2, 1]
#     sorted(['bbb', 'a', 'cc'], key=len)        ⇒ ['a', 'cc', 'bbb']   按长度
#
#     # 名单是 [(姓名, 分数), …]，按分数排：
#     sorted(名单, key=lambda 对: 对[1])                    ⇒ 分数从小到大
#     sorted(名单, key=lambda 对: 对[1], reverse=True)      ⇒ 分数从大到小
#
# ⚠ 三条必须记住：
#
#     ① `sorted(表)` 返回**新列表**，`表.sort()` **就地改**、返回 None
#     ② 两个都是**稳定**的 —— 这一点可以放心
#     ③ key= 后面写**函数名**，不带括号：`key=len` ✅、`key=len()` ❌
#
#   ⚠ `key=len` 是把 len 这个函数**本身**交给 sorted，
#     让它自己去对每个元素调用 —— 所以不用写括号。
#
# ─────────────────────────────────────────────────────
#  四、实务：同分同名次，名次还要「跳」
# ─────────────────────────────────────────────────────
#
#     分数 = [90, 90, 80, 70]
#     名次 = [ 1,  1,  3,  4]        ← 并列第 1，接着直接是第 3（没有第 2 名）
#
# 写法：**只有分数和前一个不同，才把名次更新成 i + 1**：
#
#     def 给名次(名单):                 # 名单已经按分数从高到低排好
#         结果 = []
#         for i, (姓名, 分数) in enumerate(名单):
#             if i > 0 and 分数 == 名单[i - 1][1]:
#                 名次 = 结果[-1][2]     ← 同分：沿用上一个名次
#             else:
#                 名次 = i + 1           ← 不同分：名次就是 i + 1
#             结果.append((姓名, 分数, 名次))
#         return 结果
#
# ⚠ 名次不能写成「同分就并列、下一个 +1」：那会变成 1, 1, 2, 3。
#   标准做法是**跳跃**的：1, 1, 3, 4（第 2 名空缺）。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：把 sort() 的返回值接住了
# ─────────────────────────────────────────────────────
#
#     排好的 = 名单.sort(key=lambda 对: 对[1])
#     print(排好的[0])
#
#     ⇒ TypeError: 'NoneType' object is not subscriptable
#
# ⚠ `.sort()` 是**就地**排，它返回的是 `None`（表示「我没有新东西给你」）。
#   名单其实已经排好了，可你接住的是个 None：
#
#     排好的[0]      ⇒ None[0]      ⇒ 就是上面那个报错
#
# ⇒ 两条：
#     ① 要返回值 ⇒ 用 `sorted(名单, key=…)`
#     ② 用 `.sort()` 就别接返回值：`名单.sort(key=…)`，然后直接用 `名单`
#
#   ⚠ 这个报错里一个字母都没提「排序」，第一次见很难联想过去 —— 记住它。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   多级排序（key 返回元组）、快排 / 归并的稳定性、排序内部怎么实现 —— 用到再说。
#   这一课只讲：稳定性是什么、谁稳定，以及 sorted 的 key= 和 reverse=。
