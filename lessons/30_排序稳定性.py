import io


def _稳定降序(名单):
    """标准答案：Python 的 sorted 是稳定的，reverse=True 不会翻乱同分的顺序。"""
    return sorted(名单, key=lambda 对: 对[1], reverse=True)


def CHECK_成绩排名(答案):
    f = 答案.__dict__.get("成绩排名")
    if not callable(f):
        return False, ("还没有定义函数「成绩排名」。\n"
                       "      写法：def 成绩排名(名单):\n"
                       "                return sorted(名单, key=lambda 对: 对[1], reverse=True)")
    for 名单 in ([('小明', 90), ('小红', 90), ('小刚', 80)],
                [], [('单人', 5)],
                [('甲', 0), ('乙', 0), ('丙', 0)],
                [('x', -1), ('y', 3), ('z', -1)],
                [('a', 7), ('b', 9), ('c', 7), ('d', 9)]):
        原样 = list(名单)
        想 = _稳定降序(原样)
        try:
            得 = f(list(名单))
        except Exception as e:                              # noqa: BLE001
            return False, f"成绩排名({原样!r}) 出错了：{type(e).__name__}: {e}"
        if not isinstance(得, list):
            return False, (f"成绩排名({原样!r}) 应当返回列表，"
                           f"得到 {type(得).__name__}：{得!r}。")
        if 得 != 想:
            # ⚠ 先分清是哪一类错：**分数顺序**错了，还是分数对、只是同分被翻乱。
            #   第一版我用 `sorted(得) == sorted(想)` 去猜，结果「忘了 reverse」
            #   也被说成「同分被打乱」—— 提示指错了地方，学员按它改只会更糊涂。
            #   ⇒ 判据要盯住**分数这一列**，那是真正该有序的东西。
            该分数 = [对[1] for 对 in 想]
            try:
                得分数 = [对[1] for 对 in 得]
            except Exception:                               # noqa: BLE001
                得分数 = None
            if 得分数 == 该分数:
                return False, (f"成绩排名({原样!r}) 分数排对了，但**同分的顺序被打乱**：\n"
                               f"        得到 {得!r}\n"
                               f"        应当 {想!r}\n"
                               f"      ⚠ 这就是「不稳定」。用 Python 的 sorted 加 reverse=True "
                               f"就是稳定的：\n"
                               f"          sorted(名单, key=lambda 对: 对[1], reverse=True)\n"
                               f"        （自己写两层循环也行，但比较时只能用 > ，不能用 >=）")
            return False, (f"成绩排名({原样!r})\n"
                           f"        得到 {得!r}\n"
                           f"        应当 {想!r}\n"
                           f"      ⚠ 分数高的要在前面：key 取 对[1]，再加 reverse=True。\n"
                           f"        （只写 key 是从低到高 —— 分数列现在是 {得分数!r}）")
        if 名单 != 原样:
            return False, (f"成绩排名 把**传进来的名单**改成了 {名单!r}。\n"
                           f"      ⚠ 要返回新列表 ⇒ 用 sorted(…)，不要用 名单.sort(…)。")
    return True, "六组都对（含空名单、单人、全同分、负数分），同分的先后没被打乱"


def CHECK_按长度排(答案):
    f = 答案.__dict__.get("按长度排")
    if not callable(f):
        return False, ("还没有定义函数「按长度排」。\n"
                       "      写法：def 按长度排(文字们):\n"
                       "                return sorted(文字们, key=len)")
    for 文字们 in ([], ['a'], ['bb', 'a', 'cc', 'd'], ['', 'a'],
                  ['aaa', 'b', 'cc'], ['同一个', '长度', '的', '词']):
        原样 = list(文字们)
        想 = sorted(原样, key=len)
        try:
            得 = f(list(文字们))
        except Exception as e:                              # noqa: BLE001
            return False, f"按长度排({原样!r}) 出错了：{type(e).__name__}: {e}"
        if 得 != 想:
            # 同上：先看**长度这一列**对不对，再谈同长度有没有被翻乱
            该长度 = [len(文字) for 文字 in 想]
            try:
                得长度 = [len(文字) for 文字 in 得]
            except Exception:                               # noqa: BLE001
                得长度 = None
            if 得长度 == 该长度:
                return False, (f"按长度排({原样!r}) 长度排对了，但**同长度的顺序被打乱**：\n"
                               f"        得到 {得!r}\n"
                               f"        应当 {想!r}\n"
                               f"      ⚠ 同长度要保持原来的先后 ⇒ 用稳定的 sorted(文字们, key=len)。")
            return False, (f"按长度排({原样!r}) 应当是 {想!r}，得到 {得!r}。\n"
                           f"      ⚠ 一行就够：return sorted(文字们, key=len)\n"
                           f"        （key= 后面写 len，**不要加括号**；长度列现在是 {得长度!r}）")
    return True, "六组都对（含空列表、单元素、空字符串、多个同长度的词）"


def CHECK_给名次(答案):
    f = 答案.__dict__.get("给名次")
    if not callable(f):
        return False, ("还没有定义函数「给名次」。\n"
                       "      写法：同分就沿用上一个名次，不同分才把名次写成 i + 1。")
    for 名单, 想 in (([('a', 90), ('b', 90), ('c', 80), ('d', 70)],
                     [('a', 90, 1), ('b', 90, 1), ('c', 80, 3), ('d', 70, 4)]),
                    ([], []),
                    ([('x', 5)], [('x', 5, 1)]),
                    ([('p', 0), ('q', 0), ('r', 0)], [('p', 0, 1), ('q', 0, 1), ('r', 0, 1)]),
                    ([('m', -1), ('n', -5)], [('m', -1, 1), ('n', -5, 2)]),
                    ([('甲', 9), ('乙', 9), ('丙', 9), ('丁', 3)],
                     [('甲', 9, 1), ('乙', 9, 1), ('丙', 9, 1), ('丁', 3, 4)])):
        try:
            得 = f([tuple(项) for 项 in 名单])
        except Exception as e:                              # noqa: BLE001
            return False, f"给名次({名单!r}) 出错了：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"给名次({名单!r})\n"
                           f"        得到 {得!r}\n"
                           f"        应当 {想!r}\n"
                           f"      ⚠ 同分同名次，而且名次**跳跃**：\n"
                           f"          if i > 0 and 分数 == 名单[i - 1][1]:\n"
                           f"              名次 = 结果[-1][2]      ← 沿用上一个\n"
                           f"          else:\n"
                           f"              名次 = i + 1            ← 不是 上一个名次 + 1")
    return True, "六组都对（空名单 / 单人 / 全同分 / 负数分 / 三个并列第 1）"


def CHECK_用了key(答案):
    """⚠ 这一课要练的是 sorted 的 key= 和它的稳定性 —— 必须真的用上。"""
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件，没法确认用没用 key=。"
    try:
        源码 = io.open(答案.__file__, encoding="utf-8").read()
    except OSError as e:
        return False, f"读不了你的答题文件：{e}"
    i = 源码.find("def 成绩排名")
    if i < 0:
        return False, "源码里找不到「def 成绩排名」。"
    j = 源码.find("\ndef ", i + 1)
    段 = 源码[i:j if j > 0 else i + 500]
    if "key=" not in 段:
        方案 = ("      ⚠ 「成绩排名」里没有 key= 。这一课要的就是它：\n"
                "          return sorted(名单, key=lambda 对: 对[1], reverse=True)\n"
                "        用 key= 指定「按哪个东西排」，元素本身可以很复杂（这里是 "
                "一个 (姓名, 分数) 的元组）。")
        if ".sort(" in 段 and "sorted(" in 段:
            方案 += ("\n      ⚠ 另外：`sorted(` 和 `.sort(` 你两个都写了？"
                     "排序只用其中一个，别让两个排同一份数据。")
        return False, 方案
    return True, "用上了 sorted 的 key=（按分数取 对[1]）"
