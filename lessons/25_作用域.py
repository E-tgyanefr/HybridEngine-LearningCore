# ─────────────────────────────────────────────────────
#  先介绍：函数里的变量，出门就没了
# ─────────────────────────────────────────────────────
#
# 函数你已经会写了。但有个问题一直没问过：**函数里定义的名字，外面能不能看见？**
# 答案是看不见 —— 每次调用函数，Python 都发给它一套**自己的抽屉**，
# 函数一返回，那套抽屉就扔了。这套「谁能看见谁」的规矩，就叫**作用域**。
#
# 这一课只讲清三件事：函数里读得到外面吗（读得到）、
# 外面读得到函数里吗（读不到）、想在函数里**改**外面的变量怎么办（写 global）。
#
# ─────────────────────────────────────────────────────
#  一、函数里的名字是「临时工」：外面看不见
# ─────────────────────────────────────────────────────
#
#     def 数一数():
#         局部 = 3          ← 这个名字只活在函数里面
#         return 局部
#
#     数一数()      ⇒ 3
#     局部          ❌ NameError: name '局部' is not defined
#
# 函数一返回，`局部` 就跟着没了 —— 这叫**局部变量**。
# 为什么这么设计：函数是「一段能反复用的代码」，
# 要是它里面的临时名字都留到外面，十个函数就会互相撞名字。
#
# ⚠ 变量定义在哪个函数里，就只归那个函数 —— 换个函数、或者写到外面，都看不见它。
#
# ─────────────────────────────────────────────────────
#  二、写在最外层的叫全局，函数里**读得到**
# ─────────────────────────────────────────────────────
#
#     称呼 = '小明'          ← 不缩进、写在整个文件最外层 = **全局变量**
#
#     def 打招呼():
#         return '你好，' + 称呼        ← 函数里**读**全局，没问题
#
#     打招呼()      ⇒ '你好，小明'
#
# 函数里找不到的名字，Python 会往外层找 —— 读全局是允许的，而且很常用。
# 注意区分：**读**（直接用）和**改**（赋值）是两回事，下面就是那个坎。
#
# ─────────────────────────────────────────────────────
#  三、想**改**全局，必须写 global
# ─────────────────────────────────────────────────────
#
#     次数 = 0
#
#     def 加一():
#         次数 = 次数 + 1        ❌ 报错
#
# 报错原文（真跑过）：
#
#     UnboundLocalError: cannot access local variable '次数' where it is not associated with a value
#
# 为什么：**只要函数里给某个名字赋过值，Python 就认定它是这个函数的局部变量** ——
# 而且是整个函数从头到尾都算。于是 `次数 = 次数 + 1` 里右边那个 `次数`
# 也成了「还没赋值的局部变量」，赋值之前就拿来用 ⇒ 报错。
#
# 正确写法：先用 global 声明一句。
#
#     def 加一():
#         global 次数          ← 告诉 Python：下面那些 次数 说的是外面那个
#         次数 = 次数 + 1
#         return 次数
#
#     加一()        ⇒ 1
#     加一()        ⇒ 2
#     次数          ⇒ 2          ← **外面那个真的被改了**
#
# ⚠ global 只能写在函数里面，而且要写在**第一次用到这个名字之前**。
#
# ─────────────────────────────────────────────────────
#  四、global 不是越多越好：能用 return 就别用 global
# ─────────────────────────────────────────────────────
#
#     想让 双倍(5) 算出 10   ⇒   让它 return 10，不要顺手去改全局
#
# 理由很实在：
#   · 读函数的人看不出它偷偷改了外面的什么
#   · 两处都改同一个全局，就会互相干扰
#   · 全局变量一多，「这个值到底是谁改的」就成了悬案
#
# ⚠ 口诀：**只要一个结果就 return；要长期记住（计数器、开关）才 global。**
#
# ─────────────────────────────────────────────────────
#  五、LEGB：Python 找名字的顺序（入门）
# ─────────────────────────────────────────────────────
#
# 一个名字，Python 按四层从里往外找，找到就停：
#
#     L  Local       本函数自己的
#     E  Enclosing   套着自己的那个函数（函数里再定义函数）
#     G  Global      文件最外层的
#     B  Built-in    Python 自带的（print、len、sum…）
#
#     def 外层():
#         甲 = '外层的'
#         def 内层():
#             return 甲          ← 自己层没有 ⇒ 往 E 层找 ⇒ 找到
#         return 内层()
#
#     外层()      ⇒ '外层的'
#
# ⚠ 四层都没有 ⇒ `NameError: name '甲' is not defined`。
#   （内层想**改**外层的局部变量要用 nonlocal —— 用得少，这一课不展开。）
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：想在函数里改全局，忘了写 global
# ─────────────────────────────────────────────────────
#
#     次数 = 0
#
#     def 加一():
#         次数 += 1
#
#     加一()
#     ⇒ UnboundLocalError: cannot access local variable '次数' where it is not associated with a value
#
# ⚠ 这个报错看起来像「次数 没定义」，可它明明就在上面第一行写着。
#   真因是：**函数里出现了对 次数 的赋值 ⇒ Python 把 次数 当成了局部变量**，
#   于是函数体里那个 `次数 += 1` 读的是一个还没诞生的局部变量。
#
# ⇒ 两条记牢：
#     ① 只想**读** ⇒ 直接读，什么都不用写
#     ② 想要**改** ⇒ 函数第一行写 `global 次数`
#
#   ⚠ `次数 = 次数 + 1` 和 `次数 += 1` 都会报同一个错 —— 这两种写法是一回事。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   nonlocal、闭包、装饰器、类里面的作用域 —— 用到再说。
#   这一课只讲：函数里外谁能看见谁，以及 global 怎么写。
#
