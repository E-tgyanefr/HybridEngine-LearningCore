def CHECK_次数和现在几次(答案):
    if not hasattr(答案, "次数"):
        return False, ("还没有定义全局变量「次数」。\n"
                       "      写法（写在最外层，不要缩进）：\n"
                       "          次数 = 0")
    if isinstance(答案.次数, bool) or not isinstance(答案.次数, int):
        return False, (f"「次数」应当是整数，现在是 {type(答案.次数).__name__}："
                       f"{答案.次数!r}。\n"
                       f"      ⚠ 计数用的变量从 0 开始：次数 = 0")
    f = 答案.__dict__.get("现在几次")
    if not callable(f):
        return False, ("还没有定义函数「现在几次」。\n"
                       "      写法：def 现在几次():\n"
                       "                return 次数      ← 只读，**不要**写 global")
    try:
        得 = f()
    except Exception as e:                                  # noqa: BLE001
        return False, f"现在几次() 出错了：{type(e).__name__}: {e}"
    if 得 != 答案.次数:
        return False, (f"现在几次() 应当返回全局的 次数（现在是 {答案.次数!r}），"
                       f"得到 {得!r}。\n"
                       f"      ⚠ 函数里直接 `return 次数` 就行 —— 读全局不需要 global。")
    return True, f"次数 = {答案.次数}，现在几次() 读到的也是 {得}"


def CHECK_加一(答案):
    f = 答案.__dict__.get("加一")
    if not callable(f):
        return False, ("还没有定义函数「加一」。\n"
                       "      写法：def 加一():\n"
                       "                global 次数\n"
                       "                次数 = 次数 + 1\n"
                       "                return 次数")
    if not isinstance(hasattr(答案, "次数") and 答案.次数, int):
        return False, "先定义全局变量 次数 = 0，再写 加一()。"
    前 = 答案.次数
    for 第几次 in (1, 2, 3):
        try:
            得 = f()
        except Exception as e:                              # noqa: BLE001
            return False, (f"第 {第几次} 次调用 加一() 出错了："
                           f"{type(e).__name__}: {e}\n"
                           f"      ⚠ 想在函数里改全局，函数第一行要写 `global 次数`。")
        if 得 != 前 + 1:
            return False, (f"第 {第几次} 次调用 加一() 应当返回 {前 + 1}，得到 {得!r}。\n"
                           f"      ⚠ 返回的应当是**加完之后**的 次数。")
        if 答案.次数 != 前 + 1:
            return False, (f"调用了 加一()，但全局的 次数 还是 {答案.次数}，"
                           f"应当是 {前 + 1}。\n"
                           f"      ⚠ 只 `return 次数 + 1` 不够 —— 要真的把外面那个改掉：\n"
                           f"          global 次数\n"
                           f"          次数 = 次数 + 1")
        前 += 1
    return True, f"连着调三次，次数 从 {前 - 3} 一路涨到 {前}"


def CHECK_加几个(答案):
    f = 答案.__dict__.get("加几个")
    if not callable(f):
        return False, ("还没有定义函数「加几个」。\n"
                       "      写法：def 加几个(n):\n"
                       "                global 次数\n"
                       "                次数 += n\n"
                       "                return 次数")
    if not isinstance(hasattr(答案, "次数") and 答案.次数, int):
        return False, "先定义全局变量 次数 = 0，再写 加几个()。"
    for n in (0, 1, 5, -3):
        前 = 答案.次数
        try:
            得 = f(n)
        except Exception as e:                              # noqa: BLE001
            return False, f"加几个({n}) 出错了：{type(e).__name__}: {e}"
        if 得 != 前 + n or 答案.次数 != 前 + n:
            return False, (f"加几个({n}) 应当让 次数 从 {前} 变成 {前 + n}，"
                           f"实际返回 {得!r}、次数 变成 {答案.次数!r}。\n"
                           f"      ⚠ 用 `次数 += n` 一句就够。\n"
                           f"        写成 `for _ in range(n)` 的话：n 是 0 或负数时一次都不循环，\n"
                           f"        次数 就加不上 —— 而题目说了 n 可能是 0 或负数。")
    return True, "四组都对（含 n=0 和 n=-3）"


def CHECK_双倍不许碰全局(答案):
    f = 答案.__dict__.get("双倍")
    if not callable(f):
        return False, ("还没有定义函数「双倍」。\n"
                       "      写法：def 双倍(n):\n"
                       "                结果 = n * 2      ← 局部变量\n"
                       "                return 结果")
    if not isinstance(hasattr(答案, "次数") and 答案.次数, int):
        return False, "先定义全局变量 次数 = 0，再写 双倍()。"
    前 = 答案.次数
    for n in (0, 1, -4, 7):
        try:
            得 = f(n)
        except Exception as e:                              # noqa: BLE001
            return False, f"双倍({n}) 出错了：{type(e).__name__}: {e}"
        if 得 != n * 2:
            return False, (f"双倍({n}) 应当是 {n * 2}，得到 {得!r}。\n"
                           f"      ⚠ 两倍就是 n * 2，别忘了 return。")
        if 答案.次数 != 前:
            return False, (f"调了一次 双倍({n})，全局的 次数 却从 {前} "
                           f"变成了 {答案.次数}。\n"
                           f"      ⚠ 这一课的要求是「不碰全局」—— 双倍 只管算，"
                           f"要改 次数 的是 加一 / 加几个。")
    return True, "四组都对（0 / 1 / 负数 / 正数），而且没有动全局的 次数"
