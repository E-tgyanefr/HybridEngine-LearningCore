# 第 39 课：二分答案 —— 不找元素，找「最大的那个能满足的值」
# ─────────────────────────────────────────────────────
#  这一课你会学到
# ─────────────────────────────────────────────────────
#    把「求最大 / 最小满足条件的值」变成二分：猜数字、切绳子、分巧克力
#
#  需要先会
#    第 38 课：二分查找
#
# ─────────────────────────────────────────────────────
#  怎么读这一课
# ─────────────────────────────────────────────────────
#
#   先从头读一遍讲解，再照着最后的「轮到你了」写。
#   卡住了看答案（先自己写一遍）—— 命令在「怎么自己测」那一节。
#
# ─────────────────────────────────────────────────────
#  先介绍：答案本身可以二分
# ─────────────────────────────────────────────────────
# 第 38 课是在**有序表**里找元素。这一课换个玩法：**答案在一段区间里，去二分答案**。
# 猜 1~100 的数最多 7 次（log2 100 ≈ 6.64），猜 1~1000000000 的数最多 **30 次**。
# 前提是每猜一次能知道「猜大了还是猜小了」 —— 这就是下面说的**单调性**。
#
# ─────────────────────────────────────────────────────
#  一、模板：把「能不能」当判据
# ─────────────────────────────────────────────────────
#     def 二分答案(下界, 上界, 可以吗):
#         答案 = None
#         while 下界 <= 上界:
#             中 = (下界 + 上界) // 2
#             if 可以吗(中):            ← 「中」这个值做得到吗
#                 答案 = 中            ← 做得到就记下来，再往大试
#                 下界 = 中 + 1
#             else:
#                 上界 = 中 - 1        ← 做不到就往小试
#         return 答案
#
# 拿「x² ≤ 100 的最大整数 x」试一遍：1…100 里二分最后停在 **10**（11² = 121 不行）。
# 区间换成 1…1000000000 时：二分 **30 次**，一个个试 **10 亿次**。
#
# ─────────────────────────────────────────────────────
#  二、判据必须是单调的
# ─────────────────────────────────────────────────────
# `可以吗(x)` 必须长这样：**一旦某个 x 能行，比它小的（或大的）全都行。**
#     切绳子：长度 200 能剪出 11 段 ⇒ 199、198 也一定能                    ✅ 单调
#     反例：「能不能正好剪出 3 段」就不是单调的 —— 有的长度行，更长的反而不行。
# 判据不单调时二分**照样跑完、照样返回一个数**，只是那个数没有意义。
#
# ─────────────────────────────────────────────────────
#  三、两个例子
# ─────────────────────────────────────────────────────
# **切绳子**：4 根绳子 802、743、457、539，要剪出 11 段等长的（整数米），最长能多长？
#     猜 200：802//200 + 743//200 + 457//200 + 539//200 = 4+3+2+2 = 11 段   ✅ 行
#     猜 201：3+3+2+2 = 10 段                                               ❌ 不行  ⇒ 200
# **分巧克力**：边长 5 和 6 的两块给 10 个人，每人一块正方形，边长最大多少？
#     边长 2：(5//2)² + (6//2)² = 4 + 9 = 13 块    ✅ 够
#     边长 3：1² + 2² = 5 块                       ❌ 不够   ⇒ 2
# 两题写法一模一样：把「够不够」写成一个函数，然后二分它。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：`中` 取整方向错了就死循环
# ─────────────────────────────────────────────────────
#     while 左 <= 右:
#         中 = (左 + 右) // 2
#         if 可以吗(中):
#             左 = 中            ← ⚠ 错！
#
# 为什么死循环：只剩两个数时（左=2，右=3），`中 = (2+3)//2 = 2` **永远等于 左**，
#   若 `可以吗(2)` 为真，左 又被赋成 2 —— 区间一点没变，程序卡死。两条都对：
#     ① 老老实实 `左 = 中 + 1` / `右 = 中 - 1`（上面的模板）
#     ② 非要写 `左 = 中`，就得把取整改成上取整 `中 = (左 + 右 + 1) // 2`
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课只讲「二分答案」这个套路；排序、图论都不碰。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 写函数 二分答案(下界, 上界, 可以吗)：返回**最大**的 x（下界 ≤ x ≤ 上界）使
#    可以吗(x) 为 True；连下界都不满足就返回 None
# 2. 写函数 切绳子(绳长表, 要的段数)：每根绳子各剪各的，求能满足段数的**最大整数长度**；
#    做不到返回 0
# 3. 写函数 分巧克力(边长表, 人数)：每块边长 s 能切出 (s // 边长)² 块，求能满足人数的
#    **最大整数边长**；做不到返回 0
