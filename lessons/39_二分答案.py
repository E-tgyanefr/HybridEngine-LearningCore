def _限次(谓词, 上限=200):
    """把谓词包起来数调用次数；超过上限就抛错（防止线性扫描把检查卡死）。"""
    次数 = [0]

    def 问(x):
        次数[0] += 1
        if 次数[0] > 上限:
            raise RuntimeError(f'谓词被调用了超过 {上限} 次 —— 这不像二分')
        return 谓词(x)
    return 问, 次数


def CHECK_二分答案(答案):
    f = 答案.__dict__.get('二分答案')
    if not callable(f):
        return False, ('还没有定义「二分答案」。写法：答案 = None；while 下界 <= 上界: '
                       '中 = (下界 + 上界) // 2；\n'
                       '      可以吗(中) 为真就 答案 = 中; 下界 = 中 + 1，否则 上界 = 中 - 1。')
    for 下, 上, 谓词, 想 in ((1, 100, lambda x: x * x <= 100, 10),
                            (1, 50, lambda x: x <= 0, None),
                            (1, 50, lambda x: x >= 0, 50),
                            (7, 7, lambda x: x <= 7, 7),
                            (7, 7, lambda x: x < 7, None),
                            (1, 10 ** 9, lambda x: x <= 12345, 12345)):
        问, 次数 = _限次(谓词)
        try:
            得 = f(下, 上, 问)
        except Exception as e:                                  # noqa: BLE001
            return False, (f'二分答案({下}, {上}, 谓词) 出错：{type(e).__name__}: {e}\n'
                           f'      ⚠ 一条一条往上试就会撞上"调用太多次"—— 那说明不是二分。')
        if 得 != 想:
            return False, (f'二分答案({下}, {上}, 谓词) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 全都不满足时返回 None；全都满足时返回**上界**。')
        if 次数[0] > 200:
            return False, f'二分答案({下}, {上}, 谓词) 问了 {次数[0]} 次 —— 太多了，不是二分。'
    return True, '六组都对（含全都满足 / 全都不满足 / 下界==上界 / 1 到 10 亿只问 30 次）'


def CHECK_切绳子(答案):
    import time
    f = 答案.__dict__.get('切绳子')
    if not callable(f):
        return False, ('还没有定义「切绳子」。思路：写一个 可以吗(m) = 各根绳子 '
                       'sum(绳 // m) >= 要的段数，\n'
                       '      然后二分 m（1 到 max(绳长表)）；表空或要 0 段返回 0。')
    for 绳, 段, 想 in (([1], 1, 1), ([10], 3, 3), ([10], 4, 2), ([1, 1], 3, 0),
                      ([], 5, 0), ([802, 743, 457, 539], 11, 200), ([5, 5, 5], 1, 5)):
        try:
            得 = f(list(绳), 段)
        except Exception as e:                                  # noqa: BLE001
            return False, f'切绳子({绳}, {段}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'切绳子({绳}, {段}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 802/743/457/539 要 11 段时答案是 200'
                           f'（200 段数 4+3+2+2=11；201 只有 3+3+2+2=10）。')
    t0 = time.perf_counter()
    try:
        大 = f([10 ** 8], 1)
    except Exception as e:                                      # noqa: BLE001
        return False, f'切绳子([100000000], 1) 出错：{type(e).__name__}: {e}'
    秒 = time.perf_counter() - t0
    if 大 != 10 ** 8:
        return False, f'切绳子([100000000], 1) 应当是 100000000，得到 {大!r}。'
    if 秒 > 3.0:
        return False, (f'切绳子([100000000], 1) 答案对，但用了 **{秒:.1f} 秒** —— 太慢了。\n'
                       f'      ⚠ 从 1 往上一个个试要试 1 亿次；二分只要 27 次。')
    return True, f'八组都对（含空表、只够一段、做不到），1 亿那组用了 {秒:.3f} 秒'


def CHECK_分巧克力(答案):
    f = 答案.__dict__.get('分巧克力')
    if not callable(f):
        return False, ('还没有定义「分巧克力」。思路：可以吗(m) = sum((s // m) ** 2 for s in 边长表) '
                       '>= 人数，\n'
                       '      然后二分 m（1 到 max(边长表)）；表空返回 0。')
    for 边, 人, 想 in (([5, 6], 10, 2), ([1, 1, 1], 10, 0), ([], 1, 0), ([3, 3], 4, 1),
                      ([1], 1, 1), ([10 ** 6], 1, 10 ** 6)):
        try:
            得 = f(list(边), 人)
        except Exception as e:                                  # noqa: BLE001
            return False, f'分巧克力({边}, {人}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'分巧克力({边}, {人}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 边长 5 和 6 给 10 个人时答案是 2：边长 2 得 4+9=13 块够，\n'
                           f'        边长 3 只有 1+4=5 块不够。块数是 (s // 边长)²，不是面积比。')
    return True, '六组都对（含空表、切不出、正好一人一块、边长一百万）'
