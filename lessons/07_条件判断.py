# ─────────────────────────────────────────────────────
#  先介绍：程序要会「分岔」
# ─────────────────────────────────────────────────────
#
# 到现在为止，你的程序都是一条直线：从第一行跑到最后一行。
# 但真实的事情几乎都需要判断：
#
#     分数 >= 60 才及格
#     余额够才让取钱
#     名字为空就提示「请输入名字」
#
# 判断用 `if`：
#
#     if 条件:
#         条件成立时做的事          ← ⚠ 这一行要**缩进**
#
# ─────────────────────────────────────────────────────
#  缩进是语法，不是美观
# ─────────────────────────────────────────────────────
#
#     if 年龄 >= 18:
#     print("成年")            ❌ IndentationError: expected an indented block
#
#     if 年龄 >= 18:
#         print("成年")        ✅ 缩进 4 个空格
#
#   ⚠ Python 靠**缩进**判断「哪些行属于这个 if」。
#     其他语言用花括号 {}，Python 用空格 —— 这是 Python 最鲜明的特点。
#     统一用 **4 个空格**（别用 Tab，也别混用）。
#
# ─────────────────────────────────────────────────────
#  三种形态
# ─────────────────────────────────────────────────────
#
#   ① 只有 if
#         if 分数 >= 60:
#             print("及格")
#
#   ② if + else（两条路必走一条）
#         if 分数 >= 60:
#             print("及格")
#         else:
#             print("不及格")
#
#   ③ if + elif + else（多条路）
#         if 分数 >= 90:
#             等级 = 「优秀」
#         elif 分数 >= 60:
#             等级 = 「及格」
#         else:
#             等级 = 「不及格」
#
# ─────────────────────────────────────────────────────
#  比较运算符
# ─────────────────────────────────────────────────────
#
#     ==   等于        ⚠ **两个等号**！一个等号是赋值
#     !=   不等于
#     >    大于        >=  大于或等于
#     <    小于        <=  小于或等于
#
#   ⚠⚠ 最常见的错：
#
#         if 分数 = 60:            ❌ SyntaxError
#         if 分数 == 60:           ✅
#
#     一个等号是「把 60 装进 分数」（赋值），两个才是「相等吗」。
#
# ─────────────────────────────────────────────────────
#  ⚠ 判断的顺序很重要
# ─────────────────────────────────────────────────────
#
#     if 分数 >= 60:
#         等级 = 「及格」
#     elif 分数 >= 90:            ← ❌ 到不了这里！
#         等级 = 「优秀」
#
#   95 分在第一行就已经满足 `>= 60` 了，程序不会再看后面的。
#   ⇒ **条件要从「最严格的」往「最宽松的」写**。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   循环在第 08 课。这一课只写「分岔」，不写循环。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   写一个函数 判等级(分数)：
#     · 90 分及以上  → 返回 "优秀"
#     · 60 分及以上  → 返回 "及格"
#     · 其他         → 返回 "不及格"
#
#   ⚠ 检查会试 95 / 90 / 60 / 59 四个分数，特别注意 **90 和 60** 这两个边界。
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 07


def CHECK_判等级函数(答案):
    if not hasattr(答案, "判等级"):
        return False, "还没有定义「判等级」函数。写法：def 判等级(分数): ..."
    if not callable(答案.判等级):
        return False, "「判等级」不是函数。"
    return True, "判等级 是个函数"


def CHECK_四个边界都对(答案):
    if not hasattr(答案, "判等级"):
        return False, "还没有定义「判等级」函数。"
    for 分, 期望 in ((95, "优秀"), (90, "优秀"), (60, "及格"), (59, "不及格")):
        try:
            得 = 答案.判等级(分)
        except Exception as e:                                  # noqa: BLE001
            return False, f"判等级({分}) 出错了：{type(e).__name__}: {e}"
        if 得 != 期望:
            提示 = ""
            if 分 in (90, 60):
                提示 = (f"\n      ⚠⚠ {分} 是**边界**：题目说「{分} 分及以上」⇒ 要用 `>= {分}`。\n"
                        f"         写成 `> {分}` 的话，正好 {分} 分会被判成下一档。")
            return False, (f"判等级({分}) 应当是 {期望!r}，实际是 {得!r}。{提示}")
    return True, "95→优秀 · 90→优秀 · 60→及格 · 59→不及格"


def CHECK_用了elif(答案):
    """⚠ 这一课要练 if/elif/else 的多路判断。"""
    import io
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    i = 源码.find("def 判等级")
    段 = 源码[i:i + 600] if i >= 0 else ""
    if "elif" not in 段:
        return False, ("「判等级」里没有用 `elif`。\n"
                       "      这一课练的就是多路判断：\n"
                       "          if 分数 >= 90:   return '优秀'\n"
                       "          elif 分数 >= 60: return '及格'\n"
                       "          else:            return '不及格'\n"
                       "      ⚠ 三个独立的 if 也能得到同样结果，但那样容易漏掉"
                       "「顺序」这件事 —— elif 会逼你想清楚顺序。")
    return True, "用了 if / elif / else"
