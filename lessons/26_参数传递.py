def CHECK_加进去(答案):
    f = 答案.__dict__.get("加进去")
    if not callable(f):
        return False, ("还没有定义函数「加进去」。\n"
                       "      写法：def 加进去(表, 东西):\n"
                       "                表.append(东西)")
    for 表, 东西 in (([], 1), ([1, 2], 3), ([0], 0), ([-1, -2], -3)):
        原长 = len(表)
        try:
            f(表, 东西)
        except Exception as e:                              # noqa: BLE001
            return False, f"加进去({表!r}, {东西!r}) 出错了：{type(e).__name__}: {e}"
        if len(表) != 原长 + 1:
            return False, (f"加进去({表!r}, {东西!r}) 之后，外面那个表有 "
                           f"{len(表)} 个元素，应当是 {原长 + 1} 个：{表!r}\n"
                           f"      ⚠ 要**就地改**它：表.append(东西)\n"
                           f"        写成 `表 = 表 + [东西]` 只是换了个新列表，外面看不见。")
        if 表[-1] != 东西:
            return False, (f"加进去之后，表的末尾应当是 {东西!r}，实际是 {表[-1]!r}。\n"
                           f"      ⚠ append 是加到**末尾**。")
    return True, "四组都对（空表 / 两个元素 / 0 / 负数），外面那个表真的变了"


def CHECK_清空(答案):
    f = 答案.__dict__.get("清空")
    if not callable(f):
        return False, ("还没有定义函数「清空」。\n"
                       "      写法：def 清空(表):\n"
                       "                表.clear()")
    for 表 in ([1, 2, 3], [], [0], [None, None]):
        原样 = list(表)
        try:
            f(表)
        except Exception as e:                              # noqa: BLE001
            return False, f"清空({原样!r}) 出错了：{type(e).__name__}: {e}"
        if 表 != []:
            return False, (f"清空({原样!r}) 之后，外面那个表还是 {表!r}，应当是 []。\n"
                           f"      ⚠ 表.clear() 是就地清空；\n"
                           f"        写成 `表 = []` 只是让函数里的名字换了目标，外面不变。")
    return True, "四组都对（含本来就是空的表），清空是就地生效的"


def CHECK_复制一份再加(答案):
    f = 答案.__dict__.get("复制一份再加")
    if not callable(f):
        return False, ("还没有定义函数「复制一份再加」。\n"
                       "      写法：def 复制一份再加(表, 东西):\n"
                       "                新的 = 表[:]        ← 先复制\n"
                       "                新的.append(东西)\n"
                       "                return 新的")
    for 表, 东西 in (([], 7), ([1, 2], 3), ([0], 0), ([-1], -2)):
        原样 = list(表)
        try:
            得 = f(表, 东西)
        except Exception as e:                              # noqa: BLE001
            return False, f"复制一份再加({原样!r}, {东西!r}) 出错了：{type(e).__name__}: {e}"
        if 表 != 原样:
            return False, (f"复制一份再加({原样!r}, {东西!r}) 把**传进来的表**改成了 "
                           f"{表!r} —— 这一课要的是「不许改它」。\n"
                           f"      ⚠ 先复制：新的 = 表[:]，改 新的，return 新的。")
        if 得 != 原样 + [东西]:
            return False, (f"复制一份再加({原样!r}, {东西!r}) 应当返回 "
                           f"{原样 + [东西]!r}，得到 {得!r}。\n"
                           f"      ⚠ 返回的应当是**新**列表，而且要以 return 交出去。")
    return True, "四组都对：外面没被动过，返回的是一份加了东西的新列表"


def CHECK_排好序不动原表(答案):
    f = 答案.__dict__.get("排好序")
    if not callable(f):
        return False, ("还没有定义函数「排好序」。\n"
                       "      写法：def 排好序(表):\n"
                       "                return sorted(表)     ← 注意是 sorted，不是 .sort()")
    for 表 in ([3, 1, 2], [], [5], [-1, -7, 0], [2, 2, 1]):
        原样 = list(表)
        try:
            得 = f(表)
        except Exception as e:                              # noqa: BLE001
            return False, f"排好序({原样!r}) 出错了：{type(e).__name__}: {e}"
        if 表 != 原样:
            return False, (f"排好序({原样!r}) 把传进来的表改成了 {表!r} —— "
                           f"它应当一点不动。\n"
                           f"      ⚠ `.sort()` 是**就地**改（原表会乱），"
                           f"`sorted()` 才返回新列表。")
        if 得 != sorted(原样):
            return False, (f"排好序({原样!r}) 应当返回 {sorted(原样)!r}，得到 {得!r}。\n"
                           f"      ⚠ 一行就够：return sorted(表)")
    return True, "五组都对（含空表、单元素、负数、重复），原表顺序一点没动"


def CHECK_塞进元组(答案):
    f = 答案.__dict__.get("塞进元组")
    if not callable(f):
        return False, ("还没有定义函数「塞进元组」。\n"
                       "      写法：def 塞进元组(元组, 东西):\n"
                       "                return 元组 + (东西,)     ← 逗号别丢")
    for 元组, 东西 in (((), 1), ((1, 2), 3), ((0,), 0), ((5,), -5)):
        try:
            得 = f(元组, 东西)
        except Exception as e:                              # noqa: BLE001
            return False, (f"塞进元组({元组!r}, {东西!r}) 出错了：{type(e).__name__}: {e}\n"
                           f"      ⚠ 元组不能 append（它改不了），要用 `元组 + (东西,)`。")
        if not isinstance(得, tuple):
            return False, (f"塞进元组({元组!r}, {东西!r}) 应当返回**元组**，"
                           f"得到 {type(得).__name__}：{得!r}。\n"
                           f"      ⚠ 一个元素的元组要写成 (东西,)，逗号不能省 —— "
                           f"(东西) 是括号，不是元组。")
        if 得 != 元组 + (东西,):
            return False, (f"塞进元组({元组!r}, {东西!r}) 应当是 {元组 + (东西,)!r}，"
                           f"得到 {得!r}。")
    return True, "四组都对（含空元组），返回的是新元组，原来那个没动"
