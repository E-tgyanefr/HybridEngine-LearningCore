# ─────────────────────────────────────────────────────
#  先介绍：一件让人踩坑的事
# ─────────────────────────────────────────────────────
#
# 先看这段，猜猜最后打印什么：
#
#     def 加进去(表):
#         表.append(99)
#
#     甲 = [1, 2]
#     加进去(甲)
#     print(甲)          ⇒ [1, 2, 99]     ← 外面真的被改了！
#
# 很多人会猜 [1, 2]（函数里的改动「应该」留在函数里）。
# 可换成数字，同样的写法外面却纹丝不动。这一课讲清为什么。
# （考试里叫「值传递 / 引用传递」，我们只记 Python 的真实行为，不背名词。）
#
# ─────────────────────────────────────────────────────
#  一、先记住一句话：变量是「名字贴在东西上」
# ─────────────────────────────────────────────────────
#
#    甲 = [1, 2]
#    乙 = 甲            ← **不是复制**！两个名字贴在同一个列表上
#
#    乙.append(3)
#    甲                 ⇒ [1, 2, 3]
#
# 想确认两个名字是不是同一个东西，用 `is`：
#
#    甲 is 乙           ⇒ True      （同一个列表）
#    甲 == [1, 2, 3]    ⇒ True      （内容一样 —— == 比内容，is 比身份）
#
# 想要「另一个一模一样的列表」，得**主动复制**：丙 = 甲[:]（甲 is 丙 ⇒ False）
#
# ─────────────────────────────────────────────────────
#  二、可变 / 不可变：一张表记牢
# ─────────────────────────────────────────────────────
#
#     能改（可变）        不能改（不可变）
#     ─────────────       ────────────────
#     列表  [1, 2]        数字  5 / 3.14
#     字典  {'a': 1}      字符串 'abc'
#     集合  {1, 2}        元组  (1, 2)
#     自己写的对象        布尔  True / False
#
# 怎么判断？问一句：**能不能原地改它，而不用造新的？**
#
#     表.append(3)      ⇒ 表 本身变长了      ✅ 能原地改
#     表 = 表 + [3]     ⇒ 造了一个**新**列表  ← 这不是「改」，是换
#
#     文字 = 'a' + 'b'  ⇒ 造了一个新字符串    ← 改不了，只能造新的
#
# ─────────────────────────────────────────────────────
#  三、传参数 = 把名字再贴一次（不复制）
# ─────────────────────────────────────────────────────
#
# 调用 `加进去(甲)` 的时候，函数里的 `表` 和外面的 `甲` **贴在同一个列表上**：
#
#     甲 ─┐
#         ├─→ [1, 2]        （只有一个列表，两个名字）
#     表 ─┘
#
# 所以函数里 append，外面看得见 —— 改的就是那个列表本身。
# 传**列表**、**字典**进去 ⇒ 函数里的改动，外面也变。
#
# ─────────────────────────────────────────────────────
#  四、数字 / 字符串 / 元组：函数里怎么改都影响不到外面
# ─────────────────────────────────────────────────────
#
#     def 加一(数):
#         数 = 数 + 1         ← 这不是「改数字」，是让 数 改贴一个新数字
#         return 数
#
#     n = 5
#     加一(n)      ⇒ 6
#     n            ⇒ 5        ← 外面没变
#
# 为什么：数字不可变。`数 + 1` 造出了一个**新**数字（6），函数里的 `数` 改去贴它；
# 外面的 `n` 还贴着老的 5。⇒ 传不可变对象进去，函数里「改」的只是它自己那个名字。
#
# ⚠ 元组和字符串更直接 —— 连「原地改」这条路都没有，Python 当场拒绝：
#
#     改((1, 2)) 里写 元组[0] = 99
#     ⇒ TypeError: 'tuple' object does not support item assignment
#
#     'abc'[0] = 'A'
#     ⇒ TypeError: 'str' object does not support item assignment
#
# ─────────────────────────────────────────────────────
#  五、两条能直接用的规则
# ─────────────────────────────────────────────────────
#
#  ① 想让函数**改掉外面**那个列表 ⇒ 就地对它动手，不用 return
#         def 清空(表):  表.clear()          ← 外面那个当场空了
#
#  ② 想让外面**不受影响** ⇒ 在函数里造一个新的（`return sorted(表)`），
#     或者传之前先复制一份（`新的 = 表[:]`，再把副本传进去）
#
#   ⚠ `.sort()` 是就地改（原表会乱），`sorted()` 是造新的（原表不动）。
#     这一对和 `.append()` / `表 + [x]` 是同一类区别，一起记。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：函数改了参数，外面那个也变了（而且不报错）
# ─────────────────────────────────────────────────────
#
#     def 清零(表):
#         表.clear()
#
#     我的 = [1, 2, 3]
#     清零(我的)
#     我的                ⇒ []        ← 谁也没告诉它，它就空了
#
# 一个报错都不给。对照组是「不可变的」：
#
#     改((1, 2)) 里写 元组[0] = 99
#     ⇒ TypeError: 'tuple' object does not support item assignment
#
# 看出来了吗：**不可变的会当场拒绝，可变的会悄悄改掉。**
# 悄悄改掉的那种才是真的坑 —— 程序不崩，结果不对。
#
# ⇒ 两条：
#     ① 你的函数**想**改外面那个列表 ⇒ 放心就地改，这是设计好的
#     ② 你**不想**改外面 ⇒ 传之前 `表[:]` 复制一份，或让函数 return 新的
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   深复制 / 浅复制（copy 模块）、自定义对象传参、函数默认参数是列表的坑
#   —— 用到再说。这一课只讲：传进去的东西，函数能不能改到外面。
#
# ─────────────────────────────────────────────────────
