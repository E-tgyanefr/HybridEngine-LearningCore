def CHECK_数字列表(答案):
    if not hasattr(答案, "数字"):
        return False, "还没有定义「数字」列表。写法：数字 = [3, 1, 4, 1, 5]"
    if not isinstance(答案.数字, list):
        return False, f"「数字」应当是列表，现在是 {type(答案.数字).__name__}。"
    if len(答案.数字) < 3:
        return False, f"「数字」里只有 {len(答案.数字)} 个元素，至少 3 个。"
    if not all(isinstance(x, int) and not isinstance(x, bool) for x in 答案.数字):
        return False, f"「数字」里应当都是整数，现在有：{答案.数字}"
    return True, f"数字 = {答案.数字}"


def CHECK_和(答案):
    if not hasattr(答案, "和"):
        return False, ("还没有定义「和」。\n"
                       "      ⚠ 要先写 `和 = 0`（起点），再用循环累加 ——\n"
                       "        少了这一行会报 NameError。")
    if not hasattr(答案, "数字"):
        return False, "先定义好「数字」列表。"
    期望 = sum(答案.数字)
    if 答案.和 != 期望:
        return False, (f"「和」应当是 {期望}，现在是 {答案.和!r}。\n"
                       f"      写法：\n"
                       f"          和 = 0\n"
                       f"          for x in 数字:\n"
                       f"              和 += x\n"
                       f"      ⚠ `+=` 是「加上并放回去」的意思，和 `和 = 和 + x` 等价。")
    return True, f"和 = {期望}"


def CHECK_个数(答案):
    if not hasattr(答案, "个数"):
        return False, "还没有定义「个数」。"
    if not hasattr(答案, "数字"):
        return False, "先定义好「数字」列表。"
    期望 = len(答案.数字)
    if 答案.个数 != 期望:
        # 用 len() 也算对，但这一课想练循环 —— 给个提示而不是判错
        return False, (f"「个数」应当是 {期望}，现在是 {答案.个数!r}。\n"
                       f"      用循环数：\n"
                       f"          个数 = 0\n"
                       f"          for x in 数字:\n"
                       f"              个数 += 1\n"
                       f"      ⚠ 每见到一个元素就 +1。")
    return True, f"个数 = {期望}"


def CHECK_用了for循环(答案):
    """⚠ 这一课的核心是循环本身，不是结果对。"""
    import io
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    if "for " not in 源码:
        return False, ("文件里没有看到 `for` —— 这一课就是要练循环。\n"
                       "      写法：\n"
                       "          for x in 数字:\n"
                       "              和 += x")
    # 个数 不能用 len
    i = 源码.find("个数")
    段 = 源码[i:i + 400] if i >= 0 else ""
    if "len(" in 段 and "个数" in 段:
        return False, ("「个数」看起来是用 `len()` 直接拿的。\n"
                       "      这一课请**用循环数一遍**：\n"
                       "          个数 = 0\n"
                       "          for x in 数字:\n"
                       "              个数 += 1\n"
                       "      ⚠ 先会自己数，再用现成的 —— 顺序不能反。")
    return True, "用了 for 循环，而且个数是自己数出来的"
