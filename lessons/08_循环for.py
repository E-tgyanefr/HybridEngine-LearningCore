# ─────────────────────────────────────────────────────
#  先介绍：为什么需要循环
# ─────────────────────────────────────────────────────
#
# 要打印 5 个分数，不要循环就得写 5 行 print。
# 一百个分数就写一百行 —— 而且加一个就要改一次代码。
#
# 循环让**一段代码重复跑**：
#
#     for x in 分数表:
#         print(x)
#         ↑ 这一行会被执行 len(分数表) 次
#
# ─────────────────────────────────────────────────────
#  for 的两半，各有名字
# ─────────────────────────────────────────────────────
#
#     for  x  in  分数表:
#          ↑        ↑
#        取出来的   要遍历的东西
#        那个东西
#
#   读作：「**对于 分数表 里的每一个元素，把它叫做 x，然后做下面的事**」。
#
#   ⚠ `x` 这个名字是你随便起的（`分数`、`item`、`每个` 都行），
#     但**要起得看得懂**：`for x in ...` 在复杂代码里是灾难。
#
# ─────────────────────────────────────────────────────
#  两种常见的循环
# ─────────────────────────────────────────────────────
#
#   ① 遍历一个列表（最常用）
#
#         for 分数 in 分数表:
#             print(分数)
#
#   ② 重复固定次数
#
#         for i in range(5):
#             print("第", i, "次")        ⇒ 0 1 2 3 4     ← ⚠ 从 0 开始！
#
#         range(1, 6)                     ⇒ 1 2 3 4 5   ← 含头不含尾
#
#   ⚠ `range(5)` 给的是 0,1,2,3,4 —— **5 个**数，但没有 5。
#     `range(1, 6)` 才是 1 到 5。这两个最容易记混。
#
# ─────────────────────────────────────────────────────
#  累加：循环最常用的套路
# ─────────────────────────────────────────────────────
#
#     和 = 0                      ← ⚠ 起点**必须**先定义
#     for x in [1, 2, 3]:
#         和 += x                 ← 和 = 和 + x 的简写
#     print(和)                   ⇒ 6
#
#   ⚠ 忘了 `和 = 0` 会报 `NameError`（第 01 课见过这个错）。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课**只遍历**、不修改列表（增删是第 06 课）。
#   函数（def）是第 09 课，这一课先不写函数。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 定义列表 数字 = [3, 1, 4, 1, 5]
#   2. 定义变量 和（先给 0），然后用 for 把 数字 里的每个数累加进去
#   3. 定义变量 个数，用循环数出有几个数（**不要用 len()**，练循环）
#
# ─────────────────────────────────────────────────────
#  怎么自己测
