#   卡住了看答案（先自己写一遍）—— 命令在「怎么自己测」那一节。
#
# ─────────────────────────────────────────────────────
#  先介绍：程序一关，变量就全没了
# ─────────────────────────────────────────────────────
#
# 前面几十课，数据都活在变量里 —— 程序一结束就烟消云散。
# 想让结果留下来（成绩单、日记、游戏存档），就得写进**文件**。
# 文件是这一次运行和下一次运行之间唯一的通道。
#
# 这一课只学四个动作：读全部、按行读、写一行、追加。
#
# ─────────────────────────────────────────────────────
#  一、三步：打开 → 用 → 关
# ─────────────────────────────────────────────────────
#
#     文件 = open('成绩.txt', 'w', encoding='utf-8')
#     文件.write('小明 90\n')
#     文件.close()                          ← 别忘了这一行
#
# ⚠ `encoding='utf-8'` 在中文系统上是**必须**的：不写的话，Python 用系统的
#   GBK 去读写，中文会变乱码或者直接报错。养成写它的习惯。
#
# ─────────────────────────────────────────────────────
#  二、with：让 Python 替你关（**一律用这个**）
# ─────────────────────────────────────────────────────
#
#     with open('成绩.txt', 'w', encoding='utf-8') as 文件:
#         文件.write('小明 90\n')
#     # 出了这个缩进块，文件已经自动关好了
#
# ⚠ 为什么「必须」用 with，而不是「记得住 close」：
#   中间一旦抛异常，`文件.close()` 那一行**根本走不到**。
#
#     with open('a.txt', 'w', encoding='utf-8') as 文件:
#         文件.write('第一句')
#         数字 = int('abc')            ← 这里会抛异常
#         文件.write('第二句')
#     # 虽然是异常退出的，文件依然被关好了，第一句也已经落到磁盘上
#
# ─────────────────────────────────────────────────────
#  三、打开模式：'r' / 'w' / 'a'
# ─────────────────────────────────────────────────────
#
#     模式    意思          文件不存在时         会不会清空原内容
#     ────  ────────────  ──────────────────  ────────────────────
#     'r'   只读（默认）    报 FileNotFoundError  —
#     'w'   只写（新写）    自动新建              **会！一打开就清空**
#     'a'   追加（写在末尾） 自动新建             不会
#
# ⚠ 'w' 是最危险的：它**一打开就把原文件清空**。路径打错一个字母，
#   就等于亲手删了一份数据。想往已有文件里加内容，用 'a'。
#
# ─────────────────────────────────────────────────────
#  四、读：三种方式，外加最常用的那种
# ─────────────────────────────────────────────────────
#
#     with open('成绩.txt', encoding='utf-8') as 文件:
#         全部 = 文件.read()          ⇒ 整个文件，一个字符串
#         行们 = 文件.readlines()     ⇒ ['小明 90\n', '小红 95\n']
#         一行 = 文件.readline()      ⇒ 只读一行
#
# 最常用的是**一行一行读**（文件很大也不怕）：
#
#     with open('成绩.txt', encoding='utf-8') as 文件:
#         for 行 in 文件:
#             行 = 行.strip()              ← ⚠ 去掉末尾的换行
#             print(行)
#
# ⚠ 读进来的每一行**末尾都带着换行符** `\n`（只有最后一行可能没有）。
#   拿去比较或者转数字之前，先 `行.strip()`。
#
# ⚠ 同一个文件对象**不能既 read() 又 readlines()** —— 读过一次，
#   位置就停在末尾了（像书签夹到了最后）。想重来就再 open 一次。
#
# ─────────────────────────────────────────────────────
#  五、写：write 只收字符串
# ─────────────────────────────────────────────────────
#
#     文件.write('一句')                      ← 想换行要自己写 '\n'
#     文件.write('分数：' + str(90) + '\n')    ← ⚠ 数字要先 str()
#     文件.writelines(['a\n', 'b\n'])         ← 一串字符串一次写完（不自动加换行）
#
# ⚠ `文件.write(90)` 会报（真跑过）：
#
#     TypeError: write() argument must be str, not int
#
#   转成文字再写：文件.write(str(90) + '\n')
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：读一个不存在的文件
# ─────────────────────────────────────────────────────
#
#     with open('成绩.txt', encoding='utf-8') as 文件:
#         内容 = 文件.read()
#
#     ⇒ FileNotFoundError: [Errno 2] No such file or directory: '成绩.txt'
#
# ⚠ 两种最常见的真因：
#     ① 相对路径是相对于**你运行命令时所在的目录**，不是脚本文件所在的目录
#     ② 上一步本来是「写」这个文件的，但两次的路径写得不一样（打错一个字）
#
# ⇒ 记住这条分界：**'w' / 'a' 会自动新建文件，'r' 不会** ——
#   文件不在就是上面那个报错。别拿 'w' 去「确认文件在不在」（它会清空！）。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   csv / json 模块、二进制文件（'rb'）、os 和 pathlib 遍历目录、
#   编码到底是怎么回事 —— 用到再说。这一课只讲文本文件怎么读、怎么写。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 写函数 写几句(路径, 文字们)：把列表里的每一句写成一行，每行末尾要有换行
#    （空列表就写一个空文件）
# 2. 写函数 读全部(路径)：返回文件里的**全部内容**（一个字符串）
# 3. 写函数 读成列表(路径)：返回**去掉末尾换行**之后的行列表（空文件返回 []）
# 4. 写函数 数行数(路径)：返回文件有多少行（空文件返回 0）
#    （四个都要用 `with open(...)`，检查会看你的代码）
#
