import io
import os
import shutil
import tempfile


def _读回来(路径):
    with open(路径, encoding="utf-8") as f:
        return f.read()


def _造文件(目录, 名字, 内容):
    路径 = os.path.join(目录, 名字)
    with open(路径, "w", encoding="utf-8") as f:
        f.write(内容)
    return 路径


def _编码出错说明(路径):
    return (f"写出来的文件不是 UTF-8（我用 utf-8 读它时报了编码错）。\n"
            f"      ⚠ 打开文件时加上 encoding：\n"
            f"          with open({os.path.basename(路径)!r}, 'w', encoding='utf-8') as 文件:\n"
            f"        中文系统上不加它，Python 会用 GBK 去写，中文就成了乱码。")


def CHECK_写几句(答案):
    f = 答案.__dict__.get("写几句")
    if not callable(f):
        return False, ("还没有定义函数「写几句」。\n"
                       "      写法：def 写几句(路径, 文字们):\n"
                       "              with open(路径, 'w', encoding='utf-8') as 文件:\n"
                       "                  for 句 in 文字们:\n"
                       "                      文件.write(句 + '\\n')")
    组 = (['小明 90'], ['小明 90', '小红 95', '小刚 80'], [], ['只有一句'],
         ['中文 English 123', '第二行'])
    目录 = tempfile.mkdtemp(prefix="py32a_")
    try:
        for i, 文字们 in enumerate(组):
            路径 = os.path.join(目录, f"写{i}.txt")
            try:
                f(路径, list(文字们))
            except Exception as e:                          # noqa: BLE001
                return False, f"写几句(…, {文字们!r}) 出错了：{type(e).__name__}: {e}"
            if not os.path.isfile(路径):
                return False, (f"写几句(…, {文字们!r}) 之后没有生成文件。\n"
                               f"      ⚠ 'w' 模式会自动新建文件 —— 检查一下路径是不是拼错了，\n"
                               f"        或者函数里其实什么都没写。")
            try:
                实际 = _读回来(路径)
            except UnicodeDecodeError:
                return False, _编码出错说明(路径)
            想 = "".join(句 + "\n" for 句 in 文字们)
            if 实际 != 想:
                if 实际 == "".join(文字们):
                    return False, (f"写几句(…, {文字们!r}) 内容对了，但**每行末尾少了换行**。\n"
                                   f"        文件里现在是 {实际!r}\n"
                                   f"      ⚠ write 不会自动换行，要自己写 '\\n'：\n"
                                   f"          文件.write(句 + '\\n')")
                return False, (f"写几句(…, {文字们!r}) 写出来的内容是 {实际!r}，应当是 {想!r}。\n"
                               f"      ⚠ 每一句一行、末尾带 '\\n'；空列表就写个空文件。")
        return True, "五组都对（1 行 / 3 行 / 空列表 / 单行 / 中英混排），每行末尾都有换行"
    finally:
        shutil.rmtree(目录, ignore_errors=True)


def CHECK_读全部(答案):
    f = 答案.__dict__.get("读全部")
    if not callable(f):
        return False, ("还没有定义函数「读全部」。\n"
                       "      写法：def 读全部(路径):\n"
                       "              with open(路径, encoding='utf-8') as 文件:\n"
                       "                  return 文件.read()")
    组 = ('小明 90\n小红 95\n', '', '没有换行的最后一行', '中文\nEnglish\n123\n')
    目录 = tempfile.mkdtemp(prefix="py32b_")
    try:
        for i, 内容 in enumerate(组):
            路径 = _造文件(目录, f"读{i}.txt", 内容)
            try:
                得 = f(路径)
            except Exception as e:                          # noqa: BLE001
                return False, f"读全部(某个文件) 出错了：{type(e).__name__}: {e}"
            if 得 != 内容:
                return False, (f"读全部(内容为 {内容!r} 的文件) 应当返回 {内容!r}，"
                               f"得到 {得!r}。\n"
                               f"      ⚠ read() 返回的是**整个文件的字符串**（换行也在里面）。\n"
                               f"        别忘了 return。")
        return True, "四组都对（多行 / 空文件 / 没有末尾换行 / 中英混排）"
    finally:
        shutil.rmtree(目录, ignore_errors=True)


def CHECK_读成列表(答案):
    f = 答案.__dict__.get("读成列表")
    if not callable(f):
        return False, ("还没有定义函数「读成列表」。\n"
                       "      写法：def 读成列表(路径):\n"
                       "              with open(路径, encoding='utf-8') as 文件:\n"
                       "                  return [行.strip() for 行 in 文件]")
    组 = (('小明 90\n小红 95\n', ['小明 90', '小红 95']),
         ('', []),
         ('单行', ['单行']),
         ('a\nb\nc', ['a', 'b', 'c']),
         ('\n\n', ['', '']))
    目录 = tempfile.mkdtemp(prefix="py32c_")
    try:
        for i, (内容, 想) in enumerate(组):
            路径 = _造文件(目录, f"列{i}.txt", 内容)
            try:
                得 = f(路径)
            except Exception as e:                          # noqa: BLE001
                return False, f"读成列表(内容为 {内容!r} 的文件) 出错了：{type(e).__name__}: {e}"
            if not isinstance(得, list) or 得 != 想:
                return False, (f"读成列表(内容为 {内容!r} 的文件) 应当是 {想!r}，得到 {得!r}。\n"
                               f"      ⚠ 每行末尾的换行要去掉（用 行.strip()）；\n"
                               f"        空文件要返回 **[]**（不是 ['']，也不是 None）。")
        return True, "五组都对（多行 / 空文件 / 单行 / 末行没换行 / 两个空行）"
    finally:
        shutil.rmtree(目录, ignore_errors=True)


def CHECK_数行数(答案):
    f = 答案.__dict__.get("数行数")
    if not callable(f):
        return False, ("还没有定义函数「数行数」。\n"
                       "      写法：def 数行数(路径):\n"
                       "              with open(路径, encoding='utf-8') as 文件:\n"
                       "                  return len(文件.readlines())")
    组 = (('', 0), ('a', 1), ('a\nb', 2), ('a\nb\nc\n', 3), ('一二三\n四\n', 2))
    目录 = tempfile.mkdtemp(prefix="py32d_")
    try:
        for i, (内容, 想) in enumerate(组):
            路径 = _造文件(目录, f"行{i}.txt", 内容)
            try:
                得 = f(路径)
            except Exception as e:                          # noqa: BLE001
                return False, f"数行数(内容为 {内容!r} 的文件) 出错了：{type(e).__name__}: {e}"
            if 得 != 想:
                return False, (f"数行数(内容为 {内容!r} 的文件) 应当是 {想}，得到 {得!r}。\n"
                               f"      ⚠ 空文件是 **0** 行；`'a\\nb\\nc\\n'` 是 **3** 行\n"
                               f"        （末尾那个换行不算新的一行）。")
        return True, "五组都对（空文件 0 行 / 一行不带换行 / 带末尾换行 / 中文）"
    finally:
        shutil.rmtree(目录, ignore_errors=True)


def CHECK_用了with(答案):
    """⚠ 这一课的核心就是 with —— 不许用 文件 = open(...) 再手动 close。"""
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件，没法确认用没用 with。"
    try:
        源码 = io.open(答案.__file__, encoding="utf-8").read()
    except OSError as e:
        return False, f"读不了你的答题文件：{e}"
    if "with open(" not in 源码 and "with io.open(" not in 源码:
        return False, ("你的代码里没有 `with open(...)`。\n"
                       "      ⚠ 这一课要求四个函数都用 with：\n"
                       "          with open(路径, encoding='utf-8') as 文件:\n"
                       "              …\n"
                       "        它保证**就算中间抛异常，文件也会被关好**；\n"
                       "        手动 close() 在异常时根本走不到那一行。")
    return True, "用了 with open(...)"
