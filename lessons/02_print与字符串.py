# ─────────────────────────────────────────────────────
#  先介绍：print 是什么
# ─────────────────────────────────────────────────────
#
# 前面写的程序，跑完什么都不会发生 —— 因为**你没让它说话**。
#
#     print("你好")
#     ↑
#     把括号里的东西**打印到屏幕上**
#
# 这是你和程序之间唯一的「输出」通道。没有 print，
# 你只能靠猜程序里发生了什么。
#
# ─────────────────────────────────────────────────────
#  字符串：一段文字
# ─────────────────────────────────────────────────────
#
# 用**引号**包起来的东西就是字符串：
#
#     "你好"        双引号
#     '你好'        单引号 —— 和双引号**完全一样**
#     "it's ok"     里面有单引号，就用双引号包
#     'he said "hi"'  里面有双引号，就用单引号包
#
#   ⚠ 两种引号没有区别，选哪种只看「里面有没有另一种引号」。
#
# ─────────────────────────────────────────────────────
#  ⚠ 三个最常见的坑
# ─────────────────────────────────────────────────────
#
#  ① **括号忘了**
#         print "你好"          ❌ Python 3 里 print 是函数，括号必须有
#         print("你好")          ✅
#
#  ② **中文标点**
#         print（"你好"）        ❌ 全角括号！报 SyntaxError: invalid character '（'
#         print("你好")          ✅ 括号和引号都要**半角**
#
#     这个坑特别隐蔽：全角括号和半角括号看起来几乎一样。
#     ⇒ 报 `invalid character` 时，先检查是不是中文输入法打的标点。
#
#  ③ **一次打印多个东西**
#         print("你好", "小明")     ⇒  你好 小明
#         print("你好" + "小明")    ⇒  你好小明
#     `,` 会加一个空格，`+` 直接拼 —— 不一样。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   怎么把变量放进句子里（f-string）是第 04 课，这一课不碰。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 写一行 print，打印：第 02 课开始
#   2. 写一行 print，用 `+` 把两段文字拼起来打印：你好 + 世界
#
#   ⚠ 就这些。不用变量、不用函数。
#
# ─────────────────────────────────────────────────────
