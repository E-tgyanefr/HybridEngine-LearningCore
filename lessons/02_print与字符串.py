def _行(答案):
    """把答题文件的 print 输出抓成行。"""
    import io
    import contextlib
    import runpy
    buf = io.StringIO()
    try:
        with contextlib.redirect_stdout(buf):
            runpy.run_path(str(答案.__file__), run_name="__答题__")
    except Exception as e:                                      # noqa: BLE001
        return None, f"运行你的代码时出错了：{type(e).__name__}: {e}"
    return [l for l in buf.getvalue().split("\n") if l.strip()], None


def CHECK_打印了第一行(答案):
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    行, 错 = _行(答案)
    if 错:
        return False, 错
    if not 行:
        return False, ("你的文件一行都没打印。\n"
                       "      写法：print('第 02 课开始')\n"
                       "      ⚠ print 后面那对**圆括号**不能少。")
    if "第 02 课开始" not in 行[0]:
        return False, (f"第一行应当是「第 02 课开始」，实际是 {行[0]!r}。\n"
                       f"      ⚠ 检查：括号和引号是不是**半角**的？\n"
                       f"        全角（）会报 invalid character，全角引号也一样。")
    return True, f"第一行 = {行[0]}"


def CHECK_拼接打印了(答案):
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    行, 错 = _行(答案)
    if 错:
        return False, 错
    if len(行) < 2:
        return False, (f"应该有 2 行输出，实际 {len(行)} 行 —— 是不是忘了第二行 print？\n"
                       f"      写法：print('你好' + '世界')")
    if 行[1].strip() != "你好世界":
        return False, (f"第二行应当是「你好世界」（中间**没有空格**），实际是 {行[1]!r}。\n"
                       f"      ⚠ 用 `+` 拼接是紧挨着的；用 `,` 会多一个空格。\n"
                       f"        print('你好' + '世界')   ⇒  你好世界\n"
                       f"        print('你好', '世界')   ⇒  你好 世界")
    return True, f"第二行 = {行[1]}"
