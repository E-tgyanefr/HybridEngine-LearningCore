import math


def _喂(函数, 名字, 用例们, 提示, 近似=False):
    for 用例 in 用例们:
        *参数们, 想 = 用例
        try:
            得 = 函数(*参数们)
        except Exception as e:                                  # noqa: BLE001
            return False, f"{名字}{tuple(参数们)} 出错：{type(e).__name__}: {e}｜{提示}"
        对 = math.isclose(得, 想) if 近似 and isinstance(得, (int, float)) else 得 == 想
        if not 对:
            return False, f"{名字}{tuple(参数们)} 应当是 {想!r}，得到 {得!r}｜{提示}"
    return True, f"{len(用例们)} 组都对"


def CHECK_圆面积和斜边(答案):
    f = 答案.__dict__.get("圆面积")
    g = 答案.__dict__.get("斜边")
    if not callable(f) or not callable(g):
        return False, ("还没有定义「圆面积」或「斜边」。写法：\n"
                       "      def 圆面积(半径): return math.pi * 半径 ** 2\n"
                       "      def 斜边(甲, 乙): return math.sqrt(甲 ** 2 + 乙 ** 2)")
    出 = _喂(f, "圆面积", ((0, 0.0), (1, math.pi), (2, 4 * math.pi),
                          (2.5, 6.25 * math.pi), (0.5, 0.25 * math.pi)),
             "用 math.pi，别把 π 手写成 3.14（那会差 0.0013）", 近似=True)
    if not 出[0]:
        return 出
    return _喂(g, "斜边", ((3, 4, 5.0), (0, 0, 0.0), (5, 12, 13.0), (1, 1, math.sqrt(2)),
                          (0, 5, 5.0), (6, 8, 10.0)),
               "勾股定理 math.sqrt(甲**2 + 乙**2)；一条直角边为 0 就返回另一条", 近似=True)


def CHECK_取整(答案):
    f = 答案.__dict__.get("向下取整")
    g = 答案.__dict__.get("向上取整")
    if not callable(f) or not callable(g):
        return False, ("还没有定义「向下取整」「向上取整」。写法：def 向下取整(x): "
                       "return math.floor(x)，def 向上取整(x): return math.ceil(x)")
    出 = _喂(f, "向下取整", ((2.5, 2), (-2.5, -3), (3.0, 3), (0.1, 0), (-0.1, -1)),
             "math.floor 往小走：floor(-2.5) 是 -3，不是 int(-2.5) 的 -2")
    if not 出[0]:
        return 出
    return _喂(g, "向上取整", ((2.5, 3), (-2.5, -2), (3.0, 3), (0.1, 1), (-0.1, 0)),
               "math.ceil 往大走：ceil(-2.5) 是 -2")


def CHECK_最大公约数和二进制位数(答案):
    f = 答案.__dict__.get("最大公约数")
    g = 答案.__dict__.get("二进制位数")
    if not callable(f):
        return False, ("还没有定义「最大公约数」。写法：def 最大公约数(甲, 乙): "
                       "return math.gcd(甲, 乙)")
    if not callable(g):
        return False, ("还没有定义「二进制位数」。写法：\n"
                       "      def 二进制位数(数):\n"
                       "          if 数 <= 0: return 0\n"
                       "          return math.floor(math.log2(数)) + 1")
    出 = _喂(f, "最大公约数", ((12, 18, 6), (7, 13, 1), (0, 5, 5), (5, 0, 5),
                            (0, 0, 0), (-12, 18, 6)),
             "直接用 math.gcd，它会自己处理负数和 0，不用自己写循环")
    if not 出[0]:
        return 出
    return _喂(g, "二进制位数", ((1, 1), (2, 2), (3, 2), (4, 3), (1000, 10), (1024, 11),
                                (0, 0), (-5, 0)),
               "位数 = floor(log2(数)) + 1；先挡掉 数 ≤ 0，"
               "否则 log2(0) 会抛 ValueError: math domain error")


def CHECK_约等于(答案):
    f = 答案.__dict__.get("约等于")
    if not callable(f):
        return False, "还没有定义「约等于」。写法：return math.isclose(甲, 乙)"
