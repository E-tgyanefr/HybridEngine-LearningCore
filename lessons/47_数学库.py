# 第 03 课的 `9 ** 0.5` 能算出 3.0，但开方、三角函数、对数都不是四则运算能表达的。
# Python 把它们放在 **math** 库里，用之前先请它进来：
#
#     import math
#     math.sqrt(2)          ⇒ 1.4142135623730951
#
# ⚠ 少了 import 直接调 sqrt：NameError: name 'sqrt' is not defined —— 它点的是
#   **sqrt** 不是 math，说明你把函数名单独拎出来用了。
#
# ─────────────────────────────────────────────────────
#  一、速查表：这一课要用的九个
# ─────────────────────────────────────────────────────
#
#     math.pi         3.141592653589793   圆周率（是**值**，不加括号）
#     math.e          2.718281828459045   自然常数
#     math.sqrt(x)    平方根        sqrt(9) ⇒ 3.0     （结果永远是 float）
#     math.exp(x)     e 的 x 次方   exp(1) ⇒ 2.718281828459045
#     math.log(x)     自然对数      log(math.e) ⇒ 1.0
#     math.log(x, b)  以 b 为底     log(8, 2) ⇒ 3.0
#     math.log2(x)    以 2 为底     log2(1024) ⇒ 10.0   ← 数二进制位数用它
#     math.log10(x)   以 10 为底    log10(1000) ⇒ 3.0
#     math.sin(x)     正弦，x 是**弧度**：sin(radians(30)) ⇒ 0.49999999999999994
#     math.cos(x)     余弦：cos(0) ⇒ 1.0
#     math.floor(x)   向下取整（往小走）：floor(-2.5) ⇒ -3
#     math.ceil(x)    向上取整（往大走）：ceil(-2.5) ⇒ -2
#     math.gcd(a, b)  最大公约数：gcd(12, 18) ⇒ 6，gcd(5, 0) ⇒ 5，gcd(0, 0) ⇒ 0
#
# ⚠ 四个一眼看不出来的地方：
#   ① pi / e 是**值**不是函数：math.pi() 报 TypeError: 'float' object is not callable
#   ② 三角函数收**弧度**（180 度 = pi 弧度）：radians(30) ⇒ 0.5235987755982988
#   ③ gcd 只吃整数：math.gcd(1.5, 2) 报 TypeError: 'float' object cannot be
#      interpreted as an integer
#   ④ int(-2.5) ⇒ -2 是**向零截断**，floor(-2.5) ⇒ -3 才是「不超过它的最大整数」
#
# ─────────────────────────────────────────────────────
#  二、浮点误差：为什么 0.1 + 0.2 不等于 0.3
# ─────────────────────────────────────────────────────
#
#     0.1 + 0.2                  ⇒ 0.30000000000000004
#     0.1 + 0.2 == 0.3           ⇒ False     （！）
#     math.sqrt(2) ** 2          ⇒ 2.0000000000000004
#     math.sin(math.radians(30)) ⇒ 0.49999999999999994    ← 不是 0.5
#     math.cos(math.pi / 2)      ⇒ 6.123233995736766e-17  ← 不是 0
#
# 为什么：计算机用**二进制**存小数，0.1 写成二进制是 0.0001100110011… 无限
# 循环 —— 和十进制里 1/3 = 0.333… 写不完是一回事。float 只有 **53 位**有效
# 数字，写不完就得截断，误差还会随运算累积。反过来 2 的负次幂精确：
# 0.5 + 0.25 == 0.75 ⇒ True，这个真的相等。
#
# ⚠ 别把「定义域报错」误当成浮点误差 —— sqrt 要求 x ≥ 0、log 要求 x > 0：
#     math.sqrt(-1) ❌ ValueError: math domain error
#     math.log(0)   ❌ ValueError: math domain error
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：拿 == 比浮点数
# ─────────────────────────────────────────────────────
#
#     if 0.1 + 0.2 == 0.3:        ❌ 这个分支永远进不去
#
# 它不报错、不崩溃，只是**悄悄走了另一条路** —— 最难查的一类错。
# ⇒ 一律换成 math.isclose：
#
#     math.isclose(0.1 + 0.2, 0.3)     ⇒ True    （允许 1e-9 以内的相对误差）
#     math.isclose(1.0, 1.0000001)     ⇒ False
#     math.isclose(1e9, 1e9 + 0.5)     ⇒ True    ← 差 0.5 也算「近」！
#
#   ⚠ 最后一行要留意：isclose 比的是**相对误差**，数大了容差也跟着大；要比 sqrt(a) 和 sqrt(b) 谁大，平方回 a 和 b 再比更稳。
