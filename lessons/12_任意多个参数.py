def CHECK_加全部(答案):
    if not hasattr(答案, "加全部"):
        return False, "还没有定义「加全部」函数。写法：def 加全部(*数字): ..."
    if not callable(答案.加全部):
        return False, "「加全部」不是函数。"
    try:
        得 = 答案.加全部(1, 2, 3)
    except TypeError as e:
        return False, (f"加全部(1, 2, 3) 调用失败：{e}\n"
                       f"      ⚠ 说明参数前面**少了那个星号**。\n"
                       f"        写法：def 加全部(*数字):")
    except Exception as e:                                      # noqa: BLE001
        return False, f"加全部(1, 2, 3) 出错了：{type(e).__name__}: {e}"
    if 得 != 6:
        return False, f"加全部(1, 2, 3) 应当是 6，实际是 {得!r}。"
    if 答案.加全部() != 0:
        return False, (f"加全部()（一个都不传）应当是 **0**，实际是 {答案.加全部()!r}。\n"
                       f"      ⚠ 不传时 `数字` 是空元组 ()，sum(()) 正好是 0。\n"
                       f"        自己写循环的话，记得起点 `和 = 0`。")
    if 答案.加全部(7) != 7:
        return False, f"加全部(7) 应当是 7，实际是 {答案.加全部(7)!r}。"
    if 答案.加全部(1, 2, 3, 4, 5) != 15:
        return False, f"加全部(1..5) 应当是 15，实际是 {答案.加全部(1,2,3,4,5)!r}。"
    return True, "0 个 / 1 个 / 3 个 / 5 个 都对"


def CHECK_最长(答案):
    if not hasattr(答案, "最长"):
        return False, "还没有定义「最长」函数。写法：def 最长(*文字们): ..."
    if not callable(答案.最长):
        return False, "「最长」不是函数。"
    try:
        得 = 答案.最长("a", "bbb", "cc")
    except Exception as e:                                      # noqa: BLE001
        return False, f"最长('a','bbb','cc') 出错了：{type(e).__name__}: {e}"
    if 得 != "bbb":
        return False, (f"最长('a','bbb','cc') 应当是 'bbb'，实际是 {得!r}。\n"
                       f"      ⚠ 比的是**长度**（len），不是字典序。")
    # ⚠ 核心判据：一个都不传不能崩
    try:
        空 = 答案.最长()
    except Exception as e:                                      # noqa: BLE001
        return False, (f"最长()（一个都不传）崩了：{type(e).__name__}: {e}\n"
                       f"      ⚠⚠ 用了 `*参数` 就必须想一下「什么都不传」是什么意思。\n"
                       f"        最省事的写法是先判断：\n"
                       f"            if not 文字们:\n"
                       f"                return ''")
    if 空 != "":
        return False, (f"最长() 应当返回**空文字** ''，实际是 {空!r}。\n"
                       f"      ⚠ 返回 None 也行不通 —— 调用者拿去做字符串拼接会崩。")
    if 答案.最长("只有一段") != "只有一段":
        return False, "只有一段时应当返回它自己。"
    return True, "含「一个都不传」边界"
