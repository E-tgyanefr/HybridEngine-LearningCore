# ─────────────────────────────────────────────────────
#  先介绍：参数个数可以不定
# ─────────────────────────────────────────────────────
#
# 你一直在用 `print`，有没有想过它怎么能接任意多个东西？
#
#     print("a")
#     print("a", "b")
#     print("a", "b", "c", "d", ...)      都能用！
#
# 因为它用了 `*参数`：
#
#     def 加全部(*数字):
#         ...
#
# 那个**星号**的意思是：「把传进来的所有参数**收成一个元组**」。
#
#     加全部(1, 2, 3)      数字 是 (1, 2, 3)
#     加全部(5)            数字 是 (5,)
#     加全部()             数字 是 ()          ← 空元组，不是报错
#
# ─────────────────────────────────────────────────────
#  ⚠ 收进来的是**元组**，不是列表
# ─────────────────────────────────────────────────────
#
#     type(数字)      ⇒  <class 'tuple'>
#
#   能用 for 遍历（和列表一样），但**不能** append（元组不可改）。
#   ⇒ 要加东西就先转成列表：`表 = list(数字)`
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课唯一要记住的坑：一个都不传时怎么办
# ─────────────────────────────────────────────────────
#
#     def 加全部(*数字):
#         和 = 0
#         for x in 数字:
#             和 += x
#         return 和
#
#   `加全部()` 时 `数字` 是 `()` —— 循环一次都不跑，返回 0。**这是对的。**
#
#   但如果你写成这样：
#
#     def 最大值(*数字):
#         return max(数字)         ← 加全部() 时会 ValueError: max() arg is an empty sequence
#
#   ⇒ 用 `*参数` 时**必须想一下「什么都不传」是什么意思**。
#     能返回 0 就返回 0；不能返回 0 的（比如最大值），要想清楚返回什么。
#
# ─────────────────────────────────────────────────────
#  顺带：星号还有一种用法（反过来的）
# ─────────────────────────────────────────────────────
#
#     def 画点(x, y):
#         ...
#
#     坐标 = (3, 4)
#     画点(*坐标)          ⇒  等于 画点(3, 4)      ← 把元组「拆开」传进去
#
#   同一个星号，在**定义**时是「收起来」，在**调用**时是「拆开」。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课只讲 `*`。关键字参数（`**`）等你以后用到再学，现在不用碰。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 写函数 加全部(*数字)，返回它们的和（一个都不传时返回 0）
#   2. 写函数 最长(*文字们)，返回最长的那一段（一个都不传时返回 ""）
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
