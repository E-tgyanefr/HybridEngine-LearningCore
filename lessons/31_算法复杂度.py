import io
import threading


def _限时跑(函数, 参数们, 秒=2.0):
    """在另一个线程里跑，超时判失败。

    ⚠ 这一课的核心就是「复杂度估错就跑不完」：
      第 2 题如果学员真去写两层循环，n=100000 那一组会跑到天荒地老。
      没有这个超时，检查会跟着一起卡死。
    """
    结果 = {}

    def 干():
        try:
            结果["值"] = 函数(*参数们)
        except BaseException as e:                          # noqa: BLE001
            结果["错"] = e

    线 = threading.Thread(target=干, daemon=True)
    线.start()
    线.join(秒)
    if 线.is_alive():
        return False, "超时"
    if "错" in 结果:
        return False, f"{type(结果['错']).__name__}: {结果['错']}"
    return True, 结果["值"]


def CHECK_平方次数(答案):
    f = 答案.__dict__.get("平方次数")
    if not callable(f):
        return False, ("还没有定义函数「平方次数」。\n"
                       "      写法：def 平方次数(n):\n"
                       "              次数 = 0\n"
                       "              for i in range(n):\n"
                       "                  for j in range(n):\n"
                       "                      次数 += 1\n"
                       "              return 次数")
    for n, 想 in ((0, 0), (1, 1), (2, 4), (5, 25), (10, 100), (20, 400)):
        try:
            得 = f(n)
        except Exception as e:                              # noqa: BLE001
            return False, f"平方次数({n}) 出错了：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"平方次数({n}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 两层循环，每层都跑 n 次：一共 n × n 次。\n"
                           f"        n=0 时里面一次都不跑，所以是 0。")
    return True, "六组都对（含 n=0 和 n=1），确实是数出来的"


def CHECK_数出次数(答案):
    f = 答案.__dict__.get("数出次数")
    if not callable(f):
        return False, ("还没有定义函数「数出次数」。\n"
                       "      提示：for i in range(n) 里再 for j in range(i)，\n"
                       "      总次数 = (n-1) + (n-2) + … + 1 = n(n-1)/2。\n"
                       "      写法：return n * (n - 1) // 2")
    for n, 想 in ((0, 0), (1, 0), (2, 1), (3, 3), (10, 45), (100, 4950)):
        try:
            得 = f(n)
        except Exception as e:                              # noqa: BLE001
            return False, f"数出次数({n}) 出错了：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"数出次数({n}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 内层是 range(i)：i=0 时跑 0 次、i=1 时跑 1 次…\n"
                           f"        n=10 时是 0+1+…+9 = 45，也就是 n(n-1)/2。\n"
                           f"        ⚠ 是 // 整除，不是 /（要整数）。")
    # ⚠ 关键一测：不许真的去循环。n=100000 用两层循环要跑 50 亿次（几分钟）。
    行不行, 值 = _限时跑(f, (100000,), 秒=2.0)
    if not 行不行:
        if 值 == "超时":
            return False, ("数出次数(100000) 跑了 2 秒还没出来 —— 你真的去循环了吧？\n"
                           "      ⚠ 这一题考的是**用公式算**，不是数一遍：\n"
                           "          次数 = n * (n - 1) // 2      ⇒ 4999950000\n"
                           "        两层循环要跑 50 亿次（几分钟），公式是瞬间。\n"
                           "        这正是这一课的主题：O(n²) 和 O(1) 的差距。")
        return False, f"数出次数(100000) 出错了：{值}"
    if 值 != 4999950000:
        return False, (f"数出次数(100000) 应当是 4999950000，得到 {值!r}。\n"
                       f"      ⚠ 公式：n * (n - 1) // 2，别写成 n * (n - 1) / 2（那会变小数）。")
    return True, "六组小数据都对，n=100000 也是瞬间算出 4999950000（没去循环）"


def CHECK_平方次数真的是数出来的(答案):
    """⚠ 这一题的重点是**亲手跑够那个次数**，不是背一句 n*n。

    所以除了结果对，还要看代码里确实有循环 —— 否则这一课最有价值的
    「感受到 100 万次有多久」就白费了。
    """
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件，没法确认是不是数出来的。"
    try:
        源码 = io.open(答案.__file__, encoding="utf-8").read()
    except OSError as e:
        return False, f"读不了你的答题文件：{e}"
    i = 源码.find("def 平方次数")
    if i < 0:
        return False, "源码里找不到「def 平方次数」。"
    j = 源码.find("\ndef ", i + 1)
    段 = 源码[i:j if j > 0 else i + 400]
    if 段.count("for ") < 2:
        return False, ("「平方次数」里没有两层循环。\n"
                       "      ⚠ 直接 `return n * n` 结果虽然对，但这一题要的是**数一遍**：\n"
                       "          次数 = 0\n"
                       "          for i in range(n):\n"
                       "              for j in range(n):\n"
                       "                  次数 += 1\n"
                       "          return 次数\n"
                       "        亲手跑一次 n=1000（100 万次、约 0.03 秒），"
                       "你对 O(n²) 才有个真实的感受。")
    return True, "确实写了循环去数（两层 for）"


def CHECK_线性查找(答案):
    f = 答案.__dict__.get("线性查找")
    if not callable(f):
        return False, ("还没有定义函数「线性查找」。\n"
                       "      写法：def 线性查找(表, 要找的):\n"
                       "              for i in range(len(表)):\n"
                       "                  if 表[i] == 要找的:\n"
                       "                      return i\n"
                       "              return -1")
    for 表, 要找的, 想 in (([], 1, -1), ([7], 7, 0), ([3, 1, 2], 2, 2),
                          ([1, 2, 3], 9, -1), ([5, 5, 5], 5, 0), ([0], 0, 0)):
        try:
            得 = f(list(表), 要找的)
        except Exception as e:                              # noqa: BLE001
            return False, f"线性查找({表!r}, {要找的!r}) 出错了：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"线性查找({表!r}, {要找的!r}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 找到就返回**下标**（有重复的返回第一个）；\n"
                           f"        找不到返回 **-1**（不是 None，也不是报错）。")
    return True, "六组都对（空表 / 单个 / 末尾 / 找不到 / 重复 / 找 0）"


def CHECK_有没有重复(答案):
    f = 答案.__dict__.get("有没有重复")
    if not callable(f):
        return False, ("还没有定义函数「有没有重复」。\n"
                       "      写法：两层循环，表[i] 和表[j]（j > i）比一比，\n"
                       "            相等就 return True；全比完没找到就 return False。")
    for 表, 想 in (([], False), ([1], False), ([1, 2, 3], False), ([1, 2, 1], True),
                  ([0, 0], True), ([-1, 1, -1], True), ([2, 2, 2, 2], True)):
        try:
            得 = f(list(表))
        except Exception as e:                              # noqa: BLE001
            return False, f"有没有重复({表!r}) 出错了：{type(e).__name__}: {e}"
        if bool(得) != 想:
            return False, (f"有没有重复({表!r}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 边界：空表、单元素表都没有重复（False）；\n"
                           f"        两层循环时内层从 i+1 开始（自己和自己当然相等，别比）。")
    return True, "七组都对（空表 / 单元素 / 无重复 / 有重复 / 全相同 / 负数）"
