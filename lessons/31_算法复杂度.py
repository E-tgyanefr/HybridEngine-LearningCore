#   卡住了看答案（先自己写一遍）—— 命令在「怎么自己测」那一节。
#
# ─────────────────────────────────────────────────────
#  先介绍：两种写法都对，一个 0.03 秒，一个 5 分钟
# ─────────────────────────────────────────────────────
#
# 「算出答案」只是及格线。同一道题，写法不同，速度能差几百万倍。
#
# 复杂度就是**提前看出这件事**的工具：它不问「你这台电脑多快」，
# 只问「数据量 n 变大时，工作量按什么规律涨」。
#
#     n 是数据的规模（有几个数、要走几步）
#
# 学会看它，你就能在**写完之前**知道程序会不会卡死 —— 而不是等它跑一晚上。
#
# ─────────────────────────────────────────────────────
#  一、四个必须认识的记号
# ─────────────────────────────────────────────────────
#
#     记号      n 翻倍时工作量…    典型样子              n=1000 时大约
#     ──────  ───────────────  ───────────────────  ──────────────
#     O(1)     完全不变          取 表[0]、一次加法      1 步
#     O(n)     翻倍              遍历一遍、求和          1000 步
#     O(n²)    变 4 倍           两层嵌套循环            100 万步
#     O(2ⁿ)    n 加 1 就翻倍     枚举所有子集、慢递归    天文数字
#
# ⚠ 两个规矩：① 只留涨得最快的那一项（n + n² ⇒ O(n²)）；
#   ② 丢掉常数（3n、100n 都写 O(n)）—— 决定胜负的是**趋势**，不是系数。
#
# ─────────────────────────────────────────────────────
#  二、怎么数：循环嵌套就是「相乘」
# ─────────────────────────────────────────────────────
#
#     for i in range(n):            ← n 次
#         print(i)                  ⇒ O(n)
#
#     for i in range(n):            ← 外层 n 次
#         for j in range(n):        ← 内层每次都跑 n 次
#             次数 += 1             ⇒ 一共 n × n ⇒ O(n²)
#
#     for i in range(n):            ← 一个循环
#         次数 += 1
#         print('x')                ⇒ 两句都跑 n 次，还是 O(n)
#
#     for i in range(n):            ← 并列的两个循环：相加
#         ...
#     for i in range(n):            ← n + n² ⇒ 看最大的 ⇒ O(n²)
#         for j in range(n):
#             ...
#
# ⚠ 数复杂度的口诀：**一层循环 O(n)，两层嵌套 O(n²)，三层 O(n³)…**
#   看到 `range(n)` 里套 `range(n)`，就要立刻想到「这是平方级的」。
#
# ─────────────────────────────────────────────────────
#  三、常见写法的复杂度（这张表很值钱）
# ─────────────────────────────────────────────────────
#
#     写法                    复杂度        为什么
#     ─────────────────────  ──────────  ────────────────────────
#     表[0] / 表[i]           O(1)        直接算地址，一步到位
#     表.append(x)            O(1)        加到末尾
#     x in 表                 O(n)        最坏要把整个表看一遍
#     遍历一遍求和             O(n)        每个元素看一次
#     两层嵌套循环             O(n²)       n × n
#     冒泡 / 插入 / 选择排序    O(n²)       第 29 课数过了
#     慢递归斐波那契           O(2ⁿ)       每一层分成两个
#     sorted(表)              O(n log n)  比 n² 好得多
#
# ⚠ 最隐蔽的一个：`x in 表` 是 O(n)。把它写在循环里，程序就悄悄变成 O(n²)：
#
#     for x in 表:              ← n 次
#         if x in 另表:         ← 每次都 O(n)
#             ...               ⇒ 合起来 O(n²)
#
# ─────────────────────────────────────────────────────
#  四、实测：差多少（用 time 量出来）
# ─────────────────────────────────────────────────────
#
#     import time
#     起 = time.perf_counter()        ← 秒表开始
#     …要测的代码…
#     花 = time.perf_counter() - 起    ← 过去了多少秒
#
# 两层嵌套循环（这台机器上实测）：1000 ⇒ 100 万次 / 0.03 秒；
# 3000 ⇒ 900 万次 / 0.27 秒；10000 ⇒ 1 亿次 / 约 3 秒；
# 100000 ⇒ 100 亿次 / 约 300 秒（5 分钟）。
#
# 同一台机器，O(n) 建一张 10 万格的表：**0.005 秒**（1 万倍差距）。
#
# 慢递归斐波那契（O(2ⁿ)）实测：n=30 ⇒ 0.06 秒；n=35 ⇒ 0.66 秒；
# n=40 ⇒ 8.3 秒；n=50 ⇒ 十几分钟。
# ⚠ n 从 40 到 50 只多了 10，时间涨了 100 多倍 —— 这就是「指数级」的可怕。
#
# ─────────────────────────────────────────────────────
#  五、考试怎么问（两种题型）
# ─────────────────────────────────────────────────────
#
#   ① 「这段代码的时间复杂度是？」⇒ 数循环层数，写成 O(…)
#   ② 「n=1000 时循环体大约跑多少次？」⇒ 把 n 代进式子算
#
# 内层是 `range(i)` 这种「越跑越短」的循环时：
#     总次数 = (n-1) + (n-2) + … + 1 = n(n-1)/2
#     n=1000 ⇒ 约 50 万次（**还是 O(n²)**，只是系数小一半）
#
# ⚠ 答题要写 O(…)，不要写「很快」「有点慢」—— 那是感觉，不是答案。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：复杂度估错时，程序不是报错，是「跑不完」
# ─────────────────────────────────────────────────────
#
# 你把 O(n²) 当成了 O(n)：n=1000 时没事（0.03 秒），
# 可数据一到 10 万，程序就变成要跑 5 分钟 —— 而它**一句话都不说**。
#
# 你等不下去，只能 Ctrl+C 打断它，屏幕上留下的是这个（真跑过）：
#
#     Traceback (most recent call last):
#       …
#         和 += i
#         ^^
#     KeyboardInterrupt
#
# ⇒ 看到 KeyboardInterrupt，先问自己：**它是不是复杂度估错了？**
#   写完先算一遍最坏要跑多少次；超过 1 亿次就该重新想想了。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   O(n log n) 怎么来的、空间复杂度、均摊分析、怎么优化常数 —— 用到再说。
#   这一课只讲：看清一段代码是 O(1) / O(n) / O(n²) / O(2ⁿ)。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 写函数 平方次数(n)：**用两层循环真的数一遍**，返回 `次数 += 1` 执行了多少次
#    （别直接写 n * n —— 这一题就是要你亲手跑够那个次数）
# 2. 写函数 数出次数(n)：**不许写循环**，直接算出下面这段的执行次数：
#        for i in range(n):
#            for j in range(i):
#                次数 += 1
#    提示：答案是 n(n-1)/2（要能算 n=100000 这种大数）
# 3. 写函数 线性查找(表, 要找的)：从头找，找到返回下标，找不到返回 -1
# 4. 写函数 有没有重复(表)：两层循环判断表里有没有重复元素，返回 True / False
#    （空表和只有一个元素的表都返回 False）
#
