# 第 16 课：封装 —— 把一个东西的规则关进它自己里面

# ─────────────────────────────────────────────────────
#  先介绍：什么叫"规则只有一个出口"
# ─────────────────────────────────────────────────────
#
# 第 15 课你学会了造对象。但光有属性还不够 —— 看这个：
#
#     class 存钱罐:
#         def __init__(self, 初值=0):
#             self.余额 = 初值
#
#     罐 = 存钱罐(100)
#     罐.余额 = -999          ← ⚠ 外面随便就能把余额改成负数！
#
# 问题：`余额` 是公开的，**谁都能乱改** —— 你在方法里写多少检查都没用。
#
# 封装就是：**把"改数据"这件事收进方法里，外面只能通过方法改。**
#
#     class 存钱罐:
#         def __init__(self, 初值=0):
#             self._余额 = 初值          ← 下划线开头 = "别从外面碰它"
#
#         @property
#         def 余额(self):                ← 外面读 罐.余额 会走到这里
#             return self._余额
#
#         def 存(self, n):
#             self._余额 += n
#
#         def 取(self, n):
#             if n > self._余额:          ← 规则就在这里，跑不掉
#                 return False
#             self._余额 -= n
#             return True
#
#   ⇒ 想把余额改成负数？做不到 —— 唯一的入口是 `取`，而 `取` 会检查。
#
#   ⚠ "封装"不要理解成"藏起来"。它的真实意思是：
#     **一个东西的规则只有一个出口。**
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课唯一要记住的顺序：先检查，通过才动
# ─────────────────────────────────────────────────────
#
# 新手最容易这么写：
#
#     def 取(self, n):
#         self.余额 -= n              ← ❌ 已经扣了！
#         if self.余额 < 0:
#             return False
#
# 这时余额**已经被改坏了** —— 你返回 False 也晚了。
#
#   ⇒ 顺序永远是：**先检查，通过才动。**
#
#     def 取(self, n):
#         if n > self.余额:
#             return False            ← 什么都没动
#         self.余额 -= n              ← 检查过了才扣
#         return True
#
#   ⚠ 边界：`n > self.余额` 是"大于才拒绝"。
#     写成 `>=` 的话，"正好取光"（取 100，余额 100）会被拒绝 —— 那是错的。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课只讲"用方法管住数据"。继承、接口这些以后再说。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   写一个类 存钱罐：
#     · 造出来时有余额（默认 0）
#     · 方法 `存(n)`：增加余额
#     · 方法 `取(n)`：够就扣掉并返回 True，**不够就返回 False 且余额一点都不变**
#     · 属性 `余额`：外面能读，但不能直接改
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 16


def CHECK_存钱罐(答案):
    if not hasattr(答案, "存钱罐"):
        return False, "还没有定义「存钱罐」类。"
    类 = 答案.存钱罐
    if not isinstance(类, type):
        return False, f"「存钱罐」应当是类，现在是 {type(类).__name__}。"
    try:
        a = 类(100)
    except Exception as e:                                      # noqa: BLE001
        return False, f"`存钱罐(100)` 造不出来：{type(e).__name__}: {e}"
    if not hasattr(a, "余额"):
        return False, "存钱罐上没有 `.余额`。"
    if a.余额 != 100:
        return False, f"`存钱罐(100).余额` 应当是 100，实际是 {a.余额!r}。"
    if 类().余额 != 0:
        return False, f"不传初值时余额应当是 0，实际是 {类().余额!r}。"
    return True, "能造出来，余额默认 0、也能指定"


def CHECK_存(答案):
    if not hasattr(答案, "存钱罐"):
        return False, "还没有定义「存钱罐」类。"
    a = 答案.存钱罐(100)
    if not hasattr(a, "存") or not callable(a.存):
        return False, "没有 `存(n)` 方法。"
    a.存(50)
    if a.余额 != 150:
        return False, (f"存(50) 之后余额应当是 150，实际是 {a.余额!r}。\n"
                       f"      ⚠ 写法：self._余额 += n（或 self.余额 由属性提供）")
    a.存(0)
    if a.余额 != 150:
        return False, f"存(0) 不该改变余额，实际变成了 {a.余额!r}。"
    return True, "存钱加法正确"


def CHECK_取钱够(答案):
    if not hasattr(答案, "存钱罐"):
        return False, "还没有定义「存钱罐」类。"
    a = 答案.存钱罐(100)
    if not hasattr(a, "取") or not callable(a.取):
        return False, "没有 `取(n)` 方法。"
    得 = a.取(30)
    if 得 is not True:
        return False, (f"取(30)（钱够）应当返回 **True**，实际是 {得!r}。\n"
                       f"      ⚠ 方法要 `return True` / `return False`，不能只是 print。")
    if a.余额 != 70:
        return False, f"取(30) 之后余额应当是 70，实际是 {a.余额!r}。"
    return True, "取钱扣得对"


def CHECK_取钱不够(答案):
    """⚠⚠ 这一课最要紧的一条：失败时余额**一点都不变**。"""
    if not hasattr(答案, "存钱罐"):
        return False, "还没有定义「存钱罐」类。"
    a = 答案.存钱罐(100)
    得 = a.取(999)
    if 得 is not False:
        return False, f"钱不够时取(999) 应当返回 **False**，实际是 {得!r}。"
    if a.余额 != 100:
        return False, (f"⚠⚠ 取款失败之后余额**被改动了**：应当是 100，实际是 {a.余额!r}。\n"
                       f"      这就是这一课最要紧的一条。常见错法是**先扣再判断**：\n"
                       f"          self.余额 -= n          ← 已经扣了\n"
                       f"          if self.余额 < 0:\n"
                       f"              return False\n"
                       f"      正确顺序永远是：**先检查，通过才动**。\n"
                       f"          if n > self.余额:\n"
                       f"              return False        ← 什么都没动\n"
                       f"          self.余额 -= n")
    # 正好取光：不能用 >=
    b = 答案.存钱罐(120)
    得2 = b.取(120)
    if 得2 is not True or b.余额 != 0:
        return False, (f"正好取光（余额 120，取 120）应当成功、余额变 0；"
                       f"实际返回 {得2!r}、余额 {b.余额!r}。\n"
                       f"      ⚠ 边界要写 `if n > self.余额`（大于才拒绝），不能写 `>=`。")
    return True, "钱不够拒绝且余额不变 · 正好取光能成功"


def CHECK_外面改不到余额(答案):
    """⚠ 这条查「封装「有没有真的做到。"""
    if not hasattr(答案, "存钱罐"):
        return False, "还没有定义「存钱罐」类。"
    a = 答案.存钱罐(100)
    try:
        a.余额 = -999
    except AttributeError:
        return True, "余额是只读的 —— 外面改不到（封装做到了）"
    except Exception:                                           # noqa: BLE001
        return True, "余额改不动（封装做到了）"
    if a.余额 == -999:
        return False, ("外面能直接把 `.余额` 改成 -999 —— **封装没做到**。\n"
                       "      这一课要的正是「改数据必须走方法」：\n"
                       "          class 存钱罐:\n"
                       "              def __init__(self, 初值=0):\n"
                       "                  self._余额 = 初值        ← 下划线开头\n"
                       "              @property\n"
                       "              def 余额(self):              ← 读的时候走这里\n"
                       "                  return self._余额\n"
                       "      这样 `罐.余额` 能读，但**赋不了值** ——\n"
                       "      想改余额只能通过 存() / 取()，而它们会检查。")
    return True, "余额改不动（封装做到了）"
