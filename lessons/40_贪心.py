def CHECK_贪心找零(答案):
    f = 答案.__dict__.get('贪心找零')
    if not callable(f):
        return False, ('还没有定义「贪心找零」。写法：面额 sorted(零钱表, reverse=True)，\n'
                       '      逐个 张数 += 剩下 // 面额; 剩下 %= 面额；最后 剩下 == 0 才算成功。')
    for 币, 金额, 想 in (([1, 5, 10, 25], 63, 6), ([1, 5, 10, 25], 0, 0),
                        ([1, 5, 10, 25], 9999, 405), ([2], 3, -1), ([5, 10], 4, -1),
                        ([1], 7, 7), ([1, 3, 4], 6, 3)):
        try:
            得 = f(list(币), 金额)
        except Exception as e:                                  # noqa: BLE001
            return False, f'贪心找零({币}, {金额}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            提示 = ('（这一条要的是贪心的 3 张 = 4+1+1；算出 2 张说明用了枚举/DP）'
                    if (币 == [1, 3, 4] and 金额 == 6) else '')
            return False, (f'贪心找零({币}, {金额}) 应当是 {想} 张，得到 {得!r}。{提示}\n'
                           f'      ⚠ 面额从大到小拿；金额 0 是 0 张；凑不出返回 -1。')
    return True, '七组都对（含 0 元、凑不出、9999、以及贪心会错的 [1, 3, 4] 找 6）'


def CHECK_区间调度(答案):
    f = 答案.__dict__.get('区间调度')
    if not callable(f):
        return False, ('还没有定义「区间调度」。写法：按 x[1]（结束时间）排序，'
                       '记一个"上一个结束时间"，\n'
                       '      开始 >= 它 就选上，并把结束时间更新掉。')
    for 区间, 想 in (([], 0), ([(1, 10)], 1), ([(1, 2), (2, 3), (3, 4)], 3),
                    ([(1, 3), (2, 4), (3, 5)], 2), ([(1, 10), (2, 3), (3, 4), (4, 5)], 3),
                    ([(1, 2)] * 5, 1), ([(4, 5), (3, 4), (2, 3)], 3)):
        try:
            得 = f(list(区间))
        except Exception as e:                                  # noqa: BLE001
            return False, f'区间调度({区间}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'区间调度({区间}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 按**结束时间**排（不是开始时间）：[(1,10),(2,3),(3,4),(4,5)] 的答案\n'
                           f'        是 3，按开始排会把 (1,10) 选走只剩 1 个。首尾相接（3 和 3）算不冲突。')
    return True, '七组都对（含空表、单区间、首尾相接、逆序输入、全相同）'


def CHECK_选中的区间(答案):
    f = 答案.__dict__.get('选中的区间')
    if not callable(f):
        return False, '还没有定义「选中的区间」。写法：在 区间调度 里把选中的 (开始, 结束) 收集起来。'
    for 区间 in ([], [(1, 10)], [(1, 2), (2, 3), (3, 4)], [(1, 10), (2, 3), (3, 4), (4, 5)]):
        try:
            得 = list(f(list(区间)))
        except Exception as e:                                  # noqa: BLE001
            return False, f'选中的区间({区间}) 出错：{type(e).__name__}: {e}'
        剩 = [list(x) for x in 区间]
        for 段 in 得:
            if list(段) not in 剩:
                return False, f'选中的区间({区间}) 里有 {段}，但输入里没有这一段。'
            剩.remove(list(段))
        for i in range(1, len(得)):
            if 得[i][0] < 得[i - 1][1]:
                return False, (f'选中的区间({区间}) 里 {得[i-1]} 和 {得[i]} 重叠了。\n'
                               f'      ⚠ 上一个的结束 ≤ 下一个的开始，才叫不冲突。')
        比较 = 答案.__dict__.get('区间调度')
        期望个数 = 比较(list(区间)) if callable(比较) else len(得)
        if len(得) != 期望个数:
            return False, (f'选中的区间({区间}) 选了 {len(得)} 个，但 区间调度 得到 {期望个数} 个 —— '
                           f'两个函数要用同一套贪心。')
    return True, '四组都对（个数一致、两两不重叠、每一段都真的在输入里）'


def CHECK_贪心会错(答案):
    """这一课真正要考的一件事：贪心的答案 ≠ 最优答案。"""
    f = 答案.__dict__.get('贪心找零')
    if not callable(f):
        return False, '还没有定义「贪心找零」。'
    try:
        得 = f([1, 3, 4], 6)
    except Exception as e:                                      # noqa: BLE001
        return False, f'贪心找零([1, 3, 4], 6) 出错：{type(e).__name__}: {e}'
    if 得 != 3:
        return False, (f'贪心找零([1, 3, 4], 6) 是 {得!r}，这里要的是**贪心的结果 3**。\n'
                       f'      ⚠ 贪心：拿 4 ⇒ 剩 2 ⇒ 拿 1、1，共 3 张（4+1+1）。\n'
                       f'        最优是 3+3 = 2 张 —— 贪心在这里会输一张，这一课就是让你看清这件事。')
    return True, ('贪心给出 3 张（4+1+1），而最优是 2 张（3+3）—— 贪心会错，'
                  '所以用它之前必须给出理由或反例')
