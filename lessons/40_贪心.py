# ─────────────────────────────────────────────────────
#  先介绍：贪心就是不回头
# ─────────────────────────────────────────────────────
# 贪心是**每一步都选当前看起来最好的，选完不回头**。好处是又快又短，坏处是它经常是错的：
#     面额 [1, 5, 10, 25]，63 元 ⇒ 25+25+10+1+1+1 = 6 张      ✅ 这里它对了
#     面额 [1, 3, 4]，6 元     ⇒ 4+1+1 = 3 张，而 3+3 只要 2 张  ❌ 这里它错了
#
# ─────────────────────────────────────────────────────
#  一、找零：面额从大到小，能拿就拿
# ─────────────────────────────────────────────────────
#     def 贪心找零(零钱表, 金额):
#         剩下 = 金额
#         张数 = 0
#         for 面额 in sorted(零钱表, reverse=True):     ← ⚠ 必须先排好序
#             张数 += 剩下 // 面额
#             剩下 %= 面额
#         return 张数 if 剩下 == 0 else -1              ← 凑不出就 -1
#
#     贪心找零([1, 5, 10, 25], 63)  ⇒ 6 张     （25、25、10、1、1、1）
#     贪心找零([1, 5, 10, 25], 9999) ⇒ 405 张  （399 个 25 + 2 个 10 + 4 个 1）
#     贪心找零([2], 3)              ⇒ -1       （面额是 2，凑不出奇数）
#
# 人民币那种面额上贪心是对的，但这是**运气**不是规律 —— 见下面 [1, 3, 4]。
#
# ─────────────────────────────────────────────────────
#  二、区间调度：按「结束时间」排，先结束的先选
# ─────────────────────────────────────────────────────
# 题目：一堆活动都要用同一个教室，最多能安排几场？区间表 [(开始, 结束), …]，
# [1,3] 和 [3,5] 首尾相接**算**不冲突。贪心策略：**按结束时间从早到晚排**，能接上就选。
#
#     def 区间调度(区间表):
#         上一个结束 = None
#         数 = 0
#         for 开始, 结束 in sorted(区间表, key=lambda x: x[1]):    ← 按**结束**排
#             if 上一个结束 is None or 开始 >= 上一个结束:
#                 数 += 1
#                 上一个结束 = 结束
#         return 数
#
# 为什么按结束时间：**结束得越早，后面剩下的时间越多**。按「开始时间」排就会翻车：
#     [(1,10), (2,3), (3,4), (4,5)] 按开始排先选 (1,10)，之后一个也接不上 ⇒ 1 个；
#                                   正确答案是 (2,3)(3,4)(4,5)          ⇒ 3 个
#
# ─────────────────────────────────────────────────────
#  三、怎么知道贪心对不对
# ─────────────────────────────────────────────────────
# 没有万能办法，但有三条实用判据：
#     ① 能举出**反例** ⇒ 贪心一定是错的（找零 [1,3,4] 就是反例）
#     ② 能说清「这一步为什么不会吃亏」⇒ 多半对（区间调度：结束早 ⇒ 后面余地大）
#     ③ 拿小数据跟暴力/DP 对一遍（n ≤ 10 时枚举所有子集就能当标尺）
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：贪心不是万能的
# ─────────────────────────────────────────────────────
#     `贪心找零([1, 3, 4], 6)`
#     贪心：先拿最大的 4 ⇒ 剩 2 ⇒ 拿 1、1  ⇒  4+1+1 = **3 张**
#     最优：3 + 3 = **2 张**
#
# ⚠ 贪心给出的答案**看起来很合理**（都是先拿大面额），也不会报错，只是比最优多一张。
# ⇒ 所以「贪心找零」要你**就按贪心写**，别换成枚举/DP：先写对贪心，再看清它在哪出错；
#   真要最优解，金额小的时候用 DP（第 46 课会讲背包）。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
