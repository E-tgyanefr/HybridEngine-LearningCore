def CHECK_位数和原码(答案):
    if getattr(答案, "位数", None) != 8:
        return False, (f"先定义「位数」= 8（现在是 {getattr(答案, '位数', None)!r}）——"
                       f"这一课一律按 8 位算。")
    f = 答案.__dict__.get("原码")
    if not callable(f):
        return False, ("还没有定义函数「原码」。写法：\n"
                       "          def 原码(数):\n"
                       "              符号位 = '1' if 数 < 0 else '0'\n"
                       "              return 符号位 + format(abs(数), '07b')")
    for 数, 想 in ((5, "00000101"), (-5, "10000101"), (0, "00000000"),
                  (127, "01111111"), (-127, "11111111")):
        try:
            得 = f(数)
        except Exception as e:                                  # noqa: BLE001
            return False, f"原码({数}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"原码({数}) 应当是 {想!r}，得到 {得!r}。\n"
                           f"      ⚠ 原码 = **符号位**（负数写 1）后面接**绝对值**的二进制，\n"
                           f"        一共 8 位，不够就在前面补 0。")
    return True, "五组都对（含 0、含边界 ±127）"


def CHECK_补码(答案):
    f = 答案.__dict__.get("补码")
    if not callable(f):
        return False, ("还没有定义函数「补码」。两种写法都行：\n"
                       "          return format(数 & 0xFF, '08b')\n"
                       "        或者 正数照原码、负数「反码 + 1」")
    for 数, 想 in ((5, "00000101"), (-5, "11111011"), (0, "00000000"),
                  (-1, "11111111"), (127, "01111111"), (-127, "10000001")):
        try:
            得 = f(数)
        except Exception as e:                                  # noqa: BLE001
            return False, f"补码({数}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"补码({数}) 应当是 {想!r}，得到 {得!r}。\n"
                           f"      ⚠ 负数：先写原码 → 符号位不动、其余取反 → 最后 +1。\n"
                           f"        也可以一步到位：format(数 & 0xFF, '08b')")
    return True, "六组都对（含 0、-1、±127）"


def CHECK_补码转十进制(答案):
    f = 答案.__dict__.get("补码转十进制")
    if not callable(f):
        return False, ("还没有定义函数「补码转十进制」。写法：\n"
                       "          def 补码转十进制(文字):\n"
                       "              if 文字[0] == '1':\n"
                       "                  return int(文字, 2) - 256\n"
                       "              return int(文字, 2)")
    for 文字, 想 in (("00000101", 5), ("11111011", -5), ("00000000", 0),
                    ("10000001", -127), ("10000000", -128), ("01111111", 127)):
        try:
            得 = f(文字)
        except Exception as e:                                  # noqa: BLE001
            return False, f"补码转十进制({文字!r}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"补码转十进制({文字!r}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 最高位是 1 ⇒ 先把 8 位当正整数读，再**减去 256**\n"
                           f"        （256 = 2 的 8 次方，等于把符号位那一位的重量抵消掉）。")
    return True, "六组都对（含 -128 和 0）"


def CHECK_负五的补码值(答案):
    import io
    if not hasattr(答案, "负五的补码值"):
        return False, ("还没有定义「负五的补码值」。\n"
                       "      写法：负五的补码值 = -5 & 0xFF      ⇒ 251")
    得 = 答案.负五的补码值
    if 得 != 251:
        return False, (f"「负五的补码值」应当是 251（11111011 当无符号数读），现在是 {得!r}。\n"
                       f"      ⚠ 光写 -5 不行 —— 要的就是那 8 个格子里的 0/1 对应的数。")
    if hasattr(答案, "__file__"):
        源码 = io.open(答案.__file__, encoding="utf-8").read()
        i = 源码.find("负五的补码值")
        if "&" not in 源码[i:i + 60]:
            return False, ("值是对的，但这一课要你**用 & 算出来**：\n"
                           "      ⚠ 写法：负五的补码值 = -5 & 0xFF\n"
                           "        0xFF 就是「低 8 位全是 1」，& 一下等于截到 8 位。")
    return True, f"负五的补码值 = {得}（用 & 截到 8 位）"
