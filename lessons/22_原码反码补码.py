# ─────────────────────────────────────────────────────
#  先介绍：计算机里没有负号
# ─────────────────────────────────────────────────────
# 格子里只有 0 和 1，没有「负号」这个东西。要给负数找个位置，最省事的
# 办法是**拿最高位当符号位**：0 表示正、1 表示负。于是有了三种约定 ——
# 原码、反码、补码，算的都是「-5 这八个格子填什么」，但**只有补码能让
# 加减法直接算**，所以今天用的一律是补码。
# ─────────────────────────────────────────────────────
#  一、以 8 位为例：-5 的三种写法
# ─────────────────────────────────────────────────────
#   最高位是符号位，剩下 7 位放大小。+5 是 0000101，所以：
#    原码：符号位 + 大小          -5 ⇒ 1 0000101  ⇒ 10000101
#    反码：负数**符号位不动**，其余逐位取反
#                                -5 ⇒ 1 1111010  ⇒ 11111010
#    补码：反码 **+1**            -5 ⇒ 1 1111011  ⇒ 11111011
#   ⚠ 正数的三种写法**一模一样**（都是 00000101），只有负数要变。
# ─────────────────────────────────────────────────────
#  二、为什么最后用了补码：减法能当加法算
# ─────────────────────────────────────────────────────
#   用补码算 5 + (-5)：
#      00000101
#    + 11111011
#    ──────────
#    1 00000000     ← 最高位进上来的 1 **溢出丢掉**
#      00000000     ⇒ 0    ✅ 算对了
#   用原码算同一个式子会得到 10001010（也就是 -10）—— **全错**。
#   ⚠ 补码还有两个好处：
#    ① 0 只有一种写法（00000000）；原码里 00000000 和 10000000 都是 0
#    ② 不用为减法单独做一套电路：**减一个数 = 加它的补码**
# ─────────────────────────────────────────────────────
#  三、8 位补码能表示的范围
# ─────────────────────────────────────────────────────
#    00000000 ~ 01111111     ⇒   0 ~ 127
#    10000000 ~ 11111111     ⇒   -128 ~ -1
#   ⇒ 一共 256 个：**-128 ~ 127**。
#   ⚠ -128 没有对应的原码和反码（8 位原码最大只能写到 -127）——它是补码
#     比那两种表示法**多出来的**那个数。
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：Python 的整数没有位数
# ─────────────────────────────────────────────────────
#  Python 的整数是**无限位**的，所以 `~` 和 `bin()` 给的都不是 8 位补码：
#    bin(-5)      ⇒ '-0b101'     ← 前面是个负号，不是补码的形状
#    ~5           ⇒ -6           ← 取反是「-x-1」，不是 8 位反码
#    ~5 & 0xFF    ⇒ 250          ← 要**自己截到 8 位**，才是 11111010
#    -5 & 0xFF    ⇒ 251          ← 11111011，-5 的 8 位补码
#  ⇒ 记法：**要 8 位补码，就在最后 & 0xFF**（0xFF = 255 = 低 8 位全是 1）。
#    反过来，8 位补码要变回负数：最高位是 1 就**减去 256**。
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   只讲这三种表示法怎么算、为什么。真正的位运算（<< >> ^ |）用到再说。
