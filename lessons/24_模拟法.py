# ─────────────────────────────────────────────────────
#  先介绍：没有公式，只有过程
# ─────────────────────────────────────────────────────
# 有些题给的是一套**规则**：「先来的先办，一次办一个」「每秒走一格，到 60
# 就进位」。这类题没有公式可套，但很好写 —— 把规则翻成代码，让程序按同样的
# 顺序走一遍，走完答案自然就出来了。这就是模拟法。
# ─────────────────────────────────────────────────────
#  一、模拟排队：列表就是队列
# ─────────────────────────────────────────────────────
#   排队只有两件事：**新来的排到队尾**、**办业务的人从队首走**。
#    队伍 = ['小明']
#    队伍.append('小红')   ⇒ ['小明', '小红']  入队：加到**末尾**
#    队伍.pop(0)           ⇒ '小明'，队伍变 ['小红']（出队：从**队首**拿走）
#   ⚠ `append` + `pop(0)` 合起来才是队列（先来先办），两个都不能换。
# ─────────────────────────────────────────────────────
#  二、模拟钟表：一秒一秒地走
# ─────────────────────────────────────────────────────
#   时:分:秒 的进位规则：秒满 60 进 1 分，分满 60 进 1 时，时满 24 回到 0。
#    def 走一秒(时, 分, 秒):
#        秒 += 1
#        if 秒 == 60:          ← 秒满了，进到分
#            秒 = 0
#            分 += 1
#        if 分 == 60:          ← 分满了，进到时
#            分 = 0
#            时 += 1
#        if 时 == 24:          ← 时满了，回到 0
#            时 = 0
#        return 时, 分, 秒
#   ⚠ 三个 if 是**并列**的、从上到下走一遍；但**进位只写一半**就糟了：
#     少了 `分 += 1`，23:59:59 走过去会变成 23:59:00，而且**不报错**。
#   另一种写法是「合成总秒数，走完再拆开」（算走 n 秒时最省事，86400 = 一整天）：
#    总秒 = (时 * 3600 + 分 * 60 + 秒 + n) % 86400
#    时, 分, 秒 = 总秒 // 3600, 总秒 // 60 % 60, 总秒 % 60
# ─────────────────────────────────────────────────────
#  三、动手前先想清三件事
# ─────────────────────────────────────────────────────
#   ① **状态**：什么在变？（队伍、时间、余额）　② **一步**：一次变化是
#      什么？（一个人办完、时间过了一秒）　③ **走几步**：重复多少、何时停？
#   ⚠ 先把这三条写清楚再动手，比边写边想快得多。
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：pop() 少了那个 0
# ─────────────────────────────────────────────────────
#   队伍 = ['小明', '小红', '小刚']
#   队伍.pop()      ⇒ '小刚'     ← ⚠ 拿的是**队尾**！排队变成了插队
#   队伍.pop(0)     ⇒ '小明'     ← 队首先办，这才对
#  ⚠ 更糟的是它**不报错**，只是顺序反了；队伍空了还取才报：
#   [].pop(0)  ❌ IndexError: pop from empty list
#  ⇒ 记法：**排队用 pop(0)，那个 0 不能省**；不确定空不空就先 `if 队伍:`。
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   只讲「按规则一步步走」。多人多窗口、随机事件那种复杂模拟用到再说。
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
