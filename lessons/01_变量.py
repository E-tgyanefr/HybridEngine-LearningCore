# ─────────────────────────────────────────────────────
#  先介绍：变量是什么
# ─────────────────────────────────────────────────────
#
# 变量就是「**给一个值起个名字**」。
#
#     名字 = 「小明」
#     ↑     ↑
#     名字   值
#
# 那个等号不是数学里的「相等」，是「**把右边的值装进左边的名字里**」。
# 读作「把 「小明」 赋给 名字」。
#
# ⚠ 起名字的意义在于**后面能重复使用**：
#
#     名字 = 「小明」
#     print(名字)            ← 用到它，不用重打一遍
#     print(名字 + "你好")    ← 还能拼起来
#
# 如果不起名字，你就得每次重打一遍 「小明」 ——
# 改的时候要改好几个地方，漏一处就错了。
#
# ─────────────────────────────────────────────────────
#  变量名怎么起
# ─────────────────────────────────────────────────────
#
#     年龄 = 18           ✅ 中文也行（Python 3 支持）
#     age = 18            ✅ 英文最常见
#     2号 = 18            ❌ 不能以数字开头
#     我的 名字 = 18       ❌ 不能有空格
#
#   ⚠ 大小写敏感：`名字` 和 `名字 ` 不是一回事，`Name` 和 `name` 也是两个变量。
#
# ─────────────────────────────────────────────────────
#  ⚠ 最常见的错：字符串忘了引号
# ─────────────────────────────────────────────────────
#
#     名字 = 小明          ❌ NameError: name '小明' is not defined
#     名字 = 「小明」        ✅
#
#   Python 看到 `小明` 不带引号，会以为你在说「一个叫小明的变量」，
#   然后去找 —— 找不到就报 `NameError: name '小明' is not defined`。
#
#   ⇒ **错误信息里说 "name ... is not defined" 时，先看引号。**
#     这是新手第一个必踩的坑，也是这一课唯一要记住的坑。
#
# ─────────────────────────────────────────────────────
