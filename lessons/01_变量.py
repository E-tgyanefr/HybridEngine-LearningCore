def CHECK_我的名字(答案):
    if not hasattr(答案, "我的名字"):
        return False, ("还没有定义「我的名字」。\n"
                       "      写法：我的名字 = '小明'        ← 名字要加引号\n"
                       "      ⚠ 不加引号会报 NameError: name '小明' is not defined")
    v = 答案.我的名字
    if not isinstance(v, str):
        return False, (f"「我的名字」应当是**文字**（用引号括起来），现在是 {type(v).__name__}。\n"
                       f"      写法：我的名字 = '小明'\n"
                       f"      ⚠ 引号不能少 —— 少了 Python 会去找一个叫这个名字的变量。")
    if not v.strip():
        return False, "「我的名字」是空的 —— 写个真名字进去。"
    if len(v) > 40:
        return False, f"「我的名字」有 {len(v)} 个字符，太长了 —— 写个名字就行。"
    return True, f"我的名字 = {v!r}"


def CHECK_我的年龄(答案):
    if not hasattr(答案, "我的年龄"):
        return False, ("还没有定义「我的年龄」。\n"
                       "      写法：我的年龄 = 18          ← 整数**不要**引号\n"
                       "      ⚠ 写成 '18' 会是文字，不能拿来做算术（第 03 课会讲）。")
    v = 答案.我的年龄
    if isinstance(v, bool) or not isinstance(v, int):
        if isinstance(v, str):
            return False, (f"「我的年龄」现在是文字 {v!r} —— **把引号去掉**。\n"
                           f"      写法：我的年龄 = 18\n"
                           f"      ⚠ '18'（带引号）是文字，18（不带）才是数字。")
        return False, (f"「我的年龄」应当是整数，现在是 {type(v).__name__}。\n"
                       f"      写法：我的年龄 = 18")
    if not (0 < v < 200):
        return False, f"「我的年龄」是 {v} —— 这不像一个年龄。"
    return True, f"我的年龄 = {v}"
