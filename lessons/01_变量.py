def CHECK_名字变量(答案):
    if not hasattr(答案, "名字"):
        return False, "还没有定义「名字」这个变量。\n写法：名字 = \"你的名字\""
    v = 答案.名字
    if not isinstance(v, str):
        return False, (f"「名字」应该是文字（用引号括起来），但它现在是 {type(v).__name__}。\n"
                       f"实际值：{v!r}\n"
                       f"改法：名字 = \"{v}\"   ← 加上引号")
    if not v.strip():
        return False, "「名字」是空的。放个真实的字符串进去，比如 名字 = \"小明\""
    return True, f"名字 = {v!r}"


def CHECK_年龄变量(答案):
    if not hasattr(答案, "年龄"):
        return False, "还没有定义「年龄」这个变量。\n写法：年龄 = 18"
    v = 答案.年龄
    if isinstance(v, bool):
        return False, "「年龄」不应该是 True/False。放一个整数，比如 年龄 = 18"
    if not isinstance(v, int):
        return False, (f"「年龄」应该是整数（不要引号），但它现在是 {type(v).__name__}。\n"
                       f"实际值：{v!r}\n"
                       f"改法：年龄 = 18     ← 去掉引号\n"
                       f"（如果写成 年龄 = \"18\"，那是文字不是数字）")
    return True, f"年龄 = {v}"


def CHECK_打招呼函数存在(答案):
    if not hasattr(答案, "打招呼"):
        return False, "还没有定义「打招呼」这个函数。\n写法：\n    def 打招呼():\n        return ..."
    f = 答案.打招呼
    if not callable(f):
        return False, "「打招呼」存在，但它不是函数（是个变量？）。\n要用 def 定义：def 打招呼():"
    return True, "打招呼 是个函数"


def CHECK_打招呼能调用(答案):
    if not hasattr(答案, "打招呼"):
        return False, "还没有定义「打招呼」函数"
    try:
        out = 答案.打招呼()
    except Exception as e:                            # noqa: BLE001
        return False, (f"调用 打招呼() 时出错了：{type(e).__name__}: {e}\n"
                       f"检查一下函数体里有没有写错变量名。")
    if not isinstance(out, str):
        return False, (f"打招呼() 应该返回一句话（文字），但它返回了 {type(out).__name__}。\n"
                       f"实际返回：{out!r}\n"
                       f"改法：用 return 返回一个字符串，而不是 print")
    return True, f"返回：{out!r}"


def CHECK_打招呼用到变量(答案):
    """这一条才是重点：句子必须**跟着两个变量一起变**，而不是只跟着名字。

    ⚠ 审查发现过一个漏洞：原来只替换「名字」，不替换「年龄」。
      于是 `return f"你好，{名字}！我今年 18 岁。"`（年龄写死）能拿满分 ——
      而课程第 7 行明写「要真的用上面两个变量」。
      只验证一半就宣布通过，等于那一半白学。
    """
    if not hasattr(答案, "打招呼"):
        return False, "需要先有「打招呼」函数"
    if not (hasattr(答案, "名字") and hasattr(答案, "年龄")):
        return False, "需要先有「名字」和「年龄」两个变量"

    try:
        原句 = 答案.打招呼()
    except Exception:                                 # noqa: BLE001
        return False, "打招呼() 调用失败，先让它能正常返回"

    原名, 原龄 = 答案.名字, 答案.年龄
    # 两个都换成**明显不同**的值，这样任何一处写死都会露出来
    测试名, 测试龄 = "测试用名字_zzz", 999
    try:
        答案.名字 = 测试名
        答案.年龄 = 测试龄
        换过之后 = 答案.打招呼()
    except Exception as e:                            # noqa: BLE001
        return False, f"换掉变量之后再调用就出错了：{type(e).__name__}: {e}"
    finally:
        答案.名字, 答案.年龄 = 原名, 原龄

    问题 = []
    if 测试名 not in str(换过之后):
        问题.append("名字")
    if str(测试龄) not in str(换过之后):
        问题.append("年龄")

    if not 问题:
        return True, "句子会跟着「名字」和「年龄」一起变 —— 两个变量都真的用上了"

    用到的 = "「名字」和「年龄」" if len(问题) == 2 else f"「{问题[0]}」"
    没变的 = "、".join(f"「{x}」" for x in 问题)
    return False, (
        f"打招呼() 返回的句子**不跟着{没变的}变** —— 说明这个(些)值被写死在句子里了。\n"
        f"      我把「名字」改成 {测试名!r}、「年龄」改成 {测试龄}，\n"
        f"      期望句子里出现这两样东西，但实际返回的是：\n"
        f"          {换过之后!r}\n"
        f"      改法：用 f-string 把{用到的}都放进句子：\n"
        f'          return f"你好，{{名字}}！我今年 {{年龄}} 岁。"\n'
        f"          注意前面的 f 不能少。")


def CHECK_打招呼格式(答案):
    if not (hasattr(答案, "打招呼") and hasattr(答案, "名字") and hasattr(答案, "年龄")):
        return False, "需要先有「名字」「年龄」两个变量和「打招呼」函数"
    try:
        out = 答案.打招呼()
    except Exception:                                 # noqa: BLE001
        return False, "打招呼() 调用失败"
    want = f"你好，{答案.名字}！我今年 {答案.年龄} 岁。"
    if out != want:
        return False, (f"格式不太一样。\n"
                       f"期望：{want!r}\n"
                       f"实际：{out!r}\n"
                       f"对照一下标点：逗号、感叹号、句号都要和上面一致。")
    return True, "格式正确"
