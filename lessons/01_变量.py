# 要做：
#   1. 定义一个变量 名字，里面放你自己的名字（用引号括起来，因为那是文字）
#   2. 定义一个变量 年龄，里面放一个整数（不要引号）
#   3. 写一个函数 打招呼()，返回一句话，格式是：你好，<名字>！我今年 <年龄> 岁。
#      要真的用上面两个变量，而不是把名字硬写死在句子里。

# ─────────────────────────────────────────────────────
#  为什么会这样要求
# ─────────────────────────────────────────────────────
#
# 变量就是"给一个值起个名字"。起名字的意义在于**后面能重复使用**：
#
#     名字 = "小明"          ← 把 "小明" 这个名字叫「名字」
#     print(名字)            ← 用到它，不用重打一遍
#     print(名字 + "你好")    ← 还能拼起来
#
# 为什么第 3 条要求"真的用变量"：
#     把句子写死成 return "你好，小明！..." 也能通过输出，但那样改个名字就要改整句。
#     用变量的话，改一处（名字 = "小红"）整句话就跟着变了 ——
#     这才是变量存在的**理由**，也是这一课真正要学的东西。
#
# 关于引号：Python 里文字必须加引号。
#     "小明"  是文字
#     小明    是变量名（会被拿去查有没有定义过）
# 这是新手最容易混的一点，也是 NameError 的头号来源。
#
# 关于 f-string（把变量放进句子里的写法）：
#     f"你好，{名字}！"
#      ↑ 这个 f 不能少，少了就变成普通文字，{名字} 会原样打出来
#     详见 第 01 课的答案文件；这是本课唯一的新语法。

