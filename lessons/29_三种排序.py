def CHECK_是排好的(答案):
    f = 答案.__dict__.get("是排好的")
    if not callable(f):
        return False, ("还没有定义函数「是排好的」。\n"
                       "      写法：def 是排好的(表):\n"
                       "               for i in range(len(表) - 1):\n"
                       "                   if 表[i] > 表[i + 1]:\n"
                       "                       return False\n"
                       "               return True")
    for 表, 想 in (([], True), ([5], True), ([1, 2, 3], True), ([2, 2, 2], True),
                  ([1, 3, 2], False), ([3, 2, 1], False), ([-5, -1, 0], True)):
        try:
            得 = f(list(表))
        except Exception as e:                              # noqa: BLE001
            return False, f"是排好的({表!r}) 出错了：{type(e).__name__}: {e}"
        if bool(得) != 想:
            return False, (f"是排好的({表!r}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 边界想清楚：空表、单元素表都算「排好的」；\n"
                           f"        相等的相邻元素（2, 2）也算排好 —— 判断要用 `>`，不是 `>=`。")
    return True, "七组都对（空表 / 单元素 / 有序 / 全相等 / 乱序 / 逆序 / 负数）"


