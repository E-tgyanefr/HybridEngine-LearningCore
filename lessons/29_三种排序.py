# ─────────────────────────────────────────────────────
#  先约定一件事：这一课是「就地排」
# ─────────────────────────────────────────────────────
#
# 三个函数都要求：**直接改传进来的那个表**，最后把它 return 出去。
#
#     def 某某排序(表):
#         表[i], 表[j] = 表[j], 表[i]        ← 就地改
#         return 表                          ← 顺手交出来，方便链式使用
#
# ⚠ 第 26 课说过：列表传进函数，函数里改了外面也变 —— 这一课正好用上它。
#
# ─────────────────────────────────────────────────────
#  一、选择排序：每一轮挑出最小的，换到前面
# ─────────────────────────────────────────────────────
#
# 拿 [5, 2, 9, 1, 7] 走一遍：
#
#     第 1 轮：在 0~4 号里找最小的（1，在 3 号），和 0 号换 → [1, 2, 9, 5, 7]
#     第 2 轮：在 1~4 号里找最小的（2，已经在 1 号）→ 不变
#     第 3 轮：在 2~4 号里找最小的（5，在 3 号），和 2 号换 → [1, 2, 5, 9, 7]
#     第 4 轮：在 3~4 号里找最小的（7，在 4 号），和 3 号换 → [1, 2, 5, 7, 9]
#
#     def 选择排序(表):
#         n = len(表)
#         for i in range(n - 1):              ← 最后一个自然就位，不用挑
#             最小 = i                        ← 先假定 i 号最小
#             for j in range(i + 1, n):       ← 只在 i **后面**找
#                 if 表[j] < 表[最小]:
#                     最小 = j                ← 记住位置，先不换（少换几次）
#             表[i], 表[最小] = 表[最小], 表[i]
#         return 表
#
# 为什么一定对：**每轮结束时，前 i+1 格放的正好是最小的 i+1 个数**。
# 于是第 n-1 轮结束时（只剩最后一格），整个表就排好了。
#
# ─────────────────────────────────────────────────────
#  二、冒泡排序：相邻两个比，大的往后冒
# ─────────────────────────────────────────────────────
#
# 一趟（i=0）走完，最大的那个一定被顶到最后一格 —— 像气泡浮上来。
#
#     def 冒泡排序(表):
#         n = len(表)
#         for i in range(n - 1):                  ← 最多 n-1 趟
#             换过 = False
#             for j in range(n - 1 - i):          ← 尾巴那 i 格已经排好，不比了
#                 if 表[j] > 表[j + 1]:           ← 前面比后面大 ⇒ 换
#                     表[j], 表[j + 1] = 表[j + 1], 表[j]
#                     换过 = True
#             if not 换过:                        ← 一整趟都没换 ⇒ 已经有序，收工
#                 break
#         return 表
#
# 为什么一定对：每趟都把「还没排好的部分」里最大的那个顶到末尾，
# 而末尾那些格子**再也不会被碰**（`n - 1 - i` 保证了这点）。
#
# ⚠ `换过` 那三行是「提前收工」：本来就有序的表，一趟就结束（O(n)）。
#   删掉它们程序照样对，只是有序数据也要白跑 n-1 趟。
#
# ─────────────────────────────────────────────────────
#  三、插入排序：像整理手里的扑克牌
# ─────────────────────────────────────────────────────
#
# 摸到一张新牌，就把它插进左边那把**已经排好的牌**里：
#
#     def 插入排序(表):
#         for i in range(1, len(表)):
#             要插的 = 表[i]                       ← 摸到的新牌
#             j = i - 1
#             while j >= 0 and 表[j] > 要插的:
#                 表[j + 1] = 表[j]                ← 比它大的都往右挪一格
#                 j -= 1
#             表[j + 1] = 要插的                   ← 空出来的位置就是它的
#         return 表
#
# 为什么一定对：进入第 i 轮之前，`表[0..i-1]` 已经是排好的；
# 把 表[i] 插到它该在的位置后，`表[0..i]` 也排好了 —— 一轮扩一格。
#
# ⚠ `while j >= 0 and …` 里的 `j >= 0` **不能省**！
#   少写了它，j 会变成 -1，而 Python 里 `表[-1]` 是**最后一个元素**（不报错），
#   于是程序悄悄算错。这是三种排序里最阴的一个 bug。
#
# ─────────────────────────────────────────────────────
#  四、三种排一起比一比
# ─────────────────────────────────────────────────────
#
#     算法     怎么想的          比较次数              什么情况最划算
#     ──────  ──────────────  ───────────────────  ──────────────────
#     选择    每轮挑最小        总是 n(n-1)/2 次      交换次数最少（最多 n-1 次）
#     冒泡    相邻两个换        最坏 n(n-1)/2，最好 n 本来就有序时最快
#     插入    摸牌插进去        最坏 n(n-1)/2，最好 n-1 数据接近有序时极快
#
# ⚠ 三个都是 **O(n²)**：比较次数随 n 的平方涨。
#
#     n = 10     ⇒ 约 45 次        几乎瞬间
#     n = 1000   ⇒ 约 50 万次      约 0.02 秒
#     n = 100000 ⇒ 约 50 亿次      几分钟
#
# 所以数据一大就该用自带的 `sorted`（它是 O(n log n)，同样 10 万个数只要零点几秒）。
# 手写三种排序是为了**懂**，不是为了替代 `sorted`。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：内层循环的边界多写一格 ⇒ 越界
# ─────────────────────────────────────────────────────
#
#     for j in range(n):            ← 想写 n-1，写成了 n
#         if 表[j] > 表[j + 1]:
#
# 当 j = n-1 时，`表[j + 1]` 就是 `表[n]` —— 没有这一格：
#
#     ⇒ IndexError: list index out of range
#
# ⚠ 边界是这一课最容易错的地方，每个循环都数一遍最大下标：
#
#     选择：内层 `range(i + 1, n)`，用 表[j]，最大下标 n-1 ✅
#     冒泡：内层 `range(n - 1 - i)`，用 表[j + 1]，最大下标 n-1 ✅
#     插入：`while j >= 0`，用 表[j]，最小下标 0 ✅
#
#   ⚠ 反过来「少减 1」不会报错，只是白比几趟 —— 报错的那个反而好查。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   快排、归并、堆排序、`sorted` 内部怎么实现的、稳定性 —— 前三个在五级，
#   稳定性是下一课（第 30 课）的事。这一课只讲这三段代码和它们的边界。
