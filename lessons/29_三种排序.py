排序测试组 = ([3, 1, 2], [], [5], [4, 4, 1], [-1, -7, 0], [9, 8, 7, 6, 5, 4, 3, 2, 1])


def _验一个排序(答案, 函数名):
    """三件事一起验：结果对（有序 + 元素没丢）、就地改了、返回的不是 None。"""
    f = 答案.__dict__.get(函数名)
    if not callable(f):
        return False, (f"还没有定义函数「{函数名}」。\n"
                       f"      三段模板在课程文件里，抄下来先跑通再改。")
    for 原表 in 排序测试组:
        表 = list(原表)
        想 = sorted(原表)
        try:
            得 = f(表)
        except IndexError:
            return False, (f"{函数名}({原表!r}) 报了 IndexError —— 下标越界了。\n"
                           f"      ⚠ 逐个数一遍内层循环的最大下标：\n"
                           f"         · 用 表[j + 1] 的话，j 最大只能到 len(表) - 2\n"
                           f"         · 冒泡的内层是 range(n - 1 - i)，不是 range(n)")
        except Exception as e:                              # noqa: BLE001
            return False, f"{函数名}({原表!r}) 出错了：{type(e).__name__}: {e}"
        if 得 is None:
            return False, (f"{函数名}({原表!r}) 返回了 None —— 写完忘了 `return 表`。\n"
                           f"      ⚠ 就地排完，最后一行要 `return 表`。")
        if not isinstance(得, list):
            return False, (f"{函数名}({原表!r}) 返回的是 {type(得).__name__}：{得!r}，"
                           f"应当返回列表（就地把表排好后 `return 表`）。")
        if sorted(得) != 想 or len(得) != len(想):
            return False, (f"{函数名}({原表!r}) 的结果是 {得!r}，应当是 {想!r}。\n"
                           f"      ⚠ 元素**不能丢也不能多**。交换时最常见的错法：\n"
                           f"          表[j] = 表[j + 1]\n"
                           f"          表[j + 1] = 表[j]      ← 这样两个格子会变成同一个值\n"
                           f"        正确写法是一行搞定：表[j], 表[j + 1] = 表[j + 1], 表[j]")
        if 得 != 想:
            return False, (f"{函数名}({原表!r}) 的结果是 {得!r}，顺序不对，应当是 {想!r}。")
        if 表 != 想:
            return False, (f"{函数名}({原表!r}) 返回的列表是对的，"
                           f"但**传进来的那个表**还是 {表!r}。\n"
                           f"      ⚠ 这一课要求「就地排」：直接改传进来的表，"
                           f"而不是造一个新的返回。")
    return True, "六组全对（乱序 / 空 / 单个 / 重复 / 负数 / 逆序），而且真的就地排了"


