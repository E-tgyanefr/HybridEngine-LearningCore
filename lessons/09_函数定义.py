# ─────────────────────────────────────────────────────
#  先介绍：为什么要打包
# ─────────────────────────────────────────────────────
#
# 假设你要算三次平均分，就得把同样的几行抄三遍：
#
#     和 = 0
#     for x in 成绩1: 和 += x
#     平均1 = 和 / len(成绩1)
#
#     # ... 又抄一遍 ... 又抄一遍 ...
#
# 抄三遍的问题不是「打字数多」，而是**改的时候要改三处** ——
# 漏一处就出 bug。而且三个月后你看到这段代码，得重新读一遍才知道它在干嘛。
#
# 函数把这几行**打包**并**起个名字**：
#
#     def 算平均(分数表):
#         和 = 0
#         for x in 分数表:
#             和 += x
#         return 和 / len(分数表)
#
# 以后只要写 `算平均(成绩1)` —— 一眼就知道在做什么。
#
# ─────────────────────────────────────────────────────
#  def 的四个部分
# ─────────────────────────────────────────────────────
#
#     def  算平均  (  分数表  ):
#      ↑      ↑        ↑      ↑
#    关键字  函数名   参数    冒号不能少
#
#     函数体要**缩进**（和 if / for 一样，4 个空格）
#
# ─────────────────────────────────────────────────────
#  参数：把外面的东西递进去
# ─────────────────────────────────────────────────────
#
#     def 加一(数):
#         return 数 + 1
#
#     加一(5)        ⇒  6          这里的 5 会装进 `数`
#
#   ⚠ 参数名（`数`）和调用时传的东西（`5`）是**两回事**：
#     参数名只在函数**里面**有效，外面看不见。
#
#   ⚠ 参数个数要对上：
#         加一()         ❌ TypeError: 加一() missing 1 required positional argument
#         加一(5, 6)     ❌ TypeError: takes 1 positional argument but 2 were given
#     报这类 `TypeError` 时，数一数参数个数。
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课唯一要记住的坑：光定义不会执行
# ─────────────────────────────────────────────────────
#
#     def 打招呼():
#         print("你好")
#
#     # 到这里，程序**什么都没打印** —— 你只是"教"了 Python 一个新动作，
#     # 还没让它做。
#
#     打招呼()        ← 这一行才是「让它做」
#
#   ⇒ 现象：定义了一堆函数，跑起来什么输出都没有。
#     原因永远是：**忘了调用**（没写那一对括号）。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   `return`（把结果交出来）是第 10 课。这一课的函数可以先只做动作、
#   或者在最后用 print 把结果打出来 —— 不用 return。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 写函数 打招呼()：打印两行
#          你好
#          我在学 Python
#   2. **调用它一次**（检查会看你有没有真的调用）
#
#   ⚠ 就这两条。不用 return、不用参数 —— 那是第 10、11 课。
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 09


def _跑文件(答案):
    import io
    import contextlib
    import runpy
    buf = io.StringIO()
    try:
        with contextlib.redirect_stdout(buf):
            runpy.run_path(str(答案.__file__), run_name="__答题__")
    except Exception as e:                                      # noqa: BLE001
        return None, f"运行你的代码时出错了：{type(e).__name__}: {e}"
    return [l for l in buf.getvalue().split("\n") if l.strip()], None


def CHECK_定义了打招呼(答案):
    if not hasattr(答案, "打招呼"):
        return False, ("还没有定义「打招呼」函数。\n"
                       "      写法：\n"
                       "          def 打招呼():\n"
                       "              print('你好')\n"
                       "              print('我在学 Python')\n"
                       "      ⚠ def 那一行末尾的**冒号**不能少，函数体要**缩进**。")
    if not callable(答案.打招呼):
        return False, "「打招呼」不是函数。"
    return True, "打招呼 是个函数"


def CHECK_两行都打印了(答案):
    """⚠ 核心判据：既要有定义，也要**真的调用**。"""
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    if not hasattr(答案, "打招呼"):
        return False, "还没有定义「打招呼」函数。"
    行, 错 = _跑文件(答案)
    if 错:
        return False, 错
    if not 行:
        return False, ("你的文件一行都没打印 —— **最可能的原因是忘了调用**。\n"
                       "      ⚠⚠ `def 打招呼():` 只是「教」Python 一个新动作，\n"
                       "         它自己不会跑。要另外写一行：\n"
                       "             打招呼()\n"
                       "         注意那一对括号 —— 它们就是「执行「的意思。")
    if "你好" not in 行[0]:
        return False, f"第一行应当是「你好」，实际是 {行[0]!r}。"
    if len(行) < 2 or "我在学 Python" not in 行[1]:
        return False, (f"第二行应当是「我在学 Python」，实际是 "
                       f"{行[1] if len(行) > 1 else '（没有第二行）'!r}。\n"
                       f"      ⚠ 两行 print 都要在函数体里（**缩进** 4 个空格）。")
    return True, "调用后打印了两行"


def CHECK_真的调用了(答案):
    import io
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    # 找函数体之外的 `打招呼()` 调用
    行们 = 源码.split("\n")
    在函数里 = False
    调用过 = False
    for l in 行们:
        if l.startswith("def 打招呼"):
            在函数里 = True
            continue
        if 在函数里 and l and not l[0].isspace() and not l.startswith("#"):
            在函数里 = False
        if not 在函数里 and "打招呼()" in l and not l.strip().startswith("#"):
            调用过 = True
    if not 调用过:
        return False, ("没有看到调用「打招呼()」。\n"
                       "      ⚠ 定义（def）和调用（写一行 打招呼()）是两件事，\n"
                       "        少了调用，程序什么都不会做。")
    return True, "确实调用了"
