def _全源最短路(图, 起点):
    点们 = sorted(图)
    序 = {点: i for i, 点 in enumerate(点们)}
    n = len(点们)
    距 = [[float("inf")] * n for _ in range(n)]
    for i in range(n):
        距[i][i] = 0
    for 点 in 图:
        for 邻, 权 in 图[点]:
            距[序[点]][序[邻]] = min(距[序[点]][序[邻]], 权)
    for k in range(n):
        for i in range(n):
            for j in range(n):
                if 距[i][k] + 距[k][j] < 距[i][j]:
                    距[i][j] = 距[i][k] + 距[k][j]
    return {点: 距[序[起点]][序[点]] for 点 in 点们}


def CHECK_最短路(答案):
    f = 答案.__dict__.get("最短路")
    if not callable(f):
        return False, ("还没有定义「最短路」。要点：最短 = {点: inf}、起点改 0；堆里放 "
                       "(距离, 点)，出堆后用 距离[点] + 权 去更新邻居")
    for 图, 起点, 想 in 用例们:
        try:
            得 = f(图, 起点)
        except Exception as e:                                  # noqa: BLE001
            return False, f"最短路({图}, {起点!r}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            错点 = [点 for 点 in 想 if not isinstance(得, dict) or 得.get(点) != 想[点]]
            return False, (f"从 {起点} 出发：{错点} 这几个点的距离不对。应当是 {想}，"
                           f"得到 {得}｜走不到的点要写 float('inf')（不是 -1 / 0 / 999999），"
                           f"而且每个点都要在字典里")
    return True, "6 组都对（含单点、0 条边、有环、平行边、走不到的点）"


def CHECK_和Floyd一致(答案):
    f = 答案.__dict__.get("最短路")
    if not callable(f):
        return False, "还没有定义「最短路」函数。"
    for 图, 起点, _ in 用例们:
        try:
            得 = f(图, 起点)
        except Exception as e:                                  # noqa: BLE001
            return False, f"最短路({图}, {起点!r}) 出错：{type(e).__name__}: {e}"
        想 = _全源最短路(图, 起点)
        if 得 != 想:
            错点 = [点 for 点 in 想 if not isinstance(得, dict) or 得.get(点) != 想[点]]
            return False, (f"从 {起点} 出发：{错点} 的距离和 Floyd 暴力算出来的不一样。\n"
                           f"      应当是 {想}，得到 {得}")
    return True, "6 张图都和 Floyd（三重循环的暴力算法）的结果一模一样"


