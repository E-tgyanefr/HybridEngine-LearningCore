def CHECK_朴素最短路(答案):
    f = 答案.__dict__.get("朴素最短路")
    if not callable(f):
        return False, ("还没有定义「朴素最短路」。要点：先把所有边收成一个列表，再重复 "
                       "len(图)-1 轮：每轮扫所有边，能松弛就松弛")
    无穷 = float("inf")
    for 图, 起点, 想 in (({"A": [("B", 2), ("C", 3)], "B": [], "C": [("B", -2)]}, "A",
                       {"A": 0, "B": 1, "C": 3}),
                      ({"A": [("B", 1)], "C": [("D", 1)], "B": [("C", 1)], "D": []}, "A",
                       {"A": 0, "B": 1, "C": 2, "D": 3}),
                      ({"A": [], "B": []}, "A", {"A": 0, "B": 无穷}),
                      ({"A": [("B", 5)], "B": [("C", -3)], "C": [("D", 1)], "D": []}, "A",
                       {"A": 0, "B": 5, "C": 2, "D": 3}),
                      ({"A": [], "B": []}, "B", {"A": 无穷, "B": 0})):
        try:
            得 = f(图, 起点)
        except Exception as e:                                  # noqa: BLE001
            return False, f"朴素最短路({图}, {起点!r}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"朴素最短路({图}, {起点!r}) 应当是 {想}，得到 {得}｜"
                           f"A→B 直接走 2，绕 A→C→B 是 3-2 = **1**，答案是 1；"
                           f"而且只扫一轮不够（C 排在 B 前面时，第一轮还用不上 B 的结果），"
                           f"要扫 len(图)-1 轮")
    return True, "5 组都对（含负边、边序不巧要多扫几轮、不可达、单点）"
