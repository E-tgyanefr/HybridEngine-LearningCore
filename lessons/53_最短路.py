# ─────────────────────────────────────────────────────
#
# 第 49 课的图只问「连不连得通」。现在每条边带一个**权**（距离、时间、花费），问的是
# 「从起点到每个点最少要走多少」：
#     图 = {'A': [('B', 1), ('C', 4)], 'B': [('C', 2), ('D', 5)],
#           'C': [('D', 1)], 'D': []}    ← A─1─B、A─4─C、B─2─C、B─5─D、C─1─D
#
# 从 A 出发的答案：A=0、B=1、C=3（走 B 更近）、D=4（走 C 更近）。
# 格式是 {点: [(邻居, 权), ...]}，⚠ 每个点都要有键，没有出边的点写空列表。
#
# ─────────────────────────────────────────────────────
#  一、Dijkstra：每次都从「当前最近的点」往外扩
# ─────────────────────────────────────────────────────
#
#     ① 起点距离 0，其余全是 ∞
#     ② 取出「还没定下来、距离最小」的点 u
#     ③ 用 u 更新它的邻居：如果 距离[u] + 权 < 距离[邻居]，就把邻居改小
#     ④ 重复 ②③，直到所有点都定下来
# 拿上面的图走一遍：A 定 0 → 更新 B=1、C=4 → 取 B 定 1 → 更新 C=3、D=6 → 取 C 定 3 →
# 更新 D=4 → 取 D 定 4。 答案就是 0、1、3、4。② 用列表找最小是每轮 O(n)，用小根堆快得多。
#
# ─────────────────────────────────────────────────────
#  二、为什么不能处理负边
# ─────────────────────────────────────────────────────
#
# Dijkstra 有一条**假设**：一个点一旦被取出来，它的距离就不会再变小了。负边打破它：
#     A → B 权 2、A → C 权 3、C → B 权 -2
#     堆里先弹出 B（距离 2），按假设「B 就是 2 了」；可绕一下 C 只要 3 - 2 = 1！
#
# ⇒ 有负边就得换算法：**朴素最短路**（Bellman-Ford）把每条边反复松弛 V-1 轮，
#   慢一些（O(V×E)）但负边也能算对。这一课给你测的图都是非负权，负边只做演示。
# ─────────────────────────────────────────────────────
#  三、堆怎么用（heapq）
# ─────────────────────────────────────────────────────
#
#     import heapq
#     heapq.heappush(堆, (距离, 点))     ← 堆里放 (距离, 点) 这种元组
#     距离, 点 = heapq.heappop(堆)      ← 每次拿出来的都是距离最小的
# ⚠ 一个点可能被**重复放进堆**（距离更新一次就放一次）。出堆时先看一眼：
#     if 距离 > 最短[点]: continue      ← 过期的记录，跳过
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：不可达的点写成了 -1 或者 0
# ─────────────────────────────────────────────────────
#
# 有的点根本走不到，这时距离是多少？这一课的约定是 **float('inf')**（∞）：
#     最短[点] == float('inf')   ⇒ 走不到
#
# ⚠ 写成 -1、0、999999 都不行：这几个值本身也可能是真实距离，分不清。
#   返回的字典里也必须**带上**这些走不到的点，别把它们漏掉。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   负环、次短路、多源最短路（Floyd）、A* —— 都不在这一课里。
#
