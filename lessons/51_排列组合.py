# 「有多少种？」这类问题不用一个个列出来 —— 只要看清一件事：
# 这几步是**分几类**（相加），还是**分几步**（相乘）。
#     加法原理：北京到上海有 3 趟高铁 + 2 班飞机      3 + 2 = 5 种走法
#     乘法原理：北京→上海 3 种，上海→杭州 4 种        3 × 4 = 12 条路线
# 一句话记法：**「或者」用加，「然后」用乘。**
#
# ─────────────────────────────────────────────────────
#  一、排列 P(n,k)：挑出来还要排队
# ─────────────────────────────────────────────────────
#
# 从 n 个人里挑 k 个排成一队，第一个位置有 n 种选法、第二个 n-1 种…… —— 乘法原理：
#
#     P(5, 2) = 5 × 4 = 20            P(10, 3) = 10 × 9 × 8 = 720
#     P(5, 5) = 5 × 4 × 3 × 2 × 1 = 120 = 5!      P(n, 0) = 1（一个都不挑，只有一种）
#
# ⚠ P(n,k) 一共只乘 **k 个数**，不是乘到 1：P(5,2) 是 5×4。写成 5! ÷ 3! 也对
#   （= 120 ÷ 6 = 20），但别把 k 个和 n 个搞混。
#
# ─────────────────────────────────────────────────────
#  二、组合 C(n,k)：挑出来不管顺序
# ─────────────────────────────────────────────────────
#
# C(n,k) 就是「先按顺序挑」再「除掉 k 个的全排列」：
#
#     C(n, k) = P(n, k) ÷ k!
#
#     C(5, 2) = 20 ÷ 2 = 10          从 5 个人里挑 2 个，不管谁先谁后，10 种
#     C(10, 5) = 252；C(52, 5) = 2598960（一手扑克牌 259 万种）；C(n, 0) = C(n, n) = 1
#
# ─────────────────────────────────────────────────────
#  三、杨辉三角：每一行就是一行组合数
# ─────────────────────────────────────────────────────
#
#     1                 第 0 行      C(0,0)
#     1  1              第 1 行      C(1,0) C(1,1)
#     1  2  1           第 2 行      C(2,0) C(2,1) C(2,2)
#     1  5 10 10  5  1  第 5 行      ← 10 就是 C(5,2) 和 C(5,3)
#
# 每个数等于**正上方两个数之和**（三角[i][j] = 三角[i-1][j-1] + 三角[i-1][j]），
# 而它的第 j 个数正好是 C(i, j) —— 这两个说法是同一件事的两种写法。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：k 比 n 大时硬算阶乘
# ─────────────────────────────────────────────────────
#
#     C(5, 7) = math.factorial(5) // (math.factorial(7) * math.factorial(5 - 7))
#     → ValueError: factorial() not defined for negative values
#
# 5 个人里挑 7 个是**不可能**，答案就是 0，不该去算（k < 0 同理）。
# ⇒ 函数开头先挡一句：`if not 0 <= k <= n or n < 0: return 0`
#
