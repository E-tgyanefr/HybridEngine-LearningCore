def _喂(函数, 名字, 用例们, 提示):
    for 用例 in 用例们:
        *参数们, 想 = 用例
        try:
            得 = 函数(*参数们)
        except Exception as e:                                  # noqa: BLE001
            return False, f"{名字}{tuple(参数们)} 出错：{type(e).__name__}: {e}｜{提示}"
        if 得 != 想:
            return False, f"{名字}{tuple(参数们)} 应当是 {想!r}，得到 {得!r}｜{提示}"
    return True, f"{len(用例们)} 组都对"


def CHECK_排列数(答案):
    f = 答案.__dict__.get("排列数")
    if not callable(f):
        return False, ("还没有定义「排列数」。写法：先 `if not 0 <= k <= n: return 0`，"
                       "再连乘 k 个数：结果 = 1; for i in range(k): 结果 *= n - i")
    return _喂(f, "排列数", ((5, 2, 20), (5, 0, 1), (5, 5, 120), (10, 3, 720), (1, 1, 1),
                          (0, 0, 1), (3, 5, 0), (5, -1, 0)),
               "P(5,2) = 5×4（只乘 2 个数，别乘到 1）；k 比 n 大或为负时返回 0")


def CHECK_组合数(答案):
    f = 答案.__dict__.get("组合数")
    if not callable(f):
        return False, ("还没有定义「组合数」。写法：先挡 k 越界，"
                       "再用「先排队再除掉 k!」：排列数(n, k) // math.factorial(k)")
    return _喂(f, "组合数", ((5, 2, 10), (5, 0, 1), (5, 5, 1), (10, 5, 252), (52, 5, 2598960),
                          (0, 0, 1), (5, 6, 0)),
               "C(5,2) = 20 ÷ 2! = 10；C(52,5) = 2598960；k 越界返回 0，别抛 ValueError")


def CHECK_加法乘法原理(答案):
    f = 答案.__dict__.get("乘法原理")
    g = 答案.__dict__.get("加法原理")
    if not callable(f) or not callable(g):
        return False, ("还没有定义「乘法原理」或「加法原理」。乘法是「然后」（连乘），"
                       "加法是「或者」（连加）")
    出 = _喂(f, "乘法原理", (([3, 4], 12), ([1], 1), ([], 1), ([0, 3], 0), ([2, 2, 2], 8),
                          ([10, 10, 10, 10], 10000), ([1, 1, 1, 7], 7)),
             "各组数量相乘；空列表返回 1（一步都不做，也算一种方案）；有一组是 0 就是 0")
    if not 出[0]:
        return 出
    return _喂(g, "加法原理", (([3, 2], 5), ([], 0), ([7], 7), ([0, 4], 4), ([1, 1, 1], 3)),
               "各类数量相加；空列表返回 0")


def CHECK_杨辉三角(答案):
    f = 答案.__dict__.get("杨辉三角")
    if not callable(f):
        return False, ("还没有定义「杨辉三角」。要点：第 0 行是 [1]；每一行两头补 1，"
                       "中间用 上一行[j-1] + 上一行[j] 算出来")
    if f(0) != [] or f(1) != [[1]]:
        return False, f"杨辉三角(0) 应当是 []，杨辉三角(1) 应当是 [[1]]；现在分别是 {f(0)!r} 和 {f(1)!r}"
    for 层 in (1, 2, 3, 5, 6, 12):
        try:
            得 = f(层)
        except Exception as e:                                  # noqa: BLE001
            return False, f"杨辉三角({层}) 出错：{type(e).__name__}: {e}"
        对形状 = (isinstance(得, list) and len(得) == 层
                  and all(isinstance(r, list) and len(r) == i + 1 for i, r in enumerate(得)))
        if not 对形状:
            return False, (f"杨辉三角({层}) 应当是 {层} 行的三角形（第 i 行有 i+1 个数），"
                           f"得到 {得!r}")
        for i, 行 in enumerate(得):
            if 行[0] != 1 or 行[-1] != 1:
                return False, f"杨辉三角({层}) 第 {i} 行两头应当是 1，得到 {行!r}"
            for j in range(1, i):
                if 行[j] != 得[i - 1][j - 1] + 得[i - 1][j]:
                    return False, (f"杨辉三角({层}) 第 {i} 行第 {j} 个数应当是 "
                                   f"{得[i-1][j-1]} + {得[i-1][j]} = "
                                   f"{得[i-1][j-1] + 得[i-1][j]}，得到 {行[j]!r}")
    return True, "层数 0/1/2/3/5/6/12 都对：形状对、两头是 1、中间等于上一行两数之和"


def CHECK_组合数和暴力一致(答案):
    f = 答案.__dict__.get("组合数")
    g = 答案.__dict__.get("杨辉三角")
    if not callable(f):
        return False, "还没有定义「组合数」函数。"
    from itertools import combinations
    for n in range(9):
        for k in range(n + 1):
            想 = len(list(combinations(range(n), k)))       # 每一种都真的列出来数一遍
            try:
                得 = f(n, k)
            except Exception as e:                              # noqa: BLE001
                return False, f"组合数({n}, {k}) 出错：{type(e).__name__}: {e}"
            if 得 != 想:
                return False, (f"组合数({n}, {k}) 应当是 {想}（把可能全列出来数出来的），"
                               f"得到 {得!r}")
    三 = g(12) if callable(g) else []
    对不上 = [(i, j) for i in range(len(三)) for j in range(i + 1) if 三[i][j] != f(i, j)]
    if 对不上:
        i, j = 对不上[0]
        return False, (f"杨辉三角第 {i} 行第 {j} 个数应当是 组合数({i}, {j}) = {f(i, j)}，"
                       f"得到 {三[i][j]!r} —— 杨辉三角的第 j 个数就是 C(i, j)")
    return True, "n ≤ 8 的所有 (n,k) 都和 itertools 枚举的结果一致；杨辉三角也对上了组合数"
