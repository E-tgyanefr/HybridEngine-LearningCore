# 第 11 课：默认参数 —— 调用时可以少传几个
# ─────────────────────────────────────────────────────
#  这一课你会学到
# ─────────────────────────────────────────────────────
#    默认参数：调用时可以少传几个
#
#  需要先会
#    第 10 课：return


# ─────────────────────────────────────────────────────
#  先介绍：让函数「不用每次都填满」
# ─────────────────────────────────────────────────────
#
#      def 问候(名字, 称呼):
#          return f"你好，{名字}{称呼}！"
#
#     问候(「小明」, 「同学」)      每次都得写两样。
#     可大部分时候称呼就是「同学」 —— 每次都写很烦。
#
# 给参数一个**默认值**：
#
#     def 问候(名字, 称呼="同学"):
#                         ↑ 用等号给默认值
#         return f"你好，{名字}{称呼}！"
#
#     问候(「小明」)             ⇒ 你好，小明同学！        （用默认的）
#     问候(「小明」, 「老师」)      ⇒ 你好，小明老师！        （用传进来的）
#
#   ⇒ 不传就用默认值，传了就用你给的。
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课唯一要记住的坑：有默认值的参数必须写在后面
# ─────────────────────────────────────────────────────
#
#     def 问候(称呼="同学", 名字):      ❌ SyntaxError
#                                      non-default argument follows default argument
#
#     def 问候(名字, 称呼="同学"):      ✅
#
#   为什么：如果默认值在前面，调用时 `问候(「小明」)` 到底是给名字还是给称呼？
#   Python 规定不了，所以**直接不允许这么写**。
#
#   ⇒ 报 `non-default argument follows default argument` 时，
#     把带默认值的参数**挪到后面**。
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 另一个更阴的坑：默认值别用列表
# ─────────────────────────────────────────────────────
#
#     def 记一笔(事情, 清单=[]):        ❌ 千万别这么写！
#         清单.append(事情)
#         return 清单
#
#   看起来没问题，但默认的 `[]` **只在定义函数时创建一次**，
#   所有调用会**共用同一个列表**：
#
#     记一笔(「买菜」)     ⇒ ['买菜']
#     记一笔(「取快递」)   ⇒ ['买菜', '取快递']     ← 上一次的还在！
#
#   ⇒ 正确写法是用 `None` 当默认值，进函数再造：
#
#     def 记一笔(事情, 清单=None):
#         if 清单 is None:
#             清单 = []
#         清单.append(事情)
#         return 清单
#
#   这个坑叫「**可变默认参数**」，是 Python 最有名的坑之一。
#   （第 16 课写类的时候还会遇到同一个问题的另一种形态。）
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   `*参数`（接收任意多个）是第 12 课。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 写函数 问候(名字, 称呼=「同学」)，返回 f-string：
#          你好，<名字><称呼>！
#   2. 写函数 打折(价格, 折扣=0.9)，返回 价格 * 折扣
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 11


def CHECK_问候(答案):
    if not hasattr(答案, "问候"):
        return False, ('还没有定义「问候」函数。\n'
                       '      写法：def 问候(名字, 称呼="同学"): ...')
    if not callable(答案.问候):
        return False, "「问候」不是函数。"
    try:
        一个 = 答案.问候("小明")
    except TypeError as e:
        return False, (f"问候('小明') 调用失败：{e}\n"
                       f"      ⚠ 说明「称呼」**没有默认值** —— 这一课的第一个要求就是它。\n"
                       f"        写法：def 问候(名字, 称呼='同学'):")
    except Exception as e:                                      # noqa: BLE001
        return False, f"问候('小明') 出错了：{type(e).__name__}: {e}"
    if 一个 != "你好，小明同学！":
        return False, (f"问候('小明') 应当是 '你好，小明同学！'，实际是 {一个!r}。\n"
                       f"      对照标点：逗号、感叹号都要一致；「同学」是默认称呼。")
    try:
        两个 = 答案.问候("李老师", "老师")
    except Exception as e:                                      # noqa: BLE001
        return False, f"问候('李老师', '老师') 出错了：{type(e).__name__}: {e}"
    if 两个 != "你好，李老师老师！":
        return False, (f"问候('李老师', '老师') 应当是 '你好，李老师老师！'，"
                       f"实际是 {两个!r}。\n"
                       f"      ⚠ 传了第二个参数时要用**传进来的那个**，不能还是写死「同学」。")
    return True, "不传用默认 / 传了用传的 —— 都对"


def CHECK_打折(答案):
    if not hasattr(答案, "打折"):
        return False, "还没有定义「打折」函数。写法：def 打折(价格, 折扣=0.9): ..."
    if not callable(答案.打折):
        return False, "「打折」不是函数。"
    try:
        默认 = 答案.打折(100)
    except TypeError as e:
        return False, (f"打折(100) 调用失败：{e}\n"
                       f"      ⚠ 「折扣」要有默认值 0.9。")
    except Exception as e:                                      # noqa: BLE001
        return False, f"打折(100) 出错了：{type(e).__name__}: {e}"
    if abs(默认 - 90.0) > 1e-9:
        return False, (f"打折(100) 应当是 90.0（默认 9 折），实际是 {默认!r}。\n"
                       f"      ⚠ 默认值要写 0.9（小数），不是 9。")
    if abs(答案.打折(200, 0.5) - 100.0) > 1e-9:
        return False, f"打折(200, 0.5) 应当是 100.0，实际是 {答案.打折(200, 0.5)!r}。"
    if abs(答案.打折(50, 1.0) - 50.0) > 1e-9:
        return False, f"打折(50, 1.0) 应当是 50.0（不打折），实际是 {答案.打折(50, 1.0)!r}。"
    return True, "默认 9 折 / 传 5 折 / 不打折 都对"


def CHECK_顺序对了(答案):
    """⚠ 带默认值的参数必须在后面 —— 这是这一课要记的语法点。"""
    import io
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    # 有默认值的参数如果出现在无默认值参数之前，Python 会直接报 SyntaxError，
    # 所以这里只要文件能加载就说明顺序是对的 —— 但值得说清楚为什么。
    if "def 问候(称呼" in 源码:
        return False, ("「问候」的参数顺序反了：带默认值的「称呼」写在了前面。\n"
                       "      ⚠ Python 不允许这样 —— 会报\n"
                       "         SyntaxError: non-default argument follows default argument\n"
                       "        因为那样 `问候('小明')` 到底给谁就说不清了。\n"
                       "      ⇒ 把带默认值的参数**挪到后面**。")
    return True, "带默认值的参数在后面"
