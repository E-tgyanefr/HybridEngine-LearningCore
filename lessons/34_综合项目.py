#   卡住了看答案（先自己写一遍）—— 命令在「怎么自己测」那一节。
#
# ─────────────────────────────────────────────────────
#  先介绍：会语法 ≠ 会写程序
# ─────────────────────────────────────────────────────
#
# 前面每一课都只练一个零件。可真实的程序长这样：
#
#     读进来 → 整理 → 算 → 排 → 写回去
#
# 这一课就把这条流水线走完一遍：**成绩单程序**。
#
# 输入文件 `成绩.txt` 每行是「姓名 空格 分数」，输出文件 `排名.txt` 每行是
# 「名次 空格 姓名 空格 分数」（同分同名次）：
#
#     小明 90            1 小红 95
#     小红 95      ⇒     2 小明 90
#     小刚 80            3 小刚 80
#
# ─────────────────────────────────────────────────────
#  一、先把任务拆成四步（拆开才写得动）
# ─────────────────────────────────────────────────────
#
#     ① 读文件   成绩.txt ⇒ [('小明', 90), ('小红', 95), …]    第 32 课 + 第 17 课
#     ② 处理     算平均分、找最高分                              第 08 课
#     ③ 排序     从高到低 + 算名次（同分同名次）                  第 30 课
#     ④ 写文件   [名次, 姓名, 分数] ⇒ 排名.txt                   第 32 课
#
# ⚠ 每一步只做一件事，都写成**小函数**。这样出错时你立刻知道该去哪一步找，
#   而不是对着一百行代码发呆。这就是「会写程序」和「会语法」的差别。
#
# ─────────────────────────────────────────────────────
#  二、第一步：读（把文本变成数据）
# ─────────────────────────────────────────────────────
#
#     def 读成绩(路径):
#         成绩们 = []
#         with open(路径, encoding='utf-8') as 文件:
#             for 行 in 文件:
#                 行 = 行.strip()
#                 if not 行:                 ← 空行跳过
#                     continue
#                 姓名, 分数 = 行.split()    ← 一行拆成两半
#                 成绩们.append((姓名, int(分数)))
#         return 成绩们
#
# ⚠ `行.split()` **不加参数**：它会自动把连续空格、Tab 都当成一个分隔符。
#   写成 `行.split(' ')` 的话，遇到两个连续空格就会拆出空字符串。
#
# ⚠ `int(分数)` 可能抛 ValueError（文件被人手改坏了、里面有个 abc）。
#   想更结实就用第 33 课的 try/except 接住。
#
# ─────────────────────────────────────────────────────
#  三、第二步：算（先想清楚空输入）
# ─────────────────────────────────────────────────────
#
#     def 算平均(成绩们):
#         if not 成绩们:
#             return 0.0                 ← ⚠ 空表要单独处理
#         总分 = 0
#         for 姓名, 分数 in 成绩们:
#             总分 += 分数
#         return 总分 / len(成绩们)
#
# ⚠ 不处理空表就是 `总分 / 0` ⇒ ZeroDivisionError。空输入是最容易被忘的边界。
#
# ─────────────────────────────────────────────────────
#  四、第三步：排序 + 名次（第 30 课的组合拳）
# ─────────────────────────────────────────────────────
#
#     def 排出名次(成绩们):
#         排好的 = sorted(成绩们, key=lambda 对: 对[1], reverse=True)
#         结果 = []
#         for i, (姓名, 分数) in enumerate(排好的):
#             if i > 0 and 分数 == 排好的[i - 1][1]:
#                 名次 = 结果[-1][0]          ← 同分：沿用上一个名次
#             else:
#                 名次 = i + 1                ← 名次会跳跃：1, 1, 3
#             结果.append((名次, 姓名, 分数))
#         return 结果
#
# ⚠ 这里的「同分保持原来的先后」靠的就是 sorted 是**稳定**的（第 30 课）。
#
# ─────────────────────────────────────────────────────
#  五、第四步：写回去（数据变回文本）
# ─────────────────────────────────────────────────────
#
#     def 写成绩(路径, 带名次的):
#         with open(路径, 'w', encoding='utf-8') as 文件:
#             for 名次, 姓名, 分数 in 带名次的:
#                 文件.write(str(名次) + ' ' + 姓名 + ' ' + str(分数) + '\n')
#
# ⚠ 两件事：数字要 `str()` 才能拼；换行 `\n` 要自己写（write 不会自动换行）。
#
# ─────────────────────────────────────────────────────
#  六、串起来：主函数只负责「按顺序调用」
# ─────────────────────────────────────────────────────
#
#     def 处理一遍(原路径, 新路径):
#         成绩们 = 读成绩(原路径)
#         名次们 = 排出名次(成绩们)
#         写成绩(新路径, 名次们)
#         return 名次们
#
# ⚠ 这个函数自己不做任何细节活 —— 它的价值是**把顺序讲清楚**：
#   读 → 排 → 写。以后要加一步（比如「过滤掉不及格的」），就插在这里。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：with 块外面还用文件对象
# ─────────────────────────────────────────────────────
#
#     with open('成绩.txt', encoding='utf-8') as 文件:
#         内容 = 文件.read()
#
#     print(文件.read())          ← with 已经把它关掉了
#
#     ⇒ ValueError: I/O operation on closed file.
#
# ⚠ 出了 with 的缩进块，文件就是**关好的**（这正是 with 的好处，第 32 课）。
#   所以：**要用的数据，在 with 里面就读出来存进变量**，别把文件对象带出去。
#
#   ⚠ 同样的坑还有一版：with 里只写了 `文件.read()` 没接住返回值，
#     然后拿 `文件` 去做别的事 —— 一样是上面这个报错。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   真实项目的分层、给程序写测试、超大文件怎么边读边处理 —— 后面的事。
#   这一课只讲：把学过的东西串成一条能跑通的流水线。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 写函数 读成绩(路径)：读文件（每行 姓名 分数），返回 [('姓名', 分数), …]
#    （分数转成整数；空行跳过；用 with open(…, encoding='utf-8')）
# 2. 写函数 算平均(成绩们)：返回平均分；空列表返回 0.0
# 3. 写函数 排出名次(成绩们)：返回 [(名次, 姓名, 分数), …]，
#    按分数从高到低；同分同名次，名次跳跃（90, 90, 80 ⇒ 1, 1, 3）
# 4. 写函数 写成绩(路径, 带名次的)：把 [(名次, 姓名, 分数), …] 写成文件，
#    每行 `名次 姓名 分数`，末尾带换行
# 5. 写函数 处理一遍(原路径, 新路径)：读 → 排名次 → 写回去，并**返回名次表**
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#    python -m hybridengine_light 检查 34

import io
import os
import shutil
import tempfile


def _造文件(目录, 名字, 内容):
    路径 = os.path.join(目录, 名字)
    with open(路径, "w", encoding="utf-8") as f:
        f.write(内容)
    return 路径


def _读回来(路径):
    with open(路径, encoding="utf-8") as f:
        return f.read()


def CHECK_读成绩(答案):
    f = 答案.__dict__.get("读成绩")
    if not callable(f):
        return False, ("还没有定义函数「读成绩」。\n"
                       "      写法（重点）：with open(路径, encoding='utf-8') as 文件:\n"
                       "                        for 行 in 文件:\n"
                       "                            行 = 行.strip()\n"
                       "                            if not 行: continue\n"
                       "                            姓名, 分数 = 行.split()")
    组 = (('小明 90\n小红 95\n', [('小明', 90), ('小红', 95)]),
         ('', []),
         ('甲 1\n\n乙 2\n', [('甲', 1), ('乙', 2)]),
         ('单 5', [('单', 5)]),
         ('宽  7\n', [('宽', 7)]),
         ('丙 0\n丁 -3\n', [('丙', 0), ('丁', -3)]))
    目录 = tempfile.mkdtemp(prefix="py34a_")
    try:
        for i, (内容, 想) in enumerate(组):
            路径 = _造文件(目录, f"读{i}.txt", 内容)
            try:
                得 = f(路径)
            except ValueError as e:
                return False, (f"读成绩(内容为 {内容!r} 的文件) 出错了：ValueError: {e}\n"
                               f"      ⚠ 最常见的两个原因：\n"
                               f"        · 拆行写成了 `行.split(' ')` —— 两个词之间不止一个空格时，\n"
                               f"          它会把空字符串也拆出来。用 `行.split()`（不加参数）。\n"
                               f"        · 分数忘了 `int(分数)` 之外，还可能有空行没跳过。")
            except Exception as e:                          # noqa: BLE001
                return False, (f"读成绩(内容为 {内容!r} 的文件) 出错了："
                               f"{type(e).__name__}: {e}")
            if 得 != 想:
                return False, (f"读成绩(内容为 {内容!r} 的文件)\n"
                               f"        得到 {得!r}\n"
                               f"        应当 {想!r}\n"
                               f"      ⚠ 分数要 `int(分数)` 转成整数（否则会是 '90' 这种文字）；\n"
                               f"        空行要跳过；拆行用 `行.split()` —— 不加参数才能对付连续空格。")
    finally:
        shutil.rmtree(目录, ignore_errors=True)
    # ⚠ 「文件操作一律 with」并进这一条检查里 —— 这一课已经有 5 条 CHECK_，
    #   再单开一条就超出「每课 3~5 条」的规约（with 本身在第 32 课已经单练过）。
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件，没法确认用没用 with。"
    try:
        源码 = io.open(答案.__file__, encoding="utf-8").read()
    except OSError as e:
        return False, f"读不了你的答题文件：{e}"
    # ⚠ 只看「读成绩」这一段：写成绩 里当然也有 with，
    #   拿整个文件去搜的话，读成绩 用手动 open 也能蒙混过去（实测撞到过）。
    i = 源码.find("def 读成绩")
    if i < 0:
        return False, "源码里找不到「def 读成绩」。"
    j = 源码.find("\ndef ", i + 1)
    段 = 源码[i:j if j > 0 else i + 500]
    if "with open(" not in 段:
        return False, ("「读成绩」里没有 `with open(...)` —— 读文件也要用它。\n"
                       "      ⚠ 出了 with 的缩进块文件就关好了；手动 close 遇到异常会关不掉。")
    return True, "六组都对（多行 / 空文件 / 空格行 / 末行没换行 / 两个空格 / 负数），且用了 with"


def CHECK_算平均(答案):
    f = 答案.__dict__.get("算平均")
    if not callable(f):
        return False, ("还没有定义函数「算平均」。\n"
                       "      写法：总分 = 0\n"
                       "            for 姓名, 分数 in 成绩们: 总分 += 分数\n"
                       "            return 总分 / len(成绩们)      ← 空表要先 return 0.0")
    for 成绩们, 想 in (([], 0.0), ([('a', 90)], 90.0), ([('a', 90), ('b', 80)], 85.0),
                      ([('a', 0), ('b', 0)], 0.0), ([('a', -3), ('b', 3)], 0.0),
                      ([('a', 1), ('b', 2), ('c', 3)], 2.0)):
        try:
            得 = f(list(成绩们))
        except ZeroDivisionError:
            return False, (f"算平均({成绩们!r}) 报了 ZeroDivisionError。\n"
                           f"      ⚠ 空列表要单独处理：\n"
                           f"          if not 成绩们:\n"
                           f"              return 0.0")
        except Exception as e:                              # noqa: BLE001
            return False, f"算平均({成绩们!r}) 出错了：{type(e).__name__}: {e}"
        if not isinstance(得, (int, float)) or isinstance(得, bool) or abs(得 - 想) > 1e-9:
            return False, (f"算平均({成绩们!r}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 用 / （不是 // —— 平均分会有小数）；空列表返回 0.0。")
    return True, "六组都对（空表 / 单个 / 两个 / 全 0 / 一正一负 / 三个）"


def CHECK_排出名次(答案):
    f = 答案.__dict__.get("排出名次")
    if not callable(f):
        return False, ("还没有定义函数「排出名次」。\n"
                       "      写法：先 sorted(成绩们, key=lambda 对: 对[1], reverse=True)，\n"
                       "            再按「同分沿用上一个名次、不同分用 i+1」编号。")
    for 成绩们, 想 in (([('小明', 90), ('小红', 90), ('小刚', 80)],
                      [(1, '小明', 90), (1, '小红', 90), (3, '小刚', 80)]),
                     ([], []),
                     ([('单人', 5)], [(1, '单人', 5)]),
                     ([('甲', 0), ('乙', 0)], [(1, '甲', 0), (1, '乙', 0)]),
                     ([('低', -5), ('高', -1)], [(1, '高', -1), (2, '低', -5)]),
                     ([('a', 9), ('b', 9), ('c', 9), ('d', 3)],
                      [(1, 'a', 9), (1, 'b', 9), (1, 'c', 9), (4, 'd', 3)])):
        try:
            得 = f([tuple(项) for 项 in 成绩们])
        except Exception as e:                              # noqa: BLE001
            return False, f"排出名次({成绩们!r}) 出错了：{type(e).__name__}: {e}"
        if 得 != 想:
            # 先分清是「排序错」还是「名次编号错」—— 提示要指对地方
            该序 = [(对[1], 对[2]) for 对 in 想]
            try:
                得序 = [(对[1], 对[2]) for 对 in 得]
            except Exception:                               # noqa: BLE001
                得序 = None
            if 得序 != 该序:
                return False, (f"排出名次({成绩们!r}) 的**排序**就不对：\n"
                               f"        得到 {得!r}\n"
                               f"        应当 {想!r}\n"
                               f"      ⚠ 分数高的在前：sorted(成绩们, key=lambda 对: 对[1], "
                               f"reverse=True)")
            return False, (f"排出名次({成绩们!r}) 排的顺序对了，但**名次编号不对**：\n"
                           f"        得到 {得!r}\n"
                           f"        应当 {想!r}\n"
                           f"      ⚠ 同分同名次，而且名次**跳跃**（并列第 1 之后直接是第 3）：\n"
                           f"          if i > 0 and 分数 == 排好的[i - 1][1]:\n"
                           f"              名次 = 结果[-1][0]      ← 沿用上一个名次\n"
                           f"          else:\n"
                           f"              名次 = i + 1            ← 不是 上一个名次 + 1")
    return True, "六组都对（含并列第 1、三个并列、全负数、空表）"


def CHECK_写成绩(答案):
    f = 答案.__dict__.get("写成绩")
    if not callable(f):
        return False, ("还没有定义函数「写成绩」。\n"
                       "      写法：with open(路径, 'w', encoding='utf-8') as 文件:\n"
                       "                for 名次, 姓名, 分数 in 带名次的:\n"
                       "                    文件.write(str(名次) + ' ' + 姓名 + ' ' "
                       "+ str(分数) + '\\n')")
    组 = (([(1, '小红', 95), (2, '小明', 90), (3, '小刚', 80)],
         '1 小红 95\n2 小明 90\n3 小刚 80\n'),
         ([], ''),
         ([(1, '单人', 0)], '1 单人 0\n'),
         ([(1, 'a', -5), (2, 'b', -1)], '1 a -5\n2 b -1\n'))
    目录 = tempfile.mkdtemp(prefix="py34b_")
    try:
        for i, (数据, 想) in enumerate(组):
            路径 = os.path.join(目录, f"写{i}.txt")
            try:
                f(路径, list(数据))
            except Exception as e:                          # noqa: BLE001
                return False, f"写成绩(…, {数据!r}) 出错了：{type(e).__name__}: {e}"
            if not os.path.isfile(路径):
                return False, (f"写成绩(…, {数据!r}) 之后没有生成文件 —— "
                               f"检查一下 with open(路径, 'w', …) 里的路径。")
            try:
                实际 = _读回来(路径)
            except UnicodeDecodeError:
                return False, ("写出来的文件不是 UTF-8。\n"
                               "      ⚠ with open(路径, 'w', encoding='utf-8') 里的 encoding "
                               "不能省。")
            if 实际 != 想:
                return False, (f"写成绩(…, {数据!r})\n"
                               f"        文件里是 {实际!r}\n"
                               f"        应当是 {想!r}\n"
                               f"      ⚠ 每行 `名次 姓名 分数`（中间一个空格），末尾要 '\\n'；\n"
                               f"        名次和分数是数字，拼字符串前要 str()。")
        return True, "四组都对（三行 / 空列表写空文件 / 单人 / 负数）"
    finally:
        shutil.rmtree(目录, ignore_errors=True)


def CHECK_处理一遍(答案):
    f = 答案.__dict__.get("处理一遍")
    if not callable(f):
        return False, ("还没有定义函数「处理一遍」。\n"
                       "      写法：成绩们 = 读成绩(原路径)\n"
                       "            名次们 = 排出名次(成绩们)\n"
                       "            写成绩(新路径, 名次们)\n"
                       "            return 名次们")
    组 = (('小明 90\n小红 95\n小刚 80\n',
         [(1, '小红', 95), (2, '小明', 90), (3, '小刚', 80)],
         '1 小红 95\n2 小明 90\n3 小刚 80\n'),
         ('', [], ''),
         ('甲 90\n乙 90\n', [(1, '甲', 90), (1, '乙', 90)], '1 甲 90\n1 乙 90\n'),
         ('独 7\n', [(1, '独', 7)], '1 独 7\n'))
    目录 = tempfile.mkdtemp(prefix="py34c_")
    try:
        for i, (内容, 想返回, 想文件) in enumerate(组):
            原 = _造文件(目录, f"原{i}.txt", 内容)
            新 = os.path.join(目录, f"新{i}.txt")
            try:
                得 = f(原, 新)
            except Exception as e:                          # noqa: BLE001
                return False, (f"处理一遍(原文件内容 {内容!r}) 出错了："
                               f"{type(e).__name__}: {e}\n"
                               f"      ⚠ 顺着查：读成绩 → 排出名次 → 写成绩，"
                               f"哪个还没写对？")
            if 得 != 想返回:
                return False, (f"处理一遍(原文件内容 {内容!r}) 应当返回 {想返回!r}，"
                               f"得到 {得!r}。\n"
                               f"      ⚠ 这个函数要把**名次表** return 出来（别忘 return）。")
            if not os.path.isfile(新):
                return False, (f"处理一遍 没有写出新文件 {os.path.basename(新)}。\n"
                               f"      ⚠ 三步都要做：读 → 排名次 → **写回文件**。")
            实际 = _读回来(新)
            if 实际 != 想文件:
                return False, (f"处理一遍(原文件内容 {内容!r}) 写出来的文件是\n"
                               f"        {实际!r}\n"
                               f"        应当是 {想文件!r}")
        return True, "四组端到端都对（正常三行 / 空文件 / 并列第 1 / 单人）"
    finally:
        shutil.rmtree(目录, ignore_errors=True)
