# 第 07 课：类 —— 把数据和动作放在一起

# 要做：
#   1. 写一个类 计数器：
#        · 造出来时有 `值`（默认 0，可以传初值）
#        · 方法 `加(n)` 让值增加 n
#        · 方法 `重置()` 让值回到 0
#   2. 写一个类 存钱罐：
#        · 造出来时有 `余额`（默认 0）
#        · 方法 `存(n)` 增加余额
#        · 方法 `取(n)`：钱够就扣掉并返回 True；**不够就返回 False 且余额不变**

# ─────────────────────────────────────────────────────
#  为什么需要「类」
# ─────────────────────────────────────────────────────
#
# 没有类的时候你会这么写：
#
#     余额 = 0
#     def 存(n):
#         global 余额        # ← 要声明 global，丑
#         余额 += n
#     def 取(n):
#         global 余额
#         余额 -= n          # ← 忘了检查够不够 ⇒ 余额变负数
#
# 两个问题：
#   ① `余额` 是个**谁都能改**的全局变量，别处一行代码就能弄坏它
#   ② 「余额」和「改余额的规则」**离得很远** —— 你想检查规则得翻遍整个文件
#
# 有类之后，它们被放进同一个地方：
#
#     class 存钱罐:
#         def __init__(self, 初值=0):
#             self.余额 = 初值
#         def 取(self, n):
#             if n > self.余额:        # ← 规则就在这里，跑不掉
#                 return False
#             self.余额 -= n
#             return True
#
# ⇒ 这叫**封装**。不要把它理解成「藏起来」，
#   它的真实意思是：**一个东西的规则只有一个出口**。
#   想把余额改成负数？做不到 —— 唯一的入口是 `取`，而 `取` 会检查。
#
# ─────────────────────────────────────────────────────
#  三个必须记住的东西
# ─────────────────────────────────────────────────────
#
#  ① `__init__` —— 造对象时自动跑的方法（前后各两个下划线）
#
#         def __init__(self, 初值=0):
#             self.余额 = 初值
#
#     ⚠ 不是 __int__、不是 _init_ —— 拼错的话它只是个普通方法，
#       造对象时**不会被调用**，然后你会奇怪「为什么属性不存在」。
#
#  ② `self` —— 「我自己」
#
#         每个方法第一个参数都是 self（名字可以改，但没人改）
#         写 self.余额 才是这个对象的余额；
#         写 余额 是一个**局部变量**，跟对象没关系 —— 新手最常混这点。
#
#  ③ 方法调用时**不用传 self**
#
#         定义：def 加(self, n):
#         调用：罐.加(5)          ← 不写 self，Python 自己塞进去
#
# ─────────────────────────────────────────────────────
#  第 2 条最容易错的地方
# ─────────────────────────────────────────────────────
#
# `取(n)` 钱不够时要「返回 False **且余额不变**」。
# 常见错法是**先扣再判断**：
#
#         self.余额 -= n            # ← 已经扣了！
#         if self.余额 < 0:
#             return False
#
# 这时余额已经被改坏了。正确顺序永远是：**先检查，通过才动**。
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 07


def CHECK_计数器类(答案):
    if not hasattr(答案, "计数器"):
        return False, "还没有定义「计数器」类。写法：class 计数器: ..."
    类 = 答案.计数器
    if not isinstance(类, type):
        return False, f"「计数器」应当是类，现在是 {type(类).__name__}。"
    try:
        a = 类()
    except Exception as e:                                      # noqa: BLE001
        return False, (f"计数器() 造不出来：{type(e).__name__}: {e}\n"
                       f"      ⚠ 检查 __init__ 的拼写（前后各两个下划线）。")
    if not hasattr(a, "值"):
        return False, ("造出来的计数器没有 .值 这个属性。\n"
                       "      写法：def __init__(self, 初值=0): self.值 = 初值\n"
                       "      ⚠ 一定要写 self.值 —— 只写 值 是个局部变量，对象上没有。")
    if a.值 != 0:
        return False, f"不传初值时 .值 应当是 0，实际是 {a.值!r}。"
    try:
        b = 类(100)
    except Exception as e:                                      # noqa: BLE001
        return False, (f"计数器(100) 造不出来：{type(e).__name__}: {e}\n"
                       f"      ⚠ 构造函数要有 初值=0 这个**带默认值**的参数。")
    if b.值 != 100:
        return False, f"计数器(100).值 应当是 100，实际是 {b.值!r}。"
    if not hasattr(a, "加") or not callable(a.加):
        return False, "没有 加(n) 这个方法。"
    a.加(3)
    a.加(4)
    if a.值 != 7:
        return False, f"加(3) 再 加(4) 之后应当是 7，实际是 {a.值!r}。"
    if not hasattr(a, "重置") or not callable(a.重置):
        return False, "没有 重置() 这个方法。"
    a.重置()
    if a.值 != 0:
        return False, f"重置() 之后应当是 0，实际是 {a.值!r}。"
    c = 类()
    c.加(9)
    if b.值 != 100:
        return False, (f"改动 c 的时候 b 也跟着变了（b.值 变成了 {b.值}）。\n"
                       f"      ⚠ 说明你把 值 写成了**类属性**而不是实例属性。\n"
                       f"        要写在 __init__ 里用 self.值 = ... 赋值。")
    return True, "默认初值 / 指定初值 / 加 / 重置 / 对象互不影响 都对"


def CHECK_存钱罐类(答案):
    if not hasattr(答案, "存钱罐"):
        return False, "还没有定义「存钱罐」类。"
    类 = 答案.存钱罐
    if not isinstance(类, type):
        return False, f"「存钱罐」应当是类，现在是 {type(类).__name__}。"
    try:
        a = 类(100)
    except Exception as e:                                      # noqa: BLE001
        return False, f"存钱罐(100) 造不出来：{type(e).__name__}: {e}"
    if not hasattr(a, "余额"):
        return False, "存钱罐上没有 .余额 属性。"
    if a.余额 != 100:
        return False, f"存钱罐(100).余额 应当是 100，实际是 {a.余额!r}。"
    if 类().余额 != 0:
        return False, f"不传初值时余额应当是 0，实际是 {类().余额!r}。"
    if not hasattr(a, "存") or not callable(a.存):
        return False, "没有 存(n) 这个方法。"
    a.存(50)
    if a.余额 != 150:
        return False, f"存(50) 之后应当是 150，实际是 {a.余额!r}。"
    if not hasattr(a, "取") or not callable(a.取):
        return False, "没有 取(n) 这个方法。"
    得 = a.取(30)
    if 得 is not True:
        return False, (f"取(30)（钱够）应当返回 **True**，实际是 {得!r}。\n"
                       f"      ⚠ 方法要 return True/False，不能只是 print。")
    if a.余额 != 120:
        return False, f"取(30) 之后应当是 120，实际是 {a.余额!r}。"
    得 = a.取(999)
    if 得 is not False:
        return False, f"钱不够时取(999) 应当返回 **False**，实际是 {得!r}。"
    if a.余额 != 120:
        return False, (f"取款失败之后余额**被改动了**：应当是 120，实际是 {a.余额!r}。\n"
                       f"      ⚠⚠ 这是这一课最要紧的一条。常见错法是**先扣再判断**：\n"
                       f"          self.余额 -= n          ← 已经扣了\n"
                       f"          if self.余额 < 0: return False\n"
                       f"        正确顺序永远是：**先检查，通过才动**。")
    得 = a.取(120)
    if 得 is not True or a.余额 != 0:
        return False, (f"正好取光（取 120，余额 120）应当成功、余额变 0；"
                       f"实际返回 {得!r}、余额 {a.余额!r}。\n"
                       f"      ⚠ 边界要写 if n > self.余额（大于才拒绝），不能写 >=。")
    return True, "存 / 取 / 钱不够拒绝且余额不变 / 正好取光 都对"
