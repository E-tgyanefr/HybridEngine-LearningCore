# ─────────────────────────────────────────────────────
#
# 画图软件里的油漆桶、扫雷点开一片空白、地图上数岛屿 —— 都是同一件事：
# **从一格出发，把连着的同色格子全灌满，灌不到的就是另一块。**
#
#     网格 = [[1, 1, 0],
#             [1, 0, 0],        1 是陆地、0 是水
#             [0, 0, 1]]
#
# 左上角那三格 1 连成一块，右下角那个 1 自己一块 —— 一共 **2 块**。只有上下左右算
# 连着，**斜着不算**：(0,0) 和 (1,1) 是对角，不通。
# ─────────────────────────────────────────────────────
#  一、泛洪：一格一格灌过去
# ─────────────────────────────────────────────────────
#
# 第 49 课的 DFS 在这里直接用：把「格子」当成「点」，「上下左右挨着」当成「边」。
# 区别只有一个 —— 不用真的建图，走的时候现算四个方向：
#
#     方向 = ((1, 0), (-1, 0), (0, 1), (0, -1))      下、上、右、左
#
#     def 灌(网格, 行, 列, 见过):
#         if not (0 <= 行 < len(网格) and 0 <= 列 < len(网格[0])): return   ← 先问界
#         if 网格[行][列] != 1 or (行, 列) in 见过: return                  ← 再问色
#         见过.add((行, 列))                                               ← 进来就标记
#         for 下, 右 in 方向:
#             灌(网格, 行 + 下, 列 + 右, 见过)
#
# ⚠ 顺序不能反：**先问「在不在界内」，再问「是什么颜色」**。反过来先读
#   网格[行][列] 就会越界（见这一课的坑）。
#
# ─────────────────────────────────────────────────────
#  二、数岛屿：每个没去过的陆地下水一次
# ─────────────────────────────────────────────────────
#
# 两层循环扫过每一格；碰到「是陆地、又没被灌过」的，块数 +1，然后从它泛洪一次。
# 3×3 的网格一共 2^9 = 512 种填法 —— 检查里就是把 512 种**全试一遍**，拿暴力结果
# 跟你对，不是抽查。
# ─────────────────────────────────────────────────────
#  三、哈希表：为什么 in 是 O(1)
# ─────────────────────────────────────────────────────
#
# 在 100 万个名字里找一个，列表只能从头挨着比 —— 平均要比 50 万次。集合和字典
# 不一样，它们先拿键**算一个位置**（哈希），直接跳到那一格看：
#
#     位置 = 键 % 表长        表长 3 时：1、4、7 全落到 1 号桶
#
# ⇒ 这就是「O(1)」：不管表里有多少个，都是一次加法加一次取。
# ⚠ 两个键算到同一个位置叫**冲突**，冲突了就只能在那个桶里挨着找：桶里挤了 8 个，
#   那几次查找就退化成 O(8)。所以哈希表也要留够空间。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：先动手再问，越界了
# ─────────────────────────────────────────────────────
#
#     def 灌(网格, 行, 列):
#         网格[行][列] = 2                  ❌ 还没判界就先写下标
#     → IndexError: list index out of range
# ⇒ 每个方向走之前都问两件事：**0 <= 行 < len(网格) 吗？颜色对吗？**
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   8 个方向的泛洪、带权最短路、写自己的哈希类 —— 都不在这几行要你做的事里。
#
# ─────────────────────────────────────────────────────
