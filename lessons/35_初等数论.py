# ─────────────────────────────────────────────────────
#  先介绍：一切从「能不能整除」开始
# ─────────────────────────────────────────────────────
# 12 能被 1、2、3、4、6、12 整除 —— 这六个数叫 12 的**因数**，12 叫它们的**倍数**；
#
#     12 = 2 × 2 × 3        ← 拆到不能再拆，叫**质因数分解**
#     2、3 叫**质数**：只有 1 和它自己两个因数
#
# 这一课就四件事：判质数、拆质因数、数约数、列约数。
#
# ─────────────────────────────────────────────────────
#  一、质数判断：试到 √n 就够了
# ─────────────────────────────────────────────────────
# 笨办法是拿 2、3、…、n-1 一个个试。但**试到 √n 就够了**：
# 若 n = 甲 × 乙 且 甲 ≤ 乙，则 甲 ≤ √n —— 小的找不到，大的更不可能有。
# 判 1000003 是不是质数：试到 100 万要 100 万次，试到 √1000003 ≈ 1000 只要 1000 次。
#
#     def 是质数(n):
#         if n < 2:
#             return False
#         试除数 = 2
#         while 试除数 * 试除数 <= n:      ← ⚠ 这个 <= 不能写成 <
#             if n % 试除数 == 0:
#                 return False
#             试除数 += 1
#         return True
#
#     是质数(2) ⇒ True    是质数(1) ⇒ False    是质数(9) ⇒ False
#     是质数(97) ⇒ True   是质数(-7) ⇒ False（负数一律不是质数）
#
# ─────────────────────────────────────────────────────
#  二、质因数分解：唯一分解定理
# ─────────────────────────────────────────────────────
# **唯一分解定理**：每个大于 1 的整数都能写成质数的乘积，写法只有一种（不看顺序）。
#
#     12 = 2 × 2 × 3      100 = 2 × 2 × 5 × 5     1024 = 2 连乘 10 次
#
# 怎么拆：从 2 开始，能整除就一直除：12 ÷ 2 = 6，6 ÷ 2 = 3，3 ÷ 3 = 1 ⇒ [2, 2, 3]
# 收尾的小机关：循环结束时剩下的 n 若大于 1，它自己就是质数（97、999983 这样留下）。
#
# ─────────────────────────────────────────────────────
#  三、约数个数：不用一个个数
# ─────────────────────────────────────────────────────
# 把 n 写成 2^a × 3^b × 5^c × …，那么 **约数个数 = (a+1) × (b+1) × (c+1) × …**
#
#     12 = 2² × 3¹ ⇒ (2+1)(1+1) = 6        100 = 2² × 5² ⇒ 3 × 3 = 9
#     97 = 97¹     ⇒ 1+1 = 2               1024 = 2¹⁰ ⇒ 10+1 = 11
#
# 为什么：指数有 0、1、…、a 共 a+1 种取法，乘起来就是总个数。硬数也行，但 n = 10⁹ 要试 10 亿次。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：判质数的循环边界少了个等号
# ─────────────────────────────────────────────────────
#     def 是质数(n):                  # ← 错的版本
#         试除数 = 2
#         while 试除数 * 试除数 < n:    ← 少了等号
#             if n % 试除数 == 0: return False
#             试除数 += 1
#         return True
#
#     是质数(9) ⇒ True      ← 错！9 = 3 × 3
#
# 为什么：试除数到 3 时 `3 * 3 < 9` 已经是 False，循环**提前退出**，
#   根本没机会检查 `9 % 3 == 0`。9、25、49、121 这些**平方数**全会判成质数。
# 换个写法也一样：`range(2, int(n ** 0.5))` 的右端**不含**，9 只得到 `range(2, 3)`。
#
# ⇒ 记法：**边界要含 √n，`<=` 或 `+ 1` 二选一，少一个就错** —— 这类错不报错，只是答案悄悄不对。
#
