def CHECK_是质数(答案):
    f = 答案.__dict__.get('是质数')
    if not callable(f):
        return False, ('还没有定义「是质数」。写法：n < 2 直接返回 False；\n'
                       '      试除数从 2 试到 `试除数 * 试除数 <= n`，能整除就返回 False。')
    for n, 想 in ((2, True), (1, False), (0, False), (-7, False), (9, False),
                  (25, False), (49, False), (100, False), (97, True), (999983, True)):
        try:
            得 = f(n)
        except Exception as e:                                  # noqa: BLE001
            return False, f'是质数({n}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            if n in (9, 25, 49):
                根 = int(n ** 0.5)
                return False, (f'是质数({n}) 应当是 {想}，得到 {得!r}。\n'
                               f'      ⚠ {n} = {根} × {根} 是平方数：边界写成 `试除数 * 试除数 < n` 时，'
                               f'试除数到 {根} 循环就退出了，这一对因数没被检查到。')
            return False, f'是质数({n}) 应当是 {想}，得到 {得!r}。'
    return True, '十组都对（含 0、1、负数、平方数 9/25/49、大质数 999983）'


def CHECK_分解质因数(答案):
    f = 答案.__dict__.get('分解质因数')
    if not callable(f):
        return False, ('还没有定义「分解质因数」。思路：从 2 开始能整除就一直除；\n'
                       '      最后剩下的 n 大于 1 就接在结果后面。')
    for n, 想 in ((12, [2, 2, 3]), (2, [2]), (1, []), (0, []), (-6, []), (97, [97]),
                  (100, [2, 2, 5, 5]), (1024, [2] * 10), (999983, [999983])):
        try:
            得 = f(n)
        except Exception as e:                                  # noqa: BLE001
            return False, f'分解质因数({n}) 出错：{type(e).__name__}: {e}'
        if list(得) != 想:
            return False, (f'分解质因数({n}) 应当是 {想}，得到 {得!r}。'
                           f'（要**升序**列表；97 这种本身就是质数的要原样留下）')
        import math
        积 = math.prod(得)
        if n >= 2 and 积 != n:
            return False, (f'分解质因数({n}) 得到 {得!r}，乘起来是 {积}，不等于 {n}。\n'
                           f'      ⚠ 因数乘回去必须还原成原来的数。')
    return True, '九组都对（含 0、1、负数、大质数、2 连乘 10 次的 1024）'


def CHECK_约数个数(答案):
    f = 答案.__dict__.get('约数个数')
    if not callable(f):
        return False, ('还没有定义「约数个数」。写法一：约数们(n) 数长度；'
                       '写法二：(a+1)(b+1)… 的公式。')
    for n, 想 in ((1, 1), (2, 2), (12, 6), (36, 9), (97, 2), (100, 9),
                  (1024, 11), (0, 0), (-5, 0), (999983, 2)):
        try:
            得 = f(n)
        except Exception as e:                                  # noqa: BLE001
            return False, f'约数个数({n}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'约数个数({n}) 应当是 {想}，得到 {得!r}。'
                           f'（别漏了 n 自己：12 的约数是 1、2、3、4、6、12）')
    return True, '十组都对（含 1、0、负数、质数、1024 = 2¹⁰）'


def CHECK_约数们(答案):
    f = 答案.__dict__.get('约数们')
    if not callable(f):
        return False, ('还没有定义「约数们」。写法：只试到 √n —— 发现约数 约 时，'
                       'n // 约 也是约数（成对出现），最后别忘 排序。')
    for n, 想 in ((1, [1]), (12, [1, 2, 3, 4, 6, 12]), (97, [1, 97]),
                  (36, [1, 2, 3, 4, 6, 9, 12, 18, 36]),
                  (100, [1, 2, 4, 5, 10, 20, 25, 50, 100]), (0, []), (-5, []),
                  (1024, [2 ** k for k in range(11)])):
        try:
            得 = f(n)
        except Exception as e:                                  # noqa: BLE001
            return False, f'约数们({n}) 出错：{type(e).__name__}: {e}'
        if list(得) != 想:
            return False, (f'约数们({n}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 要升序、要含 1 和 n 自己、别漏掉平方根那个（如 36 里的 6）。')
    return True, '八组都对（含 1、0、负数、质数、完全平方数 36、1024）'
