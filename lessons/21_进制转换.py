# ─────────────────────────────────────────────────────
#  先介绍：计算机只会数 0 和 1
# ─────────────────────────────────────────────────────
# 一根线只有「通电 / 不通电」两种状态，所以计算机里一切都是 0 和 1。
# 但一串 1 和 0 太长、太难读，于是人们用 8 进制、16 进制来缩写它。
# 这四个进制在 Python 里都是一等公民，而且**有现成函数**，不用自己换算。
# ─────────────────────────────────────────────────────
#  一、同一个数，四种写法
# ─────────────────────────────────────────────────────
#    10          十进制   0~9，平时写的数
#    0b1010      二进制   只有 0 和 1，前面写 0b
#    0o12        八进制   0~7，前面写 0o
#    0xa         十六进制 0~9 和 a~f（a 是 10、f 是 15），前面写 0x
#   ⚠ 这四个**是同一个数**：
#    10 == 0b1010 == 0o12 == 0xa      ⇒ True
#    print(0b1010)                    ⇒ 10      （打印出来一律是十进制）
# ─────────────────────────────────────────────────────
#  二、十进制 → 别的进制：bin() oct() hex()
# ─────────────────────────────────────────────────────
#    bin(10)    ⇒ '0b1010'     ⚠ 返回的是**文字**，还带前缀
#    oct(10)    ⇒ '0o12'       hex(255) ⇒ '0xff'   ⚠ 字母是**小写**的
#   ⚠ 不带前缀那一截用切片去掉：bin(10)[2:] ⇒ '1010'
#   ⚠ 它们只吃整数：bin(3.5) ❌ TypeError: 'float' object cannot be interpreted
# ─────────────────────────────────────────────────────
#  三、别的进制 → 十进制：int(文字, 进制)
# ─────────────────────────────────────────────────────
#    int('1010', 2)      ⇒ 10      按二进制读那一串
#    int('0b1010', 2)    ⇒ 10      带前缀也认
#    int('ff', 16)       ⇒ 255     大小写都认
#    int('12', 8)        ⇒ 10      int('1010') ⇒ 1010  ⚠ 不给进制就是十进制
#   ⚠ 第一个参数**必须是文字**（要引号）：
#    int(1010, 2) ❌ TypeError: int() can't convert non-string with explicit base
# ─────────────────────────────────────────────────────
#  四、手算（考试会考过程，代码不一定用得上）
# ─────────────────────────────────────────────────────
#   二进制 → 十进制：按位乘权再相加
#     1011 ⇒ 1×8 + 0×4 + 1×2 + 1×1 = 11
#   十进制 → 二进制：除 2 取余，**倒着读**
#     11÷2=5 余 1　5÷2=2 余 1　2÷2=1 余 0　1÷2=0 余 1   ⇒ 倒着读：1011
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：int() 的第一个参数要加引号
# ─────────────────────────────────────────────────────
#    int(1010, 2)   ❌ TypeError: int() can't convert non-string with explicit base
#    int('1010', 2) ⇒ 10        ✅
#  ⇒ 记忆：**带进制的 int() 是把「一串文字」读成数**，带前缀也认。
#  ⚠ 反过来也要当心：`bin()` 的返回值是文字，不能直接拿去算：
#      bin(5) + bin(3)   ⇒ '0b1010b11'     ← 两个文字**粘**起来了，不报错！
