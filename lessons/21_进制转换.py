def CHECK_二进制文字和十进制(答案):
    if not hasattr(答案, "二进制文字"):
        return False, "还没有定义「二进制文字」。写法：二进制文字 = '1011'   ← 要加引号"
    v = 答案.二进制文字
    if not isinstance(v, str):
        return False, (f"「二进制文字」应当是**文字**（带引号），现在是 {type(v).__name__}：{v!r}\n"
                       f"      ⚠ 1011 是十进制的一千零一十一；'1011' 才是二进制那一串。")
    if v not in ("1011", "0b1011"):
        return False, f"「二进制文字」应当是 '1011'，现在是 {v!r}。"
    if not hasattr(答案, "它的十进制"):
        return False, "还没有定义「它的十进制」。写法：它的十进制 = int(二进制文字, 2)"
    if 答案.它的十进制 != 11:
        return False, (f"「它的十进制」应当是 11，现在是 {答案.它的十进制!r}。\n"
                       f"      ⚠ 二进制 1011 = 8 + 2 + 1 = 11。写法：int(二进制文字, 2)")
    return True, f"{v} ⇒ {答案.它的十进制}"


def CHECK_十六进制(答案):
    if not hasattr(答案, "十进制数"):
        return False, "还没有定义「十进制数」。写法：十进制数 = 255"
    n = 答案.十进制数
    if not isinstance(n, int) or isinstance(n, bool) or n < 16:
        return False, f"「十进制数」应当是一个不小于 16 的整数，现在是 {n!r}。"
    if not hasattr(答案, "它的十六进制"):
        return False, "还没有定义「它的十六进制」。写法：它的十六进制 = hex(十进制数)"
    得 = 答案.它的十六进制
    if not isinstance(得, str) or not 得.lower().startswith("0x"):
        return False, (f"「它的十六进制」应当是 hex() 给出的那种**带 0x 前缀的文字**，"
                       f"现在是 {得!r}\n"
                       f"      ⚠ 少了前缀就只是另一个文字，不是十六进制的写法。")
    if 得.lower() != hex(n):
        return False, (f"hex({n}) 应当是 {hex(n)!r}，现在是 {得!r}。\n"
                       f"      ⚠ 直接写 它的十六进制 = hex(十进制数) 就行，别自己拼。")
    return True, f"hex({n}) = {得!r}"


def CHECK_两个转换函数(答案):
    转十 = 答案.__dict__.get("转十进制")
    转二 = 答案.__dict__.get("转二进制文字")
    if not callable(转十) or not callable(转二):
        return False, ("「转十进制」和「转二进制文字」都要写成函数。写法：\n"
                       "          def 转十进制(文字, 进制):\n"
                       "              return int(文字, 进制)\n"
                       "          def 转二进制文字(数):\n"
                       "              return bin(数)[2:]")
    for 文字, 进制, 想 in (("1011", 2, 11), ("0b1010", 2, 10), ("ff", 16, 255),
                          ("12", 8, 10), ("0", 2, 0), ("1010", 10, 1010)):
        try:
            得 = 转十(文字, 进制)
        except Exception as e:                                  # noqa: BLE001
            return False, f"转十进制({文字!r}, {进制}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"转十进制({文字!r}, {进制}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 写法：return int(文字, 进制)   ← 第二个参数不能丢")
    for 数, 想 in ((10, "1010"), (0, "0"), (255, "11111111"), (1, "1")):
        try:
            得 = 转二(数)
        except Exception as e:                                  # noqa: BLE001
            return False, f"转二进制文字({数}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"转二进制文字({数}) 应当是 {想!r}，得到 {得!r}。\n"
                           f"      ⚠ bin({数}) 给的是 {bin(数)!r} —— 要去掉前面的 0b：bin(数)[2:]")
    return True, "转十进制六组、转二进制文字四组都对"


def CHECK_数几个1(答案):
    f = 答案.__dict__.get("数几个1")
    if not callable(f):
        return False, ("还没有定义函数「数几个1」。写法：\n"
                       "          def 数几个1(数):\n"
                       "              return bin(数).count('1')")
    for 数, 想 in ((0, 0), (1, 1), (10, 2), (255, 8), (7, 3), (8, 1)):
        try:
            得 = f(数)
        except Exception as e:                                  # noqa: BLE001
            return False, f"数几个1({数}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"数几个1({数}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ {数} 的二进制是 {bin(数)!r}，数一数里面有几个 '1'。\n"
                           f"        写法：return bin(数).count('1')")
    return True, "六组都对（含 0 和全是 1 的 255）"
