def _验树(点数, 边们, 总, 选):
    """生成树的硬指标：边数 = 点数-1、连成一片、没环、权和 = 总权值。"""
    if not isinstance(选, list) or len(选) != max(点数 - 1, 0):
        return f"生成树的边数必须是 {max(点数 - 1, 0)} 条（点数-1），得到 {选!r}"
    父, 和 = list(range(点数)), 0

    def 根(x):
        while 父[x] != x:
            x = 父[x]
        return x

    for e in 选:
        if not (isinstance(e, tuple) and len(e) == 3):
            return f"每条边都要写成 (权, 甲, 乙)，得到 {e!r}"
        if e not in 边们 and (e[0], e[2], e[1]) not in 边们:
            return f"选中的边 {e!r} 不在给你的边列表里"
        if 根(e[1]) == 根(e[2]):
            return f"选中的边 {e!r} 让图出了环 —— 生成树不能有环"
        父[根(e[1])] = 根(e[2])
        和 += e[0]
    if 点数 > 1 and len({根(i) for i in range(点数)}) != 1:
        return "选中的边没有把所有点连起来"
    return None if 和 == 总 else f"总权值应当是选中边的和 {和}，得到 {总!r}"


def CHECK_并查集(答案):
    f = 答案.__dict__.get("找根")
    g = 答案.__dict__.get("合并")
    if not callable(f) or not callable(g):
        return False, ("还没有定义「找根」或「合并」。找根(父, x) 要沿着 父[x] 一路往上直到 "
                       "父[x] == x；合并 把两个根接起来，已经同集合就返回 False")
    父 = [0, 1, 2, 3, 4, 5]
    if f(父, 3) != 3:
        return False, f"只管自己的点，找根应当返回它自己：找根(父, 3) 得到 {f(父, 3)!r}"
    if g(父, 0, 1) is not True:
        return False, f"合并(父, 0, 1) 第一次应当是 True，得到 {g(父, 0, 1)!r}"
    if g(父, 0, 1) is not False:
        return False, f"合并(父, 0, 1) 第二次应当是 False（已经同集合），得到 {g(父, 0, 1)!r}"
    if f(父, 1) != f(父, 0):
        return False, f"合过 0 和 1 之后两个根应当相等，得到 {f(父, 0)!r} 和 {f(父, 1)!r}"
    if g(父, 2, 3) is not True or g(父, 3, 4) is not True or g(父, 4, 2) is not False:
        return False, "合并(2,3)=True、合并(3,4)=True、合并(4,2)=False（2、3、4 已连成一片）"
    if f(父, 4) != f(父, 2) or f(父, 5) == f(父, 2):
        return False, (f"链式合并 2-3、3-4 之后 4 和 2 应当同根，5 应当还是自己一个集合；"
                       f"现在的根是 {[f(父, i) for i in range(6)]}")
    if g(父, 5, 5) is not False:
        return False, f"合并(父, 5, 5) 应当是 False（自己跟自己同集合），得到 {g(父, 5, 5)!r}"
    return True, "单点找根、两次合并、链式找根、自合，全对"


def CHECK_克鲁斯卡尔(答案):
    f = 答案.__dict__.get("最小生成树")
    if not callable(f):
        return False, ("还没有定义「最小生成树」。要点：边按权从小到大排序，用并查集一条条试："
                       "不在同一集合就选它（总权值 += 权），凑够 点数-1 条就停；最后没凑够就是"
                       "不连通，返回 (None, [])")
    for 点数, 边们, 想总 in 用例们:
        try:
            得 = f(点数, 边们)
        except Exception as e:                                  # noqa: BLE001
            return False, f"最小生成树({点数}, {边们!r}) 出错：{type(e).__name__}: {e}"
        if not (isinstance(得, tuple) and len(得) == 2):
            return False, f"最小生成树 应当返回 (总权值, 选中的边列表)，得到 {得!r}"
        总, 选 = 得
        if 想总 is None:
            if 总 is not None or 选 != []:
                return False, f"{点数} 个点、边 {边们!r} **不连通**，应当返回 (None, [])，得到 {得!r}"
            continue
        if 总 != 想总:
            return False, (f"最小生成树({点数}, {边们!r}) 的总权值应当是 {想总}，得到 {总!r}｜"
                           f"按权从小到大挑，凑够 点数-1 = {点数 - 1} 条")
        出 = _验树(点数, 边们, 总, 选)
        if 出:
            return False, f"最小生成树({点数}, {边们!r}) 选出来的边不对：{出}"
    return True, "10 组都对：总权值对、边数都是 点数-1、连成一片而且没有环"


def CHECK_普里姆(答案):
    f = 答案.__dict__.get("普里姆")
    if not callable(f):
        return False, ("还没有定义「普里姆」。要点：从 0 号点开始，每次从「已经进树的点」连出去"
                       "的所有边里挑权最小的（另一端还没进树），把那个点拉进来；拉不动还有点"
                       "没进来就是不连通，返回 None")
    for 点数, 边们, 想总 in 用例们:
        try:
            得 = f(点数, 边们)
        except Exception as e:                                  # noqa: BLE001
            return False, f"普里姆({点数}, {边们!r}) 出错：{type(e).__name__}: {e}"
        if 得 != 想总:
            return False, (f"普里姆({点数}, {边们!r}) 应当是 {想总!r}，得到 {得!r}｜"
                           f"不连通要返回 None；它和 Kruskal 算出的总权值必须一样")
    return True, "10 组都和 Kruskal 的总权值一致（含单点、不连通、重边、自环、有环）"
