# ─────────────────────────────────────────────────────
#  先介绍：修路要花最少的钱
# ─────────────────────────────────────────────────────
#
# 有 n 个村子，修一条路有花费，要求**所有村子都能互相走到**、花的钱最少。选出来的路
# 一定是一棵**树**（有环就去掉环上最贵的那条，更省），所以叫**最小生成树** —— n 个点
# 的树正好有 **n-1 条边**。边的格式是 (权, 甲, 乙)：
#     边们 = [(1, 0, 1), (2, 1, 2), (3, 0, 2), (4, 2, 3), (5, 0, 3)]
#
# ─────────────────────────────────────────────────────
#  一、Kruskal：边按权排序，能加就加
# ─────────────────────────────────────────────────────
#
#     ① 所有边按权从小到大排序
#     ② 一条条看：两端**还没连通**就选它；已经连通就跳过（加了会成环）
#     ③ 选够 n-1 条就停
#
# 上面那张图排序后是 1、2、3、4、5：选 (1,0,1)、(2,1,2)，(3,0,2) 会成环跳过，再选
# (4,2,3) 就够 3 条 = 4-1，停。总权值 = 1+2+4 = **7**。② 里的「通没通」用**并查集**
# 判断：每个集合挑一个「根」，父[x] 记着 x 的上一层，父[x] == x 的那个就是根。判断两点
# 通不通 = 比它们的根是不是同一个；合并 = 把一个根接到另一个根上。
#
# ─────────────────────────────────────────────────────
#  二、Prim：从一个点开始，每次拉最近的进来
# ─────────────────────────────────────────────────────
#
#     ① 随便挑一个点进树（一般挑 0 号）
#     ② 从「树里的点连出去」的所有边里挑权最小的那条，把另一端点拉进树
#     ③ 重复 ②，直到所有点都进树
# 同一张图从 0 号点开始：进 0 → 候选 0-1(1)、0-2(3)、0-3(5) → 拉 1（权 1）→ 候选多了
# 1-2(2) → 拉 2（权 2）→ 候选多了 2-3(4) → 拉 3（权 4）。总权值也是 **7**。
#
# ─────────────────────────────────────────────────────
#  三、什么时候用哪个
# ─────────────────────────────────────────────────────
#
#     Kruskal：O(E log E)，贵在排序 —— 边少的**稀疏**图更快（1000 个点、2000 条边）
#     Prim   ：O(V²)（朴素）/ O(E log V)（配堆）—— 边多的**稠密**图更快（1000 个点
#              最多 499500 条边，这时 Kruskal 光排序就比 Prim 慢）
#
# 两种算法算出来的**总权值一定一样**（生成树可能不止一棵，总权值唯一），检查里就是拿
# 它俩互相印证。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：找根只往上看了一层
# ─────────────────────────────────────────────────────
#
#     def 找根(父, x):
#         return 父[x]                  ❌ 链式合并（0→1→2→3）之后就不对了
# 它**不报错**：只是该跳过的边没被跳过，选出来的东西带环，总权值悄悄偏大。
# ⇒ 找根必须一路跟到底：`while 父[x] != x: x = 父[x]`。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   次小生成树、最小树形图、Boruvka —— 用到再说，这一课只讲这两个。
