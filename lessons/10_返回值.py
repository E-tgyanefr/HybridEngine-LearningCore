# ─────────────────────────────────────────────────────
#  先介绍：print 和 return 完全不是一回事
# ─────────────────────────────────────────────────────
#
# 这是初学者最大的一个坎。看两个函数：
#
#     def 甲(x):
#         print(x * 2)          ← 只是**打出来给你看**
#
#     def 乙(x):
#         return x * 2          ← **把结果交出去**，给调用它的人
#
# 用起来差别巨大：
#
#     甲(5)            ⇒ 屏幕上是 10，但你**拿不到**这个 10
#     得 = 甲(5)        ⇒ 得 是 **None**！（函数没交东西出来）
#
#     乙(5)            ⇒ 屏幕上**什么都没有**
#     得 = 乙(5)        ⇒ 得 是 10 ✅
#
#   ⇒ 一句话：**print 是给人看的，return 是给程序用的。**
#
#   什么时候用哪个：
#     · 只想让你看到 → print
#     · 结果还要接着算（再相加、再比较、存起来）→ **return**
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课唯一的坑：忘了 return，拿到 None
# ─────────────────────────────────────────────────────
#
#     def 算平均(分数表):
#         和 = sum(分数表) / len(分数表)
#                                   ← 没写 return！
#
#     算平均([60, 80])        ⇒  None
#     算平均([60, 80]) + 1    ⇒  TypeError: unsupported operand type(s) for +: 'NoneType' and 'int'
#
#   ⇒ 看到 **`NoneType`** 出现在报错里，八成就是"某个函数忘了 return"。
#     这是最值得记住的一条排错线索。
#
# ─────────────────────────────────────────────────────
#  return 还有一个作用：立刻结束函数
# ─────────────────────────────────────────────────────
#
#     def 判等级(分数):
#         if 分数 >= 90:
#             return "优秀"          ← 到这里就结束了
#         return "其他"              ← 上面返回过就不会走到这里
#
#   ⚠ `return` 之后的代码**不会被执行**。写多了也是白写（而且会让人看不懂）。
#
# ─────────────────────────────────────────────────────
#  一个函数可以返回多个值 —— 其实是一个"元组"
# ─────────────────────────────────────────────────────
#
#     def 统计(数字们):
#         return len(数字们), sum(数字们)
#              ↑ 用逗号隔开
#
#     个数, 总和 = 统计([1, 2, 3])      ⇒  个数=3，总和=6      （自动拆开）
#     整个 = 统计([1, 2, 3])            ⇒  整个=(3, 6)        （其实是一个东西）
#
#   ⚠ 不是真的返回两个，而是返回了一个**元组** `(3, 6)`。
#     左边用两个变量接的时候自动拆开 —— 这叫"解包"。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   带默认值的参数是第 11 课，接收任意多个是第 12 课。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 写函数 平方(数)，**返回**它的平方
#   2. 写函数 统计(数字们)，**返回**一个元组：(个数, 总和)
#
#   ⚠ 两个都要用 return，不要用 print —— 检查会拿走返回值去比对。
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 10


def CHECK_平方(答案):
    if not hasattr(答案, "平方"):
        return False, "还没有定义「平方」函数。写法：def 平方(数): return 数 * 数"
    if not callable(答案.平方):
        return False, "「平方」不是函数。"
    for n, 期望 in ((3, 9), (0, 0), (-4, 16), (1, 1)):
        try:
            得 = 答案.平方(n)
        except Exception as e:                                  # noqa: BLE001
            return False, f"平方({n}) 出错了：{type(e).__name__}: {e}"
        if 得 is None:
            return False, (f"平方({n}) 返回了 **None** —— **函数里忘了 `return`**。\n"
                           f"      ⚠⚠ print 和 return 是两回事：\n"
                           f"         print(x * x)     只是打出来给你看，函数没交东西出去\n"
                           f"         return x * x     把结果交给调用它的人 ✅\n"
                           f"      （看到报错里有 `NoneType`，八成就是这个原因。）")
        if 得 != 期望:
            return False, (f"平方({n}) 应当是 {期望}，实际是 {得!r}。\n"
                           f"      ⚠ 负负得正：(-4) × (-4) = 16。")
    return True, "3 / 0 / -4 / 1 都对"


def CHECK_统计(答案):
    if not hasattr(答案, "统计"):
        return False, "还没有定义「统计」函数。"
    if not callable(答案.统计):
        return False, "「统计」不是函数。"
    try:
        得 = 答案.统计([1, 2, 3])
    except Exception as e:                                      # noqa: BLE001
        return False, f"统计([1,2,3]) 出错了：{type(e).__name__}: {e}"
    if 得 is None:
        return False, "统计([1,2,3]) 返回了 None —— 忘了 `return`。"
    if not isinstance(得, tuple):
        return False, (f"「统计」应当返回**元组**，现在返回的是 {type(得).__name__}：{得!r}\n"
                       f"      写法：return len(数字们), sum(数字们)\n"
                       f"      ⚠ 两个值用逗号隔开 —— 那在 Python 里就是一个元组。")
    if 得 != (3, 6):
        return False, (f"统计([1,2,3]) 应当是 (3, 6)（个数, 总和），实际是 {得!r}。\n"
                       f"      ⚠ 顺序是**先个数后总和**。")
    if 答案.统计([]) != (0, 0):
        return False, f"统计([]) 应当是 (0, 0)，实际是 {答案.统计([])!r}。"
    return True, "含空列表都对"


def CHECK_没用print代替return(答案):
    """⚠ 这一课的核心：结果要 return 出去，不是打出来。"""
    import io
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    有问题 = []
    for 名 in ("平方", "统计"):
        i = 源码.find("def " + 名)
        if i < 0:
            continue
        段 = 源码[i:i + 400]
        if "return" not in 段 and "print(" in 段:
            有问题.append(名)
    if 有问题:
        return False, (f"「{'、'.join(有问题)}」里只有 print、没有 return。\n"
                       f"      ⚠⚠ print 是**给人看**的，return 是**给程序用**的。\n"
                       f"         检查会拿走你的返回值去比对 —— print 出来的东西拿不到。")
    return True, "结果都是 return 出去的"
