# 第 05 课：函数 —— 把一件事打包，还能给默认值


# ─────────────────────────────────────────────────────
#  先介绍：三个让函数好用的语法点
# ─────────────────────────────────────────────────────
#
#  ① **默认参数** —— 调用时可以不传
#
#         def 问候(名字, 称呼="同学"):
#             ...
#
#         问候("小明")            用默认的"同学"
#         问候("小明", "老师")     传了就用传的
#
#     ⚠ 有默认值的参数必须写在**后面**。
#        def f(a="x", b) 是语法错误。
#
#  ② **返回多个值** —— 其实返回的是一个**元组**
#
#         def 统计(数字们):
#             return len(数字们), sum(数字们)
#
#         个数, 总和 = 统计([1,2,3])      ← 这样「拆开」接住（叫解包）
#
#     ⚠ 不是真的返回了两个东西，而是返回了一个元组 (3, 6)，
#       左边用两个变量接的时候自动拆开。这一点在用到「整个返回值」时会露出来：
#         x = 统计([1,2,3])   ⇒ x 是 (3, 6)，不是 3
#
#  ③ **任意多个参数** —— 参数名前面加一个星号
#
#         def 加全部(*数字):
#             ...
#
#         加全部(1, 2, 3)      数字 是 (1, 2, 3)
#         加全部()             数字 是 ()   ← 空元组，要返回 0
#
#     ⚠ *数字 收进来的是**元组**，不是列表。
#       所以第 2 条返回元组、第 3 条接收元组 —— 这一课在练同一件事。
#
# ─────────────────────────────────────────────────────
#  为什么值得单独一课
# ─────────────────────────────────────────────────────
#
# 默认参数和 *args 不是「花哨语法」，它们决定了一个函数**好不好用**：
#
#     print(...)          能接任意多个 —— 所以你能一次打一堆东西
#     sorted(列表)        默认从小到大，但能 reverse=True 改 —— 所以常用
#
# 你以后写工具函数时，「要不要给个默认值」「要不要支持任意多个」
# 就是判断一个函数成熟不成熟的标准。
#
# ─────────────────────────────────────────────────────
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在下面的答题文件里写这几件事
# ─────────────────────────────────────────────────────
#
#   1. 写函数 问候(名字, 称呼="同学")，返回 "你好，<名字><称呼>！"
#      例如 问候("小明")        → "你好，小明同学！"
#           问候("李老师", "老师") → "你好，李老师老师！"
#      ⚠ 「称呼」要**有默认值**，不传也能调用
#   2. 写函数 统计(数字们)，返回一个**元组** (个数, 总和)
#   3. 写函数 加全部(*数字)，接收**任意多个**参数，返回它们的和
#
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 05


def CHECK_问候(答案):
    if not hasattr(答案, "问候"):
        return False, '还没有定义「问候」函数。写法：def 问候(名字, 称呼="同学"): ...'
    if not callable(答案.问候):
        return False, "「问候」不是函数。"
    try:
        一个 = 答案.问候("小明")
    except TypeError as e:
        return False, (f"问候('小明') 调用失败：{e}\n"
                       f"      ⚠ 说明「称呼」**没有默认值** —— 这一课的第一个要求就是它。\n"
                       f"        写法：def 问候(名字, 称呼='同学'):")
    except Exception as e:                                      # noqa: BLE001
        return False, f"问候('小明') 出错了：{type(e).__name__}: {e}"
    if 一个 != "你好，小明同学！":
        return False, (f"问候('小明') 应当是 '你好，小明同学！'，实际是 {一个!r}。\n"
                       f"      对照标点：逗号、感叹号都要一致；「同学」是默认称呼。")
    try:
        两个 = 答案.问候("李老师", "老师")
    except Exception as e:                                      # noqa: BLE001
        return False, f"问候('李老师', '老师') 出错了：{type(e).__name__}: {e}"
    if 两个 != "你好，李老师老师！":
        return False, (f"问候('李老师', '老师') 应当是 '你好，李老师老师！'，"
                       f"实际是 {两个!r}。\n"
                       f"      ⚠ 传了第二个参数时要用**传进来的那个**，不能还是写死「同学」。")
    return True, "默认参数与显式传参都对"


def CHECK_统计(答案):
    if not hasattr(答案, "统计"):
        return False, "还没有定义「统计」函数。"
    if not callable(答案.统计):
        return False, "「统计」不是函数。"
    得 = 答案.统计([1, 2, 3])
    if not isinstance(得, tuple):
        return False, (f"「统计」应当返回**元组**（Python 里 return a, b 就是元组），"
                       f"现在返回的是 {type(得).__name__}：{得!r}\n"
                       f"      写法：return len(数字们), sum(数字们)")
    if 得 != (3, 6):
        return False, (f"统计([1,2,3]) 应当是 (3, 6)（个数, 总和），实际是 {得!r}。\n"
                       f"      ⚠ 顺序是**先个数后总和**。")
    if 答案.统计([]) != (0, 0):
        return False, f"统计([]) 应当是 (0, 0)，实际是 {答案.统计([])!r}。"
    if 答案.统计([5]) != (1, 5):
        return False, f"统计([5]) 应当是 (1, 5)，实际是 {答案.统计([5])!r}。"
    return True, "三组都对（含空列表）"


def CHECK_加全部(答案):
    if not hasattr(答案, "加全部"):
        return False, ('还没有定义「加全部」函数。写法：def 加全部(*数字): ...')
    if not callable(答案.加全部):
        return False, "「加全部」不是函数。"
    try:
        得 = 答案.加全部(1, 2, 3)
    except TypeError as e:
        return False, (f"加全部(1, 2, 3) 调用失败：{e}\n"
                       f"      ⚠ 说明参数前面**少了那个星号**。\n"
                       f"        写法：def 加全部(*数字):")
    except Exception as e:                                      # noqa: BLE001
        return False, f"加全部(1, 2, 3) 出错了：{type(e).__name__}: {e}"
    if 得 != 6:
        return False, f"加全部(1, 2, 3) 应当是 6，实际是 {得!r}。"
    if 答案.加全部() != 0:
        return False, (f"加全部() （一个都不传）应当是 0，实际是 {答案.加全部()!r}。\n"
                       f"      ⚠ 不传时 `数字` 是空元组 ()，sum(()) 正好是 0 ——\n"
                       f"        用 sum 就自然对了；自己写循环的话记得起点是 0。")
    if 答案.加全部(5) != 5:
        return False, f"加全部(5) 应当是 5，实际是 {答案.加全部(5)!r}。"
    if 答案.加全部(1, 2, 3, 4, 5, 6, 7, 8) != 36:
        return False, f"加全部(1..8) 应当是 36，实际是 {答案.加全部(1,2,3,4,5,6,7,8)!r}。"
    return True, "任意个参数都对（含 0 个与 1 个）"
