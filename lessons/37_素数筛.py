def _参考筛(n):
    """课程自己用的埃氏筛 —— 不依赖学生的答案，免得两边一起错。"""
    标记 = [True] * max(n + 1, 2)
    标记[0] = 标记[1] = False
    for p in range(2, int(n ** 0.5) + 1):
        if 标记[p]:
            for 倍 in range(p * p, n + 1, p):
                标记[倍] = False
    return [i for i in range(2, n + 1) if 标记[i]]


def CHECK_筛质数(答案):
    f = 答案.__dict__.get('筛质数')
    if not callable(f):
        return False, ('还没有定义「筛质数」。骨架：标记 = [True] * (n + 1)；把 0、1 标成 False；p 从 2 筛到 p * p <= n，把 p*p、p*p+p、… 标掉。')
    for n in (0, 1, 2, 3, 10, 100, 1000, 10000, 100000):
        想 = _参考筛(n)
        try:
            得 = f(n)
        except Exception as e:                                  # noqa: BLE001
            if isinstance(e, IndexError):
                return False, (f'筛质数({n}) 抛了 IndexError: {e}\n'
                               f'      ⚠ 十有八九是长度写成 `[True] * n` 了，要写 `[True] * (n + 1)`。')
            return False, f'筛质数({n}) 出错：{type(e).__name__}: {e}'
        if list(得) != 想:
            if len(得) != len(想):
                多 = sorted(set(得) - set(想))
                return False, (f'筛质数({n}) 应当有 {len(想)} 个质数，得到 {len(得)} 个。\n'
                               f'      ⚠ 多出来的：{多[:5]} —— 最常见的原因是'
                               f'忘了把 0 和 1 标成非质数。')
            for i, (a, b) in enumerate(zip(list(得), 想)):
                if a != b:
                    return False, (f'筛质数({n}) 的第 {i} 个应当是 {b}，得到 {a} —— '
                                   f'要升序，合数不能被留下。')
    return True, '九组都对（n = 0/1/2/3/10/100/1000/10000/100000，最后一个 9592 个）'


def CHECK_质数个数(答案):
    import time
    f = 答案.__dict__.get('质数个数')
    if not callable(f):
        return False, '还没有定义「质数个数」。写法：return len(筛质数(n))。'
    for n, 想 in ((0, 0), (1, 0), (2, 1), (10, 4), (100, 25), (1000, 168),
                  (10000, 1229), (100000, 9592)):
        try:
            得 = f(n)
        except Exception as e:                                  # noqa: BLE001
            return False, f'质数个数({n}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'质数个数({n}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 100→25、1000→168、10000→1229、100000→9592。')
    t0 = time.perf_counter()
    try:
        大 = f(1000000)
    except Exception as e:                                      # noqa: BLE001
        return False, f'质数个数(1000000) 出错：{type(e).__name__}: {e}'
    秒 = time.perf_counter() - t0
    if 大 != 78498:
        return False, f'质数个数(1000000) 应当是 78498，得到 {大!r}。'
    if 秒 > 1.5:
        return False, (f'质数个数(1000000) 算对了，但用了 **{秒:.1f} 秒** —— 太慢了。\n'
                       f'      ⚠ 这是"一个一个判"的写法：1000000 以内要约 6774 万次取余（实测 4 秒）。\n'
                       f'        埃氏筛只要约 212 万次标记，实测 0.12 秒。')
    return True, f'九组都对（含 0、1、大数），1000000 那组用了 {秒:.3f} 秒'


def CHECK_最小质因数表(答案):
    f = 答案.__dict__.get('最小质因数表')
    if not callable(f):
        return False, ('还没有定义「最小质因数表」。做法：i 从 2 往后走，没被标过的 i 就是\n'
                       '      质数，用它去标自己的倍数（只标还没标的）。')
    for n, 想 in ((0, [0]), (1, [0, 0]), (2, [0, 0, 2]), (3, [0, 0, 2, 3]),
                  (10, [0, 0, 2, 3, 2, 5, 2, 7, 2, 3, 2]),
                  (20, [0, 0, 2, 3, 2, 5, 2, 7, 2, 3, 2, 11, 2, 13, 2, 3, 2, 17, 2, 19, 2])):
        try:
            得 = f(n)
        except Exception as e:                                  # noqa: BLE001
            return False, f'最小质因数表({n}) 出错：{type(e).__name__}: {e}'
        if list(得) != 想:
            return False, (f'最小质因数表({n}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 长度是 n+1（下标 0…n），0 和 1 存 0；4 的最小质因数是 2，不是 4。')
    try:
        表 = list(f(1000))
    except Exception as e:                                      # noqa: BLE001
        return False, f'最小质因数表(1000) 出错：{type(e).__name__}: {e}'
    if len(表) != 1001:
        return False, f'最小质因数表(1000) 的长度应当是 1001，得到 {len(表)}。'
    for i in range(2, 1001):
        if 表[i] < 2 or i % 表[i] != 0:
            return False, (f'最小质因数表(1000) 里下标 {i} 存的是 {表[i]}，它不是 {i} 的因数 —— '
                           f'每个位置要存**能整除它的最小质数**。')
    return True, '六组都对（含 0、1、2、3、10、20），1000 那张表逐项查过'
