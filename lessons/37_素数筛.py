# ─────────────────────────────────────────────────────
#  先介绍：判一个数，和找出所有质数，是两回事
# ─────────────────────────────────────────────────────
# 第 35 课的 是质数(n) 一次只回答一个问题。要 100000 以内的全部质数，一个个判
# 实测约 **274 万次**取余（0.15 秒）。埃氏筛换个方向：**不去判，把合数划掉** ——
# 先假设 2…n 全是质数，再把 2、3、5…的倍数挨个划掉，只要约 **19 万次**标记（0.01 秒）。
#
# ─────────────────────────────────────────────────────
#  一、埃氏筛：把合数划掉
# ─────────────────────────────────────────────────────
#     def 筛质数(n):
#         if n < 2: return []
#         标记 = [True] * (n + 1)        ← ⚠ 长度是 n + 1，不是 n
#         标记[0] = 标记[1] = False      ← ⚠ 0 和 1 不是质数
#         for 质数 in range(2, int(n ** 0.5) + 1):
#             if 标记[质数]:
#                 for 倍数 in range(质数 * 质数, n + 1, 质数):   ← 从 p*p 开始
#                     标记[倍数] = False
#         return [i for i in range(n + 1) if 标记[i]]
#
#     筛质数(2) ⇒ [2]    筛质数(10) ⇒ [2, 3, 5, 7]    筛质数(100) ⇒ 25 个，末位 97
# 外层只筛到 √n：合数 m 的最小质因数一定 ≤ √m（同 第 35 课）。
# 内层从 p*p 开始：p 的 `2p、3p、…、(p-1)p` 都含一个比 p 小的质因数，早被划掉了 ——
# 跳过它们，n = 100000 时标记次数从几十万降到约 19 万。
#
# ─────────────────────────────────────────────────────
#  三、线性筛：每个合数只划一次
# ─────────────────────────────────────────────────────
# 埃氏筛里 12 会被 2 和 3 各划一次。线性筛只让每个合数被它的**最小质因数**划掉，
# 总标记次数不超过 n 次，复杂度是干净的 O(n)。副产品就是**最小质因数表**：
#     最小质因数表(20) = [0, 0, 2, 3, 2, 5, 2, 7, 2, 3, 2, 11, 2, 13, 2, 3, 2, 17, 2, 19, 2]
#
# ─────────────────────────────────────────────────────
#  四、快多少（实测数字，这张表就是这一课的重点）
# ─────────────────────────────────────────────────────
#                        n = 100000          n = 1000000
#     一个一个判         274 万次  0.15 秒    6774 万次  4.0 秒
#     埃氏筛             19 万次   0.01 秒    212 万次   0.12 秒
#     质数个数：100 → 25    1000 → 168    10000 → 1229    100000 → 9592    1000000 → 78498
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：标记表的长度忘了 +1
# ─────────────────────────────────────────────────────
#     def 筛质数(n):                  # ← 错的版本
#         标记 = [True] * n            ← 下标只到 n - 1
#         标记[倍数] = False
#
#     筛质数(100)  ⇒  IndexError: list assignment index out of range
#
# n = 100 时表只有下标 0…99，2 的倍数里有 100 写不进去。长度一律写 `n + 1`。
# ⚠ 这个错只在某些 n 上暴露（筛质数(7) 反而能过）；另一个同样隐蔽的错是
#   忘了把 0 和 1 标成非质数 —— 筛质数(10) 得到 `[0, 1, 2, 3, 5, 7]`，多两个，不报错。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课只讲筛法；约数个数、唯一分解定理在 第 35 课，这里不重复。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 写函数 筛质数(n)：返回 ≤ n 的**全部质数**（升序列表）；n < 2 返回 []
# 2. 写函数 质数个数(n)：返回 ≤ n 的质数个数
# 3. 写函数 最小质因数表(n)：返回长度 **n+1** 的列表，下标 i（i ≥ 2）存 i 的
#    **最小质因数**；下标 0 和 1 存 0
