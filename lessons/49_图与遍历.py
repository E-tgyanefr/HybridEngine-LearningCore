# ─────────────────────────────────────────────────────
#  先介绍：图就是「点 + 边」
# ─────────────────────────────────────────────────────
#
# 前面处理的东西要么排成一排（列表），要么一层层分好（树）。图更松：任意两个点都可能
# 有边，还可能有环。两种存法都要会看：
#
#     邻接表（字典）：{0: [1], 1: [0, 2], 2: [1]}   只存有的边，省地方
#     邻接矩阵（二维列表）：矩阵[甲][乙] = 1 有边   查两点有没有边最快，但 n 个点要
#                          开 n² 格 —— 1000 个点就是 100 万格
#
# ⚠ 无向图的边要**两边都写**：(0,1) 既要在 表[0] 里加 1，也要在 表[1] 里加 0；只写
#   一边，从 1 出发就搜不到 0，这是这一课最容易犯的错。
# ─────────────────────────────────────────────────────
#  一、DFS：一条路走到黑，走不动再回头
# ─────────────────────────────────────────────────────
#
# 从起点出发，随便挑一个没去过的邻居一头扎进去；走不动了退回来再挑。图 0-1、0-2、
# 1-3 从 0 出发的 DFS 是 0 → 1 → 3 → 2（1 只连着 3，退回来再走 2）。
#
#     def 深度优先(邻接表, 点, 去过):
#         去过.add(点)                     ← 进门先标记
#         for 邻 in 邻接表[点]:
#             if 邻 not in 去过: 深度优先(邻接表, 邻, 去过)      ← 出门前先问
# ⚠ 邻居的先后顺序会影响 DFS 的具体次序，所以检查只看「次序合不合法」，不抠顺序。
#
# ─────────────────────────────────────────────────────
#  二、BFS：一层一层往外扩
# ─────────────────────────────────────────────────────
#
# 用一个**队列**（先来先服务）：起点进队 → 出队一个，把它的邻居全进队……
#
#     队 = deque([起点])
#     while 队:
#         点 = 队.popleft()      ← popleft 是 O(1)；list.pop(0) 要搬整个列表
#         for 邻 in 邻接表[点]:
#             if 邻 not in 去过: 去过.add(邻); 队.append(邻)
#
# BFS 走完一圈，每个点**第一次被访问时的层数**就是它到起点的最短步数：0-1、0-2、1-3
# 里，0 到 3 最短是 2 步（0→1→3），不是 3 步。
#
# ─────────────────────────────────────────────────────
#  三、连通块：一堆点能不能互相走到
# ─────────────────────────────────────────────────────
#
# 从没去过的点出发做一次完整遍历，能走到的全归一块；再找下一个没去过的点。
#     0-1、2-3、4 ⇒ 3 块（4 自己一块）；0-1、1-2、2-0 三角形 ⇒ 1 块
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：忘了标记「已访问」
# ─────────────────────────────────────────────────────
#
#     def 深度优先(邻接表, 点, 去过):
#         for 邻 in 邻接表[点]: 深度优先(邻接表, 邻, 去过)      ❌ 从头到尾没记「去过」
#
# 图里有环时：0 → 1 → 0 → 1 → … 永远出不来，最后是
#     RecursionError: maximum recursion depth exceeded
# ⇒ 两句话：**进门先标记**（去过.add(点)），**出门前先问**（if 邻 not in 去过）。
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   带权图、有向图、最短路 —— 第 53 课才讲，这一课只讲「怎么把图走一遍」。
