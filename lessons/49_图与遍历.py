def _喂(函数, 名字, 用例们, 提示):
    for 用例 in 用例们:
        *参数们, 想 = 用例
        try:
            得 = 函数(*参数们)
        except Exception as e:                                  # noqa: BLE001
            return False, f"{名字}{tuple(参数们)} 出错：{type(e).__name__}: {e}｜{提示}"
        if 得 != 想:
            return False, f"{名字}{tuple(参数们)} 应当是 {想!r}，得到 {得!r}｜{提示}"
    return True, f"{len(用例们)} 组都对"


def _验遍历(答案, 名字, 要点, 按层):
    f = 答案.__dict__.get(名字)
    if not callable(f):
        return False, f"还没有定义「{名字}」。要点：{要点}"
    for 表, 起点 in (({0: [1], 1: [0, 2], 2: [1]}, 0), ({0: [1, 2], 1: [0, 3], 2: [0], 3: [1]}, 0),
                     ({0: [1], 1: [0, 2], 2: [1, 3], 3: [2]}, 1), ({0: [], 1: [], 2: []}, 2),
                     ({0: [1, 2, 3], 1: [0], 2: [0], 3: [0]}, 0)):
        try:
            序 = f(表, 起点)
        except Exception as e:                                  # noqa: BLE001
            return False, f"{名字}({表}, {起点}) 出错：{type(e).__name__}: {e}"
        层, 队 = {起点: 0}, [起点]
        while 队:
            点 = 队.pop(0)
            for 邻 in 表.get(点, []):
                if 邻 not in 层:
                    层[邻] = 层[点] + 1
                    队.append(邻)
        if (not isinstance(序, list) or 序[:1] != [起点]
                or len(序) != len(set(序)) or set(序) != set(层)):
            return False, (f"{名字}({表}, {起点}) 应当是从 {起点} 开始、不重复、正好走到 "
                           f"{sorted(层)} 的列表，得到 {序!r}｜{要点}")
        for i in range(1, len(序)):
            if 按层 and 层[序[i]] < 层[序[i - 1]]:
                return False, (f"{名字}({表}, {起点}) 层数倒退了：{序!r}｜BFS 要一层一层往外"
                               f"扩，第 {层[序[i]]} 层的 {序[i]} 不能排在第 {层[序[i-1]]} 层的 "
                               f"{序[i-1]} 前面")
            if not 按层 and not any(序[i] in 表.get(序[j], []) for j in range(i)):
                return False, (f"{名字}({表}, {起点}) 里第 {i+1} 个访问的 {序[i]} 和前面访问过"
                               f"的点都不相邻，DFS 不可能这么走：{序!r}")
    return True, "5 张图：起点、点数、次序都对（具体顺序不抠）"


def CHECK_建邻接表和矩阵(答案):
    f = 答案.__dict__.get("建邻接表")
    g = 答案.__dict__.get("建邻接矩阵")
    if not callable(f) or not callable(g):
        return False, ("还没有定义「建邻接表」或「建邻接矩阵」。邻接表是字典 {点: [邻居...]}"
                       "（无向图两边都要写），矩阵是 点数×点数、有边填 1")
    for 点数, 边们, 想 in ((0, [], {}), (1, [], {0: []}), (2, [(0, 1)], {0: [1], 1: [0]}),
                         (3, [(0, 1), (1, 2), (0, 2)], {0: [1, 2], 1: [0, 2], 2: [0, 1]}),
                         (4, [(0, 0), (1, 2)], {0: [], 1: [2], 2: [1], 3: []})):
        矩 = [[0] * 点数 for _ in range(点数)]
        for 甲, 乙 in 边们:
            if 甲 != 乙:
                矩[甲][乙] = 矩[乙][甲] = 1
        try:
            得表, 得矩 = f(点数, 边们), g(点数, 边们)
        except Exception as e:                                  # noqa: BLE001
            return False, f"建图({点数}, {边们!r}) 出错：{type(e).__name__}: {e}"
        if (not isinstance(得表, dict) or {k: sorted(v) for k, v in 得表.items()} != {k: sorted(v) for k, v in 想.items()}):
            return False, (f"建邻接表({点数}, {边们!r}) 应当是 {想}，得到 {得表!r}｜"
                           f"每个点都要有键（哪怕它没边），无向图的边**两边都要写**，"
                           f"自环 (甲==乙) 忽略")
        if 得矩 != 矩:
            return False, (f"建邻接矩阵({点数}, {边们!r}) 应当是 {矩}，得到 {得矩!r}｜"
                           f"有边填 1、无边填 0，自己到自己填 0（自环不算）")
    return True, "邻接表 5 组、矩阵 5 组都对（含 0 个点、1 个点、自环）"


def CHECK_深度优先(答案):
    return _验遍历(答案, "深度优先", "进门先 去过.add(点)，只对不在 去过 里的邻居递归", 按层=False)


def CHECK_广度优先(答案):
    return _验遍历(答案, "广度优先", "用 deque 当队列：出队一个就把邻居全进队（进队时标记）", 按层=True)


def CHECK_连通块和两点连通(答案):
    f = 答案.__dict__.get("连通块个数")
    g = 答案.__dict__.get("两点连通")
    if not callable(f) or not callable(g):
        return False, "还没有定义「连通块个数」或「两点连通」函数。"
    出 = _喂(f, "连通块个数",
             ((0, [], 0), (1, [], 1), (5, [], 5), (3, [(0, 1), (1, 2)], 1), (4, [(0, 1), (2, 3)], 2),
              (4, [(0, 1), (1, 2), (2, 0)], 2), (2, [(0, 0)], 2), (6, [(0, 1), (2, 3), (4, 5)], 3)),
             "从每个没去过的点出发走一遍，能走到的算一块；0 个点是 0 块，自环 (0,0) 不并点")
    if not 出[0]:
        return 出
    return _喂(g, "两点连通",
               ((3, [(0, 1)], 0, 1, True), (3, [(0, 1)], 0, 2, False), (1, [], 0, 0, True),
                (2, [(0, 1)], 1, 1, True), (4, [(0, 1), (2, 3)], 1, 3, False), (4, [], 0, 3, False)),
               "同一张图里 甲 能不能走到 乙；单点图里 0 到 0 算连通")
