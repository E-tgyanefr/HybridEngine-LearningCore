# 1. 定义二维列表 表 = [[1, 2, 3], [4, 5, 6]]（两行三列，全是整数）
# 2. 定义变量 全部和（先给 0），用**两层 for** 把 表 里所有数加起来（不许用 sum）
# 3. 写一个函数 取一列(表, 列号)：返回这一列的数组成的列表
# 4. 写一个函数 造棋盘(n)：返回 n 行 n 列的棋盘，每格都是 '.'（每行要各造一个）
