# ─────────────────────────────────────────────────────
#  先介绍：一列装不下一张表
# ─────────────────────────────────────────────────────
# 成绩单有 3 行 4 列。用一维列表也装得下，但「第 2 行第 3 个」要自己算下标：
# `成绩[1 * 4 + 2]` —— 一改列数就全乱。二维列表把每一行也做成一个列表，
# 于是「第几行第几个」就是两个下标，一眼看得懂。
# ─────────────────────────────────────────────────────
#  一、长得就是一张表格
# ─────────────────────────────────────────────────────
#    表 = [[1, 2, 3],
#          [4, 5, 6]]         ← 2 行 3 列
#    表[0]        ⇒ [1, 2, 3]    第 0 行（整个一行）
#    表[0][2]     ⇒ 3            第 0 行第 2 列（从 0 开始数）
#    表[1][0]     ⇒ 4            ⚠ 读成 (表[1])[0]：**先取行，再取列**
#    len(表)      ⇒ 2            几行        len(表[0]) ⇒ 3   几列
# ─────────────────────────────────────────────────────
#  二、两层循环：一行一行看过去
# ─────────────────────────────────────────────────────
#    和 = 0
#    for 行 in 表:          ← 外层拿到的是一**行**
#        for x in 行:       ← 内层拿到的是行里的**一个数**
#            和 += x        ⇒ 21
#   要行号列号就用 range：
#    for i in range(len(表)):
#        for j in range(len(表[i])):
#            print(i, j, 表[i][j])
#   ⚠ 里层写 `range(len(表[0]))` 也能跑，但**每行长度不一样时会越界**；
#     写成 `len(表[i])` 才跟着当前这一行走。
# ─────────────────────────────────────────────────────
#  三、按列取：先定列号，再走遍每一行
# ─────────────────────────────────────────────────────
#    第 1 列 = [表[0][1], 表[1][1]]     ⇒ [2, 5]
#   ⚠ 按行还是按列，区别只在**谁在外层**：按列时外层是列号、内层是行号。
#     写错了不报错，只是结果不对 —— `表[0]` 是一整行，不是一列。
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：每行要各造一个
# ─────────────────────────────────────────────────────
#   造棋盘想省事，很容易这么写：
#    棋盘 = [['.'] * 3] * 3      ← ❌ 三行是**同一个列表**
#    棋盘[0][0] = 'X'
#    print(棋盘)   ⇒ [['X', '.', '.'], ['X', '.', '.'], ['X', '.', '.']]
#   ⚠ 三行一起变了，而且**不报错** —— 这种错最难查。
#     `['.'] * 3` 造了一个新列表；`* 3` 只是把**同一个**列表的引用放了三次
#     （第 05 课讲过的「别名」）。
#  ⇒ 每一行都要**各造一个**（第 19 课的嵌套解析正好合用）：
#    棋盘 = [['.' for _ in range(3)] for _ in range(3)]
#   ⚠ `_` 是「这个变量我用不上」的约定写法，不是关键字。
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   只讲「列表套列表」和一格一格地访问。矩阵运算（转置、乘法）用到再说。
# ─────────────────────────────────────────────────────
