def CHECK_表和全部和(答案):
    if not hasattr(答案, "表"):
        return False, "还没有定义「表」。写法：表 = [[1, 2, 3], [4, 5, 6]]"
    v = 答案.表
    if not isinstance(v, list) or len(v) < 2 or not all(isinstance(行, list) for 行 in v):
        return False, f"「表」应当是**列表套列表**（每一行也要方括号），现在是 {type(v).__name__}：{v!r}"
    if len({len(行) for 行 in v}) != 1 or len(v[0]) < 2:
        return False, f"「表」每行长度应当一样、至少 2 列 —— 现在是 {[len(x) for x in v]}"
    if not all(isinstance(x, int) and not isinstance(x, bool) for 行 in v for x in 行):
        return False, f"「表」里应当都是整数，现在是 {v!r}。"
    if not hasattr(答案, "全部和"):
        return False, "还没有定义「全部和」。先写 全部和 = 0，再用两层循环累加。"
    想 = sum(x for 行 in v for x in 行)
    if 答案.全部和 != 想:
        return False, (f"「全部和」应当是 {想}，现在是 {答案.全部和!r}。"
                       f"（要先 全部和 = 0，再在两层循环里一个个加）")
    return True, f"表={v!r} 全部和={想}"


def CHECK_用了两层循环(答案):
    """⚠ 这一课练的是**嵌套循环**，不是 sum(sum(行) for 行 in 表)。"""
    import io
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    i = 源码.find("全部和")
    缩进 = [len(l) - len(l.lstrip()) for l in 源码[max(0, i - 500):i + 200].splitlines()
            if l.strip().startswith("for ")]
    if len(缩进) < 2 or len(set(缩进)) < 2:
        return False, ("「全部和」看起来不是用**两层** for 算出来的 —— 结果对也算不过。\n"
                       "      ⚠ 这一课练的就是套起来写：全部和 = 0，然后\n"
                       "          for 行 in 表:\n"
                       "              for x in 行:\n"
                       "                  全部和 += x")
    return True, "用了两层 for 累加"


def CHECK_取一列(答案):
    f = 答案.__dict__.get("取一列")
    if not callable(f):
        return False, ("还没有定义函数「取一列」。写法：\n"
                       "          def 取一列(表, 列号):\n"
                       "              return [行[列号] for 行 in 表]")
    for 表, 列号, 想 in (([[1, 2, 3], [4, 5, 6]], 1, [2, 5]), ([[1, 2, 3], [4, 5, 6]], 0, [1, 4]),
                       ([[1, 2], [3, 4], [5, 6]], 1, [2, 4, 6])):
        try:
            得 = list(f([list(行) for 行 in 表], 列号))
        except Exception as e:                                  # noqa: BLE001
            return False, f"取一列({表!r}, {列号}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"取一列({表!r}, {列号}) 应当是 {想!r}，得到 {得!r}。\n"
                           f"      ⚠ 一列 = 每一行的**同一个位置**：`[行[列号] for 行 in 表]`；\n"
                           f"        只写 表[列号] 拿到的是**一整行**（那是按行不是按列）。")
    return True, "四组都对（含只有一列的、含非方阵）"


def CHECK_造棋盘(答案):
    f = 答案.__dict__.get("造棋盘")
    if not callable(f):
        return False, ("还没有定义函数「造棋盘」。写法：\n"
                       "          def 造棋盘(n):\n"
                       "              return [['.' for _ in range(n)] for _ in range(n)]")
    for n in (3, 1, 4):
        try:
            盘 = f(n)
        except Exception as e:                                  # noqa: BLE001
            return False, f"造棋盘({n}) 出错：{type(e).__name__}: {e}"
        if not isinstance(盘, list) or len(盘) != n or not all(
                isinstance(行, list) and len(行) == n for 行 in 盘):
            return False, f"造棋盘({n}) 应当是 {n} 行 {n} 列的二维列表，现在是 {盘!r}。"
        if any(x != "." for 行 in 盘 for x in 行):
            return False, f"造棋盘({n}) 里每一格都应当是 '.'，现在是 {盘!r}。"
        if n == 3:
            盘[0][0] = "X"
            连着的 = [i for i, 行 in enumerate(盘) if 行[0] == "X"]
            if len(连着的) > 1:
                return False, (f"改一格，第 {连着的} 行**一起变了** —— 这几行是同一个列表。\n"
                               f"      ⚠ `[['.'] * n] * n` 把**同一个**列表放了 n 次。\n"
                               f"        要每一行各造一个：[['.' for _ in range(n)] for _ in range(n)]")
    return True, "三组都对，而且每一行是各自独立的"
