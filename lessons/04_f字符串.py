# 第 04 课：f-string —— 把变量放进句子里
# ─────────────────────────────────────────────────────
#  这一课你会学到
# ─────────────────────────────────────────────────────
#    f-string：把变量放进句子里
#
#  需要先会
#    第 02 课：字符串；第 03 课：数字


# ─────────────────────────────────────────────────────
#  先介绍：为什么需要它
# ─────────────────────────────────────────────────────
#
# 你想打印「你好，小明！」，而名字存在变量里。用第 02 课的 `+` 拼：
#
#     print("你好，" + 名字 + "！")
#
# 能行，但**括号和加号满天飞**，句子一长就看不清了。
# 而且变量不是文字时还得手动转：
#
#     print("我今年 " + str(年龄) + " 岁")      ← 不加 str() 会 TypeError
#
# ─────────────────────────────────────────────────────
#  f-string：在引号前面加一个 f
# ─────────────────────────────────────────────────────
#
#     print(f"你好，{名字}！")
#            ↑            ↑
#            f           变量名用花括号包起来
#
# 就这么多。`{...}` 里面可以直接写变量，也可以直接写算式：
#
#     f"{苹果数 + 梨数}"        ⇒  9
#     f"{年龄}"                 ⇒  18      ← **不用 str()**，f-string 自己会转
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 三个必须记住的坑
# ─────────────────────────────────────────────────────
#
#  ① **那个 f 不能少**
#
#         print("你好，{名字}！")      ❌  ⇒  你好，{名字}！
#         print(f"你好，{名字}！")     ✅  ⇒  你好，小明！
#
#     少了 f，花括号里的东西会**原样打出来** —— 不报错，只是不对。
#
#  ② **花括号要用半角** `{` `}`，不能用全角 `｛` `｝`
#     而且里面**不要加引号**：`f"{'名字'}"` 是「打印"名字"这两个字」，
#     不是打印变量 —— 因为加了引号它就变成一段文字了。
#
#  ③ **变量名必须真的存在**
#     `f"{名子}"`（打错字）⇒  NameError: name '名子' is not defined
#     这时照着错误信息里的名字，检查你拼写的**每一个字**。
#
# ─────────────────────────────────────────────────────
#  还可以控制小数位数（顺便记住）
# ─────────────────────────────────────────────────────
#
#     f"{3.14159:.2f}"     ⇒  3.14        （保留 2 位小数）
#     f"{4.5:.1f}"         ⇒  4.5
#
#   冒号后面是"格式"，`.2f` 意思是"小数点后 2 位的浮点数"。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   print 本身是第 02 课；数字运算在第 03 课。这一课只碰 f-string。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 定义变量 名字（文字）和 年龄（整数）
#   2. 写一个函数 自我介绍()，**用 f-string** 返回：
#         我叫<名字>，今年<年龄>岁。
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 04


def CHECK_两个变量(答案):
    for 名, 类型, 说明 in (("名字", str, "文字（要加引号）"),
                           ("年龄", int, "整数（不要引号）")):
        if not hasattr(答案, 名):
            return False, f"还没有定义「{名}」（{说明}）。"
        v = getattr(答案, 名)
        if isinstance(v, bool) or not isinstance(v, 类型):
            return False, (f"「{名}」应当是{说明}，现在是 {type(v).__name__}：{v!r}")
    if not 答案.名字.strip():
        return False, "「名字」是空的。"
    return True, f"名字 = {答案.名字!r}，年龄 = {答案.年龄}"


def CHECK_自我介绍(答案):
    if not hasattr(答案, "自我介绍"):
        return False, "还没有定义「自我介绍」函数。写法：def 自我介绍(): ..."
    if not callable(答案.自我介绍):
        return False, "「自我介绍」不是函数。"
    try:
        out = 答案.自我介绍()
    except Exception as e:                                      # noqa: BLE001
        return False, (f"自我介绍() 出错了：{type(e).__name__}: {e}\n"
                       f"      ⚠ 如果是 NameError，照着错误里的名字检查拼写。")
    if not isinstance(out, str):
        return False, (f"「自我介绍」应当**返回文字**，现在返回的是 {type(out).__name__}。\n"
                       f"      写法：return f\"我叫{答案.名字}，今年{答案.年龄}岁。\"")
    期望 = f"我叫{答案.名字}，今年{答案.年龄}岁。"
    if out != 期望:
        # 少了 f 的典型症状
        if "{" in out and "}" in out:
            return False, (f"打印/返回的是 {out!r} —— **花括号和变量名原样出来了**。\n"
                           f"      ⚠⚠ 引号前面**少了那个 f**！\n"
                           f"         错：  \"我叫{{名字}}…\"\n"
                           f"         对：  f\"我叫{{名字}}…\"")
        return False, (f"格式不太一样。\n"
                       f"      期望：{期望!r}\n"
                       f"      实际：{out!r}\n"
                       f"      对照标点：逗号和句号都要和上面一致（中文标点）。")
    return True, f"自我介绍() ⇒ {out}"


def CHECK_真的用了f字符串(答案):
    """⚠ 这一课的核心：必须用 f-string，不能用 `+` 拼。"""
    import io
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    # 只看 自我介绍 那个函数体
    i = 源码.find("def 自我介绍")
    段 = 源码[i:i + 800] if i >= 0 else ""
    if "f\"" not in 段 and "f'" not in 段:
        return False, ("「自我介绍」里没有看到 f-string。\n"
                       "      这一课就是要练它 —— 用 `+` 拼也能得到同样结果，\n"
                       "      但变量一多就会变成一团乱麻。\n"
                       "      写法：return f\"我叫{名字}，今年{年龄}岁。\"")
    return True, "确实用了 f-string"
