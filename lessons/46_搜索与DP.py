# ─────────────────────────────────────────────────────
#  一、DFS 和 BFS：一个往深里钻，一个一层层铺
# ─────────────────────────────────────────────────────
#     深度优先（DFS）：一条路走到黑，走不通再退回来        ← 用递归或栈
#     广度优先（BFS）：先看一步能到的，再看两步能到的……    ← 用队列
#
# 求**最短步数只能用 BFS**。看这个 5×5 迷宫（`.` 能走、`#` 是墙），从 (0,0) 到 (0,4)：
#
#     .....        最短：沿着第一排走 4 步 ⇒ 4
#     .#.#.        DFS 按 下→右→上→左 的顺序钻：先一路下到底、再绕右边上去，
#     .#.#.        第一条走通的路是 **12 步** —— 它找到的是「一条路」，不是最短路
#     .#.#.
#     .....
#
# BFS 的写法（**步数就存在队列里**，一层层加一）：
#
#     队 = deque([(起点, 0)])
#     见过 = {起点}
#     while 队:
#         (r, c), 步 = 队.popleft()
#         if (r, c) == 终点: return 步
#         for 四个方向:
#             新格子能走 且 没走过 ⇒ 见过.add(它); 队.append((它, 步 + 1))
#     return -1                        ← 队空了还没到 ⇒ 走不通
#
# n×n 全空的迷宫从角到角是 2(n-1) 步：50×50 ⇒ 98 步；走过的格子最多 n² 个 ⇒ 复杂度 O(n²)。
#
# ─────────────────────────────────────────────────────
#  二、动态规划：把「走法数」写成递推
# ─────────────────────────────────────────────────────
# 爬楼梯：每次走 1 级或 2 级，走到第 n 级有几种走法？
#
#     最后一步只能是「从 n-1 迈 1 级」或「从 n-2 迈 2 级」
#     ⇒ 走法数(n) = 走法数(n-1) + 走法数(n-2)          走法数(0) = 1、走法数(1) = 1
#
#     1 级 1 种、2 级 2 种、3 级 3 种、5 级 8 种、10 级 89 种、50 级 **20365011074** 种
#
# ⚠ 这就是斐波那契数列，n = 50 时答案已经大到 200 亿 —— 用**递归**算会重复计算到崩
#   （算 走法数(40) 要调用函数上亿次），而递推只做 n 次加法。
#
# 0/1 背包：n 件物品各只有一件，每件有重量和价值，容量 c 的包最多装多少价值？
#
#     dp[容量] = 目前能装的最大价值        ← 从「只考虑前 i 件」一件件加进来
#     加第 i 件时倒着扫容量：dp[x] = max(dp[x], dp[x - 重量[i]] + 价值[i])
#
# ⚠ **倒着扫**是关键：正着扫会让同一件物品被装两次（那就变成完全背包了）。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：求最短步数用了 DFS
# ─────────────────────────────────────────────────────
#     def 最短步数(迷宫, 起点, 终点):
#         走一遍深搜，第一次碰到终点就 return        ← ⚠ 这是「第一条路」，不是「最短路」
#
# 上面那个迷宫里，DFS 会返回 **12**（正确答案 4）—— **不报错、看起来也挺合理**，
# 只是比最短路长。判断方法很简单：**要最短就用队列（BFS），不要用递归/栈（DFS）**。
