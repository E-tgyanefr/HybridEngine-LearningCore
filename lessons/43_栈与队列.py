def CHECK_括号匹配(答案):
    f = 答案.__dict__.get('括号匹配')
    if not callable(f):
        return False, ('还没有定义「括号匹配」。写法：左括号压栈；右括号就看栈顶对不对，'
                       '不对或栈空返回 False；\n      扫完栈必须是空的。')
    for 文字, 想 in (('', True), ('()', True), ('([{}])', True), ('([)]', False),
                    ('(((', False), (')', False), ('(]', False), ('a(b[c]{d})e', True),
                    ('(' * 500 + ')' * 500, True), (')(' , False)):
        try:
            得 = f(文字 if len(文字) < 20 else '500 个左括号 + 500 个右括号')
        except Exception as e:                                  # noqa: BLE001
            return False, f'括号匹配({文字[:20]!r}) 出错：{type(e).__name__}: {e}'
        if bool(得) != 想:
            return False, (f'括号匹配({文字[:20]!r}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ ([)] 是**不匹配**的（个数相等但顺序错）；'
                           f'((( 和 ) 也要判 False。')
    return True, '十组都对（含空串、只有一种括号、顺序错、没关上、多余右括号、500 层深）'


def CHECK_逆波兰(答案):
    f = 答案.__dict__.get('逆波兰')
    if not callable(f):
        return False, ('还没有定义「逆波兰」。写法：数字就 int 后压栈；遇到运算符弹出两个，'
                       '先弹出的是**右**操作数。')
    for 式子, 想 in (('5', 5), ('3 4 +', 7), ('3 4 + 2 *', 14), ('2 3 4 * +', 14),
                    ('7 2 -', 5), ('10 2 * 3 -', 17), ('0 5 *', 0), ('1 2 3 4 + + +', 10)):
        try:
            得 = f(式子)
        except Exception as e:                                  # noqa: BLE001
            return False, f'逆波兰({式子!r}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'逆波兰({式子!r}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 弹出的两个数里，**先弹出的是右操作数**：'
                           f'7 2 - 是 7-2=5，不是 2-7。')
    return True, '八组都对（含单个数字、连续运算、减法方向、乘法得 0）'


def CHECK_模拟排队(答案):
    f = 答案.__dict__.get('模拟排队')
    if not callable(f):
        return False, ('还没有定义「模拟排队」。写法：队 = deque()；'
                       "'进' 就 append，'出' 就 popleft（空队列放 None）。")
    for 操作, 想 in (([], []),
                    ([('进', '甲'), ('进', '乙'), ('出', None)], ['甲']),
                    ([('进', '甲'), ('出', None), ('进', '乙'), ('出', None)], ['甲', '乙']),
                    ([('出', None)], [None]),
                    ([('出', None), ('进', '丙'), ('出', None)], [None, '丙']),
                    ([('进', i) for i in range(100)] + [('出', None)] * 100, list(range(100)))):
        try:
            得 = list(f(list(操作)))
        except Exception as e:                                  # noqa: BLE001
            return False, f'模拟排队({操作[:4]}…) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'模拟排队({操作[:6]}{"…" if len(操作) > 6 else ""}) 应当是 '
                           f'{想[:6]}{"…" if len(想) > 6 else ""}，得到 {得[:6]}。\n'
                           f'      ⚠ 队列是**先进先出**：出队要 popleft（列表的 pop() 是后进先出）。')
    return True, '六组都对（含空操作表、空队列出队、进进出出、进 100 个再出 100 个）'


def CHECK_用了deque(答案):
    import io
    if not hasattr(答案, '__file__'):
        return False, '找不到你的答题文件。'
    源码 = io.open(答案.__file__, encoding='utf-8').read()
    i = 源码.find('def 模拟排队')
    if i < 0:
        return False, '找不到「模拟排队」这个函数。'
    段 = 源码[i:]
    j = 段.find('\ndef ', 1)
    if j > 0:
        段 = 段[:j]
    if 'deque' not in 段:
        return False, ('「模拟排队」里没有用 collections.deque。\n'
                       '      ⚠ 用列表当队列要写 队.pop(0)，那是 O(n)：把后面 n-1 个元素全往前挪。\n'
                       '        实测长度 100000 的队列全部出队一次：pop(0) 4.03 秒，deque 0.0034 秒。')
    if '.pop(0)' in 段:
        return False, ('「模拟排队」里出现了 .pop(0) —— 那是 O(n) 的写法。\n'
                       '      ⚠ 用 deque 的 popleft()，它是 O(1)。')
    return True, '用的是 collections.deque（队尾进、队头出都是 O(1)）'
