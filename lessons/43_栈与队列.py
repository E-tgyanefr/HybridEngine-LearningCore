# ─────────────────────────────────────────────────────
#  先介绍：栈和队列，区别只在一头
# ─────────────────────────────────────────────────────
# 栈像一摞盘子：**后放上去的先拿走**（后进先出）。队列像排队：**先来的先走**（先进先出）。
# 两个都是「只能从一头进出的容器」，只是出口不一样 —— 但它们解决的问题完全不同。
#
# ─────────────────────────────────────────────────────
#  一、栈：Python 的列表天生就是栈
# ─────────────────────────────────────────────────────
#     栈 = []
#     栈.append(1)        # 压栈    栈 ⇒ [1]
#     栈.append(2)        # 压栈    栈 ⇒ [1, 2]
#     栈.pop()            # 弹栈 ⇒ 2，栈 ⇒ [1]
#
# `append` 和 `pop()` 都是 **O(1)**（在末尾动手，不用搬别的元素），所以列表就是栈，
# 不需要另造一个类。要看栈顶但不弹出来，就用 `栈[-1]`；判断空不空用 `if not 栈:`。
#
# ─────────────────────────────────────────────────────
#  二、括号匹配：栈最经典的用处
# ─────────────────────────────────────────────────────
# 从左往右扫，遇到左括号就压栈，遇到右括号就看栈顶是不是配对的：
#
#     ( [ { } ] )      ✅ 配对      ( [ ) ]      ❌ 不配对      ( ( (      ❌ 有没关的
#
# 为什么只能用栈：`([)]` 里两种括号**个数都相等**，数个数的方法判不出来；
# 栈顶记的正是「最近一个还没关上的左括号」，顺序对不上就露馅：
#
#     遇到 ) 时栈顶是 [ ⇒ 期望是 ( ⇒ 不匹配 ⇒ False
#
# ⚠ 两个收尾判断别忘：扫完还有剩（`(((`）⇒ False；遇到右括号时栈是空的（`)`）⇒ False。
#
# ─────────────────────────────────────────────────────
#  三、队列：必须用 collections.deque
# ─────────────────────────────────────────────────────
#     用列表当队列（慢）              用 deque（快）
#     队.append(x)                   队.append(x)
#     队.pop(0)      ← O(n)          队.popleft()   ← O(1)
#
# ⚠ `列表.pop(0)` 要把后面 n-1 个元素**全往前挪一格**，所以是 O(n)。
#   实测（长度 100000 的队列全部出队一次）：
#
#     list.pop(0)   4.03 秒          deque.popleft()   0.0034 秒      ← 差 1000 多倍
#
# deque 还能当栈用（append / pop）、两头进出（appendleft / popleft）、
# 固定长度（deque(maxlen=5) 满了自动挤掉最老的）。
#
# ─────────────────────────────────────────────────────
#  四、逆波兰：栈的另一个用处
# ─────────────────────────────────────────────────────
# 后缀表达式 `3 4 + 2 *` 的意思是 (3+4)×2。算法：遇到数字压栈，遇到运算符弹出两个：
#
#     3 4 + 2 *     压 3、压 4；遇 + ⇒ 弹 4 和 3 ⇒ 7 压回去；压 2；遇 * ⇒ 弹 2 和 7 ⇒ 14
#
# ⚠ 弹出的顺序：**先弹出的是右操作数**。`7 2 -` 是 7-2 = 5，不是 2-7 = -5。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：用 list.pop(0) 当队列
# ─────────────────────────────────────────────────────
#     队 = [1, 2, 3]
#     队.pop(0)      ⇒ 1        ← 结果完全正确，一个字都不报
#
# ⚠ 它只是**慢**。上面的实测：100000 次出队，list 要 4.03 秒，deque 只要 0.0034 秒。
#   竞赛里这点差别就是「通过」和「超时」的差别，而且**它不会给你任何提示** ——
#   所以你只能靠「知道该用哪个容器」来避免。
#
# ─────────────────────────────────────────────────────
