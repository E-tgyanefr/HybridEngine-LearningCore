# ─────────────────────────────────────────────────────
#  先介绍：想不出公式，就一个一个试
# ─────────────────────────────────────────────────────
# 「哪些三位数等于各位数字的立方和？」这种题没有现成公式。但可能的情况
# **数得过来**：三位数只有 900 个，全试一遍就行了。这种「把范围里的可能
# 一个个试过来，符合条件的收下」就是枚举法。
# ─────────────────────────────────────────────────────
#  一、枚举法的三步
# ─────────────────────────────────────────────────────
#   ① 定范围：可能的值有哪些？用 for + range 圈出来
#   ② 造候选：把这一组值拼成一个「可能」
#   ③ 验条件：符合的收下（if + append）
#   水仙花数（各位数字的立方和等于自己，例如 153 = 1 + 125 + 27）：
#    for 数 in range(100, 1000):            ← ① 三位数（含头不含尾）
#        百, 十, 个 = 数 // 100, 数 // 10 % 10, 数 % 10
#        if 百 ** 3 + 十 ** 3 + 个 ** 3 == 数:    ← ③ 验条件
#            收下.append(数)                       ← 收进结果
# ─────────────────────────────────────────────────────
#  二、判断素数：试到「一半」就够
# ─────────────────────────────────────────────────────
#   素数 = 只能被 1 和自己整除、而且**大于 1** 的数。
#    def 是素数(n):
#        if n < 2:
#            return False              ← ⚠ 1 不是素数，0 和负数也不是
#        for i in range(2, n // 2 + 1):
#            if n % i == 0:
#                return False          ← 找到一个能整除的，就不是素数
#        return True
#   ⚠ 两处最容易错：① `n // 2 + 1` 里的 **+1 不能省**（range 含头不含尾）；
#     ② `n < 2` 那一条不能省，否则 1 会被判成素数。
# ─────────────────────────────────────────────────────
#  三、百钱百鸡：一层等式省掉一层循环
# ─────────────────────────────────────────────────────
#   公鸡 5 钱一只、母鸡 3 钱一只、小鸡 3 只 1 钱；100 钱买 100 只。
#   公鸡最多 20 只（100 ÷ 5 = 20），母鸡最多 33 只 —— 范围就圈出来了。
#   ⚠ 小鸡**不用循环**：`小鸡 = 100 - 公鸡 - 母鸡`，用等式算出来。
#     三层循环变两层，快得多。最后要同时验两件事：钱正好 100，
#     而且**小鸡数能被 3 整除**（小鸡按「3 只 1 钱」卖，不能只买 1 只）。
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：range() 里不能用 /
# ─────────────────────────────────────────────────────
#   写「试到一半」时很自然会用 `/`：
#      for i in range(2, n / 2):     ❌ n / 2 是**小数**
#      TypeError: 'float' object cannot be interpreted as an integer
#  ⇒ `range()` 只吃**整数**，要一半就写整除 `//`：`range(2, n // 2 + 1)`
#  ⚠ 同一个坑还有 range(2, n ** 0.5)、range(0, len(表) / 2) —— 都报这一句。
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   只讲「试出答案」，不管快慢。剪枝、二分、筛法都是后面的事。
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 写一个函数 是素数(n)：n 小于 2 返回 False；否则试到 n // 2（含）就够
# 2. 写一个函数 找素数(上限)：返回不超过 上限 的所有素数（从小到大）
# 3. 写一个函数 水仙花数()：返回所有三位水仙花数（从小到大）
# 4. 写一个函数 百钱百鸡()：返回所有解，每个解是 (公鸡, 母鸡, 小鸡) 的元组
# ─────────────────────────────────────────────────────
