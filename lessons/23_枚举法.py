def CHECK_是素数(答案):
    f = 答案.__dict__.get("是素数")
    if not callable(f):
        return False, ("还没有定义函数「是素数」。写法：n < 2 返回 False；\n"
                       "          然后 for i in range(2, n // 2 + 1): 能整除就 return False；\n"
                       "          循环走完 return True。")
    for n, 想 in ((0, False), (1, False), (2, True), (3, True), (4, False),
                  (9, False), (25, False), (97, True), (100, False), (121, False)):
        try:
            得 = f(n)
        except Exception as e:                                  # noqa: BLE001
            return False, f"是素数({n}) 出错：{type(e).__name__}: {e}"
        if bool(得) != 想:
            return False, (f"是素数({n}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 记两条：**小于 2 的一律不是素数**（1 也不是）；\n"
                           f"        试到 `n // 2` 就够（写上 +1），不用试到 n。")
    return True, "十组都对（含 0、1、2、完全平方数）"


def CHECK_找素数(答案):
    f = 答案.__dict__.get("找素数")
    if not callable(f):
        return False, ("还没有定义函数「找素数」。写法：在 2~上限 之间逐个用 是素数 试，"
                       "是就 append 进结果列表。")
    for 上限, 想 in ((20, [2, 3, 5, 7, 11, 13, 17, 19]), (7, [2, 3, 5, 7]),
                    (2, [2]), (1, []), (0, [])):
        try:
            得 = list(f(上限))
        except Exception as e:                                  # noqa: BLE001
            return False, f"找素数({上限}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"找素数({上限}) 应当是 {想!r}，得到 {得!r}。\n"
                           f"      ⚠ 范围是 `range(2, 上限 + 1)` —— 少了那个 +1 就会漏掉"
                           f"**上限本身**（上限正好是素数时最明显）。")
    return True, "五组都对（含上限就是素数、含上限小于 2）"


def CHECK_水仙花数(答案):
    f = 答案.__dict__.get("水仙花数")
    if not callable(f):
        return False, ("还没有定义函数「水仙花数」。写法：for 数 in range(100, 1000) 里\n"
                       "          取各位数字，立方和等于自己就 append 进结果列表。")
    try:
        得 = list(f())
    except Exception as e:                                      # noqa: BLE001
        return False, f"水仙花数() 出错：{type(e).__name__}: {e}"
    想 = [153, 370, 371, 407]
    if 得 != 想:
        return False, (f"水仙花数() 应当是 {想!r}，得到 {得!r}。\n"
                       f"      ⚠ 三个条件都要对：范围是 `range(100, 1000)`（三位数）；\n"
                       f"        各位数字用 `// 100`、`// 10 % 10`、`% 10` 取出来；\n"
                       f"        验的是**立方**和（`** 3`），不是平方。")
    return True, f"四个都对：{想!r}"


def CHECK_百钱百鸡(答案):
    f = 答案.__dict__.get("百钱百鸡")
    if not callable(f):
        return False, ("还没有定义函数「百钱百鸡」。写法：两层循环枚举公鸡、母鸡，\n"
                       "          小鸡 = 100 - 公鸡 - 母鸡；\n"
                       "          再验 小鸡 % 3 == 0 和 5*公 + 3*母 + 小//3 == 100。")
    try:
        得 = f()
    except Exception as e:                                      # noqa: BLE001
        return False, f"百钱百鸡() 出错：{type(e).__name__}: {e}"
    想 = [(0, 25, 75), (4, 18, 78), (8, 11, 81), (12, 4, 84)]
    try:
        得组 = sorted(tuple(x) for x in 得)
    except Exception:                                           # noqa: BLE001
        return False, (f"百钱百鸡() 返回的应当是**一组解**（每个解是一个元组），"
                       f"现在是 {得!r}。")
    if 得组 != 想:
        return False, (f"百钱百鸡() 应当是 {想!r}（共 4 组），得到 {得组!r}。\n"
                       f"      ⚠ 三条最容易漏：① 公鸡 range(0, 21)、母鸡 range(0, 34)\n"
                       f"        ② 小鸡用 `100 - 公 - 母` 算出来，别再套一层循环\n"
                       f"        ③ 小鸡要 `% 3 == 0`（按 3 只 1 钱卖），钱数才算得对")
    return True, f"四组解都对：{想!r}"
