def CHECK_平方表和偶数表(答案):
    if not hasattr(答案, "数字"):
        return False, "还没有定义「数字」。写法：数字 = [1, 2, 3, 4, 5, 6]"
    v = 答案.数字
    if not isinstance(v, list) or len(v) < 6 or not all(
            isinstance(x, int) and not isinstance(x, bool) for x in v):
        return False, f"「数字」应当是至少 6 个整数的列表，现在是 {v!r}。"
    if not hasattr(答案, "平方表"):
        return False, "还没有定义「平方表」。写法：平方表 = [x * x for x in 数字]"
    想平方 = [x * x for x in v]
    if list(答案.平方表) != 想平方:
        return False, (f"「平方表」应当是 {想平方!r}，现在是 {答案.平方表!r}。\n"
                       f"      ⚠ 写法：平方表 = [x * x for x in 数字]")
    if not hasattr(答案, "偶数表"):
        return False, "还没有定义「偶数表」。写法：偶数表 = [x for x in 数字 if x % 2 == 0]"
    想偶 = [x for x in v if x % 2 == 0]
    if list(答案.偶数表) != 想偶:
        return False, (f"「偶数表」应当是 {想偶!r}，现在是 {答案.偶数表!r}。\n"
                       f"      ⚠ 写法：偶数表 = [x for x in 数字 if x % 2 == 0]")
    return True, f"平方表={想平方!r} 偶数表={想偶!r}"


def CHECK_翻倍(答案):
    f = 答案.__dict__.get("翻倍")
    if not callable(f):
        return False, ("还没有定义函数「翻倍」。\n"
                       "      写法：def 翻倍(数字们):\n"
                       "                return [x * 2 for x in 数字们]")
    for 备份 in ([1, 2, 3], [], [-1, 5], [7]):
        原 = list(备份)
        try:
            得 = list(f(原))
        except Exception as e:                                  # noqa: BLE001
            return False, f"翻倍({备份!r}) 出错：{type(e).__name__}: {e}"
        if 原 != 备份:
            return False, (f"翻倍({备份!r}) 把**传进去的列表改了**：现在是 {原!r}\n"
                           f"      ⚠ 列表解析造的是**新**列表，原来那个不许动。")
        if 得 != [x * 2 for x in 备份]:
            return False, (f"翻倍({备份!r}) 应当是 {[x * 2 for x in 备份]!r}，得到 {得!r}。\n"
                           f"      ⚠ 写法：return [x * 2 for x in 数字们]")
    return True, "四组都对，而且没改传进去的列表"


def CHECK_摊平(答案):
    f = 答案.__dict__.get("摊平")
    if not callable(f):
        return False, ("还没有定义函数「摊平」。\n"
                       "      写法：def 摊平(二维表):\n"
                       "                return [x for 行 in 二维表 for x in 行]")
    for 表, 想 in (([[1, 2], [3, 4]], [1, 2, 3, 4]), ([[1], []], [1]),
                   ([], []), ([[5, 6, 7]], [5, 6, 7])):
        try:
            得 = list(f(表))
        except Exception as e:                                  # noqa: BLE001
            return False, f"摊平({表!r}) 出错：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"摊平({表!r}) 应当是 {想!r}，得到 {得!r}。\n"
                           f"      ⚠ 要**两层**：`[x for 行 in 二维表 for x in 行]`\n"
                           f"        只写一层 `[行 for 行 in 二维表]` 拿到的是原来的行。")
    return True, "四组都对（含空表、含空行）"


def CHECK_用了列表解析(答案):
    """⚠ 这一课要练的就是方括号里那个写法，不是用循环凑出同样的结果。"""
    import io, re
    if not hasattr(答案, "__file__") or not hasattr(答案, "数字"):
        return False, "先定义好「数字」列表，再跑这条检查。"
    源码 = io.open(答案.__file__, encoding="utf-8").read()
    命中 = re.findall(r"\[[^\[\]]*\bfor\b[^\[\]]*\]", 源码)
    if len(命中) < 3:
        return False, (f"只找到 {len(命中)} 处方括号解析，至少要 3 处"
                       f"（平方表、偶数表，以及两个函数里）。\n"
                       f"      ⚠ 这一课练的是**列表解析**，不是用 for + append 凑出同样的结果。\n"
                       f"        写法：平方表 = [x * x for x in 数字]")
    return True, f"找到 {len(命中)} 处列表解析"
