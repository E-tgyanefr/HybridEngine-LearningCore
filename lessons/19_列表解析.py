# ─────────────────────────────────────────────────────
#  先介绍：造新列表这件事太常见了
# ─────────────────────────────────────────────────────
#
# 把每个元素都变一下、再装进一个新列表 —— 这个套路你已经写过很多遍：
#
#    平方 = []
#    for x in 数字:
#        平方.append(x * x)
# 三行只为做一件小事。Python 给了个短写法：一行写完，读起来也更顺。
# ─────────────────────────────────────────────────────
#  一、列表解析的两半
# ─────────────────────────────────────────────────────
#
#    平方 = [x * x   for x in 数字]
#             ↑          ↑
#          造什么      从哪来
#   ⚠ 顺序**和直觉相反**：先写「要造的东西」，再写「从哪来」。
#    偶数 = [x for x in 数字 if x % 2 == 0]
#                            ↑ 这一段是**筛子**：不满足的丢掉，不进新列表
#   ⚠ 筛子写在**最后**，还能叠好几层：`... if x > 0 if x % 2 == 0`
# ─────────────────────────────────────────────────────
#  二、和 for 循环一一对照
# ─────────────────────────────────────────────────────
#   用循环（要 3 行）：                用列表解析（1 行）：
#     平方 = []                        平方 = [x * x for x in 数字]
#     for x in 数字:                    偶数 = [x for x in 数字 if x % 2 == 0]
#         平方.append(x * x)
#
#   ⚠ 唯一不同的是：解析**造一个新列表**，原来那个一点不动；
#     而且解析里不能 print、不能赋值 —— 它只负责「造」。
# ─────────────────────────────────────────────────────
#  三、嵌套：两个 for 就是两层循环
# ─────────────────────────────────────────────────────
#
#    表 = [[1, 2], [3, 4]]
#    摊平 = [x for 行 in 表 for x in 行]        ⇒ [1, 2, 3, 4]
#   读法：**从左往右，就是 for 从外到内**（等于 `for 行 in 表:` 里再套一层）。
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：忘了方括号
# ─────────────────────────────────────────────────────
#  `[ ]` 写成 `( )`，就差一个符号，结果差很远：
#
#    平方 = (x * x for x in 数字)      ← 圆括号，这不是列表
#    print(平方)   ⇒ <generator object <genexpr> at 0x000001E794EFB6B0>
#    len(平方)     ❌ TypeError: object of type 'generator' has no len()
#  ⇒ 要列表就写**方括号**。圆括号那个叫生成器，只能从头走一遍，这一课用不上。
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   只讲「从旧列表造新列表」。字典/集合推导式、生成器用到再说，这里不碰。
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 定义列表 数字 = [1, 2, 3, 4, 5, 6]（至少 6 个整数）
# 2. 定义 平方表 = 用列表解析算出的每个数的平方
# 3. 定义 偶数表 = 用列表解析挑出 数字 里的偶数
# 4. 写一个函数 翻倍(数字们)：用列表解析返回每个数乘 2 的**新列表**（原列表不许改）
# 5. 写一个函数 摊平(二维表)：用列表解析把 [[1, 2], [3, 4]] 摊成 [1, 2, 3, 4]
# ─────────────────────────────────────────────────────
