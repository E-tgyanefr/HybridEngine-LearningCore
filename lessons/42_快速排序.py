# ─────────────────────────────────────────────────────
#  先介绍：快排和归并正相反
# ─────────────────────────────────────────────────────
# 归并是「先分、排好、再合」，功夫在**合**；快排反过来：**先按基准分好，两边各自递归** ——
# 分完基准就已经在它最终的位置上。平均也是 O(n log n)，但它多一个毛病：最坏 O(n²)。
#
# ─────────────────────────────────────────────────────
#  一、划分：小的放左边，大的放右边
# ─────────────────────────────────────────────────────
# 取 表[右] 当基准（Lomuto 写法），用 界 记住「小于等于基准的区域」到哪了：
#     def 划分(表, 左, 右):
#         基准 = 表[右]
#         界 = 左 - 1
#         for i in range(左, 右):
#             if 表[i] <= 基准:
#                 界 += 1
#                 表[界], 表[i] = 表[i], 表[界]
#         表[界 + 1], 表[右] = 表[右], 表[界 + 1]     ← 基准归位
#         return 界 + 1
#
# 走一遍 `划分([3, 7, 1, 9, 2], 0, 4)`（基准 = 2）：3 跳过、7 跳过、1 ≤ 2 就和 3 换 ⇒ [1, 7, 3, 9, 2]、
# 9 跳过，最后把基准换到 界+1 ⇒ **[1, 2, 3, 9, 7]**，返回 **1**（左边都 ≤ 2，右边都 ≥ 2 ✅）。
#
# ─────────────────────────────────────────────────────
#  二、快排本体（原地排序）
# ─────────────────────────────────────────────────────
#     def 快排(表, 左=0, 右=None):
#         右 = len(表) - 1 if 右 is None else 右
#         if 左 >= 右:
#             return 表                   ← 递归出口：0 个或 1 个元素
#         位 = 划分(表, 左, 右)
#         快排(表, 左, 位 - 1)
#         快排(表, 位 + 1, 右)
#         return 表
#
# 它是**原地**的：所有交换都发生在 表 自己身上，不像归并要另一个数组（但代价是不稳定）。
#
# ─────────────────────────────────────────────────────
#  三、最坏情况 O(n²)：什么时候发生
# ─────────────────────────────────────────────────────
# 每次划分如果只分出「0 个」和「n-1 个」，递归就有 n 层，比较次数变成 n(n-1)/2：
#     n = 10000：平均约 13 万次，最坏 **4999 万次**；n = 100000：最坏约 **50 亿次**。
# 什么时候正好最坏？**表已经排好序（或逆序），而基准又取最后一个** ——
#     划分([1, 2, 3, 4, 5], 0, 4)：基准 5，谁都比它小 ⇒ 返回 4，下次只处理前 4 个……
# 而且还会撞上递归上限：快排(已排序的 2000 个数) ⇒ RecursionError: maximum recursion depth exceeded
# 对策：① **三数取中**（这一课的作业）② 随机选基准 ③ 小区间（n ≤ 16）改用插入排序
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：一堆相同的数也能把它拖成 O(n²)
# ─────────────────────────────────────────────────────
# 上面的 Lomuto 划分比较写的是 `<=`：**所有元素都等于基准时，每次划分都返回 右**，
# 于是左边 n-1 个、右边 0 个 —— 又是最坏情况：
#
#     快排([4, 4, 4, …, 4])（2000 个 4）⇒ RecursionError: maximum recursion depth exceeded
#
# ⚠ 「一堆相同的数」很常见（全班都是 100 分那种表），要解决得用**三路划分**（分三堆）。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课只讲快排和最坏情况；归并、稳定性在 第 41 / 30 课。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 写函数 划分(表, 左, 右)：以 表[右] 为基准**原地**划分，返回基准最后的下标；
#    要求 表[左:位] 全都 ≤ 表[位] ≤ 表[位+1:右+1]
# 2. 写函数 快排(表)：**原地**把 表 排成升序并返回它（不许用 sorted / sort）
# 3. 写函数 三数取中(表, 左, 右)：返回 表[左]、表[(左+右)//2]、表[右] 里**居中**
#    那个值的下标（值相同时，返回这三个下标里任意一个都算对）
#
