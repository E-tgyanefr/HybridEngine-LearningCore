def CHECK_划分(答案):
    from collections import Counter
    f = 答案.__dict__.get('划分')
    if not callable(f):
        return False, ('还没有定义「划分」。基准 = 表[右]；界 = 左 - 1；i 从 左 到 右-1，'
                       '表[i] <= 基准 就 界 += 1 并交换；最后把基准换到 界+1，返回 界+1。')
    for 原, 左, 右 in (([3, 7, 1, 9, 2], 0, 4), ([4, 4, 4, 4], 0, 3), ([1, 2, 3, 4, 5], 0, 4),
                      ([5, 4, 3, 2, 1], 0, 4), ([9], 0, 0), ([2, 1], 0, 1),
                      ([-3, 0, -7, 5], 0, 3), ([3, 7, 1, 9, 2], 1, 4)):
        表 = list(原)
        基准 = 表[右]
        try:
            位 = f(表, 左, 右)
        except Exception as e:                                  # noqa: BLE001
            return False, f'划分({原}, {左}, {右}) 出错：{type(e).__name__}: {e}'
        if not (isinstance(位, int) and 左 <= 位 <= 右):
            return False, (f'划分({原}, {左}, {右}) 返回 {位!r} —— 应当是 [左, 右] 之间的下标'
                           f'（基准 = 表[{右}] = {基准}）。')
        if 表[位] != 基准:
            return False, (f'划分({原}, {左}, {右}) 之后 表[{位}] = {表[位]!r}，但基准是 {基准!r} —— '
                           f'基准要落在返回的那个位置上。')
        if any(x > 基准 for x in 表[左:位]) or any(x < 基准 for x in 表[位 + 1:右 + 1]):
            return False, (f'划分({原}, {左}, {右}) 之后 表 = {表} —— 左半有比基准大的、或右半有比基准小的。\n'
                           f'      ⚠ 要求：表[左:位] 都 ≤ 基准 ≤ 表[位+1:右+1]。')
        if Counter(表[左:右 + 1]) != Counter(原[左:右 + 1]):
            return False, f'划分({原}, {左}, {右}) 之后 表 = {表} —— 元素被弄丢/弄多了（只许交换）。'
    return True, '八组都对（含全相同、已排序、逆序、单元素、负数、只划一段）'


def CHECK_快排(答案):
    from collections import Counter
    f = 答案.__dict__.get('快排')
    if not callable(f):
        return False, ('还没有定义「快排」。骨架：左 >= 右 直接返回；位 = 划分(表, 左, 右)，再递归左右两段。')
    for 原 in ([], [1], [3, 3, 3, 3], [1, 2, 3, 4, 5], [2, 1, 2, 1],
               [5, 4, 3, 2, 1], [-3, 5, -1, 0], [((i * 37) % 101) for i in range(1000)]):
        给 = list(原)
        try:
            得 = f(给)
        except RecursionError:
            return False, (f'快排({原 if len(原) < 12 else "1000 个数"}) 抛了 '
                           f'RecursionError: maximum recursion depth exceeded —— 每次划分只\n'
                           f'      分出一个元素 ⇒ 递归 n 层（已排序 / 逆序 / 大量重复 + 基准取表[右]）。')
        except Exception as e:                                  # noqa: BLE001
            return False, f'快排({原 if len(原) < 12 else "1000 个数"}) 出错：{type(e).__name__}: {e}'
        if list(得) != sorted(原) or 给 != sorted(原):
            return False, (f'快排({原 if len(原) < 12 else "1000 个数"}) 得到 {list(得)[:12]}…，'
                           f'原表现在是 {给[:12]}… —— 要求：① 返回升序 ② **原地**排好原表。')
        if Counter(给) != Counter(原):
            return False, f'快排({原 if len(原) < 12 else "1000 个数"}) 把元素弄丢/弄多了。'
    return True, '八组都对（含空表、单元素、全相同、已排序、逆序、负数、1000 个乱序）'


def CHECK_三数取中(答案):
    f = 答案.__dict__.get('三数取中')
    if not callable(f):
        return False, ('还没有定义「三数取中」。取 表[左]、表[(左+右)//2]、表[右] 三个值，返回**值居中**那个的下标。')
    for 表, 左, 右 in (([3, 1, 2], 0, 2), ([1, 5, 3], 0, 2), ([2, 1, 3], 0, 2),
                      ([5, 5, 5], 0, 2), ([9], 0, 0), ([2, 1], 0, 1),
                      ([9, 2, 7, 4, 1], 0, 4), ([-3, 0, -7, 5], 0, 3)):
        中位 = sorted((表[左], 表[(左 + 右) // 2], 表[右]))[1]
        try:
            得 = f(list(表), 左, 右)
        except Exception as e:                                  # noqa: BLE001
            return False, f'三数取中({表}, {左}, {右}) 出错：{type(e).__name__}: {e}'
        if not (isinstance(得, int) and 得 in (左, (左 + 右) // 2, 右) and 表[得] == 中位):
            return False, (f'三数取中({表}, {左}, {右}) 返回 {得!r}：三个位置 {左}、{(左+右)//2}、{右} 的值是 '
                           f'{表[左]}、{表[(左+右)//2]}、{表[右]}，中位数 {中位} —— 要返回**下标**（不是值）。')
    return True, '八组都对（含三个值全相同、单元素、两个元素、负数）'


def CHECK_不用sorted(答案):
    import io
    if not hasattr(答案, '__file__'):
        return False, '找不到你的答题文件。'
    源码 = io.open(答案.__file__, encoding='utf-8').read()
    for 名 in ('def 快排', 'def 划分'):
        i = 源码.find(名)
        if i < 0:
            continue
        段 = 源码[i:]
        j = 段.find('\ndef ', 1)
        if j > 0:
            段 = 段[:j]
        if 'sorted(' in 段 or '.sort(' in 段:
            return False, f'「{名[4:]}」里用了 sorted / sort —— 结果对，但这一课就白上了（要划分 + 递归）。'
    return True, '没有偷用 sorted / sort'
