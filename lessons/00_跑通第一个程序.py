# ─────────────────────────────────────────────────────
#  一、怎么跑一个 Python 程序（就这一条命令）
# ─────────────────────────────────────────────────────
#
#     python 文件名.py
#
# 也可以点这个界面上的「检查」—— 它替你跑，还会告诉你对不对。
#
# ─────────────────────────────────────────────────────
#  二、print：让程序说话
# ─────────────────────────────────────────────────────
#
#     print("你好，Python")
#
# 拆开看：
#
#     print        打印（这是 Python 自带的一个工具）
#     ( )          括号里放你要打印的东西
#     "你好，Python"  要打印的文字，**必须用引号包起来**
#
# 它能打印好几行：
#
#     print("第一行")
#     print("第二行")
#
#     输出：
#         第一行
#         第二行
#
# ⚠ 一句 print 只负责一行。想要两行，就写两句。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：括号和引号必须是**半角**
# ─────────────────────────────────────────────────────
#
#     print（"你好"）        ❌ 全角括号
#     print("你好")          ✅ 半角括号
#
# 报错长这样：
#
#     SyntaxError: invalid character '（' (U+FF08)
#
# ⚠ 那串 U+FF08 就是全角括号的学名。看到 `invalid character`，
#   先去把中文输入法切回英文 —— 这是新手第一个必踩的坑。
#
# 同类的还有：全角引号 “ ” 、全角逗号 ，、全角冒号 ：
#
# ─────────────────────────────────────────────────────
#  这一课不碰什么
# ─────────────────────────────────────────────────────
#   变量 → 第 01 课。别的什么都是更后面的事。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   在答题文件里写 print，让它打印出这三行：
#
# 1. 打印 工具链就绪
# 2. 打印 我准备好学 Python 了
# 3. 打印 第一步：写，第二步：跑
#
#   ⚠ 就这三句。不用变量、不用函数。
#
#   ⚠ 三行的**顺序**别改 —— 检查是按顺序比对的。
#      —— 每一句就是一条 `print("...")`。
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 00


def _行(答案):
    """把答题文件的 print 输出抓成行。"""
    import io
    import contextlib
    import runpy
    buf = io.StringIO()
    try:
        with contextlib.redirect_stdout(buf):
            runpy.run_path(str(答案.__file__), run_name="__答题__")
    except SyntaxError as e:
        return None, (f"你的文件有语法错误，Python 读不下去：\n"
                      f"      {type(e).__name__}: {e.msg}（第 {e.lineno} 行）\n"
                      f"      ⚠ 最常见的原因：括号或引号打成了**全角**。\n"
                      f"        半角 ( ) \" \" 才行，全角 （ ） “ ” 不行。")
    except Exception as e:                                      # noqa: BLE001
        return None, f"运行你的代码时出错了：{type(e).__name__}: {e}"
    return [l for l in buf.getvalue().split("\n") if l.strip()], None


def CHECK_三行都打印了(答案):
    if not hasattr(答案, "__file__"):
        return False, "找不到你的答题文件。"
    行, 错 = _行(答案)
    if 错:
        return False, 错
    if not 行:
        return False, ("你的文件一行都没打印 —— 少了 print。\n"
                       "      写法：print(\"工具链就绪\")\n"
                       "      ⚠ print 后面那对**圆括号**，还有文字的**引号**，都不能少。")
    期望 = ["工具链就绪", "我准备好学 Python 了", "第一步：写，第二步：跑"]
    for i, 想 in enumerate(期望):
        if i >= len(行):
            return False, (f"只打印了 {len(行)} 行，应该有 {len(期望)} 行。\n"
                           f"      第 {i + 1} 行缺了：{想}")
        实 = 行[i].strip()
        if 实 != 想:
            return False, (f"第 {i + 1} 行应当是「{想}」，实际是「{实}」。\n"
                           f"      ⚠ 一个字、一个标点都要对上；顺序也别改。")
    if len(行) > len(期望):
        return False, (f"打印了 {len(行)} 行，多出来的是「{行[len(期望)].strip()}」。\n"
                       f"      这一课只要三行。")
    return True, "三行都对"


def CHECK_用了半角括号和引号(答案):
    """⚠ 这一条是**专门为新手准备**的：全角标点是最高频的错。"""
    import io
    import os
    文 = io.open(str(答案.__file__), encoding="utf-8").read()
    全角 = {"（": "全角左括号", "）": "全角右括号",
            "“": "全角左引号", "”": "全角右引号"}
    找到 = [n for c, n in 全角.items() if c in 文]
    if 找到:
        return False, ("你的文件里有全角标点：" + "、".join(找到) + "。\n"
                       "      ⚠ 把输入法切回**英文**重打一遍那几行。\n"
                       "        半角：  print(\"你好\")\n"
                       "        全角：  print（“你好”）   ← 这样会报 SyntaxError")
    if "print" not in 文:
        return False, "没看到 `print`。这一课就是要你用它打印三行。"
    return True, "用的都是半角，没问题"
