"""第 38 课参考答案 —— 二分查找。"""

import bisect


def 二分查找(有序表, 目标):
    左, 右 = 0, len(有序表) - 1
    # ⚠ 是 <= ：写成 < 的话，[5] 找 5 直接不进循环，返回 -1
    while 左 <= 右:
        中 = (左 + 右) // 2
        if 有序表[中] == 目标:
            return 中
        if 有序表[中] < 目标:
            左 = 中 + 1          # ⚠ 必须 +1，否则 左 = 中 时死循环
        else:
            右 = 中 - 1
    return -1


def 找第一个(有序表, 目标):
    左, 右 = 0, len(有序表) - 1
    答案 = -1
    while 左 <= 右:
        中 = (左 + 右) // 2
        if 有序表[中] == 目标:
            答案 = 中
            右 = 中 - 1          # 命中不返回，继续往左找
        elif 有序表[中] < 目标:
            左 = 中 + 1
        else:
            右 = 中 - 1
    return 答案


def 用bisect找(有序表, 目标):
    得 = bisect.bisect_left(有序表, 目标)
    # ⚠ bisect_left 找不到时返回"该插在哪"，不是 -1
    if 得 < len(有序表) and 有序表[得] == 目标:
        return 得
    return -1
