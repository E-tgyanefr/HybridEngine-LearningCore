"""第 19 课参考答案 —— 列表解析。"""

数字 = [1, 2, 3, 4, 5, 6]

平方表 = [x * x for x in 数字]                  # 先写"要造的东西"，再写 for
偶数表 = [x for x in 数字 if x % 2 == 0]        # 筛子写在**最后**


def 翻倍(数字们):
    # ⚠ 列表解析造的是**新**列表，传进来的那个一点不动
    return [x * 2 for x in 数字们]


def 摊平(二维表):
    # 两个 for：从左往右就是 for 从外到内
    return [x for 行 in 二维表 for x in 行]
