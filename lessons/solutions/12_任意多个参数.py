"""第 12 课参考答案 —— *参数。"""


def 加全部(*数字):
    # ⚠ `*数字` 把传进来的所有参数收成一个**元组**
    #    不传时是空元组 ()，sum(()) 正好是 0 —— 边界自然就对
    return sum(数字)


def 最长(*文字们):
    # ⚠⚠ 用了 *参数 就必须想「什么都不传」是什么意思。
    #    这里 max() 对空序列会抛 ValueError，所以先判断。
    if not 文字们:
        return ""
    最长的 = 文字们[0]
    for s in 文字们:
        if len(s) > len(最长的):
            最长的 = s
    return 最长的
