"""第 25 课参考答案 —— 作用域。"""

# ① 全局变量：写最外层，不缩进
次数 = 0


def 加一():
    # ⚠ 想**改**全局，第一行就得声明它说的是外面那个
    global 次数
    次数 = 次数 + 1
    return 次数


def 加几个(n):
    global 次数
    # ⚠ 用 += 而不是 for _ in range(n)：n 是 0 或负数时循环一次都不跑
    次数 += n
    return 次数


def 双倍(n):
    # 这一课的要求是「不碰全局」：算完直接 return，不要动 次数
    结果 = n * 2
    return 结果


def 现在几次():
    # 只读全局 —— 读不需要 global
    return 次数
