def 二分答案(下界, 上界, 可以吗):
    答案 = None
    # ⚠ 老老实实写 下界 = 中 + 1 / 上界 = 中 - 1；
    #   写成 下界 = 中 时，只剩两个数会死循环（中 永远等于 下界）
    while 下界 <= 上界:
        中 = (下界 + 上界) // 2
        if 可以吗(中):
            答案 = 中
            下界 = 中 + 1
        else:
            上界 = 中 - 1
    return 答案


def 切绳子(绳长表, 要的段数):
    if not 绳长表 or 要的段数 <= 0:
        return 0

    def 可以吗(长度):
        return sum(绳 // 长度 for 绳 in 绳长表) >= 要的段数

    return 二分答案(1, max(绳长表), 可以吗) or 0


def 分巧克力(边长表, 人数):
    if not 边长表 or 人数 <= 0:
        return 0

    def 可以吗(边长):
        return sum((s // 边长) ** 2 for s in 边长表) >= 人数

    return 二分答案(1, max(边长表), 可以吗) or 0
