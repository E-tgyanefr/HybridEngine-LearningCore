def 阶乘(n):
    # ⚠ 基准情形：0! = 1（不是 0）
    if n == 0:
        return 1
    # 规模变小：n 变成 n-1，一路朝着 0 走
    return n * 阶乘(n - 1)


def 斐波那契(n):
    # ⚠ 基准情形一次覆盖 0 和 1：fib(0)=0、fib(1)=1
    if n < 2:
        return n
    return 斐波那契(n - 1) + 斐波那契(n - 2)


def 汉诺塔(盘子数):
    if 盘子数 == 0:
        return 0
    # 两趟小搬运（各 汉诺塔(n-1) 次），中间加一趟大的（1 次）
    return 汉诺塔(盘子数 - 1) * 2 + 1


def 递归求和(数字们):
    # ⚠ 空列表是基准情形，返回 0（不是 None）
    if not 数字们:
        return 0
    # 第一个 + 剩下那些的和（剩下的是一个更短的列表 ⇒ 规模变小）
    return 数字们[0] + 递归求和(数字们[1:])
