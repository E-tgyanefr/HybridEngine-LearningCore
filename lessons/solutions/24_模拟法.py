def 走一秒(时, 分, 秒):
    秒 += 1
    if 秒 == 60:              # 秒满了，进到分
        秒 = 0
        分 += 1
    if 分 == 60:              # 分满了，进到时
        分 = 0
        时 += 1
    if 时 == 24:              # 时满了，回到 0
        时 = 0
    return 时, 分, 秒


def 走n秒(时, 分, 秒, n):
    # 合成一个"总秒数"最省事；86400 = 24 × 3600（一整天），要对它取余才能跨天
    总秒 = (时 * 3600 + 分 * 60 + 秒 + n) % 86400
    return 总秒 // 3600, 总秒 // 60 % 60, 总秒 % 60


def 排队办完(来的人):
    # 来的人 是 [(名字, 用时), ...]：办完时刻**累加**出来，第一个人从 0 开始办
    出 = []
    时刻 = 0
    for 名字, 用时 in 来的人:
        时刻 += 用时
        出.append((名字, 时刻))
    return 出
