"""第 26 课参考答案 —— 参数传递（可变 / 不可变）。"""


def 加进去(表, 东西):
    # ⚠ 就地改：表和外面那个列表是**同一个**列表，所以外面看得见
    表.append(东西)


def 清空(表):
    # ⚠ 也是就地改。写成 `表 = []` 只是让函数里的名字换了目标，外面不变
    表.clear()


def 复制一份再加(表, 东西):
    # ⚠ 先复制（切片就是复制），再改副本 —— 外面那个表一点不动
    新的 = 表[:]
    新的.append(东西)
    return 新的


def 排好序(表):
    # ⚠ 是 sorted（造新列表），不是 表.sort()（就地改）
    return sorted(表)


def 塞进元组(元组, 东西):
    # 元组不可变 ⇒ 只能造一个新的。⚠ (东西,) 的逗号不能省
    return 元组 + (东西,)
