"""第 05 课参考答案 —— 函数与参数。"""


def 问候(名字, 称呼="同学"):
    """⚠ 有默认值的参数写在后面 —— 这样 问候("小明") 也能调用。"""
    return f"你好，{名字}{称呼}！"


def 统计(数字们):
    """返回 (个数, 总和)。

    ⚠ 看起来像返回两个值，其实是返回一个**元组**：
        x = 统计([1,2])         ⇒  x 是 (2, 3)
        个数, 和 = 统计([1,2])   ⇒  自动拆开
    """
    return len(数字们), sum(数字们)


def 加全部(*数字):
    """⚠ *数字 把任意多个参数收成一个**元组**。

    加全部()  ⇒  数字 是 ()  ⇒ 返回 0（sum(()) 正好是 0）
    """
    return sum(数字)
