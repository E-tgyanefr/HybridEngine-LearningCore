成绩 = [90, 75, 60, 45, 88]


def 平均分(分数表):
    """平均分。用循环算一遍（虽然 Python 有 sum/len）。"""
    if not 分数表:              # ⚠ 空列表要特判，否则下面除以 0
        return 0.0
    和 = 0
    for x in 分数表:
        和 += x
    return 和 / len(分数表)      # ⚠ 一个斜杠 ⇒ 有小数；两个斜杠会丢小数


def 及格的人(分数表):
    """挑出及格的，**返回新列表**（不改传进来的那个）。"""
    出 = []
    for x in 分数表:
        if x >= 60:             # ⚠ 60 分是及格 ⇒ >= 不是 >
            出.append(x)
    return 出


def 最高分(分数表):
    """最大分数。"""
    # ⚠ 起点用**第一个元素**，不能写 0 —— 否则全负数时会返回 0
    最大 = 分数表[0]
    for x in 分数表:
        if x > 最大:
            最大 = x
    return 最大
