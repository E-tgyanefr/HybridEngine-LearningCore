"""第 18 课参考答案 —— 元组与集合。"""

坐标 = (3, 5)              # 元组：不能改，所以能当字典的键
单元素 = (7,)              # ⚠ 一个元素的元组**逗号不能省**；(7) 只是个数字

带重复 = [1, 2, 2, 3, 3, 3]
去重 = set(带重复)          # set() 顺手把重复去掉

座位 = {(1, 2): '小明', (3, 4): '小红'}     # ⚠ 列表当键会报 unhashable type: 'list'


def 共同(甲, 乙):
    # 交集：两个集合**都有**的元素
    return 甲 & 乙


def 只在我这(甲, 乙):
    # 差集：只在 甲 里、不在 乙 里的元素（顺序不能反）
    return 甲 - 乙
