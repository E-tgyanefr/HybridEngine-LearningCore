"""第 13 课参考答案 —— 字典。"""

库存 = {"苹果": 3, "香蕉": 5, "橘子": 1}


def 查数量(库存表, 商品名):
    # ⚠ 查不到的键直接 [] 会抛 KeyError，而"查一个没有的商品"是**正常情况**。
    #    get 的第二个参数就是"没有时给什么" —— 最短的写法。
    return 库存表.get(商品名, 0)


def 总件数(库存表):
    和 = 0
    # ⚠ 遍历字典拿到的是**键**；要同时拿键和值用 .items()（那一对括号不能少）
    for 名, 数 in 库存表.items():
        和 += 数
    return 和
