"""第 22 课参考答案 —— 原码、反码、补码（都以 8 位为例）。"""

位数 = 8


def 原码(数):
    # 原码 = 符号位（负数写 1）+ 绝对值的二进制，一共 8 位
    符号位 = '1' if 数 < 0 else '0'
    return 符号位 + format(abs(数), '0' + str(位数 - 1) + 'b')


def 补码(数):
    # ⚠ Python 的整数是无限位的，所以 bin(-5) 给的是 '-0b101'，不是补码。
    #   `数 & 255` 就是"截到低 8 位" —— 和"反码 + 1"得到的是同一个东西。
    return format(数 & 255, '0' + str(位数) + 'b')


def 补码转十进制(文字):
    # 最高位是 1 ⇒ 先把 8 位当正整数读，再减去 256（= 2 的 8 次方）
    if 文字[0] == '1':
        return int(文字, 2) - (1 << 位数)
    return int(文字, 2)


负五的补码值 = -5 & 255        # 11111011 当无符号数读 ⇒ 251
