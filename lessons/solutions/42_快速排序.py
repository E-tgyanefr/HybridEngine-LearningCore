"""第 42 课参考答案 —— 快速排序。"""


def 划分(表, 左, 右):
    基准 = 表[右]                 # Lomuto：拿最右边那个当基准
    界 = 左 - 1
    for i in range(左, 右):
        if 表[i] <= 基准:
            界 += 1
            表[界], 表[i] = 表[i], 表[界]
    表[界 + 1], 表[右] = 表[右], 表[界 + 1]
    return 界 + 1


def 快排(表, 左=0, 右=None):
    if 右 is None:
        右 = len(表) - 1
    if 左 >= 右:
        return 表
    位 = 划分(表, 左, 右)
    快排(表, 左, 位 - 1)
    快排(表, 位 + 1, 右)
    return 表


def 三数取中(表, 左, 右):
    中 = (左 + 右) // 2
    三 = [(表[左], 左), (表[中], 中), (表[右], 右)]
    三.sort(key=lambda x: x[0])
    return 三[1][1]
