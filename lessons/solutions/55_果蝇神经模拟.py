import random

#: 这一课的固定常数（和课程文件里那组一致）
兴奋权重 = 0.09
抑制权重 = 0.35
比例 = 0.8
每步敲几个 = 20
敲的强度 = 1.0


def 造连接(神经元数, 连接概率, 种子):
    """按概率生成一张有方向的网：[(前, 后, 权重), …]。

    ⚠ 用 `random.Random(f"{种子}-连接")` —— 自己的随机流。
      用全局 random 的话，同种子两次结果不一样，检查会当场抓住。
    """
    兴奋数 = int(round(神经元数 * 比例))
    兴奋数 = max(1, min(神经元数 - 1, 兴奋数))          # 两类都要有人
    随机 = random.Random(f"{种子}-连接")
    边 = []
    for 前 in range(神经元数):
        # 前 80% 是油门（正权重），后 20% 是刹车（负权重）
        权 = 兴奋权重 if 前 < 兴奋数 else -抑制权重
        for 后 in range(神经元数):
            if 前 == 后:
                continue                               # 不给自己连
            if 随机.random() < 连接概率:
                边.append((前, 后, 权))
    return 边


def 步进(膜电位, 输入, 漏电=0.85, 阈值=1.0):
    """走一步：漏 + 加输入 + 满了就发放并清零。返回 (新膜电位, 发放编号)。"""
    新, 发放 = [], []
    for i, v in enumerate(膜电位):
        v = v * 漏电 + 输入[i]
        if v >= 阈值:
            发放.append(i)
            v = 0.0                                    # ⚠ 不清零的话它每步都会发放
        新.append(v)
    return 新, 发放


def 跑仿真(神经元数, 连接概率, 步数, 种子):
    """把网络跑起来，返回 (平均放电率, 每步放电数)。"""
    边 = 造连接(神经元数, 连接概率, 种子)
    出边 = [[] for _ in range(神经元数)]
    for 前, 后, 权 in 边:
        出边[前].append((后, 权))

    电位 = [0.0] * 神经元数
    发放过 = [False] * 神经元数
    随机 = random.Random(f"{种子}-输入")               # 另一条独立的随机流
    每步 = []

    for _ in range(步数):
        输入 = [0.0] * 神经元数
        for _ in range(每步敲几个):                    # ① 外面随机敲几下
            输入[随机.randrange(神经元数)] += 敲的强度
        for 前 in range(神经元数):                     # ② 上一步发放的人往下游传
            if 发放过[前]:
                for 后, 权 in 出边[前]:
                    输入[后] += 权
        电位, 发放 = 步进(电位, 输入, 0.85, 1.0)      # ③ 走一步
        本步集 = set(发放)
        发放过 = [k in 本步集 for k in range(神经元数)]
        每步.append(len(发放))

    总 = sum(每步)
    return 总 / (神经元数 * 步数), 每步


