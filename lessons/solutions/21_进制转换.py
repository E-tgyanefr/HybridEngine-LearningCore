"""第 21 课参考答案 —— 进制转换。"""

二进制文字 = '1011'                     # ⚠ 要加引号：这是"一串文字"，不是数
它的十进制 = int(二进制文字, 2)          # 11

十进制数 = 255
它的十六进制 = hex(十进制数)             # '0xff'（带 0x 前缀、字母小写）


def 转十进制(文字, 进制):
    return int(文字, 进制)               # ⚠ 第一个参数必须是文字


def 转二进制文字(数):
    return bin(数)[2:]                   # bin() 给的是 '0b1010'，切掉前两个字符


def 数几个1(数):
    return bin(数).count('1')
