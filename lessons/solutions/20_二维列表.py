"""第 20 课参考答案 —— 二维列表。"""

表 = [[1, 2, 3], [4, 5, 6]]        # 两行三列

全部和 = 0
for 行 in 表:                      # 外层拿到的是一**行**
    for x in 行:                   # 内层拿到的是行里的**一个数**
        全部和 += x


def 取一列(表, 列号):
    # 一列 = 每一行的**同一个位置**
    return [行[列号] for 行 in 表]


def 造棋盘(n):
    # ⚠ 每行要**各造一个**：[['.'] * n] * n 只是把同一个列表放了 n 次（改一格三行都变）
    return [['.' for _ in range(n)] for _ in range(n)]
