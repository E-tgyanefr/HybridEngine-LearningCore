def 幂(底, 指数):
    结果 = 1                    # ⚠ 从 1 起：从 0 起的话乘什么都还是 0
    while 指数 > 0:
        if 指数 % 2 == 1:
            结果 *= 底           # 这一位是 1，就把当前的 底 乘进结果
        底 *= 底                 # 平方：底 依次变成 底²、底⁴、底⁸…
        指数 //= 2               # 指数右移一位（丢一位就够）
    return 结果


def 幂取模(底, 指数, 模):
    结果 = 1 % 模               # 模是 1 时一切结果都是 0
    while 指数 > 0:
        if 指数 % 2 == 1:
            结果 = 结果 * 底 % 模
        底 = 底 * 底 % 模        # ⚠ 每一步都取模，别等乘完再取
        指数 //= 2
    return 结果


def 第一个不小于(表, 目标):
    跳 = 1
    while 跳 < len(表):
        跳 *= 2                 # 先把步长放大到 ≥ 表长，再从大到小试
    位置 = 0
    while 跳 > 0:
        # ⚠ 先问「跳过去还在表内吗」，取元素用 位置 + 跳 - 1
        if 位置 + 跳 <= len(表) and 表[位置 + 跳 - 1] < 目标:
            位置 += 跳
        跳 //= 2
    return 位置


def 翻倍步数(n):
    数, 步 = 1, 0
    while 数 < n:
        数 *= 2
        步 += 1
    return 步
