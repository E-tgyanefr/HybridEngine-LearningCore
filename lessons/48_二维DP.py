# ─────────────────────────────────────────────────────
#  先介绍：一个列表装不下的时候
# ─────────────────────────────────────────────────────
#
# 前面用到的递推，答案是一串数，一个列表就够。但有一类问题有**两个**变化的
# 量：网格里的第几行第几列、两个字符串各取到第几个字。这时要开**一张表**：
#
#     dp = [[0] * 列 for _ in range(行)]     ← dp[行][列]
# ⚠ 别写成 `[[0] * 列] * 行` —— 那是**行个同一个列表**，改一格三行一起变。
#
# ─────────────────────────────────────────────────────
#  一、网格路径数：最直观的一道二维 DP
# ─────────────────────────────────────────────────────
#
# 3 行 4 列的格子，从左上角走到右下角，每次只能**往右**或**往下**，有几条路？
# 关键只有一句：**走到某一格的最后一步，只可能从上面或左边来**。于是
#
#     路径数[行][列] = 路径数[行-1][列] + 路径数[行][列-1]
#                      ↑ 从上面下来的       ↑ 从左面过来的
# 手填 3×3 的表 —— 第一行和第一列贴着边走，只有 1 条路：
#     1  1  1 ／ 1  2  3 ／ 1  3  6        右下角是 6  ⇒ 3×3 有 6 条路
#
# 数对得上：3×7 ⇒ 28 条；10×10 ⇒ 48620 条。表只有 100 格，一格一次加法，一共
# 100 次加法；而一条条路去数，10×10 要数 48620 条，20×20 是 35345263800 条 ——
# 根本走不完。这就是「用一张表换时间」。
# ─────────────────────────────────────────────────────
#  二、状态转移方程怎么写：三句话
# ─────────────────────────────────────────────────────
#
#   ① 状态：dp[行][列] 是什么意思？  —— 「从起点走到这一格的路径数」
#   ② 转移：这一格从哪来？          —— 「只从上边或左边来，所以两项相加」
#   ③ 边界：最小的那些格子填什么？  —— 「第一行、第一列全是 1」
# ⚠ 三句话缺一句都写不对，最容易漏的是 ③ —— 见这一课的坑。
#
# ─────────────────────────────────────────────────────
#  三、最长公共子序列（LCS）
# ─────────────────────────────────────────────────────
#
# 「子序列」不要求连在一起：`AGGTAB` 里 `GTAB` 是它的子序列，`AT` 也是。
#
#     LCS('AGGTAB', 'GXTXAYB') = 4     最长的是 GTAB
#     LCS('abcde', 'ace')      = 3     ace；LCS('abc', 'def') = 0（一个都不公共）
#
# 状态：dp[i][j] = 「甲的前 i 个字」和「乙的前 j 个字」的最长公共子序列长度。
#     甲[i-1] == 乙[j-1]  ⇒  dp[i][j] = dp[i-1][j-1] + 1     ← 这个字能配上
#     否则                ⇒  dp[i][j] = max(dp[i-1][j], dp[i][j-1])
#
# 边界：dp[0][*] 和 dp[*][0] 全是 0（空串跟谁都没有公共子序列）。
# ⚠ 字符串下标从 0 开始、dp 下标从 1 开始，所以写 甲[i-1] 不是 甲[i]。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：边界忘了填
# ─────────────────────────────────────────────────────
#
#     路径数[0][0] = 1          ← 忘了这句，整张表全是 0
#     dp[0][j] = dp[i][0] = 0   ← LCS 的边界，忘了就是**错答案**（还不报错）
# 另一类会直接崩的：表开小了、循环从 0 开始。
#     路径数[行][0] = 路径数[行-1][0]      ❌ 行=0 时
#     → IndexError: list index out of range
# ⇒ 固定顺序：**先开表 → 再填边界 → 最后两层循环填中间**。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   滚动数组、LCS 到底选了哪几个字、DP 优化 —— 先都不碰。
