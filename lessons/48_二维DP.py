def _喂(函数, 名字, 用例们, 提示):
    for 用例 in 用例们:
        *参数们, 想 = 用例
        try:
            得 = 函数(*参数们)
        except Exception as e:                                  # noqa: BLE001
            return False, f"{名字}{tuple(参数们)} 出错：{type(e).__name__}: {e}｜{提示}"
        if 得 != 想:
            return False, f"{名字}{tuple(参数们)} 应当是 {想!r}，得到 {得!r}｜{提示}"
    return True, f"{len(用例们)} 组都对"


def _暴力数路(行, 列):
    if 行 <= 0 or 列 <= 0:
        return 0
    if 行 == 1 or 列 == 1:
        return 1
    return _暴力数路(行 - 1, 列) + _暴力数路(行, 列 - 1)


def _暴力LCS(甲, 乙):
    from itertools import combinations
    最好 = 0
    for 长 in range(len(甲) + 1):
        for 位置 in combinations(range(len(甲)), 长):
            it = iter(乙)
            if all(甲[i] in it for i in 位置):
                最好 = 长
    return 最好


def CHECK_网格路径数(答案):
    f = 答案.__dict__.get("路径数")
    if not callable(f):
        return False, ("还没有定义「路径数」。要点：dp = [[1] * 列 for _ in range(行)]，"
                       "再 dp[i][j] = dp[i-1][j] + dp[i][j-1]，返回 dp[-1][-1]")
    return _喂(f, "路径数", ((1, 1, 1), (1, 5, 1), (5, 1, 1), (2, 2, 2), (3, 3, 6),
                          (3, 7, 28), (10, 10, 48620), (0, 5, 0), (5, 0, 0)),
               "边界：第一行、第一列全是 1（贴着边走只有一条路）；行列为 0 时返回 0")


def CHECK_路径表和暴力一致(答案):
    f = 答案.__dict__.get("路径表")
    if not callable(f):
        return False, ("还没有定义「路径表」—— 它和 路径数 一样填表，"
                       "但返回整张 dp（二维列表），不是 dp[-1][-1]")
    for 行, 列 in ((1, 1), (2, 3), (3, 3), (4, 4), (2, 5), (5, 2)):
        try:
            表 = f(行, 列)
        except Exception as e:                                  # noqa: BLE001
            return False, f"路径表({行}, {列}) 出错：{type(e).__name__}: {e}"
        if (not isinstance(表, list) or len(表) != 行
                or any(not isinstance(r, list) or len(r) != 列 for r in 表)):
            return False, (f"路径表({行}, {列}) 应当是 {行} 行 {列} 列的二维列表，得到 {表!r}"
                           f"｜开表：dp = [[1] * 列 for _ in range(行)]")
        if any(x != 1 for x in 表[0]) or any(r[0] != 1 for r in 表):
            return False, (f"路径表({行}, {列}) 的第一行/第一列应当全是 1，得到 "
                           f"{表[0]!r} 和 {[r[0] for r in 表]!r}｜贴着边走只有一条路")
        想 = _暴力数路(行, 列)
        if 表[-1][-1] != 想:
            return False, (f"路径表({行}, {列}) 右下角应当是 {想}（暴力枚举数出来的），"
                           f"得到 {表[-1][-1]!r}｜转移：dp[i][j] = dp[i-1][j] + dp[i][j-1]")
    return True, "6 组都和暴力枚举一致（含 1×1、单行、单列）"


def CHECK_最长公共子序列(答案):
    f = 答案.__dict__.get("最长公共子序列")
    if not callable(f):
        return False, ("还没有定义「最长公共子序列」。要点：dp 比字符串多一行一列"
                       "（边界全 0），甲[i-1]==乙[j-1] 时 dp[i-1][j-1]+1，否则取两个邻居的 max")
    return _喂(f, "最长公共子序列",
               (("", "", 0), ("a", "", 0), ("", "abc", 0), ("a", "a", 1),
                ("abc", "abc", 3), ("abcde", "ace", 3), ("abc", "def", 0),
                ("AGGTAB", "GXTXAYB", 4), ("aaaa", "aa", 2)),
               "两个字符串一个为空就是 0；dp 的下标从 1 开始，取字符要写 甲[i-1]")


def CHECK_LCS和暴力一致(答案):
    f = 答案.__dict__.get("最长公共子序列")
    if not callable(f):
        return False, "还没有定义「最长公共子序列」函数。"
    for 甲, 乙 in (("abc", "ac"), ("abcd", "bd"), ("xy", "yx"), ("aab", "ab"),
                   ("abcd", "dcba"), ("aaaa", "aa"), ("ab", "abcdefg"), ("z", "z")):
        try:
            得 = f(甲, 乙)
        except Exception as e:                                  # noqa: BLE001
            return False, f"最长公共子序列({甲!r}, {乙!r}) 出错：{type(e).__name__}: {e}"
        想 = _暴力LCS(甲, 乙)
        if 得 != 想:
            return False, (f"最长公共子序列({甲!r}, {乙!r}) 应当是 {想}（枚举所有子序列数出来的），"
                           f"得到 {得!r}｜dp 比字符串多一行一列")
    return True, "8 组都和暴力枚举一致"
