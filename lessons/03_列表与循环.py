# 第 03 课：列表与循环 —— 一次处理一堆东西


# ─────────────────────────────────────────────────────
#  先介绍：列表是什么，以及一个隐蔽的坑
# ─────────────────────────────────────────────────────
#
# 新手最容易写成这样：
#
#     for x in 分数表:
#         if x < 60:
#             分数表.remove(x)      # ← 错！边遍历边删
#
# 这会**跳过**元素：删掉一个之后，后面的元素整体前移，
# 而 for 的下标已经走过去了 —— 于是紧挨着被删元素的那一项永远检查不到。
# 这个 bug 很隐蔽：数据少的时候看不出来，数据一多就漏。
#
# ⇒ 正确做法是**造一个新列表**（下面这个套路到处都是）：
#
#     出 = []
#     for x in 分数表:
#         if 条件:
#             出.append(x)
#     return 出
#
# 它还有个好处：**不修改传进来的东西**。
# 调用者的列表还是原样 —— 这叫「没有副作用」，是函数该有的样子。
#
# ─────────────────────────────────────────────────────
#  列表的四个常用操作
# ─────────────────────────────────────────────────────
#
#     成绩 = [90, 75, 60, 45, 88]
#     成绩[0]          第一个（下标从 0 开始，不是 1）
#     成绩[-1]         最后一个（负数从右边数）
#     len(成绩)        有几个
#     sum(成绩)        加起来（Python 自带的）
#     max(成绩)        最大的
#
#   ⚠ len / sum / max 是**内置函数**，不用自己写循环。
#     但这一课的 平均分 / 及格的人 / 最高分 请你**用循环写一遍** ——
#     先会自己写，再知道有现成的，顺序不能反。
#
# ─────────────────────────────────────────────────────
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在下面的答题文件里写这几件事
# ─────────────────────────────────────────────────────
#
#   1. 定义列表 成绩，里面放 5 个分数（用整数，随便写，但要有大有小）
#   2. 写一个函数 平均分(分数表)，返回平均分（保留小数）
#   3. 写一个函数 及格的人(分数表)，返回一个新列表，只装及格的（>= 60）
#   4. 写一个函数 最高分(分数表)，返回最大的那个分数
#
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 编辑 03     写代码
#     python -m hybridengine_light 检查 03     检查答案
#     python -m hybridengine_light 答案 03     参考答案（先自己写一遍）


def CHECK_成绩列表(答案):
    if not hasattr(答案, "成绩"):
        return False, ("还没有定义「成绩」这个列表。\n"
                       "      写法：成绩 = [90, 75, 60, 45, 88]\n"
                       "      ⚠ 方括号，元素之间用逗号 —— 不是圆括号也不是花括号。")
    v = 答案.成绩
    if not isinstance(v, list):
        return False, (f"「成绩」应当是列表（list），现在是 {type(v).__name__}。\n"
                       f"      写法：成绩 = [90, 75, 60, 45, 88]")
    if len(v) < 3:
        return False, f"「成绩」里只有 {len(v)} 个元素，至少要 3 个（要求 5 个）。"
    if not all(isinstance(x, int) and not isinstance(x, bool) for x in v):
        坏的 = [x for x in v if not isinstance(x, int) or isinstance(x, bool)]
        return False, (f"「成绩」里应当都是整数，但发现了 {坏的[:3]}。\n"
                       f"      ⚠ 加了引号的 '90' 是**文字**不是数字，不能拿来算平均分。")
    if len(set(v)) == 1:
        return False, ("「成绩」里所有分数都一样 —— 那样测不出「最高分」这类函数对不对。\n"
                       "      请写几个**不一样**的分数（要有大有小）。")
    return True, f"{len(v)} 个分数：{v}"


def CHECK_平均分(答案):
    if not hasattr(答案, "平均分"):
        return False, "还没有定义「平均分」函数。写法：def 平均分(分数表): ..."
    if not callable(答案.平均分):
        return False, "「平均分」存在，但它不是函数。"
    for 表, 期望 in (([60, 70, 80], 70.0), ([100], 100.0), ([0, 0, 0], 0.0)):
        try:
            得 = 答案.平均分(表)
        except Exception as e:                                  # noqa: BLE001
            return False, (f"平均分({表}) 出错了：{type(e).__name__}: {e}\n"
                           f"      检查：函数是不是接收一个参数？空列表要不要特判？")
        if abs(得 - 期望) > 0.001:
            return False, (f"平均分({表}) 应当是 {期望}，实际是 {得}。\n"
                           f"      ⚠ 检查一件事：**是不是整数除法把小数丢了**？\n"
                           f"         Python 3 里 7 / 2 是 3.5（有小数），\n"
                           f"         但 7 // 2 是 3（整除，丢小数）—— 别写错成两个斜杠。")
    表 = [10, 20, 30, 40]
    得 = 答案.平均分(表)
    if abs(得 - 25.0) > 0.001:
        return False, (f"平均分({表}) 应当是 25.0，实际是 {得}。\n"
                       f"      ⚠ 很可能是把答案写死了 —— 要**用参数**算。")
    return True, "三组输入都对（含单个元素与全零）"


def CHECK_及格的人(答案):
    if not hasattr(答案, "及格的人"):
        return False, "还没有定义「及格的人」函数。"
    if not callable(答案.及格的人):
        return False, "「及格的人」不是函数。"
    表 = [90, 59, 60, 30, 100]
    原始 = list(表)
    try:
        得 = 答案.及格的人(表)
    except Exception as e:                                      # noqa: BLE001
        return False, f"及格的人({表}) 出错了：{type(e).__name__}: {e}"
    if not isinstance(得, list):
        return False, (f"「及格的人」应当**返回一个列表**，现在返回的是 {type(得).__name__}。\n"
                       f"      写法：出 = [] … return 出")
    if 得 != [90, 60, 100]:
        return False, (f"及格的人({表}) 应当是 [90, 60, 100]，实际是 {得}。\n"
                       f"      ⚠ 三个常见错：\n"
                       f"        · 边界写成 > 60 —— 60 分**是**及格，要用 >= 60\n"
                       f"        · 边遍历边 remove（会漏元素，见课程正文）\n"
                       f"        · 忘了 return，函数返回 None")
    if 表 != 原始:
        return False, (f"函数把**传进来的列表改了**：{原始} → {表}。\n"
                       f"      ⚠ 要造一个新列表返回，不要改调用者的东西。\n"
                       f"        否则调用者手里的数据会莫名其妙变少。")
    if 答案.及格的人([10, 20]) != []:
        return False, "全班都不及格时应当返回**空列表** []，不是 None。"
    if 答案.及格的人([60, 60]) != [60, 60]:
        return False, "60 分是及格 —— [60, 60] 应当原样返回。"
    return True, "含边界（60 分）且没有改动传进来的列表"


def CHECK_最高分(答案):
    if not hasattr(答案, "最高分"):
        return False, "还没有定义「最高分」函数。"
    if not callable(答案.最高分):
        return False, "「最高分」不是函数。"
    for 表, 期望 in (([90, 75, 60], 90), ([-5, -1, -9], -1), ([7], 7)):
        try:
            得 = 答案.最高分(表)
        except Exception as e:                                  # noqa: BLE001
            return False, f"最高分({表}) 出错了：{type(e).__name__}: {e}"
        if 得 != 期望:
            return False, (f"最高分({表}) 应当是 {期望}，实际是 {得}。\n"
                           f"      ⚠ 负数那组要注意：**起点不能写 0**。\n"
                           f"         如果写 最大 = 0 再比较，[-5,-1,-9] 会返回 0（错）。\n"
                           f"         要用 最大 = 分数表[0] 这样从第一个元素起。")
    return True, "三组都对（含全负数与单个元素）"
