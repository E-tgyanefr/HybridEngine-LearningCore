def CHECK_节点类(答案):
    类 = 答案.__dict__.get('节点')
    if not isinstance(类, type):
        return False, ('还没有定义**类**「节点」。写法：class 节点: 里 __init__(self, 值) 设 self.值 = 值；self.下一个 = None。')
    try:
        甲, 乙 = 类(5), 类(6)
    except Exception as e:                                      # noqa: BLE001
        return False, f'节点(5) 造不出来：{type(e).__name__}: {e}'
    if getattr(甲, '值', None) != 5 or getattr(甲, '下一个', '缺') is not None:
        return False, (f'节点(5) 应当是 .值 == 5、.下一个 is None，得到 '
                       f'{getattr(甲, "值", None)!r} / {getattr(甲, "下一个", "（没有这个属性）")!r}。')
    if 甲 is 乙:
        return False, '两个 节点(...) 应当是各自独立的对象。'
    甲.下一个 = 乙
    if 甲.下一个.值 != 6:
        return False, '甲.下一个 = 乙 之后 甲.下一个.值 应当是 6 —— 「下一个」里装的是**节点对象**。'
    return True, '节点类能造对象、值/下一个 都对、下一个能指向另一个节点'


def CHECK_建表和转列表(答案):
    建 = 答案.__dict__.get('建表')
    转 = 答案.__dict__.get('转列表')
    if not callable(建) or not callable(转):
        return False, ('还没有定义「建表」/「转列表」。建表：for 值 in reversed(表) 里 新.下一个 = 头; 头 = 新。')
    for 原 in ([], [1], [1, 2, 3, 4, 5], [0, -1, -2], [7] * 50, list(range(1000))):
        try:
            头 = 建(list(原))
        except Exception as e:                                  # noqa: BLE001
            return False, f'建表({原 if len(原) < 10 else "长表"}) 出错：{type(e).__name__}: {e}'
        if not 原:
            if 头 is not None:
                return False, f'建表([]) 应当返回 None，得到 {头!r}。'
            continue
        if isinstance(头, list):
            return False, '建表 返回的是**列表** —— 要返回头**节点**（有 .值 和 .下一个）。'
        if getattr(头, '值', None) != 原[0]:
            return False, f'建表({原[:6]}…) 的头节点应当是第一个值 {原[0]}，得到 {getattr(头, "值", None)!r}。'
        if len(原) >= 3 and getattr(getattr(getattr(头, '下一个', None), '下一个', None), '值', None) != 原[2]:
            return False, f'建表 的链式结构不对：头.下一个.下一个.值 应当是 {原[2]}。'
        try:
            得 = 转(头)
        except Exception as e:                                  # noqa: BLE001
            return False, f'转列表(建表({原[:6]}…)) 出错：{type(e).__name__}: {e}'
        if list(得) != list(原):
            return False, (f'建表 → 转列表 应当还原成 {原[:8]}…，得到 {list(得)[:8]}… —— '
                           f'遍历要写 `while 当前:`（写成 while 当前.下一个: 会漏掉最后一个）。')
    return True, '六组都对（含空表 → None、单元素、负数、50 个、1000 个）'


def CHECK_插入(答案):
    建 = 答案.__dict__.get('建表')
    转 = 答案.__dict__.get('转列表')
    插 = 答案.__dict__.get('插入')
    if not all(callable(x) for x in (建, 转, 插)):
        return False, ('还没有定义「建表」/「转列表」/「插入」。插入先处理 位置 == 0（返回新节点当头），否则走到 位置-1 再改指针。')
    for 原, 位置, 值, 想 in (([1, 2, 3], 0, 9, [9, 1, 2, 3]), ([1, 2, 3], 1, 9, [1, 9, 2, 3]),
                            ([1, 2, 3], 3, 9, [1, 2, 3, 9]), ([], 0, 9, [9]),
                            ([1, 2, 3], 10, 9, [1, 2, 3, 9]), ([7], 0, 8, [8, 7]), ([1], 1, 2, [1, 2])):
        try:
            得 = list(转(插(建(list(原)), 位置, 值)))
        except Exception as e:                                  # noqa: BLE001
            return False, f'插入({原}, {位置}, {值}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'插入({原}, {位置}, {值}) 应当是 {想}，得到 {得}。\n'
                           f'      ⚠ 位置 0 要**返回新节点**当头；越界追加末尾；接指针顺序反了会丢一段。')
    return True, '七组都对（含插头、插中间、插尾、空表、越界、单元素）'

def CHECK_删除(答案):
    建 = 答案.__dict__.get('建表')
    转 = 答案.__dict__.get('转列表')
    删 = 答案.__dict__.get('删除')
    if not all(callable(x) for x in (建, 转, 删)):
        return False, ('还没有定义「建表」/「转列表」/「删除」。删头要单独处理并**返回新头**：if 头.值 == 值: return 头.下一个。')
    for 原, 值, 想 in (([1, 2, 3], 2, [1, 3]), ([1, 2, 3], 1, [2, 3]), ([1, 2, 3], 3, [1, 2]),
                      ([1, 2], 9, [1, 2]), ([1, 1, 1], 1, [1, 1]), ([], 1, []),
                      ([5], 5, []), ([2, 3], 2, [3])):
        try:
            得 = list(转(删(建(list(原)), 值)))
        except Exception as e:                                  # noqa: BLE001
            return False, f'删除({原}, {值}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'删除({原}, {值}) 应当是 {想}，得到 {得}。\n'
                           f'      ⚠ 删头最关键：函数里写 头 = 头.下一个 只改局部变量，必须 return 头.下一个。')
    return True, '八组都对（含删头、删中间、删尾、删不存在的、全相同、删成空表）'
