#
# ─────────────────────────────────────────────────────
#  先介绍：列表连续，链表分散
# ─────────────────────────────────────────────────────
# 列表把元素**挨着放**（`表[3]` 一步跳到）；链表每个元素是一个**节点**，只装「值 + 下一个在哪」：
# `节点(1) → 节点(2) → 节点(3) → None` 就是 [1, 2, 3]，想找第 3 个只能从头走过去 —— 这是它的缺点。
#
# ─────────────────────────────────────────────────────
#  一、节点类
# ─────────────────────────────────────────────────────
#     class 节点:
#         def __init__(self, 值):
#             self.值 = 值
#             self.下一个 = None          ← 新节点后面还没有东西
#
# ─────────────────────────────────────────────────────
#  二、建表和遍历
# ─────────────────────────────────────────────────────
#     def 建表(表):
#         头 = None
#         for 值 in reversed(表):        ← 从后往前插，头插最省事
#             新 = 节点(值); 新.下一个 = 头; 头 = 新
#         return 头
#     def 转列表(头):
#         出, 当前 = [], 头
#         while 当前:                    ← ⚠ 不是 while 当前.下一个
#             出.append(当前.值); 当前 = 当前.下一个
#         return 出
# ⚠ 写成 `while 当前.下一个:` 会漏掉最后一个节点（[1, 2, 3] 变成 [1, 2]），而且不报错。
#
# ─────────────────────────────────────────────────────
#  三、插入：改两根指针
# ─────────────────────────────────────────────────────#     插入(头, 0, 9)：新节点.下一个 = 头，**返回新节点**（插在头上，头变了）；插入(头, 1, 9)：
#     先 新.下一个 = 前.下一个，再 前.下一个 = 新 —— 顺序反了会丢掉后面一整段。越界就追加到末尾。
#
# ─────────────────────────────────────────────────────
#  四、删除：头节点是特殊情况
# ─────────────────────────────────────────────────────
#     def 删除(头, 值):
#         if 头.值 == 值:
#             return 头.下一个              ← ⚠ 返回新头，不是 头 = 头.下一个
#         前 = 头
#         while 前.下一个:
#             if 前.下一个.值 == 值:
#                 前.下一个 = 前.下一个.下一个; return 头      ← 跳过它
#             前 = 前.下一个
#         return 头                        ← 没找到就原样返回
#
# ─────────────────────────────────────────────────────
#  五、为什么 Python 里少用链表
# ─────────────────────────────────────────────────────
# 链表的长处是「头插/中间插删不用搬家」（`列表.insert(0, x)` 要把后面元素全往后挪），但实测 1000
# 个元素：链表 **136000 字节**、列表 **36056 字节** ⇒ 两头进出用 deque（第 43 课）。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：删头节点时只改了局部变量
# ─────────────────────────────────────────────────────
#     def 删除(头, 值):
#         if 头.值 == 值:
#             头 = 头.下一个        ← ⚠ 只改了函数里的局部名字，外面拿到的还是老的头
#         return 头                 ← 删除(建表([1, 2, 3]), 1) 之后 转列表 还是 [1, 2, 3]
# ⚠ 不报错，只是白删。头是链表的入口，换了入口必须**把新头交出去**（`return 头.下一个`）。#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课只讲单链表；栈和队列在 第 43 课，树在 第 45 课；双向/循环链表不碰。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 写**类** 节点：`__init__(self, 值)`，属性 `值` 和 `下一个`（默认 None）
# 2. 写函数 建表(表)：返回**头节点**（空列表返回 None）；转列表(头)：收集成列表，None → []
# 4. 写函数 插入(头, 位置, 值)：返回**新头**（越界就追加末尾）；删除(头, 值)：删掉第一个
