    if not callable(f):
        return False, ("还没有定义函数「斐波那契表」。\n"
                       "      写法：def 斐波那契表(n):\n"
                       "               表 = [0, 1]\n"
                       "               for i in range(2, n + 1):\n"
                       "                   表.append(表[i - 1] + 表[i - 2])\n"
                       "               return 表[n]")
    for n, 想 in ((0, 0), (1, 1), (2, 1), (10, 55), (30, 832040)):
        try:
            得 = f(n)
        except Exception as e:                              # noqa: BLE001
            return False, f"斐波那契表({n}) 出错了：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"斐波那契表({n}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 起点 表 = [0, 1]；循环从 2 填到 n（range 的右端写 n + 1）。")
