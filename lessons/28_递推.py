import threading


def _限时跑(函数, 参数, 秒=3.0):
    """在另一个线程里调用学员的函数，超时就判失败。

    ⚠ 为什么必须限时：这一课的核心就是「递归版算不动」。
      如果学员写了递归版，`斐波那契表(200)` 会跑到天荒地老 ——
      没有超时的话，检查会跟着一起卡死，学员看到的是"命令没反应"。
    """
    结果 = {}

    def 干():
        try:
            结果["值"] = 函数(参数)
        except BaseException as e:                          # noqa: BLE001
            结果["错"] = e

    线 = threading.Thread(target=干, daemon=True)
    线.start()
    线.join(秒)
    if 线.is_alive():
        return False, "超时"
    if "错" in 结果:
        return False, f"{type(结果['错']).__name__}: {结果['错']}"
    return True, 结果["值"]


def CHECK_爬楼梯(答案):
    f = 答案.__dict__.get("爬楼梯")
    if not callable(f):
        return False, ("还没有定义函数「爬楼梯」。\n"
                       "      写法：def 爬楼梯(n):\n"
                       "               表 = [1, 1]\n"
                       "               for i in range(2, n + 1):\n"
                       "                   表.append(表[i - 1] + 表[i - 2])\n"
                       "               return 表[n]")
    for n, 想 in ((0, 1), (1, 1), (2, 2), (3, 3), (5, 8), (20, 10946), (40, 165580141)):
        try:
            得 = f(n)
        except Exception as e:                              # noqa: BLE001
            return False, f"爬楼梯({n}) 出错了：{type(e).__name__}: {e}"
        if 得 != 想:
            return False, (f"爬楼梯({n}) 应当是 {想}，得到 {得!r}。\n"
                           f"      ⚠ 这道题的起点是 表 = [1, 1]：f(0)=1（原地不动算 1 种）、"
                           f"f(1)=1。\n"
                           f"        写成 [0, 1] 会让所有答案都错位一格。")
    return True, "七组都对（含 0 级和 40 级）"


