# ─────────────────────────────────────────────────────
#  先介绍：上一课的斐波那契，慢在哪
# ─────────────────────────────────────────────────────
#
# 第 27 课的递归版斐波那契，实测：n=30 要 0.06 秒，n=40 要 8.3 秒，
# n=50 要十几分钟 —— 明明只是加加法，为什么要那么久？
#
# 因为它在**反复算同一个值**。算 斐波那契(5) 时：
#
#     fib(5) = fib(4) + fib(3)
#              fib(4) = fib(3) + fib(2)      ← fib(3) 又算了一遍！
#
# 越往下重复越多。**递推就是把方向倒过来**：从小到大，每个值只算一次，
# 算完立刻记在表里，后面直接取 —— 于是 n=200 也是「一瞬间」。
#
# ─────────────────────────────────────────────────────
#  一、思路倒过来：从最小的开始，往前推
# ─────────────────────────────────────────────────────
#
#     递归（从上往下问）        递推（从下往上填）
#     ─────────────────         ────────────────
#     想知道 fib(5)             已知 fib(0)=0、fib(1)=1
#       先问 fib(4)、fib(3)     算 fib(2) = fib(1) + fib(0)
#         又各自往下问…          算 fib(3) = fib(2) + fib(1)
#     同一个值问很多遍           算 fib(4)、fib(5)…
#                                每个值**只算一次**
#
# 递推的三件事，缺一不可：
#
#     ① 起点：最小的那几格答案是什么（直接写死）
#     ② 循环：从第几格填到第几格
#     ③ 递推式：这一格怎么由**前面几格**推出来
#
# ─────────────────────────────────────────────────────
#  二、模板：一张表 + 一个循环
# ─────────────────────────────────────────────────────
#
#     def 斐波那契表(n):
#         表 = [0, 1]                            ← ① 起点：写最小的几格
#         for i in range(2, n + 1):              ← ② 从 2 填到 n
#             表.append(表[i - 1] + 表[i - 2])   ← ③ 用前面两格推这一格
#         return 表[n]
#
#     ⚠ `range(2, n + 1)` 里那个 `+ 1` 不能丢：要一直填到**下标 n** 那一格。
#
#   ⚠ 表里存什么，是递推题的第一步。这里存的是「第 i 个斐波那契数」，
#     所以 `表[i]` 就是答案。换个题，表里存的可能是「走法数」「最大和」……
#
# ─────────────────────────────────────────────────────
#  三、差多少倍：实测数字
# ─────────────────────────────────────────────────────
#
#          n        递归版          递推版
#     ────────  ─────────────  ─────────────
#        30      0.06 秒        0.00002 秒
#        40      8.3 秒         0.00003 秒
#        50      十几分钟        0.00004 秒
#       200      算不出来        0.00004 秒
#
# 递推版算 fib(200) 的答案（实测，瞬间出结果）：
#
#     280571172992510140037611932413038677189525
#
# ⚠ Python 的整数没有上限，所以递推版能一路算到大得吓人的数；
#   递归版连 n=50 都等不到。
#
#   ⚠ 复杂度上：递归版是 O(2ⁿ)（指数级），递推版是 O(n)（线性）。
#     第 31 课专门讲这个记号，这里先感受一下数量级的差别。
#
# ─────────────────────────────────────────────────────
#  四、爬楼梯（递推最经典的题）
# ─────────────────────────────────────────────────────
#
# 题目：n 级台阶，每次走 1 级或 2 级，一共有多少种走法？
#
# 想**最后一步**：到第 n 级之前，你在哪儿？
#
#     要么在 n-1 级，向上走 1 级        要么在 n-2 级，向上走 2 级
#
# ⇒ 走法数 = 走到 n-1 的走法数 + 走到 n-2 的走法数，也就是：
#
#     f(n) = f(n-1) + f(n-2)        又是一个斐波那契
#
#     f(0) = 1（原地不动算 1 种）   f(1) = 1   f(2) = 2   f(3) = 3   f(4) = 5
#
#     def 爬楼梯(n):
#         表 = [1, 1]
#         for i in range(2, n + 1):
#             表.append(表[i - 1] + 表[i - 2])
#         return 表[n]
#
# ⚠ 起点 `[1, 1]` 是这道题最容易错的地方：f(0) 规定为 1，不是 0。
#
# ─────────────────────────────────────────────────────
#  五、进阶一点：表里存「以它结尾的最大和」
# ─────────────────────────────────────────────────────
#
# 题目：给一串数（有正有负），求**连续一段**的和最大是多少。
#
# 递推式：`表[i] = 以第 i 个数结尾的最大和`
#
#     要么接着前面那段    表[i] = 表[i-1] + 数字[i]
#     要么从自己重新开始  表[i] = 数字[i]
#     ⇒ 表[i] = max(表[i-1] + 数字[i], 数字[i])
#
# 答案就是表里最大的那一格。⚠ 全是负数时答案不是 0，而是**最大的那个负数**
# （题目要求至少选一个数）。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：表的格子数不够（递推的经典越界）
# ─────────────────────────────────────────────────────
#
#     def 斐波那契表(n):
#         表 = [0] * n                 ← 只有 n 格，下标只到 n-1
#         for i in range(2, n + 1):
#             表[i] = 表[i - 1] + 表[i - 2]
#         return 表[n]
#
#     ⇒ IndexError: list assignment index out of range
#
# ⚠ 报错说「赋值越界」，是因为要往 `表[n]` 写 —— 可它只有 n 格。
#   要的是**下标 0 到 n 一共 n+1 格**：
#
#         表 = [0] * (n + 1)     ← 记住这个 +1
#
#   ⚠ 另一类同源错误：`for i in range(2, n)` 少写 `+1`，
#     结果最后一格没填，返回时取 表[n] 又是 IndexError（这次是读取越界）。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   动态规划、记忆化搜索、二维递推（数字三角形）、滚动数组优化 —— 用到再说。
#   这一课只讲：起点 + 循环 + 递推式，一张表从前往后填。
#
