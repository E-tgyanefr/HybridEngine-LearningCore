#
# ─────────────────────────────────────────────────────
#  先介绍：链表是一条线，树会分叉
# ─────────────────────────────────────────────────────
# 链表每个节点只有**一个** `下一个`；树节点有**两个**孩子：`左` 和 `右`。这一课都用这棵三层
# 7 节点的树（根 1，左 2 右 3，2 的孩子 4/5，3 的孩子 6/7）：
#     前序 [1, 2, 4, 5, 3, 6, 7]   中序 [4, 2, 5, 1, 6, 3, 7]   高度 3
#     后序 [4, 5, 2, 6, 7, 3, 1]   层序 [1, 2, 3, 4, 5, 6, 7]
#
# ─────────────────────────────────────────────────────
#  一、树节点类
# ─────────────────────────────────────────────────────
#     class 树节点:
#         def __init__(self, 值):
#             self.值 = 值; self.左 = None; self.右 = None     ← 没孩子就是 None
#
# ─────────────────────────────────────────────────────
#  二、前序 / 中序 / 后序：只差「根什么时候访问」
# ─────────────────────────────────────────────────────
#     def 前序(根):                       前序 = 根、左、右
#         if 根 is None: return []        ← ⚠ 不判空会 AttributeError
#         return [根.值] + 前序(根.左) + 前序(根.右)
#
# 中序把 `根.值` 挪到中间（左、根、右），后序挪到最后（左、右、根）—— 一行之差。
# 每个节点正好访问一次 ⇒ 复杂度 O(n)：7 个节点访问 7 次。
#
# ─────────────────────────────────────────────────────
#  三、层序：一层一层，从左到右（用队列）
# ─────────────────────────────────────────────────────
# 层序不是递归，是**广度优先**：根入队，每次取出一个、把它的左右孩子接到队尾。
#     队 = deque([根]); 出 = []
#     while 队:
#         点 = 队.popleft(); 出.append(点.值)
#         if 点.左: 队.append(点.左)
#         if 点.右: 队.append(点.右)
# ⚠ 队列用 deque（第 43 课）：用 `列表.pop(0)` 结果一样，但那是 O(n)。
#
# ─────────────────────────────────────────────────────
#  四、高度与完全二叉树
# ─────────────────────────────────────────────────────
# 高度 = 最长的「从根到叶子」有几层：空树 0、单节点 1、上面那棵树 3。
#     def 高度(根):
#         if 根 is None: return 0
#         return 1 + max(高度(根.左), 高度(根.右))
# **完全二叉树**：除了最后一层都排满，最后一层靠左排。好处是能**用数组装**：下标 i 的
# 左孩子是 `2i+1`、右孩子是 `2i+2`。高度 = ⌊log2 n⌋ + 1：n = 7 → 3 层、n = 100 万 → 20 层。
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：空树没判，直接 AttributeError
# ─────────────────────────────────────────────────────
#     def 前序(根):
#         return [根.值] + 前序(根.左) + 前序(根.右)      ← 没有 if 根 is None
#
#     前序(None)  ⇒  AttributeError: 'NoneType' object has no attribute '值'
# 递归到叶子时 `根.左` 是 None，下一次调用就拿到了 None ⇒ 三条遍历 + 高度第一行都要判空。
# 第二个坑：**中序写成「根左右」** —— 得到 [1, 2, 4, 5, 3, 6, 7]（跟前序一样），看着正常，其实错。
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课只讲二叉树和四种遍历；二叉排序树、哈夫曼树、图都不碰。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
# 1. 写**类** 树节点：`__init__(self, 值)`，属性 `值`、`左`、`右`（后两个默认 None）
# 2. 写函数 前序(根)、中序(根)、后序(根)：递归，返回值的列表；空树返回 []
# 3. 写函数 层序(根)：一层一层从左到右（用 collections.deque）；高度(根)：空树 0、单节点 1
