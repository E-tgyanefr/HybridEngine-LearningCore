# 第 04 课：字典 —— 按名字找东西

# 要做：
#   1. 定义字典 库存，键是商品名（文字），值是数量（整数），至少 3 样
#   2. 写一个函数 查数量(库存表, 商品名)，返回数量；**没有这样商品就返回 0**
#   3. 写一个函数 总件数(库存表)，返回所有数量之和
#   4. 写一个函数 最多的是谁(库存表)，返回数量最多的那个商品名

# ─────────────────────────────────────────────────────
#  列表 vs 字典：什么时候用哪个
# ─────────────────────────────────────────────────────
#
#   列表：一排格子，按**位置**取 —— 成绩[0]、成绩[1]
#   字典：一堆抽屉，按**名字**取 —— 库存['苹果']
#
#   ⚠ 判断标准很简单：
#     你需要问「第几个」 ⇒ 列表
#     你需要问「叫什么」 ⇒ 字典
#
#   苹果 3 个、香蕉 5 个 —— 你不会想说「第 0 样是苹果」，
#   你只想说「苹果还有几个」。那就是字典。
#
#     库存 = {'苹果': 3, '香蕉': 5}
#     库存['苹果']            3
#     库存['橘子']            ← KeyError！没有这个键
#
# ─────────────────────────────────────────────────────
#  第 2 条为什么要「没有就返回 0」
# ─────────────────────────────────────────────────────
#
# 直接 库存[商品名] 在键不存在时会**抛 KeyError**，
# 而「查一个没有的商品」是**正常情况**，不该让程序崩。
#
# ⇒ 两种写法，都行：
#
#     库存.get(商品名, 0)              ← 最简（get 的第二个参数是「没有时给什么」）
#
#     if 商品名 in 库存:               ← 先问在不在
#         return 库存[商品名]
#     return 0
#
# 这一课请你**两种都写一遍**（第 2 条用 get，另外用 in 检查一次）。
#
# ─────────────────────────────────────────────────────
#  遍历字典
# ─────────────────────────────────────────────────────
#
#     for 名 in 库存:                  遍历**键**
#         print(名)
#
#     for 名, 数 in 库存.items():      同时拿到键和值（最常用）
#         print(名, 数)
#
#   ⚠ .items() 那一对括号不能省 —— 少了就变成遍历方法对象，会报错。
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 04


def CHECK_库存字典(答案):
    if not hasattr(答案, "库存"):
        return False, ("还没有定义「库存」这个字典。\n"
                       "      写法：库存 = {'苹果': 3, '香蕉': 5}\n"
                       "      ⚠ **花括号**，键和值之间用**冒号**。")
    v = 答案.库存
    if not isinstance(v, dict):
        return False, (f"「库存」应当是字典（dict），现在是 {type(v).__name__}。\n"
                       f"      ⚠ 方括号 [] 是列表，花括号 {{}} 才是字典。")
    if len(v) < 3:
        return False, f"「库存」里只有 {len(v)} 样商品，至少要 3 样。"
    if not all(isinstance(k, str) for k in v):
        return False, "字典的**键**应当是商品名（文字，要加引号）。"
    if not all(isinstance(x, int) and not isinstance(x, bool) for x in v.values()):
        return False, "字典的**值**应当是数量（整数，不加引号）。"
    if len(set(v.values())) == 1:
        return False, ("所有商品数量都一样 —— 那样测不出「最多的是谁」。\n"
                       "      请让数量有差别。")
    return True, f"{len(v)} 样商品：{v}"


def CHECK_查数量(答案):
    if not hasattr(答案, "查数量"):
        return False, "还没有定义「查数量」函数。写法：def 查数量(库存表, 商品名): ..."
    if not callable(答案.查数量):
        return False, "「查数量」不是函数。"
    表 = {'苹果': 3, '香蕉': 5}
    if 答案.查数量(表, '苹果') != 3:
        return False, (f"查数量(表, '苹果') 应当是 3，实际是 {答案.查数量(表, '苹果')}。\n"
                       f"      是否**用参数**查的？还是写死了？")
    try:
        得 = 答案.查数量(表, '橘子')
    except KeyError:
        return False, ("查一个**没有的商品**时抛了 KeyError —— 这正是这一课要避免的。\n"
                       "      写法一：return 库存表.get(商品名, 0)\n"
                       "      写法二：if 商品名 in 库存表: return 库存表[商品名]\n"
                       "              return 0")
    except Exception as e:                                      # noqa: BLE001
        return False, f"查不存在的商品时出错了：{type(e).__name__}: {e}"
    if 得 != 0:
        return False, (f"查一个没有的商品应当返回 **0**，实际返回 {得!r}。\n"
                       f"      ⚠ 返回 None 也不行 —— 调用者拿去做加法会崩。")
    if 答案.查数量({}, '任何') != 0:
        return False, "空字典里查任何东西都应当返回 0。"
    return True, "查得到 / 查不到 两条路都对"


def CHECK_总件数(答案):
    if not hasattr(答案, "总件数"):
        return False, "还没有定义「总件数」函数。"
    if not callable(答案.总件数):
        return False, "「总件数」不是函数。"
    for 表, 期望 in (({'a': 1, 'b': 2}, 3), ({}, 0), ({'x': 10}, 10), ({'a': -1, 'b': 1}, 0)):
        try:
            得 = 答案.总件数(表)
        except Exception as e:                                  # noqa: BLE001
            return False, f"总件数({表}) 出错了：{type(e).__name__}: {e}"
        if 得 != 期望:
            return False, (f"总件数({表}) 应当是 {期望}，实际是 {得}。\n"
                           f"      ⚠ 遍历字典取的是**键**。要拿值得用 .values() 或 .items()：\n"
                           f"         for 名, 数 in 表.items(): 和 += 数")
    return True, "四组都对（含空字典与正负抵消）"


def CHECK_最多的是谁(答案):
    if not hasattr(答案, "最多的是谁"):
        return False, "还没有定义「最多的是谁」函数。"
    if not callable(答案.最多的是谁):
        return False, "「最多的是谁」不是函数。"
    表 = {'苹果': 3, '香蕉': 5, '橘子': 1}
    得 = 答案.最多的是谁(表)
    if 得 != '香蕉':
        return False, (f"最多的是谁({表}) 应当是 '香蕉'，实际是 {得!r}。\n"
                       f"      ⚠ 要返回**商品名**，不是数量。\n"
                       f"        写法：记一个「暂时最多」，遍历时发现更大的就同时换掉名字。")
    try:
        if 答案.最多的是谁({}) is not None:
            return False, "空字典时应当返回 None（没有「最多的」）。"
    except Exception as e:                                      # noqa: BLE001
        return False, (f"空字典时抛了 {type(e).__name__}。\n"
                       f"      空字典要能处理 —— 开头先 if not 库存表: return None。")
    return True, "含空字典边界"
