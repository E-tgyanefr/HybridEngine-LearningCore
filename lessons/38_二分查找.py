def CHECK_二分查找(答案):
    f = 答案.__dict__.get('二分查找')
    if not callable(f):
        return False, ('还没有定义「二分查找」。骨架：左, 右 = 0, len(表) - 1；while 左 <= 右: 中 = (左 + 右) // 2；比大小后 左 = 中 + 1 / 右 = 中 - 1。')
    for 表, 目标 in (([], 1), ([5], 5), ([5], 4), ([1, 3, 5, 7, 9], 1), ([1, 3, 5, 7, 9], 9),
                     ([1, 3, 5, 7, 9], 5), ([1, 3, 5, 7, 9], 4), ([2, 2, 2], 2),
                     ([-5, -1, 0, 3], -5), (list(range(1000000)), 999999)):
        try:
            得 = f(list(表), 目标)
        except Exception as e:                                  # noqa: BLE001
            return False, f'二分查找(长度 {len(表)} 的表, {目标}) 出错：{type(e).__name__}: {e}'
        if 目标 in 表:                    # 找到了：位置必须真的对得上
            if not (isinstance(得, int) and 0 <= 得 < len(表) and 表[得] == 目标):
                return False, (f'二分查找(长度 {len(表)} 的表, {目标}) 返回 {得!r}，'
                               f'但这个位置上的值不是 {目标}。\n'
                               f'      ⚠ 返回的必须是下标；有重复元素时返回哪一个都算对。')
        elif 得 != -1:
            return False, (f'二分查找(长度 {len(表)} 的表, {目标})：{目标} 不在表里，'
                           f'应当返回 -1，得到 {得!r}。\n'
                           f'      ⚠ 空表也要返回 -1（len(表) - 1 = -1，写成 while 左 < 右 就会漏）。')
    return True, '十组都对（含空表、单元素、找不到、重复元素、负数、100 万个数）'


def CHECK_找第一个(答案):
    f = 答案.__dict__.get('找第一个')
    if not callable(f):
        return False, ('还没有定义「找第一个」。写法：命中时别急着返回，把 右 = 中 - 1 继续往左找，用变量记住最后一次命中的下标。')
    for 表, 目标, 想 in (([], 1, -1), ([1, 2, 2, 2, 3], 2, 1), ([2, 2, 2], 2, 0),
                        ([1, 3], 2, -1), ([5] * 10, 5, 0), ([1, 2, 2, 2, 3], 3, 4),
                        ([1, 2, 2, 2, 3], 1, 0), ([-3, -3, 0], -3, 0)):
        try:
            得 = f(list(表), 目标)
        except Exception as e:                                  # noqa: BLE001
            return False, f'找第一个({表}, {目标}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'找第一个({表}, {目标}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 命中之后还要继续往左半边找：把 右 = 中 - 1，'
                           f'并且用变量记住答案。')
    return True, '八组都对（含空表、全相同、找不到、负数）'


def CHECK_用bisect找(答案):
    import io
    f = 答案.__dict__.get('用bisect找')
    if not callable(f):
        return False, ('还没有定义「用bisect找」。写法：import bisect 后用 '
                       'bisect.bisect_left(有序表, 目标)，再确认 表[得] == 目标。')
    for 表, 目标, 想 in (([], 1, -1), ([1, 2, 2, 2, 3], 2, 1), ([1, 2, 2, 2, 3], 3, 4),
                        ([1, 3], 2, -1), ([5] * 10, 5, 0), ([1, 3, 5], 0, -1), ([1, 3, 5], 9, -1)):
        try:
            得 = f(list(表), 目标)
        except Exception as e:                                  # noqa: BLE001
            return False, f'用bisect找({表}, {目标}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'用bisect找({表}, {目标}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ bisect_left 找不到时返回的是**该插的位置**（不是 -1），'
                           f'要自己确认 表[得] == 目标。')
    源码 = io.open(答案.__file__, encoding='utf-8').read() if hasattr(答案, '__file__') else ''
    i = 源码.find('def 用bisect找')
    段 = 源码[i:] if i >= 0 else ''
    j = 段.find('\ndef ', 1)
    if j > 0:
        段 = 段[:j]
    if 'bisect' not in 段:
        return False, ('「用bisect找」里没有用 bisect 模块 —— 这一条就是要练标准库。\n'
                       '      ⚠ 写法：import bisect 然后 bisect.bisect_left(表, 目标)。')
    return True, '七组都对，而且确实用了 bisect'


def CHECK_没偷懒(答案):
    import io
    if not hasattr(答案, '__file__'):
        return False, '找不到你的答题文件。'
    源码 = io.open(答案.__file__, encoding='utf-8').read()
    i = 源码.find('def 二分查找')
    if i < 0:
        return False, '找不到「二分查找」这个函数。'
    段 = 源码[i:]
    j = 段.find('\ndef ', 1)
    if j > 0:
        段 = 段[:j]
    if '.index(' in 段 or 'bisect' in 段 or ' in ' in 段:
        return False, ('「二分查找」里用了 .index() / bisect / `in` —— 那些都是一个个比（O(n)），\n'
                       '      不是二分。这一条要手写：while 左 <= 右 里比 有序表[中]。')
    if 'while' not in 段 and '二分查找(' not in 段[len('def 二分查找'):]:
        return False, '「二分查找」里既没有 while 也没有递归 —— 看起来不是二分。'
    return True, '是手写的二分（没用 .index() / bisect / in 这些线性做法）'
