# ─────────────────────────────────────────────────────
#  先介绍：有序是一笔财富
# ─────────────────────────────────────────────────────
# 在 100 万个数里找一个数，一个一个比平均要 **50 万次**；但如果表**已经排好序**，
# 每次看正中间那个就能砍掉一半：100 万 → 50 万 → 25 万 → … → 1，最多 **20 次**
# （log2 1000000 ≈ 19.93；10 亿个数也只要 30 次）。代价是：表必须是有序的。
#
# ─────────────────────────────────────────────────────
#  一、手写二分：四行核心
# ─────────────────────────────────────────────────────
#     def 二分查找(有序表, 目标):
#         左, 右 = 0, len(有序表) - 1
#         while 左 <= 右:                  ← ⚠ 是 <=，不是 <
#             中 = (左 + 右) // 2
#             if 有序表[中] == 目标:
#                 return 中
#             if 有序表[中] < 目标:
#                 左 = 中 + 1              ← ⚠ 两边都要 ±1，否则死循环
#             else:
#                 右 = 中 - 1
#         return -1
#
# 走一遍 `二分查找([1, 3, 5, 7, 9], 7)`：左=0 右=4 中=2 → 5 < 7 → 左=3；
# 左=3 右=4 中=3 → 7 == 7 → 返回 **3**。
#
# 边界为什么必须这样写：
# ① `while 左 < 右` 会漏掉只有一个元素的区间：`二分查找([5], 5)` 时 左 = 右 = 0，
#    `0 < 0` 不成立 ⇒ 循环不进 ⇒ 返回 -1（错）。
# ② `左 = 中` 会**死循环**：只剩两个数时 中 永远等于 左，区间一点没变小。
#
# ─────────────────────────────────────────────────────
#  二、bisect：标准库里的二分（别自己重造）
# ─────────────────────────────────────────────────────
#     import bisect
#     bisect.bisect_left([1, 2, 2, 2, 3], 2)    ⇒ 1    最左边那个 2 的位置
#     bisect.bisect_right([1, 2, 2, 2, 3], 2)   ⇒ 4    最右边那个 2 的**后面**一格
#     bisect.insort([1, 3], 2)                  ⇒ 表变成 [1, 2, 3]（插进去，保持有序）
#
# ⚠ 找不到时**不返回 -1**，而是返回「该插在哪」：`bisect_left([1, 3], 2)` ⇒ 1。
#   所以用它找元素要再确认一下：`得 < len(表) and 表[得] == 目标`。
#
# ─────────────────────────────────────────────────────
#  三、和一个个找比
# ─────────────────────────────────────────────────────
#     表长        1000        1000000     1000000000
#     一个一个找  500 次      50 万次     5 亿次
#     二分        10 次       20 次       30 次
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：表没排序，二分不报错，只是答案错
# ─────────────────────────────────────────────────────
#     `二分查找([1, 5, 2, 9, 3], 3)`   ⇒  -1      ← 3 明明就在表里！
#
# 为什么：中 = 2 时看到 2 < 3，就认定「3 在右半边」、把左边界推到 3，可 3 其实在
#   左边没被看过的位置。**二分只在有序表上成立。** ⚠ 这类错一个字都不报 —— 返回的
#   是一个看起来很正常的 -1。所以用二分之前先确认表是有序的（数据本身无序就先排序）。
#
