def CHECK_最大公约数(答案):
    f = 答案.__dict__.get('最大公约数')
    if not callable(f):
        return False, ('还没有定义「最大公约数」。写法：甲乙都取 abs，然后\n'
                       '      while 乙: 甲, 乙 = 乙, 甲 % 乙；循环完返回 甲。')
    for 甲, 乙, 想 in ((12, 18, 6), (0, 5, 5), (5, 0, 5), (0, 0, 0), (7, 7, 7),
                       (17, 5, 1), (1071, 462, 21), (-12, 18, 6), (12, -18, 6),
                       (999983, 1000003, 1)):
        try:
            得 = f(甲, 乙)
        except Exception as e:                                  # noqa: BLE001
            return False, (f'最大公约数({甲}, {乙}) 出错：{type(e).__name__}: {e}\n'
                           f'      ⚠ 十有八九是循环写成 `while 甲 % 乙 != 0` 了 —— '
                           f'乙 = 0 时那一句直接崩，要写成 `while 乙:`。')
        if 得 != 想:
            return False, (f'最大公约数({甲}, {乙}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 负数要先 abs；最大公约数(0, 0) 按约定返回 0。')
    return True, '十组都对（含 0、负数、相等、互质、1071/462、六位数大质数）'


def CHECK_最小公倍数(答案):
    f = 答案.__dict__.get('最小公倍数')
    if not callable(f):
        return False, ('还没有定义「最小公倍数」。写法：有 0 就返回 0，\n'
                       '      否则 return 甲 // 最大公约数(甲, 乙) * 乙')
    for 甲, 乙, 想 in ((4, 6, 12), (0, 5, 0), (5, 0, 0), (1, 1, 1), (7, 7, 7),
                       (-4, 6, 12), (21, 6, 42), (123456, 789012, 8117355456)):
        try:
            得 = f(甲, 乙)
        except Exception as e:                                  # noqa: BLE001
            return False, (f'最小公倍数({甲}, {乙}) 出错：{type(e).__name__}: {e}\n'
                           f'      ⚠ 只要有一个是 0 就该直接返回 0（0 不能当除数）。')
        if 得 != 想:
            return False, (f'最小公倍数({甲}, {乙}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 公式是 甲 // 最大公约数(甲, 乙) * 乙，负数先取绝对值。')
    return True, '八组都对（含 0、1、相等、负数、123456 与 789012）'


def CHECK_约分(答案):
    f = 答案.__dict__.get('约分')
    if not callable(f):
        return False, ('还没有定义「约分」。写法：分母是 0 返回 None；否则上下都除以\n'
                       '      最大公约数，再让分母保持正数（负号挪到分子）。')
    for 分子, 分母, 想 in ((4, 6, (2, 3)), (0, 5, (0, 1)), (-4, 6, (-2, 3)),
                          (7, 7, (1, 1)), (-4, -6, (2, 3)), (5, 0, None)):
        try:
            得 = f(分子, 分母)
        except Exception as e:                                  # noqa: BLE001
            return False, f'约分({分子}, {分母}) 出错：{type(e).__name__}: {e}'
        if 得 != 想:
            return False, (f'约分({分子}, {分母}) 应当是 {想}，得到 {得!r}。\n'
                           f'      ⚠ 分母统一保持正数（-4/-6 要变成 (2, 3)）；'
                           f'分母 0 返回 None；返回的要是**元组**。')
    return True, '六组都对（含 0、负数、分子分母都负、分母为 0）'


def CHECK_用了辗转相除(答案):
    import io
    if not hasattr(答案, '__file__'):
        return False, '找不到你的答题文件。'
    源码 = io.open(答案.__file__, encoding='utf-8').read()
    i = 源码.find('def 最大公约数')
    if i < 0:
        return False, '找不到「最大公约数」这个函数。'
    段 = 源码[i:]
    j = 段.find('\ndef ', 1)                 # 只取这一个函数的函数体
    if j > 0:
        段 = 段[:j]
    if 'math.gcd' in 段 or 'gcd(' in 段 or 'fractions' in 段:
        return False, ('「最大公约数」里用了 math.gcd 之类的现成函数。\n'
                       '      ⚠ 这一课要的就是**你自己写**辗转相除，把它删掉。')
    # 试除法的特征：需要一个一个试候选数（range / 自增自减）；辗转相除不需要
    像试除法 = ('range(' in 段 or '-= 1' in 段 or '+= 1' in 段
                or '- 1' in 段 or '+ 1' in 段)
    if '%' not in 段 or 像试除法:
        return False, ('「最大公约数」看起来不是辗转相除。\n'
                       '      ⚠ 从 min(甲, 乙) 往下一个个试也能得到正确答案，但那要 '
                       'max(甲, 乙) 次除法：\n'
                       '        最大公约数(999983, 1000003) 这两个数互质，试除法要跑 **100 万次**。\n'
                       '        辗转相除的核心只有一句：`甲, 乙 = 乙, 甲 % 乙`。')
    return True, '用的是辗转相除（有取余的辗转，也没偷用 math.gcd）'
