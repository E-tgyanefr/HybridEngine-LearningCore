# ─────────────────────────────────────────────────────
#  先介绍：从「约分」说起
# ─────────────────────────────────────────────────────
# 4/6 要约成 2/3，上下同时除以 2 —— 那个 2 就是 4 和 6 的**最大公约数**。
# 找它最省事的办法，是两千三百年前欧几里得写下的**辗转相除**：
# 把 `甲 % 乙` 的余数当下一个 乙，一直除到余数为 0。
#
# 试除法也能对，但最大公约数(999983, 1000003) 互质，要试 **100 万次**；辗转相除只要 **十几步**。
#
# ─────────────────────────────────────────────────────
#  一、算法本体：四行
# ─────────────────────────────────────────────────────
#     def 最大公约数(甲, 乙):
#         甲, 乙 = abs(甲), abs(乙)        ← 负数先取绝对值
#         while 乙:
#             甲, 乙 = 乙, 甲 % 乙          ← 这就是「辗转」
#         return 甲
#
# 走一遍 `最大公约数(12, 18)`：(12,18) → (18, 12) → (12, 6) → (6, 0)，返回 6。
# 再走一遍 `最大公约数(1071, 462)`：1071 % 462 = 147 → 462 % 147 = 21 → 147 % 21 = 0 ⇒ **21**。
# `甲, 乙 = 乙, 甲 % 乙` 靠的是**右边先整个算完再赋值**，不用借第三个变量。
#
# ─────────────────────────────────────────────────────
#  二、为什么它对
# ─────────────────────────────────────────────────────
# 关键在一句：**甲 和 乙 的公约数，与 乙 和 甲 % 乙 的公约数，是同一批。**
# 因为 甲 = 商 × 乙 + 余数：能整除 甲 和 乙 的数一定整除 余数；反过来，
# 能整除 乙 和 余数 的数一定整除 甲。两边互相包含 ⇒ 公约数集合一步都没变。
# 最后 乙 = 0 时公约数只剩 甲 自己，那它就是最大公约数。
#
# ─────────────────────────────────────────────────────
#  三、要几步
# ─────────────────────────────────────────────────────
# 每两次辗转数字至少减半（最坏情况是斐波那契数列给出的），步数约 **5 × 十进制位数**：
# 12 位以内的数几十步，10¹⁸ 也只要 87 步左右；试除法最坏要 min(甲, 乙) 次。
#
# ─────────────────────────────────────────────────────
#  四、最小公倍数与约分
# ─────────────────────────────────────────────────────
#     最小公倍数(甲, 乙) = 甲 × 乙 ÷ 最大公约数(甲, 乙)
#     最小公倍数(4, 6) = 4 × 6 ÷ 2 = 12        最小公倍数(21, 6) = 126 ÷ 3 = 42
#
# ⚠ 要写成 `甲 // 最大公约数(甲, 乙) * 乙`（**先除后乘**）：先乘中间结果白白变大
#   （Python 大整数不会溢出，但 C++ 的 int 会）。约分就是上下都除以最大公约数，
#   再把负号统一挪到分子：
#     约分(4, 6) ⇒ (2, 3)      约分(7, 7) ⇒ (1, 1)      约分(-4, -6) ⇒ (2, 3)
#
# ─────────────────────────────────────────────────────
#  ⚠ 这一课唯一要记住的坑：最大公约数(0, 0) 与 除数为 0
# ─────────────────────────────────────────────────────
#     def 最大公约数(甲, 乙):          # ← 错的版本
#         while 甲 % 乙 != 0:
#             甲, 乙 = 乙, 甲 % 乙
#         return 乙
#
#     最大公约数(5, 0)  ⇒  ZeroDivisionError: integer modulo by zero
#
# 为什么：`5 % 0` 在第一次判断时就执行了。写成 `while 乙:` 就不会 ——
#   乙 = 0 直接不进循环，返回 甲，`最大公约数(5, 0)` 得到 5（对）。
#
# ⇒ 两条约定，检查就按这两条考：
#     ① 最大公约数(甲, 0) = 最大公约数(0, 甲) = 甲；最大公约数(0, 0) = 0
#     ② 负数一律按绝对值算（-12 和 18 的最大公约数是 6，不是 -6）
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   这一课只讲 gcd / lcm / 约分。扩展欧几里得、同余方程都不碰。
#
