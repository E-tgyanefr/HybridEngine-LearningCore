# 第 03 课：数字与算术 —— 让程序算起来

# ─────────────────────────────────────────────────────
#  先介绍：两种数字
# ─────────────────────────────────────────────────────
#
#     int     整数        18      0      -5      1000000
#     float   小数        3.14    0.5    -2.75    1.0
#
# 写的时候**带小数点就是 float，不带就是 int**：
#
#     a = 18        int
#     b = 18.0      float
#
# ─────────────────────────────────────────────────────
#  五个运算符
# ─────────────────────────────────────────────────────
#
#     +    加       7 + 2  ⇒  9
#     -    减       7 - 2  ⇒  5
#     *    乘       7 * 2  ⇒  14
#     /    除       7 / 2  ⇒  3.5      ← ⚠ 一定有小数
#     //   整除     7 // 2 ⇒  3        ← ⚠ 丢掉小数
#     %    取余     7 % 2  ⇒  1        ← 剩下多少
#     **   乘方     2 ** 10 ⇒ 1024
#
# ─────────────────────────────────────────────────────
#  ⚠⚠ 这一课唯一要记住的坑：`/` 和 `//` 不一样
# ─────────────────────────────────────────────────────
#
#     10 / 4    ⇒  2.5      ← 一个斜杠：老老实实除
#     10 // 4   ⇒  2        ← 两个斜杠：只留整数部分（**不做四舍五入**）
#
#   为什么容易错：`//` 看起来很像是"注释"或者"手滑多打了一个"，
#   于是你以为写的是除法 —— 结果小数没了，而程序**不报错**。
#
#   ⇒ 算钱、算平均分、算比例时，**必须用 `/`**。
#     一个丢掉小数的结果不会报错，只会算错 —— 那是最难查的一类 bug。
#
# ─────────────────────────────────────────────────────
#  ⚠ 文字和数字不能相加
# ─────────────────────────────────────────────────────
#
#     "18" + 1      ❌ TypeError: can only concatenate str (not "int") to str
#     18 + 1        ✅ 19
#     int("18") + 1 ✅ 20        ← int() 把文字转成整数
#
#   ⇒ 报 `TypeError` 且提到 `str` 和 `int` 时，就是这个问题。
#     （输入进来的东西**永远是文字**，要算就得先 int() —— 第 14 课会讲怎么安全地转。）
#
# ─────────────────────────────────────────────────────
#  这一课只讲这一件事
# ─────────────────────────────────────────────────────
#   怎么把算出来的结果显示出来，用 print —— 那是第 02 课。
#
# ─────────────────────────────────────────────────────
#  轮到你了 —— 在答题文件里写这几件事
# ─────────────────────────────────────────────────────
#   1. 定义变量 苹果数 = 7、梨数 = 2
#   2. 定义变量 总个数，值是 苹果数 + 梨数
#   3. 定义变量 平均，值是 总个数 / 2        ← ⚠ 一个斜杠
#
# ─────────────────────────────────────────────────────
#  怎么自己测
# ─────────────────────────────────────────────────────
#     python -m hybridengine_light 检查 03


def CHECK_两个数量(答案):
    for 名, 值 in (("苹果数", 7), ("梨数", 2)):
        if not hasattr(答案, 名):
            return False, f"还没有定义「{名}」。写法：{名} = {值}"
        v = getattr(答案, 名)
        if isinstance(v, bool) or not isinstance(v, int):
            return False, (f"「{名}」应当是整数 {值}，现在是 {type(v).__name__}：{v!r}\n"
                           f"      ⚠ 加了引号就成文字了。")
        if v != 值:
            return False, f"「{名}」应当是 {值}，现在是 {v}。"
    return True, "苹果数 = 7、梨数 = 2"


def CHECK_总个数(答案):
    if not hasattr(答案, "总个数"):
        return False, "还没有定义「总个数」。写法：总个数 = 苹果数 + 梨数"
    if not (hasattr(答案, "苹果数") and hasattr(答案, "梨数")):
        return False, "需要先有「苹果数」和「梨数」两个变量。"
    v = 答案.总个数
    if v != 9:
        return False, (f"「总个数」应当是 9（7 + 2），现在是 {v!r}。\n"
                       f"      ⚠ 要写成 `苹果数 + 梨数`，用两个**变量**相加。")
    # ⚠⚠ 「是不是真的用变量算的」只能**看源码** —— 不能改变量试。
    #
    #   我第一版想的是"把 苹果数 改成 100，看 总个数 跟不跟着变"。
    #   **那个办法是错的**：`总个数 = 苹果数 + 梨数` 在模块导入时就
    #   算完了，之后改 苹果数 当然不会让已经定下的 9 变。
    #   （第 01 课那个"改变量看结果跟不跟着变"能成立，是因为那里
    #     测的是一个**函数** `打招呼()` —— 函数每次调用才重算。）
    #
    #   ⇒ 模块级变量只能用源码判据。它弱一些（改个名字绕过），
    #     但这是这一课能做到的、**不会冤枉人**的判法。
    import io as _io
    源码 = _io.open(答案.__file__, encoding="utf-8").read()
    行 = [l for l in 源码.split("\n")
          if l.strip().startswith("总个数") and "=" in l]
    if not 行:
        return False, "没找到 `总个数 = ...` 这行赋值。"
    if "+" not in 行[0]:
        return False, (f"「总个数」是这样赋值的：\n        {行[0].strip()}\n"
                       "      ⚠ 里面没有加法 —— 要用 `苹果数 + 梨数` 算出来，\n"
                       "        而不是直接写一个数字。\n"
                       "        变量存在的意义就是「改一处，结果跟着变」。")
    if "苹果数" not in 行[0] or "梨数" not in 行[0]:
        return False, (f"「总个数」里没有用到两个变量：\n        {行[0].strip()}\n"
                       "      ⚠ 要写成 `总个数 = 苹果数 + 梨数`。")
    return True, "总个数 = 9，而且确实是用 苹果数 + 梨数 算出来的"


def CHECK_平均(答案):
    if not hasattr(答案, "平均"):
        return False, "还没有定义「平均」。写法：平均 = 总个数 / 2"
    v = 答案.平均
    if v == 4:
        return False, ("「平均」算出来是 4 —— **小数被丢掉了**。\n"
                       "      ⚠⚠ 你用的是两个斜杠 `//`（整除），要用**一个**斜杠 `/`。\n"
                       "         9 // 2  ⇒  4      丢掉小数\n"
                       "         9 /  2  ⇒  4.5    正确\n"
                       "      这个错误**不会报错**，只会算错 —— 所以特别要小心。")
    if abs(v - 4.5) > 1e-9:
        return False, f"「平均」应当是 4.5（9 / 2），现在是 {v!r}。"
    return True, f"平均 = {v}（一个斜杠，小数保住了）"
