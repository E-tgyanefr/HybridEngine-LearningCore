"""界面设计令牌（颜色 / 间距 / 圆角 / 字体）。

═══ 为什么单独一个模块 ═══

  「大改 UI」最容易变成**到处手写魔数** —— 这个控件 8px、那个 10px，
  这个色 #2b2d30、那个 #34363a。改一轮之后自己都说不清"标准是什么"，
  于是越改越乱。

  ⇒ 把决定集中到一处：**改一个值，整个界面跟着变**。
    而且它能被测试（见 `tests/test_ui_tokens.py`）——
    「所有前景/背景组合的对比度够不够」这种事，**机器能判**，
    不该靠肉眼。

═══ 配色怎么定的 ═══

  底子是 VS Code 的 Dark Modern 那一套（学员以后大概率会用它，
  界面风格一致不是坏事），但**强调色换掉了**：

    VS Code 的蓝是 #0078d4（偏暗、偏灰）
    → 这里用 #4d9dff：**更亮、更饱和**

  ⚠ 为什么：这个界面的强调色要承担"指出下一步该点哪"的职责，
    而它出现的背景是 #1e1f22（很暗）。#0078d4 在那个背景上对比度只有
    4.4:1，刚过 WCAG AA 的线；教学软件的用户里有大量视力一般的成年人，
    **不值得为"看起来像 VS Code"省这点对比度**。

⚠ 一条硬约束：**任何前景/背景组合的对比度都必须 >= 4.5:1**（WCAG AA 正文）。
  这条**有测试守着** —— 拍脑袋调色最容易在这里翻车。
"""
