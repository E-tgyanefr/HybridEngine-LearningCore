码 = "Consolas"

#: Tk 的字体参数要的是"族名 字号"这种串，或者元组。统一从这里取。
def 界面字体(号: int = 字_正文, 粗: bool = False):
    return (界, 号, "bold") if 粗 else (界, 号)


def 等宽字体(号: int = 字_正文, 粗: bool = False):
    return (码, 号, "bold") if 粗 else (码, 号)


# ── 对比度（给测试用）──────────────────────────────────────────────────
def 亮度(色: str) -> float:
    """WCAG 相对亮度。`色` 形如 `#rrggbb`。"""
    色 = 色.lstrip("#")
    r, g, b = (int(色[i:i + 2], 16) / 255.0 for i in (0, 2, 4))

    def 线(c: float) -> float:
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    return 0.2126 * 线(r) + 0.7152 * 线(g) + 0.0722 * 线(b)


def 对比度(前景: str, 背景: str) -> float:
    """WCAG 对比度，1.0 ~ 21.0。**正文要 >= 4.5**，大字要 >= 3.0。"""
    a, b = 亮度(前景), 亮度(背景)
    亮, 暗 = max(a, b), min(a, b)
    return (亮 + 0.05) / (暗 + 0.05)
