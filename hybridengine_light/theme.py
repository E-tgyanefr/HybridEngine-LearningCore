# ── 字体族 ────────────────────────────────────────────────────────────
#
# ⚠⚠ "Segoe UI" 原来被用作**全部**文字的字体 —— 但它对中文是**回退**的，
#    于是中英文混排时字重、基线、行高都不一致（中文那部分由雅黑代打）。
#    结果就是"看起来有点土"，而原因很难一眼看出来。
#
# ⇒ 界面文字用 **"Microsoft YaHei UI"**（Win10+ 自带，中英文都它管，
