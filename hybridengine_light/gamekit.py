def 模板(游戏名: str = "接方块") -> str:
    """返回一个**完整可玩**的游戏源码。

    设计原则：能跑、看得懂、有几处明确标着「改这里」。
    新手先改这些地方，每次改动都有即时反馈 —— 这比从零写有效得多。
    """
    return f'''"""我的游戏：{游戏名}

玩法：左右方向键移动底部的板子，接住掉下来的方块。
      接到一个得 1 分，漏掉一个少一条命。命用完就结束。

════ 先玩一遍 ════
    python games/{游戏名}.py

════ 然后试着改这些地方（每次改一处，改完运行看效果）════
    · 板子宽不宽、移动快不快          → 看「你可以改」①②
    · 方块掉得快不快                  → 看「你可以改」③
    · 有几条命                        → 看「你可以改」④
    · 颜色                            → 看「你可以改」⑤

════ 游戏的最小骨架 ════
    状态 → 画出来 → 等按键 → 改状态 → 回到第一步
    下面每一步都标了注释，照着读一遍就懂了。
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from hybridengine_light import Stage
from hybridengine_light.gamekit import 碰撞, 夹住

# ══════════ 你可以改的地方 ══════════
板子宽 = 24          # ① 板子多宽（数字越大越好接）
板子速度 = 6         # ② 按一次方向键移动多少（越大越灵活）
方块速度 = 2         # ③ 方块每次掉多少（越大越难）
生命上限 = 3         # ④ 几条命
背景色 = "黑"        # ⑤ 换个颜色试试："白" "蓝" "紫"
板子色 = "青"
方块色 = "黄"
文字色 = "白"
# ════════════════════════════════════


def 主流程():
    舞台 = Stage(size=100, width=560, height=560, title="{游戏名}")
    舞台.background = 背景色
    舞台.hint("← → 移动，Esc 退出")

    # ── ① 状态：把游戏需要记住的东西都放在这里 ──
    板子x = 50                       # 板子的中心横坐标
    方块x = random.randint(10, 90)   # 方块的横坐标
    方块y = 100                      # 方块的纵坐标（从上面往下掉）
    分数 = 0
    生命 = 生命上限

    while True:
        # ── ② 画出来：先清空，再把当前状态画一遍 ──
        舞台.clear()
        舞台.box(板子x - 板子宽 / 2, 2, 板子宽, 4, 板子色)
        舞台.dot(方块x, 方块y, 5, 方块色)
        舞台.text(3, 94, f"分数 {{分数}}", 文字色, 14)
        舞台.text(75, 94, f"生命 {{生命}}", 文字色, 14)
        if 生命 <= 0:
            舞台.text(50, 50, "游戏结束", "红", 24)
            舞台.hint("游戏结束 —— 按空格再来，Esc 退出")
        舞台.show()

        # ── ③ 等按键 ──
        键 = 舞台.key()

        if 键 == "Escape":
            舞台.close()
            return

        if 生命 <= 0:
            if 键 == "空格":                 # 重开一局
                板子x, 方块x, 方块y = 50, random.randint(10, 90), 100
                分数, 生命 = 0, 生命上限
            continue

        # ── ④ 改状态 ──
        if 键 == "左":
            板子x = 夹住(板子x - 板子速度, 板子宽 / 2, 100 - 板子宽 / 2)
        elif 键 == "右":
            板子x = 夹住(板子x + 板子速度, 板子宽 / 2, 100 - 板子宽 / 2)

        方块y -= 方块速度

        # 碰撞：方块底部碰到板子顶部，而且横向也在板子范围内
        板子 = (板子x - 板子宽 / 2, 2, 板子宽, 4)
        方块 = (方块x - 5, 方块y - 5, 10, 10)
        if 碰撞(板子, 方块):
            分数 += 1
            方块x = random.randint(10, 90)
            方块y = 100
        elif 方块y < 0:                   # 掉到屏幕外面了
            生命 -= 1
            方块x = random.randint(10, 90)
            方块y = 100


if __name__ == "__main__":
    主流程()
'''
