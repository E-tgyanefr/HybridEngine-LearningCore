"""共用：把课程文件开头的 `#` 讲解块变成**教程式答题文件**。

════ 为什么要有这个模块 ════

作者的原话：「你这是教程吗，只有习题啊」。

起因是：学员 90% 的时间待在**答题文件**里，而最早那版模板只有三行说明
（「第 NN 课的答案 —— 在这里写你的代码」+ 两条命令），讲解全在「看课」命令里。
于是他写代码时**手边没有可对照的东西** —— 那是习题纸，不是教程。

Python 那条线（`run.py::_stub_for`）先改好了，做法是：
把课程文件开头那一整块 `#` 讲解原样搬进答题文件。
⇒「看课」与「答题文件」永远是**同一份内容**，不会"改了一处忘了另一处"。

这个模块把同一套做法给另外四条线共用：AI / 嵌入式 / 树莓派 / 引擎课程。

════ ⚠ 这四条线的课程文件结构和 Python 线**不一样** ════

    Python 线：  先介绍 → 轮到你了      ← 开头块本身就是"先讲后练"，照抄就行
    这四条线：   要做 → 讲解            ← 「要做」写在最前面，讲解在后面
                 （`ai/02_感知机.py` 就是这样，别照抄 Python 的假设）

⇒ 这里的做法是：整块搬过来，但**把「要做」那一段挪到末尾**，变成「轮到你了」。
   文件于是读成：标题 → 说明 → 讲解 → 轮到你了 → 怎么自己测 → 写代码的位置，
   既和 Python 线一致，也符合作者后来定的「先介绍、再布置任务」。

另外两个结构差异（Python 线没有）：

  · 开头块**末尾**还有一截「下面是检查用的代码，不用改」/「判分辅助」——
    那是给下面那些 `CHECK_` 代码做标题的，不是讲给学员听的 ⇒ 抄到那里就停。
  · 课程文件里写死了 `python -m hybridengine_light …`（开发时对，打包成 exe
    之后就错了 —— 学员机器上根本没有 `python` 命令）⇒ 统一换成 `命令名()`。
"""
from __future__ import annotations

from pathlib import Path

from ._paths import 命令名

__all__ = ["标题", "开头讲解块", "拆任务", "答题模板"]


横线 = "═" * 56

#: 讲解块里出现这些词，就说明"下面是判分用的代码"了 —— 不再往下抄
分界标记 = ("下面是检查用的代码", "判分辅助")

#: 「该你写了」那一小节的标题词（这四条线的课程文件里是 `# 要做：`）
任务标记 = ("要做", "轮到你了")


def 标题(p: Path) -> str:
    """课程文件第一行 `#` 注释 —— 也就是「第 NN 课：…」。"""
    try:
        text = p.read_text(encoding="utf-8")
    except OSError:
        return p.stem
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("#"):
            return s.lstrip("# ").strip()
    return p.stem


def _去注释(line: str) -> str:
    """`# 讲解` → ` 讲解`（只去掉一个 `#` 和紧随其后的一个空格，保住缩进）。"""
    body = line.rstrip()[1:]
    if body.startswith(" "):
        body = body[1:]
    return body


def _是横线(line: str) -> bool:
    """整行只有 `─` / `═` 这类分隔符（讲解里很常见）。"""
    s = line.strip()
    return bool(s) and set(s) <= set("─═-=—_ ")


def 开头讲解块(p: Path) -> list[str]:
    """课程文件开头那一整块 `#` 注释的正文（去掉注释符、去掉末尾的判分标题）。

    ⚠ 和 Python 线同一套规则：从第一行开始收，**中间的空白行照收**
      （讲解是分节的），碰到第一行真正的代码就停。
      这样「看课」和「答题文件」永远出自同一处。

    ⚠ 这四条线的额外两步：
      · 抄到「下面是检查用的代码 / 判分辅助」为止 —— 那是给下面代码做标题的。
      · 末尾剩下的空白行和 `───` 分隔线一起清掉。
    """
    try:
        src = p.read_text(encoding="utf-8").splitlines()
    except OSError:
        return []

    块: list[str] = []
    开始 = False
    for line in src:
        s = line.rstrip()
        if s.startswith("#"):
            开始 = True
            块.append(_去注释(line))
        elif 开始 and not s:
            块.append("")
        elif 开始:
            break

    for i, l in enumerate(块):
        if any(标记 in l for 标记 in 分界标记):
            块 = 块[:i]
            break

    while 块 and (not 块[-1].strip() or _是横线(块[-1])):
        块.pop()
    return 块


def _去首尾空行(行: list[str]) -> list[str]:
    a, b = 0, len(行)
    while a < b and not 行[a].strip():
        a += 1
    while b > a and not 行[b - 1].strip():
        b -= 1
    return 行[a:b]


def 拆任务(块: list[str]) -> tuple[list[str], list[str]]:
    """把开头块拆成 (`讲解`, `要做的条目`)。

    ⚠ 为什么要把「要做」挪到末尾：这四条线的课程文件是「先布置任务、再讲解」，
      而 Python 线是「先介绍、再布置任务」。学员打开答题文件应该先读到讲解，
      最后才是"该你写了" ⇒ 把那段挪到后面，其余原样保留。

    找不到「要做」就返回 (整块, []) —— 答题文件照样能用，只是末尾少一段。
    """
    for i, line in enumerate(块):
        s = line.strip()
        # ⚠ 只认**标题行**（`要做：` 这种短行）；
        #   正文里偶尔出现"这一课要做什么"之类的句子，不能当成分节。
        if any(s.startswith(标记) for 标记 in 任务标记) and len(s) <= 12:
            尾巴 = 块[i:]
            j = 0
            while j < len(尾巴) and 尾巴[j].strip():
                j += 1
            return _去首尾空行(块[:i] + 尾巴[j:]), _去首尾空行(尾巴[:j])
    return _去首尾空行(块), []


def 答题模板(课: Path, *, 命令: str, 提示: str = "", 末尾代码: str = "") -> str:
    """给这一课生成答题文件 —— **它本身就是一篇教程**。

    参数：
      `命令`     这一条线的子命令，例如 "AI" / "嵌入式" / "引擎课程"
      `提示`     这一课特有的那句话（放进最上面的说明框）
      `末尾代码` 文档字符串之后要预置的 import（引擎线需要）
    """
    编号 = 课.stem[:2]
    题 = 标题(课)
    讲解, 任务 = 拆任务(开头讲解块(课))

    # ⚠ 课程文件第一行就是标题，与文档字符串第一行重复 ⇒ 去掉
    if 讲解 and 讲解[0].strip() == 题:
        讲解 = _去首尾空行(讲解[1:])

    行 = [
        # ⚠ 用 `r"""`：讲解里有 `"\n"` 这种**字面写法**（实测 raspi/03 的「要做」里有），
        #   普通字符串会被解释成真的换行，学员看到的讲义就变形了。
        f'r"""{题}',
        "",
        横线,
        f"  这是第 {编号} 课的**答题文件**，也是一篇教程 —— 先读一遍，再往下写。",
        "",
        f"  下面这段讲解直接来自课程文件 {课.name} 的开头，",
        f"  和 `{命令名()} {命令} {编号}` 看到的是**同一份内容** ——",
        "  所以不会出现「课程改了、答题文件里还是旧的」这种事。",
    ]
    if 提示:
        行 += [""] + ["  " + l.rstrip() for l in 提示.strip().splitlines()]
    行 += [横线, ""]
    行 += 讲解
    行 += [
        "",
        横线,
        "  轮到你了 —— 就在**这个文件**里写",
        横线,
        "",
    ]
    行 += 任务 or ["  （课程文件里没写「要做」—— 用上面的命令看一遍讲义再动手）"]
    行 += [
        "",
        横线,
        "  怎么自己测",
        横线,
        f"    再看一遍讲解：  {命令名()} {命令} {编号}",
        f"    写完自己检查：  {命令名()} {命令} 检查 {编号}",
        f"    卡住了：        {命令名()} {命令} 答案 {编号}   （先自己写一遍再看）",
        "",
        "  现在开始写 —— 就在下面空出来的地方。",
        '"""',
        "",
    ]
    if 末尾代码:
        行 += [末尾代码.rstrip("\n"), "", ""]
    行 += [
        "",
        "# ↓" + "─" * 50,
        "#    在下面写你的代码",
        "#    （写错了不要紧 —— 跑一次「检查」就知道哪里不对）",
        "# ↓" + "─" * 50,
        "",
    ]
    # ⚠ 课程文件里的用法提示写死的是 `python -m hybridengine_light`：
    #   开发时对，打包成 exe 之后就错了（学员机器上可能根本没有 python）。
    #   `命令名()` 是这件事唯一的真值，这里统一换掉。
    return "\n".join(行).replace("python -m hybridengine_light", 命令名())
