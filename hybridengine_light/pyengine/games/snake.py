"""贪吃蛇 —— **只用 Python 引擎的组件拼出来的完整游戏**。

## 这个文件想证明什么

它**不是**一堆画图调用，而是一份"模块化"的示范：

    场地   = 场景对象 + `网格背景` 组件（静态装饰）
    蛇头   = 场景对象 + `网格移动` 组件 + `圆点` 组件
    蛇身   = 若干跟随节（各自一个 `蛇身节` 组件）   ← 自定义组件
    食物   = 场景对象 + `圆点` 组件
    分数   = `分数` 组件
    相机   = 场景服务（不跟随 —— 整场演出都在画面里）

**加一个功能 = 挂一个组件**。这里面没有一处"在别处插一个 if"。

## 怎么跑

    python -m hybridengine_light 引擎 贪吃蛇
"""
from __future__ import annotations

import math
import random

# ⚠ 本文件在 pyengine/games/ 里 ⇒ 上一级就是 pyengine 包本身。
