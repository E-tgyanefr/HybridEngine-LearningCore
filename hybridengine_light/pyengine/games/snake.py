from .. import 组件, 场景, 场景对象, 向量, 游戏
from .. import components as C

格 = 4.0          # 一格多大（世界单位）
列数 = 25         # 25 x 25 格
场地 = 列数 * 格


# ====================== 自定义组件 ======================

class 轨迹:
    """蛇头走过的点（所有蛇身节共享）。

    ⚠ 为什么用"共享一条轨迹"而不是"每节各自记历史"：
      各自记的话，每节的历史里混着**它自己**的旧位置，
      抖动会一层层放大（实测第 3 节就开始跳）。
      共享头部轨迹 + 每节取不同距离 ⇒ 蛇身自然整齐，
      而且**越靠后的节取越早的点**，正是蛇该有的样子。
    """

    def __init__(self, 上限: int = 4000) -> None:
        self.点: list[tuple[float, float]] = []
        self.上限 = 上限

    def 记(self, x: float, y: float) -> None:
        # 只在真的移动了才记（站着不动不该把轨迹填满同一个点）
        if self.点 and abs(self.点[-1][0] - x) < 1e-9 and abs(self.点[-1][1] - y) < 1e-9:
            return
        self.点.append((x, y))
        if len(self.点) > self.上限:
            del self.点[: len(self.点) - self.上限]

    def 回看(self, 距离: float) -> tuple[float, float]:
        """从最新往回走 `距离`（世界单位）后落在哪。"""
        if not self.点:
            return (0.0, 0.0)
        剩 = 距离
        for i in range(len(self.点) - 1, 0, -1):
            a, b = self.点[i], self.点[i - 1]
            d = math.hypot(b[0] - a[0], b[1] - a[1])
            if d <= 1e-12:
                continue
            if 剩 <= d:
                t = 剩 / d
                return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t)
            剩 -= d
        return self.点[0]


class 蛇身节(组件):
    """跟在头部轨迹上的第 `名次` 节。**这是"自己写组件"最短的例子。**"""

    def __init__(self, 轨迹_: 轨迹, 名次: int, 间距: float = 格) -> None:
        self.轨迹_ = 轨迹_
        self.名次 = 名次
        self.间距 = 间距

    def 每帧(self, dt: float) -> None:
        x, y = self.轨迹_.回看(self.名次 * self.间距)
        self.宿主.变换.位置 = 向量(x, y)


class 网格移动(组件):
    """按格子走，并记录朝向。

    ⚠ 为什么不用 `按键驱动`：贪吃蛇要**按格**走，不是连续滑。
      连续滑的话"吃到没吃到"很难判，而且转向会卡在半格上。
    """

    def __init__(self, 输入, 轨迹_: 轨迹, 速度格每秒: float = 7.0) -> None:
        self.输入 = 输入
        self.轨迹_ = 轨迹_
        self.间隔 = 1.0 / max(0.1, 速度格每秒)
        self.累计 = 0.0
        self.朝向 = (1.0, 0.0)
        #: 下一格要去的方向。按键先记下、**走到格子上才生效** ——
        #  否则一帧内连按两次会把自己转 180 度（立刻撞自己）。
        self.待转: tuple[float, float] | None = None

    def 每帧(self, dt: float) -> None:
        if self.输入 is not None:
            for 键, 方向 in (("w", (0.0, 1.0)), ("up", (0.0, 1.0)),
                            ("s", (0.0, -1.0)), ("down", (0.0, -1.0)),
                            ("a", (-1.0, 0.0)), ("left", (-1.0, 0.0)),
                            ("d", (1.0, 0.0)), ("right", (1.0, 0.0))):
                if self.输入.刚按下(键):
                    # 不许 180 度掉头
                    if not (方向[0] == -self.朝向[0] and 方向[1] == -self.朝向[1]):
                        self.待转 = 方向
                    break
        self.累计 += dt
        动了 = False
        while self.累计 >= self.间隔:
            self.累计 -= self.间隔
            if self.待转 is not None:
                self.朝向 = self.待转
                self.待转 = None
            t = self.宿主.变换
            t.位置 = 向量(t.位置.x + self.朝向[0] * 格,
                          t.位置.y + self.朝向[1] * 格)
            半 = 场地 / 2
            x, y = t.位置.x, t.位置.y
            # 穿墙：从一边出去、另一边回来
            if x < -半 + 格 / 2:
                x += 场地
            elif x > 半 - 格 / 2:
                x -= 场地
            if y < -半 + 格 / 2:
                y += 场地
            elif y > 半 - 格 / 2:
                y -= 场地
            t.位置 = 向量(x, y)
            动了 = True
        if 动了:
            p = self.宿主.变换.位置
            self.轨迹_.记(p.x, p.y)


class 吃食物(组件):
    """蛇头碰到食物 ⇒ 加分、加长、把食物换个位置。"""

    def __init__(self, 食物: 场景对象, 分数: C.分数, 随机源: random.Random,
                 回调=None) -> None:
        self.食物 = 食物
        self.分数组件 = 分数
        self.随机源 = 随机源
        self.回调 = 回调
        self.吃到 = 0

    def 每帧(self, dt: float) -> None:
        头 = self.宿主.世界位置
        食 = self.食物.世界位置
        if math.hypot(头.x - 食.x, 头.y - 食.y) > 格 * 0.7:
            return
        self.吃到 += 1
        self.分数组件.加(10)
        # 确定性：同一次吃到给同一个位置（不用全局 random，免得测试不可复现）
        self.随机源.seed(self.吃到 * 7919)
        self.食物.变换.位置 = 向量(
            (self.随机源.randrange(列数) - 列数 // 2) * 格,
            (self.随机源.randrange(列数) - 列数 // 2) * 格)
        if self.回调 is not None:
            self.回调(self.吃到)


class 网格背景(组件):
    """把场地网格画出来（浅灰细线）。静态装饰，挂一次就不用管。"""

    def 绘制(self, 画笔) -> None:
        半 = 场地 / 2
        左, 底, 右, 上 = -半, -半, 半, 半
        for i in range(列数 + 1):
            x = 左 + i * 格
            y = 底 + i * 格
            画笔.线(x, 底, x, 上, "灰", 0.12)
            画笔.线(左, y, 右, y, "灰", 0.12)
        for a, b, c, d in ((左, 底, 右, 底), (左, 上, 右, 上),
                           (左, 底, 左, 上), (右, 底, 右, 上)):
            画笔.线(a, b, c, d, "白", 0.35)


# ====================== 组装 ======================

def 造游戏(宽: int = 640, 高: int = 640, 后端=None, 种子: int = 12345,
           速度: float = 7.0) -> 游戏:
    """把贪吃蛇**装配**出来。返回的 `游戏` 可以直接 `.跑()` 或 `.一步()`。"""
    s = 场景("贪吃蛇")
    g = 游戏(场景=s, 宽=宽, 高=高, 尺寸=场地, 标题="贪吃蛇 —— Python 引擎",
             后端=后端, 背景="黑")
    s.设服务("输入", g.输入)
    # 相机对准场地中心，不跟随 —— 整场演出都在画面里
    g.相机.x = g.相机.y = 0.0

    s.造("场地").加(网格背景())

    HUD = s.造("HUD", 0, 0)
    分 = C.分数(初值=0, 颜色="白")
    分.显示x, 分.显示y = -场地 / 2 + 2, 场地 / 2 - 6
    HUD.加(分)

    轨迹_ = 轨迹()
    轨迹_.记(0, 0)
    蛇头 = s.造("蛇头", 0, 0)
    蛇头.加(网格移动(g.输入, 轨迹_, 速度格每秒=速度),
            C.圆点(半径=格 * 0.45, 颜色="绿"))

    for i in range(1, 4):
        节 = s.造(f"蛇身{i}", -格 * i, 0)
        节.加(C.圆点(半径=格 * 0.38, 颜色="青"), 蛇身节(轨迹_, i))

    食物 = s.造("食物", 格 * 6, 格 * 4)
    食物.加(C.圆点(半径=格 * 0.4, 颜色="红"))
    源 = random.Random(种子)

    def 吃到了(第几次: int) -> None:
        # ⚠ 这是"运行时给场景加东西"，而它正好在每帧遍历里 ⇒ 走 `延后加根`
        新 = 场景对象(f"蛇身{第几次 + 3}", -格, 0)
        新.加(C.圆点(半径=格 * 0.38, 颜色="青"),
               蛇身节(轨迹_, 第几次 + 3))
        s.延后加根(新)

    蛇头.加(吃食物(食物, 分, 源, 回调=吃到了))

    # 演示"原生组件"：给相机设世界边界
    s.造("世界边界").加(C.世界边界(-场地 / 2, -场地 / 2, 场地 / 2, 场地 / 2))
    return g


def 主(后端=None, 帧数: int = 0) -> int:
    g = 造游戏(后端=后端)
    if 后端 is not None or 帧数:
        return g.跑(帧数=帧数 or 60)
    print("\n  贪吃蛇 —— 用 WASD 或方向键控制，吃红点加分。\n")
    g.跑()
    return 0
