# ══════════════════════ C++ 内核切换（唯一的切换点）══════════════════════
# 上面每一行 Python 实现都**原样留着**，是**回退**：
#   · 内核在  ⇒ 把 `向量` / `变换` 换成 C++ 实现（`pyengine_c`，逐位对账过）
#   · 内核不在 ⇒ 这里什么都不做，行为与从前**逐位相同**
#
# ⚠ 为什么非要在这里切换：判据的导入是
#       from hybridengine_light import pyengine as E
#   ⇒ 想换实现，只能在**这个模块**里换。别处换了判据看不见。
#
# ⚠ 为什么"不在就退回"是必需的：手机版跑在 Chaquopy 里，
#   而 `.so` 的交叉编译是另一个大工程 ⇒ **这一阶段不能把安卓弄坏**。
#   内核不在是**正常情况**，不是错误 —— 所以这里不报错、不打印。
#
# ⚠ 为什么用 try/except 包住整个切换（而不是只包 import）：
#   `安装()` 会去改几个子模块的属性，任何一步出岔子都必须退回 Python 版，
#   而不是让"引擎能不能用"取决于加载顺序。宁可退回，不可半换。
try:                                    # pragma: no cover - 取决于内核在不在
    from .. import pyengine_c as _内核心

    _内核心.安装()
except Exception:                       # noqa: BLE001 - 退回是**设计**，不是兜底
    pass
