"""pyengine —— **用 Python 写的游戏引擎**，架构与专业版（HybridEngine）对一个形状。

## 它是什么

专业版是 C++23 内核 + 三语言绑定；这里是**同样架构的 Python 版**：

    场景图（父子变换）    →  `scene.场景` / `scene.场景对象` / `scene.变换`
    组件体系（可插拔）    →  `scene.组件` + `components.*`（原生零件）
    游戏循环（固定步长）  →  `engine.游戏`
    输入 / 相机           →  `engine.输入` / `engine.相机2D`
    渲染后端可换          →  `render.后端`（tkinter / 真引擎 / 无头录制）

## ⚠ 它**不是**什么（别误会）

  · **不是性能版**：C++ 内核 vs Python，差着量级。要性能就用专业版。
  · **不是三语言绑定**：这里只有 Python。那本来就是 Python 版的意义。
  · 3D 还没做（专业版有 `MeshVisual` / `CameraComponent`）。

## 为什么"模块化编程"是这套东西的真正目的

学员写的 Python 一长就乱 —— 变量到处飞、想加个功能要改十处。
**模块化不是"把函数拆小"，而是「把会变的东西装进可插拔的块里」。**

    玩家 = 场景.造("玩家", 50, 50)
    玩家.加(圆点(颜色="红"), 按键驱动(速度=40), 跟随相机(平滑=0.15), 分数())

"给玩家加个跟随相机"不是改玩家的代码，而是**挂一个组件**。
学员学到的第一件事就是这件事。

## 最小可用例子

    from hybridengine_light import pyengine as E
    from hybridengine_light.pyengine import components as C

    游戏 = E.游戏(标题="我的第一个游戏")
    玩家 = 游戏.场景.造("玩家", 50, 50)
    玩家.加(C.圆点(颜色="红"), C.按键驱动(速度=40), C.跟随相机())
    游戏.场景.设服务("输入", 游戏.输入)
    游戏.跑()

## 无头也能跑（判据靠这个）

`游戏(后端=录制后端())` ⇒ 不开窗口，绘制指令记进列表。
于是场景/组件/相机/输入的正确性**全都能写成判据**。
"""
