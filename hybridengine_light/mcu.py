"""mcu —— 单片机模拟器（不需要真板子也能学、也能自动检查）。

════ 先说清楚：模拟器能保证什么、保证不了什么 ════

    ✅ 能保证：**程序逻辑**对
       「按下按钮 → LED 亮 → 松开 → 灭」这个流程，模拟器能验证。
       引脚编号写错、忘了初始化、状态机少一个分支 —— 这些都能抓出来。

    ❌ 保证不了：**电路**对
       忘了接限流电阻、LED 正负极接反、引脚接错位置、
       电压不对、杜邦线没插紧 —— 模拟器一个都发现不了。
       更糟的是：**代码检查通过了，插上板子不亮**，学生会去怀疑代码。

════ 所以这个模拟器有一条**必须说清楚**的设计原则 ════

它在每个成功结果后面都提醒学生「这只验证了逻辑」。
不做成"检查通过就万事大吉"的样子 —— 那会害人。

════ 为什么不去装真工具链 ════

因为装不上也不该装：
  · avr-gcc / arduino-cli / qemu 都不在本机（实测过）
  · 让教程依赖这些东西，等于把"装环境"这道墙重新立起来 ——
    而轻量版的整个出发点就是**拆掉这道墙**

所以：用一个**真实感足够**的模拟器讲原理，
学生真的拿到板子时，代码几乎不用改（`模拟器` → `真实引脚` 只是换个对象）。

════ 模拟的是什么 ════

  · GPIO 引脚（输入/输出、拉高拉低、上下拉电阻）
  · 一个 LED（跟着引脚亮灭）
  · 一个按钮（能按下、能松开）
  · 一个"时间"（用于闪烁、去抖、超时）
  · 串口打印（print 出来的东西）
"""

from __future__ import annotations

__all__ = ["模拟器", "引脚编号错误", "短路错误"]


class 引脚编号错误(Exception):
    """用了不存在的引脚号。

    ⚠ 这个错误在真实硬件上**不会有提示** —— 写错了引脚号，
    板子只是"什么反应都没有"。所以模拟器特意做成报错，
    让学生知道"引脚号本身"就是一个必须查清楚的东西。
    """


class 短路错误(Exception):
    """把两个输出引脚接在一起了。

    真实硬件上这会**烧掉引脚**（或者整块板子）。
    模拟器在这里报错，是在替学生的钱包挡一刀。
    """


class _引脚:
    __slots__ = ("号", "模式", "高", "上下拉", "接的引脚")

    def __init__(self, 号: int):
        self.号 = 号
        self.模式 = "输入"          # 输入 / 输出
        self.高 = False             # 输出电平时是不是高
        self.上下拉 = None          # None / "上拉" / "下拉"
        self.接的引脚 = None        # 模拟"把两根线接在一起"


class 模拟器:
    """一块虚拟的单片机板子。

    用法（和真实的几乎一样）::

        from hybridengine_light.mcu import 模拟器

        板子 = 模拟器(引脚数=8)
        led = 板子.输出引脚(2, 名字="LED")
        btn = 板子.输入引脚(3, 名字="按钮")

        led.高()                      # 点亮
        print(led.状态())             # "亮"
        板子.按下(btn)
        print(板子.读到(btn))          # True
        板子.时间推进(1.0)            # 时间过了 1 秒
        板子.报告()                   # 看这一轮都发生了什么
    """

    def __init__(self, 引脚数: int = 20, 名字: str = "模拟板"):
        if 引脚数 < 2:
            raise ValueError("引脚数至少要 2 个")
        self.名字 = 名字
        self.引脚数 = 引脚数
        self._引脚: list[_引脚] = [_引脚(i) for i in range(引脚数)]
        self.时间 = 0.0
        self.日志: list[str] = []
        self.上限警告 = []          # 收集"逻辑对但硬件可能出问题"的提醒

    # ══════════════════ 引脚 ══════════════════

    def _取(self, 号: int) -> _引脚:
        if not isinstance(号, int):
            raise 引脚编号错误(f"引脚号应该是整数，你给的是 {type(号).__name__}")
        if not (0 <= 号 < self.引脚数):
            raise 引脚编号错误(
                f"引脚 {号} 不存在（这块板子只有 0~{self.引脚数 - 1}）。\n"
                f"      ⚠ 真实硬件上写错引脚号**不会报错**，板子只是毫无反应 ——\n"
                f"        所以这个报错是在帮你省时间：先确认引脚号再写代码。")
        return self._引脚[号]

    def 输出引脚(self, 号: int, 名字: str = "", 初始: str = "低"):
        """把一个引脚设成输出（用来点亮 LED、驱动蜂鸣器等）。"""
        p = self._取(号)
        p.模式 = "输出"
        p.高 = (初始 == "高")
        self.日志.append(f"[{self.时间:6.2f}s] 引脚 {号}{'(' + 名字 + ')' if 名字 else ''} "
                         f"设为输出，初始{'高' if p.高 else '低'}")
        return _输出引脚(self, p, 名字)

    def 输入引脚(self, 号: int, 名字: str = "", 上下拉: str | None = None):
        """把一个引脚设成输入（用来读按钮、传感器等）。

        `上下拉` 很重要：真实电路里如果什么都不接，引脚读到的是**随机值**
        （叫"悬空"）。上拉或下拉给它一个确定的默认电平。
        """
        p = self._取(号)
        p.模式 = "输入"
        p.上下拉 = 上下拉
        self.日志.append(f"[{self.时间:6.2f}s] 引脚 {号}{'(' + 名字 + ')' if 名字 else ''} "
                         f"设为输入{('，' + 上下拉) if 上下拉 else ''}")
        if 上下拉 is None:
            self.上限警告.append(
                f"引脚 {号} 设成了输入但没设上下拉 —— 真实电路里这叫「悬空」，"
                f"读到的值是不确定的。\n"
                f"      改法：输入引脚(号, 上下拉=\"上拉\")（按钮接地的接法）")
        return _输入引脚(self, p, 名字)

    def 接到一起(self, 甲, 乙):
        """把两个引脚"用一根线连起来"。

        ⚠ 如果两边都是**输出**，而且一个高一个低 —— 那就是短路。
        真实硬件上会烧引脚。模拟器在这里报错。
        """
        a, b = self._取(甲.号), self._取(乙.号)
        if a.模式 == "输出" and b.模式 == "输出" and a.高 != b.高:
            raise 短路错误(
                f"引脚 {a.号}（高）和引脚 {b.号}（低）都是输出、电平还相反 —— "
                f"这就是短路。\n"
                f"      ⚠ 真实硬件上这会烧掉引脚，甚至烧掉整块板子。\n"
                f"      排查方向：是不是把一个引脚既当输入又当输出用了？"
                f"或者两个输出引脚之间忘了加电阻？")
        a.接的引脚, b.接的引脚 = b, a
        self.日志.append(f"[{self.时间:6.2f}s] 引脚 {a.号} 和 {b.号} 接到了一起")
        return self

    # ══════════════════ 按钮 ══════════════════

    def 按下(self, 引脚):
        """模拟"把按钮按下去"（把输入引脚拉到低电平，因为按钮通常接地）。"""
        return self._设输入(引脚, True)

    def 松开(self, 引脚):
        return self._设输入(引脚, False)

    def _设输入(self, 引脚, 按下: bool):
        p = self._取(引脚.号)
        if p.模式 != "输入":
            raise ValueError(f"引脚 {p.号} 不是输入模式，不能被按下")
        # ⚠ 这里定的是**模拟器自己的语义**，不是电压。
        #
        #   真实电路里：上拉的按钮按下时引脚是**低**电平（因为接地），
        #   下拉的按钮按下时是**高**电平 —— 两种接法相反。
        #
        #   但对教学模拟器来说，那个反转只会制造困惑：
        #   学生按下按钮，期待读到"按下了"，却读到 False。
        #   我第一版就是照搬电压语义，结果"没按"和"按下"都返回 False。
        #
        #   所以这里**统一成：按下 = 读到 True**。
        #   想讲电平反转的话，在课程里单独讲，不要让每个练习都背上这个包袱。
        p.高 = 按下
        self.日志.append(f"[{self.时间:6.2f}s] {'按下' if 按下 else '松开'} "
                         f"{引脚.名字 or ('引脚' + str(p.号))} → "
                         f"读到 {p.高}")
        return self

    def 读到(self, 引脚) -> bool:
        """读一个输入引脚：高返回 True，低返回 False。"""
        p = self._取(引脚.号)
        if p.模式 != "输入":
            raise ValueError(
                f"引脚 {p.号} 是输出模式，读它没有意义。\n"
                f"      改法：用 输入引脚() 创建它，或者确认你没有把输入输出的引脚搞混。")
        return p.高

    # ══════════════════ 时间 ══════════════════

    def 时间推进(self, 秒: float):
        """让模拟的时间往前走。

        为什么需要它：闪烁、去抖、超时这些都要用到时间。
        真实硬件里时间是真的在走，模拟器里必须**手动推** ——
        否则你写 `while 时间 < 1: pass` 会永远跑不完。
        """
        if 秒 < 0:
            raise ValueError("时间不能倒流")
        self.时间 += 秒
        return self

    # ══════════════════ 报告 ══════════════════

    def 报告(self) -> str:
        """看这一轮模拟里都发生了什么。**这是排查问题最有用的东西。**"""
        行 = [f"── {self.名字} 状态（时间 {self.时间:.2f}s）──"]
        用过的 = [p for p in self._引脚 if p.模式 == "输出" or p.上下拉]
        if not 用过的:
            行.append("  （还没有配置过任何引脚）")
        for p in 用过的:
            if p.模式 == "输出":
                行.append(f"  引脚 {p.号}: 输出 → {'高（亮/开）' if p.高 else '低（灭/关）'}")
            else:
                行.append(f"  引脚 {p.号}: 输入 → 读到 {'高' if p.高 else '低'}"
                          f"{('（' + p.上下拉 + '）') if p.上下拉 else '  ⚠ 没设上下拉'}")
        if self.上限警告:
            行.append("")
            行.append("  ⚠ 这些地方逻辑上没问题，但真实硬件上要留意：")
            for w in self.上限警告:
                行.append(f"    · {w}")
        return "\n".join(行)

    def 日志文本(self) -> str:
        return "\n".join(self.日志) if self.日志 else "（没有记录到任何操作）"


class _输出引脚:
    """一个输出引脚。高() / 低() / 翻转()。"""

    def __init__(self, 板子: 模拟器, 引脚: _引脚, 名字: str):
        self._板 = 板子
        self.号 = 引脚.号
        self.名字 = 名字
        self._引脚 = 引脚

    def 高(self):
        self._引脚.高 = True
        self._板.日志.append(f"[{self._板.时间:6.2f}s] {self.名字 or ('引脚' + str(self.号))} → 高")
        return self

    def 低(self):
        self._引脚.高 = False
        self._板.日志.append(f"[{self._板.时间:6.2f}s] {self.名字 or ('引脚' + str(self.号))} → 低")
        return self

    def 翻转(self):
        """高变低、低变高。做闪烁最常用。"""
        return self.低() if self._引脚.高 else self.高()

    def 状态(self) -> str:
        return "亮" if self._引脚.高 else "灭"

    def 是高(self) -> bool:
        return self._引脚.高

    def __repr__(self):
        return f"<输出引脚 {self.号} {self.名字} {self.状态()}>"


class _输入引脚:
    """一个输入引脚。只能读，不能设。"""

    def __init__(self, 板子: 模拟器, 引脚: _引脚, 名字: str):
        self._板 = 板子
        self.号 = 引脚.号
        self.名字 = 名字

    def __repr__(self):
        return f"<输入引脚 {self.号} {self.名字}>"
