"""hybridengine_light.coach —— 离线学习助手。

════ 先说清楚它是什么、不是什么 ════

**它不是语言模型。** 它不联网、不需要 API key、不生成自由文本。

为什么不做成真 LLM：轻量版的**核心承诺是零依赖**。
如果助手需要联网或密钥，那学生第一次用它就会卡在配置上 ——
正好背离了"学编程最不该卡在装环境上"这个出发点。

它实际能做的事（三件，都做得很实在）：

    ① 解释报错并在**课程语境**下给出下一步
       普通翻译器告诉你"哪里错了"；它会加上"这一课要考的就是这个"。

    ② 读你的代码，指出常见坑
       死循环风险、input 没转 int、变量名拼写、用了没定义的名字……

    ③ 用**提问**帮你自己找到问题
       这是最有价值的一条。它会问"你期望输出什么？实际输出什么？"
       逼你把现象说清楚 —— 很多时候说到一半就自己发现了。

════ 为什么第 ③ 条最重要 ════

调试能力的核心不是"知道答案"，而是**会把问题拆小、会观察现象**。
一个直接给答案的助手会让学生越来越依赖；
一个会追问"你打印过中间值吗"的助手，是在教方法。

所以它的措辞刻意不直接给答案，而是给**下一步动作**。
"""

from __future__ import annotations

import re

__all__ = ["Coach", "诊断"]


# ── 常见坑的识别规则 ──
# 每条：(名字, 正则, 说明, 怎么改)
# 顺序有意义 —— 具体的放前面。
_PATTERNS: list[tuple[str, str, str, str]] = [
    (
        "input 没转成数字",
        r"input\s*\(",
        "你用了 input()。它拿到的**永远是文字**，哪怕用户输入的是 100。\n"
        "所以 \"100\" + \"1\" 会得到 \"1001\" 而不是 101。",
        "要算数就得转：int(input(\"...\")) 或 float(input(\"...\"))。\n"
        "只想拼进句子里的话不用转，f\"你输入了{输入}\" 就行。",
    ),
    (
        "可能死循环",
        r"while\s+[^:]*:",
        "你用了 while 循环。它和 for 不一样 —— **它不会自己停**，\n"
        "必须由循环体里的某个东西让条件变成假。",
        "检查两件事：\n"
        "  · 循环里有没有让条件变化的语句？（例如 i = i + 1）\n"
        "  · 那个语句真的会被执行到吗？（别被 if 挡在外面）\n"
        "拿不准就先加一句 print，看循环跑了几次。",
    ),
    (
        "range 的边界容易差一",
        r"range\s*\(",
        "你用了 range()。记住它是**含头不含尾**的：\n"
        "  range(3)     → 0, 1, 2        （3 个）\n"
        "  range(1, 4)  → 1, 2, 3        （3 个，没有 4）",
        "如果要数到 n 用 range(1, n+1) 而不是 range(1, n) ——\n"
        "这个「差一」是编程里最常见的 bug，值得现在就记牢。",
    ),
    (
        "用 = 做比较",
        r"if\s+[^=!<>]*[^=!<>]=[^=]",
        "if 里面用了单个等号。\n"
        "  =  是赋值（把值放进去）\n"
        "  == 才是判断相等",
        "改成 ==。\n"
        "（Python 这里会直接报语法错误，算是好事 —— 有些语言能编译但行为完全错。）",
    ),
    (
        "整数除法可能不符预期",
        r"[^/\s]\s*/\s*[^/\s]",
        "你用了 / 除法。在 Python 3 里 / **总是得到小数**：\n"
        "  7 / 2  →  3.5    （不是 3）",
        "如果你要的是整数结果，用 // ：7 // 2 得 3。\n"
        "如果你要小数，那 / 就是对的 —— 只是别拿它当整数用。",
    ),
]

# ── 调试点：遇到问题时该往哪里看 ──
_调试建议 = [
    "先确认程序**跑到哪一步**了：在几个关键位置加 print，看最后打印出来的是哪个。",
    "把**期望**和**实际**写下来，并排放在一起看 —— 差异最小的那一处，就是问题所在。",
    "把可疑的那一行**单独拿出来**，写最小的几行代码试它。\n"
    "（一个能跑通的 3 行小例子，比 50 行里猜要快得多。）",
    "确认变量的**类型**对不对：print(type(变量))。\n"
    "文字和数字看着像，但不是一回事。",
    "确认你改的文件**真的被运行**了 —— 保存了吗？运行的是这一个吗？",
    "把问题**说给别人听**（或者自己念一遍）。\n"
    "「我要做 X，我写了 Y，我以为会得到 Z，实际得到 W」—— 说到一半常常就发现了。",
]


class Coach:
    """一个离线的学习助手。

    用法::

        from hybridengine_light import Coach
        c = Coach()
        c.看代码("a = input()\\nb = a + 1")     # 指出潜在问题
        c.问我("为什么我的循环停不下来")
        c.查("python -m hybridengine_light 检查 01")     # 看这一课的要求
    """

    def __init__(self, 课程目录=None):
        self.课程目录 = 课程目录

    # ══════════════════ ① 解释报错 ══════════════════

    def 解释(self, 异常, 课号: str = "") -> str:
        """解释一个异常。传课号的话会带上「这一课要考的就是这个」。"""
        from .explain import explain
        基础 = explain(异常)

        语境 = self._课程语境(异常, 课号) if 课号 else ""
        if not 语境:
            return 基础
        return 基础 + "\n" + 语境

    def _课程语境(self, 异常, 课号: str) -> str:
        """根据课号补充"这一课在考什么"。"""
        提示表 = {
            "01": {
                "NameError": "这一课（变量）最常见的错就是忘了引号。\n"
                             "想写文字要加引号，不加引号 Python 会去找同名的变量。",
                "TypeError": "这一课要求把变量拼进句子里。\n"
                             "推荐用 f-string：f\"你好，{名字}\"，比用 + 拼更省事也不容易错。",
            },
            "02": {
                "ModuleNotFoundError": "模块化这一课的 import 失败，通常只有一个原因：\n"
                                       "两个文件不在同一个目录里。\n"
                                       "import 找的是「和当前文件同级」的模块。",
                "AttributeError": "如果是「module 没有 xxx 属性」，检查两点：\n"
                                  "  · 函数名拼写（Python 区分大小写）\n"
                                  "  · 那个函数真的写在 mytools.py 里了吗",
            },
        }
        该课 = 提示表.get(课号, {})
        return 该课.get(type(异常).__name__, "")

    # ══════════════════ ② 看代码 ══════════════════

    def 看代码(self, 代码: str, 课号: str = "") -> str:
        """读一段代码，指出潜在问题。

        ⚠ 它**不判断代码对不对** —— 那要靠运行。它只指出"容易出问题的地方"。
        这个定位很重要：一个号称能判断对错的静态检查会让学生失去"自己验证"的习惯。
        """
        发现 = []
        for 名字, 正则, 说明, 改法 in _PATTERNS:
            if re.search(正则, 代码):
                发现.append((名字, 说明, 改法))

        # 用了但没定义过的名字（很粗略，但能抓到拼写错误）
        未定义 = self._找未定义的名字(代码)

        行 = []
        if 发现:
            行.append("我读到这几处**容易出问题**的地方：")
            行.append("")
            for 名字, 说明, 改法 in 发现:
                行.append(f"● {名字}")
                for l in 说明.split("\n"):
                    行.append(f"    {l}")
                行.append("  怎么改：")
                for l in 改法.split("\n"):
                    行.append(f"    {l}")
                行.append("")
        if 未定义:
            行.append("● 这几个名字用了但好像没定义过：")
            行.append(f"    {'、'.join(未定义)}")
            行.append("    检查一下是不是拼错了（Python **区分大小写**），")
            行.append("    或者是不是忘了先赋值。")
            行.append("")
        if not 发现 and not 未定义:
            行.append("没发现明显的问题。")
            行.append("")
            行.append("提醒一句：我看的是**写法**，判断不了代码对不对 ——")
            行.append("那要看它跑出来的结果。直接运行一下最快。")
        return "\n".join(行)

    def _找未定义的名字(self, 代码: str) -> list[str]:
        """找"看起来用了但没定义"的名字。

        ⚠ 这是**粗略**的：它不解析语法，会漏报也会误报。
        所以措辞是"好像没定义过"，而不是"你错了"。
        """
        # 收集所有赋值过的名字
        定义过 = set()
        定义过 |= set(re.findall(r"^\s*([^\W\d]\w*)\s*=", 代码, re.M))          # 赋值
        定义过 |= set(re.findall(r"^\s*def\s+(\w+)", 代码, re.M))               # 函数
        定义过 |= set(re.findall(r"^\s*class\s+(\w+)", 代码, re.M))             # 类
        定义过 |= set(re.findall(r"for\s+(\w+)\s+in", 代码))                    # 循环变量
        定义过 |= set(re.findall(r"import\s+(\w+)", 代码))                      # 导入
        定义过 |= set(re.findall(r"from\s+\w+\s+import\s+([\w,\s]+)", 代码) and
                      [n.strip() for n in re.findall(r"from\s+\w+\s+import\s+([\w,\s]+)", 代码)[0].split(",")]
                      or [])
        # 内置的名字（不全，够用）
        内置 = set("""print input int float str len range list dict set tuple bool type
                      sum max min abs round sorted reversed enumerate zip open
                      True False None self super isinstance hasattr getattr""".split())
        定义过 |= 内置

        # 找出所有被当成变量使用的名字
        用了 = set(re.findall(r"(?<![\w.'\"])([^\W\d]\w*)(?!\s*\()", 代码))
        用了 -= set(re.findall(r"def\s+(\w+)", 代码))     # 函数定义名不算使用
        用了 -= set(re.findall(r"^\s*(\w+)\s*=", 代码, re.M))   # 赋值左边不算
        用了 -= set(re.findall(r"\.(\w+)", 代码))         # 属性名不算
        用了 -= set(re.findall(r"['\"]([^'\"]*)['\"]", 代码))   # 字符串内容不算

        # 只报"看起来像变量、但没定义"的，且过滤掉中文以外的短名噪音
        return sorted(n for n in (用了 - 定义过) if len(n) > 1 and not n.isascii())

    # ══════════════════ ③ 提问引导 ══════════════════

    def 问我(self, 问题: str) -> str:
        """把一个问题变成一串**你自己能回答**的追问。

        为什么不直接给答案：调试能力的核心是会把问题拆小、会观察现象。
        直接给答案会让你越来越依赖；会追问则会让你学会方法。
        """
        关键词 = 问题.lower()
        行 = ["我们一起来看这个问题。先回答我几个问题 —— 很多时候说到一半就自己发现了。", ""]

        if any(k in 问题 for k in ("死循环", "停不下来", "一直在跑", "卡住")):
            行 += [
                "● 你的循环条件是什么？写下来。",
                "● 循环体里**有**哪一句会让这个条件最终变成假？",
                "● 那一句每次都会被执行到吗，还是被某个 if 挡在外面？",
                "● 循环里加一句 print(变量)，跑一下 —— 那个变量在变大还是不变？",
                "",
                "最常见的死循环：条件用了一个循环体里从来没改过的变量。",
            ]
        elif any(k in 问题 for k in ("报错", "错误", "error", "exception")):
            行 += [
                "● 把报错的**最后一行**抄下来（那才是错误类型和原因）。",
                "● 报错里说的行号，对应你代码的哪一行？",
                "● 那一行里的每个变量，此刻的值分别是什么？用 print 看一下。",
                "",
                "提示：报错的前面几行是「调用路径」，只有最后一行是真正的原因。",
            ]
        elif any(k in 问题 for k in ("不对", "错", "为什么是", "结果不")):
            行 += [
                "● 你**期望**输出什么？具体写出来。",
                "● 实际输出是什么？也写出来。",
                "● 两者差在哪？从哪一步开始不一样？",
                "● 在中间加几个 print，看第一个「不符合预期」的值出现在哪一行。",
                "",
                "「从哪一步开始不对」比「整体不对」好查得多。",
            ]
        elif any(k in 问题 for k in ("led", "灯", "亮着", "引脚", "gpio", "传感器", "按钮")):
            # ── 硬件类问题（嵌入式 / 树莓派）──
            #
            # 为什么单独一类：硬件问题的排查顺序和纯软件**完全不同**。
            # 软件问题先看代码；硬件问题要先分清是程序没跑对，还是电路没接对 ——
            # 而模拟器只能验证前者。这个区分不讲清，学生会一直怀疑代码。
            行 += [
                "先分清是哪一类问题 —— 这个顺序很重要：",
                "",
                "① **程序有没有跑到那一行？**",
                "     在点灯之前加一句打印，看它有没有输出。",
                "     没有 → 是程序逻辑问题（循环没进去、函数没被调用、条件不成立）。",
                "     有 → 往下看。",
                "",
                "② **引脚号对不对？**",
                "     树莓派用 BCM 编号（17/18/27…），Arduino 用数字脚 —— 别混。",
                "     写错引脚号在真实板子上**不会报错**，只是毫无反应。",
                "",
                "③ **引脚模式设了吗？**",
                "     输出引脚要先设成输出（树莓派 GPIO.setup(n, GPIO.OUT)）。",
                "     没设就写，真实板子也是没反应、不报错。",
                "",
                "④ **程序结束后引脚会保持最后的状态。**",
                "     树莓派上你的程序是一个普通进程 —— 退出后引脚**不会自动复位**。",
                "     所以觉得'灯关不掉'时，先看代码最后有没有显式关掉它。",
                "     这是树莓派和单片机一个很实际的差别。",
                "",
                "⑤ **电路问题（软件查不出来）**",
                "     限流电阻忘了？LED 正负极接反？杜邦线没插紧？",
                "     这些**模拟器发现不了**，只能拿万用表或换个已知好的接法试。",
                "     如果代码在模拟器里一切正常、真板子却不动，八成是这一类。",
            ]
        elif any(k in 问题 for k in ("不生效", "没生效", "没反应", "改了没变", "没变")):
            行 += [
                "● 你运行的是**哪个文件**？确认路径对得上。",
                "● 保存了吗？（编辑器改了没保存是最常见的原因）",
                "● 加的 print 有没有打印出来？没有的话说明那段代码根本没跑到。",
                "● 函数真的被调用了吗？只定义不调用是不会执行的。",
            ]
        elif any(k in 问题 for k in ("import", "模块", "找不到")):
            行 += [
                "● 两个文件在**同一个目录**里吗？",
                "● import 后面写的是**文件名**（不带 .py），不是函数名。",
                "● 那个名字真的在文件里定义了吗？拼写和大小写对得上吗？",
                "",
                "提示：import 找的是「和当前文件同级、或在 Python 搜索路径里」的模块。",
                "放错目录是 ModuleNotFoundError 的头号原因。",
            ]
        else:
            行 += [
                "● 你想让它做什么？（一句话说清）",
                "● 你写的代码是什么？（贴出来）",
                "● 你**以为**会得到什么？",
                "● 实际得到了什么？（报错原文，或实际输出）",
                "",
                "把这四样凑齐，问题往往就清楚一半了。",
            ]

        行.append("")
        行.append("── 通用的排查方法 ──")
        for i, 建议 in enumerate(_调试建议[:3], 1):
            行.append(f"{i}. {建议}")
        return "\n".join(行)

    # ══════════════════ ④ 看课程语境 ══════════════════

    def 查(self, 课号: str) -> str:
        """针对某一课给一点提示 —— 但不给答案。"""
        from pathlib import Path
        if self.课程目录 is None:
            self.课程目录 = Path(__file__).resolve().parent.parent / "lessons"
        d = Path(self.课程目录)
        if not d.is_dir():
            return "找不到课程目录。"

        找到 = None
        for p in sorted(d.glob("[0-9][0-9]_*.py")):
            if p.stem.startswith(课号):
                找到 = p
                break
        if 找到 is None:
            return f"没有找到第 {课号} 课。"

        文本 = 找到.read_text(encoding="utf-8")
        行 = [f"── {找到.stem} 的要求 ──", ""]
        抄 = False
        for l in 文本.split("\n"):
            s = l.strip()
            if s.startswith("# 要做"):
                抄 = True
                continue
            if 抄:
                if s.startswith("#"):
                    行.append("  " + s.lstrip("# ").rstrip())
                elif not s:
                    行.append("")
                else:
                    break
        行.append("")
        行.append("写完之后：python -m hybridengine_light 检查 " + 课号)
        行.append("（先自己写一遍；真的卡住了再看：python -m hybridengine_light 答案 " + 课号 + "）")
        return "\n".join(行)


def 诊断(异常=None, 代码: str = "", 课号: str = "") -> str:
    """一行调用：把手上有的东西都交给助手看一下。

        from hybridengine_light import 诊断
        print(诊断(代码=我的代码))
        print(诊断(异常=e, 课号="01"))
    """
    c = Coach()
    部分 = []
    if 异常 is not None:
        部分.append(c.解释(异常, 课号))
    if 代码.strip():
        部分.append("── 我对这段代码的看法 ──\n" + c.看代码(代码, 课号))
    if not 部分:
        return c.问我("")
    return "\n".join(部分)
