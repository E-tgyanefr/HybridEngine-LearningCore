#: `--神经元数 240` 这种写法 ⇒ 字段名。只收 `参数` 里真的有的字段。
_数字参数 = {名: 型 for 名, 型 in
             (("神经元数", int), ("兴奋比例", float), ("连接概率", float),
              ("仿真步数", int), ("种子", int), ("漏电", float), ("阈值", float),
              ("外部强度", float), ("外部个数", int), ("兴奋权重", float),
              ("抑制权重", float), ("抑制强度", float))}


def 命令行(argv: list[str] | None = None) -> int:
    """`python -m hybridengine_light.果蝇 [--神经元数 N] … [--对照] [--栅格]`"""
    import sys

    参 = list(sys.argv[1:] if argv is None else argv)
    改: dict[str, object] = {}
    要对照 = "--对照" in 参
    要栅格 = "--栅格" in 参
    要帮助 = "--帮助" in 参 or "-h" in 参 or "--help" in 参

    #  ⚠⚠ 逐项走**原始**参数表。第一版先写了一行
    #        `纯参 = [x for x in 参 if not x.startswith("--")]`
    #     把开关滤掉 —— 结果**值还在**：`--神经元数 60` 变成 `["60"]`，
    #     于是解析器看到的是一个叫「60」的参数名 ⇒ 报"不认识的参数"。
    #     教训：**滤掉开关不等于滤掉它后面那个值**，要成对消费。
    i = 0
    while i < len(参):
        项 = 参[i]
        if 项 in ("--对照", "--栅格", "--帮助", "--help", "-h"):
            i += 1
            continue
        if not 项.startswith("--"):
            print("  不认识的参数：%s（用 --帮助 看能改什么）" % 项)
            return 2
        名 = 项[2:]
        if 名 not in _数字参数:
            print("  不认识的参数：%s（用 --帮助 看能改什么）" % 项)
            return 2
        if i + 1 >= len(参):
            print("  %s 后面要跟一个数" % 项)
            return 2
        try:
            改[名] = _数字参数[名](参[i + 1])
        except ValueError:
            print("  %s 要一个%s，给的是 %r" % (名, _数字参数[名].__name__, 参[i + 1]))
            return 2
        i += 2

    if 要帮助:
        print(__doc__.split("六、怎么用")[-1][:900])
        return 0

    try:
        参对象 = 默认参数(**改)
    except (ValueError, TypeError) as e:
        print("  参数有问题：%s" % e)
        return 2

    print("  果蝇神经模拟（学习内核）—— 连接矩阵是**生成的**，不是真实连接组")
    print("  参数：%s" % {k: getattr(参对象, k) for k in sorted(改) })
    print()

    if 要对照:
        有, 无 = 抑制对比(**改)
        print("  ── 同一张网络，只改「抑制」这一件事 ──")
        for 名, r in (("有抑制", 有), ("没抑制", 无)):
            print("    %-6s %s" % (名, r.摘要()))
        if 无.平均放电率 > 0:
            print("    ⇒ 抑制把放电率压到了 %.0f%%"
                  % (有.平均放电率 / 无.平均放电率 * 100))
        if 要栅格:
            print()
            print("  ── 有抑制（每步发放的神经元个数）──")
            print(放电栅格(有))
        return 0

    结 = 仿真(参对象)
    print("  %s" % 结.摘要())
    if 要栅格:
        print()
        print("  ── 每步发放的神经元个数 ──")
        print(放电栅格(结))
    return 0


if __name__ == "__main__":                                    # pragma: no cover
    raise SystemExit(命令行())
