# ═══════════════════════════════════════════════════════════════════════
#  参数 —— 学员要改的**就是这几个**
# ═══════════════════════════════════════════════════════════════════════

@dataclass
class 参数:
    """一次仿真要用的全部参数。

    ⚠ 每个字段都是**学员可以直接改**的旋钮。改完 `print(结.平均放电率)` 看变化，
      这就是这一课的"做实验"。

    常用四件套（改这四个就能玩很久）：
        神经元数    网络多大（越大越慢，统计也越稳）
        连接概率    任意两个神经元之间有边的概率（0.02 很稀，0.2 很密）
        仿真步数    跑多少步（一步 = 1 毫秒那种感觉）
        种子        同种子 ⇒ 同结果；换一个 ⇒ 换一张网络
    """

    神经元数: int = 240          # N：网络里一共几个神经元
    兴奋比例: float = 0.8        # 前 80% 是兴奋性，后 20% 是抑制性
    连接概率: float = 0.08       # p：任意两个神经元之间有边的概率
    仿真步数: int = 200          # T：跑多少步
    种子: int = 20261014         # 同种子 ⇒ 同结果

    漏电: float = 0.85           # 膜电位每步乘这个数（<1 才会"漏"）
    阈值: float = 1.0            # 电位到了这个数就发放

    外部强度: float = 1.0        # 每一步从外面"敲"几个神经元
    外部个数: int = 20           # 每一步敲几个

    兴奋权重: float = 0.090      # 兴奋性神经元传到别人的权重（正）
    抑制权重: float = 0.350      # 抑制性神经元传到别人的权重（负）
    抑制强度: float = 1.0        # ⭐ 0 = **关掉抑制**，用来做对照实验

    def 检查(self) -> None:
        """参数不合法就**当场报错**，别让它跑出个看不懂的结果。"""
        if self.神经元数 < 2:
            raise ValueError("神经元数至少要 2 个（1 个神经元称不上「网络」）")
        if not 0.0 < self.兴奋比例 < 1.0:
            raise ValueError("兴奋比例要在 0 和 1 之间（两端都得有点人）")
        if not 0.0 <= self.连接概率 <= 1.0:
            raise ValueError("连接概率是概率，要在 0~1 之间")
        if self.仿真步数 < 1:
            raise ValueError("仿真步数至少 1 步")
        if not 0.0 < self.漏电 < 1.0:
            raise ValueError("漏电要在 0 和 1 之间 —— 等于 1 就不会漏，电机位只涨不消")
        if self.阈值 <= 0:
            raise ValueError("阈值要大于 0")


def 默认参数(**改) -> 参数:
    """拿一份默认参数，并把你指定的字段换掉。

        >>> 默认参数(神经元数=100, 种子=7).神经元数
        100

    ⚠ 字段名写错会**报错**，不会静默忽略 —— 静默忽略会让你以为改了、
      其实没改，然后对着一个没变的数字想半天。
    """
    允许 = set(参数.__dataclass_fields__)
    不认识 = sorted(set(改) - 允许)
    if 不认识:
        raise TypeError(
            "不认识的参数：%s\n  能改的是：%s"
            % ("、".join(不认识), "、".join(sorted(允许))))
    参 = 参数(**改)
    参.检查()
    return 参


# ═══════════════════════════════════════════════════════════════════════
#  网：连接矩阵（稀疏 —— 只存**真的有边**的那些对）
# ═══════════════════════════════════════════════════════════════════════

@dataclass
class 网:
    """一张生成好的网络。"""

    参数: 参数
    兴奋: list[int] = field(default_factory=list)   # 兴奋性神经元的编号
    抑制: list[int] = field(default_factory=list)   # 抑制性神经元的编号
    边: list[tuple[int, int, float]] = field(default_factory=list)
    出边: list[list[tuple[int, float]]] = field(default_factory=list)

    @property
    def 神经元数(self) -> int:
        return self.参数.神经元数

    @property
    def 边数(self) -> int:
        return len(self.边)


def 造连接(神经元数: int, 连接概率: float, 种子: int,
           兴奋比例: float = 0.8,
           兴奋权重: float = 0.090, 抑制权重: float = 0.350
           ) -> tuple[list[int], list[int], list[tuple[int, int, float]]]:
    """按概率**生成**连接（⚠ 生成的，不是真实果蝇连接组）。

    规则：
        · 神经元 0 ~ 兴奋比例·N-1 是**兴奋性**，其余是**抑制性**
        · 每一对 (i, j)、i≠j，以 `连接概率` 的概率连一条 i→j 的边
        · 边的权重看**发出去的那个人**：兴奋 ⇒ 正，抑制 ⇒ 负

    ⚠ 随机数来自 `random.Random(f"{种子}-连接")` —— **本模块自己的**流，
      不碰全局 `random`。所以同种子必然同结果，而且不会和"输入"那条流互相干扰。

    返回 `(兴奋们, 抑制们, 边们)`，边们是 `[(前, 后, 权重), …]`。
    """
    兴奋数 = int(round(神经元数 * 兴奋比例))
    兴奋数 = max(1, min(神经元数 - 1, 兴奋数))       # 两类都要有人
    兴奋 = list(range(兴奋数))
    抑制 = list(range(兴奋数, 神经元数))

    随机 = random.Random("%s-连接" % 种子)
    边: list[tuple[int, int, float]] = []
    for 前 in range(神经元数):
        w = 兴奋权重 if 前 < 兴奋数 else -抑制权重
        for 后 in range(神经元数):
            if 前 == 后:
                continue                             # 不给自己连（自环没意义）
            if 随机.random() < 连接概率:
                边.append((前, 后, w))
    return 兴奋, 抑制, 边


def 造网(参: 参数) -> 网:
    """按参数生成一张网络（连接 + 索引）。"""
    参.检查()
    兴奋, 抑制, 边 = 造连接(参.神经元数, 参.连接概率, 参.种子,
                            参.兴奋比例, 参.兴奋权重, 参.抑制权重)
    出边: list[list[tuple[int, float]]] = [[] for _ in range(参.神经元数)]
    for 前, 后, w in 边:
        出边[前].append((后, w))
    return 网(参数=参, 兴奋=兴奋, 抑制=抑制, 边=边, 出边=出边)


# ═══════════════════════════════════════════════════════════════════════
#  结果
# ═══════════════════════════════════════════════════════════════════════

@dataclass
class 结果:
    """一次仿真的结果。"""

    平均放电率: float                       # 每一步平均有多少比例的神经元发放
    每步放电数: list[int]                   # 长度 = 仿真步数
    总放电: int = 0
    兴奋放电: int = 0
    抑制放电: int = 0
    步数: int = 0

    def 摘要(self) -> str:
        每步 = (sum(self.每步放电数) / len(self.每步放电数)) if self.每步放电数 else 0.0
        return ("步数 %d · 平均放电率 %.4f（每步约 %.1f 个神经元发放）· "
                "总放电 %d（兴奋 %d / 抑制 %d）"
                % (self.步数, self.平均放电率, 每步, self.总放电,
                   self.兴奋放电, self.抑制放电))


# ═══════════════════════════════════════════════════════════════════════
#  仿真
# ═══════════════════════════════════════════════════════════════════════

def 仿真(网或参, 步数: int | None = None) -> 结果:
    """跑 `步数` 步，返回结果。

    传 `参数` 也行（内部会先 `造网`）；传已经造好的 `网` 更快。

    ⚠ **确定性**：外部输入来自 `random.Random(f"{种子}-输入")`，
      和"造连接"是**两条独立的随机流**。所以
        · 同参数 ⇒ 同结果（逐位相同）
        · 只为"输入"换种子，不会把网络结构也换掉（对照实验才干净）

    模型（一步）：
        ① 从外面随机敲 `外部个数` 个神经元，每个加 `外部强度`
        ② 上一步**发放了的**神经元，沿自己的出边把权重传给下游
           （兴奋权重是正的、抑制权重是负的，乘上 `抑制强度`）
        ③ v = v · 漏电 + 输入；v ≥ 阈值 ⇒ 发放、v 归 0
    """
    if isinstance(网或参, 参数):
        网络 = 造网(网或参)
    else:
        网络 = 网或参
    参 = 网络.参数
    总步数 = 参.仿真步数 if 步数 is None else int(步数)
    if 总步数 < 1:
        raise ValueError("仿真步数至少 1 步")

    N = 参.神经元数
    随机 = random.Random("%s-输入" % 参.种子)
    电位 = [0.0] * N
    发放过 = [False] * N                 # 上一步谁发放了
    每步放电数: list[int] = []
    总 = 兴奋计 = 抑制计 = 0

    for _步 in range(总步数):
        输入 = [0.0] * N
        # ① 外部敲几下（敲到谁身上是随机的）
        for _ in range(参.外部个数):
            输入[随机.randrange(N)] += 参.外部强度
        # ② 上一步发放的人往下游传
        for 前 in range(N):
            if 发放过[前]:
                for 后, w in 网络.出边[前]:
                    # 抑制性权重是负的，`抑制强度 = 0` 就是**把它整个关掉**
                    输入[后] += (w * 参.抑制强度) if w < 0 else w
        # ③ 膜电位更新
        本步发放 = []
        for k in range(N):
            v = 电位[k] * 参.漏电 + 输入[k]
            if v >= 参.阈值:
                本步发放.append(k)
                电位[k] = 0.0
            else:
                电位[k] = v
        # 下一步的"上一步发放"就是刚刚这一步的集合（整份替换，不留旧的）
        本步集 = set(本步发放)
        发放过 = [k in 本步集 for k in range(N)]
        每步放电数.append(len(本步发放))
        总 += len(本步发放)
        兴奋计 += sum(1 for k in 本步发放 if k < len(网络.兴奋))
        抑制计 += sum(1 for k in 本步发放 if k >= len(网络.兴奋))

    return 结果(平均放电率=总 / (N * 总步数),
               每步放电数=每步放电数,
               总放电=总, 兴奋放电=兴奋计, 抑制放电=抑制计,
               步数=总步数)


def 抑制对比(**改) -> tuple[结果, 结果]:
    """同一张网络，跑两遍：**有抑制** vs **关掉抑制**。

    ⚠ 两次用的是**同一个种子** ⇒ 网络结构和外部输入**逐位相同**，
      唯一的差别就是抑制。这样比较才说明得了问题。
      （如果连网络都换了，那"放电率变了"就分不清是谁的功劳。）

    返回 `(有抑制的结果, 没抑制的结果)`。
    """
    有 = 默认参数(**改)
    无 = 默认参数(**{**改, "抑制强度": 0.0})
    return 仿真(造网(有)), 仿真(造网(无))


# ═══════════════════════════════════════════════════════════════════════
#  看结果：终端里的字符画（依然 headless —— 不开窗口）
# ═══════════════════════════════════════════════════════════════════════

def 放电栅格(结: 结果, 宽: int = 60) -> str:
    """把"每步几个神经元发放"画成一行行的字符画。

    ⚠ 这是**终端字符画**，不用显示器、不开窗口（这一课要能在服务器上跑）。
    """
    if not 结.每步放电数:
        return "（没有数据）"
    高 = 最大 = max(结.每步放电数) or 1
    行们 = []
    for 数 in 结.每步放电数[:宽]:
        条 = int(round(数 / 最大 * 25))
        行们.append("  %4d |%s%s" % (数, "█" * 条, "·" * (25 - 条)))
    if len(结.每步放电数) > 宽:
        行们.append("  …（只画了前 %d 步，共 %d 步）" % (宽, len(结.每步放电数)))
    return "\n".join(行们)


